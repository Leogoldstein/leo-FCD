function metrics = ...
    initialize_network_metrics_planes( ...
        nPlanes)

    metrics = ...
        empty_network_metrics();


    fields = ...
        fieldnames(metrics);


    for i = 1:numel(fields)

        metrics.(fields{i}) = ...
            cell( ...
                1, ...
                nPlanes);
    end
end


function metrics = ...
    normalize_network_metrics_planes( ...
        metrics, ...
        nPlanes)

    fields = ...
        fieldnames(metrics);


    for i = 1:numel(fields)

        field_name = ...
            fields{i};


        metrics.(field_name) = ...
            ensure_plane_cell( ...
                metrics.(field_name), ...
                nPlanes);
    end
end


function output = ...
    copy_network_metrics_from_struct( ...
        loaded, ...
        output, ...
        nPlanes)

    fields = ...
        fieldnames(output);


    for i = 1:numel(fields)

        field_name = ...
            fields{i};


        if isfield( ...
                loaded, ...
                field_name)

            output.(field_name) = ...
                ensure_plane_cell( ...
                    loaded.(field_name), ...
                    nPlanes);
        end
    end
end


function c = ...
    ensure_plane_cell( ...
        c, ...
        nPlanes)

    %==============================================================%
    % Vide
    %==============================================================%
    if isempty(c)

        c = ...
            cell( ...
                1, ...
                nPlanes);

        return;
    end


    %==============================================================%
    % Convertir en cell si nécessaire
    %==============================================================%
    if ~iscell(c)

        c = ...
            {c};
    end


    %==============================================================%
    % Toujours cell ligne
    %==============================================================%
    c = ...
        c(:).';


    %==============================================================%
    % Ajuster nombre de plans
    %==============================================================%
    if numel(c) > nPlanes

        c = ...
            c(1:nPlanes);


    elseif numel(c) < nPlanes

        c = ...
            [ ...
                c, ...
                cell( ...
                    1, ...
                    nPlanes - numel(c)) ...
            ];
    end
end


function planes = ...
    get_planes_or_error_nested( ...
        data, ...
        branchName, ...
        m, ...
        fieldName)

    %==============================================================%
    % Branche
    %==============================================================%
    if ~isfield(data, branchName) || ...
            ~isstruct(data.(branchName))

        error( ...
            'Session %d: branche "%s" manquante.', ...
            m, ...
            branchName);
    end


    branch = ...
        data.(branchName);


    %==============================================================%
    % Champ
    %==============================================================%
    if ~isfield(branch, fieldName) || ...
            numel(branch.(fieldName)) < m || ...
            isempty(branch.(fieldName){m})

        error( ...
            'Session %d: champ "%s.%s" manquant ou vide.', ...
            m, ...
            branchName, ...
            fieldName);
    end


    planes = ...
        branch.(fieldName){m};


    %==============================================================%
    % Format
    %==============================================================%
    if ~iscell(planes) || ...
            isempty(planes)

        error( ...
            ['Session %d: "%s.%s{%d}" doit être ' ...
             'une cell non vide de plans.'], ...
            m, ...
            branchName, ...
            fieldName, ...
            m);
    end
end