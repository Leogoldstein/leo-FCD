function results_analysis = ...
    store_metrics_in_results_analysis( ...
        results_analysis, ...
        metrics, ...
        m, ...
        process_blue)

    %==============================================================%
    % GCaMP activity
    %==============================================================%
    A = ...
        metrics.gcamp_plane.activity;


    results_analysis.gcamp_plane.activity. ...
        FrequencyPerCell{m} = ...
        A.freq_by_plane;

    results_analysis.gcamp_plane.activity. ...
        InterEventIntervals_ms{m} = ...
        A.intervals_ms_by_plane;

    results_analysis.gcamp_plane.activity. ...
        BurstRate_per_min{m} = ...
        A.burst_rate_by_plane;

    results_analysis.gcamp_plane.activity. ...
        BurstFraction{m} = ...
        A.burst_fraction_by_plane;

    results_analysis.gcamp_plane.activity. ...
        BurstSize{m} = ...
        A.burst_size_by_plane;


    %==============================================================%
    % GCaMP correlations
    %==============================================================%
    C = ...
        metrics.gcamp_plane.correlations;


    results_analysis.gcamp_plane.correlations. ...
        cross_corr_gcamp_gcamp_by_plane{m} = ...
        C.cross_corr_gcamp_gcamp_by_plane;

    results_analysis.gcamp_plane.correlations. ...
        max_corr_gcamp_gcamp_by_plane{m} = ...
        C.max_corr_gcamp_gcamp_by_plane;


    %==============================================================%
    % GCaMP SCEs
    %==============================================================%
    S = ...
        metrics.gcamp_plane.SCEs;


    results_analysis.gcamp_plane.SCEs.Race_gcamp{m} = ...
        S.Race_gcamp;

    results_analysis.gcamp_plane.SCEs.TRace_gcamp{m} = ...
        S.TRace_gcamp;

    results_analysis.gcamp_plane.SCEs.sces_distances_gcamp{m} = ...
        S.sces_distances_gcamp;

    results_analysis.gcamp_plane.SCEs.RasterRace_gcamp{m} = ...
        S.RasterRace_gcamp;

    results_analysis.gcamp_plane.SCEs.sce_n_cells_threshold{m} = ...
        S.sce_n_cells_threshold;

    results_analysis.gcamp_plane.SCEs.Threshold{m} = ...
        S.sce_n_cells_threshold;

    results_analysis.gcamp_plane.SCEs.Frequency{m} = ...
        S.sce_frequency_per_min;

    results_analysis.gcamp_plane.SCEs.CellParticipation_percent{m} = ...
        S.cell_participation_percent;

    results_analysis.gcamp_plane.SCEs.Duration_ms{m} = ...
        S.duration_ms;

    results_analysis.gcamp_plane.SCEs.Number{m} = ...
        S.number;

    results_analysis.gcamp_plane.SCEs.RecordingDuration_min{m} = ...
        S.recording_duration_min;

    results_analysis.gcamp_plane.SCEs.InterSCEIntervals_ms{m} = ...
        S.inter_sce_intervals_ms;

    results_analysis.gcamp_plane.SCEs. ...
        MeanCellParticipation_percent{m} = ...
        S.mean_cell_participation_percent;

    results_analysis.gcamp_plane.SCEs. ...
        MedianCellParticipation_percent{m} = ...
        S.median_cell_participation_percent;

    results_analysis.gcamp_plane.SCEs.MeanDuration_ms{m} = ...
        S.mean_duration_ms;

    results_analysis.gcamp_plane.SCEs.MedianDuration_ms{m} = ...
        S.median_duration_ms;


    %==============================================================%
    % Blue/mTOR
    %==============================================================%
    if ~process_blue
        return;
    end


    %==============================================================%
    % Blue activity
    %==============================================================%
    A = ...
        metrics.blue_plane.activity;


    results_analysis.blue_plane.activity. ...
        FrequencyPerCell{m} = ...
        A.freq_by_plane;

    results_analysis.blue_plane.activity. ...
        InterEventIntervals_ms{m} = ...
        A.intervals_ms_by_plane;

    results_analysis.blue_plane.activity. ...
        BurstRate_per_min{m} = ...
        A.burst_rate_by_plane;

    results_analysis.blue_plane.activity. ...
        BurstFraction{m} = ...
        A.burst_fraction_by_plane;

    results_analysis.blue_plane.activity. ...
        BurstSize{m} = ...
        A.burst_size_by_plane;


    %==============================================================%
    % Blue correlations
    %==============================================================%
    C = ...
        metrics.blue_plane.correlations;


    results_analysis.blue_plane.correlations. ...
        cross_corr_gcamp_mtor_by_plane{m} = ...
        C.cross_corr_gcamp_mtor_by_plane;

    results_analysis.blue_plane.correlations. ...
        cross_corr_mtor_mtor_by_plane{m} = ...
        C.cross_corr_mtor_mtor_by_plane;

    results_analysis.blue_plane.correlations. ...
        max_corr_gcamp_mtor_by_plane{m} = ...
        C.max_corr_gcamp_mtor_by_plane;

    results_analysis.blue_plane.correlations. ...
        max_corr_mtor_mtor_by_plane{m} = ...
        C.max_corr_mtor_mtor_by_plane;

    results_analysis.blue_plane.correlations. ...
        median_corr_gcamp_mtor_by_plane{m} = ...
        C.median_corr_gcamp_mtor_by_plane;


    %==============================================================%
    % Blue coupling
    %==============================================================%
    C = ...
        metrics.blue_plane.coupling;


    results_analysis.blue_plane.coupling. ...
        population_corr_gcamp_mtor_by_plane{m} = ...
        C.population_corr_gcamp_mtor_by_plane;

    results_analysis.blue_plane.coupling. ...
        peak_coupling_fraction_by_plane{m} = ...
        C.peak_coupling_fraction_by_plane;

    results_analysis.blue_plane.coupling. ...
        peak_coupling_shuffle_by_plane{m} = ...
        C.peak_coupling_shuffle_by_plane;

    results_analysis.blue_plane.coupling. ...
        peak_coupling_excess_by_plane{m} = ...
        C.peak_coupling_excess_by_plane;

    results_analysis.blue_plane.coupling. ...
        peak_coupling_ratio_by_plane{m} = ...
        C.peak_coupling_ratio_by_plane;

    results_analysis.blue_plane.coupling. ...
        max_lagged_corr_gcamp_population_by_plane{m} = ...
        C.max_lagged_corr_gcamp_population_by_plane;

    results_analysis.blue_plane.coupling. ...
        lag_to_gcamp_population_ms_by_plane{m} = ...
        C.lag_to_gcamp_population_ms_by_plane;
end