function [results_analysis, results_table] = compute_export_basic_metrics( ...
    current_type, ...
    current_animal_group, ...
    current_ages, ...
    gcamp_root_folders, ...
    date_group_paths, ...
    data, ...
    metadata, ...
    include_electroporated_cells)

%COMPUTE_EXPORT_BASIC_METRICS
%
% Fonction d'orchestration.
%
% Pour chaque recording :
%   1) récupère les métadonnées ;
%   2) calcule les métriques d'activité PAR PLAN ;
%   3) charge ou calcule les métriques réseau PAR PLAN ;
%   4) charge ou calcule les SCEs sur les plans concaténés ;
%   5) assemble toutes les métriques ;
%   6) remplit results_analysis ;
%   7) construit results_table.
%
% Organisation :
%
%   Activité :
%       results_analysis....activity.metric{m}{p}
%
%   Corrélations :
%       results_analysis....correlations.metric{m}{p}
%
%   Coupling :
%       results_analysis....coupling.metric{m}{p}
%
% avec :
%       m = recording
%       p = plan
%
% Les SCEs constituent volontairement une exception :
% les différents plans sont concaténés avant calcul.
% Les métriques SCE restent donc définies au niveau du recording.


    %==============================================================%
    % Initialisation
    %==============================================================%
    nRec = ...
        numel(gcamp_root_folders);

    synchronous_frames_group = ...
        cell(nRec, 1);

    if nargin < 8 || ...
            isempty(include_electroporated_cells)

        include_electroporated_cells = ...
            '1';
    end


    include_electroporated_cells = ...
        char(string(include_electroporated_cells));


    process_electroporated = ...
        strcmp( ...
            include_electroporated_cells, ...
            '1');


    current_type = ...
        string(current_type);


    current_animal_group = ...
        string(current_animal_group);


    results_analysis = ...
        init_empty_results_analysis( ...
            nRec);


    results_table = ...
        init_results_table();


    %==============================================================%
    % Boucle recordings
    %==============================================================%
    for m = 1:nRec

        date_name = ...
            get_date_name_from_path( ...
                date_group_paths, ...
                m);


        age_label = ...
            get_age_for_recording( ...
                current_ages, ...
                m);


        age_number = ...
            extract_age_number( ...
                age_label);


        session_id = ...
            current_animal_group + ...
            "_" + ...
            date_name + ...
            "_rec" + ...
            string(m);


        try

            %======================================================%
            % Metadata du recording
            %
            % Même organisation que run_gcamp_peak_detection :
            %
            % metadata
            %   -> metadata_m
            %       -> gcamp_plane
            %======================================================%
            metadata_m = ...
                get_metadata_for_record( ...
                    metadata, ...
                    m);
            
            
            %======================================================%
            % GCaMP metadata = référence
            %======================================================%
            if ~isfield(metadata_m, 'gcamp_plane') || ...
                    isempty(metadata_m.gcamp_plane)
            
                error( ...
                    'GCaMP metadata missing for rec %d.', ...
                    m);
            end
            
            
            metadata_gcamp_m = ...
                metadata_m.gcamp_plane;
            
            
            %======================================================%
            % SamplingRatePlane
            %======================================================%
            if ~isfield(metadata_gcamp_m, ...
                    'SamplingRatePlane') || ...
                    isempty(metadata_gcamp_m.SamplingRatePlane)
            
                error( ...
                    ['SamplingRatePlane missing in GCaMP metadata ' ...
                     'for rec %d.'], ...
                    m);
            end
            
            
            sampling_rate = ...
                parse_numeric_vector( ...
                    metadata_gcamp_m.SamplingRatePlane);
            
            
            if isempty(sampling_rate)
            
                error( ...
                    'SamplingRatePlane invalid for rec %d.', ...
                    m);
            end
            
            
            sampling_rate = ...
                sampling_rate(1);
            
            
            if ~isfinite(sampling_rate) || ...
                    sampling_rate <= 0
            
                error( ...
                    'SamplingRatePlane invalid for rec %d.', ...
                    m);
            end
            
            
            %======================================================%
            % Fenêtre de synchronie
            %
            % 200 ms, identique à run_peak.
            %======================================================%
            synchronous_frames = ...
                max( ...
                    1, ...
                    round( ...
                        0.2 * sampling_rate));
            
            
            synchronous_frames_group{m} = ...
                synchronous_frames;
            
            
            fprintf( ...
                ['Rec %d: SamplingRatePlane = %.4f Hz | ' ...
                 'synchronous_frames = %d\n'], ...
                m, ...
                sampling_rate, ...
                synchronous_frames);


            %======================================================%
            % 1) Activity metrics PAR PLAN
            %
            % compute_all_basic_metrics doit retourner :
            %
            %   nCells_by_plane
            %   freq_by_plane
            %   intervals_ms_by_plane
            %   burst_rate_by_plane
            %   burst_fraction_by_plane
            %   burst_size_by_plane
            %
            % chaque champ étant une cellule {p}.
            %======================================================%
            metrics = ...
                compute_all_basic_metrics( ...
                    data, ...
                    m, ...
                    sampling_rate, ...
                    include_electroporated_cells);


            %======================================================%
            % Recording invalide
            %======================================================%
            if ~metrics.valid

                warning( ...
                    ['Skipping rec %d (%s) - ' ...
                     'données GCaMP invalides.'], ...
                    m, ...
                    gcamp_root_folders{m});

                continue;
            end


            %======================================================%
            % 2) Network correlations + coupling PAR PLAN
            %======================================================%
            network_metrics = ...
                load_or_process_network_metrics_for_session( ...
                    gcamp_root_folders, ...
                    data, ...
                    m, ...
                    sampling_rate, ...
                    include_electroporated_cells);


            %======================================================%
            % 3) SCEs
            %
            % IMPORTANT :
            % Les plans sont volontairement concaténés pour les SCEs.
            % Ces métriques restent donc au niveau du recording.
            %======================================================%
            sce_metrics = ...
                load_or_process_sce_for_session( ...
                    current_animal_group, ...
                    date_group_paths, ...
                    gcamp_root_folders, ...
                    synchronous_frames_group, ...
                    data, ...
                    m, ...
                    sampling_rate);


            %======================================================%
            % 4) Assemble GCaMP correlations PAR PLAN
            %======================================================%
            metrics.gcamp_plane.correlations = ...
                struct();


            metrics.gcamp_plane.correlations. ...
                cross_corr_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                cross_corr_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.correlations. ...
                max_corr_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                max_corr_gcamp_gcamp_by_plane;


            %======================================================%
            % 5) Assemble GCaMP functional coupling PAR PLAN
            %======================================================%
            metrics.gcamp_plane.coupling = ...
                struct();


            metrics.gcamp_plane.coupling. ...
                population_corr_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                population_corr_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                peak_coupling_fraction_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                peak_coupling_fraction_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                peak_coupling_shuffle_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                peak_coupling_shuffle_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                peak_coupling_excess_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                peak_coupling_excess_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                peak_coupling_ratio_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                peak_coupling_ratio_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                max_lagged_corr_gcamp_gcamp_population_by_plane = ...
                network_metrics. ...
                max_lagged_corr_gcamp_gcamp_population_by_plane;


            metrics.gcamp_plane.coupling. ...
                lag_to_gcamp_gcamp_population_ms_by_plane = ...
                network_metrics. ...
                lag_to_gcamp_gcamp_population_ms_by_plane;


            %======================================================%
            % 6) SCEs concaténés
            %======================================================%
            metrics.gcamp_plane.SCEs = ...
                sce_metrics;


            %======================================================%
            % 7) Electroporated / mTOR PAR PLAN
            %======================================================%
            if process_electroporated

                %--------------------------------------------------%
                % Correlations
                %--------------------------------------------------%
                metrics.electroporated_plane.correlations = ...
                    struct();


                metrics.electroporated_plane.correlations. ...
                    cross_corr_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    cross_corr_gcamp_mtor_by_plane;


                metrics.electroporated_plane.correlations. ...
                    cross_corr_mtor_mtor_by_plane = ...
                    network_metrics. ...
                    cross_corr_mtor_mtor_by_plane;


                metrics.electroporated_plane.correlations. ...
                    max_corr_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    max_corr_gcamp_mtor_by_plane;


                metrics.electroporated_plane.correlations. ...
                    max_corr_mtor_mtor_by_plane = ...
                    network_metrics. ...
                    max_corr_mtor_mtor_by_plane;


                metrics.electroporated_plane.correlations. ...
                    median_corr_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    median_corr_gcamp_mtor_by_plane;


                %--------------------------------------------------%
                % Coupling
                %--------------------------------------------------%
                metrics.electroporated_plane.coupling = ...
                    struct();


                metrics.electroporated_plane.coupling. ...
                    population_corr_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    population_corr_gcamp_mtor_by_plane;


                metrics.electroporated_plane.coupling. ...
                    peak_coupling_fraction_by_plane = ...
                    network_metrics. ...
                    peak_coupling_fraction_by_plane;


                metrics.electroporated_plane.coupling. ...
                    peak_coupling_shuffle_by_plane = ...
                    network_metrics. ...
                    peak_coupling_shuffle_by_plane;


                metrics.electroporated_plane.coupling. ...
                    peak_coupling_excess_by_plane = ...
                    network_metrics. ...
                    peak_coupling_excess_by_plane;


                metrics.electroporated_plane.coupling. ...
                    peak_coupling_ratio_by_plane = ...
                    network_metrics. ...
                    peak_coupling_ratio_by_plane;


                metrics.electroporated_plane.coupling. ...
                    max_lagged_corr_gcamp_population_by_plane = ...
                    network_metrics. ...
                    max_lagged_corr_gcamp_population_by_plane;


                metrics.electroporated_plane.coupling. ...
                    lag_to_gcamp_population_ms_by_plane = ...
                    network_metrics. ...
                    lag_to_gcamp_population_ms_by_plane;
            end


            %======================================================%
            % 8) Stockage
            %======================================================%
            results_analysis = ...
                store_metrics_in_results_analysis( ...
                    results_analysis, ...
                    metrics, ...
                    m, ...
                    process_electroporated);


            %======================================================%
            % 9) Export table
            %======================================================%
            results_table = ...
                append_all_metrics_to_results_table( ...
                    results_table, ...
                    metrics, ...
                    current_type, ...
                    current_animal_group, ...
                    age_label, ...
                    age_number, ...
                    date_name, ...
                    session_id, ...
                    m, ...
                    process_electroporated);


        catch ME

            fprintf( ...
                'Error processing rec %d: %s\n', ...
                m, ...
                ME.message);
        end
    end


    %==============================================================%
    % Tri final
    %==============================================================%
    if ~isempty(results_table)

        results_table = ...
            sortrows( ...
                results_table, ...
                { ...
                    'Type', ...
                    'Animal', ...
                    'AgeNumber', ...
                    'RecordingIndex', ...
                    'Plane', ...
                    'Branch', ...
                    'Metric' ...
                });
    end
end


