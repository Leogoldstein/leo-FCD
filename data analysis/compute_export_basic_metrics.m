    end
end


function v = ...
    parse_numeric_vector(x)

    v = [];


    if isempty(x)
        return;
    end


    if isnumeric(x)

        v = ...
            double(x(:).');


        v = ...
            v(isfinite(v));

        return;
    end


    if isstring(x)

        x = ...
            cellstr(x);
    end


    if ischar(x)

        v = ...
            sscanf( ...
                x, ...
                '%f').';


        v = ...
            double(v(:).');


        v = ...
            v(isfinite(v));

        return;
    end


    if iscell(x)

        tmp = [];


        for i = 1:numel(x)

            vi = ...
                parse_numeric_vector( ...
                    x{i});


            if ~isempty(vi)

                tmp = ...
                    [ ...
                        tmp, ...
                        vi ...
                    ]; %#ok<AGROW>
            end
        end


        v = ...
            tmp;


        v = ...
            v(isfinite(v));
    end
end