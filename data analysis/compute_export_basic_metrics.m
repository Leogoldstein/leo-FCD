        results_table, current_type, current_animal_group, ...
        age_label, age_number, date_name, session_id, m, ...
        "gcamp_plane.SCEs", ...
        "CellParticipation", ...
        S.cell_participation_percent, ...
        "%");


    results_table = append_session_value( ...
        results_table, current_type, current_animal_group, ...
        age_label, age_number, date_name, session_id, m, ...
        "gcamp_plane.SCEs", ...
        "Duration", ...
        S.duration_ms, ...
        "ms");


    %==============================================================%
    % Sans électroporées
    %==============================================================%

    if ~process_electroporated
        return;
    end


    %==============================================================%
    % Electroporated activity
    %==============================================================%

    A = ...
        metrics.electroporated_plane.activity;


    if A.valid

        results_table = append_values_by_plane( ...
            results_table, current_type, current_animal_group, ...
            age_label, age_number, date_name, session_id, m, ...
            "electroporated_plane.activity", ...
            "ActiveCellsNumber", ...
            A.nCells_by_plane, ...
