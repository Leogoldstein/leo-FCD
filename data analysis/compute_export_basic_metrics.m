    append_all_metrics_to_results_table( ...
        results_table, ...
        metrics, ...
        current_type, ...
        current_animal_group, ...
        age_label, ...
        age_number, ...
        date_name, ...
        session_id, ...
        m, ...
        process_electroporated)

    %==============================================================%
    % GCaMP activity
    %==============================================================%

    A = ...
        metrics.gcamp_plane.activity;


    results_table = append_values_by_plane( ...
        results_table, current_type, current_animal_group, ...
        age_label, age_number, date_name, session_id, m, ...
        "gcamp_plane.activity", ...
        "ActiveCellsNumber", ...
        A.nCells_by_plane, ...
        "cells");


    results_table = append_values_by_plane( ...
        results_table, current_type, current_animal_group, ...
        age_label, age_number, date_name, session_id, m, ...
        "gcamp_plane.activity", ...
        "FrequencyPerCell", ...
        A.freq_by_plane, ...
        "events/min");


    results_table = append_values_by_plane( ...
        results_table, current_type, current_animal_group, ...
        age_label, age_number, date_name, session_id, m, ...
        "gcamp_plane.activity", ...
        "InterEventIntervals", ...
        A.intervals_ms_by_plane, ...
        "ms");


    results_table = append_values_by_plane( ...
        results_table, current_type, current_animal_group, ...
        age_label, age_number, date_name, session_id, m, ...
        "gcamp_plane.activity", ...
        "BurstRate", ...
        A.burst_rate_by_plane, ...
        "bursts/min");


    results_table = append_values_by_plane( ...
        results_table, current_type, current_animal_group, ...
        age_label, age_number, date_name, session_id, m, ...
        "gcamp_plane.activity", ...
        "BurstFraction", ...
        A.burst_fraction_by_plane, ...
        "fraction");


    results_table = append_values_by_plane( ...
        results_table, current_type, current_animal_group, ...
        age_label, age_number, date_name, session_id, m, ...
        "gcamp_plane.activity", ...
        "BurstSize", ...
        A.burst_size_by_plane, ...
        "events/burst");


    %==============================================================%
    % GCaMP Pearson
    %==============================================================%

