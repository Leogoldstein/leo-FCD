function [results_analysis, results_table] = compute_export_basic_metrics( ...
    current_type, ...
    current_animal_group, ...
    current_ages, ...
    gcamp_root_folders, ...
    date_group_paths, ...
    synchronous_frames_group, ...
    data, ...
    metadata, ...
    include_blue_cells)

%COMPUTE_EXPORT_BASIC_METRICS
%
% Fonction d'orchestration.
%
% Pour chaque recording :
%   1) récupère les métadonnées ;
%   2) calcule les métriques d'activité ;
%   3) charge ou calcule les métriques réseau ;
%   4) charge ou calcule les SCEs ;
%   5) assemble toutes les métriques ;
%   6) remplit results_analysis ;
%   7) construit results_table.


    %==============================================================%
    % Initialisation
    %==============================================================%
    nRec = ...
        numel(gcamp_root_folders);


    if nargin < 9 || ...
            isempty(include_blue_cells)

        include_blue_cells = ...
            '1';
    end


    include_blue_cells = ...
        char(string(include_blue_cells));


    process_blue = ...
        strcmp( ...
            include_blue_cells, ...
            '1');


    current_type = ...
        string(current_type);


    current_animal_group = ...
        string(current_animal_group);


    results_analysis = ...
        init_empty_results_analysis( ...
            nRec);


    results_table = ...
        init_results_table();


    %==============================================================%
    % Boucle recordings
    %==============================================================%
    for m = 1:nRec

        date_name = ...
            get_date_name_from_path( ...
                date_group_paths, ...
                m);


        age_label = ...
            get_age_for_recording( ...
                current_ages, ...
                m);


        age_number = ...
            extract_age_number( ...
                age_label);


        session_id = ...
            current_animal_group + ...
            "_" + ...
            date_name + ...
            "_rec" + ...
            string(m);


        try

            %======================================================%
            % Sampling rate
            %======================================================%
            sampling_rate = ...
                get_metadata_value( ...
                    metadata, ...
                    'SamplingRatePlane', ...
                    m);


            sampling_rate = ...
                parse_numeric_vector( ...
                    sampling_rate);


            if isempty(sampling_rate)

                error( ...
                    'SamplingRatePlane vide pour rec %d', ...
                    m);
            end


            sampling_rate = ...
                sampling_rate(1);


            %======================================================%
            % 1) Activity metrics
            %======================================================%
            metrics = ...
                compute_all_basic_metrics( ...
                    data, ...
                    m, ...
                    sampling_rate, ...
                    include_blue_cells);


            %======================================================%
            % Recording invalide
            %======================================================%
            if ~metrics.valid

                warning( ...
                    ['Skipping rec %d (%s) - ' ...
                     'données GCaMP invalides.'], ...
                    m, ...
                    gcamp_root_folders{m});

                continue;
            end


            %======================================================%
            % 2) Network correlations + coupling
            %======================================================%
            network_metrics = ...
                load_or_process_network_metrics_for_session( ...
                    gcamp_root_folders, ...
                    data, ...
                    m, ...
                    sampling_rate, ...
                    include_blue_cells);


            %======================================================%
            % 3) SCEs
            %======================================================%
            sce_metrics = ...
                load_or_process_sce_for_session( ...
                    current_animal_group, ...
                    date_group_paths, ...
                    gcamp_root_folders, ...
                    synchronous_frames_group, ...
                    data, ...
                    m, ...
                    sampling_rate);


            %======================================================%
            % 4) Assemble GCaMP correlations
            %======================================================%
            metrics.gcamp_plane.correlations = ...
                struct();


            metrics.gcamp_plane.correlations. ...
                cross_corr_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                cross_corr_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.correlations. ...
                max_corr_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                max_corr_gcamp_gcamp_by_plane;


            %======================================================%
            % 5) Assemble GCaMP functional coupling
            %======================================================%
            metrics.gcamp_plane.coupling = ...
                struct();


            metrics.gcamp_plane.coupling. ...
                population_corr_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                population_corr_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                peak_coupling_fraction_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                peak_coupling_fraction_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                peak_coupling_shuffle_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                peak_coupling_shuffle_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                peak_coupling_excess_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                peak_coupling_excess_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                peak_coupling_ratio_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                peak_coupling_ratio_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                max_lagged_corr_gcamp_gcamp_population_by_plane = ...
                network_metrics. ...
                max_lagged_corr_gcamp_gcamp_population_by_plane;


            metrics.gcamp_plane.coupling. ...
                lag_to_gcamp_gcamp_population_ms_by_plane = ...
                network_metrics. ...
                lag_to_gcamp_gcamp_population_ms_by_plane;


            %======================================================%
            % 6) Assemble SCEs
            %======================================================%
            metrics.gcamp_plane.SCEs = ...
                sce_metrics;


            %======================================================%
            % 7) Assemble blue/mTOR metrics
            %======================================================%
            if process_blue

                %--------------------------------------------------%
                % Correlations
                %--------------------------------------------------%
                metrics.blue_plane.correlations = ...
                    struct();


                metrics.blue_plane.correlations. ...
                    cross_corr_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    cross_corr_gcamp_mtor_by_plane;


                metrics.blue_plane.correlations. ...
                    cross_corr_mtor_mtor_by_plane = ...
                    network_metrics. ...
                    cross_corr_mtor_mtor_by_plane;


                metrics.blue_plane.correlations. ...
                    max_corr_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    max_corr_gcamp_mtor_by_plane;


                metrics.blue_plane.correlations. ...
                    max_corr_mtor_mtor_by_plane = ...
                    network_metrics. ...
                    max_corr_mtor_mtor_by_plane;


                metrics.blue_plane.correlations. ...
                    median_corr_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    median_corr_gcamp_mtor_by_plane;


                %--------------------------------------------------%
                % Coupling
                %--------------------------------------------------%
                metrics.blue_plane.coupling = ...
                    struct();


                metrics.blue_plane.coupling. ...
                    population_corr_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    population_corr_gcamp_mtor_by_plane;


                metrics.blue_plane.coupling. ...
                    peak_coupling_fraction_by_plane = ...
                    network_metrics. ...
                    peak_coupling_fraction_by_plane;


                metrics.blue_plane.coupling. ...
                    peak_coupling_shuffle_by_plane = ...
                    network_metrics. ...
                    peak_coupling_shuffle_by_plane;


                metrics.blue_plane.coupling. ...
                    peak_coupling_excess_by_plane = ...
                    network_metrics. ...
                    peak_coupling_excess_by_plane;


                metrics.blue_plane.coupling. ...
                    peak_coupling_ratio_by_plane = ...
                    network_metrics. ...
                    peak_coupling_ratio_by_plane;


                metrics.blue_plane.coupling. ...
                    max_lagged_corr_gcamp_population_by_plane = ...
                    network_metrics. ...
                    max_lagged_corr_gcamp_population_by_plane;


                metrics.blue_plane.coupling. ...
                    lag_to_gcamp_population_ms_by_plane = ...
                    network_metrics. ...
                    lag_to_gcamp_population_ms_by_plane;
            end


            %======================================================%
            % 8) Stockage dans results_analysis
            %======================================================%
            results_analysis = ...
                store_metrics_in_results_analysis( ...
                    results_analysis, ...
                    metrics, ...
                    m, ...
                    process_blue);


            %======================================================%
            % 9) Export table longue
            %======================================================%
            results_table = ...
                append_all_metrics_to_results_table( ...
                    results_table, ...
                    metrics, ...
                    current_type, ...
                    current_animal_group, ...
                    age_label, ...
                    age_number, ...
                    date_name, ...
                    session_id, ...
                    m, ...
                    process_blue);


        catch ME

            fprintf( ...
                'Error processing rec %d: %s\n', ...
                m, ...
                ME.message);
        end
    end


    %==============================================================%
    % Tri final
    %==============================================================%
    if ~isempty(results_table)

        results_table = ...
            sortrows( ...
                results_table, ...
                { ...
                    'Type', ...
                    'Animal', ...
                    'AgeNumber', ...
                    'RecordingIndex', ...
                    'Plane', ...
                    'Branch', ...
                    'Metric' ...
                });
    end
end


