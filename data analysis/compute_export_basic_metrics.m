function [results_analysis, results_table] = compute_export_basic_metrics( ...
    current_type, ...
    current_animal_group, ...
    current_ages, ...
    gcamp_root_folders, ...
    date_group_paths, ...
    data, ...
    metadata, ...
    include_electroporated_cells)

%COMPUTE_EXPORT_BASIC_METRICS
%
% Activité :
%   PAR PLAN
%
% Pearson :
%   PAR PLAN
%
% Coupling :
%   PAR PLAN
%
% SCE :
%   plans concaténés, donc niveau recording.
%
%
% Coupling sauvegardé :
%
%   coupling_*_by_plane
%   coupling_pvalue_*_by_plane
%
% Aucun lag ni valeur brute de shuffle n'est sauvegardé.


    %==============================================================%
    % Initialisation
    %==============================================================%

    nRec = ...
        numel(gcamp_root_folders);


    synchronous_frames_group = ...
        cell(nRec, 1);


    if nargin < 8 || ...
            isempty(include_electroporated_cells)

        include_electroporated_cells = ...
            '1';
    end


    include_electroporated_cells = ...
        char(string(include_electroporated_cells));


    process_electroporated = ...
        strcmp( ...
            include_electroporated_cells, ...
            '1');


    current_type = ...
        string(current_type);


    current_animal_group = ...
        string(current_animal_group);


    results_analysis = ...
        init_empty_results_analysis( ...
            nRec);


    results_table = ...
        init_results_table();


    %==============================================================%
    % Boucle recordings
    %==============================================================%

    for m = 1:nRec

        date_name = ...
            get_date_name_from_path( ...
                date_group_paths, ...
                m);


        age_label = ...
            get_age_for_recording( ...
                current_ages, ...
                m);


        age_number = ...
            extract_age_number( ...
                age_label);


        session_id = ...
            current_animal_group + ...
            "_" + ...
            date_name + ...
            "_rec" + ...
            string(m);


        try

            %======================================================%
            % Metadata
            %======================================================%

            metadata_m = ...
                get_metadata_for_record( ...
                    metadata, ...
                    m);


            if ~isfield(metadata_m, 'gcamp_plane') || ...
                    isempty(metadata_m.gcamp_plane)

                error( ...
                    'GCaMP metadata missing for rec %d.', ...
                    m);
            end


            metadata_gcamp_m = ...
                metadata_m.gcamp_plane;


            %======================================================%
            % Sampling rate
            %======================================================%

            if ~isfield( ...
                    metadata_gcamp_m, ...
                    'SamplingRatePlane') || ...
                    isempty(metadata_gcamp_m.SamplingRatePlane)

                error( ...
                    ['SamplingRatePlane missing in GCaMP metadata ' ...
                     'for rec %d.'], ...
                    m);
            end


            sampling_rate = ...
                parse_numeric_vector( ...
                    metadata_gcamp_m.SamplingRatePlane);


            if isempty(sampling_rate)

                error( ...
                    'SamplingRatePlane invalid for rec %d.', ...
                    m);
            end


            sampling_rate = ...
                sampling_rate(1);


            if ~isfinite(sampling_rate) || ...
                    sampling_rate <= 0

                error( ...
                    'SamplingRatePlane invalid for rec %d.', ...
                    m);
            end


            %======================================================%
            % SCE synchrony window
            %======================================================%

            synchronous_frames = ...
                max( ...
                    1, ...
                    round( ...
                        0.2 * ...
                        sampling_rate));


            synchronous_frames_group{m} = ...
                synchronous_frames;


            fprintf( ...
                ['Rec %d: SamplingRatePlane = %.4f Hz | ' ...
                 'synchronous_frames = %d\n'], ...
                m, ...
                sampling_rate, ...
                synchronous_frames);


            %======================================================%
            % Activity
            %======================================================%

            metrics = ...
                compute_all_basic_metrics( ...
                    data, ...
                    m, ...
                    sampling_rate, ...
                    include_electroporated_cells);


            if ~metrics.valid

                warning( ...
                    ['Skipping rec %d (%s) - ' ...
                     'données GCaMP invalides.'], ...
                    m, ...
                    gcamp_root_folders{m});

                continue;
            end


            %======================================================%
            % Network
            %======================================================%

            network_metrics = ...
                load_or_process_network_metrics_for_session( ...
                    gcamp_root_folders, ...
                    data, ...
                    m, ...
                    sampling_rate, ...
                    include_electroporated_cells);


            %======================================================%
            % SCE
            %======================================================%

            sce_metrics = ...
                load_or_process_sce_for_session( ...
                    current_animal_group, ...
                    date_group_paths, ...
                    gcamp_root_folders, ...
                    synchronous_frames_group, ...
                    data, ...
                    m, ...
                    sampling_rate);


            %======================================================%
            % GCaMP Pearson
            %======================================================%

            metrics.gcamp_plane.correlations = ...
                struct();


            metrics.gcamp_plane.correlations. ...
                cross_corr_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                cross_corr_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.correlations. ...
                max_corr_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                max_corr_gcamp_gcamp_by_plane;


            %======================================================%
            % GCaMP coupling
            %======================================================%

            metrics.gcamp_plane.coupling = ...
                struct();


            metrics.gcamp_plane.coupling. ...
                coupling_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                coupling_gcamp_gcamp_by_plane;


            metrics.gcamp_plane.coupling. ...
                coupling_pvalue_gcamp_gcamp_by_plane = ...
                network_metrics. ...
                coupling_pvalue_gcamp_gcamp_by_plane;


            %======================================================%
            % SCE
            %======================================================%

            metrics.gcamp_plane.SCEs = ...
                sce_metrics;


            %======================================================%
            % Electroporated
            %======================================================%

            if process_electroporated

                metrics.electroporated_plane.correlations = ...
                    struct();


                metrics.electroporated_plane.correlations. ...
                    cross_corr_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    cross_corr_gcamp_mtor_by_plane;


                metrics.electroporated_plane.correlations. ...
                    cross_corr_mtor_mtor_by_plane = ...
                    network_metrics. ...
                    cross_corr_mtor_mtor_by_plane;


                metrics.electroporated_plane.correlations. ...
                    max_corr_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    max_corr_gcamp_mtor_by_plane;


                metrics.electroporated_plane.correlations. ...
                    max_corr_mtor_mtor_by_plane = ...
                    network_metrics. ...
                    max_corr_mtor_mtor_by_plane;


                metrics.electroporated_plane.coupling = ...
                    struct();


                metrics.electroporated_plane.coupling. ...
                    coupling_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    coupling_gcamp_mtor_by_plane;


                metrics.electroporated_plane.coupling. ...
                    coupling_pvalue_gcamp_mtor_by_plane = ...
                    network_metrics. ...
                    coupling_pvalue_gcamp_mtor_by_plane;
            end


            %======================================================%
            % Stockage
            %======================================================%

            results_analysis = ...
                store_metrics_in_results_analysis( ...
                    results_analysis, ...
                    metrics, ...
                    m, ...
                    process_electroporated);


            %======================================================%
            % Table
            %======================================================%

            results_table = ...
                append_all_metrics_to_results_table( ...
                    results_table, ...
                    metrics, ...
                    current_type, ...
                    current_animal_group, ...
                    age_label, ...
                    age_number, ...
                    date_name, ...
                    session_id, ...
                    m, ...
                    process_electroporated);


        catch ME

            fprintf( ...
                'Error processing folder %s: %s\n', ...
                gcamp_root_folders{m}, ...
                ME.message);
        end
    end


    %==============================================================%
    % Tri
    %==============================================================%

    if ~isempty(results_table)

        results_table = ...
            sortrows( ...
                results_table, ...
                { ...
                    'Type', ...
                    'Animal', ...
                    'AgeNumber', ...
                    'RecordingIndex', ...
                    'Plane', ...
                    'Branch', ...
                    'Metric' ...
                });
    end
end


