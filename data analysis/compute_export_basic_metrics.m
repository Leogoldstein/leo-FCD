%==================================================================%
% NORMALISATION PAR PLAN
%==================================================================%
function values_by_plane = ...
    normalize_values_by_plane( ...
        values)

    if isempty(values)

        values_by_plane = ...
            {};


    elseif iscell(values)

        values_by_plane = ...
            values(:).';


    elseif isnumeric(values) || ...
            islogical(values)

        values_by_plane = ...
            {values};


    else

        values_by_plane = ...
            {};
    end
end


%==================================================================%
% RÉSUMÉ NUMÉRIQUE
%==================================================================%
function [mean_value, n_values] = ...
    summarize_numeric_values( ...
        values)

    mean_value = ...
        NaN;


    n_values = ...
        0;


    if isempty(values)
        return;
    end


    if iscell(values)

        combined = [];


        for i = 1:numel(values)

            current = ...
                values{i};


            if isnumeric(current) || ...
                    islogical(current)

                combined = ...
                    [ ...
                        combined; ...
                        double(current(:)) ...
                    ]; %#ok<AGROW>
            end
        end


        values = ...
            combined;
    end


    if ~(isnumeric(values) || ...
            islogical(values))

        return;
    end


    values = ...
        double(values(:));


    values = ...
        values(isfinite(values));


    n_values = ...
        numel(values);


    if n_values > 0

        mean_value = ...
            mean( ...
                values, ...
                'omitnan');
    end
end


