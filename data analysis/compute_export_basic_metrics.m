%==================================================================%
% AGE
%==================================================================%
function age_label = ...
    get_age_for_recording( ...
        current_ages, ...
        m)

    age_label = ...
        "";


    if isempty(current_ages)
        return;
    end


    if iscell(current_ages)

        if numel(current_ages) >= m

            age_label = ...
                string( ...
                    current_ages{m});
        end


    elseif isstring(current_ages)

        if numel(current_ages) >= m

            age_label = ...
                current_ages(m);

        elseif isscalar(current_ages)

            age_label = ...
                current_ages;
        end


    elseif ischar(current_ages)

        age_label = ...
            string(current_ages);


    elseif isnumeric(current_ages)

        if numel(current_ages) >= m

            age_label = ...
                "P" + ...
                string( ...
                    current_ages(m));

        elseif isscalar(current_ages)

            age_label = ...
                "P" + ...
                string(current_ages);
        end
    end
end


function age_number = ...
    extract_age_number( ...
        age_label)

    age_number = ...
        NaN;


    if strlength( ...
            string(age_label)) == 0

        return;
    end


    token = ...
        regexp( ...
            char(string(age_label)), ...
            '[-+]?\d*\.?\d+', ...
            'match', ...
            'once');


    if ~isempty(token)

        age_number = ...
            str2double(token);
    end
end


%==================================================================%
% METADATA DU RECORDING
%==================================================================%
function metadata_m = ...
    get_metadata_for_record( ...
        metadata, ...
        idx)

    metadata_m = ...
        struct();

    if isempty(metadata) || ...
            ~isstruct(metadata)

        return;
    end

    fields = ...
        fieldnames(metadata);

    for f = 1:numel(fields)

        field = ...
            fields{f};

        value = ...
            metadata.(field);

        %==========================================================%
        % Sous-structure
        %
        % Exemple :
        %   metadata.gcamp_plane
        %   metadata.electroporated_plane
        %==========================================================%
        if isstruct(value)

            metadata_m.(field) = ...
                get_metadata_for_record( ...
                    value, ...
                    idx);

        %==========================================================%
        % Champ indexé par recording
        %==========================================================%
        elseif iscell(value)

            if numel(value) >= idx

                metadata_m.(field) = ...
                    value{idx};

            else

                metadata_m.(field) = [];
            end

        %==========================================================%
        % Champ global
        %==========================================================%
        else

            metadata_m.(field) = ...
                value;
        end
    end
end

%==================================================================%
% NUMERIC PARSING
%==================================================================%
function v = ...
    parse_numeric_vector(x)

    v = [];


    if isempty(x)
        return;
    end


    if isnumeric(x)

        v = ...
            double(x(:).');


        v = ...
            v(isfinite(v));

        return;
    end


    if isstring(x)

        x = ...
            cellstr(x);
    end


    if ischar(x)

        v = ...
            sscanf( ...
                x, ...
                '%f').';


        v = ...
            double(v(:).');


        v = ...
            v(isfinite(v));

        return;
    end


    if iscell(x)

        tmp = [];


        for i = 1:numel(x)

            vi = ...
                parse_numeric_vector( ...
                    x{i});


            if ~isempty(vi)

                tmp = ...
                    [ ...
                        tmp, ...
                        vi ...
                    ]; %#ok<AGROW>
            end
        end


        v = ...
            tmp;


        v = ...
            v(isfinite(v));
    end
end