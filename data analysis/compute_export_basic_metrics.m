        "correlation");


    results_table = ...
        append_significant_fraction_by_plane( ...
            results_table, ...
            current_type, ...
            current_animal_group, ...
            age_label, ...
            age_number, ...
            date_name, ...
            session_id, ...
            m, ...
            "gcamp_plane.coupling", ...
            "SignificantCouplingFraction_GCaMP_GCaMP", ...
            C.coupling_pvalue_gcamp_gcamp_by_plane);


