        idx)

    metadata_m = ...
        struct();


    if isempty(metadata) || ...
            ~isstruct(metadata)

        return;
    end


    fields = ...
        fieldnames(metadata);


    for f = 1:numel(fields)

        field = ...
            fields{f};


        value = ...
            metadata.(field);


        if isstruct(value)

            metadata_m.(field) = ...
                get_metadata_for_record( ...
                    value, ...
                    idx);


        elseif iscell(value)

            if numel(value) >= idx

                metadata_m.(field) = ...
                    value{idx};

            else

                metadata_m.(field) = ...
                    [];
            end


        else

            metadata_m.(field) = ...
                value;
        end
    end
end


%==================================================================%
% NUMERIC PARSING
%==================================================================%

function v = ...
    parse_numeric_vector( ...
        x)

    v = [];


    if isempty(x)
        return;
    end


    if isnumeric(x)

        v = ...
            double(x(:).');


        v = ...
            v(isfinite(v));

        return;
    end


    if isstring(x)

        x = ...
            cellstr(x);
    end


    if ischar(x)

        v = ...
            sscanf( ...
                x, ...
                '%f').';


        v = ...
            double(v(:).');


        v = ...
            v(isfinite(v));

        return;
    end


    if iscell(x)

        tmp = [];


        for i = 1:numel(x)

            vi = ...
                parse_numeric_vector( ...
                    x{i});


            if ~isempty(vi)

                tmp = ...
                    [ ...
                        tmp, ...
                        vi ...
                    ]; %#ok<AGROW>
            end
        end


        v = ...
            tmp;


        v = ...
            v(isfinite(v));
    end
end