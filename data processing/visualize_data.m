function visualize_data( ...
        selected_groups, ...
        automatic_selection, ...
        include_electroporated, ...
        results_table, ...
        output_folders)

%VISUALIZE_DATA
%
% Génère les figures de synthèse et les figures individuelles à partir
% d'un ensemble de données déjà sélectionné.
%
% IMPORTANT :
% La séparation Development / Adult est effectuée AVANT l'appel à cette
% fonction avec split_analysis_by_development_adult.
%
% Par conséquent :
%   - selected_groups contient uniquement la période à analyser ;
%   - results_table contient uniquement cette même période ;
%   - output_folders pointe déjà vers :
%
%         ...\Development
%
%     ou
%
%         ...\Adult
%
% Cette fonction ne doit donc PAS ajouter elle-même de sous-dossier
% Development ou Adult.


    %==============================================================%
    % 1) Overview général et légende commune
    %==============================================================%
    [~, ~, ~, legend_table] = ...
        plot_selected_groups_overview( ...
            selected_groups, ...
            include_electroporated, ...
            automatic_selection, ...
            output_folders);
   
    %==============================================================
    % SUMMARY GLOBAL DF
    %==============================================================
    build_all_selected_DF_raster_summary( ...
        selected_groups, ...
        automatic_selection, ...
        output_folders, ...
        include_electroporated);

    %==============================================================%
    % Types
    %==============================================================%
    type_names = ...
        fieldnames(selected_groups);


    valid_types = ...
        type_names( ...
            cellfun( ...
                @(type_name) ...
                    ~isempty(selected_groups.(type_name)), ...
                type_names));


    %==============================================================%
    % Rien à visualiser
    %==============================================================%
    if isempty(valid_types)

        fprintf( ...
            '[VISUALIZE] No valid experimental type, skipped.\n');

        return;
    end


    %==============================================================%
    % 2) Comparaison statistique entre types
    %
    % results_table est déjà filtré Development ou Adult.
    %==============================================================%
    if any(automatic_selection) && ...
            ~include_electroporated && ...
            numel(valid_types) >= 2 && ...
            ~isempty(results_table)

        compare_groups_barplots( ...
            results_table, ...
            3, ...
            'gcamp_plane', ...
            legend_table);
    end

    %==============================================================%
    % 4) Figures radar par type et age
    %==============================================================%
    plot_radar_metrics_by_type( ...
        selected_groups, ...
        include_electroporated, ...
        type_names, ...
        automatic_selection, ...
        output_folders);

    %==============================================================%
    % 5) Figures individuelles par animal
    %==============================================================%
    for t = 1:numel(type_names)

        current_type = ...
            type_names{t};


        %----------------------------------------------------------%
        % Aucun animal dans ce type après split
        %----------------------------------------------------------%
        if isempty( ...
                selected_groups.(current_type))

            continue;
        end

        
        %----------------------------------------------------------%
        % Automatic selection
        %----------------------------------------------------------%
        current_automatic_selection = automatic_selection(t);


        %----------------------------------------------------------%
        % Vérifier output folder
        %----------------------------------------------------------%
        current_output_folder = ...
            output_folders{t};

        if isempty(current_output_folder)

            warning( ...
                'Missing output folder for type: %s', ...
                current_type);

            continue;
        end

        %----------------------------------------------------------%
        % Animaux
        %----------------------------------------------------------%
        animals = ...
            selected_groups.(current_type);


        for k = 1:numel(animals)

            animal_struct = ...
                animals(k);


            %======================================================%
            % results_analysis
            %======================================================%
            if ~isfield( ...
                    animal_struct, ...
                    'results_analysis') || ...
                    isempty(animal_struct.results_analysis)

                fprintf( ...
                    '%s | animal %d: no results_analysis, skip.\n', ...
                    current_type, ...
                    k);

                continue;
            end


            %======================================================%
            % Informations
            %======================================================%
            fprintf('\n==============================\n');
            fprintf('Visualisation\n');
            fprintf('Type: %s\n', current_type);

            fprintf( ...
                'Animal %d / %d: %s\n', ...
                k, ...
                numel(animals), ...
                char(string(animal_struct.animal)));

            fprintf( ...
                'Output: %s\n', ...
                current_output_folder);

            fprintf('==============================\n');


            %======================================================%
            % Extraire uniquement les variables nécessaires
            %======================================================%

            %------------------------------------------------------%
            % Paths
            %------------------------------------------------------%
            gcamp_root_folders = ...
                animal_struct.paths.gcamp_root;


            gcamp_output_folders = ...
                animal_struct.paths.gcamp_output;

            
            current_suite2p = ...
                animal_struct.paths.suite2p;

            %------------------------------------------------------%
            % Identité animal
            %------------------------------------------------------%
            current_line = ...
                animal_struct.line;


            current_animal = ...
                animal_struct.animal;


            %------------------------------------------------------%
            % Recordings
            %
            % Ces valeurs sont déjà filtrées par le split.
            %------------------------------------------------------%
            current_dates = ...
                animal_struct.dates;


            current_ages = ...
                animal_struct.ages;

            current_sampling_rates = ...
                animal_struct.metadata. ...
                    gcamp_plane. ...
                    SamplingRatePlane;

           current_metadata_gcamp = ...
                animal_struct.metadata.gcamp_plane;

            current_metadata_electroporated = ...
                animal_struct.metadata.electroporated_plane;

            %------------------------------------------------------%
            % Résultats
            %
            % results_analysis est lui aussi déjà filtré.
            %------------------------------------------------------%
            results_analysis = ...
                animal_struct.results_analysis;
            

            %------------------------------------------------------%
            % Mean images
            %------------------------------------------------------%
            meanImgs_gcamp = ...
                animal_struct.data.gcamp_plane.meanImgs_gcamp;

            meanImgs_electroporated =...
                animal_struct.data.electroporated_plane. ...
                meanImgs_electroporated;
            
            alignedImgs_electroporated = ...
                animal_struct.data.electroporated_plane. ...
                alignedImgs_electroporated;
   
            %--------------------------------------------------%
            % Mean images
            %--------------------------------------------------%
            save_mean_image_overviews( ...
                current_line, ...
                current_animal, ...
                current_dates, ...
                current_ages, ...
                current_automatic_selection, ...
                current_suite2p, ...
                gcamp_root_folders, ...
                current_output_folder, ...
                meanImgs_gcamp, ...
                meanImgs_electroporated, ...
                alignedImgs_electroporated, ...
                current_metadata_gcamp, ...
                current_metadata_electroporated);         
            

            %======================================================%
            % Histogrammes GCaMP
            %======================================================%
            plot_gcamp_histograms( ...
                results_analysis, ...
                gcamp_output_folders, ...
                current_line, ...
                current_animal, ...
                current_dates, ...
                current_ages);
           
            %======================================================%
            % Recording metrics summary
            %======================================================%
            plot_recording_metrics_summary( ...
                results_analysis, ...
                current_automatic_selection, ...
                current_output_folder, ...
                gcamp_root_folders, ...
                current_line, ...
                current_animal, ...
                current_dates, ...
                current_ages);

            if include_electroporated
                
                %--------------------------------------------------%
                % Frequency comparison GCaMP / mTOR
                %--------------------------------------------------%
                plot_frequency_boxplot( ...
                    results_analysis, ...
                    current_automatic_selection, ...
                    current_output_folder, ...
                    gcamp_output_folders, ...
                    current_line, ...
                    current_animal, ...
                    current_dates, ...
                    current_ages);
            end

            %======================================================%
            % Representative traces by burst rate
            %======================================================%
            plot_representative_traces_by_burst_rate( ...
                animal_struct.data, ...
                results_analysis, ...
                current_sampling_rates, ...
                current_type, ...
                current_output_folder, ...
                gcamp_output_folders, ...
                current_line, ...
                current_animal, ...
                include_electroporated);


            %======================================================%
            % Corrélations
            %
            % Les figures locales restent enregistrées dans les
            % gcamp_root_folders propres aux recordings.
            %======================================================%
            plot_all_pairwise_corr_types( ...
                current_ages, ...
                results_analysis, ...
                gcamp_root_folders, ...
                current_animal);

            %======================================================%
            % Couplage fonctionnel
            %
            % La figure de synthèse sera enregistrée dans
            % current_output_folder, donc directement dans
            % Development ou Adult.
            %======================================================%
            plot_functional_coupling( ...
                results_analysis, ...
                current_automatic_selection, ...
                current_output_folder, ...
                gcamp_output_folders, ...
                current_line, ...
                current_animal, ...
                current_dates, ...
                current_ages);
        end
    end
end

