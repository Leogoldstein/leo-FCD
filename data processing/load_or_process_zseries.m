%==========================================================================%
% 2D PARAMETER CALLBACK
%==========================================================================%

function zseries_2d_parameter_callback(src, ~)

    fig = ancestor(src, 'figure');
    state = guidata(fig);

    if state.busy
        return;
    end


    if isequal( ...
            src, ...
            state.controls.min_area_um2.slider)

        state.detection_opts.min_area_um2 = ...
            get( ...
                state.controls.min_area_um2.slider, ...
                'Value');

    elseif isequal( ...
            src, ...
            state.controls.min_circularity.slider)

        state.detection_opts.min_circularity = ...
            get( ...
                state.controls.min_circularity.slider, ...
                'Value');

    elseif isequal( ...
            src, ...
            state.controls.watershed_strength.slider)

        state.detection_opts.watershed_strength = ...
            get( ...
                state.controls.watershed_strength.slider, ...
                'Value');

    end


    set( ...
        state.controls.min_area_um2.value_text, ...
        'String', ...
        sprintf( ...
            '%.0f', ...
            state.detection_opts.min_area_um2));


    set( ...
        state.controls.min_circularity.value_text, ...
        'String', ...
        sprintf( ...
            '%.2f', ...
            state.detection_opts.min_circularity));


    set( ...
        state.controls.watershed_strength.value_text, ...
        'String', ...
        sprintf( ...
            '%.2f', ...
            state.detection_opts.watershed_strength));


    guidata(fig, state);


    % Recalcul COMPLET uniquement de la frame Z actuellement affichée.
    % Cela inclut la detection des pics, leur croissance et le watershed.
    refresh_zseries_2d_preview(fig);

    state = guidata(fig);

    set( ...
        state.status_text, ...
        'String', ...
        sprintf('Aperçu complet Z %d mis à jour', state.current_z));


    update_zseries_2d_display(fig);

end



