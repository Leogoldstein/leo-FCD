%==========================================================================%
% UPDATE DU GRAPHE DE SIGMOIDE
%==========================================================================%

function update_zseries_sigmoid_plot(fig)

    if ~ishandle(fig)
        return;
    end


    state = guidata(fig);

    if isempty(state) || ...
            ~isfield(state, 'sigmoid_ax') || ...
            ~ishandle(state.sigmoid_ax)

        return;
    end


    nz = ...
        state.nz;


    frame_values = ...
        1:max(1, nz);


    sensitivity_values = ...
        zeros( ...
            size(frame_values));


    for idx = 1:numel(frame_values)

        sensitivity_values(idx) = ...
            get_zseries_sigmoid_sensitivity( ...
                state.detection_opts, ...
                frame_values(idx), ...
                nz);

    end


    transition_depth = ...
        state.detection_opts.sensitivity_transition_depth;


    transition_width = ...
        state.detection_opts.sensitivity_transition_width_fraction;


    center_depth = ...
        transition_depth;


    left_depth = ...
        max( ...
            0, ...
            center_depth - ...
            transition_width / ...
            2);


    right_depth = ...
        min( ...
            1, ...
            center_depth + ...
            transition_width / ...
            2);


    center_frame = ...
        1 + ...
        center_depth * ...
        max(nz - 1, 0);


    left_frame = ...
        1 + ...
        left_depth * ...
        max(nz - 1, 0);


    right_frame = ...
        1 + ...
        right_depth * ...
        max(nz - 1, 0);


    center_sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            state.detection_opts, ...
            center_frame, ...
            nz);


    left_sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            state.detection_opts, ...
            left_frame, ...
            nz);


    right_sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            state.detection_opts, ...
            right_frame, ...
            nz);


    current_sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            state.detection_opts, ...
            state.current_z, ...
            nz);


    set( ...
        state.sigmoid_curve, ...
        'XData', ...
        frame_values, ...
        'YData', ...
        sensitivity_values);


    set( ...
        state.sigmoid_current_line, ...
        'XData', ...
        [state.current_z state.current_z], ...
        'YData', ...
        [0 100]);


    set( ...
        state.sigmoid_current_point, ...
        'XData', ...
        state.current_z, ...
        'YData', ...
        current_sensitivity);


    set( ...
        state.sigmoid_start_handle, ...
        'XData', ...
        1, ...
        'YData', ...
        state.detection_opts.shallow_sensitivity);


    set( ...
        state.sigmoid_left_handle, ...
        'XData', ...
        left_frame, ...
        'YData', ...
        left_sensitivity);


    set( ...
        state.sigmoid_center_handle, ...
        'XData', ...
        center_frame, ...
        'YData', ...
        center_sensitivity);


    set( ...
        state.sigmoid_right_handle, ...
        'XData', ...
        right_frame, ...
        'YData', ...
        right_sensitivity);


    set( ...
        state.sigmoid_end_handle, ...
        'XData', ...
        max(1, nz), ...
        'YData', ...
        state.detection_opts.deep_sensitivity);


    xlim( ...
        state.sigmoid_ax, ...
        [1 max(2, nz)]);


    ylim( ...
        state.sigmoid_ax, ...
        [0 100]);


    width_frames = ...
        transition_width * ...
        max(nz - 1, 0);


    title( ...
        state.sigmoid_ax, ...
        sprintf( ...
            'Frame %d : sens. %.1f', ...
            state.current_z, ...
            current_sensitivity), ...
        'Interpreter', ...
        'none');


    set( ...
        state.sigmoid_info_text, ...
        'String', ...
        sprintf( ...
            'Début %.1f | Fin %.1f | Centre %.1f | Largeur %.1f frames', ...
            state.detection_opts.shallow_sensitivity, ...
            state.detection_opts.deep_sensitivity, ...
            center_frame, ...
            width_frames));

end



%==========================================================================%
% REFRESH 2D PREVIEW
%
% IMPORTANT POUR LA FLUIDITE :
%   - seule la frame actuellement affichee est preparee / segmentee ;
%   - la sensibilite utilisee est celle de la sigmoide pour cette frame ;
%   - aucun rescue Z n'est execute dans le viewer ;
%   - le rescue Z bidirectionnel n'est execute qu'apres Confirmer.
%==========================================================================%

function refresh_zseries_2d_preview(fig)

    state = guidata(fig);
    z = state.current_z;


    if isempty(state.current_enhanced_image) || ...
            state.current_enhanced_z ~= z

        state.current_enhanced_image = ...
            prepare_zseries_detection_plane( ...
                state.registered_volume(:, :, z));


        state.current_enhanced_z = z;

    end


    current_detection_opts = ...
        get_depth_adjusted_detection_opts( ...
            state.detection_opts, ...
            z, ...
            state.nz);


    %==============================================================%
    % APERCU COMPLET DE LA FRAME COURANTE UNIQUEMENT
    %
    % Le watershed et tous les filtres 2D sont appliqués ici pour que
    % l'utilisateur voie immédiatement le résultat final de cette coupe.
    % Aucune autre frame Z n'est recalculée dans le viewer.
    %
    % Le traitement complet de TOUT le stack reste lancé uniquement
    % après Confirmer.
    %==============================================================%

    current_detection_opts.preview_fast_mode = ...
        false;


    [ ...
        state.preview_raw_mask, ...
        state.preview_candidate_mask ...
    ] = ...
        detect_zseries_candidates_plane_from_enhanced( ...
            state.current_enhanced_image, ...
            state.pixel_size_x_um, ...
            state.pixel_size_y_um, ...
            current_detection_opts);


    guidata(fig, state);

end


%==========================================================================%
% RESCUE LOCAL D'UNE FRAME A PARTIR D'UN VOISIN
%
% Cette fonction n'est appelee que pendant le traitement complet apres
% confirmation du viewer.
%
% Important :
%   - aucune sensibilite globale supplementaire ;
%   - chaque cellule du voisin definit une petite ROI ;
%   - la detection plus permissive n'est calculee que dans cette ROI ;
%   - le candidat doit rester spatialement compatible avec le voisin.
%==========================================================================%

function rescue_mask = ...
        rescue_zseries_candidates_from_neighbor( ...
            enhanced_image, ...
            neighbor_mask, ...
            existing_mask, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            current_detection_opts)

    [ny, nx] = ...
        size(enhanced_image);


    rescue_mask = ...
        false( ...
            ny, ...
            nx);


    if isempty(neighbor_mask) || ...
            ~any(neighbor_mask(:))

        return;
    end


    if ~isfield(current_detection_opts, 'z_rescue_enabled') || ...
            ~current_detection_opts.z_rescue_enabled

        return;
    end


    sensitivity_bonus = ...
        current_detection_opts.z_rescue_sensitivity_bonus;


    rescue_dilation_um = ...
        current_detection_opts.z_rescue_dilation_um;


    minimum_overlap = ...
        current_detection_opts.z_rescue_min_overlap;


    maximum_centroid_distance_um = ...
        current_detection_opts.z_rescue_max_centroid_distance_um;


    mean_pixel_size_um = ...
        mean( ...
            [ ...
                pixel_size_x_um, ...
                pixel_size_y_um]);


    dilation_px = ...
        max( ...
            1, ...
            round( ...
                rescue_dilation_um / ...
                max(mean_pixel_size_um, eps)));


    % Le calcul du fond utilise un grand sigma. On garde assez de marge
    % autour de la cellule pour que la detection locale reste comparable a
    % celle faite sur la frame complete.
    context_padding_px = ...
        max( ...
            dilation_px + 2, ...
            ceil( ...
                3 * ...
                current_detection_opts.background_sigma_um / ...
                max(mean_pixel_size_um, eps)));


    neighbor_cc = ...
        bwconncomp( ...
            neighbor_mask, ...
            8);


    if neighbor_cc.NumObjects == 0
        return;
    end


    neighbor_props = ...
        regionprops( ...
            neighbor_cc, ...
            'Centroid', ...
            'PixelIdxList');


    rescue_opts = ...
        current_detection_opts;


    rescue_opts.sensitivity = ...
        min( ...
            100, ...
            current_detection_opts.sensitivity + ...
            sensitivity_bonus);


    for obj = 1:neighbor_cc.NumObjects

        current_neighbor_mask = ...
            false( ...
                ny, ...
                nx);


        current_neighbor_mask( ...
            neighbor_props(obj).PixelIdxList) = ...
            true;


        dilated_neighbor_mask = ...
            imdilate( ...
                current_neighbor_mask, ...
                strel( ...
                    'disk', ...
                    dilation_px));


        [rows, cols] = ...
            find( ...
                dilated_neighbor_mask);


        if isempty(rows)
            continue;
        end


        row_min = ...
            max( ...
                1, ...
                min(rows) - ...
                context_padding_px);


        row_max = ...
            min( ...
                ny, ...
                max(rows) + ...
                context_padding_px);


        col_min = ...
            max( ...
                1, ...
                min(cols) - ...
                context_padding_px);


        col_max = ...
            min( ...
                nx, ...
                max(cols) + ...
                context_padding_px);


        local_image = ...
            enhanced_image( ...
                row_min:row_max, ...
                col_min:col_max);


        [ ...
            ~, ...
            ~, ...
            local_detections ...
        ] = ...
            detect_zseries_candidates_plane_from_enhanced( ...
                local_image, ...
                pixel_size_x_um, ...
                pixel_size_y_um, ...
                rescue_opts);


        if isempty(local_detections)
            continue;
        end


        neighbor_centroid = ...
            neighbor_props(obj).Centroid;


        neighbor_area = ...
            nnz( ...
                current_neighbor_mask);


        for d = 1:numel(local_detections)

            local_mask = ...
                local_detections(d).Mask;


            global_candidate_mask = ...
                false( ...
                    ny, ...
                    nx);


            global_candidate_mask( ...
                row_min:row_max, ...
                col_min:col_max) = ...
                local_mask;


            candidate_area = ...
                nnz( ...
                    global_candidate_mask);


            if candidate_area == 0
                continue;
            end


            % Si l'objet est deja detecte normalement sur cette frame, il
            % n'est pas un rescue et ne doit pas etre recolore / agrandi.
            existing_overlap_fraction = ...
                nnz( ...
                    global_candidate_mask & ...
                    existing_mask) / ...
                candidate_area;


            if existing_overlap_fraction >= 0.25
                continue;
            end


            overlap_denominator = ...
                max( ...
                    1, ...
                    min( ...
                        candidate_area, ...
                        neighbor_area));


            overlap_fraction = ...
                nnz( ...
                    global_candidate_mask & ...
                    current_neighbor_mask) / ...
                overlap_denominator;


            current_centroid = ...
                local_detections(d).Centroid + ...
                [ ...
                    col_min - 1, ...
                    row_min - 1];


            dx_um = ...
                ( ...
                    current_centroid(1) - ...
                    neighbor_centroid(1)) * ...
                pixel_size_x_um;


            dy_um = ...
                ( ...
                    current_centroid(2) - ...
                    neighbor_centroid(2)) * ...
                pixel_size_y_um;


            centroid_distance_um = ...
                hypot( ...
                    dx_um, ...
                    dy_um);


            if overlap_fraction < minimum_overlap || ...
                    centroid_distance_um > ...
                    maximum_centroid_distance_um

                continue;
            end


            rescue_mask = ...
                rescue_mask | ...
                global_candidate_mask;


            existing_mask = ...
                existing_mask | ...
                global_candidate_mask;

        end

    end

end



%==========================================================================%
% UPDATE 2D DISPLAY
%==========================================================================%

function update_zseries_2d_display(fig)

    if ~ishandle(fig)
        return;
    end


    state = guidata(fig);

    if isempty(state)
        return;
    end


    z = state.current_z;
    ax = state.ax;

    cla(ax);


    current_image = ...
        state.registered_volume(:, :, z);


    %==============================================================%
    % Auto-contraste robuste de la frame affichée
    %
    % On ne modifie pas current_image : seules les limites CLim
    % changent pour l'affichage.
    %==============================================================%

    if ~isfield(state, 'display_limits') || ...
            size(state.display_limits, 1) ~= state.nz

        state.display_limits = ...
            nan( ...
                state.nz, ...
                2);

    end


    if any( ...
            ~isfinite( ...
                state.display_limits(z, :)))

        finite_values = ...
            double( ...
                current_image( ...
                    isfinite(current_image)));


        if isempty(finite_values)

            low_display = ...
                0;


            high_display = ...
                1;

        else

            low_display = ...
                prctile( ...
                    finite_values, ...
                    state.display_low_percentile);


            high_display = ...
                prctile( ...
                    finite_values, ...
                    state.display_high_percentile);


            if ~isfinite(low_display) || ...
                    ~isfinite(high_display) || ...
                    high_display <= low_display

                low_display = ...
                    min(finite_values);


                high_display = ...
                    max(finite_values);

            end


            if high_display <= low_display

                display_padding = ...
                    max( ...
                        1, ...
                        abs(low_display) * ...
                        1e-3);


                low_display = ...
                    low_display - ...
                    display_padding;


                high_display = ...
                    high_display + ...
                    display_padding;

            end

        end


        state.display_limits(z, :) = ...
            [ ...
                low_display, ...
                high_display];


        guidata( ...
            fig, ...
            state);

    else

        low_display = ...
            state.display_limits(z, 1);


        high_display = ...
            state.display_limits(z, 2);

    end


    imagesc( ...
        ax, ...
        current_image, ...
        [ ...
            low_display, ...
            high_display]);


    axis(ax, 'image');
    axis(ax, 'off');
    colormap(ax, gray);
    hold(ax, 'on');


    %==============================================================%
    % Rejetés 2D : jaune, diagnostic optionnel uniquement
    %==============================================================%

    rejected_mask = ...
        state.preview_raw_mask & ...
        ~state.preview_candidate_mask;


    if get(state.checkbox_rejected, 'Value') && ...
            any(rejected_mask(:))

        contour( ...
            ax, ...
            rejected_mask, ...
            [0.5 0.5], ...
            'Color', ...
            [1 0.8 0], ...
            'LineWidth', ...
            1);

    end


    %==============================================================%
    % Retenus 2D : rouge
    %
    % Dans le viewer il n'y a pas encore de rescue Z : le contour
    % correspond uniquement a la segmentation de la frame courante.
    %==============================================================%

    if any(state.preview_candidate_mask(:))

        contour( ...
            ax, ...
            state.preview_candidate_mask, ...
            [0.5 0.5], ...
            'Color', ...
            [1 0 0], ...
            'LineWidth', ...
            1.5);

    end


    hold(ax, 'off');


    retained_cc = ...
        bwconncomp( ...
            state.preview_candidate_mask, ...
            8);


    rejected_cc = ...
        bwconncomp( ...
            rejected_mask, ...
            8);


    current_detection_opts = ...
        get_depth_adjusted_detection_opts( ...
            state.detection_opts, ...
            z, ...
            state.nz);


    effective_sensitivity = ...
        current_detection_opts.sensitivity;


    if get(state.checkbox_rejected, 'Value')

        title_string = ...
            sprintf( ...
                'Z %d / %d | sens. %.1f | %d retenu(s) 2D | %d rejeté(s)', ...
                z, ...
                state.nz, ...
                effective_sensitivity, ...
                retained_cc.NumObjects, ...
                rejected_cc.NumObjects);

    else


        title_string = ...
            sprintf( ...
                'Z %d / %d | sens. %.1f | %d cellule(s) retenue(s) en 2D', ...
                z, ...
                state.nz, ...
                effective_sensitivity, ...
                retained_cc.NumObjects);

    end


    title( ...
        ax, ...
        title_string, ...
        'Interpreter', ...
        'none');


    drawnow;

end



%==========================================================================%
% CONFIRM 2D DETECTION
%==========================================================================%

function zseries_2d_confirm_callback(src, ~)

    fig = ancestor(src, 'figure');
    state = guidata(fig);

    if state.busy
        return;
    end


    % Aucun calcul complet du stack dans le callback.
    % On valide simplement les paramètres courants ; le pipeline applique
    % ensuite ces paramètres à toutes les frames Z.
    state.confirmed = true;
    state.busy = true;


    if ishandle(state.confirm_button)

        set( ...
            state.confirm_button, ...
            'Enable', ...
            'off');

    end


    if ishandle(state.cancel_button)

        set( ...
            state.cancel_button, ...
            'Enable', ...
            'off');

    end


    guidata(fig, state);
    uiresume(fig);

end



%==========================================================================%
% CANCEL 2D DETECTION
%==========================================================================%

function zseries_2d_cancel_callback(src, ~)

    if strcmp(get(src, 'Type'), 'figure')

        fig = src;

    else

        fig = ancestor(src, 'figure');

    end


    state = guidata(fig);

    if isempty(state)
        delete(fig);
        return;
    end


    state.confirmed = false;
    guidata(fig, state);
    uiresume(fig);

end



