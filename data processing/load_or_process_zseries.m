                frame_idx + 1;


            volume(:, :, frame_idx) = ...
                single( ...
                    imread( ...
                        current_file, ...
                        p));

        end

    end

end



%==========================================================================%
% HYBRID NEIGHBOR REGISTRATION
%==========================================================================%

function [ ...
        registered_volume, ...
        global_shifts_px, ...
        relative_shifts_px, ...
        reference_plane, ...
        method_by_plane, ...
        registration_scores ...
    ] = ...
        register_zseries_hybrid_neighbors( ...
            volume, ...
            candidate_mask_3d)

    max_neighbor_shift_px = ...
        8;


    minimum_score_improvement = ...
        0.002;


    strong_score_improvement = ...
        0.03;


    registration_smoothing_sigma = ...
        2;


    candidate_smoothing_sigma = ...
        3;


    structure_percentile = ...
        75;


    structure_dilation_px = ...
        5;


    history_length = ...
        5;


    history_outlier_threshold_px = ...
        3;


    [ny, nx, nz] = ...
        size(volume);


    reference_plane = ...
        round( ...
            (nz + 1) / 2);


    registered_volume = ...
        zeros( ...
            ny, ...
            nx, ...
            nz, ...
            'like', ...
            volume);


    global_shifts_px = ...
        zeros( ...
            nz, ...
            2);


    relative_shifts_px = ...
        zeros( ...
            nz, ...
            2);


    method_by_plane = ...
        repmat( ...
            {'none'}, ...
            nz, ...
            1);


    method_by_plane{reference_plane} = ...
        'reference';


    registration_scores = ...
        nan( ...
            nz, ...
            4);


    registration_scores( ...
        reference_plane, :) = ...
        [1 1 NaN 1];


    registration_volume = ...
        zeros( ...
            ny, ...
            nx, ...
            nz, ...
            'single');


    candidate_registration_volume = ...
        zeros( ...
            ny, ...
            nx, ...
            nz, ...
            'single');


    parfor z = 1:nz

        registration_volume(:, :, z) = ...
            prepare_registration_image( ...
                volume(:, :, z), ...
                registration_smoothing_sigma);


        current_candidate_mask = ...
            candidate_mask_3d(:, :, z);


        if any(current_candidate_mask(:))

            candidate_image = ...
                imdilate( ...
                    current_candidate_mask, ...
                    strel( ...
                        'disk', ...
                        2));


            candidate_image = ...
                imgaussfilt( ...
                    single(candidate_image), ...
                    candidate_smoothing_sigma);


            current_max = ...
                max( ...
                    candidate_image(:));


            if current_max > 0

                candidate_image = ...
                    candidate_image ./ ...
                    current_max;

            end


            candidate_registration_volume( ...
                :, :, z) = ...
                candidate_image;

        end

    end


    %==============================================================%
    % Au-dessus de la référence
    %==============================================================%

    for z = reference_plane + 1:nz

        fixed_plane = ...
            z - 1;


        history_start = ...
            max( ...
                reference_plane + 1, ...
                z - history_length);


        shift_history = ...
            relative_shifts_px( ...
                history_start:z - 1, ...
                :);


        [ ...
            selected_shift, ...
            selected_method, ...
            scores ...
        ] = ...
            estimate_hybrid_neighbor_shift( ...
                registration_volume(:, :, z), ...
                registration_volume(:, :, fixed_plane), ...
                candidate_registration_volume(:, :, z), ...
                candidate_registration_volume(:, :, fixed_plane), ...
                shift_history, ...
                max_neighbor_shift_px, ...
                minimum_score_improvement, ...
                strong_score_improvement, ...
                history_outlier_threshold_px, ...
                structure_percentile, ...
                structure_dilation_px);


        relative_shifts_px(z, :) = ...
            selected_shift;


        global_shifts_px(z, :) = ...
            global_shifts_px(fixed_plane, :) + ...
            selected_shift;


        method_by_plane{z} = ...
            selected_method;


        registration_scores(z, :) = ...
            scores;

    end


    %==============================================================%
    % Sous la référence
    %==============================================================%

    for z = reference_plane - 1:-1:1

        fixed_plane = ...
            z + 1;


        history_end = ...
            min( ...
                reference_plane - 1, ...
                z + history_length);


        shift_history = ...
            relative_shifts_px( ...
                z + 1:history_end, ...
                :);


        [ ...
            selected_shift, ...
            selected_method, ...
            scores ...
        ] = ...
            estimate_hybrid_neighbor_shift( ...
                registration_volume(:, :, z), ...
                registration_volume(:, :, fixed_plane), ...
                candidate_registration_volume(:, :, z), ...
                candidate_registration_volume(:, :, fixed_plane), ...
                shift_history, ...
                max_neighbor_shift_px, ...
                minimum_score_improvement, ...
                strong_score_improvement, ...
                history_outlier_threshold_px, ...
                structure_percentile, ...
                structure_dilation_px);


        relative_shifts_px(z, :) = ...
            selected_shift;


        global_shifts_px(z, :) = ...
            global_shifts_px(fixed_plane, :) + ...
            selected_shift;


        method_by_plane{z} = ...
            selected_method;


        registration_scores(z, :) = ...
            scores;

    end


    %==============================================================%
    % Application unique aux images brutes
    %==============================================================%

    parfor z = 1:nz

        current_image = ...
            volume(:, :, z);


        fill_value = ...
            median( ...
                current_image(:), ...
                'omitnan');


        registered_volume(:, :, z) = ...
            imtranslate( ...
                current_image, ...
                global_shifts_px(z, :), ...
                'OutputView', ...
                'same', ...
                'FillValues', ...
                fill_value);

    end


    fprintf( ...
        'Plan de référence : %d\n', ...
        reference_plane);

end



%==========================================================================%
% PREPARE REGISTRATION IMAGE
%==========================================================================%

function registration_image = ...
        prepare_registration_image( ...
            image, ...
            smoothing_sigma)

    image = ...
        single(image);


    low_value = ...
        prctile( ...
            image(:), ...
            1);


    high_value = ...
        prctile( ...
            image(:), ...
            99.5);


    if high_value > low_value

        registration_image = ...
            ( ...
                image - ...
                low_value) ./ ...
            ( ...
                high_value - ...
                low_value);

    else

        registration_image = ...
            zeros( ...
                size(image), ...
                'single');

    end


    registration_image = ...
        min( ...
            max( ...
                registration_image, ...
                0), ...
            1);


    registration_image = ...
        imgaussfilt( ...
            registration_image, ...
            smoothing_sigma);

end



%==========================================================================%
% BUILD STRUCTURAL MASK
%==========================================================================%

function structural_mask = ...
        build_structural_registration_mask( ...
            moving_image, ...
            fixed_image, ...
            structure_percentile, ...
            structure_dilation_px)

    moving_threshold = ...
        prctile( ...
            moving_image(:), ...
            structure_percentile);


    fixed_threshold = ...
        prctile( ...
            fixed_image(:), ...
            structure_percentile);


    moving_structure = ...
        moving_image >= ...
        moving_threshold;


    fixed_structure = ...
        fixed_image >= ...
        fixed_threshold;


    structural_mask = ...
        moving_structure | ...
        fixed_structure;


    if structure_dilation_px > 0

        structural_mask = ...
            imdilate( ...
                structural_mask, ...
                strel( ...
                    'disk', ...
                    structure_dilation_px));

    end


    if nnz(structural_mask) < ...
            round( ...
                0.05 * ...
                numel(structural_mask))

        structural_mask(:) = ...
            true;

    end

end



%==========================================================================%
% HYBRID SHIFT
%==========================================================================%

function [ ...
        selected_shift, ...
        selected_method, ...
        scores ...
    ] = ...
        estimate_hybrid_neighbor_shift( ...
            moving_image, ...
            fixed_image, ...
            moving_candidates, ...
            fixed_candidates, ...
            shift_history, ...
            max_neighbor_shift_px, ...
            minimum_score_improvement, ...
            strong_score_improvement, ...
            history_outlier_threshold_px, ...
            structure_percentile, ...
            structure_dilation_px)

    structural_mask = ...
        build_structural_registration_mask( ...
            moving_image, ...
            fixed_image, ...
            structure_percentile, ...
            structure_dilation_px);


    score_zero = ...
        calculate_registration_score( ...
            moving_image, ...
            fixed_image, ...
            [0 0], ...
            structural_mask);


    image_shift = ...
        estimate_translation_imregcorr( ...
            moving_image, ...
            fixed_image);


    image_valid = ...
        all( ...
            isfinite(image_shift)) && ...
        norm(image_shift) <= ...
        max_neighbor_shift_px;


    if image_valid

        score_image = ...
            calculate_registration_score( ...
                moving_image, ...
                fixed_image, ...
                image_shift, ...
                structural_mask);

    else

        score_image = ...
            -Inf;

    end


    candidate_shift = ...
        [NaN NaN];


    score_candidates = ...
        -Inf;


    if any(moving_candidates(:)) && ...
            any(fixed_candidates(:))

        candidate_shift = ...
            estimate_translation_imregcorr( ...
                moving_candidates, ...
                fixed_candidates);


        candidate_valid = ...
            all( ...
                isfinite(candidate_shift)) && ...
            norm(candidate_shift) <= ...
            max_neighbor_shift_px;


        if candidate_valid

            score_candidates = ...
                calculate_registration_score( ...
                    moving_image, ...
                    fixed_image, ...
                    candidate_shift, ...
                    structural_mask);

        end

    end


    selected_shift = ...
        [0 0];


    selected_method = ...
        'none';


    selected_score = ...
        score_zero;


    if image_valid && ...
            score_image > ...
            selected_score + ...
            minimum_score_improvement

        selected_shift = ...
            image_shift;


        selected_method = ...
            'image';


        selected_score = ...
            score_image;

    end


    if isfinite(score_candidates) && ...
            score_candidates > ...
            selected_score + ...
            minimum_score_improvement

        selected_shift = ...
            candidate_shift;


        selected_method = ...
            'candidates';


        selected_score = ...
            score_candidates;

    end


    if ~strcmp( ...
            selected_method, ...
            'none') && ...
            size(shift_history, 1) >= 2

        history_center = ...
            median( ...
                shift_history, ...
                1);


        history_residuals = ...
            sqrt( ...
                sum( ...
                    ( ...
                        shift_history - ...
                        history_center) .^ 2, ...
                    2));


        history_dispersion = ...
            median( ...
                history_residuals);


        adaptive_threshold = ...
            max( ...
                history_outlier_threshold_px, ...
                3 * history_dispersion + ...
                1);


        distance_to_history = ...
            norm( ...
                selected_shift - ...
                history_center);


        score_improvement = ...
            selected_score - ...
            score_zero;


        if distance_to_history > ...
                adaptive_threshold && ...
                score_improvement < ...
                strong_score_improvement

            selected_shift = ...
                [0 0];


            selected_method = ...
                'none_outlier';


            selected_score = ...
                score_zero;

        end

    end


    scores = ...
        [ ...
            score_zero, ...
            score_image, ...
            score_candidates, ...
            selected_score];

end



%==========================================================================%
% ESTIMATE TRANSLATION
%==========================================================================%

function shift_xy = ...
        estimate_translation_imregcorr( ...
            moving, ...
            fixed)

    shift_xy = ...
        [NaN NaN];


    if isempty(moving) || ...
            isempty(fixed)

        return;

    end


    if std( ...
            double(moving(:)), ...
            0, ...
            'omitnan') <= eps || ...
            std( ...
                double(fixed(:)), ...
                0, ...
                'omitnan') <= eps

        return;

    end


    try

        tform = ...
            imregcorr( ...
                moving, ...
                fixed, ...
                'translation');


        shift_xy = ...
            [ ...
                tform.T(3, 1), ...
                tform.T(3, 2)];


    catch

        shift_xy = ...
            [NaN NaN];

    end

end



%==========================================================================%
% REGISTRATION SCORE
%==========================================================================%

function score = ...
        calculate_registration_score( ...
            moving, ...
            fixed, ...
            shift_xy, ...
            structural_mask)

    if any( ...
            ~isfinite(shift_xy))

        score = ...
            -Inf;

        return;

    end


    shifted_moving = ...
        imtranslate( ...
            moving, ...
            shift_xy, ...
            'OutputView', ...
            'same', ...
            'FillValues', ...
            single(0));


    valid_mask_numeric = ...
        imtranslate( ...
            ones( ...
                size(moving), ...
                'single'), ...
            shift_xy, ...
            'OutputView', ...
            'same', ...
            'FillValues', ...
            single(0));


    valid_mask = ...
        valid_mask_numeric > ...
        0.5;


    valid_mask = ...
        valid_mask & ...
        structural_mask & ...
        isfinite(shifted_moving) & ...
        isfinite(fixed);


    if nnz(valid_mask) < 100

        score = ...
            -Inf;

        return;

    end


    moving_values = ...
        double( ...
            shifted_moving(valid_mask));


    fixed_values = ...
        double( ...
            fixed(valid_mask));


    moving_values = ...
        moving_values - ...
        mean(moving_values);


    fixed_values = ...
        fixed_values - ...
        mean(fixed_values);


    denominator = ...
        sqrt( ...
            sum(moving_values .^ 2) * ...
            sum(fixed_values .^ 2));


    if denominator <= eps

        score = ...
            -Inf;

        return;

    end


    score = ...
        sum( ...
            moving_values .* ...
            fixed_values) / ...
        denominator;

end



%==========================================================================%
% FILTRE VOLUMIQUE 3D DIRECT DU STACK DE MASQUES 2D
%
% Aucun tracking / appariement de cellules entre plans n'est effectue.
% Le stack reste un simple empilement des detections 2D finales.
%
% volume_um3 = nb_voxels * PixelSizeX * PixelSizeY * ZStep
%==========================================================================%

function [filtered_mask_3d, stats] = ...
        filter_zseries_detection_volume_3d( ...
            candidate_mask_3d, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            z_step_um, ...
            detection_opts)

    filtered_mask_3d = ...
        logical(candidate_mask_3d);


    stats = struct();
    stats.enabled = false;
    stats.connectivity = [];
    stats.total_components = 0;
    stats.kept_components = 0;
    stats.removed_components = 0;
    stats.removed_too_small = 0;
    stats.removed_too_large = 0;
    stats.removed_too_few_z_planes = 0;
    stats.removed_z_extent = 0;
    stats.component_volumes_um3 = [];
    stats.component_z_extents_um = [];
    stats.component_z_planes = [];


    if isempty(filtered_mask_3d) || ...
            ~any(filtered_mask_3d(:))

        return;
    end


    if isfield(detection_opts, 'volume_filter_enabled') && ...
            ~isempty(detection_opts.volume_filter_enabled)

        volume_filter_enabled = ...
            logical(detection_opts.volume_filter_enabled);

    else

        volume_filter_enabled = ...
            true;

    end


    if ~volume_filter_enabled
        return;
    end


    stats.enabled = true;


    if isfield(detection_opts, 'min_cell_volume_um3') && ...
            ~isempty(detection_opts.min_cell_volume_um3)

        min_cell_volume_um3 = detection_opts.min_cell_volume_um3;

    else

        min_cell_volume_um3 = 300;

    end


    if isfield(detection_opts, 'max_cell_volume_um3') && ...
            ~isempty(detection_opts.max_cell_volume_um3)

        max_cell_volume_um3 = detection_opts.max_cell_volume_um3;

    else

        max_cell_volume_um3 = 50000;

    end


    if isfield(detection_opts, 'min_z_planes') && ...
            ~isempty(detection_opts.min_z_planes)

        min_z_planes = ...
            max( ...
                1, ...
                round(detection_opts.min_z_planes));

    else

        min_z_planes = ...
            2;

    end


    if isfield(detection_opts, 'min_z_extent_um') && ...
            ~isempty(detection_opts.min_z_extent_um)

        min_z_extent_um = detection_opts.min_z_extent_um;

    else

        min_z_extent_um = 0;

    end


    if isfield(detection_opts, 'max_z_extent_um') && ...
            ~isempty(detection_opts.max_z_extent_um)

        max_z_extent_um = detection_opts.max_z_extent_um;

    else

        max_z_extent_um = Inf;

    end


    if isfield(detection_opts, 'volume_connectivity') && ...
            ~isempty(detection_opts.volume_connectivity)

        connectivity = round(detection_opts.volume_connectivity);

    else

        connectivity = 18;

    end


    if ~ismember(connectivity, [6 18 26])
        connectivity = 18;
    end


    stats.connectivity = connectivity;


    pixel_size_x_um = double(pixel_size_x_um);
    pixel_size_y_um = double(pixel_size_y_um);
    z_step_um = double(z_step_um);


    if ~isfinite(pixel_size_x_um) || pixel_size_x_um <= 0
        pixel_size_x_um = 1;
    end


    if ~isfinite(pixel_size_y_um) || pixel_size_y_um <= 0
        pixel_size_y_um = pixel_size_x_um;
    end


    if ~isfinite(z_step_um) || z_step_um <= 0
        z_step_um = 1;
    end


    voxel_volume_um3 = ...
        pixel_size_x_um * ...
        pixel_size_y_um * ...
        z_step_um;


    cc = ...
        bwconncomp( ...
            filtered_mask_3d, ...
            connectivity);


    stats.total_components = cc.NumObjects;


    output_mask = ...
        false( ...
            size(filtered_mask_3d));


    volume_values_um3 = ...
        zeros( ...
            cc.NumObjects, ...
            1);


    z_extent_values_um = ...
        zeros( ...
            cc.NumObjects, ...
            1);


    z_plane_values = ...
        zeros( ...
            cc.NumObjects, ...
            1);


    for component_idx = 1:cc.NumObjects

        current_idx = ...
            cc.PixelIdxList{component_idx};


        current_volume_um3 = ...
            numel(current_idx) * ...
            voxel_volume_um3;


        [~, ~, current_z] = ...
            ind2sub( ...
                size(filtered_mask_3d), ...
                current_idx);


        if isempty(current_z)

            current_z_extent_um = 0;
            current_z_planes = 0;

        else

            current_z_planes = ...
                numel( ...
                    unique(current_z));


            current_z_extent_um = ...
                (max(current_z) - min(current_z) + 1) * ...
                z_step_um;

        end


        volume_values_um3(component_idx) = current_volume_um3;
        z_extent_values_um(component_idx) = current_z_extent_um;
        z_plane_values(component_idx) = current_z_planes;


        if current_volume_um3 < min_cell_volume_um3

            stats.removed_too_small = ...
                stats.removed_too_small + 1;

            continue;
        end


        if current_volume_um3 > max_cell_volume_um3

            stats.removed_too_large = ...
                stats.removed_too_large + 1;

            continue;
        end


        if current_z_planes < min_z_planes

            stats.removed_too_few_z_planes = ...
                stats.removed_too_few_z_planes + 1;

            continue;
        end


        if current_z_extent_um < min_z_extent_um || ...
                current_z_extent_um > max_z_extent_um

            stats.removed_z_extent = ...
                stats.removed_z_extent + 1;

            continue;
        end


        output_mask(current_idx) = true;
        stats.kept_components = stats.kept_components + 1;

    end


    stats.removed_components = ...
        stats.total_components - ...
        stats.kept_components;


    stats.component_volumes_um3 = volume_values_um3;
    stats.component_z_extents_um = z_extent_values_um;
    stats.component_z_planes = z_plane_values;
    stats.min_z_planes = min_z_planes;
    stats.min_cell_volume_um3 = min_cell_volume_um3;
    stats.max_cell_volume_um3 = max_cell_volume_um3;
    stats.min_z_extent_um = min_z_extent_um;
    stats.max_z_extent_um = max_z_extent_um;


    filtered_mask_3d = output_mask;


    fprintf( ...
        ['Filtre volume 3D : %d composante(s) -> %d conservee(s), ' ...
         '%d retiree(s).\n'], ...
        stats.total_components, ...
        stats.kept_components, ...
        stats.removed_components);


    fprintf( ...
        ['  Volume %.1f-%.1f um3 | >= %d plans Z | connectivite %d | ' ...
         'petites %d | grandes %d | 1-plan %d | extension Z %d\n'], ...
        min_cell_volume_um3, ...
        max_cell_volume_um3, ...
        min_z_planes, ...
        connectivity, ...
        stats.removed_too_small, ...
        stats.removed_too_large, ...
        stats.removed_too_few_z_planes, ...
        stats.removed_z_extent);

end



%==========================================================================%
% SAVE Z PROJECTION OF FINAL 2D DETECTIONS
%
% No 3D reconstruction and no isotropic resampling.
% The grayscale PNG is the Z maximum projection of the registered signal,
% restricted to pixels retained by the final 2D masks.
%
% For compatibility with the current folder organization, the historical
% *_cells_3D_MIP.png filename is retained by get_zseries_3d_output_paths.
%==========================================================================%

function preview_file = ...
        save_zseries_2d_z_projection( ...
            registered_volume, ...
            detection_mask_3d, ...
            output_folder, ...
            summary_output_folder, ...
            current_automatic_selection, ...
            zseries_path, ...
            overwrite_existing, ...
            current_line, ...
            current_animal, ...
            current_date, ...
            current_age, ...
            num_frames, ...
            z_step_um, ...
            z_start_um, ...
            z_end_um)

    preview_file = '';


    if nargin < 7 || isempty(overwrite_existing)

        overwrite_existing = ...
            false;

    end


    if isempty(registered_volume) || ...
            isempty(detection_mask_3d)

        fprintf( ...
            'Projection Z non sauvegardée : volume ou masque 2D vide.\n');

        return;

    end


    if ~isequal( ...
            size(registered_volume), ...
            size(detection_mask_3d))

        warning( ...
            ['Projection Z non sauvegardée : dimensions du volume et ' ...
             'du masque 2D incompatibles.']);

        return;

    end


    [ ...
        ~, ...
        preview_file, ...
        summary_preview_file ...
    ] = ...
        get_zseries_3d_output_paths( ...
            output_folder, ...
            summary_output_folder, ...
            current_automatic_selection, ...
            zseries_path);


    %==============================================================%
    % Volume d'intensité masqué par les détections 2D
    %==============================================================%

    masked_volume = ...
        zeros( ...
            size(registered_volume), ...
            'single');


    valid_mask = ...
        logical(detection_mask_3d) & ...
        isfinite(registered_volume);


    masked_volume(valid_mask) = ...
        single( ...
            registered_volume(valid_mask));


    z_projection = ...
        max( ...
            masked_volume, ...
            [], ...
            3);


    max_value = ...
        max( ...
            z_projection(:), ...
            [], ...
            'omitnan');


    if isempty(max_value) || ...
            ~isfinite(max_value) || ...
            max_value <= 0

        fprintf( ...
            'Projection Z non sauvegardée : aucune détection 2D finale.\n');

        return;

    end


    z_projection = ...
        max( ...
            z_projection, ...
            0);


    z_projection_uint16 = ...
        uint16( ...
            min( ...
                z_projection ./ ...
                single(max_value), ...
                1) * ...
            65535);


    %==============================================================%
    % AFFICHAGE DE LA PROJECTION AVANT SAUVEGARDE
    %
    % La projection finale est toujours montrée avant toute écriture
    % disque. Le pipeline reste bloqué tant que l'utilisateur n'a pas
    % fermé la fenêtre ou cliqué sur "Fermer et enregistrer".
    %==============================================================%

    show_zseries_projection_before_save( ...
        z_projection_uint16, ...
        current_line, ...
        current_animal, ...
        current_date, ...
        current_age, ...
        num_frames, ...
        z_step_um, ...
        z_start_um, ...
        z_end_um);


    %==============================================================%
    % Preview locale
    %==============================================================%

    if ~isempty(preview_file)

        if isfile(preview_file) && ...
                overwrite_existing

            delete(preview_file);

        end


        if ~isfile(preview_file)

            if ~isfolder(output_folder)

                mkdir(output_folder);

            end


            save_zseries_preview_figure( ...
                z_projection_uint16, ...
                preview_file, ...
                current_line, ...
                current_animal, ...
                current_date, ...
                current_age, ...
                num_frames, ...
                z_step_um, ...
                z_start_um, ...
                z_end_um);


            fprintf( ...
                'Projection Z 2D locale sauvegardée :\n%s\n', ...
                preview_file);

        else

            fprintf( ...
                'Projection Z 2D locale déjà existante :\n%s\n', ...
                preview_file);

        end

    end


    %==============================================================%
    % Preview summary
    %==============================================================%

    if ~isempty(summary_preview_file)

        same_destination = ...
            ~isempty(preview_file) && ...
            strcmpi( ...
                char(preview_file), ...
                char(summary_preview_file));


        if ~same_destination

            if isfile(summary_preview_file) && ...
                    overwrite_existing

                delete(summary_preview_file);

            end


            if ~isfile(summary_preview_file)

                if ~isfolder(summary_output_folder)

                    mkdir(summary_output_folder);

                end


                save_zseries_preview_figure( ...
                    z_projection_uint16, ...
                    summary_preview_file, ...
                    current_line, ...
                    current_animal, ...
                    current_date, ...
                    current_age, ...
                    num_frames, ...
                    z_step_um, ...
                    z_start_um, ...
                    z_end_um);


                fprintf( ...
                    'Projection Z 2D summary sauvegardée :\n%s\n', ...
                    summary_preview_file);

            end

        end

    end

end



