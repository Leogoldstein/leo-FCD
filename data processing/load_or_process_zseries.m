            if z == 1

                imwrite( ...
                    volume_uint16(:, :, z), ...
                    tiff_file, ...
                    'tif', ...
                    'Compression', ...
                    'none');

            else

                imwrite( ...
                    volume_uint16(:, :, z), ...
                    tiff_file, ...
                    'tif', ...
                    'WriteMode', ...
                    'append', ...
                    'Compression', ...
                    'none');

