%==========================================================================%
% HYBRID NEIGHBOR REGISTRATION
%==========================================================================%

function [ ...
        registered_volume, ...
        global_shifts_px, ...
        relative_shifts_px, ...
        reference_plane, ...
        method_by_plane, ...
        registration_scores ...
    ] = ...
        register_zseries_hybrid_neighbors( ...
            volume, ...
            candidate_mask_3d)

    max_neighbor_shift_px = ...
        8;


    minimum_score_improvement = ...
        0.002;


    strong_score_improvement = ...
        0.03;


    registration_smoothing_sigma = ...
        2;


    candidate_smoothing_sigma = ...
        3;


    structure_percentile = ...
        75;


    structure_dilation_px = ...
        5;


    history_length = ...
        5;


    history_outlier_threshold_px = ...
        3;


    [ny, nx, nz] = ...
        size(volume);


    reference_plane = ...
        round( ...
            (nz + 1) / 2);


    registered_volume = ...
        zeros( ...
            ny, ...
            nx, ...
            nz, ...
            'like', ...
            volume);


    global_shifts_px = ...
        zeros( ...
            nz, ...
            2);


    relative_shifts_px = ...
        zeros( ...
            nz, ...
            2);


    method_by_plane = ...
        repmat( ...
            {'none'}, ...
            nz, ...
            1);


    method_by_plane{reference_plane} = ...
        'reference';


    registration_scores = ...
        nan( ...
            nz, ...
            4);


    registration_scores( ...
        reference_plane, :) = ...
        [1 1 NaN 1];


    registration_volume = ...
        zeros( ...
            ny, ...
            nx, ...
            nz, ...
            'single');


    candidate_registration_volume = ...
        zeros( ...
            ny, ...
            nx, ...
            nz, ...
            'single');


    parfor z = 1:nz

        registration_volume(:, :, z) = ...
            prepare_registration_image( ...
                volume(:, :, z), ...
                registration_smoothing_sigma);


        current_candidate_mask = ...
            candidate_mask_3d(:, :, z);


        if any(current_candidate_mask(:))

            candidate_image = ...
                imdilate( ...
                    current_candidate_mask, ...
                    strel( ...
                        'disk', ...
                        2));


            candidate_image = ...
                imgaussfilt( ...
                    single(candidate_image), ...
                    candidate_smoothing_sigma);


            current_max = ...
                max( ...
                    candidate_image(:));


            if current_max > 0

                candidate_image = ...
                    candidate_image ./ ...
                    current_max;

            end


            candidate_registration_volume( ...
                :, :, z) = ...
                candidate_image;

        end

    end


    %==============================================================%
    % Au-dessus de la référence
    %==============================================================%

    for z = reference_plane + 1:nz

        fixed_plane = ...
            z - 1;


        history_start = ...
            max( ...
                reference_plane + 1, ...
                z - history_length);


        shift_history = ...
            relative_shifts_px( ...
                history_start:z - 1, ...
                :);


        [ ...
            selected_shift, ...
            selected_method, ...
            scores ...
        ] = ...
            estimate_hybrid_neighbor_shift( ...
                registration_volume(:, :, z), ...
                registration_volume(:, :, fixed_plane), ...
                candidate_registration_volume(:, :, z), ...
                candidate_registration_volume(:, :, fixed_plane), ...
                shift_history, ...
                max_neighbor_shift_px, ...
                minimum_score_improvement, ...
                strong_score_improvement, ...
                history_outlier_threshold_px, ...
                structure_percentile, ...
                structure_dilation_px);


        relative_shifts_px(z, :) = ...
            selected_shift;


        global_shifts_px(z, :) = ...
            global_shifts_px(fixed_plane, :) + ...
            selected_shift;


        method_by_plane{z} = ...
            selected_method;


        registration_scores(z, :) = ...
            scores;

    end


    %==============================================================%
    % Sous la référence
    %==============================================================%

    for z = reference_plane - 1:-1:1

        fixed_plane = ...
            z + 1;


        history_end = ...
            min( ...
                reference_plane - 1, ...
                z + history_length);


        shift_history = ...
            relative_shifts_px( ...
                z + 1:history_end, ...
                :);


        [ ...
            selected_shift, ...
            selected_method, ...
            scores ...
        ] = ...
            estimate_hybrid_neighbor_shift( ...
                registration_volume(:, :, z), ...
                registration_volume(:, :, fixed_plane), ...
                candidate_registration_volume(:, :, z), ...
                candidate_registration_volume(:, :, fixed_plane), ...
                shift_history, ...
                max_neighbor_shift_px, ...
                minimum_score_improvement, ...
                strong_score_improvement, ...
                history_outlier_threshold_px, ...
                structure_percentile, ...
                structure_dilation_px);


        relative_shifts_px(z, :) = ...
            selected_shift;


        global_shifts_px(z, :) = ...
            global_shifts_px(fixed_plane, :) + ...
            selected_shift;


        method_by_plane{z} = ...
            selected_method;


        registration_scores(z, :) = ...
            scores;

    end


    %==============================================================%
    % Application unique aux images brutes
    %==============================================================%

    parfor z = 1:nz

        current_image = ...
            volume(:, :, z);


        fill_value = ...
            median( ...
                current_image(:), ...
                'omitnan');


        registered_volume(:, :, z) = ...
            imtranslate( ...
                current_image, ...
                global_shifts_px(z, :), ...
                'OutputView', ...
                'same', ...
                'FillValues', ...
                fill_value);

    end


    fprintf( ...
        'Plan de référence : %d\n', ...
        reference_plane);

end



%==========================================================================%
% PREPARE REGISTRATION IMAGE
%==========================================================================%

function registration_image = ...
        prepare_registration_image( ...
            image, ...
            smoothing_sigma)

    image = ...
        single(image);


    low_value = ...
        prctile( ...
            image(:), ...
            1);


    high_value = ...
        prctile( ...
            image(:), ...
            99.5);


    if high_value > low_value

        registration_image = ...
            ( ...
                image - ...
                low_value) ./ ...
            ( ...
                high_value - ...
                low_value);

    else

        registration_image = ...
            zeros( ...
                size(image), ...
                'single');

    end


    registration_image = ...
        min( ...
            max( ...
                registration_image, ...
                0), ...
            1);


    registration_image = ...
        imgaussfilt( ...
            registration_image, ...
            smoothing_sigma);

end



%==========================================================================%
% BUILD STRUCTURAL MASK
%==========================================================================%

function structural_mask = ...
        build_structural_registration_mask( ...
            moving_image, ...
            fixed_image, ...
            structure_percentile, ...
            structure_dilation_px)

    moving_threshold = ...
        prctile( ...
            moving_image(:), ...
            structure_percentile);


    fixed_threshold = ...
        prctile( ...
            fixed_image(:), ...
            structure_percentile);


    moving_structure = ...
        moving_image >= ...
        moving_threshold;


    fixed_structure = ...
        fixed_image >= ...
        fixed_threshold;


    structural_mask = ...
        moving_structure | ...
        fixed_structure;


    if structure_dilation_px > 0

        structural_mask = ...
            imdilate( ...
                structural_mask, ...
                strel( ...
                    'disk', ...
                    structure_dilation_px));

    end


    if nnz(structural_mask) < ...
            round( ...
                0.05 * ...
                numel(structural_mask))

        structural_mask(:) = ...
            true;

    end

end



%==========================================================================%
% HYBRID SHIFT
%==========================================================================%

function [ ...
        selected_shift, ...
        selected_method, ...
        scores ...
    ] = ...
        estimate_hybrid_neighbor_shift( ...
            moving_image, ...
            fixed_image, ...
            moving_candidates, ...
            fixed_candidates, ...
            shift_history, ...
            max_neighbor_shift_px, ...
            minimum_score_improvement, ...
            strong_score_improvement, ...
            history_outlier_threshold_px, ...
            structure_percentile, ...
            structure_dilation_px)

    structural_mask = ...
        build_structural_registration_mask( ...
            moving_image, ...
            fixed_image, ...
            structure_percentile, ...
            structure_dilation_px);


    score_zero = ...
        calculate_registration_score( ...
            moving_image, ...
            fixed_image, ...
            [0 0], ...
            structural_mask);


    image_shift = ...
        estimate_translation_imregcorr( ...
            moving_image, ...
            fixed_image);


    image_valid = ...
        all( ...
            isfinite(image_shift)) && ...
        norm(image_shift) <= ...
        max_neighbor_shift_px;


    if image_valid

        score_image = ...
            calculate_registration_score( ...
                moving_image, ...
                fixed_image, ...
                image_shift, ...
                structural_mask);

    else

        score_image = ...
            -Inf;

    end


    candidate_shift = ...
        [NaN NaN];


    score_candidates = ...
        -Inf;


    if any(moving_candidates(:)) && ...
            any(fixed_candidates(:))

        candidate_shift = ...
            estimate_translation_imregcorr( ...
                moving_candidates, ...
                fixed_candidates);


        candidate_valid = ...
            all( ...
                isfinite(candidate_shift)) && ...
            norm(candidate_shift) <= ...
            max_neighbor_shift_px;


        if candidate_valid

            score_candidates = ...
                calculate_registration_score( ...
                    moving_image, ...
                    fixed_image, ...
                    candidate_shift, ...
                    structural_mask);

        end

    end


    selected_shift = ...
        [0 0];


    selected_method = ...
        'none';


    selected_score = ...
        score_zero;


    if image_valid && ...
            score_image > ...
            selected_score + ...
            minimum_score_improvement

        selected_shift = ...
            image_shift;


        selected_method = ...
            'image';


        selected_score = ...
            score_image;

    end


    if isfinite(score_candidates) && ...
            score_candidates > ...
            selected_score + ...
            minimum_score_improvement

        selected_shift = ...
            candidate_shift;


        selected_method = ...
            'candidates';


        selected_score = ...
            score_candidates;

    end


    if ~strcmp( ...
            selected_method, ...
            'none') && ...
            size(shift_history, 1) >= 2

        history_center = ...
            median( ...
                shift_history, ...
                1);


        history_residuals = ...
            sqrt( ...
                sum( ...
                    ( ...
                        shift_history - ...
                        history_center) .^ 2, ...
                    2));


        history_dispersion = ...
            median( ...
                history_residuals);


        adaptive_threshold = ...
            max( ...
                history_outlier_threshold_px, ...
                3 * history_dispersion + ...
                1);


        distance_to_history = ...
            norm( ...
                selected_shift - ...
                history_center);


        score_improvement = ...
            selected_score - ...
            score_zero;


        if distance_to_history > ...
                adaptive_threshold && ...
                score_improvement < ...
                strong_score_improvement

            selected_shift = ...
                [0 0];


            selected_method = ...
                'none_outlier';


            selected_score = ...
                score_zero;

        end

    end


    scores = ...
        [ ...
            score_zero, ...
            score_image, ...
            score_candidates, ...
            selected_score];

end



%==========================================================================%
% ESTIMATE TRANSLATION
%==========================================================================%

function shift_xy = ...
        estimate_translation_imregcorr( ...
            moving, ...
            fixed)

    shift_xy = ...
        [NaN NaN];


    if isempty(moving) || ...
            isempty(fixed)

        return;

    end


    if std( ...
            double(moving(:)), ...
            0, ...
            'omitnan') <= eps || ...
            std( ...
                double(fixed(:)), ...
                0, ...
                'omitnan') <= eps

        return;

    end


    try

        tform = ...
            imregcorr( ...
                moving, ...
                fixed, ...
                'translation');


        shift_xy = ...
            [ ...
                tform.T(3, 1), ...
                tform.T(3, 2)];


    catch

        shift_xy = ...
            [NaN NaN];

    end

end



%==========================================================================%
% REGISTRATION SCORE
%==========================================================================%

function score = ...
        calculate_registration_score( ...
            moving, ...
            fixed, ...
            shift_xy, ...
            structural_mask)

    if any( ...
            ~isfinite(shift_xy))

        score = ...
            -Inf;

        return;

    end


    shifted_moving = ...
        imtranslate( ...
            moving, ...
            shift_xy, ...
            'OutputView', ...
            'same', ...
            'FillValues', ...
            single(0));


    valid_mask_numeric = ...
        imtranslate( ...
            ones( ...
                size(moving), ...
                'single'), ...
            shift_xy, ...
            'OutputView', ...
            'same', ...
            'FillValues', ...
            single(0));


    valid_mask = ...
        valid_mask_numeric > ...
        0.5;


    valid_mask = ...
        valid_mask & ...
        structural_mask & ...
        isfinite(shifted_moving) & ...
        isfinite(fixed);


    if nnz(valid_mask) < 100

        score = ...
            -Inf;

        return;

    end


    moving_values = ...
        double( ...
            shifted_moving(valid_mask));


    fixed_values = ...
        double( ...
            fixed(valid_mask));


    moving_values = ...
        moving_values - ...
        mean(moving_values);


    fixed_values = ...
        fixed_values - ...
        mean(fixed_values);


    denominator = ...
        sqrt( ...
            sum(moving_values .^ 2) * ...
            sum(fixed_values .^ 2));


    if denominator <= eps

        score = ...
            -Inf;

        return;

    end


    score = ...
        sum( ...
            moving_values .* ...
            fixed_values) / ...
        denominator;

end



%==========================================================================%
% ISOTROPIC VOLUME
%==========================================================================%

function isotropic_volume = ...
        make_isotropic_zseries_volume( ...
            volume, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            z_step_um)

    if isempty(volume)

        isotropic_volume = [];

        return;

    end


    target_voxel_um = ...
        min( ...
            [ ...
                pixel_size_x_um, ...
                pixel_size_y_um, ...
                z_step_um]);


    [ny, nx, nz] = ...
        size(volume);


    new_ny = ...
        max( ...
            1, ...
            round( ...
                ny * ...
                pixel_size_y_um / ...
                target_voxel_um));


    new_nx = ...
        max( ...
            1, ...
            round( ...
                nx * ...
                pixel_size_x_um / ...
                target_voxel_um));


    new_nz = ...
        max( ...
            1, ...
            round( ...
                nz * ...
                z_step_um / ...
                target_voxel_um));


    isotropic_volume = ...
        imresize3( ...
            volume, ...
            [ ...
                new_ny, ...
                new_nx, ...
                new_nz], ...
            'linear');

end



%==========================================================================%
