%==========================================================================%
% PREPARE DETECTION VOLUME
%==========================================================================%

function enhanced_volume = ...
        prepare_zseries_detection_volume( ...
            volume)

    [ny, nx, nz] = ...
        size(volume);


    enhanced_volume = ...
        zeros( ...
            ny, ...
            nx, ...
            nz, ...
            'single');


    %==============================================================%
    % Chaque plan est indépendant : parallélisation sûre
    %==============================================================%

    parfor z = 1:nz

        enhanced_volume(:, :, z) = ...
            prepare_zseries_detection_plane( ...
                volume(:, :, z));

    end

end



%==========================================================================%
% PREPARE ONE DETECTION PLANE
%==========================================================================%

function enhanced_image = ...
        prepare_zseries_detection_plane( ...
            image)

    current_image = ...
        single(image);


    low_value = ...
        prctile( ...
            current_image(:), ...
            1);


    high_value = ...
        prctile( ...
            current_image(:), ...
            99.8);


    if high_value > low_value

        normalized_image = ...
            ( ...
                current_image - ...
                low_value) ./ ...
            ( ...
                high_value - ...
                low_value);

    else

        normalized_image = ...
            zeros( ...
                size(current_image), ...
                'single');

    end


    normalized_image = ...
        min( ...
            max( ...
                normalized_image, ...
                0), ...
            1);


    %==============================================================%
    % IMPORTANT
    %
    % Pas de CLAHE pour la segmentation :
    % il peut amplifier les petites textures du neuropile et créer
    % de faux maxima. L'auto-contraste de l'interface est indépendant.
    %==============================================================%

    enhanced_image = ...
        single( ...
            normalized_image);

end



%==========================================================================%
% DETECT CANDIDATES FROM PREPARED VOLUME
%==========================================================================%

function [ ...
        candidate_mask_3d, ...
        detections_by_plane ...
    ] = ...
        detect_zseries_candidates_from_enhanced( ...
            enhanced_volume, ...
            pixel_size_x_um, ...
