function zseries_all = load_or_process_zseries( ...
        zseries_paths, ...
        gcamp_root_folders, ...
        zseries_metadata, ...
        output_folders, ...
        current_automatic_selection, ...
        current_line, ...
        current_animal, ...
        current_dates, ...
        current_ages)

    if nargin < 4 || isempty(output_folders)
        output_folders = {};
    end


    if nargin < 5 || isempty(current_automatic_selection)
        current_automatic_selection = 0;
    end


    if nargin < 6
        current_line = '';
    end


    if nargin < 7
        current_animal = '';
    end


    if nargin < 8 || isempty(current_dates)
        current_dates = {};
    end


    if nargin < 9 || isempty(current_ages)
        current_ages = {};
    end

    %==============================================================%
    % LOAD OR PROCESS ZSERIES
    %
    % Pipeline :
    %
    %   1) Reconstruction volume brut
    %
    %   2) Détection préliminaire permissive
    %      utilisée uniquement comme aide au recalage
    %
    %   3) Recalage hybride entre plans voisins
    %
    %   4) Application unique des shifts aux images brutes
    %
    %   5) Interface interactive 2D uniquement :
    %        - sensibilité
    %        - aire minimale
    %        - circularité
    %
    %   6) Après confirmation : reconstruction des cellules en 3D
    %
    %   7) Filtres volumiques 3D
    %
    %   8) Sauvegarde results_zseries.mat + image 3D isotrope
    %
    %==============================================================%

    zseries_all = ...
        repmat( ...
            create_empty_zseries_result(), ...
            0, ...
            1);


    if isempty(zseries_paths)
        return;
    end


    %==============================================================%
    % Supprimer les doublons de ZSeries
    %
    % Une même ZSeries peut être référencée plusieurs fois par les
    % recordings associés. Elle ne doit être traitée / affichée
    % qu'une seule fois.
    %==============================================================%

    [ ...
        zseries_paths, ...
        gcamp_root_folders, ...
        zseries_metadata, ...
        output_folders, ...
        current_dates, ...
        current_ages ...
    ] = ...
        remove_duplicate_zseries_entries( ...
            zseries_paths, ...
            gcamp_root_folders, ...
            zseries_metadata, ...
            output_folders, ...
            current_dates, ...
            current_ages);


    %==============================================================%
    % Nombre de ZSeries
    %==============================================================%

    if iscell(zseries_paths)

        if isvector(zseries_paths)

            number_zseries = ...
                numel(zseries_paths);

        else

            number_zseries = ...
                size(zseries_paths, 1);

        end

    else

        number_zseries = 1;

    end


    %==============================================================%
    % Boucle ZSeries
    %==============================================================%

    for i = 1:number_zseries

        fprintf('\n');
        fprintf('====================================================\n');
        fprintf('ZSeries %d / %d\n', i, number_zseries);
        fprintf('====================================================\n');


        %==========================================================%
        % Chemin
        %==========================================================%

        if iscell(zseries_paths)

            if isvector(zseries_paths)

                current_zseries_path = ...
                    zseries_paths{i};

            else

                current_zseries_path = ...
                    zseries_paths{i, 1};

            end

        else

            current_zseries_path = ...
                zseries_paths;

        end


        if isempty(current_zseries_path)
            continue;
        end


        fprintf( ...
            'ZSeries : %s\n', ...
            current_zseries_path);


        %==========================================================%
        % Output
        %==========================================================%

        if numel(gcamp_root_folders) >= i

            current_output_folder = ...
                gcamp_root_folders{i};

        else

            current_output_folder = ...
                fileparts(current_zseries_path);

        end


        if isempty(current_output_folder)

            current_output_folder = ...
                current_zseries_path;

        end


        if ~exist(current_output_folder, 'dir')

            mkdir(current_output_folder);

        end


        results_file = ...
            fullfile( ...
                current_output_folder, ...
                'results_zseries.mat');


        legacy_results_movie_file = ...
            fullfile( ...
                current_output_folder, ...
                'results_movie.mat');


        %==========================================================%
        % Dossier summary du recording
        %
        % Comme dans save_mean_image_overviews, output_folders{i}
        % contient déjà le dossier final du recording.
        %==========================================================%

        current_summary_output_folder = '';


        if iscell(output_folders) && ...
                numel(output_folders) >= i && ...
                ~isempty(output_folders{i})

            current_summary_output_folder = ...
                output_folders{i};

        end


        %==========================================================%
        % Identifiants du recording pour le titre du preview
        %==========================================================%

        current_date = '';


        if iscell(current_dates) && ...
                numel(current_dates) >= i && ...
                ~isempty(current_dates{i})

            current_date = ...
                current_dates{i};

        elseif ~iscell(current_dates) && ...
                numel(current_dates) >= i

            current_date = ...
                current_dates(i);

        end


        current_age = '';


        if iscell(current_ages) && ...
                numel(current_ages) >= i && ...
                ~isempty(current_ages{i})

            current_age = ...
                current_ages{i};

        elseif ~iscell(current_ages) && ...
                numel(current_ages) >= i

            current_age = ...
                current_ages(i);

        end


        %==========================================================%
        % Metadata
        %
        % zseries_metadata correspond directement à metadata.ZSeries.
        % La structure elle-même n'est pas indexée par ZSeries :
        % ce sont ses champs qui contiennent une valeur par ZSeries.
        %
        % Exemple :
        %   zseries_metadata.PixelSize_um(i)
        %   zseries_metadata.ZStep_um(i)
        %   zseries_metadata.ZPositions{i}
        %
        % L'indexation est faite directement dans
        % get_metadata_value / get_metadata_numeric_value.
        %==========================================================%


        %==========================================================%
        % Pixel size
        %
        % Certaines métadonnées possèdent PixelSizeX_um /
        % PixelSizeY_um, d'autres un seul champ PixelSize_um.
        %
        % On accepte les deux formats.
        %==========================================================%

        pixel_size_common_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'PixelSize_um', ...
                i, ...
                NaN);


        pixel_size_x_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'PixelSizeX_um', ...
                i, ...
                pixel_size_common_um);


        pixel_size_y_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'PixelSizeY_um', ...
                i, ...
                pixel_size_common_um);


        if ~isfinite(pixel_size_x_um) || ...
                pixel_size_x_um <= 0

            pixel_size_x_um = ...
                1;

        end


        if ~isfinite(pixel_size_y_um) || ...
                pixel_size_y_um <= 0

            pixel_size_y_um = ...
                pixel_size_x_um;

        end


        %==========================================================%
        % Z step
        %
        % IMPORTANT :
        % si ZStep_um est explicitement présent dans les métadonnées,
        % on le conserve. On ne l'écrase plus avec diff(ZPositions).
        %
        % ZPositions n'est utilisé comme fallback que si ZStep_um
        % est absent ou invalide.
        %==========================================================%

        z_step_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'ZStep_um', ...
                i, ...
                NaN);


        z_positions = ...
            get_metadata_value( ...
                zseries_metadata, ...
                'ZPositions', ...
                i, ...
                []);


        z_positions = ...
            normalize_z_positions( ...
                z_positions);


        if ~isfinite(z_step_um) || ...
                z_step_um <= 0

            if ~isempty(z_positions) && ...
                    numel(z_positions) > 1

                valid_dz = ...
                    abs( ...
                        diff( ...
                            z_positions(:)));


                valid_dz = ...
                    valid_dz( ...
                        isfinite(valid_dz) & ...
                        valid_dz > 0);


                if ~isempty(valid_dz)

                    z_step_um = ...
                        median(valid_dz);

                end

            end

        end


        if ~isfinite(z_step_um) || ...
                z_step_um <= 0

            z_step_um = ...
                1;

        end


        fprintf( ...
            'Pixel size : %.4f x %.4f um\n', ...
            pixel_size_x_um, ...
            pixel_size_y_um);


        fprintf( ...
            'Z step     : %.4f um\n', ...
            z_step_um);


        %==========================================================%
        % Boucle locale de traitement / reprocess
        %
        % Si l'utilisateur ouvre des résultats existants en 2D puis
        % clique sur Reprocess, on reboucle sur CETTE ZSeries uniquement
        % en ignorant le results_zseries.mat existant.
        %==========================================================%

        force_reprocess_current = ...
            false;


        while true


        %==========================================================%
        % Résultats existants
        %
        % Priorité :
        %   1) results_zseries.mat
        %   2) ancien results_movie.mat s'il contient réellement
        %      une structure / des champs de ZSeries
        %
        % Aucun recalcul si une ZSeries valide est rechargée.
        %==========================================================%

        use_existing_results = ...
            false;


        loaded_from_file = ...
            '';


        if force_reprocess_current

            loaded_zseries = ...
                [];


            loaded_from_file = ...
                '';


            fprintf( ...
                'Reprocess ZSeries : anciens résultats ignorés pendant le recalcul.\n');

        else

            [ ...
                loaded_zseries, ...
                loaded_from_file ...
            ] = ...
                load_existing_zseries_result( ...
                    results_file, ...
                    legacy_results_movie_file);

        end


        if ~isempty(loaded_zseries)

            use_existing_results = ...
                true;

        end


        %==========================================================%
        % Charger ou traiter
        %==========================================================%

        if use_existing_results

            fprintf( ...
                'Résultats ZSeries rechargés : %s\n', ...
                loaded_from_file);


            zseries = ...
                standardize_zseries_result( ...
                    loaded_zseries);


        else

            fprintf( ...
                'Nouveau traitement ZSeries.\n');


            %======================================================%
            % Paramètres initiaux
            %======================================================%

            detection_opts = ...
                get_default_zseries_detection_opts();


            %======================================================%
            % Volume brut
            %======================================================%

            raw_volume = ...
                reconstruct_raw_zseries_volume( ...
                    current_zseries_path);


            if isempty(raw_volume)

                warning( ...
                    'Impossible de reconstruire : %s', ...
                    current_zseries_path);


                if force_reprocess_current

                    fprintf( ...
                        'Reprocess impossible : anciens résultats conservés.\n');

                end


                break;

            end


            fprintf( ...
                'Volume brut : %d x %d x %d\n', ...
                size(raw_volume, 1), ...
                size(raw_volume, 2), ...
                size(raw_volume, 3));


            %======================================================%
            % Candidats préliminaires
            %
            % Uniquement utilisés comme aide éventuelle au recalage.
            %======================================================%

            fprintf( ...
                'Détection candidats préliminaires...\n');


            [ ...
                registration_candidate_mask_3d, ...
                ~ ...
            ] = ...
                detect_zseries_candidates( ...
                    raw_volume, ...
                    pixel_size_x_um, ...
                    pixel_size_y_um, ...
                    detection_opts);


            %======================================================%
            % Recalage
            %======================================================%

            fprintf( ...
                'Recalage hybride entre plans voisins...\n');


            [ ...
                registered_volume, ...
                registration_shifts_px, ...
                registration_relative_shifts_px, ...
                registration_reference_plane, ...
                registration_method_by_plane, ...
                registration_scores ...
            ] = ...
                register_zseries_hybrid_neighbors( ...
                    raw_volume, ...
                    registration_candidate_mask_3d);


            %======================================================%
            % Tuner interactif 2D uniquement
            %
            % L'utilisateur ne règle ici que la segmentation 2D.
            % Aucun tracking ni filtre 3D n'est exécuté pendant
            % l'utilisation de l'interface.
            %======================================================%

            fprintf( ...
                'Ouverture du tuner de détection 2D...\n');


            [ ...
                detection_opts, ...
                detection_2d_confirmed ...
            ] = ...
                tune_zseries_2d_detection( ...
                    registered_volume, ...
                    pixel_size_x_um, ...
                    pixel_size_y_um, ...
                    detection_opts);


            %======================================================%
            % ANNULER = arrêt immédiat de cette ZSeries
            %
            % Aucun calcul 3D, aucun results_zseries.mat sauvegardé.
            % La prochaine exécution reproposera donc le tuner 2D.
            %======================================================%

            if ~detection_2d_confirmed

                fprintf( ...
                    'Détection 2D annulée : reconstruction 3D ignorée.\n');


                zseries = ...
                    create_empty_zseries_result();


                zseries.path = ...
                    current_zseries_path;


                zseries.pixel_size_x_um = ...
                    pixel_size_x_um;


                zseries.pixel_size_y_um = ...
                    pixel_size_y_um;


                zseries.z_step_um = ...
                    z_step_um;


                zseries.z_positions = ...
                    z_positions;


                zseries.detection_opts = ...
                    detection_opts;


                if force_reprocess_current

                    [ ...
                        previous_zseries, ...
                        previous_results_file ...
                    ] = ...
                        load_existing_zseries_result( ...
                            results_file, ...
                            legacy_results_movie_file);


                    if ~isempty(previous_zseries)

                        zseries = ...
                            standardize_zseries_result( ...
                                previous_zseries);


                        fprintf( ...
                            ['Reprocess annulé : anciens résultats conservés ' ...
                             'depuis %s.\n'], ...
                            previous_results_file);

                    end

                end


                zseries_all(i) = ...
                    zseries;


                break;

            end


            %======================================================%
            % APPLICATION A TOUTES LES FRAMES UNIQUEMENT APRES CONFIRMATION
            %
            % Dans le viewer, seule la frame courante a été segmentée.
            % Ici seulement, après clic sur Confirmer, la courbe de
            % sensibilité et les filtres sont appliqués à tout le stack.
            %======================================================%
            % Reconstruction 3D UNIQUEMENT APRES confirmation 2D
            %======================================================%

            fprintf( ...
                'Détection 2D de tous les plans...\n');


            prepared_detection_volume = ...
                prepare_zseries_detection_volume( ...
                    registered_volume);


            fprintf( ...
                'Reconstruction des cellules dans le volume 3D...\n');


            [ ...
                filtered_volume, ...
                candidate_mask_3d, ...
                rescue_mask_3d, ...
                reconstructed_cell_mask_3d, ...
                cell_mask_3d, ...
                reconstructed_cells_3d, ...
                cells_3d ...
            ] = ...
                reconstruct_zseries_cells_3d( ...
                    registered_volume, ...
                    pixel_size_x_um, ...
                    pixel_size_y_um, ...
                    z_step_um, ...
                    z_positions, ...
                    detection_opts, ...
                    prepared_detection_volume);


            fprintf( ...
                '%d cellule(s) reconstruite(s) avant filtre 3D.\n', ...
                numel(reconstructed_cells_3d));


            fprintf( ...
                '%d cellule(s) retenue(s) après filtre 3D.\n', ...
                numel(cells_3d));


            %======================================================%
            % Structure résultats
            %======================================================%

            zseries = ...
                create_empty_zseries_result();


            zseries.path = ...
                current_zseries_path;


            zseries.pixel_size_x_um = ...
                pixel_size_x_um;


            zseries.pixel_size_y_um = ...
                pixel_size_y_um;


            zseries.z_step_um = ...
                z_step_um;


            zseries.z_positions = ...
                z_positions;


            zseries.raw_volume = ...
                raw_volume;


            zseries.registered_volume = ...
                registered_volume;


            zseries.registration_candidate_mask_3d = ...
                registration_candidate_mask_3d;


            zseries.registration_shifts_px = ...
                registration_shifts_px;


            zseries.registration_relative_shifts_px = ...
                registration_relative_shifts_px;


            zseries.registration_reference_plane = ...
                registration_reference_plane;


            zseries.registration_method_by_plane = ...
                registration_method_by_plane;


            zseries.registration_scores = ...
                registration_scores;


            zseries.detection_opts = ...
                detection_opts;


            zseries.detected_cells_2d_mask_3d = ...
                candidate_mask_3d;


            zseries.rescue_mask_3d = ...
                rescue_mask_3d;


            zseries.reconstructed_cell_mask_3d = ...
                reconstructed_cell_mask_3d;


            zseries.reconstructed_cells_3d = ...
                reconstructed_cells_3d;


            zseries.cell_mask_3d = ...
                cell_mask_3d;


            zseries.filtered_volume = ...
                filtered_volume;


            zseries.cells_3d = ...
                cells_3d;


        end


        %==========================================================%
        % Nettoyage des anciennes sorties APRES reprocess confirmé
        %
        % On attend que le nouveau traitement soit terminé avec succès
        % avant de supprimer les anciennes sorties. Ainsi, une annulation
        % dans le tuner ne détruit jamais le résultat précédent.
        %==========================================================%

        if force_reprocess_current && ...
                ~use_existing_results

            delete_zseries_existing_outputs( ...
                results_file, ...
                current_output_folder, ...
                current_summary_output_folder, ...
                current_automatic_selection, ...
                current_zseries_path);

        end


        %==========================================================%
        % Sauvegarde locale de la détection 2D finale
        %
        % Nouveau traitement : le fichier est remplacé afin de rester
        % strictement synchronisé avec la segmentation courante.
        %
        % Résultats rechargés : le TIFF est recréé uniquement s'il manque,
        % sans relancer la segmentation.
        %
        % Valeurs TIFF :
        %   0 = fond
        %   1 = détection normale
        %   2 = rescue Z
        %==========================================================%

        if ~isempty(zseries.detected_cells_2d_mask_3d)

            save_zseries_2d_detection_local( ...
                zseries.detected_cells_2d_mask_3d, ...
                zseries.rescue_mask_3d, ...
                current_output_folder, ...
                current_zseries_path, ...
                ~use_existing_results);

        end


        %==========================================================%
        % Résumé simple dans la console
        %==========================================================%

        print_zseries_summary( ...
            zseries);


        %==========================================================%
        % Sauvegarde du volume 3D + previews
        %
        % TIFF isotrope :
        %   - gcamp_root uniquement
        %
        % Preview MIP :
        %   - toujours dans gcamp_root
        %   - également dans output_folders si
        %     current_automatic_selection ~= 0
        %
        % Les PNG existants ne sont jamais écrasés.
        % Une preview manquante peut être recréée à partir d'un
        % results_zseries.mat déjà existant, sans relancer la segmentation.
        %==========================================================%

        isotropic_volume = [];


        %==========================================================%
        % Informations affichées dans le titre du preview
        %==========================================================%

        preview_num_frames = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'NumSlices', ...
                i, ...
                NaN);


        if ~isfinite(preview_num_frames) || ...
                preview_num_frames <= 0

            if ~isempty(zseries.registered_volume)

                preview_num_frames = ...
                    size( ...
                        zseries.registered_volume, ...
                        3);

            else

                preview_num_frames = ...
                    NaN;

            end

        end


        preview_z_step_um = ...
            zseries.z_step_um;


        preview_z_start_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'ZStart', ...
                i, ...
                NaN);


        preview_z_end_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'ZEnd', ...
                i, ...
                NaN);


        preview_z_positions = ...
            zseries.z_positions;


        preview_z_positions = ...
            normalize_z_positions( ...
                preview_z_positions);


        if ~isfinite(preview_z_start_um) && ...
                ~isempty(preview_z_positions)

            preview_z_start_um = ...
                preview_z_positions(1);

        end


        if ~isfinite(preview_z_end_um) && ...
                ~isempty(preview_z_positions)

            preview_z_end_um = ...
                preview_z_positions(end);

        end


        [ ...
            expected_tiff_file, ...
            expected_preview_file, ...
            expected_summary_preview_file ...
        ] = ...
            get_zseries_3d_output_paths( ...
                current_output_folder, ...
                current_summary_output_folder, ...
                current_automatic_selection, ...
                current_zseries_path);


        local_preview_needs_save = ...
            ~isempty(expected_preview_file) && ...
            ~isfile(expected_preview_file);


        summary_preview_needs_save = ...
            ~isempty(expected_summary_preview_file) && ...
            ~isfile(expected_summary_preview_file);


        %==========================================================%
        % Nouveau traitement
        %==========================================================%

        if ~use_existing_results

            fprintf( ...
                'Construction du volume isotrope 3D...\n');


            isotropic_volume = ...
                make_isotropic_zseries_volume( ...
                    zseries.filtered_volume, ...
                    zseries.pixel_size_x_um, ...
                    zseries.pixel_size_y_um, ...
                    zseries.z_step_um);


            [ ...
                zseries.image_3d_path, ...
                zseries.image_3d_preview_path ...
            ] = ...
                save_zseries_3d_images( ...
                    isotropic_volume, ...
                    current_output_folder, ...
                    current_summary_output_folder, ...
                    current_automatic_selection, ...
                    current_zseries_path, ...
                    true, ...
                    current_line, ...
                    current_animal, ...
                    current_date, ...
                    current_age, ...
                    preview_num_frames, ...
                    preview_z_step_um, ...
                    preview_z_start_um, ...
                    preview_z_end_um);


            save( ...
                results_file, ...
                'zseries', ...
                '-v7.3');


        %==========================================================%
        % Résultats déjà existants mais preview manquante
        %==========================================================%

        elseif local_preview_needs_save || ...
                summary_preview_needs_save

            fprintf( ...
                ['Preview ZSeries manquante : création depuis les ' ...
                 'résultats existants.\n']);


            isotropic_volume = ...
                make_isotropic_zseries_volume( ...
                    zseries.filtered_volume, ...
                    zseries.pixel_size_x_um, ...
                    zseries.pixel_size_y_um, ...
                    zseries.z_step_um);


            [ ...
                ~, ...
                zseries.image_3d_preview_path ...
            ] = ...
                save_zseries_3d_images( ...
                    isotropic_volume, ...
                    current_output_folder, ...
                    current_summary_output_folder, ...
                    current_automatic_selection, ...
                    current_zseries_path, ...
                    false, ...
                    current_line, ...
                    current_animal, ...
                    current_date, ...
                    current_age, ...
                    preview_num_frames, ...
                    preview_z_step_um, ...
                    preview_z_start_um, ...
                    preview_z_end_um);


            zseries.image_3d_path = ...
                expected_tiff_file;


        else

            zseries.image_3d_path = ...
                expected_tiff_file;


            zseries.image_3d_preview_path = ...
                expected_preview_file;


            fprintf( ...
                'Toutes les previews ZSeries disponibles existent déjà.\n');

        end


        %==========================================================%
        % CHOIX D'AFFICHAGE 2D / 3D
        %
        % 2D :
        %   - réouvre directement l'interface MATLAB de contrôle ;
        %   - rouge = détections normales ;
        %   - cyan  = rescue Z ;
        %   - aucun recalcul de segmentation.
        %
        % 3D :
        %   - ouvre la reconstruction isotrope comme auparavant.
        %
        % Fermer la boîte de dialogue = aucun affichage.
        %==========================================================%

        if use_existing_results

            answer = ...
                questdlg( ...
                    'Résultats ZSeries rechargés. Quel affichage ouvrir ?', ...
                    'ZSeries', ...
                    '2D', ...
                    '3D', ...
                    '2D');

        else

            answer = ...
                questdlg( ...
                    'Quel affichage ouvrir ?', ...
                    'ZSeries', ...
                    '2D', ...
                    '3D', ...
                    '2D');

        end


        %==========================================================%
        % AFFICHAGE 2D DEPUIS LES MASQUES DEJA SAUVEGARDES
        %==========================================================%

        if strcmp(answer, '2D')

            if isempty(zseries.detected_cells_2d_mask_3d)

                warning( ...
                    'Aucune détection 2D sauvegardée pour cette ZSeries.');

            elseif isempty(zseries.registered_volume)

                warning( ...
                    'Volume recalé non disponible pour l''affichage 2D.');

            else

                rescue_mask_to_show = ...
                    zseries.rescue_mask_3d;


                if isempty(rescue_mask_to_show)

                    rescue_mask_to_show = ...
                        false( ...
                            size( ...
                                zseries.detected_cells_2d_mask_3d));

                end


                % detected_cells_2d_mask_3d contient les détections
                % normales + les rescues. On retire donc les rescues
                % pour afficher uniquement les détections normales
                % en rouge.
                normal_mask_to_show = ...
                    zseries.detected_cells_2d_mask_3d & ...
                    ~rescue_mask_to_show;


                review_action = ...
                    show_zseries_rescue_review( ...
                        zseries.registered_volume, ...
                        normal_mask_to_show, ...
                        rescue_mask_to_show, ...
                        use_existing_results);


                if use_existing_results && ...
                        strcmp( ...
                            review_action, ...
                            'reprocess')

                    fprintf( ...
                        ['Reprocess demandé : recalcul complet de cette ' ...
                         'ZSeries.\n']);


                    force_reprocess_current = ...
                        true;


                    continue;

                end

            end


        %==========================================================%
        % AFFICHAGE 3D
        %==========================================================%

        elseif strcmp(answer, '3D')

            if isempty(isotropic_volume)

                fprintf( ...
                    'Construction du volume isotrope pour affichage 3D...\n');


                isotropic_volume = ...
                    make_isotropic_zseries_volume( ...
                        zseries.filtered_volume, ...
                        zseries.pixel_size_x_um, ...
                        zseries.pixel_size_y_um, ...
                        zseries.z_step_um);

            end


            show_zseries_3d_physical( ...
                isotropic_volume);

        end


        fprintf( ...
            'Ajout ZSeries %d / %d à zseries_all.\n', ...
            i, ...
            number_zseries);


        zseries_all(i) = ...
            zseries;


        break;

        end

    end

end



