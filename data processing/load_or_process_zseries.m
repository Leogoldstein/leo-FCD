%==========================================================================%
% NORMALIZE Z POSITIONS
%==========================================================================%

function z_positions = ...
        normalize_z_positions( ...
            raw_z_positions)

    z_positions = [];


    if isempty(raw_z_positions)
        return;
    end


    if isnumeric(raw_z_positions)

        z_positions = ...
            double( ...
                raw_z_positions(:));


    elseif iscell(raw_z_positions)

        values = ...
            cell( ...
                numel(raw_z_positions), ...
                1);


        number_values = ...
            0;


        for k = 1:numel(raw_z_positions)

            current_value = ...
                raw_z_positions{k};


            if isempty(current_value) || ...
                    ~isnumeric(current_value)

                continue;
            end


            current_value = ...
                double( ...
                    current_value(:));


            current_value = ...
                current_value( ...
                    isfinite(current_value));


            if isempty(current_value)
                continue;
            end


            number_values = ...
                number_values + 1;


            values{number_values} = ...
                current_value;

        end


        if number_values > 0

            z_positions = ...
                vertcat( ...
                    values{1:number_values});

        end

    end


    z_positions = ...
        z_positions( ...
            isfinite(z_positions));

end



%==========================================================================%
% GET METADATA VALUE
%
% metadata correspond directement à metadata.ZSeries.
% La structure est scalaire ; ses champs contiennent une valeur par
% ZSeries.
%
% Exemples :
%   metadata.PixelSize_um(i)
%   metadata.ZStep_um(i)
%   metadata.ZPositions{i}
%==========================================================================%

function value = ...
        get_metadata_value( ...
            metadata, ...
            field_name, ...
            index, ...
            default_value)

    value = ...
        default_value;


    if isempty(metadata) || ...
            ~isstruct(metadata)

        return;

    end


    if ~isfield( ...
            metadata, ...
            field_name)

        return;

    end


    field_value = ...
        metadata.(field_name);


    if isempty(field_value)
        return;
    end


    %==============================================================%
    % CELL
    %==============================================================%

    if iscell(field_value)

        if numel(field_value) >= index

            current_value = ...
                field_value{index};

        elseif numel(field_value) == 1

            current_value = ...
                field_value{1};

        else

            return;

        end


    %==============================================================%
    % NUMERIQUE / LOGIQUE
    %==============================================================%

    elseif isnumeric(field_value) || ...
            islogical(field_value)

        if isscalar(field_value)

            current_value = ...
                field_value;

        elseif isvector(field_value)

            if numel(field_value) < index
                return;
            end


            current_value = ...
                field_value(index);

        elseif size(field_value, 1) >= index

            current_value = ...
                field_value(index, :);

        elseif size(field_value, 2) >= index

            current_value = ...
                field_value(:, index);

        else

            return;

        end


    %==============================================================%
    % STRING
    %==============================================================%

    elseif isstring(field_value)

        if isscalar(field_value)

            current_value = ...
                field_value;

        elseif numel(field_value) >= index

            current_value = ...
                field_value(index);

        else

            return;

        end


    %==============================================================%
    % CHAR
    %
    % Une chaîne char simple est considérée comme une valeur commune.
    %==============================================================%

    elseif ischar(field_value)

        current_value = ...
            field_value;


    %==============================================================%
    % STRUCT
    %==============================================================%

    elseif isstruct(field_value)

        if isscalar(field_value)

            current_value = ...
                field_value;

        elseif numel(field_value) >= index

            current_value = ...
                field_value(index);

        else

            return;

        end


    %==============================================================%
    % AUTRE TYPE
    %==============================================================%

    else

        current_value = ...
            field_value;

    end


    if isempty(current_value)
        return;
    end


    value = ...
        current_value;

end



%==========================================================================%
% GET NUMERIC METADATA VALUE
%==========================================================================%

function value = ...
        get_metadata_numeric_value( ...
            metadata, ...
            field_name, ...
            index, ...
            default_value)

    value = ...
        default_value;


    current_value = ...
        get_metadata_value( ...
            metadata, ...
            field_name, ...
            index, ...
            []);


    if isempty(current_value)
        return;
    end


    if isnumeric(current_value) || ...
            islogical(current_value)

        current_value = ...
            current_value(1);


        if isfinite(current_value)

            value = ...
