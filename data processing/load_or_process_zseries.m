    %==============================================================%

    mip_image = ...
        max( ...
            volume_uint16, ...
            [], ...
            3);


    %==============================================================%
    % Preview local
    %==============================================================%

    if ~isempty(preview_file)

        if isfile(preview_file)

            fprintf( ...
                'Preview ZSeries locale déjà existante :\n%s\n', ...
                preview_file);

        else

            save_zseries_preview_figure( ...
                mip_image, ...
                preview_file, ...
                current_line, ...
                current_animal, ...
                current_date, ...
                current_age, ...
                num_frames, ...
                z_step_um, ...
                z_start_um, ...
                z_end_um);


            fprintf( ...
                'Preview ZSeries locale sauvegardée :\n%s\n', ...
                preview_file);

        end

    end


    %==============================================================%
    % Preview summary
    %==============================================================%

    if ~isempty(summary_preview_file)

        if isfile(summary_preview_file)

            fprintf( ...
                'Preview ZSeries summary déjà existante :\n%s\n', ...
                summary_preview_file);

        else

            if ~isfolder(summary_output_folder)

                mkdir( ...
                    summary_output_folder);

            end


            same_destination = ...
                ~isempty(preview_file) && ...
                strcmpi( ...
                    char(preview_file), ...
                    char(summary_preview_file));


            if same_destination

                fprintf( ...
                    ['Preview ZSeries summary identique à la ' ...
                     'destination locale.\n']);

            else

                save_zseries_preview_figure( ...
                    mip_image, ...
                    summary_preview_file, ...
                    current_line, ...
                    current_animal, ...
                    current_date, ...
                    current_age, ...
                    num_frames, ...
                    z_step_um, ...
                    z_start_um, ...
                    z_end_um);


                fprintf( ...
                    'Preview ZSeries summary sauvegardée :\n%s\n', ...
                    summary_preview_file);

            end

        end

    end

end



%==========================================================================%
