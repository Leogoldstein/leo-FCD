%==========================================================================%
% REVIEW RESCUE - AFFICHAGE
%==========================================================================%

function update_zseries_rescue_review_display(fig)

    if ~ishandle(fig)
        return;
    end


    state = ...
        guidata(fig);


    z = ...
        state.current_z;


    current_image = ...
        state.volume(:, :, z);


    if any( ...
            ~isfinite( ...
                state.display_limits(z, :)))

        finite_values = ...
            double( ...
                current_image( ...
                    isfinite(current_image)));


        if isempty(finite_values)

            low_display = ...
                0;


            high_display = ...
                1;

        else

            low_display = ...
                prctile( ...
                    finite_values, ...
                    1);


            high_display = ...
                prctile( ...
                    finite_values, ...
                    99.5);


            if ~isfinite(low_display) || ...
                    ~isfinite(high_display) || ...
                    high_display <= low_display

                low_display = ...
                    min(finite_values);


                high_display = ...
                    max(finite_values);

            end


            if high_display <= low_display

                high_display = ...
                    low_display + ...
                    1;

            end

        end


        state.display_limits(z, :) = ...
            [ ...
                low_display, ...
                high_display];


        guidata( ...
            fig, ...
            state);

    else

        low_display = ...
            state.display_limits(z, 1);


        high_display = ...
            state.display_limits(z, 2);

    end


    ax = ...
        state.ax;


    cla(ax);


    imagesc( ...
        ax, ...
        current_image, ...
        [ ...
            low_display, ...
            high_display]);


    axis(ax, 'image');
    axis(ax, 'off');
    colormap(ax, gray);
    hold(ax, 'on');


    normal_mask = ...
        state.normal_candidate_mask_3d(:, :, z);


    rescue_mask = ...
        state.rescue_mask_3d(:, :, z);


    if any(normal_mask(:))

        contour( ...
            ax, ...
            normal_mask, ...
            [0.5 0.5], ...
            'Color', ...
            [1 0 0], ...
            'LineWidth', ...
            1.5);

    end


    if any(rescue_mask(:))

        contour( ...
            ax, ...
            rescue_mask, ...
            [0.5 0.5], ...
            'Color', ...
            [0 1 1], ...
            'LineWidth', ...
            2.0);

    end


    hold(ax, 'off');


    normal_cc = ...
        bwconncomp( ...
            normal_mask, ...
            8);


    rescue_cc = ...
        bwconncomp( ...
            rescue_mask, ...
            8);


    title( ...
        ax, ...
        sprintf( ...
            'Z %d / %d | %d normale(s) | %d rescue(s)', ...
            z, ...
            state.nz, ...
            normal_cc.NumObjects, ...
            rescue_cc.NumObjects), ...
        'Interpreter', ...
        'none');


    drawnow;

end


%==========================================================================%
% RECONSTRUCT CELLS 3D FROM CONFIRMED 2D DETECTIONS
%
% Etapes :
%   1) détection 2D de tous les plans ;
%   2) association des détections entre plans ;
%   3) reconstruction de chaque track comme un objet 3D indépendant ;
%   4) filtres réellement 3D : volume et extension Z ;
%   5) construction du volume filtré.
%
% Important : on ne fusionne plus les tracks via bwconncomp(26).
% Deux cellules voisines qui se touchent restent donc deux cellules.
%==========================================================================%

function [ ...
        filtered_volume, ...
        candidate_mask_3d, ...
        rescue_mask_3d, ...
        reconstructed_cell_mask_3d, ...
        cell_mask_3d, ...
        reconstructed_cells_3d, ...
        cells_3d ...
    ] = ...
        reconstruct_zseries_cells_3d( ...
            volume, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            z_step_um, ...
            z_positions, ...
            detection_opts, ...
            prepared_detection_volume)

    min_real_detections = detection_opts.min_real_detections;
    max_z_gap_um = detection_opts.max_z_gap_um;
    max_centroid_distance_um = detection_opts.max_centroid_distance_um;
    min_overlap_fraction = detection_opts.min_overlap_fraction;

    min_cell_volume_um3 = detection_opts.min_cell_volume_um3;
    max_cell_volume_um3 = detection_opts.max_cell_volume_um3;
    min_z_extent_um = detection_opts.min_z_extent_um;
    max_z_extent_um = detection_opts.max_z_extent_um;


    [ny, nx, nz] = size(volume);


    %==============================================================%
    % Coordonnées Z physiques
    %
    % Utilise ZPositions si elles sont disponibles et cohérentes.
    % Sinon, utilise le pas Z médian.
    %==============================================================%

    if ~isempty(z_positions) && ...
            numel(z_positions) == nz && ...
            all(isfinite(z_positions))

        z_coordinates_um = ...
            double(z_positions(:));

    else

        z_coordinates_um = ...
            (0:nz - 1)' * ...
            z_step_um;

    end


    plane_size = ny * nx;

    voxel_volume_um3 = ...
        pixel_size_x_um * ...
        pixel_size_y_um * ...
        z_step_um;


    %==============================================================%
    % Détections 2D confirmées
    %==============================================================%

    if nargin >= 7 && ...
            ~isempty(prepared_detection_volume)

        enhanced_volume_for_rescue = ...
            prepared_detection_volume;


        [ ...
            candidate_mask_3d, ...
            detections_by_plane ...
        ] = ...
            detect_zseries_candidates_from_enhanced( ...
                prepared_detection_volume, ...
                pixel_size_x_um, ...
                pixel_size_y_um, ...
                detection_opts);

    else

        enhanced_volume_for_rescue = ...
            prepare_zseries_detection_volume( ...
                volume);


        [ ...
            candidate_mask_3d, ...
            detections_by_plane ...
        ] = ...
            detect_zseries_candidates_from_enhanced( ...
                enhanced_volume_for_rescue, ...
                pixel_size_x_um, ...
                pixel_size_y_um, ...
                detection_opts);

    end


    %==============================================================%
    % RESCUE Z COMPLET - STRICTEMENT APRES CONFIRMATION
    %
    % Aucun rescue n'est execute dans le viewer. A ce stade seulement,
    % tous les plans ont deja ete segmentes avec la sigmoide confirmee.
    %
    % Les detections normales sont conservees separement afin de pouvoir
    % afficher ensuite :
    %   rouge = detection normale
    %   cyan  = detection recuperee par continuite Z
    %==============================================================%

    normal_candidate_mask_3d = ...
        candidate_mask_3d;


    rescue_mask_3d = ...
        false( ...
            size(candidate_mask_3d));


    if isfield(detection_opts, 'z_rescue_enabled') && ...
            detection_opts.z_rescue_enabled

        fprintf( ...
            'Rescue Z bidirectionnel apres confirmation...\n');


        [ ...
            candidate_mask_3d, ...
            detections_by_plane, ...
            rescue_mask_3d ...
        ] = ...
            apply_zseries_z_rescue_full( ...
                enhanced_volume_for_rescue, ...
                candidate_mask_3d, ...
                pixel_size_x_um, ...
                pixel_size_y_um, ...
                detection_opts);


        rescue_cc_3d = ...
            bwconncomp( ...
                rescue_mask_3d, ...
                26);


        fprintf( ...
            'Rescue Z : %d composante(s) ajoutee(s).\n', ...
            rescue_cc_3d.NumObjects);

    end


    %==============================================================%
    % CONTROLE VISUEL APRES CONFIRMATION
    %
    % Aucun recalcul de segmentation ici. On affiche uniquement les
    % masques deja calcules. La fenetre est bloquante : fermer ou cliquer
    % sur Continuer pour lancer ensuite le tracking / la reconstruction 3D.
    %==============================================================%

    show_zseries_rescue_review( ...
        volume, ...
        normal_candidate_mask_3d, ...
        rescue_mask_3d, ...
        false);



    %==============================================================%
    % Tracking entre plans
    %==============================================================%

    tracks = ...
        struct( ...
            'planes', {}, ...
            'centroids', {}, ...
            'median_centroid', {}, ...
            'masks', {});


    for z = 1:nz

        current_detections = detections_by_plane{z};

        if isempty(current_detections)
            continue;
        end


        detection_assigned = ...
            false(1, numel(current_detections));


        active_tracks = [];

        for tr = 1:numel(tracks)

            last_plane = ...
                tracks(tr).planes(end);


            z_gap_um = ...
                abs( ...
                    z_coordinates_um(z) - ...
                    z_coordinates_um(last_plane));


            if z > last_plane && ...
                    z_gap_um <= max_z_gap_um

                active_tracks(end + 1) = tr; %#ok<AGROW>

            end

        end


        for d = 1:numel(current_detections)

            current_centroid = ...
                current_detections(d).Centroid;


            current_mask = ...
                current_detections(d).Mask;


            best_track = [];
            best_score = Inf;


            for a = 1:numel(active_tracks)

                tr = active_tracks(a);

                last_plane = tracks(tr).planes(end);
                plane_gap = z - last_plane;


                z_gap_um = ...
                    abs( ...
                        z_coordinates_um(z) - ...
                        z_coordinates_um(last_plane));


                if z_gap_um > max_z_gap_um
                    continue;
                end


                track_centroid = ...
                    tracks(tr).median_centroid;


                dx_um = ...
                    (current_centroid(1) - track_centroid(1)) * ...
                    pixel_size_x_um;


                dy_um = ...
                    (current_centroid(2) - track_centroid(2)) * ...
                    pixel_size_y_um;


                centroid_distance_um = hypot(dx_um, dy_um);


                if centroid_distance_um > max_centroid_distance_um
                    continue;
                end


                previous_mask = tracks(tr).masks{end};


                intersection_area = ...
                    nnz(previous_mask & current_mask);


                minimum_area = ...
                    min(nnz(previous_mask), nnz(current_mask));


                if minimum_area > 0

                    overlap_fraction = ...
                        intersection_area / minimum_area;

                else

                    overlap_fraction = 0;

                end


                if plane_gap == 1 && ...
                        overlap_fraction < min_overlap_fraction && ...
                        centroid_distance_um > max_centroid_distance_um / 2

                    continue;

                end


                score = ...
                    centroid_distance_um / max_centroid_distance_um - ...
                    overlap_fraction;


                if score < best_score

                    best_score = score;
                    best_track = tr;

                end

            end


            if ~isempty(best_track)

                tracks(best_track).planes(end + 1) = z;
                tracks(best_track).centroids{end + 1} = current_centroid;
                tracks(best_track).masks{end + 1} = current_mask;


                track_centroids = ...
                    vertcat(tracks(best_track).centroids{:});


                tracks(best_track).median_centroid = ...
                    median(track_centroids, 1);


                detection_assigned(d) = true;

            end

        end


        for d = 1:numel(current_detections)

            if detection_assigned(d)
                continue;
            end


            new_track = numel(tracks) + 1;

            tracks(new_track).planes = z;
            tracks(new_track).centroids = {current_detections(d).Centroid};
            tracks(new_track).median_centroid = current_detections(d).Centroid;
            tracks(new_track).masks = {current_detections(d).Mask};

        end

    end


    fprintf('Tracks trouvés       : %d\n', numel(tracks));


    %==============================================================%
    % Reconstruction individuelle de chaque track
    %==============================================================%

    reconstructed_cell_mask_3d = ...
        false(ny, nx, nz);


    reconstructed_cells_3d = ...
        struct( ...
            'VoxelIdxList', {}, ...
            'Volume_um3', {}, ...
            'ZExtent_um', {}, ...
            'Centroid', {}, ...
            'BoundingBox', {}, ...
            'Planes', {}, ...
            'NumRealDetections', {});


    reconstructed_idx = 0;
    interpolated_planes_count = 0;


    for tr = 1:numel(tracks)

        planes = tracks(tr).planes;


        if numel(planes) < min_real_detections
            continue;
        end


        if numel(planes) > 1

            track_z_gaps_um = ...
                abs( ...
                    diff( ...
                        z_coordinates_um(planes)));


            if any(track_z_gaps_um > max_z_gap_um)
                continue;
            end

        end


        voxel_indices = [];
        used_planes = planes;


        %----------------------------------------------------------%
        % Détections réelles
        %----------------------------------------------------------%

        for k = 1:numel(planes)

            z = planes(k);
            idx2d = find(tracks(tr).masks{k});

            voxel_indices = ...
                [ ...
                    voxel_indices; ...
                    idx2d + (z - 1) * plane_size]; %#ok<AGROW>

        end


        %----------------------------------------------------------%
        % Plans manquants autorisés
        %----------------------------------------------------------%

        for k = 1:numel(planes) - 1

            first_plane = planes(k);
            second_plane = planes(k + 1);
            plane_gap = second_plane - first_plane;


            z_gap_um = ...
                abs( ...
                    z_coordinates_um(second_plane) - ...
                    z_coordinates_um(first_plane));


            if plane_gap <= 1 || ...
                    z_gap_um > max_z_gap_um

                continue;
            end


            previous_mask = tracks(tr).masks{k};
            next_mask = tracks(tr).masks{k + 1};


            for missing_plane = first_plane + 1:second_plane - 1

                alpha = ...
                    (missing_plane - first_plane) / plane_gap;


                if alpha < 0.5

                    interpolated_mask = previous_mask;

                elseif alpha > 0.5

                    interpolated_mask = next_mask;

                else

                    interpolated_mask = ...
                        previous_mask | next_mask;

                end


                interpolated_mask = ...
                    imclose( ...
                        interpolated_mask, ...
                        strel('disk', 1));


                interpolated_mask = ...
                    imfill( ...
                        interpolated_mask, ...
                        'holes');


                idx2d = find(interpolated_mask);


                voxel_indices = ...
                    [ ...
                        voxel_indices; ...
                        idx2d + ...
                        (missing_plane - 1) * plane_size]; %#ok<AGROW>


                used_planes(end + 1) = missing_plane; %#ok<AGROW>
                interpolated_planes_count = interpolated_planes_count + 1;

            end

        end


        voxel_indices = unique(voxel_indices);

        if isempty(voxel_indices)
            continue;
        end


        reconstructed_idx = reconstructed_idx + 1;


        reconstructed_cell_mask_3d(voxel_indices) = true;


        [yy, xx, zz] = ...
            ind2sub( ...
                [ny nx nz], ...
                voxel_indices);


        volume_um3 = ...
            numel(voxel_indices) * voxel_volume_um3;


        z_extent_um = ...
            abs( ...
                z_coordinates_um(max(zz)) - ...
                z_coordinates_um(min(zz))) + ...
            z_step_um;


        centroid = ...
            [ ...
                mean(xx), ...
                mean(yy), ...
                mean(zz)];


        bounding_box = ...
            [ ...
                min(xx), ...
                min(yy), ...
                min(zz), ...
                max(xx) - min(xx) + 1, ...
                max(yy) - min(yy) + 1, ...
                max(zz) - min(zz) + 1];


        reconstructed_cells_3d(reconstructed_idx).VoxelIdxList = voxel_indices;
        reconstructed_cells_3d(reconstructed_idx).Volume_um3 = volume_um3;
        reconstructed_cells_3d(reconstructed_idx).ZExtent_um = z_extent_um;
        reconstructed_cells_3d(reconstructed_idx).Centroid = centroid;
        reconstructed_cells_3d(reconstructed_idx).BoundingBox = bounding_box;
        reconstructed_cells_3d(reconstructed_idx).Planes = sort(unique(used_planes));
        reconstructed_cells_3d(reconstructed_idx).NumRealDetections = numel(planes);

    end


    fprintf( ...
        'Cellules reconstruites : %d\n', ...
        numel(reconstructed_cells_3d));


    fprintf( ...
        'Plans interpolés       : %d\n', ...
        interpolated_planes_count);


    %==============================================================%
    % Filtres spécifiques au VOLUME 3D
    %==============================================================%

    cell_mask_3d = ...
        false(ny, nx, nz);


    cells_3d = ...
        struct( ...
            'VoxelIdxList', {}, ...
            'Volume_um3', {}, ...
            'ZExtent_um', {}, ...
            'Centroid', {}, ...
            'BoundingBox', {}, ...
            'Planes', {}, ...
            'NumRealDetections', {});


    cell_idx = 0;


    for obj = 1:numel(reconstructed_cells_3d)

        current_cell = reconstructed_cells_3d(obj);


        if current_cell.Volume_um3 < min_cell_volume_um3 || ...
                current_cell.Volume_um3 > max_cell_volume_um3

            continue;
        end


        if current_cell.ZExtent_um < min_z_extent_um || ...
                current_cell.ZExtent_um > max_z_extent_um

            continue;
        end


        cell_idx = cell_idx + 1;
        cells_3d(cell_idx) = current_cell;


        cell_mask_3d(current_cell.VoxelIdxList) = true;

    end


    fprintf( ...
        'Après filtres volume   : %d\n', ...
        numel(cells_3d));


    %==============================================================%
    % Volume d'intensité final
    %==============================================================%

    filtered_volume = ...
        zeros( ...
            size(volume), ...
            'like', ...
            volume);


    filtered_volume(cell_mask_3d) = ...
        volume(cell_mask_3d);

end



