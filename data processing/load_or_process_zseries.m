%==========================================================================%
% SAVE FINAL 2D DETECTION LOCALLY
%
% Sauvegarde la segmentation 2D finale de chaque plan Z dans un TIFF
% multipage local.
%
% Valeurs :
%   0 = fond
%   1 = détection normale
%   2 = rescue Z
%
% candidate_mask_3d contient déjà les détections normales + les rescues.
% Le fichier est sauvegardé dans le même dossier que results_zseries.mat.
%==========================================================================%

function detection_file = ...
        save_zseries_2d_detection_local( ...
            candidate_mask_3d, ...
            rescue_mask_3d, ...
            output_folder, ...
            zseries_path, ...
            overwrite_existing)

    detection_file = '';


    if nargin < 5 || isempty(overwrite_existing)

        overwrite_existing = ...
            true;

    end


    if isempty(candidate_mask_3d) || ...
            isempty(output_folder)

        return;
    end


    if ~isfolder(output_folder)

        mkdir(output_folder);

    end


    [~, zseries_name] = ...
        fileparts(zseries_path);


    if isempty(zseries_name)

        zseries_name = ...
            'zseries';

    end


    safe_name = ...
        regexprep( ...
            zseries_name, ...
            '[^a-zA-Z0-9_-]', ...
            '_');


    detection_file = ...
        fullfile( ...
            output_folder, ...
            [safe_name '_cells_2D_detection.tif']);


    %==============================================================%
    % Séparation normal / rescue
    %==============================================================%

    if isempty(rescue_mask_3d)

        rescue_mask_3d = ...
            false( ...
                size(candidate_mask_3d));

    end


    normal_mask_3d = ...
        candidate_mask_3d & ...
        ~rescue_mask_3d;


    %==============================================================%
    % Gestion d'un fichier local déjà existant
    %==============================================================%

    if isfile(detection_file)

        if overwrite_existing

            delete(detection_file);

        else

            fprintf( ...
                'Détection 2D locale déjà existante :\n%s\n', ...
                detection_file);

            return;

        end

    end


    [ny, nx, nz] = ...
        size(candidate_mask_3d);


    %==============================================================%
    % TIFF multipage uint8
    %
    % 0 = fond
    % 1 = détection normale
    % 2 = rescue Z
    %==============================================================%

    for z = 1:nz

        detection_image = ...
            zeros( ...
                ny, ...
                nx, ...
                'uint8');


        detection_image( ...
            normal_mask_3d(:, :, z)) = ...
            uint8(1);


        detection_image( ...
            rescue_mask_3d(:, :, z)) = ...
            uint8(2);


        if z == 1

            imwrite( ...
                detection_image, ...
                detection_file, ...
                'tif', ...
                'Compression', ...
                'none');

