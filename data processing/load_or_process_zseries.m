            nx, ...
            nz);


    for z = 1:nz

        candidate_mask_3d(:, :, z) = ...
            candidate_masks_by_plane{z};

    end

end



%==========================================================================%
% SIGMOID SENSITIVITY CURVE
%
% La courbe est parametree de facon graphique :
%
%   shallow_sensitivity
%       niveau du plateau de depart.
%
%   deep_sensitivity
%       niveau du plateau final.
%
%   sensitivity_transition_depth
%       position du point d'inflexion entre 0 et 1.
%
%   sensitivity_transition_width_fraction
%       largeur de la zone de transition entre environ 25 % et 75 %
%       de la sigmoide brute.
%
% Le resultat est normalise pour garantir :
%   frame 1  -> shallow_sensitivity exactement
%   frame nz -> deep_sensitivity exactement
%==========================================================================%

function effective_sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            detection_opts, ...
            z, ...
            nz)

    if isfield(detection_opts, 'shallow_sensitivity') && ...
            ~isempty(detection_opts.shallow_sensitivity)

        shallow_sensitivity = ...
            detection_opts.shallow_sensitivity;

    elseif isfield(detection_opts, 'sensitivity') && ...
            ~isempty(detection_opts.sensitivity)

        shallow_sensitivity = ...
            detection_opts.sensitivity;

    else

        shallow_sensitivity = ...
            45;

    end


    if isfield(detection_opts, 'minimum_sensitivity') && ...
            ~isempty(detection_opts.minimum_sensitivity)

        minimum_sensitivity = ...
            detection_opts.minimum_sensitivity;

    else

        minimum_sensitivity = ...
            -50;

    end


    minimum_sensitivity = ...
        min( ...
            max( ...
                minimum_sensitivity, ...
                -100), ...
            100);


    if isfield(detection_opts, 'deep_sensitivity') && ...
            ~isempty(detection_opts.deep_sensitivity)

        deep_sensitivity = ...
            detection_opts.deep_sensitivity;

    else

        deep_sensitivity = ...
            max( ...
                shallow_sensitivity, ...
                95);

    end


    shallow_sensitivity = ...
        min( ...
            max( ...
                shallow_sensitivity, ...
                minimum_sensitivity), ...
            100);


    deep_sensitivity = ...
        min( ...
            max( ...
                deep_sensitivity, ...
                minimum_sensitivity), ...
            100);


    if nz <= 1

        effective_sensitivity = ...
            shallow_sensitivity;

        return;

    end


    depth_fraction = ...
        (z - 1) / ...
        max( ...
            nz - 1, ...
            1);


    depth_fraction = ...
        min( ...
            max( ...
                depth_fraction, ...
                0), ...
            1);


    if isfield(detection_opts, 'sensitivity_transition_depth') && ...
            ~isempty(detection_opts.sensitivity_transition_depth)

        transition_depth = ...
            detection_opts.sensitivity_transition_depth;

    else

        transition_depth = ...
            0.42;

    end


    transition_depth = ...
        min( ...
            max( ...
                transition_depth, ...
                0), ...
            1);


    if isfield(detection_opts, 'sensitivity_transition_width_fraction') && ...
            ~isempty(detection_opts.sensitivity_transition_width_fraction)

        transition_width = ...
            detection_opts.sensitivity_transition_width_fraction;

    else

        transition_width = ...
            0.20;

    end


    minimum_width = ...
        max( ...
            0.02, ...
            2 / ...
            max(nz - 1, 2));


    transition_width = ...
        min( ...
            max( ...
                transition_width, ...
                minimum_width), ...
            1);


    % Pour une logistique standard, la distance entre les niveaux
    % 25 % et 75 % vaut 2*log(3)/k.
    % On definit donc directement k a partir de la largeur choisie.
    sigmoid_steepness = ...
        2 * ...
        log(3) / ...
        transition_width;


    sigmoid_current = ...
        1 ./ ...
        ( ...
            1 + ...
            exp( ...
                -sigmoid_steepness * ...
                ( ...
                    depth_fraction - ...
                    transition_depth)));


    sigmoid_start = ...
        1 ./ ...
        ( ...
            1 + ...
            exp( ...
                sigmoid_steepness * ...
                transition_depth));


    sigmoid_end = ...
        1 ./ ...
        ( ...
            1 + ...
            exp( ...
                -sigmoid_steepness * ...
                ( ...
                    1 - ...
                    transition_depth)));


    denominator = ...
        sigmoid_end - ...
        sigmoid_start;


    if denominator <= eps

        sigmoid_fraction = ...
            depth_fraction;

    else

        sigmoid_fraction = ...
            ( ...
                sigmoid_current - ...
                sigmoid_start) ./ ...
            denominator;

    end


    sigmoid_fraction = ...
        min( ...
            max( ...
                sigmoid_fraction, ...
                0), ...
            1);


    effective_sensitivity = ...
        shallow_sensitivity + ...
        sigmoid_fraction * ...
        ( ...
            deep_sensitivity - ...
            shallow_sensitivity);


    effective_sensitivity = ...
        min( ...
            max( ...
                effective_sensitivity, ...
                minimum_sensitivity), ...
            100);

end



%==========================================================================%
% DEPTH-ADJUSTED DETECTION OPTIONS
%==========================================================================%

function current_detection_opts = ...
        get_depth_adjusted_detection_opts( ...
            detection_opts, ...
            z, ...
            nz)

    current_detection_opts = ...
        detection_opts;


    current_detection_opts.sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            detection_opts, ...
            z, ...
            nz);

end



%==========================================================================%
% DETECT OBJECTS ON ONE PREPARED PLANE - PICS BRILLANTS
%
% Principe :
%   1) calcul de la reponse soma ;
%   2) recherche de maxima locaux suffisamment proeminents ;
%   3) la sensibilite selectionne les maxima suffisamment brillants ;
%   4) chaque maximum retenu fait croitre SA propre region dans soma_response ;
%   5) nettoyage leger du masque ;
%   6) watershed eventuel pour separer les regions voisines.
%
% IMPORTANT : il n'existe plus de re-detection apres le watershed.
% Une validation de circularite optionnelle peut toutefois etre appliquee aux
% objets deja separes. A min_circularity = 0, elle est totalement desactivee.
%==========================================================================%

function [ ...
        raw_candidate_mask, ...
        retained_candidate_mask, ...
        current_detections, ...
        diagnostics ...
    ] = ...
        detect_zseries_candidates_plane_from_enhanced( ...
            enhanced_image, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            detection_opts)

    want_diagnostics = ...
        nargout >= 4;


    diagnostics = ...
        struct();


    %==============================================================%
    % PARAMETRES
    %==============================================================%

    sensitivity = ...
        detection_opts.sensitivity;



    soma_signal_sigma_um = ...
        detection_opts.soma_signal_sigma_um;


    background_sigma_um = ...
        detection_opts.background_sigma_um;


    min_area_um2 = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'min_area_um2', ...
            60);


    min_circularity = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'min_circularity', ...
            0.50);


    min_circularity = ...
        min( ...
            max( ...
                min_circularity, ...
                0), ...
            1);


    candidate_min_area_um2 = ...
        detection_opts.candidate_min_area_um2;


    peak_smoothing_um = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'peak_smoothing_um', ...
            0.8);


    if isfield(detection_opts, 'watershed_strength') && ...
            ~isempty(detection_opts.watershed_strength)

        watershed_strength = ...
            detection_opts.watershed_strength;

    else

        watershed_strength = ...
            1.00;

    end


    if isfield(detection_opts, 'watershed_smoothing_um') && ...
            ~isempty(detection_opts.watershed_smoothing_um)

        watershed_smoothing_um = ...
            detection_opts.watershed_smoothing_um;

    else

        watershed_smoothing_um = ...
            0.5;

    end


    watershed_core_radius_um = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'watershed_core_radius_um', ...
            3.5);


    if isfield(detection_opts, 'preview_fast_mode') && ...
            ~isempty(detection_opts.preview_fast_mode)

        preview_fast_mode = ...
            logical(detection_opts.preview_fast_mode);

    else

        preview_fast_mode = ...
            false;

    end


    %==============================================================%
    % DIMENSIONS PHYSIQUES
    %==============================================================%

    [ny, nx] = ...
        size(enhanced_image);


    pixel_area_um2 = ...
        pixel_size_x_um * ...
        pixel_size_y_um;


    mean_pixel_size_um = ...
        mean( ...
            [ ...
                pixel_size_x_um, ...
                pixel_size_y_um]);


    soma_sigma_px = ...
        max( ...
            0.5, ...
            soma_signal_sigma_um / ...
            mean_pixel_size_um);


    background_sigma_px = ...
        max( ...
            soma_sigma_px + 1, ...
            background_sigma_um / ...
            mean_pixel_size_um);


    peak_smoothing_px = ...
        max( ...
            0, ...
            peak_smoothing_um / ...
            max(mean_pixel_size_um, eps));


    min_area_px = ...
        max( ...
            1, ...
            round( ...
                min_area_um2 / ...
                pixel_area_um2));


    candidate_min_area_px = ...
        max( ...
            1, ...
            round( ...
                candidate_min_area_um2 / ...
                pixel_area_um2));


    %==============================================================%
    % IMAGE
    %==============================================================%

    image = ...
        single( ...
            enhanced_image);


    image( ...
        ~isfinite(image)) = ...
        0;


    if want_diagnostics

        zero_map = ...
            zeros( ...
                size(image), ...
                'like', ...
                image);


        zero_mask = ...
            false( ...
                size(image));


        diagnostics.normalized_image = image;
        diagnostics.soma_signal = zero_map;
        diagnostics.background = zero_map;
        diagnostics.soma_response = zero_map;
        diagnostics.response_normalized = zero_map;
        diagnostics.peak_response = zero_map;
        diagnostics.local_maxima_mask = zero_mask;
        diagnostics.peak_seed_mask = zero_mask;
        diagnostics.response_growth_mask = zero_mask;
        diagnostics.response_reference = NaN;
        diagnostics.response_seed_threshold = NaN;
        diagnostics.peak_prominence = NaN;
        diagnostics.before_morphology_mask = zero_mask;
        diagnostics.after_morphology_mask = zero_mask;
        diagnostics.after_watershed_mask = zero_mask;
        diagnostics.after_size_mask = zero_mask;
        diagnostics.after_circularity_mask = zero_mask;
        diagnostics.final_mask = zero_mask;

    end


    %==============================================================%
    % 1) SIGNAL A L'ECHELLE D'UN SOMA
    %==============================================================%

    soma_signal = ...
        imgaussfilt( ...
            image, ...
            soma_sigma_px);


    if want_diagnostics
        diagnostics.soma_signal = soma_signal;
    end


    %==============================================================%
    % 2) SOUSTRACTION DU FOND LARGE
    %==============================================================%

    background = ...
        imgaussfilt( ...
            image, ...
            background_sigma_px);


    if want_diagnostics
        diagnostics.background = background;
    end


    soma_response = ...
        soma_signal - ...
        background;


    soma_response = ...
        max( ...
            soma_response, ...
            0);


    if want_diagnostics
        diagnostics.soma_response = soma_response;
    end


    %==============================================================%
    % 3) STATISTIQUES DE LA REPONSE SOMA
    %==============================================================%

    positive_response = ...
        double( ...
            soma_response( ...
                isfinite(soma_response) & ...
                soma_response > 0));


    if isempty(positive_response)

        [ ...
            raw_candidate_mask, ...
            retained_candidate_mask, ...
            current_detections ...
        ] = ...
            empty_zseries_2d_detection( ...
                ny, ...
                nx);

        return;
    end


    response_reference_percentile = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_reference_percentile', ...
            99.9);


    response_reference_percentile = ...
        min( ...
            max( ...
                response_reference_percentile, ...
                90), ...
            100);


    response_reference = ...
        prctile( ...
            positive_response, ...
            response_reference_percentile);


    if ~isfinite(response_reference) || ...
            response_reference <= 0

        response_reference = ...
            max(positive_response);

    end


    if ~isfinite(response_reference) || ...
            response_reference <= 0

        response_reference = ...
            eps;

    end


    response_normalized = ...
        single( ...
            soma_response ./ ...
            max( ...
                response_reference, ...
                eps));


    response_normalized = ...
        min( ...
            max( ...
                response_normalized, ...
                0), ...
            1.5);


    response_median = ...
        median( ...
            positive_response, ...
            'omitnan');


    response_mad = ...
        1.4826 * ...
        median( ...
            abs( ...
                positive_response - ...
                response_median), ...
            'omitnan');


    if ~isfinite(response_mad) || ...
            response_mad <= 0

        response_mad = ...
            max( ...
                0.02 * response_reference, ...
                eps);

    end


    %==============================================================%
    % 4) SENSIBILITE -> BRILLANCE MINIMALE DU PIC
    %==============================================================%

    minimum_sensitivity = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'minimum_sensitivity', ...
            -50);


    sensitivity = ...
        min( ...
            max( ...
                sensitivity, ...
                minimum_sensitivity), ...
            100);


    response_sensitivity_power = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_sensitivity_power', ...
            1.5);


    response_sensitivity_power = ...
        max( ...
            response_sensitivity_power, ...
            0.1);


    % 0..100 pilote la transition stricte -> sensible.
    % Les valeurs negatives ajoutent un regime ultra-strict independant.
    if sensitivity >= 0

        sensitivity_control = ...
            (sensitivity / 100) ^ ...
            response_sensitivity_power;


        negative_strictness = ...
            0;

    else

        sensitivity_control = ...
            0;


        negative_strictness = ...
            min( ...
                max( ...
                    -sensitivity / ...
                    max(abs(minimum_sensitivity), eps), ...
                    0), ...
                1);

    end


    seed_fraction_strict = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_seed_fraction_strict', ...
            0.98);


    seed_fraction_ultrastrict = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_seed_fraction_ultrastrict', ...
            1.25);


    seed_fraction_sensitive = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_seed_fraction_sensitive', ...
            0.10);


    if sensitivity >= 0

        seed_fraction = ...
            seed_fraction_strict + ...
            sensitivity_control * ...
            ( ...
                seed_fraction_sensitive - ...
                seed_fraction_strict);

    else

        seed_fraction = ...
            seed_fraction_strict + ...
            negative_strictness * ...
            ( ...
                seed_fraction_ultrastrict - ...
                seed_fraction_strict);

    end


    mad_multiplier_strict = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_mad_multiplier_strict', ...
            12.0);


    mad_multiplier_ultrastrict = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_mad_multiplier_ultrastrict', ...
            20.0);


    mad_multiplier_sensitive = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_mad_multiplier_sensitive', ...
            1.5);


    if sensitivity >= 0

        mad_multiplier = ...
            mad_multiplier_strict + ...
            sensitivity_control * ...
            ( ...
                mad_multiplier_sensitive - ...
                mad_multiplier_strict);

    else

        mad_multiplier = ...
            mad_multiplier_strict + ...
            negative_strictness * ...
            ( ...
                mad_multiplier_ultrastrict - ...
                mad_multiplier_strict);

    end


    relative_seed_threshold = ...
        seed_fraction * ...
        response_reference;


    robust_seed_threshold = ...
        response_median + ...
        mad_multiplier * ...
        response_mad;


    response_seed_threshold = ...
        max( ...
            relative_seed_threshold, ...
            robust_seed_threshold);


    %==============================================================%
    % 5) MAXIMA LOCAUX PROEMINENTS
    %
    % La detection ne part plus d'un grand masque au-dessus du seuil.
    % Elle part de centres cellulaires potentiels : maxima locaux de la
    % reponse soma. Une structure diffuse sans maximum convaincant est donc
    % eliminee tres tot.
    %==============================================================%

    if peak_smoothing_px > 0

        peak_response = ...
            imgaussfilt( ...
                soma_response, ...
                peak_smoothing_px);

    else

        peak_response = ...
            soma_response;

    end


    prominence_fraction_strict = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'peak_prominence_fraction_strict', ...
            0.25);


    prominence_fraction_ultrastrict = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'peak_prominence_fraction_ultrastrict', ...
            0.45);


    prominence_fraction_sensitive = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'peak_prominence_fraction_sensitive', ...
            0.025);


    if sensitivity >= 0

        prominence_fraction = ...
            prominence_fraction_strict + ...
            sensitivity_control * ...
            ( ...
                prominence_fraction_sensitive - ...
                prominence_fraction_strict);

    else

        prominence_fraction = ...
            prominence_fraction_strict + ...
            negative_strictness * ...
            ( ...
                prominence_fraction_ultrastrict - ...
                prominence_fraction_strict);

    end


    peak_prominence = ...
        max( ...
            eps, ...
            prominence_fraction * ...
            response_reference);


    local_maxima_mask = ...
        imextendedmax( ...
            peak_response, ...
            peak_prominence, ...
            8);


    bright_local_maxima = ...
        local_maxima_mask & ...
        soma_response >= ...
        response_seed_threshold;


    % Un seul pixel seed par maximum/plateau.
    peak_seed_mask = ...
        false( ...
            ny, ...
            nx);


    peak_cc = ...
        bwconncomp( ...
            bright_local_maxima, ...
            8);


    for peak_idx = 1:peak_cc.NumObjects

        current_peak_indices = ...
            peak_cc.PixelIdxList{peak_idx};


        [~, best_local_idx] = ...
            max( ...
                soma_response( ...
                    current_peak_indices));


        best_peak_index = ...
            current_peak_indices( ...
                best_local_idx);


        peak_seed_mask( ...
            best_peak_index) = ...
            true;

    end


    if want_diagnostics
        diagnostics.response_normalized = response_normalized;
        diagnostics.peak_response = peak_response;
        diagnostics.local_maxima_mask = local_maxima_mask;
        diagnostics.peak_seed_mask = peak_seed_mask;
        diagnostics.response_reference = response_reference;
        diagnostics.response_seed_threshold = response_seed_threshold;
        diagnostics.peak_prominence = peak_prominence;
    end


    if ~any(peak_seed_mask(:))

        [ ...
            raw_candidate_mask, ...
            retained_candidate_mask, ...
            current_detections ...
        ] = ...
            empty_zseries_2d_detection( ...
                ny, ...
                nx);


        if want_diagnostics
            diagnostics.before_morphology_mask = false(ny, nx);
            diagnostics.after_morphology_mask = false(ny, nx);
            diagnostics.after_watershed_mask = false(ny, nx);
            diagnostics.after_size_mask = false(ny, nx);
            diagnostics.after_circularity_mask = false(ny, nx);
            diagnostics.final_mask = false(ny, nx);
        end

        return;
    end


    %==============================================================%
    % 6) CROISSANCE INDIVIDUELLE AUTOUR DE CHAQUE PIC
    %
    % Chaque cellule est segmentee relativement a SON propre maximum.
    % Le seuil de croissance est une fraction de la valeur du pic.
    % Cela evite qu'un seuil global fusionne une cellule brillante avec une
    % grande zone diffuse plus faible.
    %==============================================================%

    growth_fraction_strict = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_growth_fraction_strict', ...
            0.65);


    growth_fraction_ultrastrict = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_growth_fraction_ultrastrict', ...
            0.78);


    growth_fraction_sensitive = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            'response_growth_fraction_sensitive', ...
            0.32);


    if sensitivity >= 0

        growth_fraction = ...
            growth_fraction_strict + ...
            sensitivity_control * ...
            ( ...
                growth_fraction_sensitive - ...
                growth_fraction_strict);

    else

        growth_fraction = ...
            growth_fraction_strict + ...
            negative_strictness * ...
            ( ...
                growth_fraction_ultrastrict - ...
                growth_fraction_strict);

    end


    growth_fraction = ...
        min( ...
            max( ...
                growth_fraction, ...
                0.10), ...
            0.95);


    growth_floor = ...
        max( ...
            response_median + ...
            0.25 * response_mad, ...
            0.20 * response_seed_threshold);


    raw_candidate_mask = ...
        false( ...
            ny, ...
            nx);


    seed_indices = ...
        find( ...
            peak_seed_mask);


    for seed_idx = 1:numel(seed_indices)

        current_seed_index = ...
            seed_indices(seed_idx);


        current_peak_value = ...
            double( ...
                soma_response( ...
                    current_seed_index));


        if ~isfinite(current_peak_value) || ...
                current_peak_value <= 0

            continue;
        end


        current_growth_threshold = ...
            max( ...
                growth_floor, ...
                growth_fraction * ...
                current_peak_value);


        current_domain = ...
            soma_response >= ...
            current_growth_threshold;


        [seed_row, seed_col] = ...
            ind2sub( ...
                [ny nx], ...
                current_seed_index);


        current_region = ...
            bwselect( ...
                current_domain, ...
                seed_col, ...
                seed_row, ...
                8);


        raw_candidate_mask = ...
            raw_candidate_mask | ...
            current_region;

    end


    raw_candidate_mask = ...
        bwareaopen( ...
            raw_candidate_mask, ...
            candidate_min_area_px, ...
            8);


    if want_diagnostics
        diagnostics.response_growth_mask = raw_candidate_mask;
        diagnostics.before_morphology_mask = raw_candidate_mask;
    end


    %==============================================================%
    % 7) NETTOYAGE LEGER
    %
    % Pas de closing global : il pouvait relier artificiellement des objets.
    % On remplit simplement les trous puis on retire les tres petits fragments.
    %==============================================================%

    raw_candidate_mask = ...
        imfill( ...
            raw_candidate_mask, ...
            'holes');


    % Important : la taille utilisateur n'est PAS appliquee avant le
    % watershed. Comme dans la premiere version, le watershed doit pouvoir
    % couper librement une grande composante en plusieurs objets. La taille
    % minimale utilisateur sera appliquee seulement APRES la separation.
    if want_diagnostics
        diagnostics.after_morphology_mask = raw_candidate_mask;
    end


    %==============================================================%
    % APERCU RAPIDE EVENTUEL
    %==============================================================%

    if preview_fast_mode

        retained_candidate_mask = ...
            filter_zseries_mask_by_circularity( ...
                raw_candidate_mask, ...
                min_circularity);


        current_detections = ...
            build_zseries_detections_from_mask( ...
                retained_candidate_mask, ...
                pixel_size_x_um, ...
                pixel_size_y_um);


        if want_diagnostics
            diagnostics.after_watershed_mask = raw_candidate_mask;
            diagnostics.after_size_mask = raw_candidate_mask;
            diagnostics.after_circularity_mask = retained_candidate_mask;
            diagnostics.final_mask = retained_candidate_mask;
        end

        return;
    end


    %==============================================================%
    % 8) WATERSHED
    %
    % Il ne peut pas creer de nouvelle cellule. Il sert uniquement a separer
    % les regions voisines issues des pics deja selectionnes. La circularite
    % optionnelle est ensuite evaluee sur les objets deja separes.
    %==============================================================%

    raw_candidate_mask = ...
        split_zseries_candidates_watershed( ...
            raw_candidate_mask, ...
            soma_response, ...
            mean_pixel_size_um, ...
            watershed_core_radius_um, ...
            watershed_strength, ...
            watershed_smoothing_um, ...
            candidate_min_area_px);


    if want_diagnostics
        diagnostics.after_watershed_mask = raw_candidate_mask;
    end


    %==============================================================%
    % FILTRE DE TAILLE APRES WATERSHED
    %
    % C'est volontairement apres la separation. Ainsi, une grosse
    % composante contenant plusieurs cellules peut d'abord etre coupee,
    % puis chaque morceau est evalue individuellement selon Taille min.
    % Cela reproduit le comportement de la premiere version.
    %==============================================================%

    raw_candidate_mask = ...
        bwareaopen( ...
            raw_candidate_mask, ...
            min_area_px, ...
            8);


    if want_diagnostics
        diagnostics.after_size_mask = raw_candidate_mask;
    end


    %==============================================================%
    % VALIDATION DE CIRCULARITE APRES WATERSHED
    %
    % On applique ce filtre uniquement APRES separation des objets afin de
    % ne pas rejeter une composante simplement parce que deux somas se
    % touchaient avant le watershed. min_circularity = 0 desactive le filtre.
    %==============================================================%

    retained_candidate_mask = ...
        filter_zseries_mask_by_circularity( ...
            raw_candidate_mask, ...
            min_circularity);


    current_detections = ...
        build_zseries_detections_from_mask( ...
            retained_candidate_mask, ...
            pixel_size_x_um, ...
            pixel_size_y_um);


    if want_diagnostics
        diagnostics.after_circularity_mask = ...
            retained_candidate_mask;

        diagnostics.final_mask = ...
            retained_candidate_mask;
    end

end


%==========================================================================%
% FILTRE DE CIRCULARITE 2D APRES WATERSHED
%==========================================================================%

function filtered_mask = ...
        filter_zseries_mask_by_circularity( ...
            input_mask, ...
            min_circularity)

    filtered_mask = ...
        logical(input_mask);


    if isempty(filtered_mask) || ...
            ~any(filtered_mask(:)) || ...
            ~isfinite(min_circularity) || ...
            min_circularity <= 0

        return;
    end


    min_circularity = ...
        min( ...
            max( ...
                min_circularity, ...
                0), ...
            1);


    cc = ...
        bwconncomp( ...
            filtered_mask, ...
            8);


    props = ...
        regionprops( ...
            cc, ...
            'Area', ...
            'Perimeter', ...
            'PixelIdxList');


    output_mask = ...
        false( ...
            size(filtered_mask));


    for obj = 1:numel(props)

        area_px = ...
            props(obj).Area;


        perimeter_px = ...
            props(obj).Perimeter;


        if ~isfinite(area_px) || ...
                area_px <= 0 || ...
                ~isfinite(perimeter_px) || ...
                perimeter_px <= 0

            continue;
        end


        circularity = ...
            4 * pi * ...
            area_px / ...
            (perimeter_px ^ 2);


        circularity = ...
            min( ...
                max( ...
                    circularity, ...
                    0), ...
                1);


        if circularity >= min_circularity

            output_mask( ...
                props(obj).PixelIdxList) = ...
                true;

        end

    end


    filtered_mask = ...
        output_mask;

end



%==========================================================================%
% WATERSHED 2D - SEPARATION DES CANDIDATS QUI SE TOUCHENT
%
% VERSION OPTIMISEE : chaque composante est traitee dans sa bounding box
% locale et non sur toute la frame. Cela evite de refaire bwdist,
% imgaussfilt, imextendedmax et watershed sur une image complete pour chaque
% cellule candidate.
%==========================================================================%

function split_mask = ...
        split_zseries_candidates_watershed( ...
            candidate_mask, ...
            soma_response, ...
            mean_pixel_size_um, ...
            min_soma_core_radius_um, ...
            watershed_strength, ...
            watershed_smoothing_um, ...
            candidate_min_area_px)

    split_mask = ...
        false( ...
            size(candidate_mask));


    if isempty(candidate_mask) || ...
            ~any(candidate_mask(:))

        return;
    end


    watershed_strength = ...
        min( ...
            max( ...
                watershed_strength, ...
                0), ...
            1.5);


    if watershed_strength <= 0

        split_mask = ...
            candidate_mask;

        return;
    end


    [ny, nx] = ...
        size(candidate_mask);


    component_cc = ...
        bwconncomp( ...
            candidate_mask, ...
            8);


    smoothing_sigma_px = ...
        max( ...
            0, ...
            watershed_smoothing_um / ...
            max(mean_pixel_size_um, eps));


    expected_core_radius_px = ...
        max( ...
            1, ...
            min_soma_core_radius_um / ...
            max(mean_pixel_size_um, eps));


    % Marge locale suffisante pour que le fond autour du composant soit
    % present et que le lissage ne soit pas coupe au bord du crop.
    local_padding_px = ...
        max( ...
            2, ...
            ceil( ...
                3 * ...
                max(smoothing_sigma_px, 0.5)));


    for component_idx = 1:component_cc.NumObjects

        global_idx = ...
            component_cc.PixelIdxList{component_idx};


        component_area_px = ...
            numel(global_idx);


        if component_area_px < ...
                2 * candidate_min_area_px

            split_mask(global_idx) = ...
                true;

            continue;
        end


        [global_rows, global_cols] = ...
            ind2sub( ...
                [ny nx], ...
                global_idx);


        row_min = ...
            max( ...
                1, ...
                min(global_rows) - ...
                local_padding_px);


        row_max = ...
            min( ...
                ny, ...
                max(global_rows) + ...
                local_padding_px);


        col_min = ...
            max( ...
                1, ...
                min(global_cols) - ...
                local_padding_px);


        col_max = ...
            min( ...
                nx, ...
                max(global_cols) + ...
                local_padding_px);


        local_ny = ...
            row_max - ...
            row_min + ...
            1;


        local_nx = ...
            col_max - ...
            col_min + ...
            1;


        local_rows = ...
            global_rows - ...
            row_min + ...
            1;


        local_cols = ...
            global_cols - ...
            col_min + ...
            1;


        local_idx = ...
            sub2ind( ...
                [local_ny local_nx], ...
                local_rows, ...
                local_cols);


        component_mask = ...
            false( ...
                local_ny, ...
                local_nx);


        component_mask(local_idx) = ...
            true;


        %==========================================================%
        % 1) CARTE DE DISTANCE LOCALE
        %==========================================================%

        distance_map = ...
            single( ...
                bwdist( ...
                    ~component_mask));


        if smoothing_sigma_px > 0

            distance_map = ...
                imgaussfilt( ...
                    distance_map, ...
                    smoothing_sigma_px);

        end


        distance_score = ...
            normalize_zseries_map_inside_mask( ...
                distance_map, ...
                component_mask);


        %==========================================================%
        % 2) REPONSE SOMA LOCALE
        %==========================================================%

        current_soma_response = ...
            single( ...
                soma_response( ...
                    row_min:row_max, ...
                    col_min:col_max));


        current_soma_response( ...
            ~component_mask) = ...
            0;


        if smoothing_sigma_px > 0

            current_soma_response = ...
                imgaussfilt( ...
                    current_soma_response, ...
                    max( ...
                        0.5, ...
                        0.75 * ...
                        smoothing_sigma_px));

        end


        response_score = ...
            normalize_zseries_map_inside_mask( ...
                current_soma_response, ...
                component_mask);


        %==========================================================%
        % 3) SCORE DE CENTRE HYBRIDE
        %==========================================================%

        center_score = ...
            0.70 * ...
            distance_score + ...
            0.30 * ...
            response_score;


        center_score( ...
            ~component_mask) = ...
            0;


        minimum_core_depth_px = ...
            expected_core_radius_px * ...
            ( ...
                0.55 - ...
                0.35 * ...
                watershed_strength);


        minimum_core_depth_px = ...
            max( ...
                0.50, ...
                minimum_core_depth_px);


        valid_center_region = ...
            component_mask & ...
            distance_map >= ...
            minimum_core_depth_px;


        %==========================================================%
        % 4) MARQUEURS
        %==========================================================%

        marker_prominence = ...
            0.18 - ...
            0.16 * ...
            watershed_strength;


        marker_prominence = ...
            max( ...
                0.005, ...
                marker_prominence);


        center_markers = ...
            imextendedmax( ...
                center_score, ...
                marker_prominence, ...
                8);


        center_markers = ...
            center_markers & ...
            valid_center_region;


        marker_cc = ...
            bwconncomp( ...
                center_markers, ...
                8);


        if marker_cc.NumObjects < 2 && ...
                watershed_strength >= 0.35

            center_markers = ...
                imregionalmax( ...
                    center_score, ...
                    8) & ...
                valid_center_region;

        end


        %==========================================================%
        % 5) REDUCTION DES MARQUEURS
        %==========================================================%

        minimum_center_distance_um = ...
            2 * ...
            min_soma_core_radius_um * ...
            ( ...
                1.05 - ...
                0.55 * ...
                watershed_strength);


        minimum_center_distance_um = ...
            max( ...
                1.5, ...
                minimum_center_distance_um);


        minimum_center_distance_px = ...
            minimum_center_distance_um / ...
            max(mean_pixel_size_um, eps);


        center_markers = ...
            reduce_zseries_watershed_markers( ...
                center_markers, ...
                center_score, ...
                minimum_center_distance_px, ...
                component_area_px, ...
                candidate_min_area_px);


        marker_cc = ...
            bwconncomp( ...
                center_markers, ...
                8);


        if marker_cc.NumObjects < 2

            split_mask(global_idx) = ...
                true;

            continue;
        end


        %==========================================================%
        % 6) WATERSHED CONTROLE PAR MARQUEURS
        %==========================================================%

        watershed_surface = ...
            -( ...
                0.65 * ...
                distance_score + ...
                0.35 * ...
                response_score);


        watershed_surface( ...
            ~component_mask) = ...
            1;


        imposed_surface = ...
            imimposemin( ...
                watershed_surface, ...
                center_markers | ...
                ~component_mask, ...
                8);


        watershed_labels = ...
            watershed( ...
                imposed_surface, ...
                8);


        current_split = ...
            component_mask;


        current_split( ...
            watershed_labels == 0) = ...
            false;


        %==========================================================%
        % 7) VALIDATION DE LA COUPURE
        %==========================================================%

        split_cc = ...
            bwconncomp( ...
                current_split, ...
                8);


        valid_piece_count = ...
            0;


        for piece_idx = 1:split_cc.NumObjects

            if numel( ...
                    split_cc.PixelIdxList{piece_idx}) >= ...
                    candidate_min_area_px

                valid_piece_count = ...
                    valid_piece_count + ...
                    1;

            end

        end


        if valid_piece_count >= 2

            current_split = ...
                bwareaopen( ...
                    current_split, ...
                    candidate_min_area_px, ...
                    8);


            local_output = ...
                split_mask( ...
                    row_min:row_max, ...
                    col_min:col_max);


            local_output = ...
                local_output | ...
                current_split;


            split_mask( ...
                row_min:row_max, ...
                col_min:col_max) = ...
                local_output;

        else

            split_mask(global_idx) = ...
                true;

        end

    end

end


%==========================================================================%
% NORMALISE UNE CARTE UNIQUEMENT DANS UN MASQUE
%==========================================================================%

function normalized_map = ...
        normalize_zseries_map_inside_mask( ...
            input_map, ...
            mask)

    normalized_map = ...
        zeros( ...
            size(input_map), ...
            'single');


    values = ...
        single( ...
            input_map(mask));


    values = ...
        values( ...
            isfinite(values));


    if isempty(values)
        return;
    end


    low_value = ...
        min(values);


    high_value = ...
        max(values);


    if ~isfinite(low_value) || ...
            ~isfinite(high_value) || ...
            high_value <= low_value

        return;
    end


    normalized_map = ...
        single( ...
            ( ...
                input_map - ...
                low_value) ./ ...
            ( ...
                high_value - ...
                low_value));


    normalized_map = ...
        min( ...
            max( ...
                normalized_map, ...
                0), ...
            1);


    normalized_map( ...
        ~mask) = ...
        0;

end


%==========================================================================%
% REDUIT LES MARQUEURS DU WATERSHED
%==========================================================================%

function reduced_markers = ...
        reduce_zseries_watershed_markers( ...
            marker_mask, ...
            center_score, ...
            minimum_distance_px, ...
            component_area_px, ...
            candidate_min_area_px)

    reduced_markers = ...
        false( ...
            size(marker_mask));


    marker_cc = ...
        bwconncomp( ...
            marker_mask, ...
            8);


    if marker_cc.NumObjects == 0
        return;
    end


    marker_positions = ...
        zeros( ...
            marker_cc.NumObjects, ...
            2);


    marker_scores = ...
        zeros( ...
            marker_cc.NumObjects, ...
            1);


    marker_indices = ...
        zeros( ...
            marker_cc.NumObjects, ...
            1);


    for marker_idx = 1:marker_cc.NumObjects

        current_indices = ...
            marker_cc.PixelIdxList{marker_idx};


        current_scores = ...
            center_score(current_indices);


        [ ...
            marker_scores(marker_idx), ...
            best_local_idx ...
        ] = ...
            max(current_scores);


        best_index = ...
            current_indices(best_local_idx);


        [row, col] = ...
            ind2sub( ...
                size(marker_mask), ...
                best_index);


        marker_positions(marker_idx, :) = ...
            [col row];


        marker_indices(marker_idx) = ...
            best_index;

    end


    [~, order] = ...
        sort( ...
            marker_scores, ...
            'descend');


    maximum_markers = ...
        max( ...
            2, ...
            min( ...
                8, ...
                floor( ...
                    component_area_px / ...
                    max(candidate_min_area_px, 1))));


    accepted_positions = ...
        zeros( ...
            0, ...
            2);


    accepted_count = ...
        0;


    for order_idx = 1:numel(order)

        marker_idx = ...
            order(order_idx);


        current_position = ...
            marker_positions(marker_idx, :);


        if isempty(accepted_positions)

            accept_marker = ...
                true;

        else

            distances = ...
                sqrt( ...
                    sum( ...
                        ( ...
                            accepted_positions - ...
                            current_position) .^ 2, ...
                        2));


            accept_marker = ...
                all( ...
                    distances >= ...
                    minimum_distance_px);

        end


        if ~accept_marker
            continue;
        end


        accepted_count = ...
            accepted_count + ...
            1;


        reduced_markers( ...
            marker_indices(marker_idx)) = ...
            true;


        accepted_positions( ...
            accepted_count, :) = ...
            current_position;


        if accepted_count >= maximum_markers
            break;
        end

    end


end


%==========================================================================%
% GET DETECTION OPTION OR DEFAULT
%==========================================================================%

function value = ...
        get_detection_option_or_default( ...
            detection_opts, ...
            field_name, ...
            default_value)

    value = ...
        default_value;


    if isstruct(detection_opts) && ...
            isfield(detection_opts, field_name) && ...
            ~isempty(detection_opts.(field_name))

        current_value = ...
            detection_opts.(field_name);


        if isnumeric(current_value) && ...
                isscalar(current_value) && ...
                isfinite(current_value)

            value = ...
                current_value;

        end

    end

end


