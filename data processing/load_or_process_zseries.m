%==========================================================================%
% NORMALIZE Z POSITIONS
%==========================================================================%

function z_positions = ...
        normalize_z_positions( ...
            raw_z_positions)

    z_positions = [];


    if isempty(raw_z_positions)
        return;
    end


    if isnumeric(raw_z_positions)

        z_positions = ...
            double( ...
                raw_z_positions(:));


    elseif iscell(raw_z_positions)

        values = ...
            cell( ...
                numel(raw_z_positions), ...
                1);


        number_values = ...
            0;


        for k = 1:numel(raw_z_positions)

            current_value = ...
                raw_z_positions{k};


            if isempty(current_value) || ...
                    ~isnumeric(current_value)

                continue;
            end


            current_value = ...
                double( ...
                    current_value(:));


            current_value = ...
                current_value( ...
                    isfinite(current_value));


            if isempty(current_value)
                continue;
            end


            number_values = ...
                number_values + 1;


            values{number_values} = ...
                current_value;

        end


        if number_values > 0

            z_positions = ...
                vertcat( ...
                    values{1:number_values});

        end

    end


    z_positions = ...
        z_positions( ...
            isfinite(z_positions));

end



%==========================================================================%
% REMOVE DUPLICATE ZSERIES ENTRIES
%==========================================================================%

function [ ...
        zseries_paths, ...
        gcamp_root_folders, ...
        zseries_metadata, ...
        output_folders, ...
        current_dates, ...
        current_ages ...
    ] = ...
        remove_duplicate_zseries_entries( ...
            zseries_paths, ...
            gcamp_root_folders, ...
            zseries_metadata, ...
            output_folders, ...
            current_dates, ...
            current_ages)

    if isempty(zseries_paths)
        return;
    end


    if iscell(zseries_paths)

        if isvector(zseries_paths)

            original_count = ...
                numel(zseries_paths);

        else

            original_count = ...
                size(zseries_paths, 1);

        end

    else

        original_count = ...
            1;

    end


    if original_count <= 1
        return;
    end


    keep_entry = ...
        true( ...
            original_count, ...
            1);


    seen_keys = ...
        cell( ...
            0, ...
            1);


    for idx_entry = 1:original_count

        if iscell(zseries_paths)

            if isvector(zseries_paths)

                current_path = ...
                    zseries_paths{idx_entry};

            else

                current_path = ...
                    zseries_paths{idx_entry, 1};

            end

        else

            current_path = ...
                zseries_paths;

        end


        if isempty(current_path)
            continue;
        end


        current_key = ...
            char( ...
                string(current_path));


        current_key = ...
            strtrim( ...
                current_key);


        current_key = ...
            strrep( ...
                current_key, ...
                '/', ...
                '\');


        while ~isempty(current_key) && ...
                current_key(end) == '\'

            current_key(end) = [];

        end


        current_key = ...
            lower( ...
                current_key);


        if any( ...
                strcmp( ...
                    seen_keys, ...
                    current_key))

            keep_entry(idx_entry) = ...
                false;

        else

            seen_keys{end + 1, 1} = ...
                current_key;

        end

    end


    keep_indices = ...
        find( ...
            keep_entry);


    duplicate_count = ...
        original_count - ...
        numel(keep_indices);


    if duplicate_count == 0
        return;
    end


    fprintf( ...
        '%d ZSeries dupliquée(s) ignorée(s).\n', ...
        duplicate_count);


    %==============================================================%
    % ZSeries paths
    %==============================================================%

    if iscell(zseries_paths)

        if isvector(zseries_paths)

            zseries_paths = ...
                zseries_paths( ...
                    keep_indices);

        else

            zseries_paths = ...
                zseries_paths( ...
                    keep_indices, ...
                    :);

        end

    end


    %==============================================================%
    % GCaMP root folders correspondants
    %==============================================================%

    if iscell(gcamp_root_folders)

        if isvector(gcamp_root_folders) && ...
                numel(gcamp_root_folders) >= ...
                original_count

            gcamp_root_folders = ...
                gcamp_root_folders( ...
                    keep_indices);

        elseif size(gcamp_root_folders, 1) >= ...
                original_count

            gcamp_root_folders = ...
                gcamp_root_folders( ...
                    keep_indices, ...
                    :);

        end

    end


    %==============================================================%
    % Output folders correspondants
    %==============================================================%

    if iscell(output_folders)

        if isvector(output_folders) && ...
                numel(output_folders) >= ...
                original_count

            output_folders = ...
                output_folders( ...
                    keep_indices);

        elseif size(output_folders, 1) >= ...
                original_count

            output_folders = ...
                output_folders( ...
                    keep_indices, ...
                    :);

        end

    end


    %==============================================================%
    % Dates correspondantes
    %==============================================================%

    if iscell(current_dates) || ...
            isstring(current_dates) || ...
            isnumeric(current_dates) || ...
            islogical(current_dates)

        if isvector(current_dates) && ...
                numel(current_dates) >= ...
                original_count

            current_dates = ...
                current_dates( ...
                    keep_indices);

        elseif size(current_dates, 1) >= ...
                original_count

            current_dates = ...
                current_dates( ...
                    keep_indices, ...
                    :);

        end

    end


    %==============================================================%
    % Ages correspondants
    %==============================================================%

    if iscell(current_ages) || ...
            isstring(current_ages) || ...
            isnumeric(current_ages) || ...
            islogical(current_ages)

        if isvector(current_ages) && ...
                numel(current_ages) >= ...
                original_count

            current_ages = ...
                current_ages( ...
                    keep_indices);

        elseif size(current_ages, 1) >= ...
                original_count

            current_ages = ...
                current_ages( ...
                    keep_indices, ...
                    :);

        end

    end


    %==============================================================%
    % Métadonnées correspondantes
    %
    % metadata.ZSeries est une structure scalaire dont chaque champ
    % contient une valeur par ZSeries. Il faut donc appliquer
    % keep_indices à chacun des champs et non à la structure.
    %==============================================================%

    if isstruct(zseries_metadata) && ...
            isscalar(zseries_metadata)

        metadata_fields = ...
            fieldnames( ...
                zseries_metadata);


        for f = 1:numel(metadata_fields)

            current_field = ...
                metadata_fields{f};


            current_value = ...
                zseries_metadata.(current_field);


            if isempty(current_value)
                continue;
            end


            if iscell(current_value) || ...
                    isstring(current_value)

                if isvector(current_value) && ...
                        numel(current_value) >= original_count

                    zseries_metadata.(current_field) = ...
                        current_value( ...
                            keep_indices);

                elseif size(current_value, 1) >= original_count

                    zseries_metadata.(current_field) = ...
                        current_value( ...
                            keep_indices, ...
                            :);

                end


            elseif isnumeric(current_value) || ...
                    islogical(current_value)

                if isscalar(current_value)

                    % Valeur commune : ne pas modifier.

                elseif isvector(current_value) && ...
                        numel(current_value) >= original_count

                    zseries_metadata.(current_field) = ...
                        current_value( ...
                            keep_indices);

                elseif size(current_value, 1) >= original_count

                    zseries_metadata.(current_field) = ...
                        current_value( ...
                            keep_indices, ...
                            :);

                elseif size(current_value, 2) >= original_count

                    zseries_metadata.(current_field) = ...
                        current_value( ...
                            :, ...
                            keep_indices);

                end


            elseif isstruct(current_value) && ...
                    numel(current_value) >= original_count

                zseries_metadata.(current_field) = ...
                    current_value( ...
                        keep_indices);

            end

        end


    elseif iscell(zseries_metadata)

        if isvector(zseries_metadata) && ...
                numel(zseries_metadata) >= ...
                original_count

            zseries_metadata = ...
                zseries_metadata( ...
                    keep_indices);

        elseif size(zseries_metadata, 1) >= ...
                original_count

            zseries_metadata = ...
                zseries_metadata( ...
                    keep_indices, ...
                    :);

        end

    end

end



%==========================================================================%
% GET METADATA VALUE
%
% metadata correspond directement à metadata.ZSeries.
% La structure est scalaire ; ses champs contiennent une valeur par
% ZSeries.
%
% Exemples :
%   metadata.PixelSize_um(i)
%   metadata.ZStep_um(i)
%   metadata.ZPositions{i}
%==========================================================================%

function value = ...
        get_metadata_value( ...
            metadata, ...
            field_name, ...
            index, ...
            default_value)

    value = ...
        default_value;


    if isempty(metadata) || ...
            ~isstruct(metadata)

        return;

    end


    if ~isfield( ...
            metadata, ...
            field_name)

        return;

    end


    field_value = ...
        metadata.(field_name);


    if isempty(field_value)
        return;
    end


    %==============================================================%
    % CELL
    %==============================================================%

    if iscell(field_value)

        if numel(field_value) >= index

            current_value = ...
                field_value{index};

        elseif numel(field_value) == 1

            current_value = ...
                field_value{1};

        else

            return;

        end


    %==============================================================%
    % NUMERIQUE / LOGIQUE
    %==============================================================%

    elseif isnumeric(field_value) || ...
            islogical(field_value)

        if isscalar(field_value)

            current_value = ...
                field_value;

        elseif isvector(field_value)

            if numel(field_value) < index
                return;
            end


            current_value = ...
                field_value(index);

        elseif size(field_value, 1) >= index

            current_value = ...
                field_value(index, :);

        elseif size(field_value, 2) >= index

            current_value = ...
                field_value(:, index);

        else

            return;

        end


    %==============================================================%
    % STRING
    %==============================================================%

    elseif isstring(field_value)

        if isscalar(field_value)

            current_value = ...
                field_value;

        elseif numel(field_value) >= index

            current_value = ...
                field_value(index);

        else

            return;

        end


    %==============================================================%
    % CHAR
    %
    % Une chaîne char simple est considérée comme une valeur commune.
    %==============================================================%

    elseif ischar(field_value)

        current_value = ...
            field_value;


    %==============================================================%
    % STRUCT
    %==============================================================%

    elseif isstruct(field_value)

        if isscalar(field_value)

            current_value = ...
                field_value;

        elseif numel(field_value) >= index

            current_value = ...
                field_value(index);

        else

            return;

        end


    %==============================================================%
    % AUTRE TYPE
    %==============================================================%

    else

        current_value = ...
            field_value;

    end


    if isempty(current_value)
        return;
    end


    value = ...
        current_value;

end



%==========================================================================%
% GET NUMERIC METADATA VALUE
%==========================================================================%

function value = ...
        get_metadata_numeric_value( ...
            metadata, ...
            field_name, ...
            index, ...
            default_value)

    value = ...
        default_value;


    current_value = ...
        get_metadata_value( ...
            metadata, ...
            field_name, ...
            index, ...
            []);


    if isempty(current_value)
        return;
    end


    if isnumeric(current_value) || ...
            islogical(current_value)

        current_value = ...
            current_value(1);


        if isfinite(current_value)

            value = ...
                double(current_value);

        end

    end

end