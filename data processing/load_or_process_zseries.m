function zseries_all = load_or_process_zseries( ...
        zseries_paths, ...
        gcamp_root_folders, ...
        zseries_metadata, ...
        output_folders, ...
        current_automatic_selection, ...
        processing_mode, ...
        data, ...
        current_line, ...
        current_animal, ...
        current_dates, ...
        current_ages)

    if nargin < 4 || isempty(output_folders)
        output_folders = {};
    end


    if nargin < 5 || isempty(current_automatic_selection)
        current_automatic_selection = 0;
    end


    if nargin < 6 || isempty(processing_mode)
        processing_mode = ...
            'interactive';
    end


    if ~ismember( ...
            processing_mode, ...
            {'load_only', 'interactive'})

        error( ...
            ['processing_mode doit être ''load_only'' ' ...
             'ou ''interactive''.']);

    end


    if nargin < 7 || isempty(data)
        data = struct();
    end


    if nargin < 8
        current_line = '';
    end


    if nargin < 9
        current_animal = '';
    end


    if nargin < 10 || isempty(current_dates)
        current_dates = {};
    end


    if nargin < 11 || isempty(current_ages)
        current_ages = {};
    end

    %==============================================================%
    % LOAD OR PROCESS ZSERIES
    %
    % processing_mode :
    %   'load_only'   -> data.ZSeries d'abord, puis disque en fallback ;
    %                    aucun calcul, aucune interface, aucune écriture.
    %   'interactive' -> même priorité au cache mémoire, puis comportement
    %                    interactif habituel avec traitement/reprocess.
    %
    % Pipeline interactif :
    %
    %   1) Reconstruction du stack brut
    %
    %   2) Détection préliminaire permissive
    %      utilisée uniquement comme aide au recalage
    %
    %   3) Recalage hybride entre plans voisins
    %
    %   4) Application unique des shifts aux images brutes
    %
    %   5) Interface interactive 2D uniquement :
    %        - sensibilité appliquée directement à la réponse soma
    %        - aire minimale
    %        - séparation watershed
    %
    %   6) Après confirmation : détection 2D sur tous les plans
    %      + rescue Z éventuel
    %
    %   7) Validation volumique 3D des masques 2D :
    %        - volume
    %        - nombre minimal de plans Z
    %        - extension Z
    %      sans reconstruction ni tracking de cellules 3D
    %
    %   8) Projection Z directe des détections 2D validées
    %
    %   9) Sauvegarde results_zseries.mat + PNG de projection Z
    %
    %==============================================================%

    zseries_all = ...
        repmat( ...
            create_empty_zseries_result(), ...
            0, ...
            1);


    if isempty(zseries_paths)
        return;
    end


    %==============================================================%
    % Nombre de ZSeries
    %==============================================================%

    if iscell(zseries_paths)

        if isvector(zseries_paths)

            number_zseries = ...
                numel(zseries_paths);

        else

            number_zseries = ...
                size(zseries_paths, 1);

        end

    else

        number_zseries = 1;

    end


    %==============================================================%
    % Boucle ZSeries
    %==============================================================%

    for i = 1:number_zseries

        fprintf('\n');
        fprintf('====================================================\n');
        fprintf('ZSeries %d / %d\n', i, number_zseries);
        fprintf('====================================================\n');


        %==========================================================%
        % Chemin
        %==========================================================%

        if iscell(zseries_paths)

            if isvector(zseries_paths)

                current_zseries_path = ...
                    zseries_paths{i};

            else

                current_zseries_path = ...
                    zseries_paths{i, 1};

            end

        else

            current_zseries_path = ...
                zseries_paths;

        end


        if isempty(current_zseries_path)
            continue;
        end


        fprintf( ...
            'ZSeries : %s\n', ...
            current_zseries_path);


        %==========================================================%
        % Output
        %==========================================================%

        if numel(gcamp_root_folders) >= i

            current_output_folder = ...
                gcamp_root_folders{i};

        else

            current_output_folder = ...
                fileparts(current_zseries_path);

        end


        if isempty(current_output_folder)

            current_output_folder = ...
                current_zseries_path;

        end


        if ~exist(current_output_folder, 'dir') && ...
                strcmp(processing_mode, 'interactive')

            mkdir(current_output_folder);

        end


        results_file = ...
            fullfile( ...
                current_output_folder, ...
                'results_zseries.mat');


        legacy_results_movie_file = ...
            fullfile( ...
                current_output_folder, ...
                'results_movie.mat');


        %==========================================================%
        % Dossier summary du recording
        %
        % Comme dans save_mean_image_overviews, output_folders{i}
        % contient déjà le dossier final du recording.
        %==========================================================%

        current_summary_output_folder = '';


        if iscell(output_folders) && ...
                numel(output_folders) >= i && ...
                ~isempty(output_folders{i})

            current_summary_output_folder = ...
                output_folders{i};

        end


        %==========================================================%
        % Identifiants du recording pour le titre du preview
        %==========================================================%

        current_date = '';


        if iscell(current_dates) && ...
                numel(current_dates) >= i && ...
                ~isempty(current_dates{i})

            current_date = ...
                current_dates{i};

        elseif ~iscell(current_dates) && ...
                numel(current_dates) >= i

            current_date = ...
                current_dates(i);

        end


        current_age = '';


        if iscell(current_ages) && ...
                numel(current_ages) >= i && ...
                ~isempty(current_ages{i})

            current_age = ...
                current_ages{i};

        elseif ~iscell(current_ages) && ...
                numel(current_ages) >= i

            current_age = ...
                current_ages(i);

        end


        %==========================================================%
        % Metadata
        %
        % zseries_metadata correspond directement à metadata.ZSeries.
        % La structure elle-même n'est pas indexée par ZSeries :
        % ce sont ses champs qui contiennent une valeur par ZSeries.
        %
        % Exemple :
        %   zseries_metadata.PixelSize_um(i)
        %   zseries_metadata.ZStep_um(i)
        %   zseries_metadata.ZPositions{i}
        %
        % L'indexation est faite directement dans
        % get_metadata_value / get_metadata_numeric_value.
        %==========================================================%


        %==========================================================%
        % Pixel size
        %
        % Certaines métadonnées possèdent PixelSizeX_um /
        % PixelSizeY_um, d'autres un seul champ PixelSize_um.
        %
        % On accepte les deux formats.
        %==========================================================%

        pixel_size_common_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'PixelSize_um', ...
                i, ...
                NaN);


        pixel_size_x_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'PixelSizeX_um', ...
                i, ...
                pixel_size_common_um);


        pixel_size_y_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'PixelSizeY_um', ...
                i, ...
                pixel_size_common_um);


        if ~isfinite(pixel_size_x_um) || ...
                pixel_size_x_um <= 0

            pixel_size_x_um = ...
                1;

        end


        if ~isfinite(pixel_size_y_um) || ...
                pixel_size_y_um <= 0

            pixel_size_y_um = ...
                pixel_size_x_um;

        end


        %==========================================================%
        % Z step
        %
        % IMPORTANT :
        % si ZStep_um est explicitement présent dans les métadonnées,
        % on le conserve. On ne l'écrase plus avec diff(ZPositions).
        %
        % ZPositions n'est utilisé comme fallback que si ZStep_um
        % est absent ou invalide.
        %==========================================================%

        z_step_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'ZStep_um', ...
                i, ...
                NaN);


        z_positions = ...
            get_metadata_value( ...
                zseries_metadata, ...
                'ZPositions', ...
                i, ...
                []);


        z_positions = ...
            normalize_z_positions( ...
                z_positions);


        if ~isfinite(z_step_um) || ...
                z_step_um <= 0

            if ~isempty(z_positions) && ...
                    numel(z_positions) > 1

                valid_dz = ...
                    abs( ...
                        diff( ...
                            z_positions(:)));


                valid_dz = ...
                    valid_dz( ...
                        isfinite(valid_dz) & ...
                        valid_dz > 0);


                if ~isempty(valid_dz)

                    z_step_um = ...
                        median(valid_dz);

                end

            end

        end


        if ~isfinite(z_step_um) || ...
                z_step_um <= 0

            z_step_um = ...
                1;

        end


        fprintf( ...
            'Pixel size : %.4f x %.4f um\n', ...
            pixel_size_x_um, ...
            pixel_size_y_um);


        fprintf( ...
            'Z step     : %.4f um\n', ...
            z_step_um);


        %==========================================================%
        % Boucle locale de traitement / reprocess
        %
        % Si l'utilisateur ouvre des résultats existants en 2D puis
        % clique sur Reprocess, on reboucle sur CETTE ZSeries uniquement
        % en ignorant le results_zseries.mat existant.
        %==========================================================%

        force_reprocess_current = ...
            false;


        while true


        %==========================================================%
        % Résultats existants
        %
        % Priorité :
        %   1) data.ZSeries(i)
        %   2) results_zseries.mat
        %   3) ancien results_movie.mat s'il contient réellement
        %      une structure / des champs de ZSeries
        %
        % Les ZSeries ne sont plus dédupliquées ici : l'indice i reste
        % donc identique dans zseries_paths, metadata et data.ZSeries.
        %
        % En cas de Reprocess, le cache mémoire et les fichiers existants
        % sont volontairement ignorés.
        %==========================================================%

        use_existing_results = ...
            false;


        loaded_zseries = ...
            [];


        loaded_from = ...
            '';


        if force_reprocess_current

            fprintf( ...
                ['Reprocess ZSeries : cache data et anciens résultats ' ...
                 'ignorés pendant le recalcul.\n']);

        else

            %======================================================%
            % 1) Cache mémoire : data.ZSeries(i)
            %======================================================%

            if isfield(data, 'ZSeries') && ...
                    isstruct(data.ZSeries) && ...
                    numel(data.ZSeries) >= i && ...
                    is_valid_zseries_result(data.ZSeries(i))

                loaded_zseries = ...
                    data.ZSeries(i);


                use_existing_results = ...
                    true;


                loaded_from = ...
                    'data.ZSeries';


                fprintf( ...
                    'ZSeries déjà disponible en mémoire : data.ZSeries(%d)\n', ...
                    i);

            else

                %==================================================%
                % 2) Fallback disque uniquement si nécessaire
                %==================================================%

                [ ...
                    loaded_zseries, ...
                    loaded_from_file ...
                ] = ...
                    load_existing_zseries_result( ...
                        results_file, ...
                        legacy_results_movie_file);


                if ~isempty(loaded_zseries)

                    use_existing_results = ...
                        true;


                    loaded_from = ...
                        loaded_from_file;


                    fprintf( ...
                        'Résultats ZSeries chargés depuis le disque : %s\n', ...
                        loaded_from_file);

                end

            end

        end


        %==========================================================%
        % Charger ou traiter
        %==========================================================%

        if use_existing_results

            zseries = ...
                standardize_zseries_result( ...
                    loaded_zseries);


            %======================================================%
            % LOAD ONLY : résultat déjà disponible
            %
            % Sortie immédiate : aucune création de TIFF/PNG, aucune
            % interface et aucune écriture disque.
            %======================================================%

            if strcmp( ...
                    processing_mode, ...
                    'load_only')

                fprintf( ...
                    'Mode load_only : ZSeries récupérée depuis %s.\n', ...
                    loaded_from);


                zseries_all(i) = ...
                    zseries;


                break;

            end


        else

            %======================================================%
            % LOAD ONLY : rien en mémoire et rien sur disque
            %======================================================%

            if strcmp( ...
                    processing_mode, ...
                    'load_only')

                fprintf( ...
                    ['Mode load_only : aucun résultat ZSeries disponible ' ...
                     'dans data ou sur disque. ZSeries ignorée.\n']);


                zseries = ...
                    create_empty_zseries_result();


                zseries.path = ...
                    current_zseries_path;


                zseries.pixel_size_x_um = ...
                    pixel_size_x_um;


                zseries.pixel_size_y_um = ...
                    pixel_size_y_um;


                zseries.z_step_um = ...
                    z_step_um;


                zseries.z_positions = ...
                    z_positions;


                zseries_all(i) = ...
                    zseries;


                break;

            end


            fprintf( ...
                'Nouveau traitement ZSeries.\n');


            %======================================================%
            % Paramètres initiaux
            %======================================================%

            detection_opts = ...
                get_default_zseries_detection_opts();


            %======================================================%
            % Volume brut
            %======================================================%

            raw_volume = ...
                reconstruct_raw_zseries_volume( ...
                    current_zseries_path);


            if isempty(raw_volume)

                warning( ...
                    'Impossible de reconstruire : %s', ...
                    current_zseries_path);


                if force_reprocess_current

                    fprintf( ...
                        'Reprocess impossible : anciens résultats conservés.\n');

                end


                break;

            end


            fprintf( ...
                'Volume brut : %d x %d x %d\n', ...
                size(raw_volume, 1), ...
                size(raw_volume, 2), ...
                size(raw_volume, 3));


            %======================================================%
            % Candidats préliminaires
            %
            % Uniquement utilisés comme aide éventuelle au recalage.
            %======================================================%

            fprintf( ...
                'Détection candidats préliminaires...\n');


            [ ...
                registration_candidate_mask_3d, ...
                ~ ...
            ] = ...
                detect_zseries_candidates( ...
                    raw_volume, ...
                    pixel_size_x_um, ...
                    pixel_size_y_um, ...
                    detection_opts);


            %======================================================%
            % Recalage
            %======================================================%

            fprintf( ...
                'Recalage hybride entre plans voisins...\n');


            [ ...
                registered_volume, ...
                registration_shifts_px, ...
                registration_relative_shifts_px, ...
                registration_reference_plane, ...
                registration_method_by_plane, ...
                registration_scores ...
            ] = ...
                register_zseries_hybrid_neighbors( ...
                    raw_volume, ...
                    registration_candidate_mask_3d);


            %======================================================%
            % Tuner interactif 2D uniquement
            %
            % L'utilisateur ne règle ici que la segmentation 2D.
            % Aucun tracking ni filtre 3D n'est exécuté pendant
            % l'utilisation de l'interface.
            %======================================================%

            fprintf( ...
                'Ouverture du tuner de détection 2D...\n');


            [ ...
                detection_opts, ...
                detection_2d_confirmed ...
            ] = ...
                tune_zseries_2d_detection( ...
                    registered_volume, ...
                    pixel_size_x_um, ...
                    pixel_size_y_um, ...
                    detection_opts);


            %======================================================%
            % ANNULER = arrêt immédiat de cette ZSeries
            %
            % Aucun traitement complet, aucun results_zseries.mat sauvegardé.
            % La prochaine exécution reproposera donc le tuner 2D.
            %======================================================%

            if ~detection_2d_confirmed

                fprintf( ...
                    'Détection 2D annulée : traitement complet ignoré.\n');


                zseries = ...
                    create_empty_zseries_result();


                zseries.path = ...
                    current_zseries_path;


                zseries.pixel_size_x_um = ...
                    pixel_size_x_um;


                zseries.pixel_size_y_um = ...
                    pixel_size_y_um;


                zseries.z_step_um = ...
                    z_step_um;


                zseries.z_positions = ...
                    z_positions;


                zseries.detection_opts = ...
                    detection_opts;


                if force_reprocess_current

                    [ ...
                        previous_zseries, ...
                        previous_results_file ...
                    ] = ...
                        load_existing_zseries_result( ...
                            results_file, ...
                            legacy_results_movie_file);


                    if ~isempty(previous_zseries)

                        zseries = ...
                            standardize_zseries_result( ...
                                previous_zseries);


                        fprintf( ...
                            ['Reprocess annulé : anciens résultats conservés ' ...
                             'depuis %s.\n'], ...
                            previous_results_file);

                    end

                end


                zseries_all(i) = ...
                    zseries;


                break;

            end


            %======================================================%
            % APPLICATION A TOUS LES PLANS UNIQUEMENT APRES CONFIRMATION
            %
            % Dans le viewer, seule la frame courante a été segmentée.
            % Ici seulement, après clic sur Confirmer, la courbe de
            % sensibilité et les filtres 2D sont appliqués à tout le stack.
            %
            % IMPORTANT : aucune reconstruction / aucun tracking 3D.
            % Les masques finaux restent indépendants plan par plan.
            %======================================================%

            fprintf( ...
                'Détection 2D de tous les plans...\n');


            prepared_detection_volume = ...
                prepare_zseries_detection_volume( ...
                    registered_volume);


            [ ...
                candidate_mask_3d, ...
                ~ ...
            ] = ...
                detect_zseries_candidates_from_enhanced( ...
                    prepared_detection_volume, ...
                    pixel_size_x_um, ...
                    pixel_size_y_um, ...
                    detection_opts);


            %======================================================%
            % RESCUE Z APRES CONFIRMATION
            %
            % Le rescue reste un complément de la segmentation 2D :
            % il ajoute éventuellement une détection sur un plan voisin,
            % mais aucune cellule 3D n'est reconstruite ensuite.
            %======================================================%

            normal_candidate_mask_3d = ...
                candidate_mask_3d;


            rescue_mask_3d = ...
                false( ...
                    size(candidate_mask_3d));


            if isfield(detection_opts, 'z_rescue_enabled') && ...
                    detection_opts.z_rescue_enabled

                fprintf( ...
                    'Rescue Z bidirectionnel après confirmation...\n');


                [ ...
                    candidate_mask_3d, ...
                    rescue_mask_3d ...
                ] = ...
                    apply_zseries_z_rescue_full( ...
                        prepared_detection_volume, ...
                        candidate_mask_3d, ...
                        pixel_size_x_um, ...
                        pixel_size_y_um, ...
                        detection_opts);

            end


            %======================================================%
            % VALIDATION 3D DES MASQUES 2D
            %
            % IMPORTANT : il ne s'agit PAS d'une reconstruction de cellules
            % 3D ni d'un tracking entre plans. On conserve les masques 2D
            % tels quels, puis on valide leur coherence volumique dans le
            % stack : volume, nombre de plans Z occupes et extension Z.
            %
            % Les voxels appartenant a une composante 3D rejetee sont retires
            % des masques 2D finaux. La sortie reste ensuite une projection Z
            % directe des detections 2D validees.
            %======================================================%

            fprintf( ...
                'Validation 3D des masques 2D...\n');


            [ ...
                candidate_mask_3d, ...
                volume_filter_stats ...
            ] = ...
                filter_zseries_detection_volume_3d( ...
                    candidate_mask_3d, ...
                    pixel_size_x_um, ...
                    pixel_size_y_um, ...
                    z_step_um, ...
                    detection_opts);


            % Synchronise les deux couches d'affichage avec le masque final
            % valide. Un objet retire par le filtre 3D ne doit plus apparaitre
            % ni comme detection normale ni comme rescue.
            normal_candidate_mask_3d = ...
                normal_candidate_mask_3d & ...
                candidate_mask_3d;


            rescue_mask_3d = ...
                rescue_mask_3d & ...
                candidate_mask_3d;


            %======================================================%
            % CONTROLE VISUEL DES MASQUES 2D FINAUX
            %======================================================%

            show_zseries_rescue_review( ...
                registered_volume, ...
                normal_candidate_mask_3d, ...
                rescue_mask_3d, ...
                false);


            %======================================================%
            % Structure résultats
            %======================================================%

            zseries = ...
                create_empty_zseries_result();


            zseries.path = ...
                current_zseries_path;


            zseries.pixel_size_x_um = ...
                pixel_size_x_um;


            zseries.pixel_size_y_um = ...
                pixel_size_y_um;


            zseries.z_step_um = ...
                z_step_um;


            zseries.z_positions = ...
                z_positions;


            zseries.raw_volume = ...
                raw_volume;


            zseries.registered_volume = ...
                registered_volume;


            zseries.registration_candidate_mask_3d = ...
                registration_candidate_mask_3d;


            zseries.registration_shifts_px = ...
                registration_shifts_px;


            zseries.registration_relative_shifts_px = ...
                registration_relative_shifts_px;


            zseries.registration_reference_plane = ...
                registration_reference_plane;


            zseries.registration_method_by_plane = ...
                registration_method_by_plane;


            zseries.registration_scores = ...
                registration_scores;


            zseries.detection_opts = ...
                detection_opts;


            zseries.detected_cells_2d_mask_3d = ...
                candidate_mask_3d;


            zseries.rescue_mask_3d = ...
                rescue_mask_3d;


            zseries.volume_filter_stats = ...
                volume_filter_stats;


            % Champs historiques conservés pour compatibilité avec les
            % anciens fichiers / appels, mais aucune donnée 3D n'est créée.
            zseries.reconstructed_cell_mask_3d = [];
            zseries.reconstructed_cells_3d = [];
            zseries.cell_mask_3d = [];
            zseries.filtered_volume = [];
            zseries.cells_3d = [];


        end


        %==========================================================%
        % Nettoyage des anciennes sorties APRES reprocess confirmé
        %
        % On attend que le nouveau traitement soit terminé avec succès
        % avant de supprimer les anciennes sorties. Ainsi, une annulation
        % dans le tuner ne détruit jamais le résultat précédent.
        %==========================================================%

        if force_reprocess_current && ...
                ~use_existing_results

            delete_zseries_existing_outputs( ...
                results_file, ...
                current_output_folder, ...
                current_summary_output_folder, ...
                current_automatic_selection, ...
                current_zseries_path);

        end


        %==========================================================%
        % Sauvegarde locale de la détection 2D finale
        %
        % Nouveau traitement : le fichier est remplacé afin de rester
        % strictement synchronisé avec la segmentation courante.
        %
        % Résultats rechargés : le TIFF est recréé uniquement s'il manque,
        % sans relancer la segmentation.
        %
        % Valeurs TIFF :
        %   0 = fond
        %   1 = détection normale
        %   2 = rescue Z
        %==========================================================%

        if ~isempty(zseries.detected_cells_2d_mask_3d)

            save_zseries_2d_detection_local( ...
                zseries.detected_cells_2d_mask_3d, ...
                zseries.rescue_mask_3d, ...
                current_output_folder, ...
                current_zseries_path, ...
                ~use_existing_results);

        end


        %==========================================================%
        % Résumé simple dans la console
        %==========================================================%

        print_zseries_summary( ...
            zseries);


        %==========================================================%
        % PROJECTION Z DES DETECTIONS 2D
        %
        % Aucune reconstruction 3D et aucun rééchantillonnage isotrope.
        % Le PNG est une projection Z directe du volume recalé, limitée
        % aux pixels appartenant aux détections 2D finales :
        %   - détections normales
        %   - rescues Z
        %
        % Le nom du PNG historique est conservé pour compatibilité avec
        % l'organisation actuelle des dossiers.
        %==========================================================%

        %==========================================================%
        % Informations affichées dans le titre du preview
        %==========================================================%

        preview_num_frames = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'NumSlices', ...
                i, ...
                NaN);


        if ~isfinite(preview_num_frames) || ...
                preview_num_frames <= 0

            if ~isempty(zseries.registered_volume)

                preview_num_frames = ...
                    size( ...
                        zseries.registered_volume, ...
                        3);

            else

                preview_num_frames = ...
                    NaN;

            end

        end


        preview_z_step_um = ...
            zseries.z_step_um;


        preview_z_start_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'ZStart', ...
                i, ...
                NaN);


        preview_z_end_um = ...
            get_metadata_numeric_value( ...
                zseries_metadata, ...
                'ZEnd', ...
                i, ...
                NaN);


        preview_z_positions = ...
            normalize_z_positions( ...
                zseries.z_positions);


        if ~isfinite(preview_z_start_um) && ...
                ~isempty(preview_z_positions)

            preview_z_start_um = ...
                preview_z_positions(1);

        end


        if ~isfinite(preview_z_end_um) && ...
                ~isempty(preview_z_positions)

            preview_z_end_um = ...
                preview_z_positions(end);

        end


        [ ...
            ~, ...
            expected_preview_file, ...
            expected_summary_preview_file ...
        ] = ...
            get_zseries_3d_output_paths( ...
                current_output_folder, ...
                current_summary_output_folder, ...
                current_automatic_selection, ...
                current_zseries_path);


        local_preview_needs_save = ...
            ~isempty(expected_preview_file) && ...
            ~isfile(expected_preview_file);


        summary_preview_needs_save = ...
            ~isempty(expected_summary_preview_file) && ...
            ~isfile(expected_summary_preview_file);


        %==========================================================%
        % Nouveau traitement : toujours synchroniser le PNG
        %==========================================================%

        if ~use_existing_results

            zseries.z_projection_path = ...
                save_zseries_2d_z_projection( ...
                    zseries.registered_volume, ...
                    zseries.detected_cells_2d_mask_3d, ...
                    current_output_folder, ...
                    current_summary_output_folder, ...
                    current_automatic_selection, ...
                    current_zseries_path, ...
                    true, ...
                    current_line, ...
                    current_animal, ...
                    current_date, ...
                    current_age, ...
                    preview_num_frames, ...
                    preview_z_step_um, ...
                    preview_z_start_um, ...
                    preview_z_end_um);


            % Alias historique uniquement pour ne pas casser le code qui
            % lirait encore image_3d_preview_path.
            zseries.image_3d_path = '';
            zseries.image_3d_preview_path = ...
                zseries.z_projection_path;


            save( ...
                results_file, ...
                'zseries', ...
                '-v7.3');


        %==========================================================%
        % Résultats existants mais projection manquante
        %==========================================================%

        elseif local_preview_needs_save || ...
                summary_preview_needs_save

            fprintf( ...
                ['Projection Z manquante : création depuis les ' ...
                 'détections 2D existantes.\n']);


            zseries.z_projection_path = ...
                save_zseries_2d_z_projection( ...
                    zseries.registered_volume, ...
                    zseries.detected_cells_2d_mask_3d, ...
                    current_output_folder, ...
                    current_summary_output_folder, ...
                    current_automatic_selection, ...
                    current_zseries_path, ...
                    false, ...
                    current_line, ...
                    current_animal, ...
                    current_date, ...
                    current_age, ...
                    preview_num_frames, ...
                    preview_z_step_um, ...
                    preview_z_start_um, ...
                    preview_z_end_um);


            zseries.image_3d_path = '';
            zseries.image_3d_preview_path = ...
                zseries.z_projection_path;


        else

            zseries.z_projection_path = ...
                expected_preview_file;


            zseries.image_3d_path = '';
            zseries.image_3d_preview_path = ...
                expected_preview_file;


            fprintf( ...
                'Projection Z ZSeries déjà disponible.\n');

        end


        %==========================================================%
        % REOUVERTURE 2D UNIQUEMENT POUR DES RESULTATS RECHARGES
        %
        % Pour un nouveau traitement, le contrôle normal/rescue a déjà été
        % affiché juste après le calcul complet des plans.
        %==========================================================%

        if use_existing_results

            answer = ...
                questdlg( ...
                    'Résultats ZSeries rechargés. Ouvrir le contrôle 2D ?', ...
                    'ZSeries', ...
                    '2D', ...
                    'Aucun', ...
                    '2D');


            if strcmp(answer, '2D')

                if isempty(zseries.detected_cells_2d_mask_3d)

                    warning( ...
                        'Aucune détection 2D sauvegardée pour cette ZSeries.');

                elseif isempty(zseries.registered_volume)

                    warning( ...
                        'Volume recalé non disponible pour l''affichage 2D.');

                else

                    rescue_mask_to_show = ...
                        zseries.rescue_mask_3d;


                    if isempty(rescue_mask_to_show)

                        rescue_mask_to_show = ...
                            false( ...
                                size( ...
                                    zseries.detected_cells_2d_mask_3d));

                    end


                    normal_mask_to_show = ...
                        zseries.detected_cells_2d_mask_3d & ...
                        ~rescue_mask_to_show;


                    review_action = ...
                        show_zseries_rescue_review( ...
                            zseries.registered_volume, ...
                            normal_mask_to_show, ...
                            rescue_mask_to_show, ...
                            true);


                    if strcmp( ...
                            review_action, ...
                            'reprocess')

                        fprintf( ...
                            ['Reprocess demandé : recalcul complet de cette ' ...
                             'ZSeries.\n']);


                        force_reprocess_current = ...
                            true;


                        continue;

                    end

                end

            end

        end


        fprintf( ...
            'Ajout ZSeries %d / %d à zseries_all.\n', ...
            i, ...
            number_zseries);


        zseries_all(i) = ...
            zseries;


        break;

        end

    end

end



