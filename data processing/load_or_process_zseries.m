%==========================================================================%
% PREPARE DETECTION VOLUME
%==========================================================================%

function enhanced_volume = ...
        prepare_zseries_detection_volume( ...
            volume)

    [ny, nx, nz] = ...
        size(volume);


    enhanced_volume = ...
        zeros( ...
            ny, ...
            nx, ...
            nz, ...
            'single');


    %==============================================================%
    % Chaque plan est indépendant : parallélisation sûre
    %==============================================================%

    parfor z = 1:nz

        enhanced_volume(:, :, z) = ...
            prepare_zseries_detection_plane( ...
                volume(:, :, z));

    end

end



%==========================================================================%
% PREPARE ONE DETECTION PLANE
%==========================================================================%

function enhanced_image = ...
        prepare_zseries_detection_plane( ...
            image)

    current_image = ...
        single(image);


    low_value = ...
        prctile( ...
            current_image(:), ...
            1);


    high_value = ...
        prctile( ...
            current_image(:), ...
            99.8);


    if high_value > low_value

        normalized_image = ...
            ( ...
                current_image - ...
                low_value) ./ ...
            ( ...
                high_value - ...
                low_value);

    else

        normalized_image = ...
            zeros( ...
                size(current_image), ...
                'single');

    end


    normalized_image = ...
        min( ...
            max( ...
                normalized_image, ...
                0), ...
            1);


    %==============================================================%
    % IMPORTANT
    %
    % Pas de CLAHE pour la segmentation :
    % il peut amplifier les petites textures du neuropile et créer
    % de faux maxima. L'auto-contraste de l'interface est indépendant.
    %==============================================================%

    enhanced_image = ...
        single( ...
            normalized_image);

end



%==========================================================================%
% DETECT CANDIDATES FROM PREPARED VOLUME
%==========================================================================%

function [ ...
        candidate_mask_3d, ...
        detections_by_plane ...
    ] = ...
        detect_zseries_candidates_from_enhanced( ...
            enhanced_volume, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            detection_opts)

    [ny, nx, nz] = ...
        size(enhanced_volume);


    candidate_masks_by_plane = ...
        cell( ...
            nz, ...
            1);


    detections_by_plane = ...
        cell( ...
            nz, ...
            1);


    %==============================================================%
    % Chaque plan est indépendant : parallélisation sûre
    %==============================================================%

    parfor z = 1:nz

        current_detection_opts = ...
            get_depth_adjusted_detection_opts( ...
                detection_opts, ...
                z, ...
                nz);


        [ ...
            ~, ...
            current_candidate_mask, ...
            current_detections ...
        ] = ...
            detect_zseries_candidates_plane_from_enhanced( ...
                enhanced_volume(:, :, z), ...
                pixel_size_x_um, ...
                pixel_size_y_um, ...
                current_detection_opts);


        candidate_masks_by_plane{z} = ...
            current_candidate_mask;


        detections_by_plane{z} = ...
            current_detections;

    end


    candidate_mask_3d = ...
        false( ...
            ny, ...
            nx, ...
            nz);


    for z = 1:nz

        candidate_mask_3d(:, :, z) = ...
            candidate_masks_by_plane{z};

    end

end



%==========================================================================%
% SIGMOID SENSITIVITY CURVE
%
% La courbe est parametree de facon graphique :
%
%   shallow_sensitivity
%       niveau du plateau de depart.
%
%   deep_sensitivity
%       niveau du plateau final.
%
%   sensitivity_transition_depth
%       position du point d'inflexion entre 0 et 1.
%
%   sensitivity_transition_width_fraction
%       largeur de la zone de transition entre environ 25 % et 75 %
%       de la sigmoide brute.
%
% Le resultat est normalise pour garantir :
%   frame 1  -> shallow_sensitivity exactement
%   frame nz -> deep_sensitivity exactement
%==========================================================================%

function effective_sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            detection_opts, ...
            z, ...
            nz)

    if isfield(detection_opts, 'shallow_sensitivity') && ...
            ~isempty(detection_opts.shallow_sensitivity)

        shallow_sensitivity = ...
            detection_opts.shallow_sensitivity;

    elseif isfield(detection_opts, 'sensitivity') && ...
            ~isempty(detection_opts.sensitivity)

        shallow_sensitivity = ...
            detection_opts.sensitivity;

    else

        shallow_sensitivity = ...
            45;

    end


    if isfield(detection_opts, 'minimum_sensitivity') && ...
            ~isempty(detection_opts.minimum_sensitivity)

        minimum_sensitivity = ...
            detection_opts.minimum_sensitivity;

    else

        minimum_sensitivity = ...
            0;

    end


    minimum_sensitivity = ...
        min( ...
            max( ...
                minimum_sensitivity, ...
                0), ...
            100);


    if isfield(detection_opts, 'deep_sensitivity') && ...
            ~isempty(detection_opts.deep_sensitivity)

        deep_sensitivity = ...
            detection_opts.deep_sensitivity;

    else

        deep_sensitivity = ...
            max( ...
                shallow_sensitivity, ...
                95);

    end


    shallow_sensitivity = ...
        min( ...
            max( ...
                shallow_sensitivity, ...
                minimum_sensitivity), ...
            100);


    deep_sensitivity = ...
        min( ...
            max( ...
                deep_sensitivity, ...
                shallow_sensitivity), ...
            100);


    if nz <= 1

        effective_sensitivity = ...
            shallow_sensitivity;

        return;

    end


    depth_fraction = ...
        (z - 1) / ...
        max( ...
            nz - 1, ...
            1);


    depth_fraction = ...
        min( ...
            max( ...
                depth_fraction, ...
                0), ...
            1);


    if isfield(detection_opts, 'sensitivity_transition_depth') && ...
            ~isempty(detection_opts.sensitivity_transition_depth)

        transition_depth = ...
            detection_opts.sensitivity_transition_depth;

    else

        transition_depth = ...
            0.42;

    end


    transition_depth = ...
        min( ...
            max( ...
                transition_depth, ...
                0), ...
            1);


    if isfield(detection_opts, 'sensitivity_transition_width_fraction') && ...
            ~isempty(detection_opts.sensitivity_transition_width_fraction)

        transition_width = ...
            detection_opts.sensitivity_transition_width_fraction;

    else

        transition_width = ...
            0.20;

    end


    minimum_width = ...
        max( ...
            0.02, ...
            2 / ...
            max(nz - 1, 2));


    transition_width = ...
        min( ...
            max( ...
                transition_width, ...
                minimum_width), ...
            1);


    % Pour une logistique standard, la distance entre les niveaux
    % 25 % et 75 % vaut 2*log(3)/k.
    % On definit donc directement k a partir de la largeur choisie.
    sigmoid_steepness = ...
        2 * ...
        log(3) / ...
        transition_width;


    sigmoid_current = ...
        1 ./ ...
        ( ...
            1 + ...
            exp( ...
                -sigmoid_steepness * ...
                ( ...
                    depth_fraction - ...
                    transition_depth)));


    sigmoid_start = ...
        1 ./ ...
        ( ...
            1 + ...
            exp( ...
                sigmoid_steepness * ...
                transition_depth));


    sigmoid_end = ...
        1 ./ ...
        ( ...
            1 + ...
            exp( ...
                -sigmoid_steepness * ...
                ( ...
                    1 - ...
                    transition_depth)));


    denominator = ...
        sigmoid_end - ...
        sigmoid_start;


    if denominator <= eps

        sigmoid_fraction = ...
            depth_fraction;

    else

        sigmoid_fraction = ...
            ( ...
                sigmoid_current - ...
                sigmoid_start) ./ ...
            denominator;

    end


    sigmoid_fraction = ...
        min( ...
            max( ...
                sigmoid_fraction, ...
                0), ...
            1);


    effective_sensitivity = ...
        shallow_sensitivity + ...
        sigmoid_fraction * ...
        ( ...
            deep_sensitivity - ...
            shallow_sensitivity);


    effective_sensitivity = ...
        min( ...
            max( ...
                effective_sensitivity, ...
                minimum_sensitivity), ...
            100);

end



%==========================================================================%
% DEPTH-ADJUSTED DETECTION OPTIONS
%==========================================================================%

function current_detection_opts = ...
        get_depth_adjusted_detection_opts( ...
            detection_opts, ...
            z, ...
            nz)

    current_detection_opts = ...
        detection_opts;


    current_detection_opts.sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            detection_opts, ...
            z, ...
            nz);

end



%==========================================================================%
% DETECT OBJECTS ON ONE PREPARED PLANE - LOCAL CONTRAST
%
% La détection ne dépend plus d'un centre défini par un percentile
% global. Les centres sont recherchés comme maxima locaux après
% correction du fond. Ils doivent à la fois ressortir de leur propre
% voisinage ET présenter un contraste spatialement soutenu sur une
% surface compatible avec une structure cellulaire.
%==========================================================================%

function [ ...
        raw_candidate_mask, ...
        retained_candidate_mask, ...
        current_detections ...
    ] = ...
        detect_zseries_candidates_plane_from_enhanced( ...
            enhanced_image, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            detection_opts)

    %==============================================================%
    % PARAMETRES
    %==============================================================%

    sensitivity = ...
        detection_opts.sensitivity;


    min_area_um2 = ...
        detection_opts.min_area_um2;


    max_area_um2 = ...
        detection_opts.max_area_um2;


    min_circularity = ...
        detection_opts.min_circularity;


    soma_signal_sigma_um = ...
        detection_opts.soma_signal_sigma_um;


    background_sigma_um = ...
        detection_opts.background_sigma_um;


    noise_sigma_um = ...
        detection_opts.noise_sigma_um;


    support_sigma_um = ...
        detection_opts.support_sigma_um;


    weak_score_fraction = ...
        detection_opts.weak_score_fraction;


    weak_support_fraction = ...
        detection_opts.weak_support_fraction;


    strong_support_fraction = ...
        detection_opts.strong_support_fraction;


    closing_radius_um = ...
        detection_opts.soma_closing_radius_um;


    opening_radius_um = ...
        detection_opts.soma_opening_radius_um;


    candidate_min_area_um2 = ...
        detection_opts.candidate_min_area_um2;


    min_soma_core_radius_um = ...
        detection_opts.min_soma_core_radius_um;


    min_soma_solidity = ...
        detection_opts.min_soma_solidity;


    max_soma_elongation = ...
        detection_opts.max_soma_elongation;


    if isfield(detection_opts, 'watershed_strength') && ...
            ~isempty(detection_opts.watershed_strength)

        watershed_strength = ...
            detection_opts.watershed_strength;

    else

        watershed_strength = ...
            0.90;

    end


    if isfield(detection_opts, 'watershed_smoothing_um') && ...
            ~isempty(detection_opts.watershed_smoothing_um)

        watershed_smoothing_um = ...
            detection_opts.watershed_smoothing_um;

    else

        watershed_smoothing_um = ...
            0.5;

    end


    if isfield(detection_opts, 'preview_fast_mode') && ...
            ~isempty(detection_opts.preview_fast_mode)

        preview_fast_mode = ...
            logical(detection_opts.preview_fast_mode);

    else

        preview_fast_mode = ...
            false;

    end


    %==============================================================%
    % DIMENSIONS PHYSIQUES
    %==============================================================%

    [ny, nx] = ...
        size(enhanced_image);


    pixel_area_um2 = ...
        pixel_size_x_um * ...
        pixel_size_y_um;


    mean_pixel_size_um = ...
        mean( ...
            [ ...
                pixel_size_x_um, ...
                pixel_size_y_um]);


    soma_sigma_px = ...
        max( ...
            0.5, ...
            soma_signal_sigma_um / ...
            mean_pixel_size_um);


    background_sigma_px = ...
        max( ...
            soma_sigma_px + 1, ...
            background_sigma_um / ...
            mean_pixel_size_um);


    noise_sigma_px = ...
        max( ...
            1, ...
            noise_sigma_um / ...
            mean_pixel_size_um);


    support_sigma_px = ...
        max( ...
            1, ...
            support_sigma_um / ...
            mean_pixel_size_um);


    closing_radius_px = ...
        max( ...
            1, ...
            round( ...
                closing_radius_um / ...
                mean_pixel_size_um));


    opening_radius_px = ...
        max( ...
            1, ...
            round( ...
                opening_radius_um / ...
                mean_pixel_size_um));


    candidate_min_area_px = ...
        max( ...
            1, ...
            round( ...
                candidate_min_area_um2 / ...
                pixel_area_um2));


    %==============================================================%
    % IMAGE
    %==============================================================%

    image = ...
        single( ...
            enhanced_image);


    image( ...
        ~isfinite(image)) = ...
        0;


    %==============================================================%
    % 1) SIGNAL A L'ECHELLE D'UN SOMA
    %
    % Le lissage à grande échelle favorise les structures étendues.
    % Un petit point très brillant est fortement dilué, alors qu'un
    % soma large garde une réponse importante.
    %==============================================================%

    soma_signal = ...
        imgaussfilt( ...
            image, ...
            soma_sigma_px);


    %==============================================================%
    % 2) SOUSTRACTION DU FOND LARGE
    %==============================================================%

    background = ...
        imgaussfilt( ...
            image, ...
            background_sigma_px);


    soma_response = ...
        soma_signal - ...
        background;


    soma_response = ...
        max( ...
            soma_response, ...
            0);


    %==============================================================%
    % 3) ESTIMATION DU BRUIT LOCAL
    %
    % On mesure les fluctuations fines plutôt que la luminosité
    % absolue. Une grosse structure peu contrastée peut ainsi être
    % conservée si son signal est spatialement cohérent.
    %==============================================================%

    fine_sigma_px = ...
        max( ...
            0.5, ...
            0.8 / ...
            mean_pixel_size_um);


    fine_image = ...
        imgaussfilt( ...
            image, ...
            fine_sigma_px);


    high_frequency_residual = ...
        abs( ...
            image - ...
            fine_image);


    local_noise = ...
        imgaussfilt( ...
            high_frequency_residual, ...
            noise_sigma_px);


    finite_noise = ...
        local_noise( ...
            isfinite(local_noise));


    if isempty(finite_noise)

        [ ...
            raw_candidate_mask, ...
            retained_candidate_mask, ...
            current_detections ...
        ] = ...
            empty_zseries_2d_detection( ...
                ny, ...
                nx);

        return;
    end


    noise_floor = ...
        median( ...
            finite_noise, ...
            'omitnan');


    if ~isfinite(noise_floor) || ...
            noise_floor <= 0

        noise_floor = ...
            0.005;

    end


    noise_floor = ...
        max( ...
            noise_floor, ...
            0.002);


    %==============================================================%
    % 4) SCORE DE STRUCTURE LARGE
    %
    % Aucun maximum local obligatoire.
    % Aucun percentile global de luminosité.
    % Une structure est jugée selon sa réponse à l'échelle du soma
    % relativement au bruit local.
    %==============================================================%

    soma_score = ...
        soma_response ./ ...
        ( ...
            local_noise + ...
            0.5 * ...
            noise_floor);


    soma_score( ...
        ~isfinite(soma_score)) = ...
        0;


    %==============================================================%
    % 5) SENSIBILITE
    %
    % 0   = sensibilite minimale / tres stricte
    % 45  = valeur superficielle par defaut
    % 65  = ancien niveau tres strict
    % 70  = stricte
    % 80  = moderee
    % 85  = intermediaire
    % 90  = sensible
    % 95  = tres sensible
    % 100 = sensibilite maximale
    %
    % La relation est volontairement non lineaire :
    % beaucoup de resolution entre 70 et 90, puis une baisse plus
    % rapide du seuil entre 90 et 100.
    %==============================================================%

    if isfield(detection_opts, 'minimum_sensitivity') && ...
            ~isempty(detection_opts.minimum_sensitivity)

        minimum_sensitivity = ...
            detection_opts.minimum_sensitivity;

    else

        minimum_sensitivity = ...
            0;

    end


    minimum_sensitivity = ...
        min( ...
            max( ...
                minimum_sensitivity, ...
                0), ...
            65);


    sensitivity = ...
        min( ...
            max( ...
                sensitivity, ...
                minimum_sensitivity), ...
            100);


    %==============================================================%
    % CONVERSION SENSIBILITE -> SEUIL
    %
    % 65-100 : comportement historique strictement conserve.
    % 0-65   : prolongement monotone vers des seuils plus stricts.
    %
    % Ainsi une valeur inferieure a 65 signifie reellement
    % "moins sensible", au lieu d'etre reforcee artificiellement a 65.
    %==============================================================%

    if sensitivity >= 65

        sensitivity_fraction = ...
            ( ...
                sensitivity - ...
                65) / ...
            35;


        strong_score_threshold = ...
            7.0 - ...
            5.5 * ...
            sensitivity_fraction ^ 2;

    else

        strict_fraction = ...
            ( ...
                65 - ...
                sensitivity) / ...
            max( ...
                65 - ...
                minimum_sensitivity, ...
                eps);


        strong_score_threshold = ...
            7.0 + ...
            8.0 * ...
            strict_fraction;

    end


    weak_score_threshold = ...
        weak_score_fraction * ...
        strong_score_threshold;


    %==============================================================%
    % 6) SUPPORT SPATIAL
    %
    % Le critère essentiel pour les grosses structures faibles :
    % un signal plus faible peut être conservé s'il est étendu.
    %
    % Un petit point isolé peut être intense mais possède un support
    % spatial faible après lissage à cette échelle.
    %==============================================================%

    weak_signal_mask = ...
        soma_score >= ...
        weak_score_threshold;


    support_map = ...
        imgaussfilt( ...
            single(weak_signal_mask), ...
            support_sigma_px);


    strong_signal_mask = ...
        soma_score >= ...
        strong_score_threshold;


    strong_large_enough = ...
        strong_signal_mask & ...
        support_map >= ...
        strong_support_fraction;


    weak_but_large = ...
        weak_signal_mask & ...
        support_map >= ...
        weak_support_fraction;


    raw_candidate_mask = ...
        strong_large_enough | ...
        weak_but_large;


    %==============================================================%
    % 7) NETTOYAGE MORPHOLOGIQUE
    %
    % Closing : rattache les zones voisines d'un même soma.
    % Opening : retire les prolongements fins et ponctuations.
    %==============================================================%

    raw_candidate_mask = ...
        imclose( ...
            raw_candidate_mask, ...
            strel( ...
                'disk', ...
                closing_radius_px));


    raw_candidate_mask = ...
        imfill( ...
            raw_candidate_mask, ...
            'holes');


    raw_candidate_mask = ...
        imopen( ...
            raw_candidate_mask, ...
            strel( ...
                'disk', ...
                opening_radius_px));


    raw_candidate_mask = ...
        imfill( ...
            raw_candidate_mask, ...
            'holes');


    raw_candidate_mask = ...
        bwareaopen( ...
            raw_candidate_mask, ...
            candidate_min_area_px, ...
            8);


    %==============================================================%
    % APERCU RAPIDE DU VIEWER
    %
    % Pour la fluidité, on s'arrête ici avant le watershed et avant
    % les filtres morphologiques les plus coûteux. On conserve tout de
    % même les deux réglages 2D légers visibles dans le viewer : aire
    % et circularité. Le masque final complet est recalculé après
    % Confirmer avec preview_fast_mode = false.
    %==============================================================%

    if preview_fast_mode

        cc_preview = ...
            bwconncomp( ...
                raw_candidate_mask, ...
                8);


        props_preview = ...
            regionprops( ...
                cc_preview, ...
                'Area', ...
                'Perimeter', ...
                'PixelIdxList');


        retained_candidate_mask = ...
            false( ...
                ny, ...
                nx);


        for obj = 1:numel(props_preview)

            area_um2 = ...
                props_preview(obj).Area * ...
                pixel_area_um2;


            if area_um2 < min_area_um2 || ...
                    area_um2 > max_area_um2

                continue;
            end


            perimeter = ...
                props_preview(obj).Perimeter;


            if perimeter <= 0
                continue;
            end


            circularity = ...
                4 * pi * ...
                props_preview(obj).Area / ...
                perimeter ^ 2;


            circularity = ...
                min( ...
                    circularity, ...
                    1);


            if circularity < min_circularity
                continue;
            end


            retained_candidate_mask( ...
                props_preview(obj).PixelIdxList) = ...
                true;

        end


        current_detections = ...
            struct( ...
                'Mask', {}, ...
                'Centroid', {}, ...
                'Area_um2', {}, ...
                'Circularity', {}, ...
                'Solidity', {}, ...
                'CoreRadius_um', {}, ...
                'Elongation', {}, ...
                'LocalContrastScore', {});


        return;

    end


    %==============================================================%
    % 8) WATERSHED : SEPARATION DES SOMAS QUI SE TOUCHENT
    %
    % Le watershed ne crée pas de nouveaux candidats. Il agit
    % uniquement dans le masque déjà détecté et coupe les ponts entre
    % plusieurs centres suffisamment distincts.
    %==============================================================%

    raw_candidate_mask = ...
        split_zseries_candidates_watershed( ...
            raw_candidate_mask, ...
            soma_response, ...
            mean_pixel_size_um, ...
            min_soma_core_radius_um, ...
            watershed_strength, ...
            watershed_smoothing_um, ...
            candidate_min_area_px);


    if ~any(raw_candidate_mask(:))

        retained_candidate_mask = ...
            false( ...
                ny, ...
                nx);


        current_detections = ...
            struct( ...
                'Mask', {}, ...
                'Centroid', {}, ...
                'Area_um2', {}, ...
                'Circularity', {}, ...
                'Solidity', {}, ...
                'CoreRadius_um', {}, ...
                'Elongation', {}, ...
                'LocalContrastScore', {});

        return;
    end


    %==============================================================%
    % 9) OBJETS INDIVIDUELS
    %==============================================================%

    cc = ...
        bwconncomp( ...
            raw_candidate_mask, ...
            8);


    props = ...
        regionprops( ...
            cc, ...
            'Area', ...
            'Perimeter', ...
            'Centroid', ...
            'PixelIdxList', ...
            'Solidity', ...
            'MajorAxisLength', ...
            'MinorAxisLength');


    retained_candidate_mask = ...
        false( ...
            ny, ...
            nx);


    current_detections = ...
        struct( ...
            'Mask', {}, ...
            'Centroid', {}, ...
            'Area_um2', {}, ...
            'Circularity', {}, ...
            'Solidity', {}, ...
            'CoreRadius_um', {}, ...
            'Elongation', {}, ...
            'LocalContrastScore', {});


    detection_idx = ...
        0;


    %==============================================================%
    % 10) FILTRES DE FORME
    %
    % A ce stade on ne demande plus qu'une forte luminosité.
    % Les petites structures sont surtout éliminées par leur aire,
    % leur épaisseur interne et leur faible support spatial.
    %==============================================================%

    for obj = 1:numel(props)

        area_um2 = ...
            props(obj).Area * ...
            pixel_area_um2;


        if area_um2 < ...
                min_area_um2 || ...
                area_um2 > ...
                max_area_um2

            continue;
        end


        %----------------------------------------------------------%
        % Epaisseur interne minimale - CALCUL LOCAL
        %
        % Anciennement bwdist etait applique a toute la frame pour chaque
        % objet. On le limite maintenant a la bounding box de l'objet.
        %----------------------------------------------------------%

        object_idx = ...
            props(obj).PixelIdxList;


        [object_rows, object_cols] = ...
            ind2sub( ...
                [ny nx], ...
                object_idx);


        row_min_object = ...
            max( ...
                1, ...
                min(object_rows) - ...
                1);


        row_max_object = ...
            min( ...
                ny, ...
                max(object_rows) + ...
                1);


        col_min_object = ...
            max( ...
                1, ...
                min(object_cols) - ...
                1);


        col_max_object = ...
            min( ...
                nx, ...
                max(object_cols) + ...
                1);


        local_ny_object = ...
            row_max_object - ...
            row_min_object + ...
            1;


        local_nx_object = ...
            col_max_object - ...
            col_min_object + ...
            1;


        local_rows_object = ...
            object_rows - ...
            row_min_object + ...
            1;


        local_cols_object = ...
            object_cols - ...
            col_min_object + ...
            1;


        local_object_mask = ...
            false( ...
                local_ny_object, ...
                local_nx_object);


        local_object_mask( ...
            sub2ind( ...
                [local_ny_object local_nx_object], ...
                local_rows_object, ...
                local_cols_object)) = ...
            true;


        distance_inside_px = ...
            bwdist( ...
                ~local_object_mask);


        core_radius_px = ...
            max( ...
                distance_inside_px( ...
                    local_object_mask), ...
                [], ...
                'omitnan');


        core_radius_um = ...
            core_radius_px * ...
            mean_pixel_size_um;


        if isempty(core_radius_um) || ...
                ~isfinite(core_radius_um) || ...
                core_radius_um < ...
                min_soma_core_radius_um

            continue;
        end


        %----------------------------------------------------------%
        % Solidité
        %----------------------------------------------------------%

        solidity = ...
            props(obj).Solidity;


        if ~isfinite(solidity) || ...
                solidity < ...
                min_soma_solidity

            continue;
        end


        %----------------------------------------------------------%
        % Elongation
        %----------------------------------------------------------%

        major_axis = ...
            props(obj).MajorAxisLength;


        minor_axis = ...
            props(obj).MinorAxisLength;


        if minor_axis > 0

            elongation = ...
                major_axis / ...
                minor_axis;

        else

            elongation = ...
                Inf;

        end


        if ~isfinite(elongation) || ...
                elongation > ...
                max_soma_elongation

            continue;
        end


        %----------------------------------------------------------%
        % Circularité
        %----------------------------------------------------------%

        perimeter = ...
            props(obj).Perimeter;


        if perimeter <= 0
            continue;
        end


        circularity = ...
            4 * pi * ...
            props(obj).Area / ...
            perimeter ^ 2;


        circularity = ...
            min( ...
                circularity, ...
                1);


        if circularity < ...
                min_circularity

            continue;
        end


        %----------------------------------------------------------%
        % Score conservé pour diagnostic uniquement
        %----------------------------------------------------------%

        object_score = ...
            median( ...
                soma_score( ...
                    object_idx), ...
                'omitnan');


        %----------------------------------------------------------%
        % Objet retenu
        %----------------------------------------------------------%

        detection_idx = ...
            detection_idx + 1;


        retained_candidate_mask( ...
            object_idx) = ...
            true;


        % Le masque plein format n'est cree qu'apres validation complete de
        % l'objet, uniquement parce qu'il fait partie de l'API historique
        % de current_detections.
        current_object_mask = ...
            false( ...
                ny, ...
                nx);


        current_object_mask( ...
            object_idx) = ...
            true;


        current_detections( ...
            detection_idx).Mask = ...
            current_object_mask;


        current_detections( ...
            detection_idx).Centroid = ...
            props(obj).Centroid;


        current_detections( ...
            detection_idx).Area_um2 = ...
            area_um2;


        current_detections( ...
            detection_idx).Circularity = ...
            circularity;


        current_detections( ...
            detection_idx).Solidity = ...
            solidity;


        current_detections( ...
            detection_idx).CoreRadius_um = ...
            core_radius_um;


        current_detections( ...
            detection_idx).Elongation = ...
            elongation;


        current_detections( ...
            detection_idx).LocalContrastScore = ...
            object_score;

    end

end


%==========================================================================%
% WATERSHED 2D - SEPARATION DES CANDIDATS QUI SE TOUCHENT
%
% VERSION OPTIMISEE : chaque composante est traitee dans sa bounding box
% locale et non sur toute la frame. Cela evite de refaire bwdist,
% imgaussfilt, imextendedmax et watershed sur une image complete pour chaque
% cellule candidate.
%==========================================================================%

function split_mask = ...
        split_zseries_candidates_watershed( ...
            candidate_mask, ...
            soma_response, ...
            mean_pixel_size_um, ...
            min_soma_core_radius_um, ...
            watershed_strength, ...
            watershed_smoothing_um, ...
            candidate_min_area_px)

    split_mask = ...
        false( ...
            size(candidate_mask));


    if isempty(candidate_mask) || ...
            ~any(candidate_mask(:))

        return;
    end


    watershed_strength = ...
        min( ...
            max( ...
                watershed_strength, ...
                0), ...
            1.5);


    if watershed_strength <= 0

        split_mask = ...
            candidate_mask;

        return;
    end


    [ny, nx] = ...
        size(candidate_mask);


    component_cc = ...
        bwconncomp( ...
            candidate_mask, ...
            8);


    smoothing_sigma_px = ...
        max( ...
            0, ...
            watershed_smoothing_um / ...
            max(mean_pixel_size_um, eps));


    expected_core_radius_px = ...
        max( ...
            1, ...
            min_soma_core_radius_um / ...
            max(mean_pixel_size_um, eps));


    % Marge locale suffisante pour que le fond autour du composant soit
    % present et que le lissage ne soit pas coupe au bord du crop.
    local_padding_px = ...
        max( ...
            2, ...
            ceil( ...
                3 * ...
                max(smoothing_sigma_px, 0.5)));


    for component_idx = 1:component_cc.NumObjects

        global_idx = ...
            component_cc.PixelIdxList{component_idx};


        component_area_px = ...
            numel(global_idx);


        if component_area_px < ...
                2 * candidate_min_area_px

            split_mask(global_idx) = ...
                true;

            continue;
        end


        [global_rows, global_cols] = ...
            ind2sub( ...
                [ny nx], ...
                global_idx);


        row_min = ...
            max( ...
                1, ...
                min(global_rows) - ...
                local_padding_px);


        row_max = ...
            min( ...
                ny, ...
                max(global_rows) + ...
                local_padding_px);


        col_min = ...
            max( ...
                1, ...
                min(global_cols) - ...
                local_padding_px);


        col_max = ...
            min( ...
                nx, ...
                max(global_cols) + ...
                local_padding_px);


        local_ny = ...
            row_max - ...
            row_min + ...
            1;


        local_nx = ...
            col_max - ...
            col_min + ...
            1;


        local_rows = ...
            global_rows - ...
            row_min + ...
            1;


        local_cols = ...
            global_cols - ...
            col_min + ...
            1;


        local_idx = ...
            sub2ind( ...
                [local_ny local_nx], ...
                local_rows, ...
                local_cols);


        component_mask = ...
            false( ...
                local_ny, ...
                local_nx);


        component_mask(local_idx) = ...
            true;


        %==========================================================%
        % 1) CARTE DE DISTANCE LOCALE
        %==========================================================%

        distance_map = ...
            single( ...
                bwdist( ...
                    ~component_mask));


        if smoothing_sigma_px > 0

            distance_map = ...
                imgaussfilt( ...
                    distance_map, ...
                    smoothing_sigma_px);

        end


        distance_score = ...
            normalize_zseries_map_inside_mask( ...
                distance_map, ...
                component_mask);


        %==========================================================%
        % 2) REPONSE SOMA LOCALE
        %==========================================================%

        current_soma_response = ...
            single( ...
                soma_response( ...
                    row_min:row_max, ...
                    col_min:col_max));


        current_soma_response( ...
            ~component_mask) = ...
            0;


        if smoothing_sigma_px > 0

            current_soma_response = ...
                imgaussfilt( ...
                    current_soma_response, ...
                    max( ...
                        0.5, ...
                        0.75 * ...
                        smoothing_sigma_px));

        end


        response_score = ...
            normalize_zseries_map_inside_mask( ...
                current_soma_response, ...
                component_mask);


        %==========================================================%
        % 3) SCORE DE CENTRE HYBRIDE
        %==========================================================%

        center_score = ...
            0.70 * ...
            distance_score + ...
            0.30 * ...
            response_score;


        center_score( ...
            ~component_mask) = ...
            0;


        minimum_core_depth_px = ...
            expected_core_radius_px * ...
            ( ...
                0.55 - ...
                0.35 * ...
                watershed_strength);


        minimum_core_depth_px = ...
            max( ...
                0.50, ...
                minimum_core_depth_px);


        valid_center_region = ...
            component_mask & ...
            distance_map >= ...
            minimum_core_depth_px;


        %==========================================================%
        % 4) MARQUEURS
        %==========================================================%

        marker_prominence = ...
            0.18 - ...
            0.16 * ...
            watershed_strength;


        marker_prominence = ...
            max( ...
                0.005, ...
                marker_prominence);


        center_markers = ...
            imextendedmax( ...
                center_score, ...
                marker_prominence, ...
                8);


        center_markers = ...
            center_markers & ...
            valid_center_region;


        marker_cc = ...
            bwconncomp( ...
                center_markers, ...
                8);


        if marker_cc.NumObjects < 2 && ...
                watershed_strength >= 0.35

            center_markers = ...
                imregionalmax( ...
                    center_score, ...
                    8) & ...
                valid_center_region;

        end


        %==========================================================%
        % 5) REDUCTION DES MARQUEURS
        %==========================================================%

        minimum_center_distance_um = ...
            2 * ...
            min_soma_core_radius_um * ...
            ( ...
                1.05 - ...
                0.55 * ...
                watershed_strength);


        minimum_center_distance_um = ...
            max( ...
                1.5, ...
                minimum_center_distance_um);


        minimum_center_distance_px = ...
            minimum_center_distance_um / ...
            max(mean_pixel_size_um, eps);


        center_markers = ...
            reduce_zseries_watershed_markers( ...
                center_markers, ...
                center_score, ...
                minimum_center_distance_px, ...
                component_area_px, ...
                candidate_min_area_px);


        marker_cc = ...
            bwconncomp( ...
                center_markers, ...
                8);


        if marker_cc.NumObjects < 2

            split_mask(global_idx) = ...
                true;

            continue;
        end


        %==========================================================%
        % 6) WATERSHED CONTROLE PAR MARQUEURS
        %==========================================================%

        watershed_surface = ...
            -( ...
                0.65 * ...
                distance_score + ...
                0.35 * ...
                response_score);


        watershed_surface( ...
            ~component_mask) = ...
            1;


        imposed_surface = ...
            imimposemin( ...
                watershed_surface, ...
                center_markers | ...
                ~component_mask, ...
                8);


        watershed_labels = ...
            watershed( ...
                imposed_surface, ...
                8);


        current_split = ...
            component_mask;


        current_split( ...
            watershed_labels == 0) = ...
            false;


        %==========================================================%
        % 7) VALIDATION DE LA COUPURE
        %==========================================================%

        split_cc = ...
            bwconncomp( ...
                current_split, ...
                8);


        valid_piece_count = ...
            0;


        for piece_idx = 1:split_cc.NumObjects

            if numel( ...
                    split_cc.PixelIdxList{piece_idx}) >= ...
                    candidate_min_area_px

                valid_piece_count = ...
                    valid_piece_count + ...
                    1;

            end

        end


        if valid_piece_count >= 2

            current_split = ...
                bwareaopen( ...
                    current_split, ...
                    candidate_min_area_px, ...
                    8);


            local_output = ...
                split_mask( ...
                    row_min:row_max, ...
                    col_min:col_max);


            local_output = ...
                local_output | ...
                current_split;


            split_mask( ...
                row_min:row_max, ...
                col_min:col_max) = ...
                local_output;

        else

            split_mask(global_idx) = ...
                true;

        end

    end

end


%==========================================================================%
% NORMALISE UNE CARTE UNIQUEMENT DANS UN MASQUE
%==========================================================================%

function normalized_map = ...
        normalize_zseries_map_inside_mask( ...
            input_map, ...
            mask)

    normalized_map = ...
        zeros( ...
            size(input_map), ...
            'single');


    values = ...
        single( ...
            input_map(mask));


    values = ...
        values( ...
            isfinite(values));


    if isempty(values)
        return;
    end


    low_value = ...
        min(values);


    high_value = ...
        max(values);


    if ~isfinite(low_value) || ...
            ~isfinite(high_value) || ...
            high_value <= low_value

        return;
    end


    normalized_map = ...
        single( ...
            ( ...
                input_map - ...
                low_value) ./ ...
            ( ...
                high_value - ...
                low_value));


    normalized_map = ...
        min( ...
            max( ...
                normalized_map, ...
                0), ...
            1);


    normalized_map( ...
        ~mask) = ...
        0;

end


%==========================================================================%
% REDUIT LES MARQUEURS DU WATERSHED
%==========================================================================%

function reduced_markers = ...
        reduce_zseries_watershed_markers( ...
            marker_mask, ...
            center_score, ...
            minimum_distance_px, ...
            component_area_px, ...
            candidate_min_area_px)

    reduced_markers = ...
        false( ...
            size(marker_mask));


    marker_cc = ...
        bwconncomp( ...
            marker_mask, ...
            8);


    if marker_cc.NumObjects == 0
        return;
    end


    marker_positions = ...
        zeros( ...
            marker_cc.NumObjects, ...
            2);


    marker_scores = ...
        zeros( ...
            marker_cc.NumObjects, ...
            1);


    marker_indices = ...
        zeros( ...
            marker_cc.NumObjects, ...
            1);


    for marker_idx = 1:marker_cc.NumObjects

        current_indices = ...
            marker_cc.PixelIdxList{marker_idx};


        current_scores = ...
            center_score(current_indices);


        [ ...
            marker_scores(marker_idx), ...
            best_local_idx ...
        ] = ...
            max(current_scores);


        best_index = ...
            current_indices(best_local_idx);


        [row, col] = ...
            ind2sub( ...
                size(marker_mask), ...
                best_index);


        marker_positions(marker_idx, :) = ...
            [col row];


        marker_indices(marker_idx) = ...
            best_index;

    end


    [~, order] = ...
        sort( ...
            marker_scores, ...
            'descend');


    maximum_markers = ...
        max( ...
            2, ...
            min( ...
                8, ...
                floor( ...
                    component_area_px / ...
                    max(candidate_min_area_px, 1))));


    accepted_positions = ...
        zeros( ...
            0, ...
            2);


    accepted_count = ...
        0;


    for order_idx = 1:numel(order)

        marker_idx = ...
            order(order_idx);


        current_position = ...
            marker_positions(marker_idx, :);


        if isempty(accepted_positions)

            accept_marker = ...
                true;

        else

            distances = ...
                sqrt( ...
                    sum( ...
                        ( ...
                            accepted_positions - ...
                            current_position) .^ 2, ...
                        2));


            accept_marker = ...
                all( ...
                    distances >= ...
                    minimum_distance_px);

        end


        if ~accept_marker
            continue;
        end


        accepted_count = ...
            accepted_count + ...
            1;


        reduced_markers( ...
            marker_indices(marker_idx)) = ...
            true;


        accepted_positions( ...
            accepted_count, :) = ...
            current_position;


        if accepted_count >= maximum_markers
            break;
        end

    end


end


