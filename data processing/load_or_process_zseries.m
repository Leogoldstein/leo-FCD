                8);


        number_2d_detections = ...
            number_2d_detections + ...
            current_cc.NumObjects;

    end


    fprintf( ...
        'Détections 2D         : %d\n', ...
        number_2d_detections);


    fprintf( ...
        'Cellules reconstruites: %d\n', ...
        numel(zseries.reconstructed_cells_3d));


    fprintf( ...
        'Cellules 3D retenues  : %d\n', ...
        numel(zseries.cells_3d));


    fprintf( ...
        'Reconstruction        : >= %d plans | gap Z <= %.1f um | distance XY <= %.1f um | overlap >= %.2f\n', ...
        zseries.detection_opts.min_real_detections, ...
        zseries.detection_opts.max_z_gap_um, ...
        zseries.detection_opts.max_centroid_distance_um, ...
        zseries.detection_opts.min_overlap_fraction);


    fprintf( ...
        'Filtre volume         : %.0f - %.0f um3\n', ...
        zseries.detection_opts.min_cell_volume_um3, ...
        zseries.detection_opts.max_cell_volume_um3);


    if isempty(zseries.cells_3d)

        fprintf('Aucune cellule 3D retenue.\n');
        fprintf('-----------------------------------------\n\n');
        return;

    end


    volumes = ...
        [zseries.cells_3d.Volume_um3];


    z_extents = ...
        [zseries.cells_3d.ZExtent_um];


    fprintf( ...
        'Volumes               : min %.0f | médiane %.0f | max %.0f um3\n', ...
        min(volumes), ...
        median(volumes), ...
        max(volumes));


    fprintf( ...
        'Extensions Z          : min %.1f | médiane %.1f | max %.1f um\n', ...
        min(z_extents), ...
        median(z_extents), ...
        max(z_extents));


    [largest_volume, largest_idx] = ...
        max(volumes);


    largest_cell = ...
        zseries.cells_3d(largest_idx);


    fprintf( ...
        'Plus grosse cellule    : %.0f um3 | Z %.1f um | %d détection(s)\n', ...
        largest_volume, ...
        largest_cell.ZExtent_um, ...
        largest_cell.NumRealDetections);


    fprintf('-----------------------------------------\n\n');

end



