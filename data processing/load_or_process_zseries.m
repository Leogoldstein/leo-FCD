%==========================================================================%
% DRAG INTERACTIF DE LA SIGMOIDE
%==========================================================================%

function zseries_sigmoid_drag_callback(fig, ~)

    if ~ishandle(fig)
        return;
    end


    state = guidata(fig);

    if isempty(state) || ...
            state.busy || ...
            ~isfield(state, 'sigmoid_drag_mode') || ...
            isempty(state.sigmoid_drag_mode)

        return;
    end


    current_point = ...
        get( ...
            state.sigmoid_ax, ...
            'CurrentPoint');


    mouse_x = ...
        current_point(1, 1);


    mouse_y = ...
        current_point(1, 2);


    if ~isfinite(mouse_x) || ...
            ~isfinite(mouse_y)

        return;
    end


    nz = ...
        state.nz;


    if nz <= 1

        normalized_x = 0;

    else

        normalized_x = ...
            (mouse_x - 1) / ...
            (nz - 1);

    end


    normalized_x = ...
        min( ...
            max( ...
                normalized_x, ...
                0), ...
            1);


    shallow_sensitivity = ...
        state.detection_opts.shallow_sensitivity;


    deep_sensitivity = ...
        state.detection_opts.deep_sensitivity;


    transition_depth = ...
        state.detection_opts.sensitivity_transition_depth;


    transition_width = ...
        state.detection_opts.sensitivity_transition_width_fraction;


    left_depth = ...
        transition_depth - ...
        transition_width / ...
        2;


    right_depth = ...
        transition_depth + ...
        transition_width / ...
        2;


    minimum_width = ...
        max( ...
            0.02, ...
            2 / ...
            max(nz - 1, 2));


    switch state.sigmoid_drag_mode

        case 'sigmoid_start'

            new_shallow = ...
                min( ...
                    max( ...
                        mouse_y, ...
                        state.detection_opts.minimum_sensitivity), ...
                    deep_sensitivity - ...
                    0.5);


            state.detection_opts.shallow_sensitivity = ...
                new_shallow;


            state.detection_opts.sensitivity = ...
                new_shallow;


        case 'sigmoid_end'

            new_deep = ...
                min( ...
                    max( ...
                        mouse_y, ...
                        shallow_sensitivity + ...
                        0.5), ...
                    100);


            state.detection_opts.deep_sensitivity = ...
                new_deep;


        case 'sigmoid_center'

            half_width = ...
                transition_width / ...
                2;


            new_center = ...
                min( ...
                    max( ...
                        normalized_x, ...
                        half_width), ...
                    1 - ...
                    half_width);


            state.detection_opts.sensitivity_transition_depth = ...
                new_center;


        case 'sigmoid_left'

            new_left_depth = ...
                min( ...
                    max( ...
                        normalized_x, ...
                        0), ...
                    right_depth - ...
                    minimum_width);


            new_width = ...
                right_depth - ...
                new_left_depth;


            new_center = ...
                ( ...
                    right_depth + ...
                    new_left_depth) / ...
                2;


            state.detection_opts.sensitivity_transition_depth = ...
                new_center;


            state.detection_opts.sensitivity_transition_width_fraction = ...
                new_width;


        case 'sigmoid_right'

            new_right_depth = ...
                max( ...
                    min( ...
                        normalized_x, ...
                        1), ...
                    left_depth + ...
                    minimum_width);


            new_width = ...
                new_right_depth - ...
                left_depth;


            new_center = ...
                ( ...
                    new_right_depth + ...
                    left_depth) / ...
                2;


            state.detection_opts.sensitivity_transition_depth = ...
                new_center;


            state.detection_opts.sensitivity_transition_width_fraction = ...
                new_width;

    end


    state.detection_opts.sensitivity_transition_depth = ...
        min( ...
            max( ...
                state.detection_opts.sensitivity_transition_depth, ...
                0), ...
            1);


    state.detection_opts.sensitivity_transition_width_fraction = ...
        min( ...
            max( ...
                state.detection_opts.sensitivity_transition_width_fraction, ...
                minimum_width), ...
            1);


    % Pendant le drag, on ne recalcule PAS la segmentation.
    % On déplace uniquement la courbe et ses poignées : cette partie
    % est très légère et reste fluide.
    %
    % La nouvelle sensibilité sera appliquée à la frame courante une
    % seule fois lorsque l'utilisateur relâche la souris.
    state.preview_dirty = true;

    guidata(fig, state);


    update_zseries_sigmoid_plot(fig);


    state = guidata(fig);

    set( ...
        state.status_text, ...
        'String', ...
        sprintf( ...
            'Courbe modifiée | relâcher pour recalculer Z %d', ...
            state.current_z));


    drawnow limitrate nocallbacks;

end



