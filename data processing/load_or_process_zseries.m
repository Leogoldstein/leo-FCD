end



%==========================================================================%
% STANDARDIZE ZSERIES RESULT
%==========================================================================%

function zseries = standardize_zseries_result(input_zseries)

    zseries = ...
        create_empty_zseries_result();


    if isempty(input_zseries) || ...
            ~isstruct(input_zseries)

        return;

    end


    input_zseries = ...
        input_zseries(1);


    template_fields = ...
        fieldnames(zseries);


    for f = 1:numel(template_fields)

        current_field = ...
            template_fields{f};


        if isfield( ...
                input_zseries, ...
                current_field)

            zseries.(current_field) = ...
                input_zseries.(current_field);

        end

    end

end



%==========================================================================%
% DEFAULT DETECTION OPTIONS
%==========================================================================%

function detection_opts = ...
        get_default_zseries_detection_opts()

    detection_opts = struct();


    %==============================================================%
    % PARAMETRES 2D VISIBLES
    %==============================================================%

    % Champ conserve pour compatibilite avec les anciens resultats.
    % La vraie sensibilite depend maintenant directement de la courbe
    % sigmoide reglee graphiquement dans le viewer.
    detection_opts.sensitivity = ...
        45;


    %==============================================================%
    % COURBE SIGMOIDE DE SENSIBILITE
    %
    % La courbe est controlee directement dans le viewer :
    %
    %   shallow_sensitivity
    %       plateau de depart, regle verticalement.
    %
    %   deep_sensitivity
    %       plateau final, regle verticalement.
    %
    %   sensitivity_transition_depth
    %       position horizontale du centre de la transition.
    %
    %   sensitivity_transition_width_fraction
    %       largeur horizontale de la transition.
    %       Petite valeur = transition abrupte.
    %       Grande valeur = transition etalee.
    %==============================================================%

    detection_opts.shallow_sensitivity = ...
        45;


    % Echelle du viewer : -50 = ultra stricte, 0 = stricte,
    % 100 = tres sensible. Les valeurs negatives permettent de reduire
    % encore la detection quand la sensibilite 0 reste trop permissive.
    detection_opts.minimum_sensitivity = ...
        -50;


    detection_opts.deep_sensitivity = ...
        95;


    detection_opts.sensitivity_transition_depth = ...
        0.42;


    detection_opts.sensitivity_transition_width_fraction = ...
        0.20;


    % Champs historiques conserves pour compatibilite uniquement.
    % Ils ne pilotent plus la courbe sigmoide.
    detection_opts.sensitivity_growth_amplitude = ...
        10.0;


    detection_opts.sensitivity_exponential_rate = ...
        20.0;


    %==============================================================%
    % ECHELLE DU SOMA
    %
    % C'est le changement principal :
    %
    %   petit objet brillant
    %       -> fortement dilué par le lissage
    %
    %   grosse structure
    %       -> signal conservé
    %==============================================================%

    detection_opts.soma_signal_sigma_um = ...
        3.5;


    detection_opts.background_sigma_um = ...
        14;


    %==============================================================%
    % DETECTION DIRECTE SUR LA REPONSE SOMA
    %
    % La segmentation est maintenant basee UNIQUEMENT sur soma_response :
    %   soma_response = signal_lisse_soma - fond_lisse_large
    %
    % Aucun score SNR, aucune branche LoG et aucun support spatial ne peut
    % ajouter de candidat en parallele. La sensibilite pilote directement
    % le seuil applique a cette image.
    %
    % Un seuil strict cree les seeds. Le masque est ensuite etendu seulement
    % dans une zone plus permissive de la MEME image soma_response avec
    % imreconstruct. Cela permet de recuperer la surface du soma sans ouvrir
    % une seconde voie de detection.
    %==============================================================%

    detection_opts.response_reference_percentile = ...
        99.9;


    detection_opts.response_seed_fraction_strict = ...
        0.98;


    detection_opts.response_seed_fraction_ultrastrict = ...
        1.25;


    detection_opts.response_seed_fraction_sensitive = ...
        0.10;


    detection_opts.response_mad_multiplier_strict = ...
        12.0;


    detection_opts.response_mad_multiplier_ultrastrict = ...
        20.0;


    detection_opts.response_mad_multiplier_sensitive = ...
        1.5;


    detection_opts.response_growth_fraction_strict = ...
        0.65;


    detection_opts.response_growth_fraction_ultrastrict = ...
        0.78;


    detection_opts.response_growth_fraction_sensitive = ...
        0.32;


    detection_opts.response_sensitivity_power = ...
        1.5;


    %==============================================================%
    % MAXIMA LOCAUX
    %
    % Une cellule doit maintenant obligatoirement :
    %   1) contenir un maximum local suffisamment brillant dans soma_response ;
    %   2) faire croitre une region autour de ce maximum.
    %
    % La sensibilite agit sur la brillance/prominence minimale acceptee.
    %==============================================================%

    detection_opts.peak_smoothing_um = ...
        0.8;


    detection_opts.peak_prominence_fraction_strict = ...
        0.25;


    detection_opts.peak_prominence_fraction_ultrastrict = ...
        0.45;


    detection_opts.peak_prominence_fraction_sensitive = ...
        0.025;


    %==============================================================%
    % NETTOYAGE DU MASQUE
    %
    % Ces operations modifient le masque binaire mais ne servent pas
    % a selectionner/rejeter les objets selon leur forme.
    %==============================================================%

    detection_opts.soma_closing_radius_um = ...
        2;


    detection_opts.soma_opening_radius_um = ...
        1.5;


    % Taille minimale visible dans le viewer. Elle est appliquee APRES le
    % watershed, sur chaque objet separe individuellement.
    detection_opts.min_area_um2 = ...
        60;


    % Circularite minimale appliquee APRES le watershed, sur les objets
    % deja separes. Valeur par defaut = 0.50.
    % 0 = filtre desactive.
    detection_opts.min_circularity = ...
        0.50;


    % Taille minimale purement technique pour eliminer les fragments
    % minuscules pendant la construction du masque.
    detection_opts.candidate_min_area_um2 = ...
        12;


    %==============================================================%
    % WATERSHED 2D
    %
    % Sépare les somas qui se touchent après la construction du
    % masque candidat.
    %
    % watershed_strength :
    %   0   = desactive
    %   1   = separation forte (valeur par defaut)
    %   1.5 = maximum du curseur
    %
    % Le watershed utilise ici exactement la logique de la premiere
    % version : distance au bord + reponse soma, avec marqueurs controles.
    %
    % Le seuil technique du watershed est calculé automatiquement
    % à partir de la taille physique attendue d'un soma.
    %==============================================================%

    detection_opts.watershed_strength = ...
        1.00;


    detection_opts.watershed_smoothing_um = ...
        0.5;


    % Echelle physique utilisee uniquement pour espacer les marqueurs
    % du watershed. Ce parametre n'est PAS un critere de selection.
    detection_opts.watershed_core_radius_um = ...
        3.5;


    %==============================================================%
    % RESCUE Z INTER-PLANS
    %
    % Une cellule clairement détectée sur une coupe peut être juste
    % sous le seuil sur la coupe voisine. Le rescue ne rend PAS toute
    % la frame plus sensible : il recherche localement autour des
    % cellules déjà détectées sur z-1 / z+1 avec une petite tolérance
    % supplémentaire.
    %
    % IMPORTANT : aucun rescue n'est calcule dans le viewer.
    % Le viewer ne segmente que la frame courante avec la sensibilite
    % donnee par la sigmoide. Le rescue Z est applique uniquement apres
    % Confirmer, lors du traitement de toutes les frames.
    %==============================================================%

    detection_opts.z_rescue_enabled = ...
        true;


    detection_opts.z_rescue_sensitivity_bonus = ...
        7;


    detection_opts.z_rescue_dilation_um = ...
        8;


    detection_opts.z_rescue_min_overlap = ...
        0.15;


    detection_opts.z_rescue_max_centroid_distance_um = ...
        8;


    %==============================================================%
    % VALIDATION 3D DES MASQUES 2D
    %
    % Aucun objet 3D n'est reconstruit. Ces criteres servent uniquement a
    % valider les composantes formees par l'empilement des masques 2D.
    %
    % min_z_planes = 2 reproduit le principe historique selon lequel une
    % cellule doit etre retrouvee sur au moins deux coupes Z. Le rescue Z
    % peut justement recuperer une coupe voisine legerement sous le seuil.
    %==============================================================%

    detection_opts.volume_filter_enabled = ...
        true;


    detection_opts.volume_connectivity = ...
        18;


    detection_opts.min_z_planes = ...
        2;


    detection_opts.min_cell_volume_um3 = ...
        300;


    detection_opts.max_cell_volume_um3 = ...
        50000;


    detection_opts.min_z_extent_um = ...
        0;


    detection_opts.max_z_extent_um = ...
        Inf;


end


%==========================================================================%
% INTERACTIVE 2D DETECTION TUNER
%==========================================================================%

function [detection_opts, confirmed] = ...
        tune_zseries_2d_detection( ...
            registered_volume, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            initial_detection_opts)

    [~, ~, nz] = size(registered_volume);

    current_z = round((nz + 1) / 2);

    detection_opts = initial_detection_opts;


    %==============================================================%
    % Compatibilite avec une structure ancienne
    %==============================================================%

    if ~isfield(detection_opts, 'shallow_sensitivity') || ...
            isempty(detection_opts.shallow_sensitivity)

        if isfield(detection_opts, 'sensitivity') && ...
                ~isempty(detection_opts.sensitivity)

            detection_opts.shallow_sensitivity = ...
                detection_opts.sensitivity;

        else

            detection_opts.shallow_sensitivity = ...
                45;

        end

    end


    if ~isfield(detection_opts, 'minimum_sensitivity') || ...
            isempty(detection_opts.minimum_sensitivity)

        detection_opts.minimum_sensitivity = ...
            -50;

    end


    % Toujours autoriser un regime plus strict que 0, y compris lorsque
    % des anciens detection_opts contiennent minimum_sensitivity = 0.
    detection_opts.minimum_sensitivity = ...
        min( ...
            detection_opts.minimum_sensitivity, ...
            -50);


    if ~isfield(detection_opts, 'deep_sensitivity') || ...
            isempty(detection_opts.deep_sensitivity)

        detection_opts.deep_sensitivity = ...
            95;

    end


    if ~isfield(detection_opts, 'sensitivity_transition_depth') || ...
            isempty(detection_opts.sensitivity_transition_depth)

        detection_opts.sensitivity_transition_depth = ...
            0.42;

    end


    if ~isfield(detection_opts, 'sensitivity_transition_width_fraction') || ...
            isempty(detection_opts.sensitivity_transition_width_fraction)

        detection_opts.sensitivity_transition_width_fraction = ...
            0.20;

    end


    if ~isfield(detection_opts, 'min_area_um2') || ...
            isempty(detection_opts.min_area_um2)

        detection_opts.min_area_um2 = ...
            60;

    end


    if ~isfield(detection_opts, 'min_circularity') || ...
            isempty(detection_opts.min_circularity)

        detection_opts.min_circularity = ...
            0.50;

    end


    detection_opts.min_circularity = ...
        min( ...
            max( ...
                detection_opts.min_circularity, ...
                0), ...
            1);


    if ~isfield(detection_opts, 'watershed_strength') || ...
            isempty(detection_opts.watershed_strength)

        detection_opts.watershed_strength = ...
            1.00;

    end


    if ~isfield(detection_opts, 'watershed_smoothing_um') || ...
            isempty(detection_opts.watershed_smoothing_um)

        detection_opts.watershed_smoothing_um = ...
            0.5;

    end



    if ~isfield(detection_opts, 'z_rescue_enabled') || ...
            isempty(detection_opts.z_rescue_enabled)

        detection_opts.z_rescue_enabled = ...
            true;

    end


    if ~isfield(detection_opts, 'z_rescue_sensitivity_bonus') || ...
            isempty(detection_opts.z_rescue_sensitivity_bonus)

        detection_opts.z_rescue_sensitivity_bonus = ...
            7;

    end


    if ~isfield(detection_opts, 'z_rescue_dilation_um') || ...
            isempty(detection_opts.z_rescue_dilation_um)

        detection_opts.z_rescue_dilation_um = ...
            8;

    end


    if ~isfield(detection_opts, 'z_rescue_min_overlap') || ...
            isempty(detection_opts.z_rescue_min_overlap)

        detection_opts.z_rescue_min_overlap = ...
            0.15;

    end


    if ~isfield(detection_opts, 'z_rescue_max_centroid_distance_um') || ...
            isempty(detection_opts.z_rescue_max_centroid_distance_um)

        detection_opts.z_rescue_max_centroid_distance_um = ...
            8;

    end


    detection_opts.watershed_strength = ...
        min( ...
            max( ...
                detection_opts.watershed_strength, ...
                0), ...
            1.5);


    detection_opts.shallow_sensitivity = ...
        min( ...
            max( ...
                detection_opts.shallow_sensitivity, ...
                detection_opts.minimum_sensitivity), ...
            100);


    detection_opts.deep_sensitivity = ...
        min( ...
            max( ...
                detection_opts.deep_sensitivity, ...
                detection_opts.minimum_sensitivity), ...
            100);


    detection_opts.sensitivity_transition_depth = ...
        min( ...
            max( ...
                detection_opts.sensitivity_transition_depth, ...
                0.02), ...
            0.98);


    detection_opts.sensitivity_transition_width_fraction = ...
        min( ...
            max( ...
                detection_opts.sensitivity_transition_width_fraction, ...
                0.02), ...
            0.90);


    detection_opts.sensitivity = ...
        detection_opts.shallow_sensitivity;


    enhanced_image = ...
        prepare_zseries_detection_plane( ...
            registered_volume(:, :, current_z));


    current_detection_opts = ...
        get_depth_adjusted_detection_opts( ...
            detection_opts, ...
            current_z, ...
            nz);


    % Aperçu COMPLET de la frame courante uniquement :
    % sensibilité + croissance + nettoyage du masque + watershed.
    % Aucun autre plan Z n'est recalculé dans le viewer.
    % Le stack complet n'est traité qu'après clic sur Confirmer.
    current_detection_opts.preview_fast_mode = ...
        false;


    [ ...
        preview_raw_mask, ...
        preview_candidate_mask, ...
        ~, ...
        preview_diagnostics ...
    ] = ...
        detect_zseries_candidates_plane_from_enhanced( ...
            enhanced_image, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            current_detection_opts);


    %==============================================================%
    % Figure : image 2D + courbe de sensibilite interactive
    %==============================================================%

    fig = ...
        figure( ...
            'Name', ...
            'ZSeries - détection 2D + courbe de sensibilité', ...
            'NumberTitle', ...
            'off', ...
            'Color', ...
            'w', ...
            'Units', ...
            'normalized', ...
            'Position', ...
            [0.03 0.05 0.94 0.88], ...
            'WindowStyle', ...
            'modal', ...
            'Interruptible', ...
            'off', ...
            'WindowScrollWheelFcn', ...
            @zseries_2d_scroll_callback, ...
            'WindowButtonMotionFcn', ...
