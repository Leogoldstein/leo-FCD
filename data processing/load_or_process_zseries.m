%==========================================================================%
% DRAG INTERACTIF DE LA SIGMOIDE
%==========================================================================%

function zseries_sigmoid_drag_callback(fig, ~)

    if ~ishandle(fig)
        return;
    end


    state = guidata(fig);

    if isempty(state) || ...
            state.busy || ...
            ~isfield(state, 'sigmoid_drag_mode') || ...
            isempty(state.sigmoid_drag_mode)

        return;
    end


    current_point = ...
        get( ...
            state.sigmoid_ax, ...
            'CurrentPoint');


    mouse_x = ...
        current_point(1, 1);


    mouse_y = ...
        current_point(1, 2);


    if ~isfinite(mouse_x) || ...
            ~isfinite(mouse_y)

        return;
    end


    nz = ...
        state.nz;


    if nz <= 1

        normalized_x = 0;

    else

        normalized_x = ...
            (mouse_x - 1) / ...
            (nz - 1);

    end


    normalized_x = ...
        min( ...
            max( ...
                normalized_x, ...
                0), ...
            1);


    shallow_sensitivity = ...
        state.detection_opts.shallow_sensitivity;


    deep_sensitivity = ...
        state.detection_opts.deep_sensitivity;


    transition_depth = ...
        state.detection_opts.sensitivity_transition_depth;


    transition_width = ...
        state.detection_opts.sensitivity_transition_width_fraction;


    left_depth = ...
        transition_depth - ...
        transition_width / ...
        2;


    right_depth = ...
        transition_depth + ...
        transition_width / ...
        2;


    minimum_width = ...
        max( ...
            0.02, ...
            2 / ...
            max(nz - 1, 2));


    switch state.sigmoid_drag_mode

        case 'sigmoid_start'

            new_shallow = ...
                min( ...
                    max( ...
                        mouse_y, ...
                        state.detection_opts.minimum_sensitivity), ...
                    100);


            state.detection_opts.shallow_sensitivity = ...
                new_shallow;


            state.detection_opts.sensitivity = ...
                new_shallow;


        case 'sigmoid_end'

            new_deep = ...
                min( ...
                    max( ...
                        mouse_y, ...
                        state.detection_opts.minimum_sensitivity), ...
                    100);


            state.detection_opts.deep_sensitivity = ...
                new_deep;


        case 'sigmoid_center'

            %------------------------------------------------------%
            % Losange central : déplacement 2D
            %
            % Horizontal : déplace le centre de la transition.
            % Vertical   : translate toute la courbe sans modifier
            %              son amplitude ni sa largeur.
            %------------------------------------------------------%

            half_width = ...
                transition_width / ...
                2;


            new_center = ...
                min( ...
                    max( ...
                        normalized_x, ...
                        half_width), ...
                    1 - ...
                    half_width);


            state.detection_opts.sensitivity_transition_depth = ...
                new_center;


            center_frame_after_horizontal_move = ...
                1 + ...
                new_center * ...
                max(nz - 1, 0);


            center_sensitivity_before_vertical_move = ...
                get_zseries_sigmoid_sensitivity( ...
                    state.detection_opts, ...
                    center_frame_after_horizontal_move, ...
                    nz);


            requested_vertical_shift = ...
                mouse_y - ...
                center_sensitivity_before_vertical_move;


            minimum_sensitivity = ...
                state.detection_opts.minimum_sensitivity;


            minimum_allowed_shift = ...
                minimum_sensitivity - ...
                min( ...
                    shallow_sensitivity, ...
                    deep_sensitivity);


            maximum_allowed_shift = ...
                100 - ...
                max( ...
                    shallow_sensitivity, ...
                    deep_sensitivity);


            vertical_shift = ...
                min( ...
                    max( ...
                        requested_vertical_shift, ...
                        minimum_allowed_shift), ...
                    maximum_allowed_shift);


            state.detection_opts.shallow_sensitivity = ...
                shallow_sensitivity + ...
                vertical_shift;


            state.detection_opts.deep_sensitivity = ...
                deep_sensitivity + ...
                vertical_shift;


            state.detection_opts.sensitivity = ...
                state.detection_opts.shallow_sensitivity;


        case 'sigmoid_left'

            new_left_depth = ...
                min( ...
                    max( ...
                        normalized_x, ...
                        0), ...
                    right_depth - ...
                    minimum_width);


            new_width = ...
                right_depth - ...
                new_left_depth;


            new_center = ...
                ( ...
                    right_depth + ...
                    new_left_depth) / ...
                2;


            state.detection_opts.sensitivity_transition_depth = ...
                new_center;


            state.detection_opts.sensitivity_transition_width_fraction = ...
                new_width;


        case 'sigmoid_right'

            new_right_depth = ...
                max( ...
                    min( ...
                        normalized_x, ...
                        1), ...
                    left_depth + ...
                    minimum_width);


            new_width = ...
                new_right_depth - ...
                left_depth;


            new_center = ...
                ( ...
                    new_right_depth + ...
                    left_depth) / ...
                2;


            state.detection_opts.sensitivity_transition_depth = ...
                new_center;


            state.detection_opts.sensitivity_transition_width_fraction = ...
                new_width;

    end


    state.detection_opts.sensitivity_transition_depth = ...
        min( ...
            max( ...
                state.detection_opts.sensitivity_transition_depth, ...
                0), ...
            1);


    state.detection_opts.sensitivity_transition_width_fraction = ...
        min( ...
            max( ...
                state.detection_opts.sensitivity_transition_width_fraction, ...
                minimum_width), ...
            1);


    % Pendant le drag, on ne recalcule PAS la segmentation.
    % On déplace uniquement la courbe et ses poignées : cette partie
    % est très légère et reste fluide.
    %
    % La nouvelle sensibilité sera appliquée à la frame courante une
    % seule fois lorsque l'utilisateur relâche la souris.
    state.preview_dirty = true;

    guidata(fig, state);


    update_zseries_sigmoid_plot(fig);


    state = guidata(fig);

    set( ...
        state.status_text, ...
        'String', ...
        sprintf( ...
            'Courbe modifiée | relâcher pour recalculer Z %d', ...
            state.current_z));


    drawnow limitrate nocallbacks;

end



%==========================================================================%
% FIN DU DRAG
%==========================================================================%

function zseries_sigmoid_drag_end_callback(fig, ~)

    if ~ishandle(fig)
        return;
    end


    state = guidata(fig);

    if isempty(state) || ...
            ~isfield(state, 'sigmoid_drag_mode') || ...
            isempty(state.sigmoid_drag_mode)

        return;
    end


    state.sigmoid_drag_mode = ...
        '';


    state.preview_dirty = ...
        false;


    guidata(fig, state);


    set( ...
        fig, ...
        'Pointer', ...
        'arrow');


    % Une seule segmentation de la frame courante au relâchement.
    update_zseries_sigmoid_plot(fig);
    refresh_zseries_2d_preview(fig);
    update_zseries_2d_display(fig);


    state = guidata(fig);

    set( ...
        state.status_text, ...
        'String', ...
        sprintf( ...
            'Aperçu Z %d mis à jour', ...
            state.current_z));

end



%==========================================================================%
% UPDATE DU GRAPHE DE SIGMOIDE
%==========================================================================%

function update_zseries_sigmoid_plot(fig)

    if ~ishandle(fig)
        return;
    end


    state = guidata(fig);

    if isempty(state) || ...
            ~isfield(state, 'sigmoid_ax') || ...
            ~ishandle(state.sigmoid_ax)

        return;
    end


    nz = ...
        state.nz;


    frame_values = ...
        1:max(1, nz);


    sensitivity_values = ...
        zeros( ...
            size(frame_values));


    for idx = 1:numel(frame_values)

        sensitivity_values(idx) = ...
            get_zseries_sigmoid_sensitivity( ...
                state.detection_opts, ...
                frame_values(idx), ...
                nz);

    end


    transition_depth = ...
        state.detection_opts.sensitivity_transition_depth;


    transition_width = ...
        state.detection_opts.sensitivity_transition_width_fraction;


    center_depth = ...
        transition_depth;


    left_depth = ...
        max( ...
            0, ...
            center_depth - ...
            transition_width / ...
            2);


    right_depth = ...
        min( ...
            1, ...
            center_depth + ...
            transition_width / ...
            2);


    center_frame = ...
        1 + ...
        center_depth * ...
        max(nz - 1, 0);


    left_frame = ...
        1 + ...
        left_depth * ...
        max(nz - 1, 0);


    right_frame = ...
        1 + ...
        right_depth * ...
        max(nz - 1, 0);


    center_sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            state.detection_opts, ...
            center_frame, ...
            nz);


    left_sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            state.detection_opts, ...
            left_frame, ...
            nz);


    right_sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            state.detection_opts, ...
            right_frame, ...
            nz);


    current_sensitivity = ...
        get_zseries_sigmoid_sensitivity( ...
            state.detection_opts, ...
            state.current_z, ...
            nz);


    set( ...
        state.sigmoid_curve, ...
        'XData', ...
        frame_values, ...
        'YData', ...
        sensitivity_values);


    set( ...
        state.sigmoid_current_line, ...
        'XData', ...
        [state.current_z state.current_z], ...
        'YData', ...
        [state.detection_opts.minimum_sensitivity 100]);


    set( ...
        state.sigmoid_current_point, ...
        'XData', ...
        state.current_z, ...
        'YData', ...
        current_sensitivity);


    set( ...
        state.sigmoid_start_handle, ...
        'XData', ...
        1, ...
        'YData', ...
        state.detection_opts.shallow_sensitivity);


    set( ...
        state.sigmoid_left_handle, ...
        'XData', ...
        left_frame, ...
        'YData', ...
        left_sensitivity);


    set( ...
        state.sigmoid_center_handle, ...
        'XData', ...
        center_frame, ...
        'YData', ...
        center_sensitivity);


    set( ...
        state.sigmoid_right_handle, ...
        'XData', ...
        right_frame, ...
        'YData', ...
        right_sensitivity);


    set( ...
        state.sigmoid_end_handle, ...
        'XData', ...
        max(1, nz), ...
        'YData', ...
        state.detection_opts.deep_sensitivity);


    xlim( ...
        state.sigmoid_ax, ...
        [1 max(2, nz)]);


    ylim( ...
        state.sigmoid_ax, ...
        [state.detection_opts.minimum_sensitivity 100]);


    width_frames = ...
        transition_width * ...
        max(nz - 1, 0);


    title( ...
        state.sigmoid_ax, ...
        sprintf( ...
            'Frame %d : sens. %.1f', ...
            state.current_z, ...
            current_sensitivity), ...
        'Interpreter', ...
        'none');


    set( ...
        state.sigmoid_info_text, ...
        'String', ...
        sprintf( ...
            'Début %.1f | Fin %.1f | Centre %.1f | Largeur %.1f frames', ...
            state.detection_opts.shallow_sensitivity, ...
            state.detection_opts.deep_sensitivity, ...
            center_frame, ...
            width_frames));

end



%==========================================================================%
% REFRESH 2D PREVIEW
%
% IMPORTANT POUR LA FLUIDITE :
%   - seule la frame actuellement affichee est preparee / segmentee ;
%   - la sensibilite utilisee est celle de la sigmoide pour cette frame ;
%   - aucun rescue Z n'est execute dans le viewer ;
%   - le rescue Z bidirectionnel n'est execute qu'apres Confirmer.
%==========================================================================%

function refresh_zseries_2d_preview(fig)

    state = guidata(fig);
    z = state.current_z;


    if isempty(state.current_enhanced_image) || ...
            state.current_enhanced_z ~= z

        state.current_enhanced_image = ...
            prepare_zseries_detection_plane( ...
                state.registered_volume(:, :, z));


        state.current_enhanced_z = z;

    end


    current_detection_opts = ...
        get_depth_adjusted_detection_opts( ...
            state.detection_opts, ...
            z, ...
            state.nz);


    %==============================================================%
    % APERCU COMPLET DE LA FRAME COURANTE UNIQUEMENT
    %
    % Le watershed et tous les filtres 2D sont appliqués ici pour que
    % l'utilisateur voie immédiatement le résultat final de cette coupe.
    % Aucune autre frame Z n'est recalculée dans le viewer.
    %
    % Le traitement complet de TOUT le stack reste lancé uniquement
    % après Confirmer.
    %==============================================================%

    current_detection_opts.preview_fast_mode = ...
        false;


    [ ...
        state.preview_raw_mask, ...
        state.preview_candidate_mask, ...
        ~, ...
        state.preview_diagnostics ...
    ] = ...
        detect_zseries_candidates_plane_from_enhanced( ...
            state.current_enhanced_image, ...
            state.pixel_size_x_um, ...
            state.pixel_size_y_um, ...
            current_detection_opts);


    guidata(fig, state);

end


%==========================================================================%
% RESCUE LOCAL D'UNE FRAME A PARTIR D'UN VOISIN
%
% Cette fonction n'est appelee que pendant le traitement complet apres
% confirmation du viewer.
%
% Important :
%   - aucune sensibilite globale supplementaire ;
%   - chaque cellule du voisin definit une petite ROI ;
%   - la detection plus permissive n'est calculee que dans cette ROI ;
%   - le candidat doit rester spatialement compatible avec le voisin.
%==========================================================================%

function rescue_mask = ...
        rescue_zseries_candidates_from_neighbor( ...
            enhanced_image, ...
            neighbor_mask, ...
            existing_mask, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            current_detection_opts)

    [ny, nx] = ...
        size(enhanced_image);


    rescue_mask = ...
        false( ...
            ny, ...
            nx);


    if isempty(neighbor_mask) || ...
            ~any(neighbor_mask(:))

        return;
    end


    if ~isfield(current_detection_opts, 'z_rescue_enabled') || ...
            ~current_detection_opts.z_rescue_enabled

        return;
    end


    sensitivity_bonus = ...
        current_detection_opts.z_rescue_sensitivity_bonus;


    rescue_dilation_um = ...
        current_detection_opts.z_rescue_dilation_um;


    minimum_overlap = ...
        current_detection_opts.z_rescue_min_overlap;


    maximum_centroid_distance_um = ...
        current_detection_opts.z_rescue_max_centroid_distance_um;


    mean_pixel_size_um = ...
        mean( ...
            [ ...
                pixel_size_x_um, ...
                pixel_size_y_um]);


    dilation_px = ...
        max( ...
            1, ...
            round( ...
                rescue_dilation_um / ...
                max(mean_pixel_size_um, eps)));


    % Le calcul du fond utilise un grand sigma. On garde assez de marge
    % autour de la cellule pour que la detection locale reste comparable a
    % celle faite sur la frame complete.
    context_padding_px = ...
        max( ...
            dilation_px + 2, ...
            ceil( ...
                3 * ...
                current_detection_opts.background_sigma_um / ...
                max(mean_pixel_size_um, eps)));


    neighbor_cc = ...
        bwconncomp( ...
            neighbor_mask, ...
            8);


    if neighbor_cc.NumObjects == 0
        return;
    end


    neighbor_props = ...
        regionprops( ...
            neighbor_cc, ...
            'Centroid', ...
            'PixelIdxList');


    rescue_opts = ...
        current_detection_opts;


    rescue_opts.sensitivity = ...
        min( ...
            100, ...
            current_detection_opts.sensitivity + ...
            sensitivity_bonus);


    for obj = 1:neighbor_cc.NumObjects

        current_neighbor_mask = ...
            false( ...
                ny, ...
                nx);


        current_neighbor_mask( ...
            neighbor_props(obj).PixelIdxList) = ...
            true;


        dilated_neighbor_mask = ...
            imdilate( ...
                current_neighbor_mask, ...
                strel( ...
                    'disk', ...
                    dilation_px));


        [rows, cols] = ...
            find( ...
                dilated_neighbor_mask);


        if isempty(rows)
            continue;
        end


        row_min = ...
            max( ...
                1, ...
                min(rows) - ...
                context_padding_px);


        row_max = ...
            min( ...
                ny, ...
                max(rows) + ...
                context_padding_px);


        col_min = ...
            max( ...
                1, ...
                min(cols) - ...
                context_padding_px);


        col_max = ...
            min( ...
                nx, ...
                max(cols) + ...
                context_padding_px);


        local_image = ...
            enhanced_image( ...
                row_min:row_max, ...
                col_min:col_max);


        [ ...
            ~, ...
            ~, ...
            local_detections ...
        ] = ...
            detect_zseries_candidates_plane_from_enhanced( ...
                local_image, ...
                pixel_size_x_um, ...
                pixel_size_y_um, ...
                rescue_opts);


        if isempty(local_detections)
            continue;
        end


        neighbor_centroid = ...
            neighbor_props(obj).Centroid;


        neighbor_area = ...
            nnz( ...
                current_neighbor_mask);


        for d = 1:numel(local_detections)

            local_mask = ...
                local_detections(d).Mask;


            global_candidate_mask = ...
                false( ...
                    ny, ...
                    nx);


            global_candidate_mask( ...
                row_min:row_max, ...
                col_min:col_max) = ...
                local_mask;


            candidate_area = ...
                nnz( ...
                    global_candidate_mask);


            if candidate_area == 0
                continue;
            end


            % Si l'objet est deja detecte normalement sur cette frame, il
            % n'est pas un rescue et ne doit pas etre recolore / agrandi.
            existing_overlap_fraction = ...
                nnz( ...
                    global_candidate_mask & ...
                    existing_mask) / ...
                candidate_area;


            if existing_overlap_fraction >= 0.25
                continue;
            end


            overlap_denominator = ...
                max( ...
                    1, ...
                    min( ...
                        candidate_area, ...
                        neighbor_area));


            overlap_fraction = ...
                nnz( ...
                    global_candidate_mask & ...
                    current_neighbor_mask) / ...
                overlap_denominator;


            current_centroid = ...
                local_detections(d).Centroid + ...
                [ ...
                    col_min - 1, ...
                    row_min - 1];


            dx_um = ...
                ( ...
                    current_centroid(1) - ...
                    neighbor_centroid(1)) * ...
                pixel_size_x_um;


            dy_um = ...
                ( ...
                    current_centroid(2) - ...
                    neighbor_centroid(2)) * ...
                pixel_size_y_um;


            centroid_distance_um = ...
                hypot( ...
                    dx_um, ...
                    dy_um);


            if overlap_fraction < minimum_overlap || ...
                    centroid_distance_um > ...
                    maximum_centroid_distance_um

                continue;
            end


            rescue_mask = ...
                rescue_mask | ...
                global_candidate_mask;


            existing_mask = ...
                existing_mask | ...
                global_candidate_mask;

        end

    end

end



%==========================================================================%
% UPDATE 2D DISPLAY
%==========================================================================%

function update_zseries_2d_display(fig)

    if ~ishandle(fig)
        return;
    end


    state = guidata(fig);

    if isempty(state)
        return;
    end


    z = state.current_z;
    ax = state.ax;

    cla(ax);


    %==============================================================%
    % ETAPE DIAGNOSTIQUE A AFFICHER
    %
    % Le popup permet de suivre le signal depuis l'image recalée jusqu'au
    % masque final. Les contours rouge / jaune restent ceux de la détection
    % finale de la frame courante afin de pouvoir comparer directement les
    % étapes intermédiaires avec la décision finale de l'algorithme.
    %==============================================================%

    stage_idx = ...
        1;


    if isfield(state, 'stage_popup') && ...
            ishandle(state.stage_popup)

        stage_idx = ...
            round( ...
                get( ...
                    state.stage_popup, ...
                    'Value'));

    end


    stage_idx = ...
        max( ...
            1, ...
            min( ...
                14, ...
                stage_idx));


    diagnostics = ...
        struct();


    if isfield(state, 'preview_diagnostics') && ...
            isstruct(state.preview_diagnostics)

        diagnostics = ...
            state.preview_diagnostics;

    end


    original_image = ...
        state.registered_volume(:, :, z);


    zero_map = ...
        zeros( ...
            size(original_image), ...
            'single');


    zero_mask = ...
        false( ...
            size(original_image));


    is_binary_stage = ...
        false;


    force_unit_limits = ...
        false;


    stage_extra = ...
        '';


    switch stage_idx

        case 1

            current_image = ...
                original_image;

            stage_name = ...
                'Image recalée';


        case 2

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'normalized_image', ...
                    state.current_enhanced_image);

            stage_name = ...
                'Image normalisée';

            force_unit_limits = ...
                true;


        case 3

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'soma_signal', ...
                    zero_map);

            stage_name = ...
                'Signal soma';


        case 4

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'background', ...
                    zero_map);

            stage_name = ...
                'Fond estimé';


        case 5

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'soma_response', ...
                    zero_map);

            stage_name = ...
                'Réponse soma';


        case 6

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'response_normalized', ...
                    zero_map);

            stage_name = ...
                'Réponse soma normalisée';

            if isfield(diagnostics, 'response_reference') && ...
                    isfinite(diagnostics.response_reference)

                stage_extra = ...
                    sprintf( ...
                        ' | référence %.4g', ...
                        diagnostics.response_reference);

            end


        case 7

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'peak_response', ...
                    zero_map);

            stage_name = ...
                'Réponse pour pics';

            if isfield(diagnostics, 'peak_prominence') && ...
                    isfinite(diagnostics.peak_prominence)

                stage_extra = ...
                    sprintf( ...
                        ' | prominence %.4g', ...
                        diagnostics.peak_prominence);

            end


        case 8

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'local_maxima_mask', ...
                    zero_mask);

            stage_name = ...
                'Maxima locaux';

            is_binary_stage = ...
                true;


        case 9

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'peak_seed_mask', ...
                    zero_mask);

            stage_name = ...
                'Pics brillants retenus';

            is_binary_stage = ...
                true;

            if isfield(diagnostics, 'response_seed_threshold') && ...
                    isfinite(diagnostics.response_seed_threshold)

                stage_extra = ...
                    sprintf( ...
                        ' | seuil pic %.4g', ...
                        diagnostics.response_seed_threshold);

            end


        case 10

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'response_growth_mask', ...
                    zero_mask);

            stage_name = ...
                'Croissance depuis les pics';

            is_binary_stage = ...
                true;


        case 11

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'before_morphology_mask', ...
                    zero_mask);

            stage_name = ...
                'Candidats bruts';

            is_binary_stage = ...
                true;


        case 12

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'after_morphology_mask', ...
                    zero_mask);

            stage_name = ...
                'Après nettoyage';

            is_binary_stage = ...
                true;


        case 13

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'after_watershed_mask', ...
                    zero_mask);

            stage_name = ...
                'Après watershed';

            is_binary_stage = ...
                true;


        case 14

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'after_size_mask', ...
                    zero_mask);

            stage_name = ...
                'Après taille';

            is_binary_stage = ...
                true;


        case 15

            current_image = ...
                get_zseries_diagnostic_field( ...
                    diagnostics, ...
                    'after_circularity_mask', ...
                    zero_mask);

            stage_name = ...
                'Après circularité = résultat final';

            is_binary_stage = ...
                true;


    end


    %==============================================================%
    % LIMITES D'AFFICHAGE
    %==============================================================%

    if stage_idx == 1

        %----------------------------------------------------------%
        % Image originale : on conserve le cache de contraste par frame.
        %----------------------------------------------------------%

        if ~isfield(state, 'display_limits') || ...
                size(state.display_limits, 1) ~= state.nz

            state.display_limits = ...
                nan( ...
                    state.nz, ...
                    2);

        end


        if any( ...
                ~isfinite( ...
                    state.display_limits(z, :)))

            [ ...
                low_display, ...
                high_display ...
            ] = ...
                get_zseries_diagnostic_display_limits( ...
                    current_image, ...
                    state.display_low_percentile, ...
                    state.display_high_percentile);


            state.display_limits(z, :) = ...
                [ ...
                    low_display, ...
                    high_display];


            guidata( ...
                fig, ...
                state);

        else

            low_display = ...
                state.display_limits(z, 1);


            high_display = ...
                state.display_limits(z, 2);

        end


    elseif is_binary_stage || ...
            force_unit_limits

        low_display = ...
            0;


        high_display = ...
            1;


    else

        [ ...
            low_display, ...
            high_display ...
        ] = ...
            get_zseries_diagnostic_display_limits( ...
                current_image, ...
                1, ...
                99.5);

    end


    imagesc( ...
        ax, ...
        current_image, ...
        [ ...
            low_display, ...
            high_display]);


    axis(ax, 'image');
    axis(ax, 'off');
    colormap(ax, gray);
    hold(ax, 'on');


    %==============================================================%
    % RESULTAT COURANT : ROUGE
    %
    % Il correspond au masque final apres watershed, taille et circularite.
    %==============================================================%

    if any(state.preview_candidate_mask(:))

        contour( ...
            ax, ...
            state.preview_candidate_mask, ...
            [0.5 0.5], ...
            'Color', ...
            [1 0 0], ...
            'LineWidth', ...
            1.5);

    end


    hold(ax, 'off');


    retained_cc = ...
        bwconncomp( ...
            state.preview_candidate_mask, ...
            8);


    current_detection_opts = ...
        get_depth_adjusted_detection_opts( ...
            state.detection_opts, ...
            z, ...
            state.nz);


    effective_sensitivity = ...
        current_detection_opts.sensitivity;


    title_string = ...
        sprintf( ...
            '%s | Z %d / %d | sens. %.1f | %d détection(s)%s', ...
            stage_name, ...
            z, ...
            state.nz, ...
            effective_sensitivity, ...
            retained_cc.NumObjects, ...
            stage_extra);


    title( ...
        ax, ...
        title_string, ...
        'Interpreter', ...
        'none');


    drawnow;

end


%==========================================================================%
% RETOURNE UN CHAMP DE DIAGNOSTIC AVEC FALLBACK
%==========================================================================%

function value = ...
        get_zseries_diagnostic_field( ...
            diagnostics, ...
            field_name, ...
            fallback_value)

    value = ...
        fallback_value;


    if isempty(diagnostics) || ...
            ~isstruct(diagnostics) || ...
            ~isfield(diagnostics, field_name)

        return;
    end


    candidate_value = ...
        diagnostics.(field_name);


    if ~isempty(candidate_value)
        value = candidate_value;
    end

end


%==========================================================================%
% LIMITES ROBUSTES POUR UNE CARTE DIAGNOSTIQUE
%==========================================================================%

function [low_display, high_display] = ...
        get_zseries_diagnostic_display_limits( ...
            current_image, ...
            low_percentile, ...
            high_percentile)

    finite_values = ...
        double( ...
            current_image( ...
                isfinite(current_image)));


    if isempty(finite_values)

        low_display = ...
            0;


        high_display = ...
            1;


        return;
    end


    low_display = ...
        prctile( ...
            finite_values, ...
            low_percentile);


    high_display = ...
        prctile( ...
            finite_values, ...
            high_percentile);


    % Pour les cartes positives très clairsemées, les percentiles peuvent
    % tous deux tomber à zéro. Dans ce cas on recalcule la borne haute sur
    % les valeurs strictement positives pour rendre les structures visibles.
    if (~isfinite(high_display) || ...
            high_display <= low_display) && ...
            all(finite_values >= 0)

        positive_values = ...
            finite_values( ...
                finite_values > 0);


        if ~isempty(positive_values)

            low_display = ...
                0;


            high_display = ...
                prctile( ...
                    positive_values, ...
                    high_percentile);

        end

    end


    if ~isfinite(low_display) || ...
            ~isfinite(high_display) || ...
            high_display <= low_display

        low_display = ...
            min(finite_values);


        high_display = ...
            max(finite_values);

    end


    if high_display <= low_display

        display_padding = ...
            max( ...
                eps, ...
                abs(low_display) * ...
                1e-3);


        low_display = ...
            low_display - ...
            display_padding;


        high_display = ...
            high_display + ...
            display_padding;

    end

end


%==========================================================================%
% CONFIRM 2D DETECTION
%==========================================================================%

function zseries_2d_confirm_callback(src, ~)

    fig = ancestor(src, 'figure');
    state = guidata(fig);

    if state.busy
        return;
    end


    % Aucun calcul complet du stack dans le callback.
    % On valide simplement les paramètres courants ; le pipeline applique
    % ensuite ces paramètres à toutes les frames Z.
    state.confirmed = true;
    state.busy = true;


    if ishandle(state.confirm_button)

        set( ...
            state.confirm_button, ...
            'Enable', ...
            'off');

    end


    if ishandle(state.cancel_button)

        set( ...
            state.cancel_button, ...
            'Enable', ...
            'off');

    end


    guidata(fig, state);
    uiresume(fig);

end



%==========================================================================%
% CANCEL 2D DETECTION
%==========================================================================%

function zseries_2d_cancel_callback(src, ~)

    if strcmp(get(src, 'Type'), 'figure')

        fig = src;

    else

        fig = ancestor(src, 'figure');

    end


    state = guidata(fig);

    if isempty(state)
        delete(fig);
        return;
    end


    state.confirmed = false;
    guidata(fig, state);
    uiresume(fig);

end



