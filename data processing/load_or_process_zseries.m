%==========================================================================%
% LOAD EXISTING ZSERIES RESULT
%==========================================================================%

function [zseries, source_file] = ...
        load_existing_zseries_result( ...
            results_file, ...
            legacy_results_movie_file)

    zseries = [];
    source_file = '';


    %==============================================================%
    % Fichier ZSeries actuel
    %==============================================================%

    if exist(results_file, 'file') == 2

        loaded = ...
            load(results_file);


        if isfield(loaded, 'zseries') && ...
                isstruct(loaded.zseries) && ...
                ~isempty(loaded.zseries)

            zseries = ...
                loaded.zseries;

            source_file = ...
                results_file;

            return;
        end


        % Tolère aussi un fichier où les champs ZSeries auraient
        % été sauvegardés directement avec save -struct.
        if is_zseries_like_struct(loaded)

            zseries = ...
                loaded;

            source_file = ...
                results_file;

            return;
        end

    end


    %==============================================================%
    % Ancien results_movie.mat
    %
    % On ne le considère comme ZSeries que s'il contient réellement
    % une variable zseries ou des champs caractéristiques de ZSeries.
    % Un fichier de motion classique n'est donc jamais interprété
    % comme une reconstruction Z.
    %==============================================================%

    if exist(legacy_results_movie_file, 'file') == 2

        loaded = ...
            load(legacy_results_movie_file);


        if isfield(loaded, 'zseries') && ...
                isstruct(loaded.zseries) && ...
                ~isempty(loaded.zseries)

            zseries = ...
                loaded.zseries;

            source_file = ...
                legacy_results_movie_file;

            return;
        end


        if is_zseries_like_struct(loaded)

            zseries = ...
                loaded;

            source_file = ...
                legacy_results_movie_file;

            return;
        end

    end

end



%==========================================================================%
% IS ZSERIES-LIKE STRUCT
%==========================================================================%

function tf = is_zseries_like_struct(value)

    tf = ...
        isstruct(value) && ...
        ( ...
            isfield(value, 'registered_volume') || ...
            isfield(value, 'filtered_volume') || ...
            isfield(value, 'cells_3d') || ...
            isfield(value, 'cell_mask_3d') || ...
            isfield(value, 'detected_cells_2d_mask_3d') ...
        );

end



%==========================================================================%
% STANDARDIZE ZSERIES RESULT
%==========================================================================%

function zseries = standardize_zseries_result(input_zseries)

    zseries = ...
        create_empty_zseries_result();


    if isempty(input_zseries) || ...
            ~isstruct(input_zseries)

        return;

    end


    input_zseries = ...
        input_zseries(1);


    template_fields = ...
        fieldnames(zseries);


    for f = 1:numel(template_fields)

        current_field = ...
            template_fields{f};


        if isfield( ...
                input_zseries, ...
                current_field)

            zseries.(current_field) = ...
                input_zseries.(current_field);

        end

    end

end



%==========================================================================%
% DEFAULT DETECTION OPTIONS
%==========================================================================%

function detection_opts = ...
        get_default_zseries_detection_opts()

    detection_opts = struct();


    %==============================================================%
    % PARAMETRES 2D VISIBLES
    %==============================================================%

    % Champ conserve pour compatibilite avec les anciens resultats.
    % La vraie sensibilite depend maintenant directement de la courbe
    % sigmoide reglee graphiquement dans le viewer.
    detection_opts.sensitivity = ...
        45;


    %==============================================================%
    % COURBE SIGMOIDE DE SENSIBILITE
    %
    % La courbe est controlee directement dans le viewer :
    %
    %   shallow_sensitivity
    %       plateau de depart, regle verticalement.
    %
    %   deep_sensitivity
    %       plateau final, regle verticalement.
    %
    %   sensitivity_transition_depth
    %       position horizontale du centre de la transition.
    %
    %   sensitivity_transition_width_fraction
    %       largeur horizontale de la transition.
    %       Petite valeur = transition abrupte.
    %       Grande valeur = transition etalee.
    %==============================================================%

    detection_opts.shallow_sensitivity = ...
        45;


    % Echelle du viewer : 0 = tres stricte, 100 = tres sensible.
    detection_opts.minimum_sensitivity = ...
        0;


    detection_opts.deep_sensitivity = ...
        95;


    detection_opts.sensitivity_transition_depth = ...
        0.42;


    detection_opts.sensitivity_transition_width_fraction = ...
        0.20;


    % Champs historiques conserves pour compatibilite uniquement.
    % Ils ne pilotent plus la courbe sigmoide.
    detection_opts.sensitivity_growth_amplitude = ...
        10.0;


    detection_opts.sensitivity_exponential_rate = ...
        20.0;


    detection_opts.min_area_um2 = ...
        100;


    detection_opts.min_circularity = ...
        0.50;


    %==============================================================%
    % ECHELLE DU SOMA
    %
    % C'est le changement principal :
    %
    %   petit objet brillant
    %       -> fortement dilué par le lissage
    %
    %   grosse structure
    %       -> signal conservé
    %==============================================================%

    detection_opts.soma_signal_sigma_um = ...
        3.5;


    detection_opts.background_sigma_um = ...
        14;


    %==============================================================%
    % ESTIMATION DU BRUIT LOCAL
    %==============================================================%

    detection_opts.noise_sigma_um = ...
        6;


    %==============================================================%
    % SUPPORT SPATIAL
    %
    % Un signal légèrement sous le seuil peut être accepté s'il est
    % présent sur une zone suffisamment large.
    %
    % Cela aide beaucoup les gros somas faiblement contrastés.
    %==============================================================%

    detection_opts.support_sigma_um = ...
        4;


    detection_opts.weak_score_fraction = ...
        0.65;


    detection_opts.weak_support_fraction = ...
        0.40;


    detection_opts.strong_support_fraction = ...
        0.10;


    %==============================================================%
    % MORPHOLOGIE
    %==============================================================%

    detection_opts.soma_closing_radius_um = ...
        2;


    detection_opts.soma_opening_radius_um = ...
        1.5;


    % Masque très préliminaire.
    % Le vrai min_area_um2 reste contrôlé par le slider.
    detection_opts.candidate_min_area_um2 = ...
        12;


    detection_opts.max_area_um2 = ...
        5000;


    %==============================================================%
    % WATERSHED 2D
    %
    % Sépare les somas qui se touchent après la construction du
    % masque candidat.
    %
    % watershed_strength :
    %   0 = désactivé
    %   1 = séparation maximale
    %
    % Le seuil technique du watershed est calculé automatiquement
    % à partir de la taille physique attendue d'un soma.
    %==============================================================%

    detection_opts.watershed_strength = ...
        0.90;


    detection_opts.watershed_smoothing_um = ...
        0.5;


    %==============================================================%
    % RESCUE Z INTER-PLANS
    %
    % Une cellule clairement détectée sur une coupe peut être juste
    % sous le seuil sur la coupe voisine. Le rescue ne rend PAS toute
    % la frame plus sensible : il recherche localement autour des
    % cellules déjà détectées sur z-1 / z+1 avec une petite tolérance
    % supplémentaire.
    %
    % IMPORTANT : aucun rescue n'est calcule dans le viewer.
    % Le viewer ne segmente que la frame courante avec la sensibilite
    % donnee par la sigmoide. Le rescue Z est applique uniquement apres
    % Confirmer, lors du traitement de toutes les frames.
    %==============================================================%

    detection_opts.z_rescue_enabled = ...
        true;


    detection_opts.z_rescue_sensitivity_bonus = ...
        7;


    detection_opts.z_rescue_dilation_um = ...
        8;


    detection_opts.z_rescue_min_overlap = ...
        0.15;


    detection_opts.z_rescue_max_centroid_distance_um = ...
        8;


    %==============================================================%
    % FILTRES DE FORME
    %
    % Le rayon interne est particulièrement efficace contre les
    % petites poussières / ponctuations.
    %==============================================================%

    detection_opts.min_soma_core_radius_um = ...
        3.5;


    detection_opts.min_soma_solidity = ...
        0.45;


    detection_opts.max_soma_elongation = ...
        3.5;


    %==============================================================%
    % RECONSTRUCTION 3D
    %==============================================================%

    detection_opts.min_real_detections = ...
        2;


    detection_opts.max_z_gap_um = ...
        6;


    detection_opts.max_centroid_distance_um = ...
        10;


    detection_opts.min_overlap_fraction = ...
        0.10;


    %==============================================================%
    % FILTRES 3D
    %==============================================================%

    detection_opts.min_cell_volume_um3 = ...
        300;


    detection_opts.max_cell_volume_um3 = ...
        50000;


    detection_opts.min_z_extent_um = ...
        0;


    detection_opts.max_z_extent_um = ...
        Inf;

end


