function volume = ...
        reconstruct_raw_zseries_volume( ...
            zseries_path)

    volume = [];


    tif_files = [ ...
        dir( ...
            fullfile( ...
                zseries_path, ...
                '*.tif')); ...
        dir( ...
            fullfile( ...
                zseries_path, ...
                '*.tiff'))];


    if isempty(tif_files)

        fprintf( ...
            'Aucun TIFF trouvé : %s\n', ...
            zseries_path);

        return;

    end


    full_paths = ...
        fullfile( ...
            {tif_files.folder}, ...
            {tif_files.name});


    [~, unique_idx] = ...
        unique( ...
            lower(full_paths), ...
            'stable');


    tif_files = ...
        tif_files(unique_idx);


    [~, order] = ...
        sort( ...
            {tif_files.name});


    tif_files = ...
        tif_files(order);


    total_frames = ...
        0;


    for i = 1:numel(tif_files)

        current_file = ...
            fullfile( ...
                tif_files(i).folder, ...
                tif_files(i).name);


        info = ...
            imfinfo( ...
                current_file);


        total_frames = ...
            total_frames + ...
            numel(info);

    end


    fprintf( ...
        'TIFF   : %d\n', ...
        numel(tif_files));


    fprintf( ...
        'Frames : %d\n', ...
        total_frames);


    if total_frames == 0
        return;
    end


    first_file = ...
        fullfile( ...
            tif_files(1).folder, ...
            tif_files(1).name);


    first_image = ...
        imread( ...
            first_file, ...
            1);


    [ny, nx] = ...
        size(first_image);


    volume = ...
        zeros( ...
            ny, ...
            nx, ...
            total_frames, ...
