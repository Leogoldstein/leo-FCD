%==========================================================================%
% RESCUE Z COMPLET APRES CONFIRMATION - VERSION OPTIMISEE
%
% Principe :
%   1) les detections normales restent les seeds immuables ;
%   2) chaque frame est re-segmentee UNE SEULE FOIS avec le bonus de
%      sensibilite du rescue ;
%   3) ce passage est parallelise sur les frames ;
%   4) parmi ces candidats permissifs, seuls ceux compatibles spatialement
%      avec une detection normale de z-1 ou z+1 sont conserves ;
%   5) une detection rescue ne peut jamais servir de seed a une autre.
%
% Cela remplace l'ancienne strategie qui relancait toute la detection
% locale pour chaque cellule voisine, ce qui pouvait multiplier fortement
% le temps de calcul apres Confirmer.
%==========================================================================%

function [ ...
        candidate_mask_3d, ...
        detections_by_plane, ...
        rescue_mask_3d ...
    ] = ...
        apply_zseries_z_rescue_full( ...
            enhanced_volume, ...
            candidate_mask_3d, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            detection_opts)

    [ny, nx, nz] = ...
        size(candidate_mask_3d);


    rescue_mask_3d = ...
        false( ...
            ny, ...
            nx, ...
            nz);


    %==============================================================%
    % PAS DE RESCUE
    %
    % Le tracking n'utilise ensuite que Mask et Centroid. On reconstruit
    % donc volontairement des structures legeres, sans recalculer bwdist,
    % solidity, elongation, etc.
    %==============================================================%

    if nz <= 1 || ...
            ~isfield(detection_opts, 'z_rescue_enabled') || ...
            ~detection_opts.z_rescue_enabled

        detections_by_plane = ...
            cell( ...
                nz, ...
                1);


        tracking_detections_by_plane = ...
            cell( ...
                nz, ...
                1);


        parfor z = 1:nz

            tracking_detections_by_plane{z} = ...
                build_zseries_tracking_detections_from_mask( ...
                    candidate_mask_3d(:, :, z));

        end


        detections_by_plane = ...
            tracking_detections_by_plane;


        return;
    end


    %==============================================================%
    % DETECTIONS NORMALES = SEEDS IMMUTABLES
    %==============================================================%

    seed_mask_3d = ...
        candidate_mask_3d;


    rescue_masks_by_plane = ...
        cell( ...
            nz, ...
            1);


    % Masques voisins pre-decales pour que les acces dans le parfor soient
    % des slices simples (..., z), compatibles avec la classification parfor.
    previous_seed_mask_3d = ...
        false( ...
            ny, ...
            nx, ...
            nz);


    next_seed_mask_3d = ...
        false( ...
            ny, ...
            nx, ...
            nz);


    if nz > 1

        previous_seed_mask_3d(:, :, 2:nz) = ...
            seed_mask_3d(:, :, 1:nz - 1);


        next_seed_mask_3d(:, :, 1:nz - 1) = ...
            seed_mask_3d(:, :, 2:nz);

    end


    %==============================================================%
    % RESCUE PAR FRAME, EN PARALLELE
    %
    % Une seule detection permissive par frame, quelle que soit la quantite
    % de cellules presentes sur les frames voisines.
    %==============================================================%

    parfor z = 1:nz

        previous_seed_mask = ...
            previous_seed_mask_3d(:, :, z);


        next_seed_mask = ...
            next_seed_mask_3d(:, :, z);


        % Aucun voisin normal = aucun rescue possible. On evite alors
        % completement le second passage de detection sur cette frame.
        if ~any(previous_seed_mask(:)) && ...
                ~any(next_seed_mask(:))

            rescue_masks_by_plane{z} = ...
                false( ...
                    ny, ...
                    nx);

            continue;
        end


        current_detection_opts = ...
            get_depth_adjusted_detection_opts( ...
                detection_opts, ...
                z, ...
                nz);


        rescue_opts = ...
            current_detection_opts;


        rescue_opts.preview_fast_mode = ...
            false;


        rescue_opts.sensitivity = ...
            min( ...
                100, ...
                current_detection_opts.sensitivity + ...
                current_detection_opts.z_rescue_sensitivity_bonus);


        [ ...
            ~, ...
            permissive_candidate_mask ...
        ] = ...
            detect_zseries_candidates_plane_from_enhanced( ...
                enhanced_volume(:, :, z), ...
                pixel_size_x_um, ...
                pixel_size_y_um, ...
                rescue_opts);


        rescue_masks_by_plane{z} = ...
            select_zseries_rescue_candidates_from_mask( ...
                permissive_candidate_mask, ...
                seed_mask_3d(:, :, z), ...
                previous_seed_mask, ...
                next_seed_mask, ...
                pixel_size_x_um, ...
                pixel_size_y_um, ...
                current_detection_opts.z_rescue_min_overlap, ...
                current_detection_opts.z_rescue_max_centroid_distance_um);

    end


    %==============================================================%
    % ASSEMBLAGE DU VOLUME RESCUE
    %==============================================================%

    for z = 1:nz

        rescue_mask_3d(:, :, z) = ...
            rescue_masks_by_plane{z};

    end


    candidate_mask_3d = ...
        candidate_mask_3d | ...
        rescue_mask_3d;


    %==============================================================%
    % STRUCTURES LEGERES POUR LE TRACKING
    %
    % On ne recalcule pas les metriques morphologiques couteuses ici : elles
    % ont deja servi a filtrer les masques lors de la detection 2D complete.
    % Le tracking utilise uniquement Mask et Centroid.
    %==============================================================%

    tracking_detections_by_plane = ...
        cell( ...
            nz, ...
            1);


    parfor z = 1:nz

        tracking_detections_by_plane{z} = ...
            build_zseries_tracking_detections_from_mask( ...
                candidate_mask_3d(:, :, z));

    end


    detections_by_plane = ...
        tracking_detections_by_plane;

end


%==========================================================================%
% SELECTION DES CANDIDATS RESCUE A PARTIR D'UN MASQUE PERMISSIF
%
% Un objet permissif est conserve uniquement s'il :
%   - n'est pas deja une detection normale sur la frame courante ;
%   - recouvre suffisamment une detection normale de z-1 OU z+1 ;
%   - reste assez proche de son centroide.
%
% Aucun nouveau calcul de segmentation n'est effectue ici.
%==========================================================================%

function rescue_mask = ...
        select_zseries_rescue_candidates_from_mask( ...
            permissive_candidate_mask, ...
            existing_mask, ...
            previous_seed_mask, ...
            next_seed_mask, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            minimum_overlap, ...
            maximum_centroid_distance_um)

    [ny, nx] = ...
        size(permissive_candidate_mask);


    rescue_mask = ...
        false( ...
            ny, ...
            nx);


    if ~any(permissive_candidate_mask(:))
        return;
    end


    if ~any(previous_seed_mask(:)) && ...
            ~any(next_seed_mask(:))

        return;
    end


    permissive_cc = ...
        bwconncomp( ...
            permissive_candidate_mask, ...
            8);


    permissive_props = ...
        regionprops( ...
            permissive_cc, ...
            'Area', ...
            'Centroid', ...
            'PixelIdxList');


    [ ...
        previous_seed_labels, ...
        previous_props ...
    ] = ...
        get_zseries_seed_props( ...
            previous_seed_mask);


    [ ...
        next_seed_labels, ...
        next_props ...
    ] = ...
        get_zseries_seed_props( ...
            next_seed_mask);


    for obj = 1:numel(permissive_props)

        candidate_idx = ...
            permissive_props(obj).PixelIdxList;


        candidate_area = ...
            permissive_props(obj).Area;


        if candidate_area <= 0
            continue;
        end


        %----------------------------------------------------------%
        % Deja present normalement sur la frame courante
        %----------------------------------------------------------%

        existing_overlap_fraction = ...
            nnz( ...
                existing_mask(candidate_idx)) / ...
            candidate_area;


        if existing_overlap_fraction >= 0.25
            continue;
        end


        candidate_centroid = ...
            permissive_props(obj).Centroid;


        accepted = ...
            rescue_candidate_matches_seed_props( ...
                candidate_idx, ...
                candidate_area, ...
                candidate_centroid, ...
                previous_seed_labels, ...
                previous_props, ...
                pixel_size_x_um, ...
                pixel_size_y_um, ...
                minimum_overlap, ...
                maximum_centroid_distance_um);


        if ~accepted

            accepted = ...
                rescue_candidate_matches_seed_props( ...
                    candidate_idx, ...
                    candidate_area, ...
                    candidate_centroid, ...
                    next_seed_labels, ...
                    next_props, ...
                    pixel_size_x_um, ...
                    pixel_size_y_um, ...
                    minimum_overlap, ...
                    maximum_centroid_distance_um);

        end


        if accepted

            rescue_mask(candidate_idx) = ...
                true;

        end

    end

end


%==========================================================================%
% PROPRIETES LEGERES DES SEEDS D'UNE FRAME VOISINE
%==========================================================================%

function [seed_labels, seed_props] = ...
        get_zseries_seed_props( ...
            seed_mask)

    seed_labels = ...
        zeros( ...
            size(seed_mask), ...
            'uint32');


    seed_props = ...
        struct( ...
            'Area', {}, ...
            'Centroid', {}, ...
            'PixelIdxList', {});


    if isempty(seed_mask) || ...
            ~any(seed_mask(:))

        return;
    end


    seed_cc = ...
        bwconncomp( ...
            seed_mask, ...
            8);


    seed_props = ...
        regionprops( ...
            seed_cc, ...
            'Area', ...
            'Centroid', ...
            'PixelIdxList');


    for obj = 1:seed_cc.NumObjects

        seed_labels( ...
            seed_cc.PixelIdxList{obj}) = ...
            uint32(obj);

    end

end


%==========================================================================%
% COMPATIBILITE D'UN CANDIDAT RESCUE AVEC UNE FRAME VOISINE
%==========================================================================%

function accepted = ...
        rescue_candidate_matches_seed_props( ...
            candidate_idx, ...
            candidate_area, ...
            candidate_centroid, ...
            seed_labels, ...
            seed_props, ...
            pixel_size_x_um, ...
            pixel_size_y_um, ...
            minimum_overlap, ...
            maximum_centroid_distance_um)

    accepted = ...
        false;


    if isempty(seed_props) || ...
            ~any(seed_labels(:))

        return;
    end


    %==============================================================%
    % Seules les composantes qui ont un recouvrement avec le candidat
    % peuvent satisfaire le critere d'overlap. Cela evite de calculer la
    % distance au centroide de toutes les cellules de la frame voisine.
    %==============================================================%

    touched_labels = ...
        unique( ...
            seed_labels(candidate_idx));


    touched_labels = ...
        touched_labels( ...
            touched_labels > 0);


    if isempty(touched_labels)
        return;
    end


    for k = 1:numel(touched_labels)

        seed_idx = ...
            double( ...
                touched_labels(k));


        if seed_idx > numel(seed_props)
            continue;
        end


        intersection_area = ...
            nnz( ...
                seed_labels(candidate_idx) == ...
                seed_idx);


        overlap_denominator = ...
            max( ...
                1, ...
                min( ...
                    candidate_area, ...
                    seed_props(seed_idx).Area));


        overlap_fraction = ...
            intersection_area / ...
            overlap_denominator;


        if overlap_fraction < minimum_overlap
            continue;
        end


        dx_um = ...
            ( ...
                candidate_centroid(1) - ...
                seed_props(seed_idx).Centroid(1)) * ...
            pixel_size_x_um;


        dy_um = ...
            ( ...
                candidate_centroid(2) - ...
                seed_props(seed_idx).Centroid(2)) * ...
            pixel_size_y_um;


        centroid_distance_um = ...
            hypot( ...
                dx_um, ...
                dy_um);


        if centroid_distance_um <= ...
                maximum_centroid_distance_um

            accepted = ...
                true;

            return;
        end

    end

end


%==========================================================================%
% STRUCTURES MINIMALES POUR LE TRACKING 3D
%
% Evite bwdist / perimeter / solidity / axes pour chaque cellule apres le
% rescue. Les filtres 2D complets ont deja ete appliques au masque final.
%==========================================================================%

function detections = ...
        build_zseries_tracking_detections_from_mask( ...
            mask)

    detections = ...
        struct( ...
            'Mask', {}, ...
            'Centroid', {});


    if isempty(mask) || ...
            ~any(mask(:))

        return;
    end


    [ny, nx] = ...
        size(mask);


    cc = ...
        bwconncomp( ...
            mask, ...
            8);


    props = ...
        regionprops( ...
            cc, ...
            'Centroid', ...
            'PixelIdxList');


    detections = ...
        repmat( ...
            struct( ...
                'Mask', [], ...
                'Centroid', []), ...
            numel(props), ...
            1);


    for obj = 1:numel(props)

        current_mask = ...
            false( ...
                ny, ...
                nx);


        current_mask( ...
            props(obj).PixelIdxList) = ...
            true;


        detections(obj).Mask = ...
            current_mask;


        detections(obj).Centroid = ...
            props(obj).Centroid;

    end

end


%==========================================================================%
% CONVERTIT UN MASQUE 2D FINAL EN STRUCTURES DE DETECTION
%==========================================================================%

function detections = ...
        build_zseries_detections_from_mask( ...
            mask, ...
            pixel_size_x_um, ...
            pixel_size_y_um)

    detections = ...
        struct( ...
            'Mask', {}, ...
            'Centroid', {}, ...
            'Area_um2', {}, ...
            'Circularity', {}, ...
            'Solidity', {}, ...
            'CoreRadius_um', {}, ...
            'Elongation', {}, ...
            'LocalContrastScore', {});


    if isempty(mask) || ...
            ~any(mask(:))

        return;
    end


    [ny, nx] = ...
        size(mask);


    pixel_area_um2 = ...
        pixel_size_x_um * ...
        pixel_size_y_um;


    mean_pixel_size_um = ...
        mean( ...
            [ ...
                pixel_size_x_um, ...
                pixel_size_y_um]);


    cc = ...
        bwconncomp( ...
            mask, ...
            8);


    props = ...
        regionprops( ...
            cc, ...
            'Area', ...
            'Perimeter', ...
            'Centroid', ...
            'PixelIdxList', ...
            'Solidity', ...
            'MajorAxisLength', ...
            'MinorAxisLength');


    for obj = 1:numel(props)

        current_mask = ...
            false( ...
                ny, ...
                nx);


        current_mask( ...
            props(obj).PixelIdxList) = ...
            true;


        distance_inside_px = ...
            bwdist( ...
                ~current_mask);


        core_radius_px = ...
            max( ...
                distance_inside_px(current_mask), ...
                [], ...
                'omitnan');


        if isempty(core_radius_px) || ...
                ~isfinite(core_radius_px)

            core_radius_px = ...
                0;

        end


        if props(obj).MinorAxisLength > 0

            elongation = ...
                props(obj).MajorAxisLength / ...
                props(obj).MinorAxisLength;

        else

            elongation = ...
                Inf;

        end


        if props(obj).Perimeter > 0

            circularity = ...
                4 * pi * ...
                props(obj).Area / ...
                props(obj).Perimeter ^ 2;


            circularity = ...
                min( ...
                    circularity, ...
                    1);

        else

            circularity = ...
                0;

        end


        detections(obj).Mask = ...
            current_mask;


        detections(obj).Centroid = ...
            props(obj).Centroid;


        detections(obj).Area_um2 = ...
            props(obj).Area * ...
            pixel_area_um2;


        detections(obj).Circularity = ...
            circularity;


        detections(obj).Solidity = ...
            props(obj).Solidity;


        detections(obj).CoreRadius_um = ...
            core_radius_px * ...
            mean_pixel_size_um;


        detections(obj).Elongation = ...
            elongation;


        detections(obj).LocalContrastScore = ...
            NaN;

    end

end



%==========================================================================%
% DELETE EXISTING ZSERIES OUTPUTS BEFORE A CONFIRMED REPROCESS
%
% Supprime uniquement les sorties appartenant à la ZSeries courante :
%   - results_zseries.mat
%   - masque 2D local
%   - TIFF 3D isotrope local
