% ========================================================================
% NORMALIZE IMAGE
% ========================================================================

function norm_img = normalize_image(img)

    if isfloat(img)

        norm_img = ...
            mat2gray(img);

    elseif isinteger(img)

        denom = ...
            double( ...
                max(img(:)));

        if denom == 0

            norm_img = ...
                uint8(img);

        else

            norm_img = ...
                uint8( ...
                    double(img) ./ denom .* 255);
        end

    else

        norm_img = ...
            mat2gray( ...
                double(img));
    end
end


% ========================================================================
% ENHANCE DISPLAY
% ========================================================================

function out = enhance_for_overlay(img)

    img = double(img);

    if isempty(img) || ...
            all(~isfinite(img(:)))

        out = zeros(size(img));
        return;
    end

    vals = ...
        img(isfinite(img));

    p_low = ...
        prctile(vals, 2);

    p_high = ...
        prctile(vals, 98);

    if p_high <= p_low

        out = ...
            mat2gray(img);

        return;
    end

    out = ...
        (img - p_low) ./ ...
        (p_high - p_low);

    out = ...
        max( ...
            min(out, 1), ...
            0);

    out = ...
        out .^ 0.7;
end


