% ========================================================================
% LOAD MEAN IMAGE
% ========================================================================

function meanImg = load_meanImg_from_path(path_in)

    meanImg = [];

    if isempty(path_in)
        return;
    end

    if isfolder(path_in)

        ops_npy = ...
            fullfile( ...
                path_in, ...
                'ops.npy');

        if isfile(ops_npy)

            try

                mod = ...
                    py.importlib.import_module( ...
                        'python_function');

                ops = ...
                    mod.read_npy_file( ...
                        ops_npy);

                meanImg = ...
                    double( ...
                        ops{'meanImg'});

                return;

            catch

                warning( ...
                    'Error reading ops.npy in %s', ...
                    path_in);
            end
        end

        ops_mat = ...
            fullfile( ...
                path_in, ...
                'ops.mat');

        if isfile(ops_mat)

            S = load(ops_mat);

            if isfield(S, 'ops') && ...
                    isfield(S.ops, 'meanImg')

                meanImg = ...
                    S.ops.meanImg;

                return;
            end
        end
    end
end


