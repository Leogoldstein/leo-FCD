    end
end


% ========================================================================
% ALIGN ELECTROPORATED
% ========================================================================

function [aligned_image, T, source_used] = ...
        align_electroporated_locally_and_confirm( ...
            meanImg_channels, ...
            aligned_image_path)

    % meanImg_channels:
    %   {1} GCaMP
    %   {2} Electroporated
    %   {3} Green

    ref_img = [];

    if numel(meanImg_channels) >= 1

        ref_img = ...
            meanImg_channels{1};
    end

    electroporated_img = [];

    if numel(meanImg_channels) >= 2

        electroporated_img = ...
            meanImg_channels{2};
    end

    green_img = [];

    if numel(meanImg_channels) >= 3

        green_img = ...
            meanImg_channels{3};
    end

    aligned_image = [];
    T = [];
    source_used = '';

    % ==============================================================
    % Vérifications
    % ==============================================================

    if isempty(ref_img)

        warning( ...
            ['align_electroporated_locally_and_confirm: ' ...
             'GCaMP absent.']);

        return;
    end

    if isempty(electroporated_img)

        warning( ...
            ['align_electroporated_locally_and_confirm: ' ...
             'Electroporated image absent.']);

        return;
    end

    ref_img = ...
        double(ref_img);

    % ==============================================================
    % Image utilisée pour ESTIMER la translation
    %
    % Green prioritaire lorsqu'il existe.
    % Sinon Electroporated.
    % ==============================================================

    if ~isempty(green_img)

        moving_for_estimation = ...
            double(green_img);

        source_used = ...
            'Green';

    else

        moving_for_estimation = ...
            double(electroporated_img);

        source_used = ...
            'Electroporated';
    end

    % ==============================================================
    % Image réellement transformée
    % ==============================================================

    moving_img = ...
        double(electroporated_img);

    % ==============================================================
    % ==============================================================
    % Registration
    %
    % Extraire les structures sombres locales
    % (ex. vaisseaux) avant imregcorr
    % ==============================================================
    
    % ==============================================================
    % Choix automatique du mode de recalage
    %
    % Peu de petits objets brillants :
    %   -> privilégier les structures sombres (vaisseaux/minima locaux)
    %
    % Beaucoup de petits objets brillants :
    %   -> utiliser directement les structures claires, car les zones
    %      sombres intercellulaires deviennent moins spécifiques.
    % ==============================================================

    [ ...
        use_dark_registration, ...
        n_small_bright_objects, ...
        bright_fraction ...
    ] = ...
        should_use_dark_registration( ...
            ref_img);

    if use_dark_registration

        [moving_reg, moving_components] = ...
            extract_dark_structures_for_registration( ...
                moving_for_estimation);

        [ref_reg, ref_components] = ...
            extract_dark_structures_for_registration( ...
                ref_img);

        registration_mode = ...
            'DARK STRUCTURES';

    else

        [moving_reg, moving_components] = ...
            extract_bright_structures_for_registration( ...
                moving_for_estimation);

        [ref_reg, ref_components] = ...
            extract_bright_structures_for_registration( ...
                ref_img);

        registration_mode = ...
            'BRIGHT STRUCTURES';
    end

    fprintf( ...
        'Registration mode: %s\n', ...
        registration_mode);

    fprintf( ...
        'Small bright objects in GCaMP reference: %d\n', ...
        n_small_bright_objects);

    fprintf( ...
        'Bright pixel fraction: %.4f\n', ...
        bright_fraction);
    
    if ~isequal(size(moving_reg), size(ref_reg))
    
        moving_reg = ...
            imresize( ...
                moving_reg, ...
                size(ref_reg));
    
        moving_components = ...
            resize_registration_components( ...
                moving_components, ...
                size(ref_reg));
    end
    
    % ==============================================================
    % Afficher les transformations utilisées pour le recalage
    % ==============================================================
    
    % show_registration_components( ...
    %     moving_components, ...
    %     ref_components, ...
    %     moving_reg, ...
    %     ref_reg, ...
    %     source_used);
    
    % ==============================================================
    % Registration rigide : rotation + translation
    %
    % Translation limitée à un rayon de 20 pixels.
    % Rotation testée de -5 à +5 degrés par pas de 0.25 degré.
    % Les angles sont évalués en parallèle avec PARFOR.
    % ==============================================================

    max_radius = 20;
    max_angle = 5;
    angle_step = 0.25;

    try

        [ ...
            T, ...
            best_angle, ...
            best_dx, ...
            best_dy, ...
            best_score ...
        ] = ...
            find_best_rigid_transform_within_limits( ...
                moving_reg, ...
                ref_reg, ...
                max_radius, ...
                max_angle, ...
                angle_step);

        fprintf( ...
            '%s -> GCaMP | dark-weighted rigid registration\n', ...
            source_used);

        fprintf( ...
            'Translation search radius = %d px\n', ...
            max_radius);

        fprintf( ...
            'Rotation search = +/- %.2f deg | step = %.2f deg\n', ...
            max_angle, ...
            angle_step);

        fprintf( ...
            'angle = %.3f deg\n', ...
            best_angle);

        fprintf( ...
            'dx = %.3f px\n', ...
            best_dx);

        fprintf( ...
            'dy = %.3f px\n', ...
            best_dy);

        fprintf( ...
            'distance = %.3f px\n', ...
            hypot( ...
                best_dx, ...
                best_dy));

        fprintf( ...
            'score = %.6f\n', ...
            best_score);

    catch ME

        warning( ...
            'Registration failed: %s', ...
            ME.message);

        T = ...
            eye(3);
    end
    % ==============================================================
    % 2e étape : correction NON RIGIDE résiduelle
    %
    % Principe :
    %   1) appliquer d'abord le recalage rigide trouvé ci-dessus ;
    %   2) mesurer des translations locales sur une grille grossière ;
    %   3) interpoler ces translations pour obtenir un champ lisse ;
    %   4) limiter strictement l'amplitude du déplacement local ;
    %   5) appliquer exactement le même champ à Electroporated.
    %
    % Cela permet de corriger une région encore décalée sans imposer
    % cette correction à toute l'image.
    % ==============================================================

    nonrigid_grid_spacing = 64;       % espacement entre points de contrôle
    nonrigid_patch_radius = 40;       % demi-taille des fenêtres locales
    nonrigid_max_shift = 8;           % déplacement local maximal, en pixels
    nonrigid_smoothing_sigma = 24;    % lissage spatial du champ final
    nonrigid_min_texture = 0.015;     % rejette les fenêtres presque uniformes

    % --------------------------------------------------------------
    % Appliquer d'abord le recalage rigide aux images utilisées
    % pour ESTIMER le champ non rigide.
    % --------------------------------------------------------------

    moving_reg_rigid = ...
        apply_affine_transform_raw( ...
            moving_reg, ...
            T, ...
            ref_reg);

    % --------------------------------------------------------------
    % Même recalage rigide sur l'image Electroporated réelle.
    % --------------------------------------------------------------

    moving_img_rigid = ...
        apply_affine_transform_raw( ...
            moving_img, ...
            T, ...
            ref_img);

    if isempty(moving_reg_rigid) || ...
            isempty(moving_img_rigid)

        warning( ...
            ['align_electroporated_locally_and_confirm: ' ...
             'rigid transformation returned an empty image.']);

        return;
    end

    try

        [ ...
            displacement_field, ...
            control_points ...
        ] = ...
            estimate_smooth_local_displacement_field( ...
                moving_reg_rigid, ...
                ref_reg, ...
                nonrigid_grid_spacing, ...
                nonrigid_patch_radius, ...
                nonrigid_max_shift, ...
                nonrigid_smoothing_sigma, ...
                nonrigid_min_texture);

        fprintf('\n');
        fprintf('NON-RIGID residual registration\n');
        fprintf('Grid spacing          = %d px\n', nonrigid_grid_spacing);
        fprintf('Patch radius          = %d px\n', nonrigid_patch_radius);
        fprintf('Max local displacement= %.2f px\n', nonrigid_max_shift);
        fprintf('Field smoothing sigma = %.2f px\n', nonrigid_smoothing_sigma);
        fprintf('Valid control points  = %d / %d\n', ...
            nnz(control_points.valid), ...
            numel(control_points.valid));

        if any(control_points.valid(:))

            local_amplitudes = ...
                hypot( ...
                    control_points.dx(control_points.valid), ...
                    control_points.dy(control_points.valid));

            fprintf('Median local shift    = %.3f px\n', ...
                median(local_amplitudes, 'omitnan'));

            fprintf('Maximum local shift   = %.3f px\n', ...
                max(local_amplitudes, [], 'omitnan'));
        end

        % ----------------------------------------------------------
        % Appliquer le champ non rigide à Electroporated.
        % ----------------------------------------------------------

        aligned_raw = ...
            apply_displacement_field( ...
                moving_img_rigid, ...
                displacement_field);

        aligned_image = ...
            normalize_image( ...
                aligned_raw);

    catch ME

        warning( ...
            ['Non-rigid registration failed: %s\n' ...
             'Rigid result will be kept instead.'], ...
            ME.message);

        displacement_field = [];
        control_points = [];

        aligned_image = ...
            normalize_image( ...
                moving_img_rigid);
    end

    if isempty(aligned_image)

        warning( ...
            ['align_electroporated_locally_and_confirm: ' ...
             'empty transformation.']);

        return;
    end

    % ==============================================================
    % Dimensions
    % ==============================================================

    if ~isequal( ...
            size(aligned_image,1), ...
            size(ref_img,1)) || ...
            ~isequal( ...
                size(aligned_image,2), ...
                size(ref_img,2))

        aligned_image = ...
            imresize( ...
                aligned_image, ...
                [ ...
                    size(ref_img,1), ...
                    size(ref_img,2) ...
                ]);
    end

    % ==============================================================
    % Métriques
    % ==============================================================

    before_cmp = ...
        mat2gray( ...
            moving_img);

    ref_cmp = ...
        mat2gray( ...
            ref_img);

    after_cmp = ...
        mat2gray( ...
            aligned_image);

    if ~isequal( ...
            size(before_cmp), ...
            size(ref_cmp))

        before_cmp = ...
            imresize( ...
                before_cmp, ...
                size(ref_cmp));
    end

    if ~isequal( ...
            size(after_cmp), ...
            size(ref_cmp))

        after_cmp = ...
            imresize( ...
                after_cmp, ...
                size(ref_cmp));
    end

    before_err = ...
        mean( ...
            abs( ...
                ref_cmp(:) - ...
                before_cmp(:)), ...
            'omitnan');

    after_err = ...
        mean( ...
            abs( ...
                ref_cmp(:) - ...
                after_cmp(:)), ...
            'omitnan');

    fprintf( ...
        'Error vs ref before = %.6f\n', ...
        before_err);

    fprintf( ...
        'Error vs ref after  = %.6f\n', ...
        after_err);

    fprintf( ...
        'Improvement         = %.6f\n', ...
        before_err - after_err);

    % ==============================================================
    % Validation manuelle
    % ==============================================================

    % ==============================================================
    % Validation manuelle
    %
    % IMPORTANT :
    % la correction manuelle est maintenant appliquée SUR le résultat
    % rigide + non rigide. Elle sert donc uniquement de petite correction
    % globale finale et ne détruit pas le champ non linéaire.
    % ==============================================================

    [ ...
        was_saved, ...
        aligned_image, ...
        T_manual_residual ...
    ] = ...
        preview_alignment_with_save_cancel( ...
            moving_img, ...
            aligned_image, ...
            ref_img, ...
            eye(3), ...
            aligned_image);

    if ~isempty(T_manual_residual)

        fprintf( ...
            'Manual transform stored as residual correction on non-rigid result.\n');
    end

    if ~was_saved

        fprintf( ...
            'Alignment cancelled by user.\n');

        aligned_image = [];
        T = [];
        source_used = '';

        return;
    end

    % ==============================================================
    % Sauvegarde
    % ==============================================================

    if ~isempty(aligned_image) && ...
            ~isempty(aligned_image_path)

        try

            imwrite( ...
                aligned_image, ...
                aligned_image_path, ...
                'tif');

            fprintf( ...
                'Aligned electroporated image saved:\n%s\n', ...
                aligned_image_path);

        catch ME

            warning( ...
                ['Unable to save aligned electroporated ' ...
                 'image "%s": %s'], ...
                aligned_image_path, ...
                ME.message);
        end
    end
end

% ========================================================================
% FIND BEST RIGID TRANSFORM WITHIN LIMITS
%
% Recherche exhaustive de la rotation et de la translation :
%   - angles évalués avec PARFOR
%   - translation recherchée dans un disque de rayon max_radius
%   - rotation appliquée autour du centre de l'image
% ========================================================================

function [ ...
        T_best, ...
        best_angle, ...
        best_dx, ...
        best_dy, ...
        best_score ...
    ] = ...
        find_best_rigid_transform_within_limits( ...
            moving_img, ...
            ref_img, ...
            max_radius, ...
            max_angle, ...
            angle_step)

    if isempty(moving_img) || ...
            isempty(ref_img)

        error( ...
            'Moving and reference images must not be empty.');
    end

    moving_img = ...
        double(moving_img);

    ref_img = ...
        double(ref_img);

    if ~isequal( ...
            size(moving_img), ...
            size(ref_img))

        moving_img = ...
            imresize( ...
                moving_img, ...
                size(ref_img));
    end

    ref_size = ...
        size(ref_img);

    ref_size = ...
        ref_size(1:2);

    angles = ...
        -max_angle:angle_step:max_angle;

    if ~any(abs(angles) < eps)

        angles = ...
            sort( ...
                [angles 0]);
    end

    n_angles = ...
        numel(angles);

    scores = ...
        -Inf(n_angles, 1);

    dx_values = ...
        zeros(n_angles, 1);

    dy_values = ...
        zeros(n_angles, 1);

    % ==============================================================
    % Chaque angle est indépendant : parallélisation sûre.
    % ==============================================================

    parfor i = 1:n_angles

        angle_deg = ...
            angles(i);

        T_rotation = ...
            build_centered_rigid_transform( ...
                ref_size, ...
                angle_deg, ...
                0, ...
                0);

        rotated_img = ...
            imwarp( ...
                moving_img, ...
                affine2d(T_rotation), ...
                'OutputView', ...
                imref2d(ref_size), ...
                'Interp', ...
                'linear');

        [ ...
            T_translation, ...
            score ...
        ] = ...
            find_best_translation_within_radius( ...
                rotated_img, ...
                ref_img, ...
                max_radius);

        scores(i) = ...
            score;

        dx_values(i) = ...
            T_translation(3,1);

        dy_values(i) = ...
            T_translation(3,2);
    end

    [ ...
        best_score, ...
        best_idx ...
    ] = ...
        max(scores);

    if ~isfinite(best_score)

        error( ...
            'No valid rigid transformation found.');
    end

    best_angle = ...
        angles(best_idx);

    best_dx = ...
        dx_values(best_idx);

    best_dy = ...
        dy_values(best_idx);

    T_best = ...
        build_centered_rigid_transform( ...
            ref_size, ...
            best_angle, ...
            best_dx, ...
            best_dy);
end


% ========================================================================
% BUILD CENTERED RIGID TRANSFORM
%
% Rotation autour du centre de l'image, suivie d'une translation.
% Convention matricielle utilisée par affine2d.
% ========================================================================

function T = ...
        build_centered_rigid_transform( ...
            image_size, ...
            angle_deg, ...
            dx, ...
            dy)

    n_rows = ...
        image_size(1);

    n_cols = ...
        image_size(2);

    cx = ...
        (n_cols + 1) / 2;

    cy = ...
        (n_rows + 1) / 2;

    T_to_origin = ...
        [ ...
            1    0    0
            0    1    0
           -cx  -cy   1
        ];

    c = ...
        cosd(angle_deg);

    s = ...
        sind(angle_deg);

    T_rotation = ...
        [ ...
             c    s    0
            -s    c    0
             0    0    1
        ];

    T_from_origin = ...
        [ ...
            1   0   0
            0   1   0
            cx  cy  1
        ];

    T_translation = ...
        [ ...
            1   0   0
            0   1   0
            dx  dy  1
        ];

    T = ...
        T_to_origin * ...
        T_rotation * ...
        T_from_origin * ...
        T_translation;
end


% ========================================================================
% DECOMPOSE CENTERED RIGID TRANSFORM
% ========================================================================

function [angle_deg, dx, dy] = ...
        decompose_centered_rigid_transform( ...
            T, ...
            image_size)

    image_size = ...
        image_size(1:2);

    angle_deg = ...
        atan2d( ...
            T(1,2), ...
            T(1,1));

    T_rotation_only = ...
        build_centered_rigid_transform( ...
            image_size, ...
            angle_deg, ...
            0, ...
            0);

    dx = ...
        T(3,1) - ...
        T_rotation_only(3,1);

    dy = ...
        T(3,2) - ...
        T_rotation_only(3,2);
end


% ========================================================================
% FIND BEST TRANSLATION WITHIN RADIUS
%
% Recherche exhaustive de la meilleure translation entière dans un
% cercle de rayon max_radius autour de (0,0).
%
% Le score est une corrélation normalisée calculée uniquement sur la
% région réellement commune aux deux images. Les pixels ajoutés par
% translation ne participent donc pas au score.
% ========================================================================

function [T, best_score] = ...
        find_best_translation_within_radius( ...
            moving_img, ...
            ref_img, ...
            max_radius)

    % ==============================================================
    % Vérifications
    % ==============================================================

    if isempty(moving_img) || ...
            isempty(ref_img)

        error( ...
            'Moving and reference images must not be empty.');
    end

    moving_img = ...
        double(moving_img);

    ref_img = ...
        double(ref_img);

    if ~isequal( ...
            size(moving_img), ...
            size(ref_img))

        moving_img = ...
            imresize( ...
                moving_img, ...
                size(ref_img));
    end

    % ==============================================================
    % Initialisation
    % ==============================================================

    best_score = ...
        -Inf;

    best_dx = 0;
    best_dy = 0;

    n_rows = ...
        size(ref_img, 1);

    n_cols = ...
        size(ref_img, 2);

    % ==============================================================
    % Tester toutes les translations autorisées
    %
    % dx² + dy² <= rayon²
    % ==============================================================

    for dy = -max_radius:max_radius

        for dx = -max_radius:max_radius

            % ------------------------------------------------------
            % Limite CIRCULAIRE
            % ------------------------------------------------------

            if dx^2 + dy^2 > max_radius^2
                continue;
            end

            % ------------------------------------------------------
            % Coordonnées X de la zone commune
            % ------------------------------------------------------

            if dx >= 0

                ref_cols = ...
                    (1 + dx):n_cols;

                moving_cols = ...
                    1:(n_cols - dx);

            else

                ref_cols = ...
                    1:(n_cols + dx);

                moving_cols = ...
                    (1 - dx):n_cols;
            end

            % ------------------------------------------------------
            % Coordonnées Y de la zone commune
            % ------------------------------------------------------

            if dy >= 0

                ref_rows = ...
                    (1 + dy):n_rows;

                moving_rows = ...
                    1:(n_rows - dy);

            else

                ref_rows = ...
                    1:(n_rows + dy);

                moving_rows = ...
                    (1 - dy):n_rows;
            end

            % ------------------------------------------------------
            % Extraire uniquement la zone commune
            % ------------------------------------------------------

            ref_crop = ...
                ref_img( ...
                    ref_rows, ...
                    ref_cols);

            moving_crop = ...
                moving_img( ...
                    moving_rows, ...
                    moving_cols);

            % ------------------------------------------------------
            % Pixels valides
            % ------------------------------------------------------

            valid = ...
                isfinite(ref_crop) & ...
                isfinite(moving_crop);

            if nnz(valid) < 100
                continue;
            end

            a = ...
                ref_crop(valid);

            b = ...
                moving_crop(valid);

            % ------------------------------------------------------
            % Retirer la moyenne
            %
            % Cela évite que le niveau moyen de fluorescence
            % détermine le recalage.
            % ------------------------------------------------------

            a = ...
                a - mean(a);

            b = ...
                b - mean(b);

            % ------------------------------------------------------
            % Corrélation normalisée
            % ------------------------------------------------------

            denominator = ...
                sqrt( ...
                    sum(a.^2) * ...
                    sum(b.^2));

            if denominator <= eps
                continue;
            end

            score = ...
                sum(a .* b) ./ ...
                denominator;

            % ------------------------------------------------------
            % Meilleur déplacement
            % ------------------------------------------------------

            if score > best_score

                best_score = ...
                    score;

                best_dx = ...
                    dx;

                best_dy = ...
                    dy;
            end
        end
    end

    % ==============================================================
    % Transformation
    % ==============================================================

    if ~isfinite(best_score)

        error( ...
            'No valid translation found within %d pixels.', ...
            max_radius);
    end

    T = ...
        eye(3);

    T(3,1) = ...
        best_dx;

    T(3,2) = ...
        best_dy;

end

% ========================================================================
% EXTRACT DARK STRUCTURES FOR REGISTRATION
%
% Prépare une image spécifiquement pour le recalage.
%
% Priorités :
%   - 65 % : minima sombres locaux / structures fines
%   - 25 % : structures sombres plus larges
%   - 10 % : organisation sombre globale
%
% Aucun seuillage dur afin de conserver les petits minima locaux.
% ========================================================================

% ========================================================================
% EXTRACT DARK STRUCTURES FOR REGISTRATION
% ========================================================================

function [out, components] = ...
        extract_dark_structures_for_registration(img)

    out = [];

    components = struct( ...
        'normalized', [], ...
        'fine_dark', [], ...
        'medium_dark', [], ...
        'coarse_dark', [], ...
        'global_dark', []);

    if isempty(img)
        return;
    end

    img = double(img);
    img(~isfinite(img)) = 0;

    % ==============================================================
    % 1) Normalisation robuste
    % ==============================================================

    vals = ...
        img(isfinite(img));

    if isempty(vals)

        out = ...
            zeros(size(img));

        return;
    end

    low_val = ...
        prctile(vals, 1);

    high_val = ...
        prctile(vals, 99);

    if high_val <= low_val

        img_norm = ...
            mat2gray(img);

    else

        img_norm = ...
            (img - low_val) ./ ...
            (high_val - low_val);

        img_norm = ...
            max( ...
                min(img_norm, 1), ...
                0);
    end

    components.normalized = ...
        img_norm;

    % ==============================================================
    % 2) Minima locaux fins
    % ==============================================================

    fine_img = ...
        imgaussfilt( ...
            img_norm, ...
            0.4);

    fine_background = ...
        imgaussfilt( ...
            img_norm, ...
            2.5);

    fine_dark = ...
        fine_background - ...
        fine_img;

    fine_dark = ...
        max( ...
            fine_dark, ...
            0);

    if any(fine_dark(:) > 0)

        fine_dark = ...
            mat2gray( ...
                fine_dark);

    else

        fine_dark = ...
            zeros(size(img_norm));
    end

    components.fine_dark = ...
        fine_dark;

    % ==============================================================
    % 3) Minima locaux intermédiaires
    % ==============================================================

    medium_img = ...
        imgaussfilt( ...
            img_norm, ...
            1);

    medium_background = ...
        imgaussfilt( ...
            img_norm, ...
            7);

    medium_dark = ...
        medium_background - ...
        medium_img;

    medium_dark = ...
        max( ...
            medium_dark, ...
            0);

    if any(medium_dark(:) > 0)

        medium_dark = ...
            mat2gray( ...
                medium_dark);

    else

        medium_dark = ...
            zeros(size(img_norm));
    end

    components.medium_dark = ...
        medium_dark;

    % ==============================================================
    % 4) Structures sombres larges
    % ==============================================================

    coarse_img = ...
        imgaussfilt( ...
            img_norm, ...
            2);

    coarse_background = ...
        imgaussfilt( ...
            img_norm, ...
            18);

    coarse_dark = ...
        coarse_background - ...
        coarse_img;

    coarse_dark = ...
        max( ...
            coarse_dark, ...
            0);

    if any(coarse_dark(:) > 0)

        coarse_dark = ...
            mat2gray( ...
                coarse_dark);

    else

        coarse_dark = ...
            zeros(size(img_norm));
    end

    components.coarse_dark = ...
        coarse_dark;

    % ==============================================================
    % 5) Organisation sombre globale
    % ==============================================================

    global_component = ...
        imgaussfilt( ...
            img_norm, ...
            2);

    global_dark = ...
        1 - global_component;

    global_dark = ...
        mat2gray( ...
            global_dark);

    components.global_dark = ...
        global_dark;

    % ==============================================================
    % 6) Combinaison
    %
    % Forte priorité aux minima locaux.
    % ==============================================================

    out = ...
        0.55 .* fine_dark + ...
        0.15 .* medium_dark + ...
        0.20 .* coarse_dark + ...
        0.10 .* global_dark;

    out = ...
        mat2gray(out);

    out = ...
        out .^ 1.1;

    out = ...
        imgaussfilt( ...
            out, ...
            0.25);

    out = ...
        mat2gray(out);
end


% ========================================================================
% SHOULD USE DARK REGISTRATION
%
% Détermine automatiquement si le recalage doit privilégier les minima
% sombres ou les structures claires.
%
% Logique :
%   - peu de petits objets brillants -> DARK
%   - beaucoup de petits objets brillants -> BRIGHT
%
% Le critère principal est le nombre de petites composantes brillantes.
% La fraction totale de pixels brillants sert de sécurité supplémentaire.
% ========================================================================

function [use_dark, n_small_bright_objects, bright_fraction] = ...
        should_use_dark_registration(img)

    use_dark = true;
    n_small_bright_objects = 0;
    bright_fraction = 0;

    if isempty(img)
        return;
    end

    img = ...
        double(img);

    img(~isfinite(img)) = 0;

    vals = ...
        img(isfinite(img));

    if isempty(vals)
        return;
    end

    low_val = ...
        prctile(vals, 1);

    high_val = ...
        prctile(vals, 99.5);

    if high_val <= low_val

        img_norm = ...
            mat2gray(img);

    else

        img_norm = ...
            (img - low_val) ./ ...
            (high_val - low_val);

        img_norm = ...
            max( ...
                min(img_norm, 1), ...
                0);
    end

    % ==============================================================
    % Léger lissage pour réduire le bruit pixel-à-pixel
    % ==============================================================

    img_smooth = ...
        imgaussfilt( ...
            img_norm, ...
            0.8);

    % ==============================================================
    % Pixels les plus brillants
    %
    % Le seuil au 90e percentile permet de rester adaptatif entre
    % acquisitions de niveaux de fluorescence différents.
    % ==============================================================

    bright_threshold = ...
        prctile( ...
            img_smooth(:), ...
            90);

    BW = ...
        img_smooth > bright_threshold;

    bright_fraction = ...
        nnz(BW) ./ numel(BW);

    % ==============================================================
    % Nettoyage léger
    % ==============================================================

    BW = ...
        bwareaopen( ...
            BW, ...
            5);

    % Séparer les amas faiblement connectés sans dilater fortement.
    BW = ...
        imopen( ...
            BW, ...
            strel('disk', 1, 0));

    CC = ...
        bwconncomp( ...
            BW, ...
            8);

    if CC.NumObjects > 0

        areas = ...
            cellfun( ...
                @numel, ...
                CC.PixelIdxList);

        % ----------------------------------------------------------
        % Objets de taille compatible avec de petits profils
        % cellulaires / puncta. Les très gros amas ne doivent pas
        % artificiellement faire croire à une forte densité cellulaire.
        % ----------------------------------------------------------

        min_area = 5;
        max_area = 300;

        n_small_bright_objects = ...
            sum( ...
                areas >= min_area & ...
                areas <= max_area);
    end

    % ==============================================================
    % Décision
    %
    % Valeurs volontairement conservatrices :
    %   < 80 petits objets -> sombre
    %   >= 80             -> clair
    %
    % Si une très grande fraction de l'image appartient déjà aux
    % pixels brillants, on force aussi le mode clair.
    % ==============================================================

    small_object_threshold = 80;
    bright_fraction_threshold = 0.14;

    use_dark = ...
        n_small_bright_objects < small_object_threshold && ...
        bright_fraction < bright_fraction_threshold;
end


% ========================================================================
% EXTRACT BRIGHT STRUCTURES FOR REGISTRATION
%
% Prépare une image de recalage privilégiant les cellules / structures
% claires. Utilisé lorsque la référence contient beaucoup de petits
% objets brillants et que les minima sombres deviennent moins fiables.
% ========================================================================

function [out, components] = ...
        extract_bright_structures_for_registration(img)

    out = [];

    components = struct( ...
        'normalized', [], ...
        'fine_dark', [], ...
        'medium_dark', [], ...
        'coarse_dark', [], ...
        'global_dark', []);

    if isempty(img)
        return;
    end

    img = ...
        double(img);

    img(~isfinite(img)) = 0;

    vals = ...
        img(isfinite(img));

    if isempty(vals)

        out = ...
            zeros(size(img));

        return;
    end

    low_val = ...
        prctile(vals, 1);

    high_val = ...
        prctile(vals, 99);

    if high_val <= low_val

        img_norm = ...
            mat2gray(img);

    else

        img_norm = ...
            (img - low_val) ./ ...
            (high_val - low_val);

        img_norm = ...
            max( ...
                min(img_norm, 1), ...
                0);
    end

    components.normalized = ...
        img_norm;

    % ==============================================================
    % Structures brillantes fines
    % ==============================================================

    fine_img = ...
        imgaussfilt( ...
            img_norm, ...
            0.5);

    fine_background = ...
        imgaussfilt( ...
            img_norm, ...
            2.5);

    fine_bright = ...
        fine_img - fine_background;

    fine_bright = ...
        max(fine_bright, 0);

    if any(fine_bright(:) > 0)

        fine_bright = ...
            mat2gray(fine_bright);

    else

        fine_bright = ...
            zeros(size(img_norm));
    end

    % ==============================================================
    % Structures intermédiaires
    % ==============================================================

    medium_img = ...
        imgaussfilt( ...
            img_norm, ...
            1);

    medium_background = ...
        imgaussfilt( ...
            img_norm, ...
            6);

    medium_bright = ...
        medium_img - medium_background;

    medium_bright = ...
        max(medium_bright, 0);

    if any(medium_bright(:) > 0)

        medium_bright = ...
            mat2gray(medium_bright);

    else

        medium_bright = ...
            zeros(size(img_norm));
    end

    % ==============================================================
    % Organisation claire plus large
    % ==============================================================

    coarse = ...
        imgaussfilt( ...
            img_norm, ...
            1.5);

    coarse_background = ...
        imgaussfilt( ...
            img_norm, ...
            12);

    coarse_bright = ...
        coarse - coarse_background;

    coarse_bright = ...
        max(coarse_bright, 0);

    if any(coarse_bright(:) > 0)

        coarse_bright = ...
            mat2gray(coarse_bright);

    else

        coarse_bright = ...
            zeros(size(img_norm));
    end

    % ==============================================================
    % Composante globale claire
    % ==============================================================

    global_bright = ...
        imgaussfilt( ...
            img_norm, ...
            1.2);

    global_bright = ...
        mat2gray(global_bright);

    % Réutilisation des noms de champs pour compatibilité avec la
    % fonction d'affichage existante.
    components.fine_dark = fine_bright;
    components.medium_dark = medium_bright;
    components.coarse_dark = coarse_bright;
    components.global_dark = global_bright;

    % ==============================================================
    % Combinaison
    %
    % Priorité aux profils cellulaires / puncta brillants.
    % ==============================================================

    out = ...
        0.45 .* fine_bright + ...
        0.30 .* medium_bright + ...
        0.15 .* coarse_bright + ...
        0.10 .* global_bright;

    out = ...
        mat2gray(out);

    out = ...
        out .^ 0.9;

    out = ...
        imgaussfilt( ...
            out, ...
            0.25);

    out = ...
        mat2gray(out);
end


