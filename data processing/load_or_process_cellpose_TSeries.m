% ========================================================================
% PREVIEW ALIGNMENT
% ========================================================================

function [was_saved, aligned_img, T] = ...
        preview_alignment_with_save_cancel( ...
            original_img, ...
            aligned_img, ...
            ref_img, ...
            T)

    was_saved = false;

    if isempty(original_img) || ...
            isempty(aligned_img) || ...
            isempty(ref_img) || ...
            isempty(T)

        return;
    end

    original_img = double(original_img);
    aligned_img  = double(aligned_img);
    ref_img      = double(ref_img);

    dx = T(3,1);
    dy = T(3,2);

    original_disp = ...
        enhance_for_overlay( ...
            original_img);

    aligned_disp = ...
        enhance_for_overlay( ...
            aligned_img);

    ref_disp = ...
        enhance_for_overlay( ...
            ref_img);

    hFig = figure( ...
        'Name', ...
        'Preview electroporated alignment', ...
        'NumberTitle', ...
        'off', ...
        'MenuBar', ...
        'none', ...
        'ToolBar', ...
        'none', ...
        'Color', ...
        'w', ...
        'Position', ...
        [80 80 1500 720], ...
        'CloseRequestFcn', ...
        @onCancel);

    S = struct();

    S.saved = false;
    S.state = 1;

    S.original_img = original_img;
    S.aligned_img = aligned_img;
