function [meanImg_channels, aligned_image, npy_file_path, meanImg] = ...
    load_or_process_cellpose_TSeries( ...
        filePath, ...
        date_group_path, ...
        gcamp_plane_path, ...
        electroporated_plane_path, ...
        green_plane_path, ...
        current_electroporated_TSeries_path, ...
        gcamp_output_folder_plane)

    % ==============================================================
    % Workflow
    %
    %   1) Charger GCaMP.
    %
    %   2) Charger Electroporated avec l'ordre de priorité suivant :
    %
    %        1. Suite2p Electroporated
    %        2. TSeries Electroporated / plane*
    %        3. Single images / ChX
    %
    %      Pour Single images, le numéro du canal Electroporated
    %      est demandé à l'utilisateur.
    %
    %   3) Charger Green si disponible.
    %
    %   4) Estimer la translation :
    %        Green -> GCaMP si Green existe,
    %        sinon Electroporated -> GCaMP.
    %
    %   5) Appliquer cette translation à Electroporated.
    %
    %   6) Segmenter l'image Electroporated alignée avec Cellpose.
    %
    %   7) Reporter ces masques sur une référence GCaMP,
    %      puis permettre leur correction manuelle.
    %
    % meanImg_channels :
    %   {1} = GCaMP
    %   {2} = Electroporated
    %   {3} = Green
    % ==============================================================

    numChannelsLocal = 3;

    meanImg_channels = ...
        cell( ...
            numChannelsLocal, ...
            1);

    aligned_image = [];
    aligned_image_path = '';
    npy_file_path = [];
    meanImg = [];
    electroporated_seg_path = [];

    % ==============================================================
    % Paths du plan courant
    % ==============================================================

    current_gcamp_suite2p_plane_path = ...
        gcamp_plane_path;

    current_electroporated_suite2p_plane_path = ...
        electroporated_plane_path;

    current_green_suite2p_plane_path = ...
        green_plane_path;

    % ==============================================================
    % Numéro du plan
    % ==============================================================

    plane_index_zero_based = ...
        infer_plane_index_from_paths( ...
            gcamp_plane_path, ...
            electroporated_plane_path, ...
            gcamp_output_folder_plane);

    p = ...
        plane_index_zero_based + 1;

    % ==============================================================
    % Output folder
    % ==============================================================

    if isempty(gcamp_output_folder_plane)

        if ~isempty(gcamp_plane_path)

            gcamp_output_folder_plane = ...
                gcamp_plane_path;

        else

            gcamp_output_folder_plane = ...
                date_group_path;
        end
    end

    if ~isempty(gcamp_output_folder_plane) && ...
            ~isfolder(gcamp_output_folder_plane)

        mkdir( ...
            gcamp_output_folder_plane);
    end

    % ==============================================================
    % Normaliser current_electroporated_TSeries_path
    % ==============================================================

    if iscell(current_electroporated_TSeries_path)

        if isempty(current_electroporated_TSeries_path)

            current_electroporated_TSeries_path = "";

        else

            current_electroporated_TSeries_path = ...
                current_electroporated_TSeries_path{1};
        end
    end

    if isempty(current_electroporated_TSeries_path)

        current_electroporated_TSeries_path = "";
    end

    % ==============================================================
    % Vérifier date_group_path
    % ==============================================================

    if isempty(date_group_path) || ...
            ~( ...
                ischar(date_group_path) || ...
                isstring(date_group_path))

        warning( ...
            'load_or_process_cellpose_TSeries:InvalidDateGroupPath', ...
            'Invalid date_group_path for plane %d.', ...
            p);

        [ ...
            meanImg_channels, ...
            meanImg ...
        ] = ...
            complete_meanImg_channels( ...
                meanImg_channels, ...
                filePath, ...
                current_gcamp_suite2p_plane_path, ...
                meanImg);

        return;
    end

    % ==============================================================
    % 1) Charger meanImg GCaMP
    % ==============================================================

    if ~isempty(current_gcamp_suite2p_plane_path)

        tmp = ...
            load_meanImg_from_path( ...
                current_gcamp_suite2p_plane_path);

        if ~isempty(tmp)

            meanImg_channels{1} = ...
                tmp;

            meanImg = ...
                tmp;
        end
    end

    % ==============================================================
    % 2) Charger meanImg Electroporated depuis Suite2p si disponible
    % ==============================================================

    if ~isempty(current_electroporated_suite2p_plane_path)

        tmp = ...
            load_meanImg_from_path( ...
                current_electroporated_suite2p_plane_path);

        if ~isempty(tmp)

            meanImg_channels{2} = ...
                tmp;
        end
    end

    % ==============================================================
    % 3) Charger meanImg Green
    % ==============================================================

    if ~isempty(current_green_suite2p_plane_path)

        tmp = ...
            load_meanImg_from_path( ...
                current_green_suite2p_plane_path);

        if ~isempty(tmp)

            meanImg_channels{3} = ...
                tmp;
        end
    end

    if isempty(meanImg) && ...
            ~isempty(meanImg_channels{1})

        meanImg = ...
            meanImg_channels{1};
    end

    % ==============================================================
    % Déterminer si TSeries Electroporated est disponible
    % ==============================================================

    has_electroporated_TSeries = ...
        ~isempty(current_electroporated_TSeries_path) && ...
        ( ...
            ischar(current_electroporated_TSeries_path) || ...
            isstring(current_electroporated_TSeries_path)) && ...
        isfolder( ...
            char(current_electroporated_TSeries_path));

    % ==============================================================
    % Single images
    % ==============================================================

    single_images_path = ...
        fullfile( ...
            date_group_path, ...
            'Single images');

    has_single_images = ...
        isfolder(single_images_path);

    % ==============================================================
    %
    % PRIORITÉ 1
    %
    % SUITE2P ELECTROPORATED
    %
    % ==============================================================

    if ~isempty(current_electroporated_suite2p_plane_path)

        fprintf('\n');
        fprintf('============================================\n');
        fprintf('ELECTROPORATED SOURCE: SUITE2P\n');
        fprintf('Plane: %d\n', p);
        fprintf('============================================\n');

        try

            % ======================================================
            % Charger Electroporated depuis Suite2p
            % ======================================================

            if isempty(meanImg_channels{2})

                tmp = ...
                    load_meanImg_from_path( ...
                        current_electroporated_suite2p_plane_path);

                if ~isempty(tmp)

                    meanImg_channels{2} = ...
                        tmp;
                end
            end

            % ======================================================
            % Chercher segmentation existante
            % ======================================================

            cellpose_files = ...
                dir( ...
                    fullfile( ...
                        current_electroporated_suite2p_plane_path, ...
                        '*_seg.npy'));

            if ~isempty(cellpose_files)

                electroporated_seg_path = ...
                    select_or_default( ...
                        cellpose_files, ...
                        '', ...
                        '*.npy');

                electroporated_seg_path = ...
                    validate_existing_file( ...
                        electroporated_seg_path);

                if ~isempty(electroporated_seg_path)

                    [ ...
                        segDir, ...
                        segName, ...
                        ~ ...
                    ] = ...
                        fileparts( ...
                            electroporated_seg_path);

                    baseName = ...
                        regexprep( ...
                            segName, ...
                            '_seg$', ...
                            '');

                    aligned_image_path = ...
                        fullfile( ...
                            segDir, ...
                            [baseName '.tif']);
                end
            end

            % ======================================================
            % Chemin aligned standard
            % ======================================================

            if isempty(aligned_image_path)

                aligned_image_path = ...
                    fullfile( ...
                        current_electroporated_suite2p_plane_path, ...
                        sprintf( ...
                            'aligned_plane%d_AVG.tif', ...
                            p - 1));
            end

            % ======================================================
            % Charger aligned s'il existe
            % ======================================================

            if isfile(aligned_image_path)

                aligned_image = ...
                    safe_read_and_normalize( ...
                        aligned_image_path);

            % ======================================================
            % Sinon recalage
            % ======================================================

            else

                [ ...
                    aligned_image, ...
                    ~, ...
                    source_used ...
                ] = ...
                    align_electroporated_locally_and_confirm( ...
                        meanImg_channels, ...
                        aligned_image_path);

                fprintf( ...
                    'Transform estimated from: %s\n', ...
                    source_used);
            end

        catch ME

            warning( ...
                'load_or_process_cellpose_TSeries:Suite2pElectroporatedFailed', ...
                ['Plane %d: Suite2p Electroporated branch ' ...
                 'failed: %s'], ...
                p, ...
                ME.message);

            aligned_image = [];
            npy_file_path = [];
        end

    % ==============================================================
    %
    % PRIORITÉ 2
    %
    % TSERIES ELECTROPORATED / plane*
    %
    % ==============================================================

    elseif has_electroporated_TSeries

        fprintf('\n');
        fprintf('============================================\n');
        fprintf('ELECTROPORATED SOURCE: TSERIES\n');
        fprintf('Plane: %d\n', p);
        fprintf('============================================\n');

        % ==========================================================
        % Chercher dossier plane*
        % ==========================================================

        planeFolderName = ...
            sprintf( ...
                'plane%d', ...
                p - 1);

        current_electroporated_TSeries_plane_path = ...
            fullfile( ...
                current_electroporated_TSeries_path, ...
                planeFolderName);

        if ~isfolder(current_electroporated_TSeries_plane_path)

            current_electroporated_TSeries_plane_path = ...
                char( ...
                    current_electroporated_TSeries_path);
        end

        % ==========================================================
        % Chercher segmentation Electroporated existante
        % ==========================================================

        segPattern = ...
            sprintf( ...
                'aligned_%s_AVG*_seg.npy', ...
                planeFolderName);

        segFiles = ...
            dir( ...
                fullfile( ...
                    current_electroporated_TSeries_plane_path, ...
                    segPattern));

        % ==========================================================
        % Segmentation déjà présente
        % ==========================================================

        if ~isempty(segFiles)

            electroporated_seg_path = ...
                fullfile( ...
                    current_electroporated_TSeries_plane_path, ...
                    segFiles(1).name);

            electroporated_seg_path = ...
                validate_existing_file( ...
                    electroporated_seg_path);

            if ~isempty(electroporated_seg_path)

                [ ...
                    segDir, ...
                    segName, ...
                    ~ ...
                ] = ...
                    fileparts( ...
                        electroporated_seg_path);

                baseName = ...
                    regexprep( ...
                        segName, ...
                        '_seg$', ...
                        '');

                aligned_image_path = ...
                    fullfile( ...
                        segDir, ...
                        [baseName '.tif']);
            end

            % ======================================================
            % Charger image brute Electroporated
            % ======================================================

            avgPattern = ...
                sprintf( ...
                    'plane%d_AVG*.tif', ...
                    p - 1);

            avgFiles = ...
                dir( ...
                    fullfile( ...
                        current_electroporated_TSeries_plane_path, ...
                        avgPattern));

            if ~isempty(avgFiles)

                avg_path = ...
                    fullfile( ...
                        current_electroporated_TSeries_plane_path, ...
                        avgFiles(1).name);

                electroporated_img = ...
                    safe_read_and_normalize( ...
                        avg_path);

                if ~isempty(electroporated_img)

                    meanImg_channels{2} = ...
                        electroporated_img;
                end
            end

            aligned_image = ...
                safe_read_and_normalize( ...
                    aligned_image_path);

            % ======================================================
            % Seg existe mais TIFF aligned absent
            % ======================================================

            if isempty(aligned_image)

                fprintf( ...
                    ['Plane %d: existing Electroporated masks found, ' ...
                     'but aligned TIFF must be reconstructed.\n'], ...
                    p);

                [ ...
                    aligned_image, ...
                    ~, ...
                    source_used ...
                ] = ...
                    align_electroporated_locally_and_confirm( ...
                        meanImg_channels, ...
                        aligned_image_path);

                fprintf( ...
                    'Transform estimated from: %s\n', ...
                    source_used);
            end

        % ==========================================================
        % Pas de segmentation
        % ==========================================================

        else

            alignedPattern = ...
                sprintf( ...
                    'aligned_plane%d_AVG*.tif', ...
                    p - 1);

            alignedFiles = ...
                dir( ...
                    fullfile( ...
                        current_electroporated_TSeries_plane_path, ...
                        alignedPattern));

            avgPattern = ...
                sprintf( ...
                    'plane%d_AVG*.tif', ...
                    p - 1);

            avgFiles = ...
                dir( ...
                    fullfile( ...
                        current_electroporated_TSeries_plane_path, ...
                        avgPattern));

            % ======================================================
            % Charger image moyenne Electroporated
            % ======================================================

            if ~isempty(avgFiles)

                avg_path = ...
                    fullfile( ...
                        current_electroporated_TSeries_plane_path, ...
                        avgFiles(1).name);

                electroporated_img = ...
                    safe_read_and_normalize( ...
                        avg_path);

                if ~isempty(electroporated_img)

                    meanImg_channels{2} = ...
                        electroporated_img;
                end
            end

            % ======================================================
            % Aligned existe
            % ======================================================

            if ~isempty(alignedFiles)

                aligned_image_path = ...
                    fullfile( ...
                        current_electroporated_TSeries_plane_path, ...
                        alignedFiles(1).name);

                aligned_image = ...
                    safe_read_and_normalize( ...
                        aligned_image_path);

            % ======================================================
            % Aucun aligned -> recalage
            % ======================================================

            else

                if isempty(meanImg_channels{2})

                    fprintf( ...
                        ['Plane %d: no Electroporated mean image ' ...
                         'found in:\n%s\n'], ...
                        p, ...
                        current_electroporated_TSeries_plane_path);

                    aligned_image = [];
                    npy_file_path = [];

                elseif isempty(meanImg_channels{1})

                    warning( ...
                        ['Plane %d: GCaMP mean image missing. ' ...
                         'Electroporated alignment impossible.'], ...
                        p);

                    aligned_image = [];
                    npy_file_path = [];

                else

                    aligned_image_path = ...
                        fullfile( ...
                            current_electroporated_TSeries_plane_path, ...
                            sprintf( ...
                                'aligned_plane%d_AVG.tif', ...
                                p - 1));

                    [ ...
                        aligned_image, ...
                        ~, ...
                        source_used ...
                    ] = ...
                        align_electroporated_locally_and_confirm( ...
                            meanImg_channels, ...
                            aligned_image_path);

                    fprintf( ...
                        'Transform estimated from: %s\n', ...
                        source_used);
                end
            end
        end

    % ==============================================================
    %
    % PRIORITÉ 3
    %
    % SINGLE IMAGES
    %
    % ==============================================================

    elseif has_single_images

        fprintf('\n');
        fprintf('============================================\n');
        fprintf('ELECTROPORATED SOURCE: SINGLE IMAGES\n');
        fprintf('Folder:\n%s\n', single_images_path);
        fprintf('============================================\n');

        % ==========================================================
        % Demander numéro du canal Electroporated
        % ==========================================================

        answer = ...
            inputdlg( ...
                'Enter electroporated channel number:', ...
                'Electroporated channel', ...
                [1 45], ...
                {'3'});

        if isempty(answer)

            fprintf( ...
                'Electroporated channel selection cancelled.\n');

            [ ...
                meanImg_channels, ...
                meanImg ...
            ] = ...
                complete_meanImg_channels( ...
                    meanImg_channels, ...
                    filePath, ...
                    current_gcamp_suite2p_plane_path, ...
                    meanImg);

            return;
        end

        electroporated_channel_number = ...
            str2double( ...
                strtrim(answer{1}));

        if ~isfinite(electroporated_channel_number) || ...
                electroporated_channel_number < 1 || ...
                electroporated_channel_number ~= ...
                    round(electroporated_channel_number)

            warning( ...
                'load_or_process_cellpose_TSeries:InvalidElectroporatedChannel', ...
                'Invalid Electroporated channel number.');

            [ ...
                meanImg_channels, ...
                meanImg ...
            ] = ...
                complete_meanImg_channels( ...
                    meanImg_channels, ...
                    filePath, ...
                    current_gcamp_suite2p_plane_path, ...
                    meanImg);

            return;
        end

        electroporated_channel_number = ...
            round( ...
                electroporated_channel_number);

        electroporated_channel_str = ...
            sprintf( ...
                'Ch%d', ...
                electroporated_channel_number);

        fprintf( ...
            'Electroporated channel: %s\n', ...
            electroporated_channel_str);

        % ==========================================================
        % Chercher les segmentations du canal demandé
        % ==========================================================

        cellpose_files = ...
            dir( ...
                fullfile( ...
                    single_images_path, ...
                    '*_seg.npy'));

        cellpose_files_electroporated = ...
            cellpose_files( ...
                contains( ...
                    {cellpose_files.name}, ...
                    electroporated_channel_str, ...
                    'IgnoreCase', ...
                    true));

        % ==========================================================
        % SINGLE IMAGES :
        % segmentation déjà présente
        % ==========================================================

        if ~isempty(cellpose_files_electroporated)

            electroporated_seg_path = ...
                select_or_default( ...
                    cellpose_files_electroporated, ...
                    electroporated_channel_str, ...
                    '*.npy');

            electroporated_seg_path = ...
                validate_existing_file( ...
                    electroporated_seg_path);

            if ~isempty(electroporated_seg_path)

                [ ...
                    seg_folder, ...
                    seg_name, ...
                    ~ ...
                ] = ...
                    fileparts( ...
                        electroporated_seg_path);

                base_name = ...
                    regexprep( ...
                        seg_name, ...
                        '_seg$', ...
                        '');

                aligned_image_path = ...
                    fullfile( ...
                        seg_folder, ...
                        [base_name '.tif']);

                % ==================================================
                % Retrouver image brute
                %
                % aligned_xxx_ChX.tif
                % ->
                % xxx_ChX.tif
                % ==================================================

                raw_name = ...
                    regexprep( ...
                        base_name, ...
                        '^aligned_', ...
                        '');

                electroporated_tif_path = ...
                    fullfile( ...
                        seg_folder, ...
                        [raw_name '.tif']);

                electroporated_img = ...
                    safe_read_and_normalize( ...
                        electroporated_tif_path);

                if ~isempty(electroporated_img)

                    meanImg_channels{2} = ...
                        electroporated_img;
                end

                aligned_image = ...
                    safe_read_and_normalize( ...
                        aligned_image_path);

                % ==================================================
                % Segmentation présente mais TIFF aligned absent
                % ==================================================

                if isempty(aligned_image)

                    fprintf( ...
                        ['Existing Electroporated masks found, ' ...
                         'but aligned TIFF must be reconstructed.\n']);

                    if isempty(meanImg_channels{2})

                        warning( ...
                            ['Raw Electroporated Single image ' ...
                             'could not be found.']);

                    elseif isempty(meanImg_channels{1})

                        warning( ...
                            ['GCaMP mean image missing. ' ...
                             'Electroporated alignment impossible.']);

                    else

                        [ ...
                            aligned_image, ...
                            ~, ...
                            source_used ...
                        ] = ...
                            align_electroporated_locally_and_confirm( ...
                                meanImg_channels, ...
                                aligned_image_path);

                        fprintf( ...
                            'Transform estimated from: %s\n', ...
                            source_used);
                    end
                end
            end

        % ==========================================================
        % SINGLE IMAGES :
        % aucune segmentation
        % ==========================================================

        else

            tif_files = ...
                dir( ...
                    fullfile( ...
                        single_images_path, ...
                        '*.tif'));

            tif_files_electroporated = ...
                tif_files( ...
                    contains( ...
                        {tif_files.name}, ...
                        electroporated_channel_str, ...
                        'IgnoreCase', ...
                        true));

            % ======================================================
            % Séparer TIFF aligned et TIFF brut
            % ======================================================

            if ~isempty(tif_files_electroporated)

                is_aligned = ...
                    startsWith( ...
                        {tif_files_electroporated.name}, ...
                        'aligned_', ...
                        'IgnoreCase', ...
                        true);

                aligned_files = ...
                    tif_files_electroporated( ...
                        is_aligned);

                raw_files = ...
                    tif_files_electroporated( ...
                        ~is_aligned);

            else

                aligned_files = ...
                    tif_files_electroporated;

                raw_files = ...
                    tif_files_electroporated;
            end

            % ======================================================
            % Aucun fichier du canal demandé
            % ======================================================

            if isempty(aligned_files) && ...
                    isempty(raw_files)

                warning( ...
                    'load_or_process_cellpose_TSeries:SingleImageChannelMissing', ...
                    ['No Single image containing "%s" ' ...
                     'was found in:\n%s'], ...
                    electroporated_channel_str, ...
                    single_images_path);

                aligned_image = [];
                aligned_image_path = '';

            % ======================================================
            % Aligned existe déjà
            % ======================================================

            elseif ~isempty(aligned_files)

                aligned_image_path = ...
                    select_or_default( ...
                        aligned_files, ...
                        electroporated_channel_str, ...
                        '*.tif');

                aligned_image = ...
                    safe_read_and_normalize( ...
                        aligned_image_path);

                % ==================================================
                % Charger également le TIFF brut
                % ==================================================

                if ~isempty(raw_files)

                    electroporated_tif_path = ...
                        select_or_default( ...
                            raw_files, ...
                            electroporated_channel_str, ...
                            '*.tif');

                    if ~isempty(electroporated_tif_path)

                        electroporated_img = ...
                            safe_read_and_normalize( ...
                                electroporated_tif_path);

                        if ~isempty(electroporated_img)

                            meanImg_channels{2} = ...
                                electroporated_img;
                        end
                    end
                end

                % ==================================================
                % Aligned trouvé mais illisible
                % ==================================================

                if isempty(aligned_image) && ...
                        ~isempty(meanImg_channels{2}) && ...
                        ~isempty(meanImg_channels{1})

                    [ ...
                        aligned_image, ...
                        ~, ...
                        source_used ...
                    ] = ...
                        align_electroporated_locally_and_confirm( ...
                            meanImg_channels, ...
                            aligned_image_path);

                    fprintf( ...
                        'Transform estimated from: %s\n', ...
                        source_used);
                end

            % ======================================================
            % Aucun aligned :
            % charger TIFF brut puis recalage
            % ======================================================

            else

                electroporated_tif_path = ...
                    select_or_default( ...
                        raw_files, ...
                        electroporated_channel_str, ...
                        '*.tif');

                if isempty(electroporated_tif_path)

                    warning( ...
                        ['No Electroporated Single image ' ...
                         'was selected.']);

                    aligned_image = [];
                    aligned_image_path = '';

                else

                    electroporated_img = ...
                        safe_read_and_normalize( ...
                            electroporated_tif_path);

                    if ~isempty(electroporated_img)

                        meanImg_channels{2} = ...
                            electroporated_img;
                    end

                    % ==============================================
                    % GCaMP absent -> essayer de le recharger
                    % ==============================================

                    if isempty(meanImg_channels{1}) && ...
                            ~isempty(current_gcamp_suite2p_plane_path)

                        tmp = ...
                            load_meanImg_from_path( ...
                                current_gcamp_suite2p_plane_path);

                        if ~isempty(tmp)

                            meanImg_channels{1} = ...
                                tmp;

                            meanImg = ...
                                tmp;
                        end
                    end

                    if isempty(meanImg_channels{1})

                        warning( ...
                            ['GCaMP mean image missing. ' ...
                             'Electroporated alignment impossible.']);

                        aligned_image = [];
                        aligned_image_path = '';

                    elseif isempty(meanImg_channels{2})

                        warning( ...
                            ['Electroporated Single image could ' ...
                             'not be loaded.']);

                        aligned_image = [];
                        aligned_image_path = '';

                    else

                        [ ...
                            ~, ...
                            electroporated_file_name, ...
                            ~ ...
                        ] = ...
                            fileparts( ...
                                electroporated_tif_path);

                        aligned_image_path = ...
                            fullfile( ...
                                single_images_path, ...
                                [ ...
                                    'aligned_' ...
                                    electroporated_file_name ...
                                    '.tif' ...
                                ]);

                        [ ...
                            aligned_image, ...
                            ~, ...
                            source_used ...
                        ] = ...
                            align_electroporated_locally_and_confirm( ...
                                meanImg_channels, ...
                                aligned_image_path);

                        fprintf( ...
                            'Transform estimated from: %s\n', ...
                            source_used);
                    end
                end
            end
        end

    % ==============================================================
    %
    % AUCUNE SOURCE ELECTROPORATED
    %
    % ==============================================================

    else

        warning( ...
            'load_or_process_cellpose_TSeries:NoElectroporatedSource', ...
            ['No Electroporated source found for plane %d.\n' ...
             'Checked:\n' ...
             '1. Suite2p Electroporated\n' ...
             '2. Electroporated TSeries\n' ...
             '3. Single images'], ...
            p);

        [ ...
            meanImg_channels, ...
            meanImg ...
        ] = ...
            complete_meanImg_channels( ...
                meanImg_channels, ...
                filePath, ...
                current_gcamp_suite2p_plane_path, ...
                meanImg);

        return;
    end

    % ==============================================================
    % FLUX CELLPOSE FINAL
    % ==============================================================

    if ~isempty(aligned_image_path) && ...
            isfile(aligned_image_path)

        if isempty(aligned_image)

            aligned_image = ...
                safe_read_and_normalize( ...
                    aligned_image_path);
        end

        if ~isempty(aligned_image)

            [ ...
                aligned_folder, ...
                aligned_name, ...
                ~ ...
            ] = ...
                fileparts( ...
                    aligned_image_path);

            electroporated_seg_path = ...
                fullfile( ...
                    aligned_folder, ...
                    [aligned_name '_seg.npy']);

            % ======================================================
            % STEP 1
            %
            % Dessiner masques Electroporated si absents
            % ======================================================

            if ~isfile(electroporated_seg_path)

                fprintf('\n');
                fprintf('============================================\n');
                fprintf('CELLPOSE STEP 1\n');
                fprintf('DRAW MASKS ON ALIGNED ELECTROPORATED IMAGE\n');
                fprintf('Save with Ctrl+S, then close Cellpose.\n');
                fprintf('============================================\n');

                electroporated_seg_path = ...
                    launch_cellpose_from_matlab( ...
                        aligned_image_path, ...
                        true, ...
                        'Draw masks on aligned electroporated image');

                electroporated_seg_path = ...
                    validate_existing_file( ...
                        electroporated_seg_path);

            else

                fprintf( ...
                    ['Existing aligned-Electroporated masks ' ...
                     'found:\n%s\n'], ...
                    electroporated_seg_path);
            end

            % ======================================================
            % STEP 2
            %
            % Reporter / corriger masques sur GCaMP
            % ======================================================

            if ~isempty(electroporated_seg_path)

                npy_file_path = ...
                    create_and_refine_masks_on_gcamp( ...
                        aligned_image_path, ...
                        meanImg_channels{1}, ...
                        gcamp_output_folder_plane, ...
                        electroporated_seg_path);

                npy_file_path = ...
                    validate_existing_file( ...
                        npy_file_path);

            else

                warning( ...
                    ['No aligned-Electroporated *_seg.npy was saved. ' ...
                     'GCaMP correction cannot start.']);

                npy_file_path = [];
            end

        else

            warning( ...
                ['Aligned Electroporated TIFF exists but ' ...
                 'could not be read.']);

            npy_file_path = [];
        end

    elseif ~isempty(aligned_image)

        warning( ...
            ['An aligned Electroporated image exists in memory, ' ...
             'but its TIFF path is unavailable.']);

        npy_file_path = [];
    end

    % ==============================================================
    % Post-processing
    % ==============================================================

    [ ...
        meanImg_channels, ...
        meanImg ...
    ] = ...
        complete_meanImg_channels( ...
            meanImg_channels, ...
            filePath, ...
            current_gcamp_suite2p_plane_path, ...
            meanImg);
end

% ========================================================================
