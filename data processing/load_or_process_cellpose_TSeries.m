        ops_npy = ...
            fullfile( ...
                path_in, ...
                'ops.npy');

        if isfile(ops_npy)

            try

                mod = ...
                    py.importlib.import_module( ...
                        'python_function');

                ops = ...
                    mod.read_npy_file( ...
                        ops_npy);

