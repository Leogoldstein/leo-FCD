% ========================================================================
% PREPARE GCAMP IMAGE
% ========================================================================

function image_out = ...
        prepare_image_for_cellpose_display( ...
            image_in)

    image_in = ...
        double(image_in);

    image_in(~isfinite(image_in)) = 0;

    values = ...
        image_in(isfinite(image_in));

    if isempty(values)

        image_out = ...
            uint16( ...
                zeros(size(image_in)));

        return;
    end

    low_value = ...
        prctile(values, 1);

    high_value = ...
        prctile(values, 99.8);

    if high_value <= low_value

        normalized = ...
            mat2gray(image_in);

    else

        normalized = ...
            (image_in - low_value) ./ ...
            (high_value - low_value);

        normalized = ...
            max( ...
                0, ...
                min(1, normalized));
    end

    normalized = ...
        normalized .^ 0.7;

    image_out = ...
        uint16( ...
            normalized .* 65535);
end


% ========================================================================
% PLANE INDEX
% ========================================================================

function plane_index = ...
        infer_plane_index_from_paths(varargin)

    plane_index = 0;

    for i = 1:nargin

        path_in = ...
            varargin{i};

        if isempty(path_in) || ...
                ~(ischar(path_in) || ...
                  isstring(path_in))

            continue;
        end

        token = ...
            regexp( ...
                char(path_in), ...
                'plane(\d+)', ...
                'tokens', ...
                'once');

        if ~isempty(token)

            plane_index = ...
                str2double( ...
                    token{1});

            if isfinite(plane_index)
                return;
            end
        end
    end
end


% ========================================================================
% CELLPOSE
% ========================================================================

function npy_file_path = ...
        launch_cellpose_from_matlab( ...
            image_path, ...
            ask_confirmation, ...
            dialog_title)

    npy_file_path = [];

    if nargin < 2 || ...
            isempty(ask_confirmation)

        ask_confirmation = true;
    end

    if nargin < 3 || ...
            isempty(dialog_title)

        dialog_title = ...
            'Launch Cellpose';
    end

    if isempty(image_path) || ...
            ~isfile(image_path)

        warning( ...
            'Cellpose image not found: %s', ...
            char(string(image_path)));

        return;
    end

    pyExec = ...
        'C:\Users\goldstein\AppData\Local\anaconda3\envs\cellpose\python.exe';

    cellposePath = ...
        'C:\Users\goldstein\AppData\Local\anaconda3\envs\cellpose\Scripts\cellpose.exe';

    if ~isfile(cellposePath)

        warning( ...
            'cellpose.exe not found: %s', ...
            cellposePath);

        return;
    end

    try

        currentPyEnv = pyenv;

        if ~strcmp( ...
                currentPyEnv.Version, ...
                pyExec)

            pyenv( ...
                'Version', ...
                pyExec);
        end

    catch ME

        warning( ...
            'Unable to configure pyenv: %s', ...
            ME.message);
    end

    [folderPath, fileName, ~] = ...
        fileparts( ...
            image_path);

    candidate_npy = ...
        fullfile( ...
            folderPath, ...
            [fileName '_seg.npy']);

    file_existed_before = ...
        isfile(candidate_npy);

    previous_datenum = [];
    previous_bytes = [];

    if file_existed_before

        info_before = ...
            dir(candidate_npy);

        previous_datenum = ...
            info_before.datenum;

        previous_bytes = ...
            info_before.bytes;
    end

    if ask_confirmation

        % Afficher le chemin dans la Command Window
        fprintf('\n');
        fprintf('Cellpose image:\n');
        fprintf('%s\n\n', image_path);
    
        answer = ...
            questdlg( ...
                ['Do you want to launch Cellpose?' newline newline ...
                 'Save with Ctrl+S, then close Cellpose.'], ...
                dialog_title, ...
                'Yes', ...
                'No', ...
                'Yes');
    
        if ~strcmp(answer, 'Yes')
            return;
        end
    end

    [status, command_output] = ...
        system( ...
            ['"' cellposePath '"']);

    if status ~= 0

        warning( ...
            'Cellpose closed with status %d:\n%s', ...
            status, ...
            command_output);

        return;
    end

    if ~isfile(candidate_npy)

        warning( ...
            'No Cellpose segmentation saved for:\n%s', ...
            image_path);

        return;
    end

    info_after = ...
        dir(candidate_npy);

    if file_existed_before

        file_was_modified = ...
            info_after.datenum > previous_datenum || ...
            info_after.bytes ~= previous_bytes;

        if ~file_was_modified

            warning( ...
                ['Existing segmentation was not modified. ' ...
                 'Use Ctrl+S before closing Cellpose.']);

            return;
        end
    end

    npy_file_path = ...
        candidate_npy;
end