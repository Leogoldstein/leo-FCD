% ========================================================================
% ESTIMATE SMOOTH LOCAL DISPLACEMENT FIELD
%
% Champ non rigide volontairement CONTRAINT :
%
%   - grille grossière de points de contrôle ;
%   - pour chaque point : recherche d'une translation locale entière ;
%   - déplacement limité à max_shift pixels ;
%   - fenêtres peu texturées ignorées ;
%   - interpolation naturelle entre les points valides ;
%   - fort lissage final du champ ;
%   - amplitude finale à nouveau limitée à max_shift.
%
% Le champ retourné respecte la convention :
%   D(:,:,1) = dx
%   D(:,:,2) = dy
%
% et apply_displacement_field utilise :
%   output(x,y) = input(x - dx, y - dy)
% ========================================================================

function [D, control_points] = ...
        estimate_smooth_local_displacement_field( ...
            moving_img, ...
            ref_img, ...
            grid_spacing, ...
            patch_radius, ...
            max_shift, ...
            smoothing_sigma, ...
            min_texture)

    moving_img = ...
        double(moving_img);

    ref_img = ...
        double(ref_img);

    if ~isequal(size(moving_img), size(ref_img))

        moving_img = ...
            imresize( ...
                moving_img, ...
                size(ref_img));
    end

    n_rows = ...
        size(ref_img, 1);

    n_cols = ...
        size(ref_img, 2);

    % --------------------------------------------------------------
    % Normalisation robuste commune pour les scores locaux.
    % --------------------------------------------------------------

    moving_norm = ...
        robust_registration_normalize( ...
            moving_img);

    ref_norm = ...
        robust_registration_normalize( ...
            ref_img);

    margin = ...
        patch_radius + ...
        max_shift + ...
        2;

    x_centers = ...
        (1 + margin):grid_spacing:(n_cols - margin);

    y_centers = ...
        (1 + margin):grid_spacing:(n_rows - margin);

    % Ajouter des points proches des limites si la grille est très pauvre.
    if isempty(x_centers)

        x_centers = ...
            round(n_cols / 2);
    end

    if isempty(y_centers)

        y_centers = ...
            round(n_rows / 2);
    end

    [Xc, Yc] = ...
        meshgrid( ...
            x_centers, ...
            y_centers);

    dx_grid = ...
        nan(size(Xc));

    dy_grid = ...
        nan(size(Yc));

    score_grid = ...
        nan(size(Xc));

    valid_grid = ...
        false(size(Xc));

    % --------------------------------------------------------------
    % Mesure locale indépendante pour chaque point de contrôle.
    % --------------------------------------------------------------

    for k = 1:numel(Xc)

        cx = ...
            Xc(k);

        cy = ...
            Yc(k);

        ref_rows = ...
            (cy - patch_radius):(cy + patch_radius);

        ref_cols = ...
            (cx - patch_radius):(cx + patch_radius);

        ref_patch = ...
            ref_norm( ...
                ref_rows, ...
                ref_cols);

        texture_level = ...
            std( ...
                ref_patch(:), ...
                0, ...
                'omitnan');

        if ~isfinite(texture_level) || ...
                texture_level < min_texture

            continue;
        end

        [ ...
            best_dx, ...
            best_dy, ...
            best_score ...
        ] = ...
            find_best_local_translation_patch( ...
                moving_norm, ...
                ref_norm, ...
                cx, ...
                cy, ...
                patch_radius, ...
                max_shift);

        if ~isfinite(best_score)

            continue;
        end

        dx_grid(k) = ...
            best_dx;

        dy_grid(k) = ...
            best_dy;

        score_grid(k) = ...
            best_score;

        valid_grid(k) = ...
            true;
    end

    % --------------------------------------------------------------
    % Rejeter les points manifestement incohérents.
    %
    % On utilise la médiane locale globale comme garde-fou, sans
    % empêcher une vraie déformation progressive de l'image.
    % --------------------------------------------------------------

    if nnz(valid_grid) >= 4

        dx_valid = ...
            dx_grid(valid_grid);

        dy_valid = ...
            dy_grid(valid_grid);

        med_dx = ...
            median( ...
                dx_valid, ...
                'omitnan');

        med_dy = ...
            median( ...
                dy_valid, ...
                'omitnan');

        residual = ...
            hypot( ...
                dx_grid - med_dx, ...
                dy_grid - med_dy);

        % Tolérance volontairement large.
        outlier_limit = ...
            max( ...
                4, ...
                0.9 * max_shift);

        reject = ...
            valid_grid & ...
            residual > outlier_limit & ...
            score_grid < median(score_grid(valid_grid), 'omitnan');

        valid_grid(reject) = ...
            false;

        dx_grid(reject) = ...
            NaN;

        dy_grid(reject) = ...
            NaN;
    end

    control_points = ...
        struct();

    control_points.x = ...
        Xc;

    control_points.y = ...
        Yc;

    control_points.dx = ...
        dx_grid;

    control_points.dy = ...
        dy_grid;

    control_points.score = ...
        score_grid;

    control_points.valid = ...
        valid_grid;

    % --------------------------------------------------------------
    % Si trop peu de points fiables : pas de déformation.
    % --------------------------------------------------------------

    if nnz(valid_grid) < 3

        D = ...
            zeros( ...
                n_rows, ...
                n_cols, ...
                2);

        return;
    end

    % --------------------------------------------------------------
    % Interpolation des points de contrôle sur tous les pixels.
    %
    % "natural" donne une transition douce sans comportement oscillant
    % fort. "nearest" est utilisé hors enveloppe convexe.
    % --------------------------------------------------------------

    valid_x = ...
        Xc(valid_grid);

    valid_y = ...
        Yc(valid_grid);

    valid_dx = ...
        dx_grid(valid_grid);

    valid_dy = ...
        dy_grid(valid_grid);

    Fdx = ...
        scatteredInterpolant( ...
            valid_x(:), ...
            valid_y(:), ...
            valid_dx(:), ...
            'natural', ...
            'nearest');

    Fdy = ...
        scatteredInterpolant( ...
            valid_x(:), ...
            valid_y(:), ...
            valid_dy(:), ...
            'natural', ...
            'nearest');

    [Xq, Yq] = ...
        meshgrid( ...
            1:n_cols, ...
            1:n_rows);

    Dx = ...
        Fdx( ...
            Xq, ...
            Yq);

    Dy = ...
        Fdy( ...
            Xq, ...
            Yq);

    % --------------------------------------------------------------
    % Lissage fort : c'est la régularisation principale.
    % --------------------------------------------------------------

    if smoothing_sigma > 0

        Dx = ...
            imgaussfilt( ...
                Dx, ...
                smoothing_sigma, ...
                'Padding', ...
                'replicate');

        Dy = ...
            imgaussfilt( ...
                Dy, ...
                smoothing_sigma, ...
                'Padding', ...
                'replicate');
    end

    % --------------------------------------------------------------
    % Limitation vectorielle stricte du déplacement final.
    % --------------------------------------------------------------

    amplitude = ...
        hypot( ...
            Dx, ...
            Dy);

    scale = ...
        ones(size(amplitude));

    too_large = ...
        amplitude > max_shift;

    scale(too_large) = ...
        max_shift ./ ...
        amplitude(too_large);

    Dx = ...
        Dx .* scale;

    Dy = ...
        Dy .* scale;

    D = ...
        zeros( ...
            n_rows, ...
            n_cols, ...
            2);

    D(:,:,1) = ...
        Dx;

    D(:,:,2) = ...
        Dy;
end


% ========================================================================
% FIND BEST LOCAL TRANSLATION PATCH
%
% Pour une position (cx,cy), teste toutes les translations dans un disque
% de rayon max_shift. Le patch de référence reste fixe ; le patch moving
% est lu autour de la position déplacée.
%
% Convention :
%   dx > 0 signifie qu'il faut déplacer le contenu moving vers la droite.
%   dy > 0 signifie qu'il faut déplacer le contenu moving vers le bas.
% ========================================================================

function [best_dx, best_dy, best_score] = ...
        find_best_local_translation_patch( ...
            moving_img, ...
            ref_img, ...
            cx, ...
            cy, ...
            patch_radius, ...
            max_shift)

    best_dx = 0;
    best_dy = 0;
    best_score = -Inf;

    ref_rows = ...
        (cy - patch_radius):(cy + patch_radius);

    ref_cols = ...
        (cx - patch_radius):(cx + patch_radius);

    ref_patch = ...
        ref_img( ...
            ref_rows, ...
            ref_cols);

    a = ...
        ref_patch(:);

    a = ...
        a - ...
        mean(a, 'omitnan');

    norm_a = ...
        sqrt( ...
            sum(a.^2, 'omitnan'));

    if norm_a <= eps

        return;
    end

    for dy = -max_shift:max_shift

        for dx = -max_shift:max_shift

            if dx^2 + dy^2 > max_shift^2
                continue;
            end

            % Si moving doit être déplacé de +dx,+dy, alors le contenu
            % correspondant au patch de référence se trouve initialement
            % autour de (cx-dx, cy-dy).
            moving_cx = ...
                cx - dx;

            moving_cy = ...
                cy - dy;

            moving_rows = ...
                (moving_cy - patch_radius):(moving_cy + patch_radius);

            moving_cols = ...
                (moving_cx - patch_radius):(moving_cx + patch_radius);

            if moving_rows(1) < 1 || ...
                    moving_rows(end) > size(moving_img,1) || ...
                    moving_cols(1) < 1 || ...
                    moving_cols(end) > size(moving_img,2)

                continue;
            end

            moving_patch = ...
                moving_img( ...
                    moving_rows, ...
                    moving_cols);

            b = ...
                moving_patch(:);

            valid = ...
                isfinite(a) & ...
                isfinite(b);

            if nnz(valid) < 100
                continue;
            end

            av = ...
                a(valid);

            bv = ...
                b(valid);

            av = ...
                av - mean(av);

            bv = ...
                bv - mean(bv);

            denominator = ...
                sqrt( ...
                    sum(av.^2) * ...
                    sum(bv.^2));

            if denominator <= eps
                continue;
            end

            score = ...
                sum(av .* bv) ./ ...
                denominator;

            if score > best_score

                best_score = ...
                    score;

                best_dx = ...
                    dx;

                best_dy = ...
                    dy;
            end
        end
    end
end


% ========================================================================
% ROBUST REGISTRATION NORMALIZE
% ========================================================================

function out = ...
        robust_registration_normalize(img)

    img = ...
        double(img);

    img(~isfinite(img)) = 0;

    vals = ...
        img(isfinite(img));

    if isempty(vals)

        out = ...
            zeros(size(img));

        return;
    end

    low_val = ...
        prctile( ...
            vals, ...
            1);

    high_val = ...
        prctile( ...
            vals, ...
            99);

    if high_val <= low_val

        out = ...
            mat2gray(img);

    else

        out = ...
            (img - low_val) ./ ...
            (high_val - low_val);

        out = ...
            max( ...
                0, ...
                min(1, out));
    end
end


% ========================================================================
% APPLY DISPLACEMENT FIELD
%
% Application inverse du champ :
% chaque pixel de sortie (x,y) échantillonne l'image source à
% (x-dx, y-dy).
%
% Cette convention correspond aux dx/dy estimés ci-dessus.
% ========================================================================

function out = ...
        apply_displacement_field( ...
            img, ...
            D)

    out = [];

    if isempty(img) || ...
            isempty(D)

        return;
    end

    img = ...
        double(img);

    n_rows = ...
        size(img,1);

    n_cols = ...
        size(img,2);

    if size(D,1) ~= n_rows || ...
            size(D,2) ~= n_cols || ...
            size(D,3) ~= 2

        error( ...
            'Displacement field dimensions do not match image.');
    end

    [X, Y] = ...
        meshgrid( ...
            1:n_cols, ...
            1:n_rows);

    Xsource = ...
        X - D(:,:,1);

    Ysource = ...
        Y - D(:,:,2);

    out = ...
        interp2( ...
            X, ...
            Y, ...
            img, ...
            Xsource, ...
            Ysource, ...
            'linear', ...
            0);
end


