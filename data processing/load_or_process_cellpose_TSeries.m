    fclose(fid);

    command = ...
        sprintf( ...
            '"%s" "%s" "%s" "%s" "%s"', ...
            pyExec, ...
            script_path, ...
            source_seg_path, ...
            gcamp_image_path, ...
            destination_seg_path);

