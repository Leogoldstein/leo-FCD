end


% ========================================================================
% ALIGN ELECTROPORATED
% ========================================================================

function [aligned_image, T, source_used] = ...
        align_electroporated_locally_and_confirm( ...
            meanImg_channels, ...
            aligned_image_path)

    % meanImg_channels:
    %   {1} GCaMP
    %   {2} Electroporated
    %   {3} Green

    ref_img = [];

    if numel(meanImg_channels) >= 1

        ref_img = ...
            meanImg_channels{1};
    end

    electroporated_img = [];

    if numel(meanImg_channels) >= 2

        electroporated_img = ...
            meanImg_channels{2};
    end

    green_img = [];

    if numel(meanImg_channels) >= 3

        green_img = ...
            meanImg_channels{3};
    end

    aligned_image = [];
    T = [];
    source_used = '';

    % ==============================================================
    % Vérifications
    % ==============================================================

    if isempty(ref_img)

        warning( ...
            ['align_electroporated_locally_and_confirm: ' ...
             'GCaMP absent.']);

        return;
    end

    if isempty(electroporated_img)

        warning( ...
            ['align_electroporated_locally_and_confirm: ' ...
             'Electroporated image absent.']);

        return;
    end

    ref_img = ...
        double(ref_img);

    % ==============================================================
    % Image utilisée pour ESTIMER la translation
    %
    % Green prioritaire lorsqu'il existe.
    % Sinon Electroporated.
    % ==============================================================

    if ~isempty(green_img)

        moving_for_estimation = ...
            double(green_img);

        source_used = ...
            'Green';

    else

        moving_for_estimation = ...
            double(electroporated_img);

        source_used = ...
            'Electroporated';
    end

    % ==============================================================
    % Image réellement transformée
    % ==============================================================

    moving_img = ...
        double(electroporated_img);

    % ==============================================================
    % ==============================================================
    % Registration
    %
    % Extraire les structures sombres locales
    % (ex. vaisseaux) avant imregcorr
    % ==============================================================
    
    [moving_reg, moving_components] = ...
    extract_dark_structures_for_registration( ...
        moving_for_estimation);

    [ref_reg, ref_components] = ...
        extract_dark_structures_for_registration( ...
            ref_img);
    
    if ~isequal(size(moving_reg), size(ref_reg))
    
        moving_reg = ...
            imresize( ...
                moving_reg, ...
                size(ref_reg));
    
        moving_components = ...
            resize_registration_components( ...
                moving_components, ...
                size(ref_reg));
    end
    
    % ==============================================================
    % Afficher les transformations utilisées pour le recalage
    % ==============================================================
    
    % show_registration_components( ...
    %     moving_components, ...
    %     ref_components, ...
    %     moving_reg, ...
    %     ref_reg, ...
    %     source_used);
    
    % ==============================================================
    % Registration limitée à un rayon de 20 pixels
    % ==============================================================
    
    max_radius = 20;
    
    try
    
        T = ...
            find_best_translation_within_radius( ...
                moving_reg, ...
                ref_reg, ...
                max_radius);
    
        fprintf( ...
            '%s -> GCaMP | dark-weighted registration\n', ...
            source_used);
    
        fprintf( ...
            'Search radius = %d px\n', ...
            max_radius);
    
        fprintf( ...
            'dx = %.3f px\n', ...
            T(3,1));
    
        fprintf( ...
            'dy = %.3f px\n', ...
            T(3,2));
    
        fprintf( ...
            'distance = %.3f px\n', ...
            hypot( ...
                T(3,1), ...
                T(3,2)));
    
    catch ME
    
        warning( ...
            'Registration failed: %s', ...
            ME.message);
    
        T = ...
            eye(3);
    end
    % ==============================================================
    % Appliquer T à ELECTROPORATED
    % ==============================================================

    aligned_image = ...
        apply_transform_with_phasecorr( ...
            moving_img, ...
            T, ...
            ref_img);

    if isempty(aligned_image)

        warning( ...
            ['align_electroporated_locally_and_confirm: ' ...
             'empty transformation.']);

        return;
    end

    % ==============================================================
    % Dimensions
    % ==============================================================

    if ~isequal( ...
            size(aligned_image,1), ...
            size(ref_img,1)) || ...
            ~isequal( ...
                size(aligned_image,2), ...
                size(ref_img,2))

        aligned_image = ...
            imresize( ...
                aligned_image, ...
                [ ...
                    size(ref_img,1), ...
                    size(ref_img,2) ...
                ]);
    end

    % ==============================================================
    % Métriques
    % ==============================================================

    before_cmp = ...
        mat2gray( ...
            moving_img);

    ref_cmp = ...
        mat2gray( ...
            ref_img);

    after_cmp = ...
        mat2gray( ...
            aligned_image);

    if ~isequal( ...
            size(before_cmp), ...
            size(ref_cmp))

        before_cmp = ...
            imresize( ...
                before_cmp, ...
                size(ref_cmp));
    end

    if ~isequal( ...
            size(after_cmp), ...
            size(ref_cmp))

        after_cmp = ...
            imresize( ...
                after_cmp, ...
                size(ref_cmp));
    end

    before_err = ...
        mean( ...
            abs( ...
                ref_cmp(:) - ...
                before_cmp(:)), ...
            'omitnan');

    after_err = ...
        mean( ...
            abs( ...
                ref_cmp(:) - ...
                after_cmp(:)), ...
            'omitnan');

    fprintf( ...
        'Error vs ref before = %.6f\n', ...
        before_err);

    fprintf( ...
        'Error vs ref after  = %.6f\n', ...
        after_err);

    fprintf( ...
        'Improvement         = %.6f\n', ...
        before_err - after_err);

    % ==============================================================
    % Validation manuelle
    % ==============================================================

    [ ...
        was_saved, ...
        aligned_image, ...
        T ...
    ] = ...
        preview_alignment_with_save_cancel( ...
            moving_img, ...
            aligned_image, ...
            ref_img, ...
            T);

    if ~was_saved

        fprintf( ...
            'Alignment cancelled by user.\n');

        aligned_image = [];
        T = [];
        source_used = '';

        return;
    end

    % ==============================================================
    % Sauvegarde
    % ==============================================================

    if ~isempty(aligned_image) && ...
            ~isempty(aligned_image_path)

        try

            imwrite( ...
                aligned_image, ...
                aligned_image_path, ...
                'tif');

            fprintf( ...
                'Aligned electroporated image saved:\n%s\n', ...
                aligned_image_path);

        catch ME

            warning( ...
                ['Unable to save aligned electroporated ' ...
                 'image "%s": %s'], ...
                aligned_image_path, ...
                ME.message);
        end
    end
end

% ========================================================================
% FIND BEST TRANSLATION WITHIN RADIUS
%
% Recherche exhaustive de la meilleure translation entière dans un
% cercle de rayon max_radius autour de (0,0).
%
% Le score est une corrélation normalisée calculée uniquement sur la
% région réellement commune aux deux images. Les pixels ajoutés par
% translation ne participent donc pas au score.
% ========================================================================

function T = ...
        find_best_translation_within_radius( ...
            moving_img, ...
            ref_img, ...
            max_radius)

    % ==============================================================
    % Vérifications
    % ==============================================================

    if isempty(moving_img) || ...
            isempty(ref_img)

        error( ...
            'Moving and reference images must not be empty.');
    end

    moving_img = ...
        double(moving_img);

    ref_img = ...
        double(ref_img);

    if ~isequal( ...
            size(moving_img), ...
            size(ref_img))

        moving_img = ...
            imresize( ...
                moving_img, ...
                size(ref_img));
    end

    % ==============================================================
    % Initialisation
    % ==============================================================

    best_score = ...
        -Inf;

    best_dx = 0;
    best_dy = 0;

    n_rows = ...
        size(ref_img, 1);

    n_cols = ...
        size(ref_img, 2);

    % ==============================================================
    % Tester toutes les translations autorisées
    %
    % dx² + dy² <= rayon²
    % ==============================================================

    for dy = -max_radius:max_radius

        for dx = -max_radius:max_radius

            % ------------------------------------------------------
            % Limite CIRCULAIRE
            % ------------------------------------------------------

            if dx^2 + dy^2 > max_radius^2
                continue;
            end

            % ------------------------------------------------------
            % Coordonnées X de la zone commune
            % ------------------------------------------------------

            if dx >= 0

                ref_cols = ...
                    (1 + dx):n_cols;

                moving_cols = ...
                    1:(n_cols - dx);

            else

                ref_cols = ...
                    1:(n_cols + dx);

                moving_cols = ...
                    (1 - dx):n_cols;
            end

            % ------------------------------------------------------
            % Coordonnées Y de la zone commune
            % ------------------------------------------------------

            if dy >= 0

                ref_rows = ...
                    (1 + dy):n_rows;

                moving_rows = ...
                    1:(n_rows - dy);

            else

                ref_rows = ...
                    1:(n_rows + dy);

                moving_rows = ...
                    (1 - dy):n_rows;
            end

            % ------------------------------------------------------
            % Extraire uniquement la zone commune
            % ------------------------------------------------------

            ref_crop = ...
                ref_img( ...
                    ref_rows, ...
                    ref_cols);

            moving_crop = ...
                moving_img( ...
                    moving_rows, ...
                    moving_cols);

            % ------------------------------------------------------
            % Pixels valides
            % ------------------------------------------------------

            valid = ...
                isfinite(ref_crop) & ...
                isfinite(moving_crop);

            if nnz(valid) < 100
                continue;
            end

            a = ...
                ref_crop(valid);

            b = ...
                moving_crop(valid);

            % ------------------------------------------------------
            % Retirer la moyenne
            %
            % Cela évite que le niveau moyen de fluorescence
            % détermine le recalage.
            % ------------------------------------------------------

            a = ...
                a - mean(a);

            b = ...
                b - mean(b);

            % ------------------------------------------------------
            % Corrélation normalisée
            % ------------------------------------------------------

            denominator = ...
                sqrt( ...
                    sum(a.^2) * ...
                    sum(b.^2));

            if denominator <= eps
                continue;
            end

            score = ...
                sum(a .* b) ./ ...
                denominator;

            % ------------------------------------------------------
            % Meilleur déplacement
            % ------------------------------------------------------

            if score > best_score

                best_score = ...
                    score;

                best_dx = ...
                    dx;

                best_dy = ...
                    dy;
            end
        end
    end

    % ==============================================================
    % Transformation
    % ==============================================================

    if ~isfinite(best_score)

        error( ...
            'No valid translation found within %d pixels.', ...
            max_radius);
    end

    T = ...
        eye(3);

    T(3,1) = ...
        best_dx;

    T(3,2) = ...
        best_dy;

    fprintf( ...
        ['Best constrained registration: ' ...
         'dx = %d px | dy = %d px | ' ...
         'r = %.2f px | score = %.5f\n'], ...
        best_dx, ...
        best_dy, ...
        hypot(best_dx, best_dy), ...
        best_score);
end

% ========================================================================
% EXTRACT DARK STRUCTURES FOR REGISTRATION
%
% Prépare une image spécifiquement pour le recalage.
%
% Priorités :
%   - 65 % : minima sombres locaux / structures fines
%   - 25 % : structures sombres plus larges
%   - 10 % : organisation sombre globale
%
% Aucun seuillage dur afin de conserver les petits minima locaux.
% ========================================================================

% ========================================================================
% EXTRACT DARK STRUCTURES FOR REGISTRATION
% ========================================================================

function [out, components] = ...
        extract_dark_structures_for_registration(img)

    out = [];

    components = struct( ...
        'normalized', [], ...
        'fine_dark', [], ...
        'medium_dark', [], ...
        'coarse_dark', [], ...
        'global_dark', []);

    if isempty(img)
        return;
    end

    img = double(img);
    img(~isfinite(img)) = 0;

    % ==============================================================
    % 1) Normalisation robuste
    % ==============================================================

    vals = ...
        img(isfinite(img));

    if isempty(vals)

        out = ...
            zeros(size(img));

        return;
    end

    low_val = ...
        prctile(vals, 1);

    high_val = ...
        prctile(vals, 99);

    if high_val <= low_val

        img_norm = ...
            mat2gray(img);

    else

        img_norm = ...
            (img - low_val) ./ ...
            (high_val - low_val);

        img_norm = ...
            max( ...
                min(img_norm, 1), ...
                0);
    end

    components.normalized = ...
        img_norm;

    % ==============================================================
    % 2) Minima locaux fins
    % ==============================================================

    fine_img = ...
        imgaussfilt( ...
            img_norm, ...
            0.4);

    fine_background = ...
        imgaussfilt( ...
            img_norm, ...
            2.5);

    fine_dark = ...
        fine_background - ...
        fine_img;

    fine_dark = ...
        max( ...
            fine_dark, ...
            0);

    if any(fine_dark(:) > 0)

        fine_dark = ...
            mat2gray( ...
                fine_dark);

    else

        fine_dark = ...
            zeros(size(img_norm));
    end

    components.fine_dark = ...
        fine_dark;

    % ==============================================================
    % 3) Minima locaux intermédiaires
    % ==============================================================

    medium_img = ...
        imgaussfilt( ...
            img_norm, ...
            1);

    medium_background = ...
        imgaussfilt( ...
            img_norm, ...
            7);

    medium_dark = ...
        medium_background - ...
        medium_img;

    medium_dark = ...
        max( ...
            medium_dark, ...
            0);

    if any(medium_dark(:) > 0)

        medium_dark = ...
            mat2gray( ...
                medium_dark);

    else

        medium_dark = ...
            zeros(size(img_norm));
    end

    components.medium_dark = ...
        medium_dark;

    % ==============================================================
    % 4) Structures sombres larges
    % ==============================================================

    coarse_img = ...
        imgaussfilt( ...
            img_norm, ...
            2);

    coarse_background = ...
        imgaussfilt( ...
            img_norm, ...
            18);

    coarse_dark = ...
        coarse_background - ...
        coarse_img;

    coarse_dark = ...
        max( ...
            coarse_dark, ...
            0);

    if any(coarse_dark(:) > 0)

        coarse_dark = ...
            mat2gray( ...
                coarse_dark);

    else

        coarse_dark = ...
            zeros(size(img_norm));
    end

    components.coarse_dark = ...
        coarse_dark;

    % ==============================================================
    % 5) Organisation sombre globale
    % ==============================================================

    global_component = ...
        imgaussfilt( ...
            img_norm, ...
            2);

    global_dark = ...
        1 - global_component;

    global_dark = ...
        mat2gray( ...
            global_dark);

    components.global_dark = ...
        global_dark;

    % ==============================================================
    % 6) Combinaison
    %
    % Forte priorité aux minima locaux.
    % ==============================================================

    out = ...
        0.55 .* fine_dark + ...
        0.15 .* medium_dark + ...
        0.20 .* coarse_dark + ...
        0.10 .* global_dark;

    out = ...
        mat2gray(out);

    out = ...
        out .^ 1.1;

    out = ...
        imgaussfilt( ...
            out, ...
            0.25);

    out = ...
        mat2gray(out);
end


