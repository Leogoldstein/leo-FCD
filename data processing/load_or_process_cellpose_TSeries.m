function img = safe_read_and_normalize(img_path)

    img = [];

    if isempty(img_path)
        return;
    end

    if ~(ischar(img_path) || ...
            isstring(img_path))
        return;
    end

    if ~isfile(img_path)
        return;
    end

    try

        img = ...
            normalize_image( ...
                imread(img_path));

    catch ME

        warning( ...
            'load_or_process_cellpose_TSeries:ReadImageFailed', ...
            'Failed reading image "%s": %s', ...
            char(img_path), ...
            ME.message);

        img = [];
    end
end


