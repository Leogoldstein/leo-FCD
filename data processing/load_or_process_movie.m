function save_motion_fields_if_needed( ...
    savePath, ...
    data, ...
    fields_motion, ...
    m, ...
    has_new_data_for_acquisition, ...
    tseries_name)

    if ~has_new_data_for_acquisition

        fprintf('\nMotion results\n');

        fprintf( ...
            '  TSeries: %s\n', ...
            tseries_name);

        fprintf( ...
            ['  Status : no new data; ' ...
             'results_motion.mat unchanged.\n']);

        return;
    end

    saveStruct = ...
        struct();

    for f = 1:numel(fields_motion)

        fieldName = ...
            fields_motion{f};

        if isfield(data, 'motion') && ...
                isfield(data.motion, fieldName) && ...
                numel(data.motion.(fieldName)) >= m

            saveStruct.(fieldName) = ...
                data.motion.(fieldName){m};
        end
    end

    try

        if exist(savePath, 'file') == 2

            save( ...
                savePath, ...
                '-struct', ...
                'saveStruct', ...
                '-append');

        else

            save( ...
                savePath, ...
                '-struct', ...
                'saveStruct');
        end

        fprintf('\nMotion results\n');

        fprintf( ...
            '  TSeries: %s\n', ...
            tseries_name);

        fprintf( ...
            '  Status : results_motion.mat updated.\n');

        fprintf( ...
            '  File   : %s\n', ...
            savePath);

    catch ME

        warning( ...
            'load_or_process_movie:SaveFailed', ...
            'TSeries %s | unable to save motion results: %s', ...
            tseries_name, ...
            ME.message);

        fprintf('\nMotion results\n');

        fprintf( ...
            '  TSeries: %s\n', ...
            tseries_name);

        fprintf( ...
            '  Status : save failed.\n');
    end
end


function y = smooth_savgol( ...
    x, ...
    order, ...
    framelen_target)

    x = ...
        x(:);

    N = ...
        numel(x);

    framelen = min( ...
        framelen_target, ...
        N);

    if mod(framelen, 2) == 0

        framelen = ...
            framelen - 1;
    end

    if framelen <= order

        framelen = ...
            order + 2;

        if mod(framelen, 2) == 0

            framelen = ...
                framelen + 1;
        end
    end

    if N < framelen || ...
            framelen < 3

        y = x;

        return;
    end

    y = sgolayfilt( ...
        x, ...
        order, ...
        framelen);
end


function onsets = get_onsets( ...
    bin_motion)

    bin_motion = ...
        bin_motion(:);

    onsets = find( ...
        bin_motion(2:end) == 1 & ...
        bin_motion(1:end - 1) == 0) + 1;
end


function offsets = get_offsets( ...
    bin_motion)

    bin_motion = ...
        bin_motion(:);

    offsets = find( ...
        bin_motion(2:end) == 0 & ...
        bin_motion(1:end - 1) == 1) + 1;
end


function tseries_path = get_tseries_path( ...
    current_gcamp_TSeries_path, ...
    m)

    tseries_path = '';

    if isempty(current_gcamp_TSeries_path) || ...
            m > numel(current_gcamp_TSeries_path) || ...
            isempty(current_gcamp_TSeries_path{m})

        return;
    end

    tseries_path = ...
        char(string( ...
            current_gcamp_TSeries_path{m}));
end


function tseries_name = find_tseries_name_in_path( ...
    path_value)

    tseries_name = ...
        'TSeries_unknown';

    if isempty(path_value)

        return;
    end

    path_value = ...
        char(string(path_value));

    while ~isempty(path_value)

        [parent_path, current_name] = ...
            fileparts(path_value);

        if startsWith( ...
                current_name, ...
                'TSeries-', ...
                'IgnoreCase', ...
                true)

            tseries_name = ...
                current_name;

            return;
        end

        if isempty(parent_path) || ...
                strcmp(parent_path, path_value)

            break;
        end

        path_value = ...
            parent_path;
    end
end


function sampling_rate_m = get_sampling_rate( ...
    sampling_rate_group, ...
    m)

    sampling_rate_m = ...
        NaN;

    if isempty(sampling_rate_group)

        return;
    end

    if iscell(sampling_rate_group)

        if m <= numel(sampling_rate_group) && ...
                ~isempty(sampling_rate_group{m})

            sampling_rate_m = ...
                double(sampling_rate_group{m});
        end

    elseif isnumeric(sampling_rate_group)

        if isscalar(sampling_rate_group)

            sampling_rate_m = ...
                double(sampling_rate_group);

        elseif m <= numel(sampling_rate_group)

            sampling_rate_m = ...
                double(sampling_rate_group(m));
        end
    end

    if isempty(sampling_rate_m) || ...
            ~isfinite(sampling_rate_m) || ...
            sampling_rate_m <= 0

        sampling_rate_m = ...
            1;

        warning( ...
            'load_or_process_movie:InvalidSamplingRate', ...
            ['Invalid sampling rate for acquisition %d. ' ...
             'Fallback value of 1 Hz used.'], ...
            m);
    end
end


function status_name = get_motion_status_name( ...
    data, ...
    m)

    status_name = ...
        'unknown';

    if ~motion_status_exists(data, m) || ...
            isempty(data.motion.motion_energy_status{m})

        return;
    end

    raw_status = string( ...
        data.motion.motion_energy_status{m});

    switch raw_status

        case "done"

            status_name = ...
                'completed';

        case "processing"

            status_name = ...
                'partial processing';

        case "skipped"

            status_name = ...
                'calculation skipped';

        case "no_camera"

            status_name = ...
                'no camera data';

        case "no_motion"

            status_name = ...
                'camera movie missing';

        otherwise

            status_name = ...
                char(raw_status);
    end
end