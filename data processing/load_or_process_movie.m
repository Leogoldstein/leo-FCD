function [motion, camFolders, needs_processing] = load_or_process_movie( ...
    current_gcamp_TSeries_path, ...
    gcamp_output_folders, ...
    avg_block, ...
    sampling_rate_group, ...
    current_animal_group, ...
    data, ...
    processing_mode)

% LOAD_OR_PROCESS_MOVIE
%
% Charge ou calcule l'énergie de mouvement pour chaque acquisition.
%
% Organisation :
%   m = acquisition / TSeries
%
% Sorties :
%   motion
%       Structure contenant uniquement les données de mouvement.
%
%   camFolders
%       Cell array contenant le dossier caméra correspondant
%       à chaque acquisition / TSeries.
%
% La fonction :
%   - conserve les données motion déjà présentes en mémoire ;
%   - recharge results_motion.mat uniquement si nécessaire ;
%   - renomme les anciens results_movie.mat en results_motion.mat ;
%   - recharge camFolders depuis results_motion.mat s'il existe ;
%   - sinon recherche automatiquement :
%         TSeries\cam\Concatenated
%         TSeries\camera\Concatenated
%   - ajoute camFolders aux anciens results_motion.mat ;
%   - calcule la motion energy si demandé ;
%   - détecte les périodes de mouvement ;
%   - sauvegarde les résultats par acquisition.
%
% IMPORTANT :
%   camFolders n'est PAS stocké dans data.motion.


    if nargin < 7 || isempty(processing_mode)
        processing_mode = 'interactive';
    end

    processing_mode = char(string(processing_mode));

    if ~ismember(lower(processing_mode), {'load_only', 'interactive'})
        error( ...
            'processing_mode must be ''load_only'' or ''interactive''.');
    end

    is_load_only = ...
        strcmpi(processing_mode, 'load_only');

    needs_processing = false;

    numAcquisitions = ...
        numel(current_gcamp_TSeries_path);

    fields_motion = { ...
        'motion_energy_group', ...
        'motion_energy_smooth_group', ...
        'avg_active_motion_onsets_group', ...
        'avg_active_motion_offsets_group', ...
        'active_motion_onsets_group', ...
        'active_motion_offsets_group', ...
        'speed_active_group', ...
        'motion_energy_status' ...
    };

    % Preserve which entries genuinely existed in the input data BEFORE
    % preallocation. This lets us distinguish a valid stored [] (for
    % example no detected motion periods) from a field that was absent and
    % has just been created as an empty placeholder by initialization.
    initial_motion_presence = ...
        capture_motion_field_presence( ...
            data, ...
            fields_motion, ...
            numAcquisitions);

    data = init_motion_data_struct_if_needed( ...
        data, ...
        numAcquisitions, ...
        fields_motion);

    camFolders = ...
        cell(numAcquisitions, 1);

    fijiPath = ...
        'C:\Users\goldstein\Fiji.app\fiji-windows-x64.exe';

    motion_strategy = [];
    motion_strategy_initialized = false;

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('MOTION PROCESSING\n');
    fprintf('Animal       : %s\n', char(string(current_animal_group)));
    fprintf('Acquisitions : %d\n', numAcquisitions);
    fprintf('Average block: %d frames\n', avg_block);
    fprintf('============================================================\n');

    for m = 1:numAcquisitions

        data = ensure_motion_entry_exists( ...
            data, ...
            fields_motion, ...
            numAcquisitions, ...
            m);

        tseries_path_m = get_tseries_path( ...
            current_gcamp_TSeries_path, ...
            m);

        tseries_name = find_tseries_name_in_path( ...
            tseries_path_m);

        sampling_rate_m = get_sampling_rate( ...
            sampling_rate_group, ...
            m);

        fprintf('\n');
        fprintf('------------------------------------------------------------\n');
        fprintf('Motion acquisition %d/%d\n', m, numAcquisitions);
        fprintf('Animal       : %s\n', char(string(current_animal_group)));
        fprintf('TSeries      : %s\n', tseries_name);
        fprintf('Sampling rate: %.4f Hz\n', sampling_rate_m);
        fprintf('------------------------------------------------------------\n');

        root_folder_m = extract_motion_root_folder( ...
            gcamp_output_folders, ...
            m);

        if isempty(root_folder_m)

            warning( ...
                'load_or_process_movie:MissingOutputFolder', ...
                ['Acquisition %d/%d | %s | impossible de ' ...
                 'déterminer le dossier de sortie.'], ...
                m, ...
                numAcquisitions, ...
                tseries_name);

            fprintf( ...
                'Status: skipped because output folder is missing.\n');

            continue;
        end

        fprintf( ...
            'Output folder: %s\n', ...
            root_folder_m);

        oldPath = fullfile( ...
            root_folder_m, ...
            'results_movie.mat');

        savePath = fullfile( ...
            root_folder_m, ...
            'results_motion.mat');

        % =========================================================
        % Rename old results file
        % =========================================================

        if exist(oldPath, 'file') == 2 && ...
                exist(savePath, 'file') ~= 2

            try

                movefile( ...
                    oldPath, ...
                    savePath);

                fprintf( ...
                    ['Existing results_movie.mat renamed to ' ...
                     'results_motion.mat.\n']);

            catch ME

                warning( ...
                    'load_or_process_movie:RenameFailed', ...
                    ['Acquisition %d/%d | %s | unable to rename ' ...
                     'results_movie.mat: %s'], ...
                    m, ...
                    numAcquisitions, ...
                    tseries_name, ...
                    ME.message);
            end
        end

        % =========================================================
        % Camera folder
        %
        % 1. Try loading camFolders from results_motion.mat.
        % 2. If missing / invalid, reconstruct from TSeries.
        % 3. Update results_motion.mat if necessary.
        %
        % camFolders remains independent from data.motion.
        % =========================================================

        fprintf('\nCamera folder\n');

        cam_folder_m = [];
        cam_folder_needs_save = false;

        % ---------------------------------------------------------
        % Load existing camFolders from results_motion.mat
        % ---------------------------------------------------------

        if exist(savePath, 'file') == 2

            try

                cam_variable = ...
                    whos( ...
                        '-file', ...
                        savePath, ...
                        'camFolders');

                if ~isempty(cam_variable)

                    loaded_cam = load( ...
                        savePath, ...
                        'camFolders');

                    saved_cam = ...
                        loaded_cam.camFolders;

                    if iscell(saved_cam)

                        if ~isempty(saved_cam)

                            cam_folder_m = ...
                                saved_cam{1};
                        end

                    else

                        cam_folder_m = ...
                            saved_cam;
                    end

                    if ~isempty(cam_folder_m) && ...
                            isfolder(cam_folder_m)

                        fprintf( ...
                            '  Status: saved camera folder reused.\n');

                        fprintf( ...
                            '  Folder: %s\n', ...
                            cam_folder_m);

                    else

                        cam_folder_m = [];

                        fprintf( ...
                            ['  Status: saved camera folder is empty ' ...
                             'or no longer exists.\n']);
                    end
                end

            catch ME

                warning( ...
                    'load_or_process_movie:CameraPathLoadFailed', ...
                    ['Acquisition %d/%d | %s | unable to load ' ...
                     'camFolders from results_motion.mat: %s'], ...
                    m, ...
                    numAcquisitions, ...
                    tseries_name, ...
                    ME.message);
            end
        end

        % ---------------------------------------------------------
        % Reconstruct camera folder if necessary
        % ---------------------------------------------------------

        if isempty(cam_folder_m)

            camPath = fullfile( ...
                tseries_path_m, ...
                'cam', ...
                'Concatenated');

            cameraPath = fullfile( ...
                tseries_path_m, ...
                'camera', ...
                'Concatenated');

            if isfolder(camPath)

                cam_folder_m = ...
                    camPath;

                cam_folder_needs_save = true;

                fprintf( ...
                    '  Status: camera folder found.\n');

                fprintf( ...
                    '  Folder: %s\n', ...
                    cam_folder_m);

            elseif isfolder(cameraPath)

                cam_folder_m = ...
                    cameraPath;

                cam_folder_needs_save = true;

                fprintf( ...
                    '  Status: camera folder found.\n');

                fprintf( ...
                    '  Folder: %s\n', ...
                    cam_folder_m);

            else

                cam_folder_m = [];

                fprintf( ...
                    '  Status: no camera folder found.\n');

                fprintf( ...
                    '  Search: %s\n', ...
                    camPath);

                fprintf( ...
                    '          %s\n', ...
                    cameraPath);

                % Sauvegarde également l'absence du dossier caméra
                % si la variable n'était pas encore présente.
                if exist(savePath, 'file') == 2

                    try

                        cam_variable = ...
                            whos( ...
                                '-file', ...
                                savePath, ...
                                'camFolders');

                        if isempty(cam_variable)

                            cam_folder_needs_save = true;
                        end

                    catch
                    end
                end
            end
        end

        camFolders{m} = ...
            cam_folder_m;

        % ---------------------------------------------------------
        % Add / update camFolders in results_motion.mat
        %
        % Each results_motion.mat corresponds to one acquisition,
        % therefore camFolders stored in the file contains the
        % camera path for THIS acquisition.
        % ---------------------------------------------------------

        if cam_folder_needs_save

            saveCam = struct();

            saveCam.camFolders = ...
                cam_folder_m;

            try

                if exist(savePath, 'file') == 2

                    save( ...
                        savePath, ...
                        '-struct', ...
                        'saveCam', ...
                        '-append');

                else

                    save( ...
                        savePath, ...
                        '-struct', ...
                        'saveCam');
                end

                fprintf( ...
                    '  Saved : camFolders added to results_motion.mat.\n');

            catch ME

                warning( ...
                    'load_or_process_movie:CameraPathSaveFailed', ...
                    ['Acquisition %d/%d | %s | unable to save ' ...
                     'camFolders: %s'], ...
                    m, ...
                    numAcquisitions, ...
                    tseries_name, ...
                    ME.message);
            end
        end

        % =========================================================
        % Data already complete in memory
        %
        % IMPORTANT:
        % Camera folder has already been handled above because
        % camFolders is intentionally independent from data.motion.
        % =========================================================

        already_has_all = ...
            motion_already_complete( ...
                data, ...
                m);

        if already_has_all

            status_name = ...
                get_motion_status_name( ...
                    data, ...
                    m);

            fprintf('\n');
            fprintf('Memory status: complete.\n');
            fprintf('Motion status: %s\n', status_name);
            fprintf( ...
                'Action       : no reload or recalculation required.\n');

            if ~is_load_only

                save_motion_figure_if_missing( ...
                    root_folder_m, ...
                    data, ...
                    m, ...
                    current_animal_group, ...
                    tseries_name, ...
                    sampling_rate_m, ...
                    avg_block);
            end

            continue;
        end

        % =========================================================
        % Complete memory selectively from results_motion.mat
        %
        % Only the variables that are genuinely needed are loaded.
        % results_motion.mat is never loaded in full.
        %
        % For a status "done", empty onset/offset arrays can be valid
        % results (no movement period). Their original presence before
        % initialization is therefore taken into account.
        %
        % For "no_camera" / "no_motion", the saved state is deliberately
        % not reloaded: the filesystem is rechecked below so newly added
        % camera data can be detected.
        % =========================================================

        has_new_data_for_acquisition = false;

        if exist(savePath, 'file') == 2

            fields_to_load = ...
                get_motion_fields_to_load( ...
                    data, ...
                    fields_motion, ...
                    initial_motion_presence(:, m), ...
                    m);

            fprintf('\n');
            fprintf('Memory status: incomplete.\n');

            if isempty(fields_to_load)

                fprintf( ...
                    ['Saved motion data: no variable needs to be ' ...
                     'loaded from results_motion.mat.\n']);

            else

                try

                    variables_in_file = ...
                        whos('-file', savePath);

                    variable_names = ...
                        {variables_in_file.name};

                    fields_available = ...
                        fields_to_load( ...
                            ismember( ...
                                fields_to_load, ...
                                variable_names));

                    if isempty(fields_available)

                        fprintf( ...
                            ['Saved motion data: none of the missing ' ...
                             'variables is available in results_motion.mat.\n']);

                    else

                        fprintf( ...
                            'Loading only missing motion variables:\n');

                        for field_idx = 1:numel(fields_available)

                            fprintf( ...
                                '  %s\n', ...
                                fields_available{field_idx});
                        end

                        loaded = ...
                            load( ...
                                savePath, ...
                                fields_available{:});

                        data = ...
                            merge_loaded_motion_into_data( ...
                                data, ...
                                loaded, ...
                                fields_available, ...
                                m);

                    end

                catch ME

                    warning( ...
                        'load_or_process_movie:ResultsLoadFailed', ...
                        ['Acquisition %d/%d | %s | unable to load ' ...
                         'missing fields from results_motion.mat: %s'], ...
                        m, ...
                        numAcquisitions, ...
                        tseries_name, ...
                        ME.message);
                end

            end

        else

            fprintf('\n');
            fprintf( ...
                'Saved motion file: not found.\n');
        end

        already_has_all = ...
            motion_already_complete( ...
                data, ...
                m);

        if already_has_all

            status_name = ...
                get_motion_status_name( ...
                    data, ...
                    m);

            fprintf( ...
                'Memory completed from saved file.\n');

            fprintf( ...
                'Motion status: %s\n', ...
                status_name);

            fprintf( ...
                'Action       : calculation skipped.\n');

            if ~is_load_only

                save_motion_figure_if_missing( ...
                    root_folder_m, ...
                    data, ...
                    m, ...
                    current_animal_group, ...
                    tseries_name, ...
                    sampling_rate_m, ...
                    avg_block);
            end

            continue;
        end

        % =========================================================
        % LOAD ONLY
        %
        % Existing saved motion values have already been merged above.
        % If the acquisition is still incomplete, stop here: no prompt,
        % no Fiji launch, no motion-energy calculation and no figure.
        % =========================================================

        if is_load_only

            needs_processing = true;

            fprintf( ...
                ['LOAD ONLY: motion data remain incomplete for this ' ...
                 'acquisition; calculation deferred to the sequential ' ...
                 'fallback.\n']);

            continue;
        end

        % =========================================================
        % No camera folder
        % =========================================================

        if isempty(cam_folder_m)

            data = assign_empty_motion_fields_if_missing( ...
                data, ...
                m);

            data.motion.motion_energy_status{m} = ...
                'no_camera';

            has_new_data_for_acquisition = ...
                true;

            save_motion_fields_if_needed( ...
                savePath, ...
                data, ...
                fields_motion, ...
                m, ...
                has_new_data_for_acquisition, ...
                tseries_name);

            continue;
        end

        % =========================================================
        % Camera movie
        % =========================================================

        filepath = fullfile( ...
            cam_folder_m, ...
            'cam_crop.tif');

        fprintf('\nCamera data\n');

        if exist(filepath, 'file') ~= 2

            fprintf( ...
                '  Movie status: cam_crop.tif not found.\n');

            fprintf( ...
                '  Expected file: %s\n', ...
                filepath);

            data = assign_empty_motion_fields_if_missing( ...
                data, ...
                m);

            data.motion.motion_energy_status{m} = ...
                'no_motion';

            has_new_data_for_acquisition = ...
                true;

            save_motion_fields_if_needed( ...
                savePath, ...
                data, ...
                fields_motion, ...
                m, ...
                has_new_data_for_acquisition, ...
                tseries_name);

            continue;
        end

        fprintf( ...
            '  Movie status: camera movie available.\n');

        fprintf( ...
            '  Movie file  : %s\n', ...
            filepath);

        % =========================================================
        % 1. Motion energy
        % =========================================================

        fprintf('\nMotion energy\n');

        if ~motion_field_has_value( ...
                data, ...
                'motion_energy_group', ...
                m)

            fprintf( ...
                ['  Status: motion energy not available ' ...
                 'in memory.\n']);

            if ~motion_strategy_initialized

                motion_strategy = ...
                    ask_motion_energy_strategy_once();

                motion_strategy_initialized = ...
                    true;
            end

            motion_energy = ...
                compute_motion_energy_with_strategy( ...
                    filepath, ...
                    fijiPath, ...
                    motion_strategy);

            data.motion.motion_energy_group{m} = ...
                motion_energy;

            if isempty(motion_energy)

                data.motion.motion_energy_status{m} = ...
                    'skipped';

                fprintf( ...
                    ['  Result: motion energy calculation ' ...
                     'skipped.\n']);

            else

                data.motion.motion_energy_status{m} = ...
                    'processing';

                fprintf( ...
                    '  Result: motion energy calculated.\n');

                fprintf( ...
                    '  Frames: %d\n', ...
                    numel(motion_energy));
            end

            has_new_data_for_acquisition = ...
                true;

        else

            motion_energy = ...
                data.motion.motion_energy_group{m};

            fprintf( ...
                '  Status: existing motion energy reused.\n');

            fprintf( ...
                '  Frames: %d\n', ...
                numel(motion_energy));

            if ~motion_status_exists(data, m) || ...
                    isempty(data.motion.motion_energy_status{m})

                data.motion.motion_energy_status{m} = ...
                    'processing';

                has_new_data_for_acquisition = ...
                    true;
            end
        end

        if isempty(motion_energy)

            data = assign_empty_motion_fields_if_missing( ...
                data, ...
                m);

            has_new_data_for_acquisition = ...
                true;

            save_motion_fields_if_needed( ...
                savePath, ...
                data, ...
                fields_motion, ...
                m, ...
                has_new_data_for_acquisition, ...
                tseries_name);

            continue;
        end

        % =========================================================
        % 2. Temporal averaging
        % =========================================================

        avg_motion_energy = average_frames( ...
            motion_energy, ...
            avg_block);

        fprintf('\nTemporal averaging\n');

        fprintf( ...
            '  Input frames : %d\n', ...
            numel(motion_energy));

        fprintf( ...
            '  Block size   : %d\n', ...
            avg_block);

        fprintf( ...
            '  Output points: %d\n', ...
            numel(avg_motion_energy));

        % =========================================================
        % 3. Smoothing
        % =========================================================

        fprintf('\nMotion smoothing\n');

        if ~motion_field_has_value( ...
                data, ...
                'motion_energy_smooth_group', ...
                m)

            motion_energy_smooth = smooth_savgol( ...
                avg_motion_energy, ...
                3, ...
                11);

            data.motion.motion_energy_smooth_group{m} = ...
                motion_energy_smooth;

            has_new_data_for_acquisition = ...
                true;

            fprintf( ...
                ['  Status: smoothed motion signal ' ...
                 'calculated.\n']);

        else

            motion_energy_smooth = ...
                data.motion.motion_energy_smooth_group{m};

            fprintf( ...
                ['  Status: existing smoothed signal ' ...
                 'reused.\n']);
        end

        if isempty(motion_energy_smooth)

            fprintf( ...
                ['  Result: smoothed motion signal ' ...
                 'is empty.\n']);

            data = assign_empty_binary_motion_fields_if_missing( ...
                data, ...
                m);

            has_new_data_for_acquisition = ...
                true;

            save_motion_fields_if_needed( ...
                savePath, ...
                data, ...
                fields_motion, ...
                m, ...
                has_new_data_for_acquisition, ...
                tseries_name);

            continue;
        end

        % =========================================================
        % 4. Motion state detection
        % =========================================================

        need_bin = ...
            ~motion_field_has_value( ...
                data, ...
                'avg_active_motion_onsets_group', ...
                m) || ...
            ~motion_field_has_value( ...
                data, ...
                'avg_active_motion_offsets_group', ...
                m) || ...
            ~motion_field_has_value( ...
                data, ...
                'active_motion_onsets_group', ...
                m) || ...
            ~motion_field_has_value( ...
                data, ...
                'active_motion_offsets_group', ...
                m) || ...
            ~motion_field_has_value( ...
                data, ...
                'speed_active_group', ...
                m);

        thr_li = [];
        bin_sig = [];

        fprintf('\nMotion state detection\n');

        if need_bin

            [~, thr_li, ~] = ...
                compute_thresholds_for_bin_state_detection( ...
                    motion_energy_smooth, ...
                    false);

            [bin_sig, ~, ~, ~] = ...
                binarise_motion( ...
                    motion_energy_smooth, ...
                    thr_li, ...
                    sampling_rate_m, ...
                    avg_block, ...
                    3.0, ...
                    5);

            avg_onsets = ...
                get_onsets(bin_sig);

            avg_offsets = ...
                get_offsets(bin_sig);

            if ~isempty(bin_sig)

                if bin_sig(1) == 1

                    avg_onsets = [ ...
                        1; ...
                        avg_onsets(:) ...
                    ];
                end

                if bin_sig(end) == 1

                    avg_offsets = [ ...
                        avg_offsets(:); ...
                        numel(bin_sig) ...
                    ];
                end
            end

            N_frames = ...
                numel(motion_energy);

            onsets_frames = ...
                (avg_onsets - 1) * avg_block + 1;

            offsets_frames = ...
                avg_offsets * avg_block;

            onsets_frames = max( ...
                1, ...
                onsets_frames);

            offsets_frames = min( ...
                N_frames, ...
                offsets_frames);

            speed_active = repelem( ...
                bin_sig(:), ...
                avg_block);

            if isempty(speed_active)

                speed_active = ...
                    zeros(N_frames, 1);

            elseif numel(speed_active) < N_frames

                speed_active( ...
                    end + 1:N_frames) = ...
                    speed_active(end);

            else

                speed_active = ...
                    speed_active(1:N_frames);
            end

            data.motion.avg_active_motion_onsets_group{m} = ...
                avg_onsets;

            data.motion.avg_active_motion_offsets_group{m} = ...
                avg_offsets;

            data.motion.active_motion_onsets_group{m} = ...
                onsets_frames;

            data.motion.active_motion_offsets_group{m} = ...
                offsets_frames;

            data.motion.speed_active_group{m} = ...
                speed_active;

            has_new_data_for_acquisition = ...
                true;

            fprintf( ...
                '  Status         : motion states calculated.\n');

            fprintf( ...
                '  Threshold      : %.6f\n', ...
                thr_li);

            fprintf( ...
                '  Motion periods : %d\n', ...
                min( ...
                    numel(avg_onsets), ...
                    numel(avg_offsets)));

        else

            avg_onsets = ...
                data.motion.avg_active_motion_onsets_group{m};

            avg_offsets = ...
                data.motion.avg_active_motion_offsets_group{m};

            fprintf( ...
                '  Status         : existing motion states reused.\n');

            fprintf( ...
                '  Motion periods : %d\n', ...
                min( ...
                    numel(avg_onsets), ...
                    numel(avg_offsets)));
        end

        % The status becomes "done" only once the complete motion
        % pipeline has reached the state-detection stage successfully.
        if ~motion_status_exists(data, m) || ...
                ~strcmp( ...
                    string(data.motion.motion_energy_status{m}), ...
                    "done")

            data.motion.motion_energy_status{m} = ...
                'done';

            has_new_data_for_acquisition = ...
                true;
        end

        % =========================================================
        % Save motion
        % =========================================================

        save_motion_fields_if_needed( ...
            savePath, ...
            data, ...
            fields_motion, ...
            m, ...
            has_new_data_for_acquisition, ...
            tseries_name);

        % =========================================================
        % Figure
        % =========================================================

        save_motion_figure_if_missing( ...
            root_folder_m, ...
            data, ...
            m, ...
            current_animal_group, ...
            tseries_name, ...
            sampling_rate_m, ...
            avg_block);

        fprintf('\nAcquisition summary\n');

        fprintf( ...
            '  TSeries: %s\n', ...
            tseries_name);

        fprintf( ...
            '  Status : %s\n', ...
            get_motion_status_name( ...
                data, ...
                m));
    end

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('MOTION PROCESSING COMPLETED\n');
    fprintf('Animal      : %s\n', char(string(current_animal_group)));
    fprintf('Acquisitions: %d\n', numAcquisitions);
    fprintf('============================================================\n');

    motion = ...
        data.motion;
end


% =====================================================================
