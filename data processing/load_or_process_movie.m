function presence = capture_motion_field_presence( ...
    data, ...
    fieldNames, ...
    numAcquisitions)

    presence = ...
        false( ...
            numel(fieldNames), ...
            numAcquisitions);

    if isempty(data) || ...
            ~isstruct(data) || ...
            ~isfield(data, 'motion') || ...
            ~isstruct(data.motion)

        return;
    end

    for f = 1:numel(fieldNames)

        fieldName = ...
            fieldNames{f};

        if ~isfield(data.motion, fieldName) || ...
                ~iscell(data.motion.(fieldName))

            continue;
        end

        nStored = ...
            min( ...
                numel(data.motion.(fieldName)), ...
                numAcquisitions);

        if nStored > 0

            presence(f, 1:nStored) = ...
                true;
        end
    end
end


function fields_to_load = get_motion_fields_to_load( ...
    data, ...
    fields_motion, ...
    initial_presence_for_acquisition, ...
    m)

    fields_to_load = ...
        {};

    status = ...
        "";

    if motion_status_exists(data, m) && ...
            ~isempty(data.motion.motion_energy_status{m})

        status = ...
            string( ...
                data.motion.motion_energy_status{m});
    end

    % No trustworthy status in memory: try to recover every missing saved
    % variable. Empty values are included because, without a status, we do
    % not yet know whether [] is a valid result or merely uninitialized.
    if strlength(status) == 0

        for f = 1:numel(fields_motion)

            fieldName = ...
                fields_motion{f};

            if ~motion_field_has_value( ...
                    data, ...
                    fieldName, ...
                    m) || ...
                    ~initial_presence_for_acquisition(f)

                fields_to_load{end + 1} = ... %#ok<AGROW>
                    fieldName;
            end
        end

        return;
    end

    switch status

        case "done"

            % These fields must contain actual data for a completed
            % acquisition.
            required_nonempty = { ...
                'motion_energy_group', ...
                'motion_energy_smooth_group', ...
                'speed_active_group' ...
            };

            for f = 1:numel(required_nonempty)

                fieldName = ...
                    required_nonempty{f};

                if ~motion_field_has_value( ...
                        data, ...
                        fieldName, ...
                        m)

                    fields_to_load{end + 1} = ... %#ok<AGROW>
                        fieldName;
                end
            end

            % Event arrays are allowed to be genuinely empty. They are
            % loaded only when that entry did not exist at all in the input
            % data before initialization.
            empty_can_be_valid = { ...
                'avg_active_motion_onsets_group', ...
                'avg_active_motion_offsets_group', ...
                'active_motion_onsets_group', ...
                'active_motion_offsets_group' ...
            };

            for f = 1:numel(empty_can_be_valid)

                fieldName = ...
                    empty_can_be_valid{f};

                field_idx = ...
                    find( ...
                        strcmp( ...
                            fields_motion, ...
                            fieldName), ...
                        1, ...
                        'first');

                if ~isempty(field_idx) && ...
                        ~initial_presence_for_acquisition(field_idx)

                    fields_to_load{end + 1} = ... %#ok<AGROW>
                        fieldName;
                end
            end

        case "skipped"

            % Intentional persistent decision: nothing else is required.

        case {"no_camera", "no_motion"}

            % Do not reload stale empty values. The camera folder / movie is
            % rechecked on every run so newly added files can be detected.

        otherwise

            % Partial / legacy state (including "processing"): recover all
            % fields that do not currently contain useful information, and
            % all fields that were absent from the original input data.
            for f = 1:numel(fields_motion)

                fieldName = ...
                    fields_motion{f};

                if strcmp( ...
                        fieldName, ...
                        'motion_energy_status')

                    continue;
                end

                if ~motion_field_has_value( ...
                        data, ...
                        fieldName, ...
                        m) || ...
                        ~initial_presence_for_acquisition(f)

                    fields_to_load{end + 1} = ... %#ok<AGROW>
                        fieldName;
                end
            end
    end

    fields_to_load = ...
        unique( ...
            fields_to_load, ...
            'stable');
end


function save_motion_figure_if_missing( ...
    root_folder_m, ...
    data, ...
    m, ...
    current_animal_group, ...
    tseries_name, ...
    sampling_rate_m, ...
    avg_block)

    png_filename = ...
        fullfile( ...
            root_folder_m, ...
            'binary_motion_energy.png');

    fprintf('\nMotion figure\n');

    if isfile(png_filename)

        fprintf( ...
            '  Status: existing figure retained.\n');

        fprintf( ...
            '  File  : %s\n', ...
            png_filename);

        return;
    end

    if ~motion_field_has_value( ...
            data, ...
            'motion_energy_smooth_group', ...
            m)

        fprintf( ...
            ['  Status: figure not generated; ' ...
             'smoothed signal is unavailable.\n']);

        return;
    end

    motion_energy_smooth = ...
        data.motion.motion_energy_smooth_group{m};

    if isempty(motion_energy_smooth)

        fprintf( ...
            ['  Status: figure not generated; ' ...
             'signal is empty.\n']);

        return;
    end

    avg_onsets = ...
        [];

    avg_offsets = ...
        [];

    if motion_field_slot_exists( ...
            data, ...
            'avg_active_motion_onsets_group', ...
            m)

        avg_onsets = ...
            data.motion.avg_active_motion_onsets_group{m};
    end

    if motion_field_slot_exists( ...
            data, ...
            'avg_active_motion_offsets_group', ...
            m)

        avg_offsets = ...
            data.motion.avg_active_motion_offsets_group{m};
    end

    try

        [~, thr_li, ~] = ...
            compute_thresholds_for_bin_state_detection( ...
                motion_energy_smooth, ...
                false);

        [bin_sig, ~, ~, ~] = ...
            binarise_motion( ...
                motion_energy_smooth, ...
                thr_li, ...
                sampling_rate_m, ...
                avg_block, ...
                3.0, ...
                5);

        fig = figure( ...
            'Visible', ...
            'off', ...
            'Color', ...
            'w');

        hold on;

        dt = ...
            avg_block / sampling_rate_m;

        time_axis = ...
            (0:numel(motion_energy_smooth) - 1) * dt;

        yl = [ ...
            min(motion_energy_smooth), ...
            max(motion_energy_smooth) ...
        ];

        if yl(1) == yl(2)

            yl = ...
                yl + [-1 1] * eps;
        end

        number_periods = ...
            min( ...
                numel(avg_onsets), ...
                numel(avg_offsets));

        for kk = 1:number_periods

            onset_idx = ...
                round(avg_onsets(kk));

            offset_idx = ...
                round(avg_offsets(kk));

            if onset_idx < 1 || ...
                    offset_idx < 1 || ...
                    onset_idx > numel(time_axis) || ...
                    offset_idx > numel(time_axis)

                continue;
            end

            patch( ...
                [ ...
                    time_axis(onset_idx), ...
                    time_axis(offset_idx), ...
                    time_axis(offset_idx), ...
                    time_axis(onset_idx) ...
                ], ...
                [ ...
                    yl(1), ...
                    yl(1), ...
                    yl(2), ...
                    yl(2) ...
                ], ...
                [1 0.8 0.8], ...
                'EdgeColor', ...
                'none', ...
                'FaceAlpha', ...
                0.4);
        end

        plot( ...
            time_axis, ...
            bin_sig(:)' * yl(2), ...
            'Color', ...
            [1 0.5 0], ...
            'LineWidth', ...
            2);

        yline( ...
            thr_li, ...
            '--r', ...
            'LineWidth', ...
            1);

        plot( ...
            time_axis, ...
            motion_energy_smooth, ...
            'Color', ...
            [0 0 1], ...
            'LineWidth', ...
            2);

        title( ...
            sprintf( ...
                'Binary motion energy - %s - %s', ...
                char(string(current_animal_group)), ...
                tseries_name), ...
            'Interpreter', ...
            'none');

        xlabel('Time (s)');
        ylabel('Motion energy');

        grid on;
        hold off;

        saveas( ...
            fig, ...
            png_filename);

        close(fig);

        fprintf( ...
            '  Status: motion figure created.\n');

        fprintf( ...
            '  File  : %s\n', ...
            png_filename);

    catch ME

        if exist('fig', 'var') && ...
                isgraphics(fig)

            close(fig);
        end

        warning( ...
            'load_or_process_movie:FigureFailed', ...
            ['%s | unable to create motion figure: %s'], ...
            tseries_name, ...
            ME.message);

        fprintf( ...
            '  Status: figure generation failed.\n');
    end
end


function tf = motion_already_complete( ...
    data, ...
    m)

    tf = false;

    if ~motion_status_exists(data, m) || ...
            isempty(data.motion.motion_energy_status{m})

        return;
    end

    status = string( ...
        data.motion.motion_energy_status{m});

    switch status

        case "done"

            tf = ...
                motion_field_has_value( ...
                    data, ...
                    'motion_energy_group', ...
                    m) && ...
                motion_field_has_value( ...
                    data, ...
                    'motion_energy_smooth_group', ...
                    m) && ...
                motion_field_has_value( ...
                    data, ...
                    'speed_active_group', ...
                    m);

        case "skipped"

            tf = true;

        case {"no_camera", "no_motion"}

            tf = false;

        otherwise

            tf = false;
    end
end


function strategy = ask_motion_energy_strategy_once()

    strategy = struct();

    strategy.open_in_fiji = false;
    strategy.compute_direct = false;
    strategy.skip = false;

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('MOTION ENERGY STRATEGY\n');
    fprintf('============================================================\n');

    choice = input( ...
        ['Open the camera movie in Fiji for cropping?\n' ...
         '  1 = Yes\n' ...
         '  2 = No\n' ...
         'Choice: '], ...
        's');

    if strcmpi(choice, '1')

        strategy.open_in_fiji = ...
            true;

        return;
    end

    subchoice = input( ...
        ['Calculate motion energy on the current movie?\n' ...
         '  1 = Calculate directly\n' ...
         '  2 = Skip motion energy\n' ...
         'Choice: '], ...
        's');

    if strcmpi(subchoice, '1')

        strategy.compute_direct = ...
            true;

    else

        strategy.skip = ...
            true;
    end
end


function motion_energy = compute_motion_energy_with_strategy( ...
    filepath, ...
    fijiPath, ...
    strategy)

    if strategy.open_in_fiji

        fprintf( ...
            'Opening camera movie in Fiji:\n');

        fprintf( ...
            '%s\n', ...
            filepath);

        system( ...
            sprintf( ...
                '"%s" "%s"', ...
                fijiPath, ...
                filepath));

        motion_energy = ...
            compute_motion_energy(filepath);

    elseif strategy.compute_direct

        fprintf( ...
            'Calculating motion energy directly from:\n');

        fprintf( ...
            '%s\n', ...
            filepath);

        motion_energy = ...
            compute_motion_energy(filepath);

    else

        fprintf( ...
            'Motion energy calculation skipped for:\n');

        fprintf( ...
            '%s\n', ...
            filepath);

        motion_energy = [];
    end
end


function data = init_motion_data_struct_if_needed( ...
    data, ...
    numAcquisitions, ...
    fieldNames)

    if nargin < 1 || isempty(data)

        data = struct();
    end

    if ~isfield(data, 'motion') || ...
            ~isstruct(data.motion) || ...
            isempty(data.motion)

        data.motion = struct();
    end

    for i = 1:numel(fieldNames)

        fieldName = ...
            fieldNames{i};

        if ~isfield(data.motion, fieldName) || ...
                ~iscell(data.motion.(fieldName))

            data.motion.(fieldName) = ...
                cell(numAcquisitions, 1);

        elseif numel(data.motion.(fieldName)) < ...
                numAcquisitions

            old_values = ...
                data.motion.(fieldName);

            new_values = ...
                cell(numAcquisitions, 1);

            new_values(1:numel(old_values)) = ...
                old_values(:);

            data.motion.(fieldName) = ...
                new_values;
        end
    end
end


function data = ensure_motion_entry_exists( ...
    data, ...
    fieldNames, ...
    numAcquisitions, ...
    m)

    data = init_motion_data_struct_if_needed( ...
        data, ...
        numAcquisitions, ...
        fieldNames);

    for i = 1:numel(fieldNames)

        fieldName = ...
            fieldNames{i};

        if numel(data.motion.(fieldName)) < m

            new_values = ...
                cell(numAcquisitions, 1);

            new_values( ...
                1:numel(data.motion.(fieldName))) = ...
                data.motion.(fieldName)(:);

            data.motion.(fieldName) = ...
                new_values;
        end
    end
end


function tf = motion_field_slot_exists( ...
    data, ...
    fieldName, ...
    m)

    tf = ...
        isfield(data, 'motion') && ...
        isfield(data.motion, fieldName) && ...
        iscell(data.motion.(fieldName)) && ...
        numel(data.motion.(fieldName)) >= m;
end


function tf = motion_field_has_value( ...
    data, ...
    fieldName, ...
    m)

    tf = ...
        motion_field_slot_exists( ...
            data, ...
            fieldName, ...
            m) && ...
        ~isempty(data.motion.(fieldName){m});
end


function tf = motion_status_exists( ...
    data, ...
    m)

    tf = motion_field_slot_exists( ...
        data, ...
        'motion_energy_status', ...
        m);
end


function data = merge_loaded_motion_into_data( ...
    data, ...
    loaded, ...
    fields_motion, ...
    m)

    for f = 1:numel(fields_motion)

        fieldName = ...
            fields_motion{f};

        if ~isfield(loaded, fieldName)

            continue;
        end

        if ~motion_field_slot_exists( ...
                data, ...
                fieldName, ...
                m) || ...
                isempty(data.motion.(fieldName){m})

            data.motion.(fieldName){m} = ...
                loaded.(fieldName);
        end
    end
end


function root_folder_m = extract_motion_root_folder( ...
    gcamp_output_folders, ...
    m)

    root_folder_m = '';

    if isempty(gcamp_output_folders) || ...
            m > numel(gcamp_output_folders) || ...
            isempty(gcamp_output_folders{m})

        return;
    end

    this_entry = ...
        gcamp_output_folders{m};

    if iscell(this_entry)

        if ~isempty(this_entry) && ...
                ~isempty(this_entry{1})

            root_folder_m = ...
                fileparts(this_entry{1});
        end

    elseif ischar(this_entry) || ...
            isstring(this_entry)

        root_folder_m = ...
            char(this_entry);
    end
end


