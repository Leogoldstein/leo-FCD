        dir(npy_file_path);

    if isempty(file_info)
        return;
    end

    signature = struct();

    signature.path = ...
        npy_file_path;

    signature.bytes = ...
        file_info(1).bytes;

    signature.datenum = ...
        file_info(1).datenum;
end


