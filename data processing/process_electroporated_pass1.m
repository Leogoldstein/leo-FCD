    for f = 1:numel(fields)

        name = ...
            fields{f};

        if ~isfield(loaded, name)
            continue;
        end

        vals = ...
            coerce_to_plane_cell_local( ...
                loaded.(name), ...
                nPlanes);

        for p = 1:nPlanes

            if ~local_gcamp_slot_exists( ...
                    data, ...
                    name, ...
                    m, ...
                    p) || ...
                    isempty( ...
                        data.gcamp_plane.(name){m}{p})

                data.gcamp_plane.(name){m}{p} = ...
                    vals{p};
            end
        end
    end
end


