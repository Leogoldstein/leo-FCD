% ========================================================================
% ELECTROPORATED PLANE COMPLETE
%
% Une sortie vide peut être valide si roi_extraction_completed_by_plane
% vaut true. On vérifie donc l'existence des slots, pas leur non-vacuité.
% ========================================================================

function tf = electroporated_plane_results_complete_pass1( ...
        data, ...
        m, ...
        p)

    tf = false;

    if ~isfield(data, 'electroporated_plane') || ...
            isempty(data.electroporated_plane) || ...
            ~isstruct(data.electroporated_plane)

        return;
    end

    ep = ...
        data.electroporated_plane;

    if ~isfield( ...
            ep, ...
            'roi_extraction_completed_by_plane')

        return;
    end

    completed_value = ...
        get_nested_plane_value_pass1( ...
            ep.roi_extraction_completed_by_plane, ...
            m, ...
            p);

    if isempty(completed_value) || ...
            numel(completed_value) ~= 1

        return;
    end

    if islogical(completed_value)

        if ~completed_value
            return;
        end

    elseif isnumeric(completed_value)

        if ~isfinite(completed_value) || ...
                completed_value == 0

            return;
        end

    else

        return;
    end

    required_slot_fields = { ...
        'matched_gcamp_idx_by_plane', ...
        'matched_cellpose_idx_by_plane', ...
        'gcamp_unmatched_idx_by_plane', ...
        'cellpose_unmatched_idx_by_plane', ...
        'num_cells_mask_by_plane', ...
        'mask_cellpose_by_plane', ...
        'props_cellpose_by_plane', ...
        'outlines_x_cellpose_by_plane', ...
        'outlines_y_cellpose_by_plane', ...
        'F_electroporated_by_plane', ...
        'electroporated_match_mask_by_plane'};

    for k = 1:numel(required_slot_fields)

        field_name = ...
            required_slot_fields{k};

        if ~isfield(ep, field_name)

            return;
        end

        if ~nested_plane_entry_exists_pass1( ...
                ep.(field_name), ...
                m, ...
                p)

            return;
        end
    end

    if ~isfield( ...
            ep, ...
            'roi_extraction_npy_signature_by_plane')

        return;
    end

    saved_signature = ...
        get_nested_plane_value_pass1( ...
            ep.roi_extraction_npy_signature_by_plane, ...
            m, ...
            p);

    if isempty(saved_signature) || ...
            ~isstruct(saved_signature) || ...
            ~isfield(saved_signature, 'path') || ...
            isempty(saved_signature.path)

        return;
    end

    tf = true;
end


% ========================================================================
% GCAMP GROUP COMPLETE
% ========================================================================

function tf = local_gcamp_group_already_complete( ...
        data, ...
        fields, ...
        m, ...
        nPlanes)

    %#ok<INUSD>

    required_nonempty_fields = { ...
        'stat_by_plane', ...
        'F_gcamp_by_plane', ...
        'gcamp_props_by_plane', ...
        'outlines_gcampx_by_plane', ...
        'outlines_gcampy_by_plane', ...
        'iscell_gcamp_by_plane', ...
        'gcamp_mask_by_plane'};

    tf = ...
        nPlanes > 0;

    for p = 1:nPlanes

        for f = 1:numel(required_nonempty_fields)

            name = ...
                required_nonempty_fields{f};

            if ~local_gcamp_slot_exists( ...
                    data, ...
                    name, ...
                    m, ...
                    p) || ...
                    isempty( ...
                        data.gcamp_plane.(name){m}{p})

                tf = false;
                return;
            end
        end

        % Si des rejected ROIs existent, leurs masks doivent exister.
        % Si stat_false est vide, les champs false vides sont valides.
        if local_gcamp_slot_exists( ...
                data, ...
                'stat_false_by_plane', ...
                m, ...
                p)

            stat_false = ...
                data.gcamp_plane.stat_false_by_plane{m}{p};

        else

            stat_false = [];
        end

        if ~isempty(stat_false)

            required_false_fields = { ...
                'iscell_false_by_plane', ...
                'gcamp_props_false_by_plane', ...
                'outlines_gcampx_false_by_plane', ...
                'outlines_gcampy_false_by_plane', ...
                'gcamp_mask_false_by_plane'};

            for f = 1:numel(required_false_fields)

                name = ...
                    required_false_fields{f};

                if ~local_gcamp_slot_exists( ...
                        data, ...
                        name, ...
                        m, ...
                        p) || ...
                        isempty( ...
                            data.gcamp_plane.(name){m}{p})

                    tf = false;
                    return;
                end
            end
        end
    end
end


