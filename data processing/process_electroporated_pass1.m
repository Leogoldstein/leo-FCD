% GET PLANE PATH
% ========================================================================

function plane_path = get_plane_path( ...
        paths_by_plane, ...
        p)

    plane_path = '';

    if isempty(paths_by_plane) || ...
            ~iscell(paths_by_plane) || ...
            p > numel(paths_by_plane) || ...
            isempty(paths_by_plane{p})

        return;
    end

    candidate = ...
        paths_by_plane{p};

    if ischar(candidate) || ...
            isstring(candidate)

        plane_path = ...
            char(candidate);
    end
end