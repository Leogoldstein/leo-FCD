function [processing_cache, data] = process_electroporated_pass1( ...
    gcamp_output_folders, ...
    include_electroporated, ...
    date_group_paths, ...
    TSeries_paths, ...
    suite2p_folders, ...
    data)

    numFolders = numel(gcamp_output_folders);

    % ==============================================================
    % Colonnes attendues dans TSeries_paths / suite2p_folders
    %
    %   1 = GCaMP
    %   2 = canal potentiel electroporated
    %   3 = canal potentiel electroporated
    %   4 = Green
    %
    % Le canal electroporated est automatiquement choisi comme
    % le premier canal présent parmi les colonnes 2 et 3.
    % ==============================================================

    current_gcamp_folders_group = ...
        get_path_column( ...
            suite2p_folders, ...
            1, ...
            numFolders);

    current_green_folders_group = ...
        get_path_column( ...
            suite2p_folders, ...
            4, ...
            numFolders);

    current_electroporated_TSeries_path = ...
        cell(numFolders, 1);

    current_electroporated_folders_group = ...
        cell(numFolders, 1);

    % ==============================================================
    % Déterminer automatiquement le canal electroporated
    % ==============================================================

    for m = 1:numFolders

        selected_column = [];

        candidate_columns = [2 3];

        for c = candidate_columns

            if m > size(TSeries_paths, 1) || ...
                    c > size(TSeries_paths, 2)

                continue;
            end

            candidate_path = ...
                TSeries_paths{m, c};

            if isempty(candidate_path)
                continue;
            end

            if ischar(candidate_path) || ...
                    isstring(candidate_path)

                candidate_path = ...
                    char(candidate_path);

                if ~isempty(strtrim(candidate_path))

                    selected_column = c;
                    break;
                end
            end
        end

        if isempty(selected_column)

            current_electroporated_TSeries_path{m} = '';
            current_electroporated_folders_group{m} = {};

            fprintf( ...
                'Group %d: no electroporated channel detected.\n', ...
                m);

            continue;
        end

        current_electroporated_TSeries_path{m} = ...
            TSeries_paths{m, selected_column};

        if m <= size(suite2p_folders, 1) && ...
                selected_column <= size(suite2p_folders, 2)

            current_electroporated_folders_group{m} = ...
                suite2p_folders{m, selected_column};

        else

            current_electroporated_folders_group{m} = {};
        end

        fprintf( ...
            ['Group %d: electroporated channel detected ' ...
             'in column %d\n'], ...
            m, ...
            selected_column);
    end

    % ==============================================================
    % Champs electroporated sauvegardés
    % ==============================================================

    fields_electroporated_saved = { ...
        'matched_gcamp_idx_by_plane', ...
        'matched_cellpose_idx_by_plane', ...
        'gcamp_unmatched_idx_by_plane', ...
        'cellpose_unmatched_idx_by_plane', ...
        'num_cells_mask_by_plane', ...
        'mask_cellpose_by_plane', ...
        'props_cellpose_by_plane', ...
        'outlines_x_cellpose_by_plane', ...
        'outlines_y_cellpose_by_plane', ...
        'F_electroporated_by_plane', ...
        'electroporated_match_mask_by_plane'};

    fields_electroporated_memory = { ...
        'ops_suite2p_electroporated_by_plane', ...
        'electroporated_fall_path_by_plane'};

    fields_electroporated_all = [ ...
        fields_electroporated_saved, ...
        fields_electroporated_memory];

    % ==============================================================
    % Champs GCaMP nécessaires
    % ==============================================================

    gcamp_needed = { ...
        'stat_by_plane', ...
        'F_gcamp_by_plane', ...
        'gcamp_props_by_plane', ...
        'outlines_gcampx_by_plane', ...
        'outlines_gcampy_by_plane', ...
        'iscell_gcamp_by_plane', ...
        'gcamp_mask_by_plane', ...
        'gcamp_props_false_by_plane', ...
        'outlines_gcampx_false_by_plane', ...
        'outlines_gcampy_false_by_plane', ...
        'gcamp_mask_false_by_plane'};

    % ==============================================================
    % Initialisation
    % ==============================================================

    data = init_electroporated_plane_struct_if_needed( ...
        data, ...
        numFolders, ...
        fields_electroporated_all);

    data = init_gcamp_plane_struct_if_needed_local( ...
        data, ...
        numFolders, ...
        gcamp_needed);

    processing_cache = ...
        cell(numFolders, 1);

    fprintf('\n============================================================\n');
    fprintf('ELECTROPORATED PASS 1: CELLPOSE PREPARATION\n');
    fprintf('============================================================\n');

    % ==============================================================
    % PASS 1A
    % ==============================================================

    for m = 1:numFolders

        cache = struct();

        cache.valid_group = false;
        cache.skip_group = false;
        cache.nPlanes = 0;

        cache.filePath_electroporated = '';
        cache.filePath_gcamp = '';

        cache.gcamp_planes = {};
        cache.electroporated_planes = {};
        cache.green_planes = {};

        cache.F_gcamp_by_plane = {};
        cache.gcamp_props_by_plane = {};
        cache.iscell_gcamp_by_plane = {};
        cache.gcamp_mask_by_plane = {};
        cache.gcamp_mask_false_by_plane = {};

        cache.has_new_electroporated_data = false;

        cache.planes = {};

        fprintf( ...
            '\nPreparing recording group %d/%d...\n', ...
            m, ...
            numFolders);

        % ==========================================================
        % Output folder
        % ==========================================================

        if m > numel(gcamp_output_folders) || ...
                isempty(gcamp_output_folders{m}) || ...
                ~iscell(gcamp_output_folders{m}) || ...
                isempty(gcamp_output_folders{m}{1})

            fprintf( ...
                'Group %d: invalid output folder, skipped.\n', ...
                m);

            cache.skip_group = true;
            processing_cache{m} = cache;

            continue;
        end

        root_folder_m = ...
            fileparts( ...
                gcamp_output_folders{m}{1});

        % ==========================================================
        % Migration ancien results_blue.mat
        % ==========================================================

        migrate_old_electroporated_results( ...
            root_folder_m);

        cache.filePath_electroporated = ...
            fullfile( ...
                root_folder_m, ...
                'results_electroporated.mat');

        cache.filePath_gcamp = ...
            fullfile( ...
                root_folder_m, ...
                'results_gcamp.mat');

        % ==========================================================
        % GCaMP planes
        % ==========================================================

        if m <= numel(current_gcamp_folders_group)

            cache.gcamp_planes = ...
                current_gcamp_folders_group{m};
        end

        cache.nPlanes = ...
            numel(cache.gcamp_planes);

        if cache.nPlanes == 0

            fprintf( ...
                'Group %d: no GCaMP planes, skipped.\n', ...
                m);

            cache.skip_group = true;
            processing_cache{m} = cache;

            continue;
        end

        % ==========================================================
        % Initialiser slots
        % ==========================================================

        for f = 1:numel(fields_electroporated_all)

            data = ensure_electroporated_plane_cell( ...
                data, ...
                fields_electroporated_all{f}, ...
                m, ...
                cache.nPlanes);
        end

        for f = 1:numel(gcamp_needed)

            data = ensure_local_gcamp_plane_cell( ...
                data, ...
                gcamp_needed{f}, ...
                m, ...
                cache.nPlanes);
        end

        % ==========================================================
        % Chemins electroporated
        % ==========================================================

        for p = 1:cache.nPlanes

            electroporated_path_p = ...
                get_electroporated_plane_folder( ...
                    current_electroporated_folders_group, ...
                    m, ...
                    p);

            if isempty(electroporated_path_p)

                data.electroporated_plane. ...
                    electroporated_fall_path_by_plane{m}{p} = '';

            else

                data.electroporated_plane. ...
                    electroporated_fall_path_by_plane{m}{p} = ...
                    char(electroporated_path_p);
            end
        end

        % ==========================================================
        % Charger results_electroporated
        % ==========================================================

        if ~electroporated_group_already_complete( ...
                data, ...
                m, ...
                cache.nPlanes) && ...
                exist( ...
                    cache.filePath_electroporated, ...
                    'file') == 2

            loaded_electroporated = ...
                load( ...
                    cache.filePath_electroporated);

            loaded_electroporated = ...
                normalize_electroporated_loaded_fields( ...
                    loaded_electroporated);

            data = merge_loaded_electroporated_into_data( ...
                data, ...
                loaded_electroporated, ...
                fields_electroporated_saved, ...
                m, ...
                cache.nPlanes);
        end

        % ==========================================================
        % Charger results_gcamp
        % ==========================================================

        if ~local_gcamp_group_already_complete( ...
                data, ...
                gcamp_needed, ...
                m, ...
                cache.nPlanes) && ...
                exist( ...
                    cache.filePath_gcamp, ...
                    'file') == 2

            loaded_gcamp = ...
                load( ...
                    cache.filePath_gcamp);

            data = merge_loaded_local_gcamp_into_data( ...
                data, ...
                loaded_gcamp, ...
                gcamp_needed, ...
                m, ...
                cache.nPlanes);
        end

        % ==========================================================
        % Processing désactivé
        % ==========================================================

        if include_electroporated ~= 1

            fprintf( ...
                ['Group %d: electroporated processing ' ...
                 'disabled.\n'], ...
                m);

            cache.skip_group = true;
            processing_cache{m} = cache;

            continue;
        end

        % ==========================================================
        % Pas de fluorescence GCaMP
        % ==========================================================

        if ~local_gcamp_group_has_values( ...
                data, ...
                'F_gcamp_by_plane', ...
                m, ...
                cache.nPlanes)

            fprintf( ...
                ['Group %d: no GCaMP fluorescence, ' ...
                 'empty electroporated outputs stored.\n'], ...
                m);

            for p = 1:cache.nPlanes

                if ~electroporated_plane_has_meaningful_content( ...
                        data, ...
                        m, ...
                        p)

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end
            end

            cache.skip_group = true;
            processing_cache{m} = cache;

            continue;
        end

        % ==========================================================
        % Extraire GCaMP
        % ==========================================================

        cache.F_gcamp_by_plane = ...
            coerce_to_plane_cell_local( ...
                data.gcamp_plane.F_gcamp_by_plane{m}, ...
                cache.nPlanes);

        cache.gcamp_props_by_plane = ...
            get_gcamp_field_as_plane_cell( ...
                data, ...
                'gcamp_props_by_plane', ...
                m, ...
                cache.nPlanes);

        cache.iscell_gcamp_by_plane = ...
            get_gcamp_field_as_plane_cell( ...
                data, ...
                'iscell_gcamp_by_plane', ...
                m, ...
                cache.nPlanes);

        cache.gcamp_mask_by_plane = ...
            get_gcamp_field_as_plane_cell( ...
                data, ...
                'gcamp_mask_by_plane', ...
                m, ...
                cache.nPlanes);

        cache.gcamp_mask_false_by_plane = ...
            get_gcamp_field_as_plane_cell( ...
                data, ...
                'gcamp_mask_false_by_plane', ...
                m, ...
                cache.nPlanes);

        % ==========================================================
        % Electroporated / Green planes
        % ==========================================================

        cache.electroporated_planes = ...
            get_group_entry( ...
                current_electroporated_folders_group, ...
                m);

        cache.green_planes = ...
            get_group_entry( ...
                current_green_folders_group, ...
                m);

        % ==========================================================
        % Cache plans
        % ==========================================================

        cache.planes = ...
            cell(cache.nPlanes, 1);

        for p = 1:cache.nPlanes

            cache.planes{p} = struct( ...
                'process_plane', false, ...
                'meanImg_channels', [], ...
                'aligned_image', [], ...
                'npy_file_path', '', ...
                'error_message', '');
        end

        cache.valid_group = true;

        processing_cache{m} = cache;
    end

    % ==============================================================
    % PASS 1B
    % ==============================================================

    for m = 1:numFolders

        cache = ...
            processing_cache{m};

        if cache.skip_group || ...
                ~cache.valid_group

            continue;
        end

        fprintf( ...
            '\nCellpose | Recording group %d/%d | %d planes\n', ...
            m, ...
            numFolders, ...
            cache.nPlanes);

        for p = 1:cache.nPlanes

            fprintf( ...
                '\nCellpose | Group %d/%d | Plane %d/%d\n', ...
                m, ...
                numFolders, ...
                p, ...
                cache.nPlanes);

            % ======================================================
            % Electroporated plane folder
            % ======================================================

            electroporated_plane_folder = ...
                get_electroporated_plane_folder( ...
                    current_electroporated_folders_group, ...
                    m, ...
                    p);

            if isempty(electroporated_plane_folder)

                data.electroporated_plane. ...
                    electroporated_fall_path_by_plane{m}{p} = '';

            else

                data.electroporated_plane. ...
                    electroporated_fall_path_by_plane{m}{p} = ...
                    char(electroporated_plane_folder);
            end

            % ======================================================
            % Ops electroporated
            % ======================================================

            if ~electroporated_plane_slot_exists( ...
                    data, ...
                    'ops_suite2p_electroporated_by_plane', ...
                    m, ...
                    p) || ...
                    isempty( ...
                        data.electroporated_plane. ...
                        ops_suite2p_electroporated_by_plane{m}{p})

                if isempty(electroporated_plane_folder)

                    data.electroporated_plane. ...
                        ops_suite2p_electroporated_by_plane{m}{p} = [];

                else

                    data.electroporated_plane. ...
                        ops_suite2p_electroporated_by_plane{m}{p} = ...
                        load_ops_only( ...
                            electroporated_plane_folder);
                end
            end

            % ======================================================
            % Résultats déjà présents ?
            % ======================================================

            electroporated_results_already_complete = ...
                electroporated_plane_has_meaningful_content( ...
                    data, ...
                    m, ...
                    p);

            if electroporated_results_already_complete

                fprintf( ...
                    ['Plane %d: electroporated ROI results already ' ...
                     'complete. Aligned image will still be loaded.\n'], ...
                    p);
            end

            % ======================================================
            % Vérifier GCaMP
            % ======================================================

            if p > numel(cache.F_gcamp_by_plane) || ...
                    isempty(cache.F_gcamp_by_plane{p})

                fprintf( ...
                    'Plane %d: empty GCaMP fluorescence.\n', ...
                    p);

                if ~electroporated_results_already_complete

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end

                continue;
            end

            if p > numel(cache.gcamp_planes) || ...
                    isempty(cache.gcamp_planes{p})

                fprintf( ...
                    'Plane %d: missing GCaMP folder.\n', ...
                    p);

                if ~electroporated_results_already_complete

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end

                continue;
            end

            % ======================================================
            % TSeries electroporated
            % ======================================================

            current_electroporated_TSeries_path_m = ...
                get_group_entry( ...
                    current_electroporated_TSeries_path, ...
                    m);

            % ======================================================
            % Charger / traiter Cellpose
            % ======================================================

            try

                [ ...
                    meanImg_channels, ...
                    aligned_image_plane, ...
                    npy_file_path, ...
                    ~ ...
                ] = load_or_process_cellpose_TSeries( ...
                    cache.filePath_electroporated, ...
                    date_group_paths{m}, ...
                    get_plane_path(cache.gcamp_planes, p), ...
                    get_plane_path(cache.electroporated_planes, p), ...
                    get_plane_path(cache.green_planes, p), ...
                    current_electroporated_TSeries_path_m, ...
                    get_plane_path(gcamp_output_folders{m}, p));

            catch ME

                warning( ...
                    'process_electroporated_pass1:CellposeFailed', ...
                    ['Group %d plane %d failed while loading ' ...
                     'the aligned image: %s'], ...
                    m, ...
                    p, ...
                    ME.message);

                cache.planes{p}.error_message = ...
                    ME.message;

                if ~electroporated_results_already_complete

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end

                continue;
            end

            % ======================================================
            % Images
            % ======================================================

            cache.planes{p}.meanImg_channels = ...
                meanImg_channels;

            cache.planes{p}.aligned_image = ...
                aligned_image_plane;

            % ======================================================
            % NPY path
            % ======================================================

            if isempty(npy_file_path) || ...
                    ~(ischar(npy_file_path) || ...
                      isstring(npy_file_path))

                fprintf( ...
                    ['Plane %d: invalid or empty NPY path. ' ...
                     'Aligned image was nevertheless stored.\n'], ...
                    p);

                cache.planes{p}.npy_file_path = '';

                if electroporated_results_already_complete

                    cache.planes{p}.process_plane = false;

                else

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end

                continue;
            end

            npy_file_path = ...
                char(npy_file_path);

            cache.planes{p}.npy_file_path = ...
                npy_file_path;

            if exist(npy_file_path, 'file') ~= 2

                fprintf( ...
                    ['Plane %d: NPY not found. ' ...
                     'Aligned image was nevertheless stored:\n%s\n'], ...
                    p, ...
                    npy_file_path);

                if electroporated_results_already_complete

                    cache.planes{p}.process_plane = false;

                else

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end

                continue;
            end

            fprintf( ...
                'Plane %d: Cellpose NPY ready:\n%s\n', ...
                p, ...
                npy_file_path);

            % ======================================================
            % PASS 2 ?
            % ======================================================

            if electroporated_results_already_complete

                cache.planes{p}.process_plane = false;

                fprintf( ...
                    ['Plane %d: aligned image loaded. ' ...
                     'Electroporated ROI extraction remains skipped.\n'], ...
                    p);

            else

                cache.planes{p}.process_plane = true;

                fprintf( ...
                    ['Plane %d: aligned image loaded. ' ...
                     'Electroporated ROI extraction enabled.\n'], ...
                    p);
            end
        end

        processing_cache{m} = ...
            cache;
    end
end


% ========================================================================
% MIGRATION OLD RESULTS
% ========================================================================

function migrate_old_electroporated_results(root_folder)

    old_file = ...
        fullfile( ...
            root_folder, ...
            'results_blue.mat');

    new_file = ...
        fullfile( ...
            root_folder, ...
            'results_electroporated.mat');

    if exist(old_file, 'file') ~= 2
        return;
    end

    if exist(new_file, 'file') ~= 2

        loaded = ...
            load(old_file);

        loaded = ...
            normalize_electroporated_loaded_fields( ...
                loaded);

        save( ...
            new_file, ...
            '-struct', ...
            'loaded', ...
            '-v7.3');

        fprintf( ...
            ['Migrated old electroporated results:\n' ...
             '%s\n'], ...
            new_file);
    end

    if exist(new_file, 'file') == 2

        delete(old_file);

        fprintf( ...
            'Old results file removed.\n');
    end
end


function loaded = normalize_electroporated_loaded_fields(loaded)

    old_names = { ...
        'F_blue_by_plane', ...
        'blue_match_mask_by_plane', ...
        'ops_suite2p_blue_by_plane', ...
        'blue_fall_path_by_plane'};

    new_names = { ...
        'F_electroporated_by_plane', ...
        'electroporated_match_mask_by_plane', ...
        'ops_suite2p_electroporated_by_plane', ...
        'electroporated_fall_path_by_plane'};

    for i = 1:numel(old_names)

        if isfield( ...
                loaded, ...
                old_names{i})

            if ~isfield( ...
                    loaded, ...
                    new_names{i})

                loaded.(new_names{i}) = ...
                    loaded.(old_names{i});
            end

            loaded = ...
                rmfield( ...
                    loaded, ...
                    old_names{i});
        end
    end
end


% ========================================================================
% GET COLUMN
% ========================================================================

function column_data = get_path_column( ...
        paths_matrix, ...
        column_idx, ...
        numFolders)

    column_data = ...
        cell(numFolders, 1);

    if isempty(paths_matrix) || ...
            ~iscell(paths_matrix) || ...
            column_idx > size(paths_matrix, 2)

        return;
    end

    n = ...
        min( ...
            numFolders, ...
            size(paths_matrix, 1));

    column_data(1:n) = ...
        paths_matrix(1:n, column_idx);
end


% ========================================================================
% GROUP ENTRY
% ========================================================================

function out = get_group_entry( ...
        group_cell, ...
        m)

    out = {};

    if isempty(group_cell)
        return;
    end

    if iscell(group_cell)

        if m <= numel(group_cell)

            out = ...
                group_cell{m};
        end

    elseif ischar(group_cell) || ...
            isstring(group_cell)

        out = ...
            char(group_cell);
    end
end


% ========================================================================
% GCAMP FIELD
% ========================================================================

function vals = get_gcamp_field_as_plane_cell( ...
        data, ...
        fieldName, ...
        m, ...
        nPlanes)

    vals = ...
        cell(nPlanes, 1);

    if isfield(data, 'gcamp_plane') && ...
            isfield( ...
                data.gcamp_plane, ...
                fieldName) && ...
            numel( ...
                data.gcamp_plane.(fieldName)) >= m

        vals = ...
            coerce_to_plane_cell_local( ...
                data.gcamp_plane.(fieldName){m}, ...
                nPlanes);
    end
end


% ========================================================================
% ELECTROPORATED GROUP COMPLETE
% ========================================================================

function tf = electroporated_group_already_complete( ...
        data, ...
        m, ...
        nPlanes)

    tf = ...
        nPlanes > 0;

    for p = 1:nPlanes

        if ~electroporated_plane_has_meaningful_content( ...
                data, ...
                m, ...
                p)

            tf = false;
            return;
        end
    end
end


% ========================================================================
% GCAMP GROUP COMPLETE
% ========================================================================

function tf = local_gcamp_group_already_complete( ...
        data, ...
        fields, ...
        m, ...
        nPlanes)

    tf = ...
        nPlanes > 0;

    for p = 1:nPlanes

        for f = 1:numel(fields)

            name = ...
                fields{f};

            if ~local_gcamp_slot_exists( ...
                    data, ...
                    name, ...
                    m, ...
                    p) || ...
                    isempty( ...
                        data.gcamp_plane.(name){m}{p})

                tf = false;
                return;
            end
        end
    end
end


% ========================================================================
% INIT ELECTROPORATED STRUCT
% ========================================================================

function data = init_electroporated_plane_struct_if_needed( ...
        data, ...
        numFolders, ...
        fields)

    if nargin < 1 || ...
            isempty(data)

        data = struct();
    end

    % ==============================================================
    % Migration data.blue_plane déjà présent en mémoire
    % ==============================================================

    if isfield(data, 'blue_plane')

        if ~isfield( ...
                data, ...
                'electroporated_plane') || ...
                ~isstruct( ...
                    data.electroporated_plane)

            data.electroporated_plane = ...
                data.blue_plane;
        end

        data = ...
            rmfield( ...
                data, ...
                'blue_plane');
    end

    if ~isfield( ...
