        end

        if field_needed

            fields_to_load{end + 1} = ...
                name; %#ok<AGROW>
        end
    end
end


% ========================================================================
% GCAMP FIELDS TO LOAD
% ========================================================================

function fields_to_load = get_local_gcamp_fields_to_load_pass1( ...
        data, ...
        fields, ...
        m, ...
        nPlanes)

    fields_to_load = {};

    accepted_required = { ...
        'stat_by_plane', ...
        'F_gcamp_by_plane', ...
        'gcamp_props_by_plane', ...
        'outlines_gcampx_by_plane', ...
        'outlines_gcampy_by_plane', ...
        'iscell_gcamp_by_plane', ...
        'gcamp_mask_by_plane'};

    false_fields = { ...
        'stat_false_by_plane', ...
        'iscell_false_by_plane', ...
        'gcamp_props_false_by_plane', ...
        'outlines_gcampx_false_by_plane', ...
        'outlines_gcampy_false_by_plane', ...
        'gcamp_mask_false_by_plane'};

    for f = 1:numel(fields)

        name = ...
            fields{f};

        field_needed = false;

        if any(strcmp(name, accepted_required))

            for p = 1:nPlanes

                if ~local_gcamp_slot_exists( ...
                        data, ...
                        name, ...
                        m, ...
                        p) || ...
                        isempty( ...
                            data.gcamp_plane.(name){m}{p})

                    field_needed = true;
                    break;
                end
            end

        elseif any(strcmp(name, false_fields))

            % Si stat_false est non vide, les champs false sont requis.
            % Si stat_false est vide, [] est un résultat valide.
            for p = 1:nPlanes

                stat_false = [];

                if local_gcamp_slot_exists( ...
                        data, ...
                        'stat_false_by_plane', ...
                        m, ...
                        p)

                    stat_false = ...
                        data.gcamp_plane.stat_false_by_plane{m}{p};
                end

                if strcmp(name, 'stat_false_by_plane')

                    % On ne peut pas distinguer ici un [] valide d'un []
                    % placeholder créé par l'initialisation. On tente donc
                    % de charger stat_false depuis le fichier uniquement
                    % lorsqu'un autre champ GCaMP indispensable manque.
                    if ~local_gcamp_group_core_complete_pass1( ...
                            data, ...
                            m, ...
                            nPlanes)

                        field_needed = true;
                        break;
                    end

                elseif ~isempty(stat_false)

                    if ~local_gcamp_slot_exists( ...
                            data, ...
                            name, ...
                            m, ...
                            p) || ...
                            isempty( ...
                                data.gcamp_plane.(name){m}{p})

                        field_needed = true;
                        break;
                    end
                end
            end
        end

        if field_needed

            fields_to_load{end + 1} = ...
                name; %#ok<AGROW>
        end
    end
end


