        get_nested_plane_value_pass1( ...
            electroporated_plane. ...
                roi_extraction_npy_signature_by_plane, ...
            m, ...
            p);

    if isempty(saved_signature) || ...
            ~isstruct(saved_signature) || ...
            ~isfield(saved_signature, 'path') || ...
            isempty(saved_signature.path)

        return;
    end

    % ==============================================================
    % Relire directement le fichier NPY correspondant
    % ==============================================================

    current_signature = ...
        get_npy_file_signature_pass1( ...
            saved_signature.path);

    if isempty(current_signature)
        return;
    end

    extraction_is_current = ...
        compare_npy_signatures_pass1( ...
            saved_signature, ...
            current_signature);
end


