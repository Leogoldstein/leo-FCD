% ========================================================================
% FIND EXISTING FINAL CELLPOSE NPY - PASS 1
%
% Recherche non interactive du masque FINAL utilisé pour l'extraction ROI.
%
% Priorité :
%   1) chemin déjà mémorisé dans cellpose_npy_file_path_by_plane ;
%   2) chemin enregistré dans roi_extraction_npy_signature_by_plane ;
%   3) gcamp_reference_*_seg.npy dans le dossier de sortie du plan.
% ========================================================================

function npy_file_path = ...
        find_existing_final_cellpose_npy_pass1( ...
            data, ...
            gcamp_output_folders, ...
            m, ...
            p)

    npy_file_path = '';

    if electroporated_plane_slot_exists( ...
            data, ...
            'cellpose_npy_file_path_by_plane', ...
            m, ...
            p)

        candidate = ...
            data.electroporated_plane. ...
                cellpose_npy_file_path_by_plane{m}{p};

        if (ischar(candidate) || isstring(candidate)) && ...
                ~isempty(candidate) && ...
                isfile(char(candidate))

            npy_file_path = ...
                char(candidate);

            return;
        end
    end

    if isfield(data, 'electroporated_plane') && ...
            isfield( ...
                data.electroporated_plane, ...
                'roi_extraction_npy_signature_by_plane') && ...
            nested_plane_entry_exists_pass1( ...
                data.electroporated_plane. ...
                    roi_extraction_npy_signature_by_plane, ...
                m, ...
                p)

        signature = ...
            get_nested_plane_value_pass1( ...
                data.electroporated_plane. ...
                    roi_extraction_npy_signature_by_plane, ...
                m, ...
                p);

        if isstruct(signature) && ...
                isfield(signature, 'path') && ...
                ~isempty(signature.path) && ...
                isfile(char(string(signature.path)))

            npy_file_path = ...
                char(string(signature.path));

            return;
        end
    end

    output_folder_p = '';

    if iscell(gcamp_output_folders) && ...
            numel(gcamp_output_folders) >= m && ...
            ~isempty(gcamp_output_folders{m})

        folders_m = ...
            gcamp_output_folders{m};

        if iscell(folders_m)

            if numel(folders_m) >= p && ...
                    ~isempty(folders_m{p})

                output_folder_p = ...
                    char(string(folders_m{p}));
            end

        elseif p == 1

            output_folder_p = ...
                char(string(folders_m));
        end
    end

    if isempty(output_folder_p) || ...
            ~isfolder(output_folder_p)

        return;
    end

    candidates = ...
        dir( ...
            fullfile( ...
                output_folder_p, ...
                'gcamp_reference_*_seg.npy'));

    if isempty(candidates)
        return;
    end

    [~, order] = ...
        sort( ...
            [candidates.datenum], ...
            'descend');

    candidate = ...
        fullfile( ...
            candidates(order(1)).folder, ...
            candidates(order(1)).name);

    if isfile(candidate)

        npy_file_path = ...
            candidate;
    end
end


% ========================================================================
% NPY FILE SIGNATURE - PASS 1
% ========================================================================

function signature = ...
        get_npy_file_signature_pass1( ...
            npy_file_path)

    signature = [];

    if isempty(npy_file_path) || ...
            ~(ischar(npy_file_path) || ...
              isstring(npy_file_path))

        return;
    end

    npy_file_path = ...
        char(npy_file_path);

    if ~isfile(npy_file_path)
        return;
    end

    file_info = ...
        dir(npy_file_path);

    if isempty(file_info)
        return;
    end

    signature = struct();

    signature.path = ...
        npy_file_path;

    signature.bytes = ...
        file_info(1).bytes;

    signature.datenum = ...
        file_info(1).datenum;
end


% ========================================================================
% COMPARE NPY SIGNATURES - PASS 1
% ========================================================================

function signatures_match = ...
        compare_npy_signatures_pass1( ...
            saved_signature, ...
            current_signature)

    signatures_match = false;

    if ~isstruct(saved_signature) || ...
            ~isstruct(current_signature)

        return;
    end

    required_fields = { ...
        'path', ...
        'bytes', ...
        'datenum'};

    for k = 1:numel(required_fields)

        field_name = ...
            required_fields{k};

        if ~isfield(saved_signature, field_name) || ...
                ~isfield(current_signature, field_name)

            return;
        end
    end

    saved_path = ...
        char( ...
            string( ...
                saved_signature.path));

    current_path = ...
        char( ...
            string( ...
                current_signature.path));

    same_path = ...
        strcmpi( ...
            saved_path, ...
            current_path);

    same_size = ...
        isequal( ...
            double(saved_signature.bytes), ...
            double(current_signature.bytes));

    saved_date = ...
        double( ...
            saved_signature.datenum);

    current_date = ...
        double( ...
            current_signature.datenum);

    same_date = ...
        isfinite(saved_date) && ...
        isfinite(current_date) && ...
        abs(saved_date - current_date) < 1e-10;

    signatures_match = ...
        same_path && ...
        same_size && ...
        same_date;
end
