function fields_to_load = get_electroporated_fields_to_load_pass1( ...
        data, ...
        fields, ...
        m, ...
        nPlanes)

    fields_to_load = {};

    for f = 1:numel(fields)

        name = ...
            fields{f};

        field_needed = false;

        for p = 1:nPlanes

            plane_completed = ...
                electroporated_completed_marker_true_pass1( ...
                    data, ...
                    m, ...
                    p);

            if ~electroporated_plane_slot_exists( ...
                    data, ...
