function loaded = load_available_variables_pass1( ...
        file_path, ...
        requested_fields)

    loaded = struct();

    if isempty(file_path) || ...
            exist(file_path, 'file') ~= 2 || ...
            isempty(requested_fields)

        return;
    end

    variables_in_file = ...
        whos( ...
            '-file', ...
            file_path);

    if isempty(variables_in_file)
        return;
    end

    variable_names = ...
        {variables_in_file.name};

    fields_to_load = ...
        requested_fields( ...
            ismember( ...
                requested_fields, ...
                variable_names));

    fields_to_load = ...
        unique( ...
            fields_to_load, ...
            'stable');

    if isempty(fields_to_load)
        return;
    end

    loaded = ...
        load( ...
            file_path, ...
            fields_to_load{:});
end


