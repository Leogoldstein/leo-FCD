function [processing_cache, data] = process_electroporated_pass1( ...
    gcamp_root_folders, ...
    gcamp_output_folders, ...
    include_electroporated, ...
    date_group_paths, ...
    TSeries_paths, ...
    suite2p_folders, ...
    metadata, ...
    data, ...
    cellpose_mode)

    if nargin < 9 || isempty(cellpose_mode)
        cellpose_mode = 'interactive';
    end

    include_electroporated_enabled = ...
        is_include_electroporated_enabled_pass1( ...
            include_electroporated);

    numFolders = numel(gcamp_root_folders);

    % ==============================================================
    % Colonnes suite2p
    %
    %   1 = GCaMP
    %   2 = canal potentiel electroporated
    %   3 = canal potentiel electroporated
    %   4 = Green
    % ==============================================================

    current_gcamp_folders_group = ...
        suite2p_folders(:, 1);

    current_green_folders_group = ...
        suite2p_folders(:, 4);

    % ==============================================================
    % Déterminer automatiquement le canal electroporated
    % ==============================================================

    [ ...
        current_electroporated_TSeries_path, ...
        current_electroporated_folders_group, ...
        electroporated_column_by_group ...
    ] = ...
        get_electroporated_channel( ...
            TSeries_paths, ...
            suite2p_folders, ...
            numFolders);

    % ==============================================================
    % Champs electroporated sauvegardés
    % ==============================================================

    fields_electroporated_saved = { ...
        'matched_gcamp_idx_by_plane', ...
        'matched_cellpose_idx_by_plane', ...
        'gcamp_unmatched_idx_by_plane', ...
        'cellpose_unmatched_idx_by_plane', ...
        'num_cells_mask_by_plane', ...
        'mask_cellpose_by_plane', ...
        'props_cellpose_by_plane', ...
        'outlines_x_cellpose_by_plane', ...
        'outlines_y_cellpose_by_plane', ...
        'F_electroporated_by_plane', ...
        'electroporated_match_mask_by_plane', ...
        'roi_extraction_completed_by_plane', ...
        'roi_extraction_npy_signature_by_plane'};

    fields_electroporated_memory = { ...
        'ops_suite2p_electroporated_by_plane', ...
        'electroporated_fall_path_by_plane', ...
        'meanImg_channels_by_plane', ...
        'alignedImgs_electroporated', ...
        'cellpose_npy_file_path_by_plane', ...
        'gcamp_reference_meanImg_by_plane'};

    fields_electroporated_all = [ ...
        fields_electroporated_saved, ...
        fields_electroporated_memory];

    % ==============================================================
    % Champs GCaMP nécessaires
    %
    % stat_false / iscell_false sont inclus pour pouvoir distinguer :
    %   - aucun ROI rejeté -> champs false vides valides
    %   - ROI rejetés présents -> masks false requis
    % ==============================================================

    gcamp_needed = { ...
        'stat_by_plane', ...
        'F_gcamp_by_plane', ...
        'gcamp_props_by_plane', ...
        'outlines_gcampx_by_plane', ...
        'outlines_gcampy_by_plane', ...
        'iscell_gcamp_by_plane', ...
        'gcamp_mask_by_plane', ...
        'stat_false_by_plane', ...
        'iscell_false_by_plane', ...
        'gcamp_props_false_by_plane', ...
        'outlines_gcampx_false_by_plane', ...
        'outlines_gcampy_false_by_plane', ...
        'gcamp_mask_false_by_plane'};

    % ==============================================================
    % Initialisation
    % ==============================================================

    data = init_electroporated_plane_struct_if_needed( ...
        data, ...
        numFolders, ...
        fields_electroporated_all);

    data = init_gcamp_plane_struct_if_needed_local( ...
        data, ...
        numFolders, ...
        gcamp_needed);

    processing_cache = cell(numFolders, 1);

    fprintf('\n============================================================\n');
    fprintf('ELECTROPORATED PASS 1: CELLPOSE PREPARATION\n');
    fprintf('Mode: %s\n', char(string(cellpose_mode)));
    fprintf('============================================================\n');

    % ==============================================================
    % PASS 1A
    % ==============================================================

    for m = 1:numFolders

        cache = struct();

        cache.valid_group = false;
        cache.skip_group = false;
        cache.nPlanes = 0;

        cache.electroporated_column = NaN;

        cache.filePath_electroporated = '';
        cache.filePath_gcamp = '';

        cache.gcamp_planes = {};
        cache.electroporated_planes = {};
        cache.green_planes = {};

        cache.F_gcamp_by_plane = {};
        cache.gcamp_props_by_plane = {};
        cache.iscell_gcamp_by_plane = {};
        cache.gcamp_mask_by_plane = {};
        cache.gcamp_mask_false_by_plane = {};

        cache.has_new_electroporated_data = false;

        % In load_only, this flag tells the outer orchestrator that
        % existing Cellpose / electroporated ROI results are missing or
        % outdated and that a sequential interactive fallback is required.
        cache.requires_processing = false;

        cache.metadata_match = true;
        cache.metadata_mismatch_message = '';

        cache.planes = {};

        fprintf( ...
            '\nPreparing recording group %d/%d...\n', ...
            m, ...
            numFolders);

        % ==========================================================
        % Processing désactivé
        % ==========================================================

        if ~include_electroporated_enabled

            fprintf( ...
                ['Group %d: electroporated processing ' ...
                 'disabled.\n'], ...
                m);

            cache.skip_group = true;
            processing_cache{m} = cache;

            continue;
        end

        % ==========================================================
        % Canal electroporated
        %
        % IMPORTANT :
        % l'absence de canal electroporated Suite2p ne doit PAS
        % provoquer le skip du recording.
        %
        % load_or_process_cellpose_TSeries pourra ensuite chercher :
        %   1) Electroporated TSeries
        %   2) Single images
        % ==========================================================

        cache.electroporated_column = ...
            electroporated_column_by_group(m);

        if ~isfinite(cache.electroporated_column)

            fprintf( ...
                ['Group %d: no electroporated Suite2p channel detected.\n' ...
                 'Continuing with empty electroporated paths.\n' ...
                 'TSeries / Single images will still be checked.\n'], ...
                m);
        end

        % ==========================================================
        % VALIDATE GCAMP / ELECTROPORATED METADATA
        % ==========================================================

        cache.metadata_match = true;
        cache.metadata_mismatch_message = '';

        if isfinite(cache.electroporated_column)

            fields_to_compare = { ...
                'PositionX_um', ...
                'PositionY_um', ...
                'PositionZ', ...
                'OpticalZoom', ...
                'NumPlanes'};

            mismatch_lines = {};

            for f = 1:numel(fields_to_compare)

                field_name = ...
                    fields_to_compare{f};

                gcamp_value = ...
                    metadata.gcamp_plane.(field_name){m};

                electroporated_value = ...
                    metadata.electroporated_plane.(field_name){m};

                if isempty(gcamp_value) || ...
                        isempty(electroporated_value)

                    mismatch_lines{end+1,1} = ...
                        sprintf( ...
                            ['%s:\n' ...
                             '    GCaMP          : %s\n' ...
                             '    Electroporated : %s\n' ...
                             '    Reason         : missing metadata value'], ...
                            field_name, ...
                            mat2str(gcamp_value), ...
                            mat2str(electroporated_value));

                    continue;
                end

                if ~isequal(gcamp_value, electroporated_value)

                    mismatch_lines{end+1,1} = ...
                        sprintf( ...
                            ['%s:\n' ...
                             '    GCaMP          : %s\n' ...
                             '    Electroporated : %s\n' ...
                             '    Reason         : different values'], ...
                            field_name, ...
                            mat2str(gcamp_value), ...
                            mat2str(electroporated_value));
                end
            end

            if ~isempty(mismatch_lines)

                cache.metadata_match = false;

                cache.metadata_mismatch_message = ...
                    strjoin(mismatch_lines, newline);
            end
        end

        % ==========================================================
        % Racine de l'analyse
        % ==========================================================

        root_folder_m = ...
            gcamp_root_folders{m};

        migrate_old_electroporated_results( ...
            root_folder_m);

        cache.filePath_electroporated = ...
            fullfile( ...
                root_folder_m, ...
                'results_electroporated.mat');

        cache.filePath_gcamp = ...
            fullfile( ...
                root_folder_m, ...
                'results_gcamp.mat');

        % ==========================================================
        % Plans GCaMP
        % ==========================================================

        cache.gcamp_planes = ...
            current_gcamp_folders_group{m};

        if ~iscell(cache.gcamp_planes)

            cache.gcamp_planes = ...
                {cache.gcamp_planes};
        end

        cache.nPlanes = ...
            numel(cache.gcamp_planes);

        if cache.nPlanes == 0

            fprintf( ...
                'Group %d: no GCaMP planes, skipped.\n', ...
                m);

            cache.skip_group = true;
            processing_cache{m} = cache;

            continue;
        end

        % ==========================================================
        % Vérification NumPlanes / suite2p
        % ==========================================================

        metadata_nplanes = ...
            metadata.gcamp_plane.NumPlanes{m};

        if cache.nPlanes ~= metadata_nplanes

            warning( ...
                'process_electroporated_pass1:Suite2pPlaneMismatch', ...
                ['Recording group %d skipped.\n' ...
                 'GCaMP suite2p planes : %d\n' ...
                 'GCaMP XML NumPlanes  : %d'], ...
                m, ...
                cache.nPlanes, ...
                metadata_nplanes);

            cache.skip_group = true;
            processing_cache{m} = cache;

            continue;
        end

        % ==========================================================
        % Initialiser slots
        % ==========================================================

        for f = 1:numel(fields_electroporated_all)

            data = ensure_electroporated_plane_cell( ...
                data, ...
                fields_electroporated_all{f}, ...
                m, ...
                cache.nPlanes);
        end

        for f = 1:numel(gcamp_needed)

            data = ensure_local_gcamp_plane_cell( ...
                data, ...
                gcamp_needed{f}, ...
                m, ...
                cache.nPlanes);
        end

        % ==========================================================
        % Plans electroporated
        % ==========================================================

        if ~isfinite(cache.electroporated_column)

            cache.electroporated_planes = ...
                repmat( ...
                    {''}, ...
                    cache.nPlanes, ...
                    1);

        else

            cache.electroporated_planes = ...
                current_electroporated_folders_group{m};

            if ~iscell(cache.electroporated_planes)

                cache.electroporated_planes = ...
                    {cache.electroporated_planes};
            end
        end

        % ==========================================================
        % Plans Green
        % ==========================================================

        cache.green_planes = ...
            current_green_folders_group{m};

        if ~iscell(cache.green_planes)

            cache.green_planes = ...
                {cache.green_planes};
        end

        % ==========================================================
        % Vérifier nombre de plans electroporated AVANT indexation
        % ==========================================================

        if numel(cache.electroporated_planes) ~= cache.nPlanes

            warning( ...
                'process_electroporated_pass1:ElectroporatedPlaneMismatch', ...
                ['Recording group %d skipped.\n' ...
                 'GCaMP suite2p planes         : %d\n' ...
                 'Electroporated suite2p planes: %d'], ...
                m, ...
                cache.nPlanes, ...
                numel(cache.electroporated_planes));

            cache.skip_group = true;
            processing_cache{m} = cache;

            continue;
        end

        % ==========================================================
        % Chemins electroporated
        % ==========================================================

        for p = 1:cache.nPlanes

            data.electroporated_plane. ...
                electroporated_fall_path_by_plane{m}{p} = ...
                cache.electroporated_planes{p};
        end

        % ==========================================================
        % Charger results_electroporated uniquement si data est
        % incomplète.
        %
        % IMPORTANT :
        % roi_extraction_completed_by_plane = true permet de considérer
        % comme valides des sorties vides (par exemple 0 cellule).
        % ==============================================================

        if ~electroporated_group_already_complete( ...
                data, ...
                m, ...
                cache.nPlanes) && ...
                exist( ...
                    cache.filePath_electroporated, ...
                    'file') == 2

            requested_electroporated_fields = ...
                get_electroporated_fields_to_load_pass1( ...
                    data, ...
                    fields_electroporated_saved, ...
                    m, ...
                    cache.nPlanes);

            legacy_fields = { ...
                'F_blue_by_plane', ...
                'blue_match_mask_by_plane'};

            requested_electroporated_fields = ...
                unique( ...
                    [ ...
                        requested_electroporated_fields, ...
                        legacy_fields ...
                    ], ...
                    'stable');

            if ~isempty(requested_electroporated_fields)

                fprintf( ...
                    ['Group %d: loading missing electroporated ' ...
                     'variables from results_electroporated.mat.\n'], ...
                    m);

                loaded_electroporated = ...
                    load_available_variables_pass1( ...
                        cache.filePath_electroporated, ...
                        requested_electroporated_fields);

                loaded_electroporated = ...
                    normalize_electroporated_loaded_fields( ...
                        loaded_electroporated);

                data = merge_loaded_electroporated_into_data( ...
                    data, ...
                    loaded_electroporated, ...
                    fields_electroporated_saved, ...
                    m, ...
                    cache.nPlanes);
            end
        end

        % ==========================================================
        % Charger results_gcamp uniquement si nécessaire.
        % Le fichier complet n'est jamais chargé.
        % ==========================================================

        if ~local_gcamp_group_already_complete( ...
                data, ...
                gcamp_needed, ...
                m, ...
                cache.nPlanes) && ...
                exist( ...
                    cache.filePath_gcamp, ...
                    'file') == 2

            requested_gcamp_fields = ...
                get_local_gcamp_fields_to_load_pass1( ...
                    data, ...
                    gcamp_needed, ...
                    m, ...
                    cache.nPlanes);

            if ~isempty(requested_gcamp_fields)

                fprintf( ...
                    ['Group %d: loading missing GCaMP variables ' ...
                     'from results_gcamp.mat.\n'], ...
                    m);

                loaded_gcamp = ...
                    load_available_variables_pass1( ...
                        cache.filePath_gcamp, ...
                        requested_gcamp_fields);

                data = merge_loaded_local_gcamp_into_data( ...
                    data, ...
                    loaded_gcamp, ...
                    gcamp_needed, ...
                    m, ...
                    cache.nPlanes);
            end
        end

        % ==========================================================
        % Pas de fluorescence GCaMP
        % ==========================================================

        if ~local_gcamp_group_has_values( ...
                data, ...
                'F_gcamp_by_plane', ...
                m, ...
                cache.nPlanes)

            fprintf( ...
                ['Group %d: no GCaMP fluorescence, ' ...
                 'empty electroporated outputs stored.\n'], ...
                m);

            for p = 1:cache.nPlanes

                if ~electroporated_plane_has_meaningful_content( ...
                        data, ...
                        m, ...
                        p)

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end
            end

            cache.skip_group = true;
            processing_cache{m} = cache;

            continue;
        end

        % ==========================================================
        % Extraire GCaMP
        % ==========================================================

        cache.F_gcamp_by_plane = ...
            coerce_to_plane_cell_local( ...
                data.gcamp_plane.F_gcamp_by_plane{m}, ...
                cache.nPlanes);

        cache.gcamp_props_by_plane = ...
            get_gcamp_field_as_plane_cell( ...
                data, ...
                'gcamp_props_by_plane', ...
                m, ...
                cache.nPlanes);

        cache.iscell_gcamp_by_plane = ...
            get_gcamp_field_as_plane_cell( ...
                data, ...
                'iscell_gcamp_by_plane', ...
                m, ...
                cache.nPlanes);

        cache.gcamp_mask_by_plane = ...
            get_gcamp_field_as_plane_cell( ...
                data, ...
                'gcamp_mask_by_plane', ...
                m, ...
                cache.nPlanes);

        cache.gcamp_mask_false_by_plane = ...
            get_gcamp_field_as_plane_cell( ...
                data, ...
                'gcamp_mask_false_by_plane', ...
                m, ...
                cache.nPlanes);

        % ==========================================================
        % Cache plans
        % ==========================================================

        cache.planes = ...
            cell(cache.nPlanes, 1);

        for p = 1:cache.nPlanes

            cache.planes{p} = struct( ...
                'process_plane', false, ...
                'requires_roi_extraction', false, ...
                'meanImg_channels', [], ...
                'aligned_image', [], ...
                'npy_file_path', '', ...
                'gcamp_reference_meanImg', [], ...
                'clear_electroporated_outputs_requested', false, ...
                'metadata_match', cache.metadata_match, ...
                'metadata_mismatch_message', ...
                    cache.metadata_mismatch_message, ...
                'error_message', '');
        end

        cache.valid_group = true;

        processing_cache{m} = cache;
    end

    % ==============================================================
    % PASS 1B
    % ==============================================================

    for m = 1:numFolders

        cache = ...
            processing_cache{m};

        if isempty(cache) || ...
                cache.skip_group || ...
                ~cache.valid_group

            continue;
        end

        % ==========================================================
        % TSeries Electroporated
        % ==========================================================

        if numel(current_electroporated_TSeries_path) >= m

            current_electroporated_TSeries_path_m = ...
                current_electroporated_TSeries_path{m};

        else

            current_electroporated_TSeries_path_m = '';
        end

        % ==========================================================
        % LOAD ONLY
        %
        % IMPORTANT:
        %   load_only ne se contente plus de regarder si les nouveaux
        %   champs de results_electroporated.mat existent.
        %
        %   Pour chaque plan on recherche aussi le masque Cellpose final
        %   réellement présent sur disque :
        %
        %       1) cellpose_npy_file_path_by_plane déjà en mémoire
        %       2) chemin mémorisé dans la signature ROI
        %       3) gcamp_reference_*_seg.npy dans le dossier de sortie
        %
        %   Si un masque final existe :
        %       - aucun fallback interactif n'est demandé ;
        %       - si l'extraction ROI est ancienne/incomplète, PASS 2 la
        %         recalculera automatiquement.
        %
        %   Le fallback séquentiel n'est demandé QUE lorsqu'aucun masque
        %   Cellpose final exploitable n'existe réellement.
        % ==========================================================

        if strcmpi(cellpose_mode, 'load_only')

            fprintf('\n');
            fprintf('============================================================\n');
            fprintf('ELECTROPORATED LOAD ONLY\n');
            fprintf('Recording group: %d/%d\n', m, numFolders);
            fprintf('============================================================\n');

            cache.requires_processing = ...
                false;

            % ------------------------------------------------------
            % IMPORTANT : en load_only, un mismatch de metadata est
            % informatif uniquement. Il ne doit JAMAIS provoquer un
            % fallback hors du PARFOR.
            %
            % Le seul critere qui peut demander le fallback
            % process_missing est l'absence reelle d'un masque Cellpose
            % final exploitable pour au moins un plan.
            % ------------------------------------------------------
            if ~cache.metadata_match

                warning( ...
                    'process_electroporated_pass1:MetadataMismatchLoadOnly', ...
                    ['GCaMP / Electroporated metadata mismatch for group %d.\n' ...
                     '%s\n' ...
                     'LOAD_ONLY: warning only; processing continues in the PARFOR.\n' ...
                     'This mismatch does not trigger process_missing.\n' ...
                     'Only a genuinely missing final Cellpose mask can do so.'], ...
                    m, ...
                    cache.metadata_mismatch_message);
            end

            for p = 1:cache.nPlanes

                cache.planes{p}.process_plane = ...
                    false;

                cache.planes{p}.requires_roi_extraction = ...
                    false;

                if electroporated_plane_slot_exists( ...
                        data, ...
                        'alignedImgs_electroporated', ...
                        m, ...
                        p)

                    cache.planes{p}.aligned_image = ...
                        data.electroporated_plane. ...
                            alignedImgs_electroporated{m}{p};

                else

                    cache.planes{p}.aligned_image = [];
                end

                existing_npy_file = ...
                    find_existing_final_cellpose_npy_pass1( ...
                        data, ...
                        gcamp_output_folders, ...
                        m, ...
                        p);

                if isempty(existing_npy_file)

                    fprintf( ...
                        ['Plane %d: no final GCaMP/Cellpose mask was found.\n' ...
                         'Sequential processing will be required only for ' ...
                         'this missing detection.\n'], ...
                        p);

                    cache.requires_processing = ...
                        true;

                    continue;
                end

                fprintf( ...
                    'Plane %d: existing final Cellpose masks found:\n%s\n', ...
                    p, ...
                    existing_npy_file);

                cache.planes{p}.npy_file_path = ...
                    existing_npy_file;

                data.electroporated_plane. ...
                    cellpose_npy_file_path_by_plane{m}{p} = ...
                    existing_npy_file;

                extraction_is_current = ...
                    is_electroporated_roi_extraction_current_pass1( ...
                        data, ...
                        m, ...
                        p, ...
                        existing_npy_file);

                if extraction_is_current

                    fprintf( ...
                        ['Plane %d: ROI extraction already complete and ' ...
                         'current.\n'], ...
                        p);

                else

                    fprintf( ...
                        ['Plane %d: masks already exist; ROI extraction is ' ...
                         'missing/outdated and will be rebuilt automatically.\n'], ...
                        p);

                    cache.planes{p}.process_plane = ...
                        true;

                    cache.planes{p}.requires_roi_extraction = ...
                        true;
                end
            end

            processing_cache{m} = ...
                cache;

            continue;
        end

        % ==========================================================
        % MODE INTERACTIF NORMAL
        % ==========================================================

        current_gcamp_TSeries_path_m = ...
            TSeries_paths{m, 1};

        fprintf( ...
            'GCaMP TSeries          : %s\n', ...
            current_gcamp_TSeries_path_m);

        fprintf( ...
            'Electroporated TSeries : %s\n', ...
            current_electroporated_TSeries_path_m);

        % ==========================================================
        % METADATA MISMATCH
        % ==========================================================

        if ~cache.metadata_match

            % ------------------------------------------------------
            % process_missing est le fallback interne du LOAD_ONLY.
            % Un mismatch ne doit donc pas demander d'interaction et
            % ne doit pas interrompre le traitement. Le fallback a ete
            % demande pour une vraie donnee manquante, pas pour le
            % mismatch lui-meme.
            % ------------------------------------------------------
            if strcmpi(cellpose_mode, 'process_missing')

                warning( ...
                    'process_electroporated_pass1:MetadataMismatchProcessMissing', ...
                    ['GCaMP / Electroporated metadata mismatch for group %d.\n' ...
                     '%s\n' ...
                     'PROCESS_MISSING: warning only; continuing automatically.'], ...
                    m, ...
                    cache.metadata_mismatch_message);

            else

                existing_results_are_complete_and_current = ...
                    electroporated_group_results_complete_and_current_pass1( ...
                        data, ...
                        m, ...
                        cache.nPlanes);

                if existing_results_are_complete_and_current

                    warning( ...
                        'process_electroporated_pass1:MetadataMismatch', ...
                        ['============================================================\n' ...
                         'GCaMP / ELECTROPORATED METADATA MISMATCH\n' ...
                         '============================================================\n\n' ...
                         '%s\n\n' ...
                         'GCaMP and electroporated metadata do not match.\n\n' ...
                         'Existing electroporated results are complete and up to date.\n' ...
                         'Existing results retained.\n' ...
                         'The existing aligned image will still be loaded.'], ...
                        cache.metadata_mismatch_message);

                    input( ...
                        '\nPress Enter to continue.\n', ...
                        's');

                    fprintf( ...
                        ['Continuing in order to load / check the existing ' ...
                         'aligned image.\n']);

                else

                    choice = input( ...
                        sprintf([ ...
                            '\n============================================================\n' ...
                            'GCaMP / ELECTROPORATED METADATA MISMATCH\n' ...
                            '============================================================\n\n' ...
                            '%s\n\n' ...
                            'GCaMP and electroporated metadata do not match.\n\n' ...
                            'Press 1 to continue with alignment / Cellpose anyway.\n' ...
                            'Press 0 to keep existing data and skip this recording.\n> '], ...
                            cache.metadata_mismatch_message), ...
                        's');

                    user_accepted_metadata_mismatch = ...
                        strcmp(strtrim(choice), '1');

                    if ~user_accepted_metadata_mismatch

                        fprintf( ...
                            ['Existing results retained.\n' ...
                             'Cellpose/alignment skipped.\n']);

                        for p = 1:cache.nPlanes

                            cache.planes{p}.process_plane = false;
                            cache.planes{p}.requires_roi_extraction = false;
                        end

                        processing_cache{m} = ...
                            cache;

                        continue;
                    end

                    fprintf( ...
                        ['Metadata mismatch accepted. ' ...
                         'Continuing with alignment / Cellpose.\n']);
                end
            end
        end

        % ==========================================================
        % Plans
        % ==========================================================

        for p = 1:cache.nPlanes

            fprintf( ...
                '\nCellpose | Date %d/%d | Plane %d/%d\n', ...
                m, ...
                numFolders, ...
                p, ...
                cache.nPlanes);

            electroporated_plane_folder = ...
                cache.electroporated_planes{p};

            data.electroporated_plane. ...
                electroporated_fall_path_by_plane{m}{p} = ...
                electroporated_plane_folder;

            % ======================================================
            % Ops electroporated
            % ======================================================

            if ~electroporated_plane_slot_exists( ...
                    data, ...
                    'ops_suite2p_electroporated_by_plane', ...
                    m, ...
                    p) || ...
                    isempty( ...
                        data.electroporated_plane. ...
                        ops_suite2p_electroporated_by_plane{m}{p})

                if isempty(electroporated_plane_folder)

                    data.electroporated_plane. ...
                        ops_suite2p_electroporated_by_plane{m}{p} = [];

                else

                    data.electroporated_plane. ...
                        ops_suite2p_electroporated_by_plane{m}{p} = ...
                        load_ops_only( ...
                            electroporated_plane_folder);
                end
            end

            electroporated_results_already_complete = ...
                electroporated_plane_has_meaningful_content( ...
                    data, ...
                    m, ...
                    p);

            if electroporated_results_already_complete

                fprintf( ...
                    ['Plane %d: electroporated ROI results already ' ...
                     'complete. Aligned image will still be loaded.\n'], ...
                    p);
            end

            % ======================================================
            % GCaMP
            % ======================================================

            if isempty(cache.F_gcamp_by_plane{p})

                fprintf( ...
                    'Plane %d: empty GCaMP fluorescence.\n', ...
                    p);

                if ~electroporated_results_already_complete

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end

                continue;
            end

            if isempty(cache.gcamp_planes{p})

                fprintf( ...
                    'Plane %d: missing GCaMP folder.\n', ...
                    p);

                if ~electroporated_results_already_complete

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end

                continue;
            end

            % ======================================================
            % Output folder plan
            % ======================================================

            output_folders_m = ...
                gcamp_output_folders{m};

            if iscell(output_folders_m)

                output_folder_p = ...
                    output_folders_m{p};

            else

                output_folder_p = ...
                    output_folders_m;
            end

            % ======================================================
            % Green
            % ======================================================

            if isempty(cache.green_planes)

                green_plane_folder = '';

            elseif numel(cache.green_planes) >= p

                green_plane_folder = ...
                    cache.green_planes{p};

            else

                green_plane_folder = '';
            end

            % ======================================================
            % Cellpose
            % ======================================================

            try

                [ ...
                    meanImg_channels, ...
                    aligned_image_plane, ...
                    npy_file_path, ...
                    gcamp_reference_meanImg, ...
                    clear_electroporated_outputs_requested ...
                ] = ...
                    load_or_process_cellpose_TSeries( ...
                        cache.filePath_electroporated, ...
                        date_group_paths{m}, ...
                        cache.gcamp_planes{p}, ...
                        cache.electroporated_planes{p}, ...
                        green_plane_folder, ...
                        current_electroporated_TSeries_path_m, ...
                        output_folder_p, ...
                        cellpose_mode);

            catch ME

                warning( ...
                    'process_electroporated_pass1:CellposeFailed', ...
                    ['Group %d plane %d failed while loading ' ...
                     'the aligned image: %s'], ...
                    m, ...
                    p, ...
                    ME.message);

                cache.planes{p}.error_message = ...
                    ME.message;

                if ~electroporated_results_already_complete

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end

                continue;
            end

            % ======================================================
            % Store outputs
            % ======================================================

            cache.planes{p}.meanImg_channels = ...
                meanImg_channels;

            cache.planes{p}.aligned_image = ...
                aligned_image_plane;

            cache.planes{p}.npy_file_path = ...
                npy_file_path;

            cache.planes{p}.gcamp_reference_meanImg = ...
                gcamp_reference_meanImg;

            data.electroporated_plane. ...
                meanImg_channels_by_plane{m}{p} = ...
                meanImg_channels;

            data.electroporated_plane. ...
                alignedImgs_electroporated{m}{p} = ...
                aligned_image_plane;

            data.electroporated_plane. ...
                cellpose_npy_file_path_by_plane{m}{p} = ...
                npy_file_path;

            data.electroporated_plane. ...
                gcamp_reference_meanImg_by_plane{m}{p} = ...
                gcamp_reference_meanImg;

            cache.planes{p}.clear_electroporated_outputs_requested = ...
                clear_electroporated_outputs_requested;

            cache.planes{p}.metadata_match = ...
                cache.metadata_match;

            cache.planes{p}.metadata_mismatch_message = ...
                cache.metadata_mismatch_message;

            % ======================================================
            % NPY
            % ======================================================

            if isempty(npy_file_path)

                fprintf( ...
                    ['Plane %d: empty NPY path. ' ...
                     'Aligned image was nevertheless stored.\n'], ...
                    p);

                if electroporated_results_already_complete

                    cache.planes{p}.process_plane = false;

                else

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end

                continue;
            end

            if exist(npy_file_path, 'file') ~= 2

                fprintf( ...
                    ['Plane %d: NPY not found. ' ...
                     'Aligned image was nevertheless stored:\n%s\n'], ...
                    p, ...
                    npy_file_path);

                if electroporated_results_already_complete

                    cache.planes{p}.process_plane = false;

                else

                    data = set_empty_electroporated_plane( ...
                        data, ...
                        m, ...
                        p);

                    cache.has_new_electroporated_data = true;
                end

                continue;
            end

            fprintf( ...
                'Plane %d: Cellpose NPY ready:\n%s\n', ...
                p, ...
                npy_file_path);

            % ======================================================
            % Extraction actuelle ?
            % ======================================================

            extraction_is_current = ...
                is_electroporated_roi_extraction_current_pass1( ...
                    data, ...
                    m, ...
                    p, ...
                    npy_file_path);

            if extraction_is_current

                cache.planes{p}.process_plane = false;

                cache.planes{p}.requires_roi_extraction = false;

                fprintf( ...
                    ['Plane %d: electroporated ROI extraction already ' ...
                     'up to date. Existing results retained.\n'], ...
                    p);

                continue;
            end

            cache.planes{p}.requires_roi_extraction = true;
            cache.planes{p}.process_plane = true;

            fprintf( ...
                ['Plane %d: electroporated ROI extraction ' ...
                 'required.\n'], ...
                p);
        end

        processing_cache{m} = ...
            cache;
    end
end


