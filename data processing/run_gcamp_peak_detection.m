            'electroporated_plane', ...
            'selection_summary_electroporated_by_plane', ...
            m, ...
            p);

    if isstruct(summary_electroporated)

        summary_electroporated.comment = ...
            comment_value;

        data.electroporated_plane. ...
            selection_summary_electroporated_by_plane{m}{p} = ...
            summary_electroporated;

        save_selection_summary_plane( ...
            filePath_electroporated, ...
            'selection_summary_electroporated_by_plane', ...
            summary_electroporated, ...
            p, ...
            nPlanes);
    end
end

function save_branch_plane_fields( ...
        filePath, ...
        data, ...
        branchName, ...
        saveFields, ...
        m, ...
        p, ...
        nPlanes)

    % ==========================================================
    % Save only detection variables, never load the entire results file.
    % Other variables in results_*.mat (raw fluorescence, masks, etc.)
    % remain untouched.
    % ==========================================================

    if isempty(filePath)
        return;
    end

    outdir = ...
        fileparts(filePath);

    if exist(outdir, 'dir') ~= 7
        mkdir(outdir);
    end

    existing = ...
        struct();

    if exist(filePath, 'file') == 2

        existing = ...
            load_available_variables_peak_detection( ...
                filePath, ...
                saveFields);
    end

    saveStruct = ...
        struct();

    for k = 1:numel(saveFields)

        fieldName = ...
            saveFields{k};

        if ~isfield(data, branchName) || ...
                ~isfield(data.(branchName), fieldName) || ...
                numel(data.(branchName).(fieldName)) < m || ...
                isempty(data.(branchName).(fieldName){m}) || ...
                ~iscell(data.(branchName).(fieldName){m}) || ...
                numel(data.(branchName).(fieldName){m}) < p

            continue;
        end

        newValue = ...
            data.(branchName).(fieldName){m}{p};

        if isfield(existing, fieldName)

            oldField = ...
                existing.(fieldName);

            if iscell(oldField)

                planeValues = ...
                    oldField(:);

            elseif nPlanes == 1

                planeValues = ...
                    {oldField};

            else

                planeValues = ...
                    cell(nPlanes,1);
            end

        else

            planeValues = ...
                cell(nPlanes,1);
        end

        if numel(planeValues) < nPlanes

            oldValues = ...
                planeValues;

            planeValues = ...
                cell(nPlanes,1);

            planeValues(1:numel(oldValues)) = ...
                oldValues(:);

        elseif numel(planeValues) > nPlanes

            planeValues = ...
                planeValues(1:nPlanes);
        end

        planeValues{p} = ...
            newValue;

        saveStruct.(fieldName) = ...
            planeValues;
    end

    if isempty(fieldnames(saveStruct))
        return;
    end

    if exist(filePath, 'file') == 2

        save( ...
            filePath, ...
            '-struct', ...
            'saveStruct', ...
            '-append');

    else

        save( ...
            filePath, ...
            '-struct', ...
            'saveStruct');
    end
end

