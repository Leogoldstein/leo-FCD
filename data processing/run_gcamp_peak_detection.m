function data = sanitize_record_selection_summaries( ...
        data,m,nPlanes,processCombined)

    branches = {'gcamp'};
    if processCombined
        branches = {'gcamp','electroporated','combined'};
    end

    for bb = 1:numel(branches)
        name = branches{bb};
        branch = [name '_plane'];
        fieldName = ['selection_summary_' name '_by_plane'];
        if ~isfield(data,branch) || ~isstruct(data.(branch)) || ...
                ~isfield(data.(branch),fieldName) || ...
                ~iscell(data.(branch).(fieldName)) || ...
                numel(data.(branch).(fieldName)) < m || ...
                ~iscell(data.(branch).(fieldName){m})
            continue;
        end
        nAvailable = min(nPlanes,numel(data.(branch).(fieldName){m}));
        for pp = 1:nAvailable
            data.(branch).(fieldName){m}{pp} = ...
                strip_selection_summary_temporal_fields( ...
                    data.(branch).(fieldName){m}{pp});
        end
    end
end

function [summary,migrated] = normalize_selection_summary_run(old_summary,nCells)
    % Migration des anciens selection_summary vers le format minimal.
    % manual_status est conservé si sa taille correspond au référentiel.
    if nargin < 2 || isempty(nCells) || ~isscalar(nCells) || ...
            ~isfinite(nCells) || nCells < 0
        nCells = 0;
    end
    nCells = round(double(nCells));

    if ~isstruct(old_summary) || isempty(old_summary) || ...
            isempty(fieldnames(old_summary))
        summary = struct();
        migrated = false;
        return;
    end

    manual_status = zeros(nCells,1);
    cutoff_status = zeros(nCells,1);
    effective_status = zeros(nCells,1);

    if isfield(old_summary,'manual_status') && ...
            numel(old_summary.manual_status) == nCells
        tmp = double(old_summary.manual_status(:));
        ok = isfinite(tmp) & ismember(tmp,[-1 0 1]);
        manual_status(ok) = tmp(ok);
        if ~all(ok)
            warning('run_gcamp_peak_detection:InvalidLegacyManualStatus', ...
                'Ancien manual_status : valeurs invalides remises à 0.');
        end
    elseif isfield(old_summary,'manual_status') && ...
            ~isempty(old_summary.manual_status) && nCells > 0

        % Ancien summary construit dans un referentiel cellulaire different
        % (typiquement des donnees anciennement filtrees/croppees).
        % Les indices ne peuvent pas etre remappes de facon fiable :
        % abandonner uniquement les anciennes decisions manuelles et
        % repartir avec un statut neutre dans le referentiel complet.
        warning('run_gcamp_peak_detection:LegacyManualStatusSizeMismatch', ...
            ['Ancien manual_status incompatible (%d cellules) avec le ' ...
             'referentiel actuel (%d cellules) : anciennes decisions ' ...
             'manuelles ecrasees et manual_status reinitialise a 0.'], ...
            numel(old_summary.manual_status),nCells);

        manual_status = zeros(nCells,1);
    end

    if isfield(old_summary,'cutoff_status') && ...
            numel(old_summary.cutoff_status) == nCells
        tmp = double(old_summary.cutoff_status(:));
        ok = isfinite(tmp) & ismember(tmp,[-1 0 1]);
        cutoff_status(ok) = tmp(ok);
    end

    if isfield(old_summary,'effective_status') && ...
            numel(old_summary.effective_status) == nCells
        tmp = double(old_summary.effective_status(:));
        ok = isfinite(tmp) & ismember(tmp,[-1 0 1]);
        effective_status(ok) = tmp(ok);
    elseif isfield(old_summary,'valid_cells') && nCells > 0
        ids = round(double(old_summary.valid_cells(:)));
        ids = unique(ids(isfinite(ids) & ids>=1 & ids<=nCells),'stable');
        effective_status = -ones(nCells,1);
        effective_status(ids) = +1;
    else
        effective_status = -ones(nCells,1);
        effective_status(cutoff_status == +1) = +1;
        effective_status(manual_status == +1) = +1;
        effective_status(manual_status == -1) = -1;
    end

    summary = struct();
    summary.manual_status = manual_status;
    summary.cutoff_status = cutoff_status;
    summary.effective_status = effective_status;
    if isfield(old_summary,'comment')
        summary.comment = old_summary.comment;
    else
        summary.comment = '';
    end

    migrated = ~isequaln(old_summary,summary);
end

function value = strip_selection_summary_temporal_fields(value)
    % selection_summary ne contient que l'état persistant de sélection.
    % Les anciens champs de stockage temporel et ceux dépendant de la
    % population affichée sont supprimés à chaque chargement/sauvegarde.
    obsolete = {'include_stims','results_include_stims', ...
        'data_include_stims','n_frames_full','n_frames_saved', ...
        'n_frames_data','selected_signal','active_indices', ...
        'comment_modified','recording_keep_modified'};

    if iscell(value)
        for ii = 1:numel(value)
            value{ii} = ...
                strip_selection_summary_temporal_fields(value{ii});
        end
    elseif isstruct(value)
        fields = intersect(fieldnames(value),obsolete);
        if ~isempty(fields)
            value = rmfield(value,fields);
        end
    end
end

function data = filter_detection_data_to_valid_cells( ...
        data,m,p,processCombined)

    if processCombined
        names = {'gcamp','electroporated','combined'};
    else
        names = {'gcamp'};
    end

    matrix_suffixes = {'F0','DF','DF_raw','Raster'};
    vector_suffixes = {'noise_est','Acttmp2','thresholds'};

    for bb = 1:numel(names)
        name = names{bb};
        branch = [name '_plane'];

        validName = ['valid_' name '_cells_by_plane'];
        valid = get_branch_plane_or_empty(data,branch,validName,m,p);
        valid = round(double(valid(:)));
        valid = valid(isfinite(valid) & valid>=1);
        valid = unique(valid,'stable');

        % ======================================================
        % IMPORTANT
        % ======================================================
        % A ce stade, Combined a deja ete reconstruit vers les branches
        % GCaMP / Electroporated. Les champs F_gcamp_by_plane et
        % F_electroporated_by_plane peuvent provenir d'un ancien
        % referentiel et ne doivent donc PAS servir a determiner le nombre
        % de cellules originales de la branche.
        %
        % Chaque matrice de detection porte elle-meme son referentiel :
        %   - si son nombre de cellules == numel(valid), elle est deja
        %     filtree ;
        %   - sinon, si les indices valid sont compatibles avec sa taille,
        %     elle est encore complete et on la filtre directement ;
        %   - aucun nOriginal externe n'est necessaire.
        % ======================================================

        % Matrices [cellules x temps].
        for kk = 1:numel(matrix_suffixes)
            fieldName = [matrix_suffixes{kk} '_' name '_by_plane'];
            X = get_branch_plane_or_empty(data,branch,fieldName,m,p);
            if isempty(X)
                continue;
            end

            nRows = size(X,1);

            if isempty(valid)
                data.(branch).(fieldName){m}{p} = X([],:);
                continue;
            end

            % Deja filtre : ne surtout pas filtrer une seconde fois avec
            % des indices exprimes dans le referentiel original.
            if nRows == numel(valid)
                continue;
            end

            % Matrice complete dans le referentiel local de la population.
            if max(valid) <= nRows
                data.(branch).(fieldName){m}{p} = X(valid,:);
            else
                warning('run_gcamp_peak_detection:InvalidValidCells', ...
                    ['%s : %s contient %d lignes mais valid_cells atteint ' ...
                     'l''indice %d. Champ laisse inchange.'], ...
                    branch,fieldName,nRows,max(valid));
            end
        end

        % Vecteurs/cell arrays indexes par cellule.
        for kk = 1:numel(vector_suffixes)
            fieldName = [vector_suffixes{kk} '_' name '_by_plane'];
            X = get_branch_plane_or_empty(data,branch,fieldName,m,p);
            if isempty(X)
                continue;
            end

            nRows = numel(X);

            if isempty(valid)
                X = X([]);
                if iscell(X) || iscolumn(X)
                    X = X(:);
                end
                data.(branch).(fieldName){m}{p} = X;
                continue;
            end

            % Deja filtre.
            if nRows == numel(valid)
                continue;
            end

            % Vecteur complet dans le referentiel local de la population.
            if max(valid) <= nRows
                X = X(valid);
                if iscell(X) || iscolumn(X)
                    X = X(:);
                end
                data.(branch).(fieldName){m}{p} = X;
            else
                warning('run_gcamp_peak_detection:InvalidValidCells', ...
                    ['%s : %s contient %d elements mais valid_cells atteint ' ...
                     'l''indice %d. Champ laisse inchange.'], ...
                    branch,fieldName,nRows,max(valid));
            end
        end
    end
end


function [data, reloaded] = restore_viewer_motion_from_results( ...
        data, ...
        m, ...
        p, ...
        filePathMotion, ...
        viewerMotionFields)

    reloaded = false;

    if isempty(filePathMotion) || ...
            exist(filePathMotion,'file') ~= 2 || ...
            isempty(viewerMotionFields)

        return;
    end

    loaded = ...
        load_available_variables_peak_detection( ...
            filePathMotion, ...
            viewerMotionFields);

    if isempty(fieldnames(loaded))
        return;
    end

    if ~isfield(data,'motion') || ...
            ~isstruct(data.motion)

        data.motion = struct();
    end

    reloaded_fields = {};


    % ==========================================================
    % CHAMPS PAR PLAN : deviation / bad_segs
    % ==========================================================

    plane_fields = { ...
        'deviation_group', ...
        'bad_segs_group'};

    for k = 1:numel(plane_fields)

        fieldName = ...
            plane_fields{k};

        if ~isfield(loaded,fieldName)
            continue;
        end

        full_value = ...
            get_loaded_motion_plane_value( ...
                loaded.(fieldName), ...
                p);

        current_value = ...
            get_motion_plane_or_empty( ...
                data, ...
                fieldName, ...
                m, ...
                p);

        if ~viewer_motion_value_is_cropped( ...
                current_value, ...
                full_value, ...
                fieldName)

            continue;
        end

        data = ...
            set_motion_plane_value( ...
                data, ...
                fieldName, ...
                m, ...
                p, ...
                full_value);

        reloaded_fields{end+1} = ...
            fieldName; %#ok<AGROW>
    end


    % ==========================================================
    % CHAMPS GLOBAUX : motion_energy / speed_active
    % ==========================================================

    group_fields = { ...
        'motion_energy_group', ...
        'speed_active_group'};

    for k = 1:numel(group_fields)

        fieldName = ...
            group_fields{k};

        if ~isfield(loaded,fieldName)
            continue;
        end

        full_value = ...
            loaded.(fieldName);

        current_value = ...
            get_motion_group_or_empty( ...
                data, ...
                fieldName, ...
                m);

        if ~viewer_motion_value_is_cropped( ...
                current_value, ...
                full_value, ...
                fieldName)

            continue;
        end

        data = ...
            set_motion_group_value( ...
                data, ...
                fieldName, ...
                m, ...
                full_value);

        reloaded_fields{end+1} = ...
            fieldName; %#ok<AGROW>
    end


    reloaded = ...
        ~isempty(reloaded_fields);

    if reloaded

        fprintf( ...
            ['Viewer - plane %d : motion croppee rechargee depuis ' ...
             'results_motion.mat (%s).\n'], ...
            p-1, ...
            strjoin( ...
                unique(reloaded_fields,'stable'), ...
                ', '));
    end
end


function value = get_loaded_motion_plane_value( ...
        loadedGroup, ...
