            if viewer_mode
            
                % ==========================================================
                % En viewer, les données sauvegardées DF/F0/Raster/etc.
                % ne contiennent QUE les cellules qui avaient été validées.
                %
                % Il faut donc réduire F aux mêmes cellules pour que :
