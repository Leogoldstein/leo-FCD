function data = run_gcamp_peak_detection( ...
    current_type, ...
    current_line, ...
    animal, ...
    current_ages, ...
    gcamp_output_folders, ...
    metadata, ...
    sampling_rate_group, ...
    synchronous_frames_group, ...
    data, ...
    meanImgs_gcamp, ...
    current_gcamp_TSeries_path, ...
    include_electroporated, ...
    peak_detection_mode, ...
    current_automatic_selection, ...
    current_output_folder)

    numFolders = numel(gcamp_output_folders);

    % ==========================================================
    % Defaults
    % ==========================================================
    if nargin < 12 || isempty(include_electroporated)
        include_electroporated = '1';
    end

    if nargin < 13 || isempty(peak_detection_mode)
        peak_detection_mode = 'global';
    end

    include_electroporated = ...
        char(string(include_electroporated));

    process_electroporated_combined = ...
        strcmp(include_electroporated, '1');

    % ==========================================================
    % Detection fields GCaMP
    % ==========================================================
    fields_detect_gcamp = { ...
        'F0_gcamp_by_plane', ...
        'noise_est_gcamp_by_plane', ...
        'DF_gcamp_by_plane', ...
        'DF_raw_gcamp_by_plane', ...
        'valid_gcamp_cells_by_plane', ...
        'Raster_gcamp_by_plane', ...
        'Acttmp2_gcamp_by_plane', ...
        'MAct_gcamp_by_plane', ...
        'thresholds_gcamp_by_plane', ...
        'bad_segs_gcamp_plane', ...
        'opts_detection_gcamp_by_plane', ...
        'isort1_gcamp_by_plane', ...
        'isort2_gcamp_by_plane', ...
        'Sm_gcamp_by_plane' ...
    };

    % ==========================================================
    % Detection fields electroporated
    % ==========================================================
    fields_detect_electroporated = { ...
        'F0_electroporated_by_plane', ...
        'noise_est_electroporated_by_plane', ...
        'DF_electroporated_by_plane', ...
        'DF_raw_electroporated_by_plane', ...
        'valid_electroporated_cells_by_plane', ...
        'Raster_electroporated_by_plane', ...
        'Acttmp2_electroporated_by_plane', ...
        'MAct_electroporated_by_plane', ...
        'thresholds_electroporated_by_plane', ...
        'bad_segs_electroporated_plane', ...
        'opts_detection_electroporated_by_plane', ...
        'isort1_electroporated_by_plane', ...
        'isort2_electroporated_by_plane', ...
        'Sm_electroporated_by_plane' ...
    };

    % ==========================================================
    % Detection fields combined
    % ==========================================================
    fields_detect_combined = { ...
        'F0_combined_by_plane', ...
        'noise_est_combined_by_plane', ...
        'DF_combined_by_plane', ...
        'DF_raw_combined_by_plane', ...
        'valid_combined_cells_by_plane', ...
        'Raster_combined_by_plane', ...
        'Acttmp2_combined_by_plane', ...
        'MAct_combined_by_plane', ...
        'thresholds_combined_by_plane', ...
        'bad_segs_combined_plane', ...
        'opts_detection_combined_by_plane', ...
        'isort1_combined_by_plane', ...
        'isort2_combined_by_plane', ...
        'Sm_combined_by_plane' ...
    };

    % ==========================================================
    % Motion
    % ==========================================================
    fields_motion_group = { ...
        'speed_active_group', ...
        'bad_frames_group', ...
        'bad_segs_group', ...
        'deviation_group', ...
        'focus_segs_group', ...
        'motion_energy_group' ...
    };

    % ==========================================================
    % Initialize branches
    % ==========================================================
    data = init_detection_branch_if_needed( ...
        data, ...
        'gcamp_plane', ...
        numFolders, ...
        fields_detect_gcamp);

    if process_electroporated_combined

        data = init_detection_branch_if_needed( ...
            data, ...
            'electroporated_plane', ...
            numFolders, ...
            fields_detect_electroporated);

        data = init_detection_branch_if_needed( ...
            data, ...
            'combined_plane', ...
            numFolders, ...
            fields_detect_combined);
    end

    data = init_motion_group_if_needed( ...
        data, ...
        numFolders, ...
        fields_motion_group);

    % ==========================================================
    % Existing-detection mode
    % ==========================================================
    processing_mode = ...
        lower(strtrim(char(string(peak_detection_mode))));

    global_existing_detection_action = '';

    switch processing_mode

        case 'viewer'

            global_existing_detection_action = ...
                'viewer';

        case 'load_only'

            global_existing_detection_action = ...
                'load_only';

        otherwise

            processing_mode = ...
                'global';
    end

    % ==========================================================
    % RECORDINGS
    % ==========================================================
    for m = 1:numFolders

        has_new_gcamp_group = false;
        has_new_electroporated_group = false;
        has_new_combined_group = false;
        has_new_motion_group = false;

        age_m = ...
            current_ages{m};

        sampling_rate_m = ...
            sampling_rate_group{m};

        sync_frames_m = ...
            synchronous_frames_group{m};

        metadata_m = ...
            get_metadata_for_record( ...
                metadata, ...
                m);

        [record_label_m, date_m] = ...
            make_record_label( ...
                animal, ...
                metadata_m, ...
                m);

        % ======================================================
        % Number of planes
        % ======================================================
        if ~isfield(metadata_m, 'NumPlanes') || ...
                isempty(metadata_m.NumPlanes)

            error( ...
                'Metadata missing NumPlanes for group %d.', ...
                m);
        end

        nPlanes = ...
            max( ...
                1, ...
                round(double(metadata_m.NumPlanes)));

        % ======================================================
        % Initialize plane slots
        % ======================================================
        for f = 1:numel(fields_detect_gcamp)

            data = ensure_branch_plane_cell( ...
                data, ...
                'gcamp_plane', ...
                fields_detect_gcamp{f}, ...
                m, ...
                nPlanes);
        end

        if process_electroporated_combined

            for f = 1:numel(fields_detect_electroporated)

                data = ensure_branch_plane_cell( ...
                    data, ...
                    'electroporated_plane', ...
                    fields_detect_electroporated{f}, ...
                    m, ...
                    nPlanes);
            end

            for f = 1:numel(fields_detect_combined)

                data = ensure_branch_plane_cell( ...
                    data, ...
                    'combined_plane', ...
                    fields_detect_combined{f}, ...
                    m, ...
                    nPlanes);
            end
        end

        % ======================================================
        % Mean images
        % ======================================================
        if m <= numel(meanImgs_gcamp) && ...
                ~isempty(meanImgs_gcamp{m})

            meanImgs_m = ...
                meanImgs_gcamp{m};

        else

            meanImgs_m = ...
                cell(nPlanes, 1);
        end

        % ======================================================
        % GCaMP TSeries
        % ======================================================
        if m <= numel(current_gcamp_TSeries_path) && ...
                ~isempty(current_gcamp_TSeries_path{m})

            TSeries_m = ...
                current_gcamp_TSeries_path{m};

        else

            TSeries_m = '';
        end

        % ======================================================
        % Stim frames
        % ======================================================
        stim_frames_m = [];

        if isfield(data, 'stim') && ...
                isfield(data.stim, 'stim_frames_log_group') && ...
                isfield(data.stim, 'stim_protocol_group') && ...
                numel(data.stim.stim_frames_log_group) >= m && ...
                numel(data.stim.stim_protocol_group) >= m

            stim_frames_tmp = ...
                data.stim.stim_frames_log_group{m};

            stim_protocol_tmp = ...
                data.stim.stim_protocol_group{m};

            if ~isempty(stim_frames_tmp) && ...
                    ~isempty(stim_protocol_tmp)

                stim_frames_tmp = ...
                    stim_frames_tmp(:);

                stim_protocol_tmp = ...
                    stim_protocol_tmp(:);

                n = ...
                    min( ...
                        numel(stim_frames_tmp), ...
                        numel(stim_protocol_tmp));

                stim_frames_tmp = ...
                    stim_frames_tmp(1:n);

                stim_protocol_tmp = ...
                    stim_protocol_tmp(1:n);

                stim_frames_m = ...
                    stim_frames_tmp( ...
                        stim_protocol_tmp == 0);
            end
        end

        % ======================================================
        % Recording output folder
        % ======================================================
        current_output_folders = [];

        if m <= numel(gcamp_output_folders)

            current_output_folders = ...
                gcamp_output_folders{m};
        end

        if ischar(current_output_folders) || ...
                isstring(current_output_folders)

            current_output_folders = ...
                cellstr(current_output_folders);
        end

        if isempty(current_output_folders) || ...
                ~iscell(current_output_folders)

            fprintf( ...
                ['%s: aucun dossier de sortie GCaMP, ' ...
                 'enregistrement ignoré.\n'], ...
                record_label_m);

            continue;
        end

        valid_output_index = ...
            find( ...
                ~cellfun(@isempty, current_output_folders), ...
                1, ...
                'first');

        if isempty(valid_output_index)

            fprintf( ...
                ['%s: tous les dossiers de sortie des plans sont ' ...
                 'vides, enregistrement ignoré.\n'], ...
                record_label_m);

            continue;
        end

        first_output_folder = ...
            current_output_folders{valid_output_index};

        if isstring(first_output_folder)
            first_output_folder = char(first_output_folder);
        end

        if ~ischar(first_output_folder) || ...
                isempty(strtrim(first_output_folder))

            fprintf( ...
                '%s: dossier de sortie GCaMP invalide.\n', ...
                record_label_m);

            continue;
        end

        outdir_m = ...
            fileparts(first_output_folder);

        if isempty(outdir_m)
            outdir_m = first_output_folder;
        end

        if exist(outdir_m, 'dir') ~= 7
            mkdir(outdir_m);
        end

        % ======================================================
        % Results paths
        % ======================================================
        filePath_gcamp = ...
            fullfile( ...
                outdir_m, ...
                'results_gcamp.mat');

        filePath_electroporated = ...
            fullfile( ...
                outdir_m, ...
                'results_electroporated.mat');

        filePath_combined = ...
            fullfile( ...
                outdir_m, ...
                'results_combined.mat');

        filePath_motion = ...
            fullfile( ...
                outdir_m, ...
                'results_motion.mat');

        % ======================================================
        % Old motion filename migration
        % ======================================================
        oldMotionPath = ...
            fullfile( ...
                outdir_m, ...
                'results_movie.mat');

        if exist(oldMotionPath, 'file') == 2 && ...
                exist(filePath_motion, 'file') ~= 2

            movefile( ...
                oldMotionPath, ...
                filePath_motion);

            fprintf( ...
                '%s: renamed results_movie.mat -> results_motion.mat\n', ...
                record_label_m);
        end

        % ======================================================
        % Load GCaMP detection if memory incomplete
        % ======================================================
        missing_gcamp = ...
            branch_has_missing_fields( ...
                data, ...
                'gcamp_plane', ...
                fields_detect_gcamp, ...
                m, ...
                nPlanes);

        if missing_gcamp

            if exist(filePath_gcamp, 'file') == 2

                fprintf( ...
                    ['%s : chargement de results_gcamp.mat ' ...
                     '(mémoire incomplète).\n'], ...
                    record_label_m);

                loaded_gcamp = ...
                    load(filePath_gcamp);

                data = ...
                    merge_loaded_branch_into_data( ...
                        data, ...
                        'gcamp_plane', ...
                        loaded_gcamp, ...
                        fields_detect_gcamp, ...
                        m, ...
                        nPlanes);

            else

                fprintf( ...
                    '%s : results_gcamp.mat absent.\n', ...
                    record_label_m);
            end

        else

            fprintf( ...
                ['%s : données GCaMP déjà complètes en mémoire, ' ...
                 'pas de reload.\n'], ...
                record_label_m);
        end

        % ======================================================
        % Electroporated + combined detections
        % ======================================================
        if process_electroporated_combined

            missing_electroporated = ...
                branch_has_missing_fields( ...
                    data, ...
                    'electroporated_plane', ...
                    fields_detect_electroporated, ...
                    m, ...
                    nPlanes);

            if missing_electroporated

                if exist(filePath_electroporated, 'file') == 2

                    fprintf( ...
                        ['%s : chargement de ' ...
                         'results_electroporated.mat.\n'], ...
                        record_label_m);

                    loaded_electroporated = ...
                        load(filePath_electroporated);

                    data = ...
                        merge_loaded_branch_into_data( ...
                            data, ...
                            'electroporated_plane', ...
                            loaded_electroporated, ...
                            fields_detect_electroporated, ...
                            m, ...
                            nPlanes);

                else

                    fprintf( ...
                        '%s : results_electroporated.mat absent.\n', ...
                        record_label_m);
                end
            end

            missing_combined = ...
                branch_has_missing_fields( ...
                    data, ...
                    'combined_plane', ...
                    fields_detect_combined, ...
                    m, ...
                    nPlanes);

            if missing_combined

                if exist(filePath_combined, 'file') == 2

                    fprintf( ...
                        ['%s : chargement de ' ...
                         'results_combined.mat.\n'], ...
                        record_label_m);

                    loaded_combined = ...
                        load(filePath_combined);

                    data = ...
                        merge_loaded_branch_into_data( ...
                            data, ...
                            'combined_plane', ...
                            loaded_combined, ...
                            fields_detect_combined, ...
                            m, ...
                            nPlanes);

                else

                    fprintf( ...
                        '%s : results_combined.mat absent.\n', ...
                        record_label_m);
                end
            end
        end

        % ======================================================
        % Motion
        % ======================================================
        missing_motion = ...
            motion_group_has_missing_fields( ...
                data, ...
                fields_motion_group, ...
                m);

        if missing_motion

            if exist(filePath_motion, 'file') == 2

                loaded_motion = ...
                    load(filePath_motion);

                data = ...
                    merge_loaded_motion_group_into_data( ...
                        data, ...
                        loaded_motion, ...
                        fields_motion_group, ...
                        m);
            end
        end

        speed_active_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'speed_active_group', ...
                m);

        bad_frames_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'bad_frames_group', ...
                m);

        bad_segs_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'bad_segs_group', ...
                m);

        deviation_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'deviation_group', ...
                m);

        focus_segs_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'focus_segs_group', ...
                m);

        motion_energy_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'motion_energy_group', ...
                m);

        % ======================================================
        % Motion reference ops
        % ======================================================
        ops_motion_ref = [];

        for pp = 1:nPlanes

            ops_motion_ref = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'ops_suite2p_by_plane', ...
                    m, ...
                    pp);

            if isempty(ops_motion_ref) && ...
                    process_electroporated_combined

                ops_motion_ref = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'electroporated_plane', ...
                        'ops_suite2p_electroporated_by_plane', ...
                        m, ...
                        pp);
            end

            if ~isempty(ops_motion_ref)
                break;
            end
        end

        motion_group_incomplete = ...
            isempty(bad_frames_group) || ...
            isempty(bad_segs_group) || ...
            isempty(deviation_group) || ...
            isempty(focus_segs_group) || ...
            isempty(motion_energy_group);

        if motion_group_incomplete

            if ~isempty(ops_motion_ref) && ...
                    isfield(ops_motion_ref, 'corrXY') && ...
                    ~isempty(ops_motion_ref.corrXY)

                corrXY = ...
                    ops_motion_ref.corrXY(:);

                N = ...
                    numel(corrXY);

                rolling_median = ...
                    movmedian( ...
                        corrXY, ...
                        300);

                deviation_group = ...
                    corrXY - rolling_median;

                sigma_dev = ...
                    std( ...
                        deviation_group( ...
                            deviation_group < 0), ...
                        'omitnan');

                seuil_bad = ...
                    -3 * sigma_dev;

                bad_frames_logical = ...
                    deviation_group < seuil_bad;

                bad_frames_logical = ...
                    conv( ...
                        double(bad_frames_logical), ...
                        [1 1 1], ...
                        'same') > 0;

                bad_frames_group = ...
                    find(bad_frames_logical);

                bad_frames_group = ...
                    bad_frames_group(:).';

                bad_segs_group = ...
                    badframes_to_segments( ...
                        bad_frames_group, ...
                        N);

                focus_segs_group = ...
                    bad_segs_group;

                deviation_group = ...
                    deviation_group(:).';

                data.motion.bad_frames_group{m} = ...
                    bad_frames_group;

                data.motion.bad_segs_group{m} = ...
                    bad_segs_group;

                data.motion.deviation_group{m} = ...
                    deviation_group;

                data.motion.focus_segs_group{m} = ...
                    focus_segs_group;

                if ~isempty(motion_energy_group)

                    data.motion.motion_energy_group{m} = ...
                        motion_energy_group;
                end

                has_new_motion_group = true;

            else

                warning( ...
                    ['%s: impossible de calculer deviation group : ' ...
                     'corrXY manquant.'], ...
                    record_label_m);
            end
        end

        % ======================================================
        % PLANES
        % ======================================================
        for p = 1:nPlanes

            % ==================================================
            % Plane output folder
            % ==================================================
            gcamp_output_folder_p = '';

            if m <= numel(gcamp_output_folders)

                current_recording_outputs = ...
                    gcamp_output_folders{m};

                if ischar(current_recording_outputs) || ...
                        isstring(current_recording_outputs)

                    current_recording_outputs = ...
                        cellstr(current_recording_outputs);
                end

                if iscell(current_recording_outputs) && ...
                        p <= numel(current_recording_outputs) && ...
                        ~isempty(current_recording_outputs{p})

                    gcamp_output_folder_p = ...
                        current_recording_outputs{p};
                end
            end

            if isstring(gcamp_output_folder_p)
                gcamp_output_folder_p = char(gcamp_output_folder_p);
            end

            if isempty(gcamp_output_folder_p) || ...
                    ~ischar(gcamp_output_folder_p)

                fprintf( ...
                    '%s - plane %d: output folder absent.\n', ...
                    record_label_m, ...
                    p);

                continue;
            end

            if exist(gcamp_output_folder_p, 'dir') ~= 7
                mkdir(gcamp_output_folder_p);
            end

            % ==================================================
            % IMPORTANT:
            %
            % Si electroporated actif :
            % on charge UNIQUEMENT COMBINED.
            %
            % GCaMP =
            %   combined hors electroporated_indices
            %
            % Electroporated =
            %   combined aux electroporated_indices
            % ==================================================
            if process_electroporated_combined

                F_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'F_combined_by_plane', ...
                        m, ...
                        p);

                masks_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'mask_combined_by_plane', ...
                        m, ...
                        p);

                electroporated_indices_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'electroporated_indices_combined_by_plane', ...
                        m, ...
                        p);

                if isempty(F_in)

                    fprintf( ...
                        ['%s - plane %d: combined unavailable, ' ...
                         'plane skipped.\n'], ...
                        record_label_m, ...
                        p);

                    continue;
                end

                % --------------------------------------------------
                % Common Suite2p information comes from GCaMP
                % --------------------------------------------------
                stat_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'stat_by_plane', ...
                        m, ...
                        p);

                iscell_idx = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'iscell_idx_gcamp_by_plane', ...
                        m, ...
                        p);

                ops_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'ops_suite2p_by_plane', ...
                        m, ...
                        p);

                cell_type = ...
                    'combined';

                % --------------------------------------------------
                % Existing detection = COMBINED
                % --------------------------------------------------
                has_detection_plane = ...
                    has_existing_detection_new( ...
                        data, ...
                        'combined_plane', ...
                        'DF_combined_by_plane', ...
                        m, ...
                        p);

            % ==================================================
            % GCaMP-only mode
            % ==================================================
            else

                F_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'F_gcamp_by_plane', ...
                        m, ...
                        p);

                masks_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'gcamp_mask_by_plane', ...
                        m, ...
                        p);

                electroporated_indices_in = [];

                stat_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'stat_by_plane', ...
                        m, ...
                        p);

                iscell_idx = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'iscell_idx_gcamp_by_plane', ...
                        m, ...
                        p);

                ops_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'ops_suite2p_by_plane', ...
                        m, ...
                        p);

                cell_type = ...
                    'gcamp';

                has_detection_plane = ...
                    has_existing_detection_new( ...
                        data, ...
                        'gcamp_plane', ...
                        'DF_gcamp_by_plane', ...
                        m, ...
                        p);
            end

            if isempty(F_in)

                fprintf( ...
                    '%s - plane %d: no signal data available.\n', ...
                    record_label_m, ...
                    p);

                continue;
            end

            % ==================================================
            % Viewer / Load-only decision
            % ==================================================
            viewer_mode_requested_plane = false;
            load_only_plane = false;

            if has_detection_plane

                if isempty(global_existing_detection_action)

                    global_existing_detection_action = ...
                        ask_existing_detection_action_global( ...
                            record_label_m);
                end

                switch global_existing_detection_action

                    case 'viewer'

                        viewer_mode_requested_plane = true;

                    case 'load_only'

                        load_only_plane = true;
                end
            end

            % ==================================================
            % Mean image
            % ==================================================
            if numel(meanImgs_m) >= p

                meanImg = ...
                    meanImgs_m{p};

            else

                meanImg = [];
            end
            
            % ==================================================
            % Load saved detection corresponding to data passed
            %
            % Combined mode -> combined saved detection
            % GCaMP-only   -> GCaMP saved detection
            % ==================================================
            Acttmp2_saved = [];
            Raster_saved = [];
            thresholds_saved = [];
            valid_cells_saved = [];
            DF_sg_saved = [];
            DF_raw_saved = [];
            F0_saved = [];
            noise_est_saved = [];

            if process_electroporated_combined

                detection_branch = ...
                    'combined_plane';

                valid_field = ...
                    'valid_combined_cells_by_plane';

                Acttmp2_field = ...
                    'Acttmp2_combined_by_plane';

                Raster_field = ...
                    'Raster_combined_by_plane';

                thresholds_field = ...
                    'thresholds_combined_by_plane';

                DF_field = ...
                    'DF_combined_by_plane';

                DF_raw_field = ...
                    'DF_raw_combined_by_plane';

