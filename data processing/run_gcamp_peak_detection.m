            case 'combined'

                branchName = ...
                    'combined_plane';

                fields = ...
                    fields_detect_combined;

            otherwise

                continue;
        end

        for f = 1:numel(fields)

            fn = ...
                fields{f};

            if isfield(data, branchName) && ...
                    isfield(data.(branchName), fn) && ...
                    numel(data.(branchName).(fn)) >= m && ...
                    iscell(data.(branchName).(fn){m}) && ...
                    numel(data.(branchName).(fn){m}) >= p

                data.(branchName).(fn){m}{p} = [];
            end
        end
    end
end
