function [data, has_new_saved, modified_planes, recap_all_animal] = run_gcamp_peak_detection( ...
    current_type, ...
    current_line, ...
    animal, ...
    current_dates, ...
    current_ages, ...
    current_gcamp_suite2p_folders, ...
    gcamp_root_folders, ...
    gcamp_output_folders, ...
    current_camera_folders, ...
    metadata, ...
    sampling_rate_plane, ...
    synchronous_frames_group, ...
    data, ...
    meanImgs_gcamp, ...
    current_gcamp_TSeries_path, ...
    include_electroporated, ...
    peak_detection_mode, ...
    current_automatic_selection, ...
    current_output_folders, ...
    clear_outputs_requested, ...
    recap_all_animal)

    numFolders = ...
        numel(gcamp_output_folders);

    % Une ligne du recap par enregistrement, une cellule par plan dans
    % chaque colonne. Conserver toutes les autres colonnes et lignes.
    if istable(recap_all_animal)
        if ~ismember('recording_keep',recap_all_animal.Properties.VariableNames) || ...
                ~iscell(recap_all_animal.recording_keep)
            recap_all_animal.recording_keep = cell(height(recap_all_animal),1);
        end
        if ~ismember('comment_saved',recap_all_animal.Properties.VariableNames) || ...
                ~iscell(recap_all_animal.comment_saved)
            recap_all_animal.comment_saved = cell(height(recap_all_animal),1);
        end
    end

    % ==========================================================
    % Full inputs / full results policy
    %
    % All F and detection inputs are assumed complete. The tuner always
    % receives the entire recording. Newly saved results_*.mat contain the
    % complete temporal detection matrices, even if include_stims=false.
    % Only the data RETURNED to the caller is cropped after the tuner
    % finishes and AFTER the complete results have been saved.
    % ==========================================================
    include_stims = false;

    % ==========================================================
    % Defaults
    % ==========================================================

    if nargin < 16 || ...
            isempty(include_electroporated)

        include_electroporated = ...
            '1';
    end

    if nargin < 17 || ...
            isempty(peak_detection_mode)

        peak_detection_mode = ...
            'global';
    end

    if nargin < 20 || ...
            isempty(clear_outputs_requested)

        clear_outputs_requested = ...
            false;
    end

    include_electroporated = ...
        char(string(include_electroporated));

    process_electroporated_combined = ...
        strcmp( ...
            include_electroporated, ...
            '1');

    % ==========================================================
    % Detection fields GCaMP
    % ==========================================================

    fields_detect_gcamp = { ...
        'F0_gcamp_by_plane', ...
        'noise_est_gcamp_by_plane', ...
        'DF_gcamp_by_plane', ...
        'DF_raw_gcamp_by_plane', ...
        'valid_gcamp_cells_by_plane', ...
        'Raster_gcamp_by_plane', ...
        'Acttmp2_gcamp_by_plane', ...
        'MAct_gcamp_by_plane', ...
        'thresholds_gcamp_by_plane', ...
        'bad_segs_gcamp_plane', ...
        'opts_detection_gcamp_by_plane', ...
        'selection_summary_gcamp_by_plane', ...
        'recording_keep_gcamp_by_plane', ...
        'isort1_gcamp_by_plane', ...
        'isort2_gcamp_by_plane', ...
        'Sm_gcamp_by_plane' ...
    };

    % ==========================================================
    % Detection fields electroporated
    % ==========================================================

    fields_detect_electroporated = { ...
        'F0_electroporated_by_plane', ...
        'noise_est_electroporated_by_plane', ...
        'DF_electroporated_by_plane', ...
        'DF_raw_electroporated_by_plane', ...
        'valid_electroporated_cells_by_plane', ...
        'Raster_electroporated_by_plane', ...
        'Acttmp2_electroporated_by_plane', ...
        'MAct_electroporated_by_plane', ...
        'thresholds_electroporated_by_plane', ...
        'bad_segs_electroporated_plane', ...
        'opts_detection_electroporated_by_plane', ...
        'selection_summary_electroporated_by_plane', ...
        'recording_keep_electroporated_by_plane', ...
        'isort1_electroporated_by_plane', ...
        'isort2_electroporated_by_plane', ...
        'Sm_electroporated_by_plane' ...
    };

    % ==========================================================
    % Detection fields combined
    % ==========================================================

    fields_detect_combined = { ...
        'F0_combined_by_plane', ...
        'noise_est_combined_by_plane', ...
        'DF_combined_by_plane', ...
        'DF_raw_combined_by_plane', ...
        'valid_combined_cells_by_plane', ...
        'Raster_combined_by_plane', ...
        'Acttmp2_combined_by_plane', ...
        'MAct_combined_by_plane', ...
        'thresholds_combined_by_plane', ...
        'bad_segs_combined_plane', ...
        'opts_detection_combined_by_plane', ...
        'selection_summary_combined_by_plane', ...
        'recording_keep_combined_by_plane', ...
        'isort1_combined_by_plane', ...
        'isort2_combined_by_plane', ...
        'Sm_combined_by_plane' ...
    };

    % ==========================================================
    % Motion
    % ==========================================================

    fields_motion_group = { ...
        'speed_active_group', ...
        'bad_frames_group', ...
        'bad_segs_group', ...
        'deviation_group', ...
        'focus_segs_group', ...
        'motion_energy_group', ...
        'motion_energy_status' ...
    };

    % ==========================================================
    % CLEAR EXISTING PEAK-DETECTION OUTPUTS
    % ==========================================================

    if clear_outputs_requested

        fprintf('\n');
        fprintf('============================================\n');
        fprintf('CLEARING EXISTING PEAK-DETECTION OUTPUTS\n');
        fprintf('Animal: %s\n', char(string(animal)));
        fprintf('============================================\n');

        if process_electroporated_combined

            branches_to_clear = { ...
                'gcamp', ...
                'electroporated', ...
                'combined'};

        else

            branches_to_clear = { ...
                'gcamp'};
        end

        clear_detection_outputs( ...
            gcamp_root_folders, ...
            branches_to_clear, ...
            fields_detect_gcamp, ...
            fields_detect_electroporated, ...
            fields_detect_combined);

        % ======================================================
        % Clear memory
        % ======================================================

        if isfield(data,'gcamp_plane')

            for f = 1:numel(fields_detect_gcamp)

                fn = ...
                    fields_detect_gcamp{f};

                if isfield(data.gcamp_plane,fn) && ...
                        ~startsWith(fn,'recording_keep_')

                    data.gcamp_plane.(fn) = ...
                        cell(numFolders,1);
                end
            end
        end

        if process_electroporated_combined && ...
                isfield(data,'electroporated_plane')

            for f = 1:numel(fields_detect_electroporated)

                fn = ...
                    fields_detect_electroporated{f};

                if isfield( ...
                        data.electroporated_plane, ...
                        fn) && ~startsWith(fn,'recording_keep_')

                    data.electroporated_plane.(fn) = ...
                        cell(numFolders,1);
                end
            end
        end

        if process_electroporated_combined && ...
                isfield(data,'combined_plane')

            for f = 1:numel(fields_detect_combined)

                fn = ...
                    fields_detect_combined{f};

                if isfield( ...
                        data.combined_plane, ...
                        fn) && ~startsWith(fn,'recording_keep_')

                    data.combined_plane.(fn) = ...
                        cell(numFolders,1);
                end
            end
        end

        fprintf( ...
            'Existing peak-detection outputs cleared.\n\n');
    end

    % ==========================================================
    % Initialize branches
    % ==========================================================

    data = ...
        init_detection_branch_if_needed( ...
            data, ...
            'gcamp_plane', ...
            numFolders, ...
            fields_detect_gcamp);

    if process_electroporated_combined

        data = ...
            init_detection_branch_if_needed( ...
                data, ...
                'electroporated_plane', ...
                numFolders, ...
                fields_detect_electroporated);

        data = ...
            init_detection_branch_if_needed( ...
                data, ...
                'combined_plane', ...
                numFolders, ...
                fields_detect_combined);
    end

    data = ...
        init_motion_group_if_needed( ...
            data, ...
            numFolders, ...
            fields_motion_group);

    % Decision independante POUR CHAQUE PLAN, sans toucher a DF/isort.
    if ~isfield(data,'recording_keep_group') || ...
            ~iscell(data.recording_keep_group)
        data.recording_keep_group = cell(numFolders,1);
    elseif numel(data.recording_keep_group) < numFolders
        data.recording_keep_group{numFolders} = [];
    end

    % ==========================================================
    % Existing-detection mode
    % ==========================================================

    processing_mode = ...
        lower( ...
            strtrim( ...
                char(string(peak_detection_mode))));

    global_existing_detection_action = '';

    switch processing_mode

        case 'viewer'

            global_existing_detection_action = ...
                'viewer';

        case 'load_only'

            global_existing_detection_action = ...
                'load_only';

        otherwise

            processing_mode = ...
                'global';
    end

    % ==========================================================
    % Outputs flags
    % ==========================================================

    has_new_saved = ...
        logical(clear_outputs_requested);

    modified_planes = ...
        cell( ...
            numFolders, ...
            1);

    % ==========================================================
    % RECORDINGS
    % ==========================================================

    for m = 1:numFolders

        has_new_gcamp_group = false;
        has_new_electroporated_group = false;
        has_new_combined_group = false;
        % ======================================================
        % Recording information
        % ======================================================

        current_output_folder = '';

        if m <= numel(current_output_folders) && ...
                ~isempty(current_output_folders{m})

            current_output_folder = ...
                current_output_folders{m};
        end

        date_m = ...
            current_dates{m};

        age_m = ...
            current_ages{m};

        record_label_m = ...
            sprintf( ...
                '%s - %s', ...
                string(animal), ...
                string(date_m));

        sampling_rate_plane_m = ...
            sampling_rate_plane{m};

        sync_frames_m = ...
            synchronous_frames_group{m};

        metadata_m = ...
            get_metadata_for_record( ...
                metadata, ...
                m);

        gcamp_suite2p_folders_m = ...
            current_gcamp_suite2p_folders{m};

        % ======================================================
        % Camera folder
        % ======================================================

        current_camera_folder_m = '';

        if m <= numel(current_camera_folders) && ...
                ~isempty(current_camera_folders{m})

            current_camera_folder_m = ...
                current_camera_folders{m};
        end

        % ======================================================
        % Metadata
        % ======================================================

        if ~isfield(metadata_m,'gcamp_plane') || ...
                isempty(metadata_m.gcamp_plane)

            error( ...
                'GCaMP metadata missing for group %d.', ...
                m);
        end

        metadata_gcamp_m = ...
            metadata_m.gcamp_plane;

        if ~isfield(metadata_gcamp_m,'NumPlanes') || ...
                isempty(metadata_gcamp_m.NumPlanes)

            error( ...
                'GCaMP metadata missing NumPlanes for group %d.', ...
                m);
        end

        nPlanes = ...
            max( ...
                1, ...
                round( ...
                    double( ...
                        metadata_gcamp_m.NumPlanes)));

        % ======================================================
        % Global frame rate
        %
        % Référentiel utilisé par :
        %   camera
        %   motion
        %   stim
        % ======================================================

        sampling_rate_motion_m = ...
            sampling_rate_plane_m * ...
            nPlanes;

        % ======================================================
        % Modified planes
        % ======================================================

        if clear_outputs_requested

            modified_planes{m} = ...
                true( ...
                    1, ...
                    nPlanes);

        else

            modified_planes{m} = ...
                false( ...
                    1, ...
                    nPlanes);
        end

        % ======================================================
        % Initialize plane slots
        % ======================================================

        for f = 1:numel(fields_detect_gcamp)

            data = ...
                ensure_branch_plane_cell( ...
                    data, ...
                    'gcamp_plane', ...
                    fields_detect_gcamp{f}, ...
                    m, ...
                    nPlanes);
        end

        if process_electroporated_combined

            for f = 1:numel(fields_detect_electroporated)

                data = ...
                    ensure_branch_plane_cell( ...
                        data, ...
                        'electroporated_plane', ...
                        fields_detect_electroporated{f}, ...
                        m, ...
                        nPlanes);
            end

            for f = 1:numel(fields_detect_combined)

                data = ...
                    ensure_branch_plane_cell( ...
                        data, ...
                        'combined_plane', ...
                        fields_detect_combined{f}, ...
                        m, ...
                        nPlanes);
            end
        end

        % ======================================================
        % Mean images
        % ======================================================

        if m <= numel(meanImgs_gcamp) && ...
                ~isempty(meanImgs_gcamp{m})

            meanImgs_m = ...
                meanImgs_gcamp{m};

        else

            meanImgs_m = ...
                cell(nPlanes,1);
        end

        % ======================================================
        % TSeries
        % ======================================================

        if m <= numel(current_gcamp_TSeries_path) && ...
                ~isempty(current_gcamp_TSeries_path{m})

            TSeries_m = ...
                current_gcamp_TSeries_path{m};

        else

            TSeries_m = '';
        end

        % ======================================================
        % Commentaire du recording : correspondance DATE + TSeries GCaMP.
        % Le tableau a deja ete filtre sur Type/Line/Animal par l'appelant.
        % Un commentaire vide dans recap_all_animal est intentionnel.
        % ======================================================

        recap_comment_m = '';
        recap_row_m = [];

        % recap_all_animal est le 21e argument et fait partie de la
        % signature actuelle de la fonction. Ne pas utiliser de test nargin
        % ici : l'ancien `nargin >= 22` rendait ce bloc inatteignable.
        if istable(recap_all_animal) && ...
                all(ismember({'Date','TSeries'}, ...
                             recap_all_animal.Properties.VariableNames)) && ...
                ~isempty(TSeries_m)

            [recap_comment_m, recap_row_m] = ...
                get_recap_comment_for_record( ...
                    recap_all_animal, ...
                    date_m, ...
                    TSeries_m);

            if isempty(recap_row_m)
                fprintf( ...
                    ['%s : aucune ligne recap associee au TSeries ' ...
                     'courant (date=%s, TSeries=%s).\n'], ...
                    record_label_m, ...
                    char(string(date_m)), ...
                    get_tseries_basename(TSeries_m));

            elseif isempty(strtrim(recap_comment_m))
                fprintf( ...
                    ['%s : aucun commentaire recap associe au TSeries ' ...
                     'courant (date=%s, TSeries=%s).\n'], ...
                    record_label_m, ...
                    char(string(date_m)), ...
                    get_tseries_basename(TSeries_m));
            end
        end

        % ======================================================
        % STIM
        % ======================================================

        stim_frames_m = [];
        first_stim_frame_global = [];

        if isfield(data,'stim') && ...
                isfield(data.stim,'stim_protocol_group') && ...
                numel(data.stim.stim_protocol_group) >= m

            % --------------------------------------------------
            % Frame reference for stimulation events
            %
            % Priority:
            %   1) stim_frames_log_group{m}
            %   2) stim_times_group{m} when stim_frames_log_group
            %      is absent or empty.
            %
            % IMPORTANT: stim_times_group is intentionally treated
            % here as already expressed in FRAMES (no time->frame
            % conversion is applied).
            % --------------------------------------------------

            stim_frames_tmp = [];

            if isfield(data.stim,'stim_frames_log_group') && ...
                    numel(data.stim.stim_frames_log_group) >= m && ...
                    ~isempty(data.stim.stim_frames_log_group{m})

                stim_frames_tmp = ...
                    data.stim.stim_frames_log_group{m};

            elseif isfield(data.stim,'stim_times_group') && ...
                    numel(data.stim.stim_times_group) >= m && ...
                    ~isempty(data.stim.stim_times_group{m})

                stim_frames_tmp = ...
                    data.stim.stim_times_group{m};
            end

            stim_protocol_tmp = ...
                data.stim.stim_protocol_group{m};

            if ~isempty(stim_frames_tmp) && ...
                    ~isempty(stim_protocol_tmp)

                stim_frames_tmp = ...
                    stim_frames_tmp(:);

                stim_protocol_tmp = ...
                    stim_protocol_tmp(:);

                n = ...
                    min( ...
                        numel(stim_frames_tmp), ...
                        numel(stim_protocol_tmp));

                stim_frames_tmp = ...
                    stim_frames_tmp(1:n);

                stim_protocol_tmp = ...
                    stim_protocol_tmp(1:n);

                stim_frames_m = ...
                    stim_frames_tmp( ...
                        stim_protocol_tmp == 0);
            end
        end

        % ======================================================
        % First stimulation in GLOBAL frame reference
        % ======================================================

        if ~isempty(stim_frames_m)

            stim_tmp = ...
                double( ...
                    stim_frames_m(:));

            stim_tmp = ...
                stim_tmp( ...
                    isfinite(stim_tmp));

            if ~isempty(stim_tmp)

                first_stim_frame_global = ...
                    round( ...
                        min(stim_tmp));
            end
        end

        % ======================================================
        % Recording root
        % ======================================================

        outdir_m = '';

        if m <= numel(gcamp_root_folders) && ...
                ~isempty(gcamp_root_folders{m})

            outdir_m = ...
                gcamp_root_folders{m};
        end

        if isstring(outdir_m)

            outdir_m = ...
                char(outdir_m);
        end

        if isempty(outdir_m) || ...
                ~ischar(outdir_m)

            fprintf( ...
                '%s: dossier gcamp_root invalide.\n', ...
                record_label_m);

            % Retourner aussi les statuts deja presents en memoire si ce
            % recording ne peut pas etre traite faute de dossier.
            if ~isempty(recap_row_m)
                recap_all_animal = update_recap_detection_row( ...
                    recap_all_animal,recap_row_m,data,m,nPlanes, ...
                    process_electroporated_combined);
            end
            continue;
        end

        if exist(outdir_m,'dir') ~= 7

            mkdir(outdir_m);
        end

        % ======================================================
        % Result files
        % ======================================================

        filePath_gcamp = ...
            fullfile( ...
                outdir_m, ...
                'results_gcamp.mat');

        filePath_electroporated = ...
            fullfile( ...
                outdir_m, ...
                'results_electroporated.mat');

        filePath_combined = ...
            fullfile( ...
                outdir_m, ...
                'results_combined.mat');

        filePath_motion = ...
            fullfile( ...
                outdir_m, ...
                'results_motion.mat');

        % ======================================================
        % Motion results are READ-ONLY in this pipeline.
        % Never create, rename or overwrite results_motion.mat.
        % If only the legacy results_movie.mat exists, read it directly.
        % ======================================================

        oldMotionPath = ...
            fullfile( ...
                outdir_m, ...
                'results_movie.mat');

        motion_read_path = ...
            filePath_motion;

        if exist(motion_read_path,'file') ~= 2 && ...
                exist(oldMotionPath,'file') == 2

            motion_read_path = ...
                oldMotionPath;

            fprintf( ...
                '%s: legacy results_movie.mat used read-only.\n', ...
                record_label_m);
        end

        % ======================================================
        % Load GCaMP detection fields selectively
        %
        % If the detection core is absent, all missing detection
        % variables are requested. Once the core is already present,
        % legitimately-empty optional outputs do not trigger reloads.
        % ======================================================

        fields_to_load_gcamp = ...
            get_branch_fields_to_load( ...
                data, ...
                'gcamp_plane', ...
                fields_detect_gcamp, ...
                m, ...
                nPlanes);

        if ~isempty(fields_to_load_gcamp)

            if exist(filePath_gcamp,'file') == 2

                fprintf( ...
                    ['%s : chargement sélectif de results_gcamp.mat ' ...
                     '(mémoire incomplète).\n'], ...
                    record_label_m);

                loaded_gcamp = ...
                    load_available_variables_peak_detection( ...
                        filePath_gcamp, ...
                        fields_to_load_gcamp);

                data = ...
                    merge_loaded_branch_into_data( ...
                        data, ...
                        'gcamp_plane', ...
                        loaded_gcamp, ...
                        fields_to_load_gcamp, ...
                        m, ...
                        nPlanes);

            else

                fprintf( ...
                    '%s : results_gcamp.mat absent.\n', ...
                    record_label_m);
            end

        else

            fprintf( ...
                ['%s : données GCaMP déjà complètes en mémoire, ' ...
                 'pas de reload.\n'], ...
                record_label_m);
        end

        % ======================================================
        % Load Electroporated / Combined selectively
        % ======================================================

        if process_electroporated_combined

            fields_to_load_electroporated = ...
                get_branch_fields_to_load( ...
                    data, ...
                    'electroporated_plane', ...
                    fields_detect_electroporated, ...
                    m, ...
                    nPlanes);

            if ~isempty(fields_to_load_electroporated) && ...
                    exist(filePath_electroporated,'file') == 2

                loaded_electroporated = ...
                    load_available_variables_peak_detection( ...
                        filePath_electroporated, ...
                        fields_to_load_electroporated);

                data = ...
                    merge_loaded_branch_into_data( ...
                        data, ...
                        'electroporated_plane', ...
                        loaded_electroporated, ...
                        fields_to_load_electroporated, ...
                        m, ...
                        nPlanes);
            end

            fields_to_load_combined = ...
                get_branch_fields_to_load( ...
                    data, ...
                    'combined_plane', ...
                    fields_detect_combined, ...
                    m, ...
                    nPlanes);

            if ~isempty(fields_to_load_combined) && ...
                    exist(filePath_combined,'file') == 2

                loaded_combined = ...
                    load_available_variables_peak_detection( ...
                        filePath_combined, ...
                        fields_to_load_combined);

                data = ...
                    merge_loaded_branch_into_data( ...
                        data, ...
                        'combined_plane', ...
                        loaded_combined, ...
                        fields_to_load_combined, ...
                        m, ...
                        nPlanes);
            end
        end

        % ======================================================
        % Load motion selectively
        % ======================================================

        fields_to_load_motion = ...
            get_motion_fields_to_load( ...
                data, ...
                fields_motion_group, ...
                m);

        if ~isempty(fields_to_load_motion) && ...
                exist(motion_read_path,'file') == 2

            loaded_motion = ...
                load_available_variables_peak_detection( ...
                    motion_read_path, ...
                    fields_to_load_motion);

            data = ...
                merge_loaded_motion_group_into_data( ...
                    data, ...
                    loaded_motion, ...
                    fields_to_load_motion, ...
                    m);
        end

        % Motion inputs are already complete (or selectively loaded above).
        % Do not reload the same results_motion.mat a second time.

        speed_active_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'speed_active_group', ...
                m);

        bad_frames_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'bad_frames_group', ...
                m);

        bad_segs_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'bad_segs_group', ...
                m);

        deviation_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'deviation_group', ...
                m);

        focus_segs_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'focus_segs_group', ...
                m);

        motion_energy_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'motion_energy_group', ...
                m);

        % ======================================================
        % COMPLETE motion before peak_detection_tuner
        %
        % IMPORTANT: nothing is cropped before the tuner anymore.
        % The Viewer therefore receives motion/speed for the complete
        % recording, including the stimulation period.
        % ======================================================

        data.motion.motion_energy_group{m} = ...
            motion_energy_group;

        data.motion.speed_active_group{m} = ...
            speed_active_group;

        % ======================================================
        % Behavior movie frame limit
        %
        % No pre-stimulation limit here.  When a motion vector is
        % available its COMPLETE length gives a safe movie limit;
        % otherwise [] lets peak_detection_tuner use the TIFF extent.
        % ======================================================

        behavior_frame_limit_m = [];

        % Leave this empty here: the per-plane fallback below derives the
        % complete global acquisition extent from the complete F_view.
        % This also avoids inheriting an old pre-stim motion length from a
        % results_motion.mat created by an earlier pipeline version.

        % ======================================================
        % Motion reference ops
        % ======================================================

        ops_motion_ref = [];

        for pp = 1:nPlanes

            ops_motion_ref = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'ops_suite2p_by_plane', ...
                    m, ...
                    pp);

            if isempty(ops_motion_ref) && ...
                    process_electroporated_combined

                ops_motion_ref = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'electroporated_plane', ...
                        'ops_suite2p_electroporated_by_plane', ...
                        m, ...
                        pp);
            end

            if ~isempty(ops_motion_ref)
                break;
            end
        end

        % bad_frames / bad_segs / focus_segs may legitimately be empty
        % when no motion artifact is detected. deviation_group is the
        % completion marker for the Suite2p-motion analysis.
        motion_group_incomplete = ...
            isempty(deviation_group);

        if motion_group_incomplete

            if ~isempty(ops_motion_ref) && ...
                    isfield(ops_motion_ref,'corrXY') && ...
                    ~isempty(ops_motion_ref.corrXY)

                corrXY = ...
                    ops_motion_ref.corrXY(:);

                N = ...
                    numel(corrXY);

                rolling_median = ...
                    movmedian( ...
                        corrXY, ...
                        300);

                deviation_group = ...
                    corrXY - ...
                    rolling_median;

                sigma_dev = ...
                    std( ...
                        deviation_group( ...
                            deviation_group < 0), ...
                        'omitnan');

                seuil_bad = ...
                    -3 * sigma_dev;

                bad_frames_logical = ...
                    deviation_group < ...
                    seuil_bad;

                bad_frames_logical = ...
                    conv( ...
                        double(bad_frames_logical), ...
                        [1 1 1], ...
                        'same') > 0;

                bad_frames_group = ...
                    find(bad_frames_logical);

                bad_frames_group = ...
                    bad_frames_group(:).';

                bad_segs_group = ...
                    badframes_to_segments( ...
                        bad_frames_group, ...
                        N);

                focus_segs_group = ...
                    bad_segs_group;

                deviation_group = ...
                    deviation_group(:).';

                data.motion.bad_frames_group{m} = ...
                    bad_frames_group;

                data.motion.bad_segs_group{m} = ...
                    bad_segs_group;

                data.motion.deviation_group{m} = ...
                    deviation_group;

                data.motion.focus_segs_group{m} = ...
                    focus_segs_group;

                data.motion.motion_energy_group{m} = ...
                    motion_energy_group;

                data.motion.speed_active_group{m} = ...
                    speed_active_group;

            else

                warning( ...
                    ['%s: impossible de calculer deviation group : ' ...
                     'corrXY manquant.'], ...
                    record_label_m);
            end
        elseif ~isempty(deviation_group) && ...
                ( ...
                    isempty(bad_frames_group) || ...
                    isempty(bad_segs_group) || ...
                    isempty(focus_segs_group) ...
                )

            % --------------------------------------------------
            % deviation_group already proves that the motion-artifact
            % analysis was performed. Empty bad-frame outputs are valid,
            % but if they are absent from memory they can be reconstructed
            % cheaply and deterministically from deviation_group.
            % --------------------------------------------------

            deviation_tmp = ...
                deviation_group(:);

            sigma_dev = ...
                std( ...
                    deviation_tmp( ...
                        deviation_tmp < 0), ...
                    'omitnan');

            seuil_bad = ...
                -3 * sigma_dev;

            bad_frames_logical = ...
                deviation_tmp < ...
                seuil_bad;

            bad_frames_logical = ...
                conv( ...
                    double(bad_frames_logical), ...
                    [1 1 1], ...
                    'same') > 0;

            bad_frames_group = ...
                find(bad_frames_logical);

            bad_frames_group = ...
                bad_frames_group(:).';

            bad_segs_group = ...
                badframes_to_segments( ...
                    bad_frames_group, ...
                    numel(deviation_tmp));

            focus_segs_group = ...
                bad_segs_group;

            data.motion.bad_frames_group{m} = ...
                bad_frames_group;

            data.motion.bad_segs_group{m} = ...
                bad_segs_group;

            data.motion.focus_segs_group{m} = ...
                focus_segs_group;

        end

        % Restaurer les decisions plan par plan, egalement en load_only.
        % L'ancien format scalaire est migre en une seule fois, en
        % privilegiant les statuts deja enregistres pour chaque plan.
        data = ensure_recording_keep_planes(data,m,nPlanes);
        for pp = 1:nPlanes
            data.recording_keep_group{m}{pp} = ...
                get_recording_keep_for_plane(data,m,pp);
        end

        % ======================================================
        % PLANES
        % ======================================================

        for p = 1:nPlanes

            has_new_gcamp_plane = false;
            has_new_electroporated_plane = false;
            has_new_combined_plane = false;

            % ==================================================
            % Output folder
            % ==================================================

            gcamp_output_folder_p = '';

            if m <= numel(gcamp_output_folders)

                current_recording_outputs = ...
                    gcamp_output_folders{m};

                if ischar(current_recording_outputs) || ...
                        isstring(current_recording_outputs)

                    current_recording_outputs = ...
                        cellstr(current_recording_outputs);
                end

                if iscell(current_recording_outputs) && ...
                        p <= numel(current_recording_outputs) && ...
                        ~isempty(current_recording_outputs{p})

                    gcamp_output_folder_p = ...
                        current_recording_outputs{p};
                end
            end

            if isstring(gcamp_output_folder_p)

                gcamp_output_folder_p = ...
                    char(gcamp_output_folder_p);
            end

            if isempty(gcamp_output_folder_p) || ...
                    ~ischar(gcamp_output_folder_p)

                fprintf( ...
                    '%s - plane %d: output folder absent.\n', ...
                    record_label_m, ...
                    p);

                continue;
            end

            if exist(gcamp_output_folder_p,'dir') ~= 7

                mkdir(gcamp_output_folder_p);
            end

            % ==================================================
            % Suite2p folder
            % ==================================================

            gcamp_suite2p_folder = '';

            if iscell(gcamp_suite2p_folders_m) && ...
                    numel(gcamp_suite2p_folders_m) >= p && ...
                    ~isempty(gcamp_suite2p_folders_m{p})

                gcamp_suite2p_folder = ...
                    gcamp_suite2p_folders_m{p};
            end

            while iscell(gcamp_suite2p_folder)

                if isempty(gcamp_suite2p_folder)

                    gcamp_suite2p_folder = '';
                    break;
                end

                gcamp_suite2p_folder = ...
                    gcamp_suite2p_folder{1};
            end

            % ==================================================
            % Branch
            % ==================================================

            use_combined_this_plane = ...
                process_electroporated_combined;

            stat_in = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'stat_by_plane', ...
                    m, ...
                    p);

            iscell_idx = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'iscell_idx_gcamp_by_plane', ...
                    m, ...
                    p);

            ops_in = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'ops_suite2p_by_plane', ...
                    m, ...
                    p);

            % ==================================================
            % Combined
            % ==================================================

            if use_combined_this_plane

                F_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'F_combined_by_plane', ...
                        m, ...
                        p);

                masks_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'mask_combined_by_plane', ...
                        m, ...
                        p);

                outlines_x_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'outlines_x_combined_by_plane', ...
                        m, ...
                        p);

                outlines_y_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'outlines_y_combined_by_plane', ...
                        m, ...
                        p);

                electroporated_indices_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'electroporated_indices_combined_by_plane', ...
                        m, ...
                        p);

                % ==================================================
                % Combined absent -> GCaMP
                % ==================================================

                if isempty(F_in)

                    use_combined_this_plane = ...
                        false;

                    F_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'F_gcamp_by_plane', ...
                            m, ...
                            p);

                    masks_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'gcamp_mask_by_plane', ...
                            m, ...
                            p);

                    outlines_x_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'outlines_gcampx_by_plane', ...
                            m, ...
                            p);

                    outlines_y_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'outlines_gcampy_by_plane', ...
                            m, ...
                            p);

                    electroporated_indices_in = [];

                    fprintf( ...
                        ['%s - plane %d: combined absent -> ' ...
                         'utilisation de F_gcamp.\n'], ...
                        record_label_m, ...
                        p);
                end

            else

                F_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'F_gcamp_by_plane', ...
                        m, ...
                        p);

                masks_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'gcamp_mask_by_plane', ...
                        m, ...
                        p);

                outlines_x_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'outlines_gcampx_by_plane', ...
                        m, ...
                        p);

                outlines_y_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'outlines_gcampy_by_plane', ...
                        m, ...
                        p);

                electroporated_indices_in = [];
            end

            % ==================================================
            % Detection branch
            % ==================================================

            if use_combined_this_plane

                cell_type = ...
                    'combined';

                detection_branch = ...
                    'combined_plane';

                valid_field = ...
                    'valid_combined_cells_by_plane';

                Acttmp2_field = ...
                    'Acttmp2_combined_by_plane';

                Raster_field = ...
                    'Raster_combined_by_plane';

                thresholds_field = ...
                    'thresholds_combined_by_plane';

                DF_field = ...
                    'DF_combined_by_plane';

                DF_raw_field = ...
                    'DF_raw_combined_by_plane';

                F0_field = ...
                    'F0_combined_by_plane';

                noise_field = ...
                    'noise_est_combined_by_plane';

                selection_summary_field = ...
                    'selection_summary_combined_by_plane';

            else

                cell_type = ...
                    'gcamp';

                detection_branch = ...
                    'gcamp_plane';

                valid_field = ...
                    'valid_gcamp_cells_by_plane';

                Acttmp2_field = ...
                    'Acttmp2_gcamp_by_plane';

                Raster_field = ...
                    'Raster_gcamp_by_plane';

                thresholds_field = ...
                    'thresholds_gcamp_by_plane';

                DF_field = ...
                    'DF_gcamp_by_plane';

                DF_raw_field = ...
                    'DF_raw_gcamp_by_plane';

                F0_field = ...
                    'F0_gcamp_by_plane';

                noise_field = ...
                    'noise_est_gcamp_by_plane';

                selection_summary_field = ...
                    'selection_summary_gcamp_by_plane';
            end

            % Tri sauvegarde du MEME referentiel que le DF charge.
            % Viewer : afficher l'ordre sauvegarde sans recalcul,
            % sauf si confirmation explicite (tri du DF final dans le tuner).
            isort1_saved = get_branch_plane_or_empty(data,detection_branch, ...
                ['isort1_' cell_type '_by_plane'],m,p);
            isort2_saved = get_branch_plane_or_empty(data,detection_branch, ...
                ['isort2_' cell_type '_by_plane'],m,p);
            Sm_saved = get_branch_plane_or_empty(data,detection_branch, ...
                ['Sm_' cell_type '_by_plane'],m,p);

            has_detection_plane = ...
                has_existing_detection_new( ...
                    data, ...
                    detection_branch, ...
                    DF_field, ...
                    m, ...
                    p);

            % ==================================================
            % Viewer / Load-only
            % ==================================================

            viewer_mode_requested_plane = ...
                false;

            load_only_plane = ...
                false;

            if has_detection_plane

                if isempty(global_existing_detection_action)

                    global_existing_detection_action = ...
                        ask_existing_detection_action_global( ...
                            record_label_m);
                end

                switch global_existing_detection_action

                    case 'viewer'

                        viewer_mode_requested_plane = ...
                            true;

                    case 'load_only'

                        load_only_plane = ...
                            true;
                end
            end

            % ==================================================
            % Mean image
            % ==================================================

            if numel(meanImgs_m) >= p

                meanImg = ...
                    meanImgs_m{p};

            else

                meanImg = [];
            end

            % ==================================================
            % Saved detection
            % ==================================================

            Acttmp2_saved = [];
            Raster_saved = [];
            thresholds_saved = [];
            valid_cells_saved = [];
            DF_sg_saved = [];
            DF_raw_saved = [];
            F0_saved = [];
            noise_est_saved = [];
            selection_summary_saved = [];

            viewer_mode = ...
                viewer_mode_requested_plane && ...
                has_existing_detection_new( ...
                    data, ...
                    detection_branch, ...
                    DF_field, ...
                    m, ...
                    p);

            if viewer_mode || ...
                    load_only_plane

                valid_cells_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        valid_field, ...
                        m, ...
                        p);

                Acttmp2_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        Acttmp2_field, ...
                        m, ...
                        p);

                Raster_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        Raster_field, ...
                        m, ...
                        p);

                thresholds_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        thresholds_field, ...
                        m, ...
                        p);

                DF_sg_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        DF_field, ...
                        m, ...
                        p);

                DF_raw_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        DF_raw_field, ...
                        m, ...
                        p);

                F0_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        F0_field, ...
                        m, ...
                        p);

                noise_est_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        noise_field, ...
                        m, ...
                        p);

                selection_summary_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        selection_summary_field, ...
                        m, ...
                        p);

                % Existing full-length peaks, sorting and traces were
                % already retrieved from data, or selectively loaded once
                % from results_*.mat at recording entry. Never recompute
                % them just because the Viewer opens.

                % ==================================================
                % Load only
                % ==================================================

                if load_only_plane

                    fprintf( ...
                        ['%s - plane %d: existing detection ' ...
                         'loaded only.\n'], ...
                        record_label_m, ...
                        p);

                    call_random_peak_preview( ...
                        valid_cells_saved, ...
                        DF_sg_saved, ...
                        Acttmp2_saved, ...
                        thresholds_saved, ...
                        electroporated_indices_in, ...
                        sampling_rate_plane_m, ...
                        use_combined_this_plane, ...
                        include_electroporated, ...
                        gcamp_output_folder_p, ...
                        current_automatic_selection, ...
                        current_output_folder, ...
                        current_line, ...
                        animal, ...
                        date_m, ...
                        age_m, ...
                        p, ...
                        record_label_m, ...
                        modified_planes{m}(p));

                    if ~include_stims
                        data = crop_detection_data_for_plane( ...
                            data,m,p,nPlanes,first_stim_frame_global, ...
                            sync_frames_m,process_electroporated_combined);
                    end

                    continue;
                end
            end

            % ==================================================
            % COMPLETE temporal inputs for peak_detection_tuner.
            % No calcium, motion or bad-frame crop before the tuner.
            % ==================================================

            F_view = F_in;

            bad_frames = ...
                bad_frames_group;

            bad_segs = ...
                bad_segs_group;

            deviation = ...
                deviation_group;

            focus_segs = ...
                focus_segs_group;

            motion_energy = ...
                motion_energy_group;

            if isempty(F_view)

                continue;
            end

            % ==================================================
            % Behavior frame limit
            %
            % Toujours dans le référentiel GLOBAL.
            %
            % Si stim / motion ont fourni une limite, on l'utilise.
            %
            % Sinon, fallback exact à partir de la dernière frame
            % calcium du plan courant :
            %
            % global_frame =
            %     p + (j-1)*nPlanes
            % ==================================================

            behavior_frame_limit = ...
                behavior_frame_limit_m;

            if isempty(behavior_frame_limit)

                nPlaneFrames = ...
                    size(F_view,2);

                if nPlaneFrames > 0

                    behavior_frame_limit = ...
                        p + ...
                        (nPlaneFrames - 1) * ...
                        nPlanes;

                else

                    behavior_frame_limit = ...
                        0;
                end
            end

            % ==================================================
            % Comment
            % ==================================================

            % Commentaire de DETECTION (independant du recapitulatif).
            % Seul selection_summary.comment alimente le panneau editable
            % et est sauvegarde dans results_*.mat.
            comment_saved = '';

            if isstruct(selection_summary_saved) && ...
                    isfield(selection_summary_saved,'comment') && ...
                    ~isempty(selection_summary_saved.comment)

                comment_saved = selection_summary_saved.comment;
            end

            % Le voyant concerne exclusivement le plan courant.
            % Un statut d'un autre plan ne peut jamais servir de fallback.
            recording_keep_saved = get_recording_keep_for_plane( ...
                data,m,p);
            data.recording_keep_group{m}{p} = recording_keep_saved;

            % ==================================================
            % Peak tuner
            % ==================================================

            [ ...
                F0, ...
                noise_est, ...
                valid_cells, ...
                DF_sg, ...
                DF_raw, ...
                Raster, ...
                Acttmp2, ...
                MAct, ...
                thresholds, ...
                bad_segs_det, ...
                opts_det, ...
                has_new, ...
                selected_signal, ...
                selection_summary, ...
                isort1_plane, ...
                isort2_plane, ...
                Sm_plane ...
            ] = ...
                peak_detection_tuner( ...
                    current_type, ...
                    current_line, ...
                    animal, ...
                    date_m, ...
                    age_m, ...
                    p, ...
                    F_view, ...
                    sampling_rate_plane_m, ...
                    sampling_rate_motion_m, ...
                    sync_frames_m, ...
                    viewer_mode, ...
                    DF_sg_saved, ...
                    DF_raw_saved, ...
                    F0_saved, ...
                    noise_est_saved, ...
                    Acttmp2_saved, ...
                    Raster_saved, ...
                    thresholds_saved, ...
                    valid_cells_saved, ...
                    cell_type, ...
                    ops_in, ...
                    gcamp_suite2p_folder, ...
                    iscell_idx, ...
                    stat_in, ...
                    masks_in, ...
                    outlines_x_in, ...
                    outlines_y_in, ...
                    electroporated_indices_in, ...
                    meanImg, ...
                    TSeries_m, ...
                    current_camera_folder_m, ...
                    behavior_frame_limit, ...
                    deviation, ...
                    bad_frames, ...
                    focus_segs, ...
                    motion_energy, ...
                    speed_active_group, ...
                    metadata_gcamp_m, ...
                    gcamp_output_folder_p, ...
                    current_output_folder, ...
                    selection_summary_saved, ...
                    comment_saved, ...
                    isort1_saved, ...
                    isort2_saved, ...
                    Sm_saved, ...
                    recording_keep_saved, ...
                    first_stim_frame_global, ...
                    include_stims, ...
                    stim_frames_m, ...
                    recap_comment_m);

            % ==================================================
            % selected_signal = display / viewer information only
            %
            % IMPORTANT:
            % When electroporated processing is active, the outputs
            % returned by the tuner remain in the COMBINED reference.
            % selected_signal must therefore NOT change the saved branch.
            % ==================================================

            if isempty(selected_signal)

                if use_combined_this_plane
                    selected_signal = 'combined';
                else
                    selected_signal = 'gcamp';
                end
            end

            selected_signal = ...
                lower( ...
                    strtrim( ...
                        char(string(selected_signal))));

            if isstruct(selection_summary)
                selection_summary.selected_signal = selected_signal;
                % The saved matrices always contain the whole recording.
                % Only the returned data can be cropped after saving.
                selection_summary.include_stims = include_stims;
                selection_summary.results_include_stims = true;
                selection_summary.n_frames_full = size(F_view,2);
                selection_summary.n_frames_saved = size(F_view,2);
                nDataFrames = size(F_view,2);
                if ~include_stims && ~isempty(first_stim_frame_global) && ...
                        isscalar(first_stim_frame_global) && ...
                        isfinite(first_stim_frame_global)
                    nDataFrames = floor((round(first_stim_frame_global)-1-p) ...
                        /max(1,nPlanes))+1;
                    nDataFrames = max(0,min(size(F_view,2),nDataFrames));
                end
                selection_summary.n_frames_data = nDataFrames;
                selection_summary.data_include_stims = ...
                    nDataFrames >= size(F_view,2);
            end

            % ==================================================
            % Random peak preview
            %
            % Called in EVERY mode whenever a DF is available:
            %   - global / new detection
            %   - viewer, modified or not
            %   - load_only without an existing detection (the detection
            %     is calculated, then previewed here)
            %
            % load_only WITH an existing detection is handled earlier,
            % because peak_detection_tuner is not called in that case.
            % ==================================================

            % Preview the complete saved recording, including stimulations.
            call_random_peak_preview( ...
                valid_cells, ...
                DF_sg, ...
                Acttmp2, ...
                thresholds, ...
                electroporated_indices_in, ...
                sampling_rate_plane_m, ...
                use_combined_this_plane, ...
                include_electroporated, ...
                gcamp_output_folder_p, ...
                current_automatic_selection, ...
                current_output_folder, ...
                current_line, ...
                animal, ...
                date_m, ...
                age_m, ...
                p, ...
                record_label_m, ...
                logical(has_new) || modified_planes{m}(p));

            % ==================================================
            % Comment modified
            % ==================================================

            comment_modified = ...
                isstruct(selection_summary) && ...
                isfield( ...
                    selection_summary, ...
                    'comment_modified') && ...
                selection_summary.comment_modified;

            recording_keep_modified = isstruct(selection_summary) && ...
                isfield(selection_summary,'recording_keep_modified') && ...
                selection_summary.recording_keep_modified;

            if comment_modified

                selection_summary = ...
                    rmfield(selection_summary,'comment_modified');
                % transient UI flag must not enter results files
                if isfield(selection_summary,'recording_keep_modified')
                    selection_summary = rmfield(selection_summary, ...
                        'recording_keep_modified');
                end

                if use_combined_this_plane

                    data.combined_plane. ...
                        selection_summary_combined_by_plane{m}{p} = ...
                        selection_summary;

                    save_selection_summary_plane( ...
                        filePath_combined, ...
                        'selection_summary_combined_by_plane', ...
                        selection_summary, ...
                        p, ...
                        nPlanes);

                    comment_value = '';

                    if isfield( ...
                            selection_summary, ...
                            'comment')

                        comment_value = ...
                            selection_summary.comment;
                    end

                    data = ...
                        update_reconstructed_comment( ...
                            data, ...
                            m, ...
                            p, ...
