    end
end

function call_random_peak_preview( ...
        valid_cells, ...
        DF_sg, ...
        Acttmp2, ...
        thresholds, ...
        electroporated_indices, ...
        sampling_rate, ...
        use_combined, ...
        include_electroporated, ...
        gcamp_output_folder, ...
        automatic_selection, ...
        current_output_folder, ...
        current_line, ...
        animal, ...
        date_name, ...
        age, ...
        plane_index, ...
        record_label, ...
        modified_plane)

    % ==========================================================
    % Defaults
    % ==========================================================

    if nargin < 18 || ...
            isempty(modified_plane)

        modified_plane = ...
            false;
    end

    modified_plane = ...
        logical( ...
            modified_plane(1));


    % ==========================================================
    % Nothing to display
    % ==========================================================

    if isempty(DF_sg) || isempty(valid_cells)

        fprintf( ...
            '%s - plane %d: preview skipped, DF/valid_cells unavailable.\n', ...
            record_label, ...
            plane_index-1);

        return;
    end


    % Les results_*.mat peuvent maintenant contenir toutes les cellules.
    % create_random_peak_preview conserve son contrat historique :
    % matrices réduites aux valid_cells + IDs originaux dans valid_cells.
    DF_preview = DF_sg;
    Acttmp2_preview = Acttmp2;
    thresholds_preview = thresholds;

    valid_preview = round(double(valid_cells(:)));
    valid_preview = valid_preview( ...
        isfinite(valid_preview) & valid_preview>=1);

    if ~isempty(valid_preview) && ...
            size(DF_sg,1) ~= numel(valid_preview) && ...
            max(valid_preview) <= size(DF_sg,1)

        DF_preview = DF_sg(valid_preview,:);

        if iscell(Acttmp2) && max(valid_preview) <= numel(Acttmp2)
            Acttmp2_preview = Acttmp2(valid_preview);
        end

        if ~isempty(thresholds) && max(valid_preview) <= numel(thresholds)
            thresholds_preview = thresholds(valid_preview);
        end
    end

    % ==========================================================
    % Random peak preview
    % ==========================================================

    try

        create_random_peak_preview( ...
            valid_cells, ...
            DF_preview, ...
            Acttmp2_preview, ...
            thresholds_preview, ...
            electroporated_indices, ...
            sampling_rate, ...
            use_combined, ...
            include_electroporated, ...
            gcamp_output_folder, ...
            automatic_selection, ...
            current_output_folder, ...
            current_line, ...
            animal, ...
            date_name, ...
            age, ...
            plane_index - 1, ...
            modified_plane);

    catch ME

        warning( ...
            ['%s - plane %d: impossible de créer les ' ...
             'figures de détection : %s'], ...
            record_label, ...
            plane_index, ...
            ME.message);
    end
end