function summary = ...
    create_reconstructed_selection_summary( ...
        summary_combined, ...
        population_indices_combined, ...
        valid_cells_local, ...
        population_name)

    % ==========================================================
    % Nouveau selection_summary dans le référentiel local.
    %
    % Source de vérité :
    %   valid_cells_local
    %
    % Décisions héritées du Combined :
    %   manual_status
    %   cutoff_status
    % ==========================================================

    population_indices_combined = ...
        round( ...
            double( ...
                population_indices_combined(:)));

    population_indices_combined = ...
        population_indices_combined( ...
            isfinite(population_indices_combined) & ...
            population_indices_combined >= 1);

    nLocal = ...
        numel( ...
            population_indices_combined);

    % ==========================================================
    % Cellules réellement retenues
    % ==========================================================

    valid_cells_local = ...
        round( ...
            double( ...
                valid_cells_local(:)));

    valid_cells_local = ...
        valid_cells_local( ...
            isfinite(valid_cells_local) & ...
            valid_cells_local >= 1 & ...
            valid_cells_local <= nLocal);

    valid_cells_local = ...
        unique( ...
            valid_cells_local, ...
            'stable');

    % ==========================================================
    % Statuts
    % ==========================================================

    manual_status = ...
        zeros( ...
            nLocal, ...
            1);

    cutoff_status = ...
        zeros( ...
            nLocal, ...
            1);

    if ~isempty(summary_combined) && ...
            isstruct(summary_combined)

        if isfield( ...
                summary_combined, ...
                'manual_status') && ...
                ~isempty(summary_combined.manual_status)

            tmp = ...
                summary_combined.manual_status(:);

            valid_source = ...
                population_indices_combined <= ...
                numel(tmp);

            local_idx = ...
                find(valid_source);

            manual_status(local_idx) = ...
                tmp( ...
                    population_indices_combined( ...
                        valid_source));
        end

        if isfield( ...
                summary_combined, ...
                'cutoff_status') && ...
                ~isempty(summary_combined.cutoff_status)

            tmp = ...
                summary_combined.cutoff_status(:);

            valid_source = ...
                population_indices_combined <= ...
                numel(tmp);

            local_idx = ...
                find(valid_source);

            cutoff_status(local_idx) = ...
                tmp( ...
                    population_indices_combined( ...
                        valid_source));
        end
    end

    % ==========================================================
    % Etat final réellement sauvegardé
    % ==========================================================

    effective_status = ...
        -ones( ...
            nLocal, ...
            1);

    effective_status(valid_cells_local) = ...
        +1;

    active_indices = ...
        (1:nLocal).';

    % ==========================================================
    % Construction du summary
    % ==========================================================

    summary = ...
        struct();

    summary.selected_signal = ...
        population_name;

    summary.active_indices = ...
        active_indices;

    summary.valid_cells = ...
        valid_cells_local;

    summary.manual_status = ...
        manual_status;

    summary.cutoff_status = ...
        cutoff_status;

    summary.effective_status = ...
        effective_status;

    switch lower(population_name)

        case 'gcamp'

            summary.gcamp_indices = ...
                (1:nLocal).';

            summary.electroporated_indices = ...
                zeros(0,1);

        case 'electroporated'

            summary.gcamp_indices = ...
                zeros(0,1);

            summary.electroporated_indices = ...
                (1:nLocal).';

        otherwise

            summary.gcamp_indices = ...
                zeros(0,1);

            summary.electroporated_indices = ...
                zeros(0,1);
    end

    summary.n_total = ...
        nLocal;

    summary.n_kept_final = ...
        numel( ...
            valid_cells_local);

    summary.n_manual_keep = ...
        sum( ...
            manual_status == +1);

    summary.n_manual_excl = ...
        sum( ...
            manual_status == -1);

    summary.n_cutoff_keep = ...
        sum( ...
            cutoff_status == +1);

    summary.n_cutoff_excl = ...
        sum( ...
            cutoff_status == -1);
end

function MAct = recompute_mact_from_raster(Raster, synchronous_frames)
    if isempty(Raster)
        MAct = zeros(1,0);
        return;
    end

    Nz = size(Raster, 2);
    if Nz > synchronous_frames
        MAct = zeros(1, Nz - synchronous_frames);
        for i = 1:(Nz - synchronous_frames)
            MAct(i) = sum(max(Raster(:, i:i+synchronous_frames), [], 2));
        end
    else
        MAct = zeros(1,0);
    end
end

function [isort1_out, isort2_out, Sm_out] = compute_sort_outputs_from_df(DF_in, ops_in)
    isort1_out = [];
    isort2_out = [];
    Sm_out     = [];

    if isempty(DF_in)
        return;
    end

    try
        [isort1_out, isort2_out, Sm_out] = ...
            raster_processing(double(DF_in), ops_in);
    catch ME
        warning('compute_sort_outputs_from_df:raster_processing', ...
            'raster_processing failed (%s).', ME.message);
        isort1_out = [];
        isort2_out = [];
        Sm_out     = [];
    end
end


% =========================================================
% VIEWER, CHOIX UTILISATEUR ET PREVIEW
% =========================================================

function [viewer_mode, skip_plane] = ask_viewer(has_detection, record_label, p, cell_type)

    viewer_mode = false;
    skip_plane  = false;

    if ~has_detection
        return;
    end

    if nargin < 2 || isempty(record_label)
        record_label = 'record';
    end

    if nargin < 3 || isempty(p)
        p = 0;
    end

    if nargin < 4 || isempty(cell_type)
        cell_type = 'plane';
    end

    plane_label = sprintf('plane %d', p);

    msg = sprintf(['%s - %s\n\n' ...
                   'Existing %s detection found.\n\n' ...
                   'What do you want to do?'], ...
                   record_label, plane_label, cell_type);

    answer = questdlg( ...
        msg, ...
        'Existing detection', ...
        'Viewer', ...
        'Load only', ...
        'Load only');

    switch answer
        case 'Viewer'
            viewer_mode = true;
            skip_plane  = false;

        otherwise
            viewer_mode = false;
            skip_plane  = true;
    end
end

function action = ask_existing_detection_action_global(record_label)

    if nargin < 1 || isempty(record_label)
        record_label = 'record';
    end

    msg = sprintf([ ...
        '%s\n\n' ...
        'Existing peak detection was found.\n\n' ...
        'What do you want to do for all existing detections?'], ...
        record_label);

    answer = questdlg( ...
        msg, ...
        'Existing detection - global mode', ...
        'Viewer', ...
        'Load only', ...
        'Load only');

    switch answer
        case 'Viewer'
            action = 'viewer';

        otherwise
            action = 'load_only';
    end
end

