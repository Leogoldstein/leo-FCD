    for rr = 1:nRows
        recap_tseries(rr) = string( ...
            get_tseries_basename(recap_all_animal.TSeries(rr)));
    end

    recap_tseries = strtrim(recap_tseries);
    tseries_matches = find(strcmpi(recap_tseries,current_tseries));

    if isempty(tseries_matches)
        return;
    end

    % Exiger Date ET TSeries : jamais attribuer les valeurs au mauvais
    % enregistrement en cas d'homonyme ou de date differente.
    current_date = normalize_recap_date(date_value);
    recap_dates = strings(numel(tseries_matches),1);

    for jj = 1:numel(tseries_matches)
        recap_dates(jj) = normalize_recap_date( ...
            recap_all_animal.Date(tseries_matches(jj)));
    end

    matches = tseries_matches(strcmpi(recap_dates,current_date));
    if numel(matches) ~= 1
        if numel(matches) > 1
            warning('run_gcamp_peak_detection:AmbiguousRecapRow', ...
                'Date + TSeries non uniques dans recap_all_animal. Ligne non modifiee.');
        end
        return;
    end
    row_idx = matches(1);

    % La colonne Comment du recap est facultative et reste independante
    % de comment_saved (commentaire de detection par plan).
    if ~ismember('Comment',recap_all_animal.Properties.VariableNames)
        return;
    end
    comment_value = recap_all_animal.Comment(row_idx);

    if iscell(comment_value)
        if isempty(comment_value)
            return;
        end
        comment_value = comment_value{1};
    end

    comment_value = string(comment_value);

    if ~isempty(comment_value) && ~ismissing(comment_value(1))
        comment_text = char(comment_value(1));
    end
end


% =========================================================
% RECAP : UNE LIGNE PAR RECORDING, UNE CELLULE PAR PLAN
% =========================================================
function recap_all_animal = update_recap_detection_row( ...
        recap_all_animal,row_idx,data,m,nPlanes,processCombined)

    keep_by_plane = cell(nPlanes,1);
    comment_by_plane = repmat({''},nPlanes,1);

    for pp = 1:nPlanes
        % Priorite aux decisions individuelles, sans recopier le statut
        % d'un autre plan ou convertir [] en 0.
        keep_by_plane{pp} = get_recording_keep_for_plane(data,m,pp);

        % Meme branche que celle selectionnee pour le signal du plan :
        % Combined s'il existe et est demande, sinon GCaMP.
        useCombined = processCombined && ~isempty( ...
            get_branch_plane_or_empty(data,'combined_plane', ...
                'F_combined_by_plane',m,pp));
        if useCombined
            branch_names = {'combined','gcamp'};
        else
            branch_names = {'gcamp','combined'};
        end

        for bb = 1:numel(branch_names)
            name = branch_names{bb};
            if strcmp(name,'combined') && ~processCombined
                continue;
            end
            summary = get_branch_plane_or_empty( ...
                data,[name '_plane'], ...
                ['selection_summary_' name '_by_plane'],m,pp);
            if ~isstruct(summary) || isempty(summary)
                continue;
            end
            % Un commentaire vide d'un summary valide est intentionnel :
            % ne pas restaurer un commentaire obsolete de l'autre branche.
            if isfield(summary,'comment') && ~isempty(summary.comment)
                comment_by_plane{pp} = summary.comment;
            end
            break;
        end
    end

    % Indexation par accolades : chaque ligne contient elle-meme un
    % cell(nPlanes,1), et non nPlanes lignes supplementaires dans la table.
    recap_all_animal.recording_keep{row_idx} = keep_by_plane;
    recap_all_animal.comment_saved{row_idx} = comment_by_plane;
end


function name = get_tseries_basename(value)

    name = '';

    while iscell(value)
        if isempty(value)
            return;
        end
        value = value{1};
    end

    if isempty(value)
        return;
    end

    value = char(string(value));
    value = strtrim(value);

    if isempty(value)
        return;
    end

    value = regexprep(value,'[\\/]+$','');
    [~,name] = fileparts(value);

    % Si la valeur fournie est deja seulement un nom de TSeries,
    % fileparts le restitue normalement. Ce fallback couvre les cas
    % pathologiques ou aucun basename n'est obtenu.
    if isempty(name)
        name = value;
    end
end


function date_text = normalize_recap_date(value)

    while iscell(value)
        if isempty(value)
            date_text = "";
            return;
        end
        value = value{1};
    end

    if isdatetime(value)
        try
            date_text = string(value,'dd-MM-yyyy');
        catch
            date_text = string(value);
        end
    else
        date_text = string(value);
    end

    if isempty(date_text) || ismissing(date_text(1))
        date_text = "";
        return;
    end

    date_text = strtrim(date_text(1));
end


% =========================================================
% VIEWER, CHOIX UTILISATEUR ET PREVIEW
% =========================================================

function [viewer_mode, skip_plane] = ask_viewer(has_detection, record_label, p, cell_type)

    viewer_mode = false;
    skip_plane  = false;

    if ~has_detection
        return;
    end

    if nargin < 2 || isempty(record_label)
        record_label = 'record';
    end

    if nargin < 3 || isempty(p)
        p = 0;
    end

    if nargin < 4 || isempty(cell_type)
        cell_type = 'plane';
    end

    plane_label = sprintf('plane %d', p);

    msg = sprintf(['%s - %s\n\n' ...
                   'Existing %s detection found.\n\n' ...
                   'What do you want to do?'], ...
                   record_label, plane_label, cell_type);

    answer = questdlg( ...
        msg, ...
        'Existing detection', ...
        'Viewer', ...
        'Load only', ...
        'Load only');

    switch answer
        case 'Viewer'
            viewer_mode = true;
            skip_plane  = false;

        otherwise
            viewer_mode = false;
            skip_plane  = true;
    end
end

function action = ask_existing_detection_action_global(record_label)

    if nargin < 1 || isempty(record_label)
        record_label = 'record';
    end

    msg = sprintf([ ...
        '%s\n\n' ...
        'Existing peak detection was found.\n\n' ...
        'What do you want to do for all existing detections?'], ...
        record_label);

    answer = questdlg( ...
        msg, ...
        'Existing detection - global mode', ...
        'Viewer', ...
        'Load only', ...
        'Load only');

    switch answer
        case 'Viewer'
            action = 'viewer';

        otherwise
            action = 'load_only';
    end
end

function call_random_peak_preview( ...
        valid_cells, ...
        DF_sg, ...
        Acttmp2, ...
        thresholds, ...
        electroporated_indices, ...
        sampling_rate, ...
        use_combined, ...
        include_electroporated, ...
        gcamp_output_folder, ...
        automatic_selection, ...
        current_output_folder, ...
        current_line, ...
        animal, ...
        date_name, ...
        age, ...
        plane_index, ...
        record_label, ...
        modified_plane)

    % ==========================================================
    % Defaults
    % ==========================================================

    if nargin < 18 || ...
            isempty(modified_plane)

        modified_plane = ...
            false;
    end

    modified_plane = ...
        logical( ...
            modified_plane(1));


    % ==========================================================
    % Nothing to display
    % ==========================================================

    if isempty(DF_sg)

        fprintf( ...
            '%s - plane %d: preview skipped, DF unavailable.\n', ...
            record_label, ...
            plane_index-1);

        return;
    end


    % ==========================================================
    % Random peak preview
    % ==========================================================

    try

        create_random_peak_preview( ...
            valid_cells, ...
            DF_sg, ...
            Acttmp2, ...
            thresholds, ...
            electroporated_indices, ...
            sampling_rate, ...
            use_combined, ...
            include_electroporated, ...
            gcamp_output_folder, ...
            automatic_selection, ...
            current_output_folder, ...
            current_line, ...
            animal, ...
            date_name, ...
            age, ...
            plane_index - 1, ...
            modified_plane);

    catch ME

        warning( ...
            ['%s - plane %d: impossible de créer les ' ...
             'figures de détection : %s'], ...
            record_label, ...
            plane_index, ...
            ME.message);
    end
end