% SAUVEGARDE ET EFFACEMENT DES RESULTATS
% =========================================================
function save_selection_summary_plane( ...
        filePath, ...
        fieldName, ...
        selection_summary, ...
        p, ...
        nPlanes)

    % ==========================================================
    % Sauvegarde UNIQUEMENT le selection_summary du plan p.
    %
    % Aucun autre champ de détection n'est modifié.
    % Les autres plans sont conservés.
    % ==========================================================

    if isempty(filePath)
        return;
    end

    % ==========================================================
    % Charger uniquement le champ existant si possible
    % ==========================================================

    % Le champ selection_summary peut ne pas encore exister dans le MAT.
    % Charger uniquement les variables presentes pour eviter le warning
    % MATLAB "Variable '...' not found" sans toucher aux autres champs.
    S = load_available_variables_peak_detection( ...
        filePath, ...
        {fieldName});

    % ==========================================================
    % Anciennes valeurs
    % ==========================================================

    if isfield(S,fieldName)

        oldField = ...
            S.(fieldName);

        if iscell(oldField)

            planeValues = ...
                oldField(:);

        elseif nPlanes == 1

            planeValues = ...
                {oldField};

        else

            planeValues = ...
                cell(nPlanes,1);
        end

    else

        planeValues = ...
            cell(nPlanes,1);
    end

    % ==========================================================
    % Garantir nPlanes
    % ==========================================================

    if numel(planeValues) < nPlanes

        oldValues = ...
            planeValues;

        planeValues = ...
            cell(nPlanes,1);

        planeValues(1:numel(oldValues)) = ...
            oldValues(:);

    elseif numel(planeValues) > nPlanes

        planeValues = ...
            planeValues(1:nPlanes);
    end

    % ==========================================================
    % Nettoyage des anciens champs temporels, sur tous les plans.
    % Ne change aucune decision de selection des autres plans.
    % ==========================================================
    planeValues = ...
        strip_selection_summary_temporal_fields(planeValues);

    % Modifier uniquement le plan courant.
    planeValues{p} = ...
        strip_selection_summary_temporal_fields(selection_summary);

    saveStruct = ...
        struct();

    saveStruct.(fieldName) = ...
        planeValues;

    % ==========================================================
    % Sauvegarde
    % ==========================================================

    if exist(filePath,'file') == 2

        save( ...
            filePath, ...
            '-struct', ...
            'saveStruct', ...
            '-append');

    else

        save( ...
            filePath, ...
            '-struct', ...
            'saveStruct');
    end
end

