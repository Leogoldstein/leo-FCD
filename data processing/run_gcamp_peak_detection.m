function tf = viewer_motion_value_is_cropped( ...
        currentValue, ...
        fullValue, ...
        fieldName)

    tf = false;

    if isempty(fullValue)
        return;
    end

    if isempty(currentValue)
        tf = true;
        return;
    end

    switch fieldName

        case { ...
                'deviation_group', ...
                'motion_energy_group', ...
                'speed_active_group'}

            tf = ...
                numel(currentValue) < ...
                numel(fullValue);

        case 'bad_segs_group'

            if size(currentValue,1) < size(fullValue,1)

                tf = true;
                return;
            end

            if size(currentValue,2) >= 2 && ...
                    size(fullValue,2) >= 2

                current_end = ...
                    max( ...
                        double(currentValue(:,2)), ...
                        [], ...
                        'omitnan');

                full_end = ...
                    max( ...
                        double(fullValue(:,2)), ...
                        [], ...
                        'omitnan');

                tf = ...
                    isfinite(full_end) && ...
                    (~isfinite(current_end) || ...
                     current_end < full_end);
            end
    end
end


