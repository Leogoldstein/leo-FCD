function [data, has_new_saved, modified_planes] = run_gcamp_peak_detection( ...
    current_type, ...
    current_line, ...
    animal, ...
    current_dates, ...
    current_ages, ...
    current_gcamp_suite2p_folders, ...
    gcamp_root_folders, ...
    gcamp_output_folders, ...
    metadata, ...
    sampling_rate_plane, ...
    synchronous_frames_group, ...
    data, ...
    meanImgs_gcamp, ...
    current_gcamp_TSeries_path, ...
    include_electroporated, ...
    peak_detection_mode, ...
    current_automatic_selection, ...
    current_output_folders, ...
    clear_outputs_requested)

    numFolders = numel(gcamp_output_folders);

    % ==========================================================
    % Defaults
    % ==========================================================
    if nargin < 13 || isempty(include_electroporated)
        include_electroporated = '1';
    end
    
    if nargin < 14 || isempty(peak_detection_mode)
        peak_detection_mode = 'global';
    end

    include_electroporated = ...
        char(string(include_electroporated));

    process_electroporated_combined = ...
        strcmp(include_electroporated, '1');
    
    if nargin < 19 || ...
        isempty(clear_outputs_requested)

        clear_outputs_requested = ...
            false;
    end

    % ==========================================================
    % Detection fields GCaMP
    % ==========================================================
    fields_detect_gcamp = { ...
        'F0_gcamp_by_plane', ...
        'noise_est_gcamp_by_plane', ...
        'DF_gcamp_by_plane', ...
        'DF_raw_gcamp_by_plane', ...
        'valid_gcamp_cells_by_plane', ...
        'Raster_gcamp_by_plane', ...
        'Acttmp2_gcamp_by_plane', ...
        'MAct_gcamp_by_plane', ...
        'thresholds_gcamp_by_plane', ...
        'bad_segs_gcamp_plane', ...
        'opts_detection_gcamp_by_plane', ...
        'selection_summary_gcamp_by_plane', ...
        'isort1_gcamp_by_plane', ...
        'isort2_gcamp_by_plane', ...
        'Sm_gcamp_by_plane' ...
    };

    % ==========================================================
    % Detection fields electroporated
    % ==========================================================
    fields_detect_electroporated = { ...
        'F0_electroporated_by_plane', ...
        'noise_est_electroporated_by_plane', ...
        'DF_electroporated_by_plane', ...
        'DF_raw_electroporated_by_plane', ...
        'valid_electroporated_cells_by_plane', ...
        'Raster_electroporated_by_plane', ...
        'Acttmp2_electroporated_by_plane', ...
        'MAct_electroporated_by_plane', ...
        'thresholds_electroporated_by_plane', ...
        'bad_segs_electroporated_plane', ...
        'opts_detection_electroporated_by_plane', ...
        'selection_summary_electroporated_by_plane', ...
        'isort1_electroporated_by_plane', ...
        'isort2_electroporated_by_plane', ...
        'Sm_electroporated_by_plane' ...
    };

    % ==========================================================
    % Detection fields combined
    % ==========================================================
    fields_detect_combined = { ...
        'F0_combined_by_plane', ...
        'noise_est_combined_by_plane', ...
        'DF_combined_by_plane', ...
        'DF_raw_combined_by_plane', ...
        'valid_combined_cells_by_plane', ...
        'Raster_combined_by_plane', ...
        'Acttmp2_combined_by_plane', ...
        'MAct_combined_by_plane', ...
        'thresholds_combined_by_plane', ...
        'bad_segs_combined_plane', ...
        'opts_detection_combined_by_plane', ...
        'selection_summary_combined_by_plane', ...
        'isort1_combined_by_plane', ...
        'isort2_combined_by_plane', ...
        'Sm_combined_by_plane' ...
    };

    % ==========================================================
    % Motion
    % ==========================================================
    fields_motion_group = { ...
        'speed_active_group', ...
        'bad_frames_group', ...
        'bad_segs_group', ...
        'deviation_group', ...
        'focus_segs_group', ...
        'motion_energy_group' ...
    };
    
    % ==========================================================
    % CLEAR EXISTING PEAK-DETECTION OUTPUTS
    % ==========================================================
    
    if clear_outputs_requested
    
        fprintf('\n');
        fprintf('============================================\n');
        fprintf('CLEARING EXISTING PEAK-DETECTION OUTPUTS\n');
        fprintf('Animal: %s\n', char(string(animal)));
        fprintf('============================================\n');
    
    
        % ======================================================
        % Branches à effacer
        % ======================================================
    
        if process_electroporated_combined
    
            branches_to_clear = { ...
                'gcamp', ...
                'electroporated', ...
                'combined'};
    
        else
    
            branches_to_clear = { ...
                'gcamp'};
        end
    
    
        % ======================================================
        % Effacer dans les fichiers results_*.mat
        % ======================================================
    
        clear_detection_outputs( ...
            gcamp_root_folders, ...
            branches_to_clear, ...
            fields_detect_gcamp, ...
            fields_detect_electroporated, ...
            fields_detect_combined);
            
    
        % ======================================================
        % Effacer également les anciennes détections en mémoire
        %
        % IMPORTANT :
        % sinon branch_has_missing_fields() pourrait considérer
        % les données comme déjà disponibles dans data.
        % ======================================================
    
        if isfield(data,'gcamp_plane')
    
            for f = 1:numel(fields_detect_gcamp)
    
                fn = ...
                    fields_detect_gcamp{f};
    
                if isfield(data.gcamp_plane,fn)
    
                    data.gcamp_plane.(fn) = ...
                        cell(numFolders,1);
                end
            end
        end
    
    
        if process_electroporated_combined && ...
                isfield(data,'electroporated_plane')
    
            for f = 1:numel(fields_detect_electroporated)
    
                fn = ...
                    fields_detect_electroporated{f};
    
                if isfield( ...
                        data.electroporated_plane, ...
                        fn)
    
                    data.electroporated_plane.(fn) = ...
                        cell(numFolders,1);
                end
            end
        end
    
    
        if process_electroporated_combined && ...
                isfield(data,'combined_plane')
    
            for f = 1:numel(fields_detect_combined)
    
                fn = ...
                    fields_detect_combined{f};
    
                if isfield( ...
                        data.combined_plane, ...
                        fn)
    
                    data.combined_plane.(fn) = ...
                        cell(numFolders,1);
                end
            end
        end
    
    
        fprintf( ...
            'Existing peak-detection outputs cleared.\n\n');
    end

    % ==========================================================
    % Initialize branches
    % ==========================================================
    data = init_detection_branch_if_needed( ...
        data, ...
        'gcamp_plane', ...
        numFolders, ...
        fields_detect_gcamp);

    if process_electroporated_combined

        data = init_detection_branch_if_needed( ...
            data, ...
            'electroporated_plane', ...
            numFolders, ...
            fields_detect_electroporated);

        data = init_detection_branch_if_needed( ...
            data, ...
            'combined_plane', ...
            numFolders, ...
            fields_detect_combined);
    end

    data = init_motion_group_if_needed( ...
        data, ...
        numFolders, ...
        fields_motion_group);

    % ==========================================================
    % Existing-detection mode
    % ==========================================================
    processing_mode = ...
        lower(strtrim(char(string(peak_detection_mode))));

    global_existing_detection_action = '';

    switch processing_mode

        case 'viewer'

            global_existing_detection_action = ...
                'viewer';

        case 'load_only'

            global_existing_detection_action = ...
                'load_only';

        otherwise

            processing_mode = ...
                'global';
    end

    % ==========================================================
    % Flag global : au moins une nouvelle sortie de détection
    % a réellement été sauvegardée dans un results_*.mat.
    % ==========================================================
    has_new_saved = false;

    % ==========================================================
    % Plans modifiés par recording
    %
    % modified_planes{m}(p) = true uniquement si le plan p
    % du recording m a réellement été réécrit dans au moins
    % un fichier results_*.mat.
    % ==========================================================
    modified_planes = ...
        cell( ...
            numFolders, ...
            1);

    % ==========================================================
    % RECORDINGS
    % ==========================================================
    for m = 1:numFolders

        has_new_gcamp_group = false;
        has_new_electroporated_group = false;
        has_new_combined_group = false;
        has_new_motion_group = false;
    
        % ======================================================
        % Summary output folder du recording
        % ======================================================
    
        current_output_folder = '';
    
        if m <= numel(current_output_folders) && ...
                ~isempty(current_output_folders{m})
    
            current_output_folder = ...
                current_output_folders{m};
        end
        
        date_m = ...
            current_dates{m};

        record_label_m = ...
            sprintf( ...
                '%s - %s', ...
                string(animal), ...
                string(date_m));
        
        age_m = ...
            current_ages{m};

        sampling_rate_plane_m = ...
            sampling_rate_plane{m};

        sync_frames_m = ...
            synchronous_frames_group{m};

        metadata_m = ...
            get_metadata_for_record( ...
                metadata, ...
                m);
        
       gcamp_suite2p_folders_m = ...
            current_gcamp_suite2p_folders{m};

        % ======================================================
        % GCaMP metadata
        % ======================================================
        if ~isfield(metadata_m, 'gcamp_plane') || ...
                isempty(metadata_m.gcamp_plane)

            error( ...
                'GCaMP metadata missing for group %d.', ...
                m);
        end

        metadata_gcamp_m = ...
            metadata_m.gcamp_plane;

        % ======================================================
        % Number of planes
        % ======================================================
        if ~isfield(metadata_gcamp_m, 'NumPlanes') || ...
                isempty(metadata_gcamp_m.NumPlanes)

            error( ...
                'GCaMP metadata missing NumPlanes for group %d.', ...
                m);
        end

        nPlanes = ...
            max( ...
                1, ...
                round( ...
                    double( ...
                        metadata_gcamp_m.NumPlanes)));
        
        % ======================================================
        % Initialiser les flags des plans de ce recording
        % ======================================================
        
        if clear_outputs_requested
        
            % Tous les anciens résultats ont été supprimés :
            % toutes les figures par plan devront être recréées.
            modified_planes{m} = ...
                true( ...
                    1, ...
                    nPlanes);
        
        else
        
            % Seuls les plans effectivement sauvegardés seront marqués.
            modified_planes{m} = ...
                false( ...
                    1, ...
                    nPlanes);
        end
        
        sampling_rate_motion_m = ...
            sampling_rate_plane_m * nPlanes;

        % ======================================================
        % Initialize plane slots
        % ======================================================
        for f = 1:numel(fields_detect_gcamp)

            data = ensure_branch_plane_cell( ...
                data, ...
                'gcamp_plane', ...
                fields_detect_gcamp{f}, ...
                m, ...
                nPlanes);
        end

        if process_electroporated_combined

            for f = 1:numel(fields_detect_electroporated)

                data = ensure_branch_plane_cell( ...
                    data, ...
                    'electroporated_plane', ...
                    fields_detect_electroporated{f}, ...
                    m, ...
                    nPlanes);
            end

            for f = 1:numel(fields_detect_combined)

                data = ensure_branch_plane_cell( ...
                    data, ...
                    'combined_plane', ...
                    fields_detect_combined{f}, ...
                    m, ...
                    nPlanes);
            end
        end

        % ======================================================
        % Mean images
        % ======================================================
        if m <= numel(meanImgs_gcamp) && ...
                ~isempty(meanImgs_gcamp{m})

            meanImgs_m = ...
                meanImgs_gcamp{m};

        else

            meanImgs_m = ...
                cell(nPlanes, 1);
        end

        % ======================================================
        % GCaMP TSeries
        % ======================================================
        if m <= numel(current_gcamp_TSeries_path) && ...
                ~isempty(current_gcamp_TSeries_path{m})

            TSeries_m = ...
                current_gcamp_TSeries_path{m};

        else

            TSeries_m = '';
        end

        % ======================================================
        % Stim frames
        % ======================================================
        stim_frames_m = [];
        first_stim_frame_global = [];

        if isfield(data, 'stim') && ...
                isfield(data.stim, 'stim_frames_log_group') && ...
                isfield(data.stim, 'stim_protocol_group') && ...
                numel(data.stim.stim_frames_log_group) >= m && ...
                numel(data.stim.stim_protocol_group) >= m

            stim_frames_tmp = ...
                data.stim.stim_frames_log_group{m};

            stim_protocol_tmp = ...
                data.stim.stim_protocol_group{m};

            if ~isempty(stim_frames_tmp) && ...
                    ~isempty(stim_protocol_tmp)

                stim_frames_tmp = ...
                    stim_frames_tmp(:);

                stim_protocol_tmp = ...
                    stim_protocol_tmp(:);

                n = ...
                    min( ...
                        numel(stim_frames_tmp), ...
                        numel(stim_protocol_tmp));

                stim_frames_tmp = ...
                    stim_frames_tmp(1:n);

                stim_protocol_tmp = ...
                    stim_protocol_tmp(1:n);

                stim_frames_m = ...
                    stim_frames_tmp( ...
                        stim_protocol_tmp == 0);
            end
        end

        % ======================================================
        % First stimulation global frame
        % ======================================================
        if ~isempty(stim_frames_m)

            stim_tmp = ...
                double(stim_frames_m(:));

            stim_tmp = ...
                stim_tmp(isfinite(stim_tmp));

            if ~isempty(stim_tmp)

                first_stim_frame_global = ...
                    round(min(stim_tmp));
            end
        end

        % ======================================================
        % Recording root folder
        % ======================================================
        
        outdir_m = '';
        
        if m <= numel(gcamp_root_folders) && ...
                ~isempty(gcamp_root_folders{m})
        
            outdir_m = ...
                gcamp_root_folders{m};
        end
        
        
        if isstring(outdir_m)
        
            outdir_m = ...
                char(outdir_m);
        end
        
        
        if isempty(outdir_m) || ...
                ~ischar(outdir_m)
        
            fprintf( ...
                '%s: dossier gcamp_root invalide.\n', ...
                record_label_m);
        
            continue;
        end
        
        
        if exist( ...
                outdir_m, ...
                'dir') ~= 7
        
            mkdir( ...
                outdir_m);
        end

        % ======================================================
        % Results paths
        % ======================================================
        filePath_gcamp = ...
            fullfile( ...
                outdir_m, ...
                'results_gcamp.mat');

        filePath_electroporated = ...
            fullfile( ...
                outdir_m, ...
                'results_electroporated.mat');

        filePath_combined = ...
            fullfile( ...
                outdir_m, ...
                'results_combined.mat');

        filePath_motion = ...
            fullfile( ...
                outdir_m, ...
                'results_motion.mat');

        % ======================================================
        % Old motion filename migration
        % ======================================================
        oldMotionPath = ...
            fullfile( ...
                outdir_m, ...
                'results_movie.mat');

        if exist(oldMotionPath, 'file') == 2 && ...
                exist(filePath_motion, 'file') ~= 2

            movefile( ...
                oldMotionPath, ...
                filePath_motion);

            fprintf( ...
                '%s: renamed results_movie.mat -> results_motion.mat\n', ...
                record_label_m);
        end

        % ======================================================
        % Load GCaMP detection
        % ======================================================
        missing_gcamp = ...
            branch_has_missing_fields( ...
                data, ...
                'gcamp_plane', ...
                fields_detect_gcamp, ...
                m, ...
                nPlanes);

        if missing_gcamp

            if exist(filePath_gcamp, 'file') == 2

                fprintf( ...
                    ['%s : chargement de results_gcamp.mat ' ...
                     '(mémoire incomplète).\n'], ...
                    record_label_m);

                loaded_gcamp = ...
                    load(filePath_gcamp);

                data = ...
                    merge_loaded_branch_into_data( ...
                        data, ...
                        'gcamp_plane', ...
                        loaded_gcamp, ...
                        fields_detect_gcamp, ...
                        m, ...
                        nPlanes);

            else

                fprintf( ...
                    '%s : results_gcamp.mat absent.\n', ...
                    record_label_m);
            end

        else

            fprintf( ...
                ['%s : données GCaMP déjà complètes en mémoire, ' ...
                 'pas de reload.\n'], ...
                record_label_m);
        end

        % ======================================================
        % Electroporated + combined
        % ======================================================
        if process_electroporated_combined

            missing_electroporated = ...
                branch_has_missing_fields( ...
                    data, ...
                    'electroporated_plane', ...
                    fields_detect_electroporated, ...
                    m, ...
                    nPlanes);

            if missing_electroporated && ...
                    exist(filePath_electroporated, 'file') == 2

                loaded_electroporated = ...
                    load(filePath_electroporated);

                data = ...
                    merge_loaded_branch_into_data( ...
                        data, ...
                        'electroporated_plane', ...
                        loaded_electroporated, ...
                        fields_detect_electroporated, ...
                        m, ...
                        nPlanes);
            end

            missing_combined = ...
                branch_has_missing_fields( ...
                    data, ...
                    'combined_plane', ...
                    fields_detect_combined, ...
                    m, ...
                    nPlanes);

            if missing_combined && ...
                    exist(filePath_combined, 'file') == 2

                loaded_combined = ...
                    load(filePath_combined);

                data = ...
                    merge_loaded_branch_into_data( ...
                        data, ...
                        'combined_plane', ...
                        loaded_combined, ...
                        fields_detect_combined, ...
                        m, ...
                        nPlanes);
            end
        end

        % ======================================================
        % Load motion
        % ======================================================
        missing_motion = ...
            motion_group_has_missing_fields( ...
                data, ...
                fields_motion_group, ...
                m);

        if missing_motion && ...
                exist(filePath_motion, 'file') == 2

            loaded_motion = ...
                load(filePath_motion);

            data = ...
                merge_loaded_motion_group_into_data( ...
                    data, ...
                    loaded_motion, ...
                    fields_motion_group, ...
                    m);
        end

        speed_active_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'speed_active_group', ...
                m);

        bad_frames_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'bad_frames_group', ...
                m);

        bad_segs_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'bad_segs_group', ...
                m);

        deviation_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'deviation_group', ...
                m);

        focus_segs_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'focus_segs_group', ...
                m);

        motion_energy_group = ...
            get_motion_group_or_empty( ...
                data, ...
                'motion_energy_group', ...
                m);

        % ======================================================
        % Crop GLOBAL motion signals before first stimulation
        % ======================================================
        [ ...
            motion_energy_group, ...
            speed_active_group, ...
            motion_was_cropped ...
        ] = ...
            crop_motion_before_first_stim( ...
                motion_energy_group, ...
                speed_active_group, ...
                first_stim_frame_global);

        data.motion.motion_energy_group{m} = ...
            motion_energy_group;

        data.motion.speed_active_group{m} = ...
            speed_active_group;

        if motion_was_cropped

            has_new_motion_group = ...
                true;

            if ~isempty(first_stim_frame_global)

                fprintf( ...
                    ['%s: motion energy / speed active cropped ' ...
                     'before first stimulation ' ...
                     '(global frame %d).\n'], ...
                    record_label_m, ...
                    first_stim_frame_global);

            else

                fprintf( ...
                    ['%s: motion energy / speed active ' ...
                     'cropped.\n'], ...
                    record_label_m);
            end
        end

        % ======================================================
        % Motion reference ops
        % ======================================================
        ops_motion_ref = [];

        for pp = 1:nPlanes

            ops_motion_ref = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'ops_suite2p_by_plane', ...
                    m, ...
                    pp);

            if isempty(ops_motion_ref) && ...
                    process_electroporated_combined

                ops_motion_ref = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'electroporated_plane', ...
                        'ops_suite2p_electroporated_by_plane', ...
                        m, ...
                        pp);
            end

            if ~isempty(ops_motion_ref)
                break;
            end
        end

        motion_group_incomplete = ...
            isempty(bad_frames_group) || ...
            isempty(bad_segs_group) || ...
            isempty(deviation_group) || ...
            isempty(focus_segs_group) || ...
            isempty(motion_energy_group);

        if motion_group_incomplete

            if ~isempty(ops_motion_ref) && ...
                    isfield(ops_motion_ref, 'corrXY') && ...
                    ~isempty(ops_motion_ref.corrXY)

                corrXY = ...
                    ops_motion_ref.corrXY(:);

                N = ...
                    numel(corrXY);

                rolling_median = ...
                    movmedian( ...
                        corrXY, ...
                        300);

                deviation_group = ...
                    corrXY - rolling_median;

                sigma_dev = ...
                    std( ...
                        deviation_group( ...
                            deviation_group < 0), ...
                        'omitnan');

                seuil_bad = ...
                    -3 * sigma_dev;

                bad_frames_logical = ...
                    deviation_group < seuil_bad;

                bad_frames_logical = ...
                    conv( ...
                        double(bad_frames_logical), ...
                        [1 1 1], ...
                        'same') > 0;

                bad_frames_group = ...
                    find(bad_frames_logical);

                bad_frames_group = ...
                    bad_frames_group(:).';

                bad_segs_group = ...
                    badframes_to_segments( ...
                        bad_frames_group, ...
                        N);

                focus_segs_group = ...
                    bad_segs_group;

                deviation_group = ...
                    deviation_group(:).';

                data.motion.bad_frames_group{m} = ...
                    bad_frames_group;

                data.motion.bad_segs_group{m} = ...
                    bad_segs_group;

                data.motion.deviation_group{m} = ...
                    deviation_group;

                data.motion.focus_segs_group{m} = ...
                    focus_segs_group;

                data.motion.motion_energy_group{m} = ...
                    motion_energy_group;

                data.motion.speed_active_group{m} = ...
                    speed_active_group;

                has_new_motion_group = ...
                    true;

            else

                warning( ...
                    ['%s: impossible de calculer deviation group : ' ...
                     'corrXY manquant.'], ...
                    record_label_m);
            end
        end

        % ======================================================
        % PLANES
        % ======================================================
        for p = 1:nPlanes

            % ==================================================
            % Flags du plan courant
            % ==================================================
            has_new_gcamp_plane = false;
            has_new_electroporated_plane = false;
            has_new_combined_plane = false;

            % ==================================================
            % Plane output folder
            % ==================================================
            gcamp_output_folder_p = '';

            if m <= numel(gcamp_output_folders)

                current_recording_outputs = ...
                    gcamp_output_folders{m};

                if ischar(current_recording_outputs) || ...
                        isstring(current_recording_outputs)

                    current_recording_outputs = ...
                        cellstr(current_recording_outputs);
                end

                if iscell(current_recording_outputs) && ...
                        p <= numel(current_recording_outputs) && ...
                        ~isempty(current_recording_outputs{p})

                    gcamp_output_folder_p = ...
                        current_recording_outputs{p};
                end
            end

            if isstring(gcamp_output_folder_p)
                gcamp_output_folder_p = char(gcamp_output_folder_p);
            end

            if isempty(gcamp_output_folder_p) || ...
                    ~ischar(gcamp_output_folder_p)

                fprintf( ...
                    '%s - plane %d: output folder absent.\n', ...
                    record_label_m, ...
                    p);

                continue;
            end

            if exist(gcamp_output_folder_p, 'dir') ~= 7
                mkdir(gcamp_output_folder_p);
            end
            
            % ==================================================
            % Suite2p folder du plan courant
            % ==================================================
            
            gcamp_suite2p_folder = '';
            
            if iscell(gcamp_suite2p_folders_m) && ...
                    numel(gcamp_suite2p_folders_m) >= p && ...
                    ~isempty(gcamp_suite2p_folders_m{p})
            
                gcamp_suite2p_folder = ...
                    gcamp_suite2p_folders_m{p};
            end
            
            while iscell(gcamp_suite2p_folder)
            
                if isempty(gcamp_suite2p_folder)
            
                    gcamp_suite2p_folder = '';
                    break;
                end
            
                gcamp_suite2p_folder = ...
                    gcamp_suite2p_folder{1};
            end
            
            % ==================================================
            % Decide branch
            % ==================================================
            use_combined_this_plane = ...
                process_electroporated_combined;

            % ==================================================
            % Common Suite2p data
            % ==================================================
            stat_in = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'stat_by_plane', ...
                    m, ...
                    p);

            iscell_idx = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'iscell_idx_gcamp_by_plane', ...
                    m, ...
                    p);

            ops_in = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'ops_suite2p_by_plane', ...
                    m, ...
                    p);

            % ==================================================
            % Try combined
            % ==================================================
            if use_combined_this_plane
            
                F_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'F_combined_by_plane', ...
                        m, ...
                        p);
            
                masks_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'mask_combined_by_plane', ...
                        m, ...
                        p);
            
                outlines_x_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'outlines_x_combined_by_plane', ...
                        m, ...
                        p);
            
                outlines_y_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'outlines_y_combined_by_plane', ...
                        m, ...
                        p);
            
                electroporated_indices_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'electroporated_indices_combined_by_plane', ...
                        m, ...
                        p);
            
                % ==================================================
                % Combined absent -> fallback GCaMP
                % ==================================================
                if isempty(F_in)
            
                    use_combined_this_plane = ...
                        false;
            
                    F_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'F_gcamp_by_plane', ...
                            m, ...
                            p);
            
                    masks_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'gcamp_mask_by_plane', ...
                            m, ...
                            p);
            
                    outlines_x_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'outlines_gcampx_by_plane', ...
                            m, ...
                            p);
            
                    outlines_y_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'outlines_gcampy_by_plane', ...
                            m, ...
                            p);
            
                    electroporated_indices_in = [];
            
                    fprintf( ...
                        ['%s - plane %d: combined absent -> ' ...
                         'utilisation de F_gcamp.\n'], ...
                        record_label_m, ...
                        p);
                end
            
            else
            
                % ==================================================
                % GCaMP only
                % ==================================================
                F_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'F_gcamp_by_plane', ...
                        m, ...
                        p);
            
                masks_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'gcamp_mask_by_plane', ...
                        m, ...
                        p);
            
                outlines_x_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'outlines_gcampx_by_plane', ...
                        m, ...
                        p);
            
                outlines_y_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'outlines_gcampy_by_plane', ...
                        m, ...
                        p);
            
                electroporated_indices_in = [];
            end

            % ==================================================
            % Detection branch
            % ==================================================
            if use_combined_this_plane

                cell_type = ...
                    'combined';

                detection_branch = ...
                    'combined_plane';

                valid_field = ...
                    'valid_combined_cells_by_plane';

                Acttmp2_field = ...
                    'Acttmp2_combined_by_plane';

                Raster_field = ...
                    'Raster_combined_by_plane';

                thresholds_field = ...
                    'thresholds_combined_by_plane';

                DF_field = ...
                    'DF_combined_by_plane';

                DF_raw_field = ...
                    'DF_raw_combined_by_plane';

                F0_field = ...
                    'F0_combined_by_plane';

                noise_field = ...
                    'noise_est_combined_by_plane';

                selection_summary_field = ...
                    'selection_summary_combined_by_plane';

            else

                cell_type = ...
                    'gcamp';

                detection_branch = ...
                    'gcamp_plane';

                valid_field = ...
                    'valid_gcamp_cells_by_plane';

                Acttmp2_field = ...
                    'Acttmp2_gcamp_by_plane';

                Raster_field = ...
                    'Raster_gcamp_by_plane';

                thresholds_field = ...
                    'thresholds_gcamp_by_plane';

                DF_field = ...
                    'DF_gcamp_by_plane';

                DF_raw_field = ...
                    'DF_raw_gcamp_by_plane';

                F0_field = ...
                    'F0_gcamp_by_plane';

                noise_field = ...
                    'noise_est_gcamp_by_plane';

                selection_summary_field = ...
                    'selection_summary_gcamp_by_plane';
            end

            has_detection_plane = ...
                has_existing_detection_new( ...
                    data, ...
                    detection_branch, ...
                    DF_field, ...
                    m, ...
                    p);

            % ==================================================
            % Viewer / Load-only decision
            % ==================================================
            viewer_mode_requested_plane = ...
                false;

            load_only_plane = ...
                false;

            if has_detection_plane

                if isempty(global_existing_detection_action)

                    global_existing_detection_action = ...
                        ask_existing_detection_action_global( ...
                            record_label_m);
                end

                switch global_existing_detection_action

                    case 'viewer'

                        viewer_mode_requested_plane = ...
                            true;

                    case 'load_only'

                        load_only_plane = ...
                            true;
                end
            end

            % ==================================================
            % Mean image
            % ==================================================
            if numel(meanImgs_m) >= p

                meanImg = ...
                    meanImgs_m{p};

            else

                meanImg = [];
            end

            % ==================================================
            % Saved detection
            % ==================================================
            Acttmp2_saved = [];
            Raster_saved = [];
            thresholds_saved = [];
            valid_cells_saved = [];
            DF_sg_saved = [];
            DF_raw_saved = [];
            F0_saved = [];
            noise_est_saved = [];
            selection_summary_saved = [];

            viewer_mode = ...
                viewer_mode_requested_plane && ...
                has_existing_detection_new( ...
                    data, ...
                    detection_branch, ...
                    DF_field, ...
                    m, ...
                    p);

            if viewer_mode || ...
                    load_only_plane

                valid_cells_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        valid_field, ...
                        m, ...
                        p);

                Acttmp2_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        Acttmp2_field, ...
                        m, ...
                        p);

                Raster_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        Raster_field, ...
                        m, ...
                        p);

                thresholds_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        thresholds_field, ...
                        m, ...
                        p);

                DF_sg_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        DF_field, ...
                        m, ...
                        p);

                DF_raw_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        DF_raw_field, ...
                        m, ...
                        p);

                F0_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        F0_field, ...
                        m, ...
                        p);

                noise_est_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        noise_field, ...
                        m, ...
                        p);

                selection_summary_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        selection_summary_field, ...
                        m, ...
                        p);

                % ==================================================
                % LOAD ONLY
                % ==================================================
                if load_only_plane

                    fprintf( ...
                        ['%s - plane %d: existing detection ' ...
                         'loaded only.\n'], ...
                        record_label_m, ...
                        p);

                    call_random_peak_preview( ...
                        valid_cells_saved, ...
                        DF_sg_saved, ...
                        Acttmp2_saved, ...
                        thresholds_saved, ...
                        electroporated_indices_in, ...
                        sampling_rate_plane_m, ...
                        use_combined_this_plane, ...
                        include_electroporated, ...
                        gcamp_output_folder_p, ...
                        current_automatic_selection, ...
                        current_output_folder, ...
                        current_line, ...
                        animal, ...
                        date_m, ...
                        age_m, ...
                        p, ...
                        record_label_m, ...
                        modified_planes{m}(p));

                    continue;
                end
            end

            % ==================================================
            % Prepare F
            %
            % VIEWER :
            % IMPORTANT -> garder TOUTES les cellules originales.
            %
            % valid_cells_saved indique seulement quelles cellules
            % avaient été retenues lors du processing précédent.
            % ==================================================
            if viewer_mode

                F_view = ...
                    F_in;
            
                if ~isempty(first_stim_frame_global) && ...
                        isfinite(first_stim_frame_global)
            
                    first_stim_frame_plane = ...
                        ceil( ...
                            first_stim_frame_global / ...
                            nPlanes);
            
                    if first_stim_frame_plane > 1 && ...
                            first_stim_frame_plane <= ...
                            size(F_in,2)
            
                        last_frame = ...
                            first_stim_frame_plane - 1;
            
                        F_view = ...
                            F_in(:,1:last_frame);
                    end
                end
            else

                % ==================================================
                % Normal processing
                % ==================================================
                F_nostims = ...
                    F_in;

                % ==================================================
                % Calcium F is plane-based:
                % divide first global stimulation by nPlanes.
                % ==================================================
                if ~isempty(first_stim_frame_global) && ...
                        isfinite(first_stim_frame_global)

                    first_stim_frame_plane = ...
                        ceil( ...
                            first_stim_frame_global / ...
                            nPlanes);

                    if first_stim_frame_plane > 1 && ...
                            first_stim_frame_plane <= ...
                            size(F_in,2)

                        last_frame = ...
                            first_stim_frame_plane - 1;

                        F_nostims = ...
                            F_in(:,1:last_frame);
                    end
                end

                nT = ...
                    size(F_nostims,2);

                bad_frames = ...
                    bad_frames_group;

                bad_segs = ...
                    bad_segs_group;

                deviation = ...
                    deviation_group;

                focus_segs = ...
                    focus_segs_group;

                motion_energy = ...
                    motion_energy_group;

                if ~isempty(bad_frames)

                    bad_frames = ...
                        bad_frames(:).';

                    bad_frames = ...
                        bad_frames( ...
                            bad_frames >= 1 & ...
                            bad_frames <= nT);
                end

                if ~isempty(deviation)

                    deviation = ...
                        deviation(:).';

                    deviation = ...
                        deviation( ...
                            1:min( ...
                                nT, ...
                                numel(deviation)));
                end

                if ~isempty(bad_frames)

                    bad_segs = ...
                        badframes_to_segments( ...
                            bad_frames, ...
                            nT);

                    focus_segs = ...
                        bad_segs;

                    F_clean = ...
                        F_nostims;

                    F_clean(:,bad_frames) = ...
                        NaN;

                    F_clean = ...
                        fillmissing( ...
                            F_clean, ...
                            'linear', ...
                            2, ...
                            'EndValues', ...
                            'nearest');

                    F_nostims = ...
                        F_clean;

                else

                    bad_segs = [];
                    focus_segs = [];
                end

                F_view = ...
                    F_nostims;
            end

            % ==================================================
            % Viewer motion
            % ==================================================
            if viewer_mode

                bad_frames = ...
                    bad_frames_group;

                bad_segs = ...
                    bad_segs_group;

                deviation = ...
                    deviation_group;

                focus_segs = ...
                    focus_segs_group;

                motion_energy = ...
                    motion_energy_group;
            end

            if isempty(F_view)
                continue;
            end

            % ==================================================
            % Peak tuner
            %
            % selection_summary_saved permet notamment de restaurer :
            %
            %   manual_status
            %   cutoff_status
            %   effective_status
            %
            % ==================================================
            [ ...
                F0, ...
                noise_est, ...
                valid_cells, ...
                DF_sg, ...
                DF_raw, ...
                Raster, ...
                Acttmp2, ...
                MAct, ...
                thresholds, ...
                bad_segs_det, ...
                opts_det, ...
                has_new, ...
                selected_signal, ...
                selection_summary ...
            ] = ...
                peak_detection_tuner( ...
                    current_type, ...
                    current_line, ...
                    animal, ...
                    date_m, ...
                    age_m, ...
                    p, ...
                    F_view, ...
                    sampling_rate_plane_m, ...
                    sampling_rate_motion_m, ...
                    sync_frames_m, ...
                    viewer_mode, ...
                    DF_sg_saved, ...
                    DF_raw_saved, ...
                    F0_saved, ...
                    noise_est_saved, ...
                    Acttmp2_saved, ...
                    Raster_saved, ...
                    thresholds_saved, ...
                    valid_cells_saved, ...
                    cell_type, ...
                    ops_in, ...
                    gcamp_suite2p_folder, ...
                    iscell_idx, ...
                    stat_in, ...
                    masks_in, ...
                    outlines_x_in, ...
                    outlines_y_in, ...
                    electroporated_indices_in, ...
                    meanImg, ...
                    TSeries_m, ...
                    deviation, ...
                    bad_frames, ...
                    focus_segs, ...
                    motion_energy, ...
                    metadata_gcamp_m, ...
                    gcamp_output_folder_p, ...
                    current_output_folder, ...
                    selection_summary_saved);
            % ==================================================
            % Random peak preview
            %
            % En Viewer :
            % DF_sg contient toutes les cellules originales afin
            % d'afficher aussi les cellules exclues.
            %
            % valid_cells contient seulement les cellules retenues.
            %
            % On ne génère donc pas de random preview en Viewer.
            % ==================================================
            if ~viewer_mode
            
                call_random_peak_preview( ...
                    valid_cells, ...
                    DF_sg, ...
                    Acttmp2, ...
                    thresholds, ...
                    electroporated_indices_in, ...
                    sampling_rate_plane_m, ...
                    use_combined_this_plane, ...
                    include_electroporated, ...
                    gcamp_output_folder_p, ...
                    current_automatic_selection, ...
                    current_output_folder, ...
                    current_line, ...
                    animal, ...
                    date_m, ...
                    age_m, ...
                    p, ...
                    record_label_m, ...
                    modified_planes{m}(p));
            end

            % ==================================================
            % Viewer sans modification confirmée
            % ==================================================
            if viewer_mode && ...
                    ~has_new
            
                continue;
            end

            % ==================================================
            % No new outputs
            % ==================================================
            if ~has_new

                fprintf( ...
                    '%s - plane %d: no new outputs.\n', ...
                    record_label_m, ...
                    p);

                continue;
            end

            % ==================================================
            % COMBINED
            % ==================================================
            if use_combined_this_plane

                has_new_combined_group = ...
                    true;

                has_new_combined_plane = ...
                    true;

                [ ...
                    isort1_combined, ...
                    isort2_combined, ...
                    Sm_combined ...
                ] = ...
                    compute_sort_outputs_from_df( ...
                        DF_sg, ...
                        ops_in);

                data.combined_plane. ...
                    F0_combined_by_plane{m}{p} = ...
                    F0;

                data.combined_plane. ...
                    noise_est_combined_by_plane{m}{p} = ...
                    noise_est;

                data.combined_plane. ...
                    valid_combined_cells_by_plane{m}{p} = ...
                    valid_cells;

                data.combined_plane. ...
                    DF_combined_by_plane{m}{p} = ...
                    DF_sg;

                data.combined_plane. ...
                    DF_raw_combined_by_plane{m}{p} = ...
                    DF_raw;

                data.combined_plane. ...
                    Raster_combined_by_plane{m}{p} = ...
                    Raster;

                data.combined_plane. ...
                    Acttmp2_combined_by_plane{m}{p} = ...
                    Acttmp2;

                data.combined_plane. ...
                    MAct_combined_by_plane{m}{p} = ...
                    MAct;

                data.combined_plane. ...
                    thresholds_combined_by_plane{m}{p} = ...
                    thresholds;

                data.combined_plane. ...
                    bad_segs_combined_plane{m}{p} = ...
                    bad_segs_det;

                data.combined_plane. ...
                    opts_detection_combined_by_plane{m}{p} = ...
                    opts_det;

                data.combined_plane. ...
                    selection_summary_combined_by_plane{m}{p} = ...
                    selection_summary;

                data.combined_plane. ...
                    isort1_combined_by_plane{m}{p} = ...
                    isort1_combined;

                data.combined_plane. ...
                    isort2_combined_by_plane{m}{p} = ...
                    isort2_combined;

                data.combined_plane. ...
                    Sm_combined_by_plane{m}{p} = ...
                    Sm_combined;

                [ ...
                    data, ...
                    has_new_gcamp_plane, ...
                    has_new_electroporated_plane ...
                ] = ...
                    reconstruct_gcamp_electroporated_from_combined( ...
                        data, ...
                        m, ...
                        p, ...
                        valid_cells, ...
                        F0, ...
                        noise_est, ...
                        DF_sg, ...
                        DF_raw, ...
                        Raster, ...
                        Acttmp2, ...
                        thresholds, ...
                        bad_segs_det, ...
                        opts_det, ...
                        electroporated_indices_in, ...
                        sync_frames_m, ...
                        ops_in, ...
                        selection_summary, ...
                        size(F_in,1));

                has_new_gcamp_group = ...
                    has_new_gcamp_group || ...
                    has_new_gcamp_plane;

                has_new_electroporated_group = ...
                    has_new_electroporated_group || ...
                    has_new_electroporated_plane;

            % ==================================================
            % GCaMP only
            % ==================================================
            else

                has_new_gcamp_group = ...
                    true;

                has_new_gcamp_plane = ...
                    true;

                [ ...
                    isort1_plane, ...
                    isort2_plane, ...
                    Sm_plane ...
                ] = ...
                    compute_sort_outputs_from_df( ...
                        DF_sg, ...
                        ops_in);

                data.gcamp_plane. ...
                    F0_gcamp_by_plane{m}{p} = ...
                    F0;

                data.gcamp_plane. ...
                    noise_est_gcamp_by_plane{m}{p} = ...
                    noise_est;

                data.gcamp_plane. ...
                    valid_gcamp_cells_by_plane{m}{p} = ...
                    valid_cells;

                data.gcamp_plane. ...
                    DF_gcamp_by_plane{m}{p} = ...
                    DF_sg;

                data.gcamp_plane. ...
                    DF_raw_gcamp_by_plane{m}{p} = ...
                    DF_raw;

                data.gcamp_plane. ...
                    Raster_gcamp_by_plane{m}{p} = ...
                    Raster;

                data.gcamp_plane. ...
                    Acttmp2_gcamp_by_plane{m}{p} = ...
                    Acttmp2;

                data.gcamp_plane. ...
                    MAct_gcamp_by_plane{m}{p} = ...
                    MAct;

                data.gcamp_plane. ...
                    thresholds_gcamp_by_plane{m}{p} = ...
                    thresholds;

                data.gcamp_plane. ...
                    bad_segs_gcamp_plane{m}{p} = ...
                    bad_segs_det;

                data.gcamp_plane. ...
                    opts_detection_gcamp_by_plane{m}{p} = ...
                    opts_det;

                data.gcamp_plane. ...
                    selection_summary_gcamp_by_plane{m}{p} = ...
                    selection_summary;

                data.gcamp_plane. ...
                    isort1_gcamp_by_plane{m}{p} = ...
                    isort1_plane;

                data.gcamp_plane. ...
                    isort2_gcamp_by_plane{m}{p} = ...
                    isort2_plane;

                data.gcamp_plane. ...
                    Sm_gcamp_by_plane{m}{p} = ...
                    Sm_plane;
            end

            % ==================================================
            % SAVE ONLY MODIFIED PLANE
            %
            % Chaque results_*.mat conserve les autres plans
            % exactement tels qu'ils étaient.
            % ==================================================
            if has_new_gcamp_plane

                save_branch_plane_fields( ...
                    filePath_gcamp, ...
                    data, ...
                    'gcamp_plane', ...
                    fields_detect_gcamp, ...
                    m, ...
                    p, ...
                    nPlanes);

                has_new_saved = ...
                    true;

                modified_planes{m}(p) = ...
                    true;
            end

            if process_electroporated_combined && ...
                    has_new_electroporated_plane

                save_branch_plane_fields( ...
                    filePath_electroporated, ...
                    data, ...
                    'electroporated_plane', ...
                    fields_detect_electroporated, ...
                    m, ...
                    p, ...
                    nPlanes);

                has_new_saved = ...
                    true;

                modified_planes{m}(p) = ...
                    true;
            end

            if process_electroporated_combined && ...
                    has_new_combined_plane

                save_branch_plane_fields( ...
                    filePath_combined, ...
                    data, ...
                    'combined_plane', ...
                    fields_detect_combined, ...
                    m, ...
                    p, ...
                    nPlanes);

                has_new_saved = ...
                    true;

                modified_planes{m}(p) = ...
                    true;
            end
        end

        % ======================================================
        % SAVE RECORDING
        % Motion reste une donnée au niveau du recording.
        % ======================================================
        if has_new_motion_group

            save_motion_group_fields( ...
                filePath_motion, ...
                data, ...
                fields_motion_group, ...
                m);
        end
    end
end

