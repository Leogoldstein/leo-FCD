function data = crop_detection_data_for_plane( ...
        data,m,p,nPlanes,first_stim_frame_global,synchronous_frames,processCombined)

    if isempty(first_stim_frame_global) || ...
            ~isscalar(first_stim_frame_global) || ...
            ~isfinite(first_stim_frame_global)
        return;
    end

    if processCombined
        names = {'gcamp','electroporated','combined'};
    else
        names = {'gcamp'};
    end

    S = round(double(first_stim_frame_global));
    plane_index = max(1,round(double(p)));

    for b = 1:numel(names)
        name = names{b};
        branch = [name '_plane'];
        if ~isfield(data,branch) || ~isstruct(data.(branch))
            continue;
        end

        dfName = ['DF_' name '_by_plane'];
        df = get_branch_plane_or_empty(data,branch,dfName,m,p);
        if isempty(df)
            continue;
        end

        nFull = size(df,2);
        nKeep = floor((S - 1 - plane_index) / max(1,nPlanes)) + 1;
        nKeep = max(0,min(nFull,nKeep));

        matrixFields = { ...
            ['F0_' name '_by_plane'], ...
            ['DF_' name '_by_plane'], ...
            ['DF_raw_' name '_by_plane'], ...
            ['Raster_' name '_by_plane']};

        for k = 1:numel(matrixFields)
            fn = matrixFields{k};
            X = get_branch_plane_or_empty(data,branch,fn,m,p);
            if isempty(X), continue; end
            nk = max(0,min(size(X,2),nKeep));
            data.(branch).(fn){m}{p} = X(:,1:nk);
        end

        actName = ['Acttmp2_' name '_by_plane'];
        acts = get_branch_plane_or_empty(data,branch,actName,m,p);
        if iscell(acts)
            for c = 1:numel(acts)
                locs = acts{c};
                if isempty(locs), continue; end
                wasRow = isrow(locs);
                locs = round(double(locs(:)));
                locs = locs(isfinite(locs) & locs>=1 & locs<=nKeep);
                if wasRow, locs = locs.'; end
                acts{c} = locs;
            end
            data.(branch).(actName){m}{p} = acts;
        end

        rasterName = ['Raster_' name '_by_plane'];
        raster = get_branch_plane_or_empty(data,branch,rasterName,m,p);
        mactName = ['MAct_' name '_by_plane'];
        if isfield(data.(branch),mactName)
            data.(branch).(mactName){m}{p} = ...
                recompute_mact_from_raster(raster,synchronous_frames);
        end

        segName = ['bad_segs_' name '_plane'];
        segs = get_branch_plane_or_empty(data,branch,segName,m,p);
        if ~isempty(segs) && isnumeric(segs) && size(segs,2)>=2
            segs = double(segs(:,1:2));
            segs(:,1) = max(1,round(segs(:,1)));
            segs(:,2) = min(nKeep,round(segs(:,2)));
            segs = segs(segs(:,1)<=segs(:,2),:);
            data.(branch).(segName){m}{p} = segs;
        end

        % Sm may contain a temporal dimension depending on raster_processing.
        % Crop it only when a dimension unambiguously matches the full time.
        smName = ['Sm_' name '_by_plane'];
        Sm = get_branch_plane_or_empty(data,branch,smName,m,p);
        if ~isempty(Sm)
            data.(branch).(smName){m}{p} = ...
                crop_sm_time_if_present(Sm,nFull,nKeep);
        end

        summaryName = ['selection_summary_' name '_by_plane'];
        summary = get_branch_plane_or_empty(data,branch,summaryName,m,p);
        if isstruct(summary)
            if isfield(summary,'n_frames_full') && ...
                    isscalar(summary.n_frames_full) && ...
                    isfinite(summary.n_frames_full)
                summary.n_frames_saved = round(double(summary.n_frames_full));
            elseif ~isfield(summary,'n_frames_saved') || ...
                    isempty(summary.n_frames_saved)
                summary.n_frames_saved = nFull;
            end
            summary.n_frames_data = nKeep;
            summary.results_include_stims = true;
            summary.data_include_stims = nKeep >= nFull;
            data.(branch).(summaryName){m}{p} = summary;
        end
    end
end

function Sm = crop_sm_time_if_present(Sm,nFull,nKeep)
    if isempty(Sm) || nFull <= 0 || nKeep >= nFull
        return;
    end
    dims = size(Sm);
    matches = find(dims == nFull);
    if numel(matches) ~= 1
        return;
    end
    d = matches(1);
    idx = repmat({':'},1,ndims(Sm));
    idx{d} = 1:nKeep;
    Sm = Sm(idx{:});
end

function data = crop_motion_data_only(data,m,first_stim_frame_global)
    if isempty(first_stim_frame_global) || ...
            ~isscalar(first_stim_frame_global) || ...
            ~isfinite(first_stim_frame_global) || ...
            ~isfield(data,'motion') || ~isstruct(data.motion)
        return;
    end

    nKeep = max(0,round(double(first_stim_frame_global))-1);

    vectorFields = {'motion_energy_group','speed_active_group','deviation_group'};
    for k = 1:numel(vectorFields)
        fn = vectorFields{k};
        if ~isfield(data.motion,fn) || numel(data.motion.(fn))<m || ...
                isempty(data.motion.(fn){m})
            continue;
        end
        v = data.motion.(fn){m};
        nk = min(numel(v),nKeep);
        data.motion.(fn){m} = v(1:nk);
    end

    if isfield(data.motion,'bad_frames_group') && ...
            numel(data.motion.bad_frames_group)>=m && ...
            ~isempty(data.motion.bad_frames_group{m})
        bf = round(double(data.motion.bad_frames_group{m}(:).'));
        bf = bf(isfinite(bf) & bf>=1 & bf<=nKeep);
        data.motion.bad_frames_group{m} = bf;
    end

    segmentFields = {'bad_segs_group','focus_segs_group'};
    for k = 1:numel(segmentFields)
        fn = segmentFields{k};
        if ~isfield(data.motion,fn) || numel(data.motion.(fn))<m || ...
                isempty(data.motion.(fn){m})
            continue;
        end
        segs = double(data.motion.(fn){m});
        if size(segs,2)<2, continue; end
        segs = segs(:,1:2);
        segs(:,1) = max(1,round(segs(:,1)));
        segs(:,2) = min(nKeep,round(segs(:,2)));
        segs = segs(segs(:,1)<=segs(:,2),:);
        data.motion.(fn){m} = segs;
    end
end

function v = normalize_recording_keep_run(v)
    % Only [] (unknown), 0 or 1 are allowed; never coerce NaN to false.
    if ~(isnumeric(v) || islogical(v)) || ~isscalar(v) || ...
            ~isreal(v) || ~isfinite(double(v)) || ...
            ~ismember(double(v),[0 1])
        v = [];
    else
        v = double(v);
    end
end

function data = ensure_recording_keep_planes(data,m,nPlanes)
    % Format public : data.recording_keep_group{m}{p} = [], 0 ou 1.
    if ~isfield(data,'recording_keep_group') || ...
            ~iscell(data.recording_keep_group)
        data.recording_keep_group = cell(m,1);
    elseif numel(data.recording_keep_group) < m
        data.recording_keep_group{m} = [];
    end

    previous = data.recording_keep_group{m};
    values = cell(nPlanes,1);
    if iscell(previous)
        for pp = 1:min(nPlanes,numel(previous))
            values{pp} = normalize_recording_keep_run(previous{pp});
        end
    else
        % Ancien format : decision unique. On la reproduit pour migrer,
        % puis on restaure les valeurs specifiques aux plans si presentes.
        legacy = normalize_recording_keep_run(previous);
        values = repmat({legacy},nPlanes,1);
        for pp = 1:nPlanes
            explicit = get_recording_keep_from_branches(data,m,pp);
            if ~isempty(explicit)
                values{pp} = explicit;
            end
        end
    end
    data.recording_keep_group{m} = values;
end

function value = get_recording_keep_from_branches(data,m,p)
    value = [];
    % Le champ independant du statut prime sur un ancien summary.
    branches = {'gcamp','combined','electroporated'};
    for b = 1:numel(branches)
        name = branches{b};
        branch = [name '_plane'];
        if ~isfield(data,branch), continue; end
        flag = get_branch_plane_or_empty(data,branch, ...
            ['recording_keep_' name '_by_plane'],m,p);
        flag = normalize_recording_keep_run(flag);
        if ~isempty(flag)
            value = flag;
            return;
        end
        ss = get_branch_plane_or_empty(data,branch, ...
            ['selection_summary_' name '_by_plane'],m,p);
        if isstruct(ss) && isfield(ss,'recording_keep')
            flag = normalize_recording_keep_run(ss.recording_keep);
            if ~isempty(flag)
                value = flag;
                return;
            end
        end
    end
end

function value = get_recording_keep_for_plane(data,m,p)
    value = [];
    if isfield(data,'recording_keep_group') && ...
            iscell(data.recording_keep_group) && ...
            numel(data.recording_keep_group) >= m
        stored = data.recording_keep_group{m};
        if iscell(stored)
            if numel(stored) >= p
                value = normalize_recording_keep_run(stored{p});
                if ~isempty(value), return; end
            end
        else
            % Compatibilite avec un appel avant la migration.
            value = get_recording_keep_from_branches(data,m,p);
            if ~isempty(value), return; end
            value = normalize_recording_keep_run(stored);
            return;
        end
    end
    value = get_recording_keep_from_branches(data,m,p);
end

function data = save_recording_keep_for_plane( ...
        data,m,p,nPlanes,value,fileGcamp,fileElectroporated, ...
        fileCombined,includeElectroporated)
    % Modifier uniquement {m}{p}; tous les autres plans restent intacts.
    % Ne toucher ni DF, ni Raster, ni isort, ni Sm.
    value = normalize_recording_keep_run(value);
    if isempty(value), return; end
    data = ensure_recording_keep_planes(data,m,nPlanes);
    data.recording_keep_group{m}{p} = value;

    branches = {'gcamp','electroporated','combined'};
    files = {fileGcamp,fileElectroporated,fileCombined};
    for b = 1:numel(branches)
        name = branches{b};
        branch = [name '_plane'];
        % Ne pas creer de fichier absent pour une population non traitee.
        if b > 1 && ~includeElectroporated && ...
                exist(files{b},'file') ~= 2 && ~isfield(data,branch)
            continue;
        end
        if ~isfield(data,branch) || ~isstruct(data.(branch))
            data.(branch) = struct();
        end
        ssName = ['selection_summary_' name '_by_plane'];
        flagName = ['recording_keep_' name '_by_plane'];
        data = ensure_branch_plane_cell(data,branch,ssName,m,nPlanes);
        data = ensure_branch_plane_cell(data,branch,flagName,m,nPlanes);

        % Un summary peut exister sur disque mais pas encore en memoire.
        summary = data.(branch).(ssName){m}{p};
        if ~isstruct(summary) || isempty(fieldnames(summary))
            loaded = load_available_variables_peak_detection(files{b},{ssName});
            if isfield(loaded,ssName)
                diskSummaries = coerce_to_plane_cell(loaded.(ssName),nPlanes);
                summary = diskSummaries{p};
            end
        end
        toSave = {flagName};
        data.(branch).(flagName){m}{p} = value;
        if isstruct(summary) && ~isempty(fieldnames(summary))
            summary.recording_keep = value;
            data.(branch).(ssName){m}{p} = summary;
            toSave{end+1} = ssName;
        end

        % La routine conserve les autres cellules du MAT par variable ;
        % elle remplace uniquement le slot {p} de ces deux champs.
        if b == 1 || exist(files{b},'file') == 2
            save_branch_plane_fields(files{b},data,branch,toSave,m,p,nPlanes);
        end
    end
end

function data = init_detection_branch_if_needed(data, branchName, numFolders, fields)
    if ~isfield(data, branchName) || ~isstruct(data.(branchName)) || isempty(data.(branchName))
        data.(branchName) = struct();
    end

    for f = 1:numel(fields)
        fieldName = fields{f};
        if ~isfield(data.(branchName), fieldName) || ~iscell(data.(branchName).(fieldName))
            tmp = cell(numFolders,1);
            [tmp{:}] = deal([]);
            data.(branchName).(fieldName) = tmp;
        elseif numel(data.(branchName).(fieldName)) < numFolders
            old = data.(branchName).(fieldName);
            tmp = cell(numFolders,1);
            tmp(1:numel(old)) = old(:);
            data.(branchName).(fieldName) = tmp;
        end
    end
end

function data = ensure_branch_plane_cell(data, branchName, fieldName, m, nPlanes)
    if ~isfield(data.(branchName), fieldName)
        data.(branchName).(fieldName) = cell(m,1);
    end
    if numel(data.(branchName).(fieldName)) < m
        tmp = cell(m,1);
        tmp(1:numel(data.(branchName).(fieldName))) = data.(branchName).(fieldName)(:);
        data.(branchName).(fieldName) = tmp;
    end
    if isempty(data.(branchName).(fieldName){m}) || ~iscell(data.(branchName).(fieldName){m})
        data.(branchName).(fieldName){m} = cell(nPlanes,1);
    elseif numel(data.(branchName).(fieldName){m}) ~= nPlanes
        old = data.(branchName).(fieldName){m};
        new = cell(nPlanes,1);
        n = min(numel(old), nPlanes);
        new(1:n) = old(1:n);
        data.(branchName).(fieldName){m} = new;
    end
end

function out = coerce_to_plane_cell(val, nPlanes)
    if isempty(val)
        out = cell(nPlanes,1);
    elseif iscell(val)
        out = cell(nPlanes,1);
        nCopy = min(numel(val), nPlanes);
        out(1:nCopy) = val(1:nCopy);
    else
        out = cell(nPlanes,1);
        if nPlanes >= 1
            out{1} = val;
        end
    end
end

function data = init_motion_group_if_needed(data, numFolders, fields_motion_group)

    if ~isfield(data,'motion') || ~isstruct(data.motion)
        data.motion = struct();
    end

    for f = 1:numel(fields_motion_group)
        fn = fields_motion_group{f};

        if ~isfield(data.motion, fn) || ~iscell(data.motion.(fn))
            data.motion.(fn) = cell(numFolders,1);

        elseif numel(data.motion.(fn)) < numFolders
            old = data.motion.(fn);
            tmp = cell(numFolders,1);
            tmp(1:numel(old)) = old(:);
            data.motion.(fn) = tmp;
        end
    end
end


