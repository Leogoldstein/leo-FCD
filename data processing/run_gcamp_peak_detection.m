function [data, has_new_saved, modified_planes, recap_all_animal] = run_gcamp_peak_detection( ...
    current_type, ...
    current_line, ...
    animal, ...
    current_dates, ...
    current_ages, ...
    current_gcamp_suite2p_folders, ...
    gcamp_root_folders, ...
    gcamp_output_folders, ...
    current_camera_folders, ...
    metadata, ...
    sampling_rate_plane, ...
    synchronous_frames_group, ...
    data, ...
    meanImgs_gcamp, ...
    current_gcamp_TSeries_path, ...
    include_electroporated, ...
    peak_detection_mode, ...
    current_automatic_selection, ...
    current_output_folders, ...
    clear_outputs_requested, ...
    recap_all_animal, ...
    viewer_recording_mask)

    numFolders = ...
        numel(gcamp_output_folders);

    % ==========================================================
    % Optional Viewer recording mask
    %
    % Used only in Viewer mode. One logical value per recording.
    % Non-selected recordings are skipped entirely and are not marked
    % as modified.
    % ==========================================================

    if nargin < 22 || isempty(viewer_recording_mask)

        viewer_recording_mask = ...
            true(numFolders,1);

    else

        viewer_recording_mask = ...
            logical(viewer_recording_mask(:));

        if numel(viewer_recording_mask) ~= numFolders

            error( ...
                'run_gcamp_peak_detection:ViewerRecordingMaskSizeMismatch', ...
                ['viewer_recording_mask doit contenir une valeur par ' ...
                 'enregistrement (%d attendues, %d recues).'], ...
                numFolders, ...
                numel(viewer_recording_mask));
        end
    end

    % Une ligne du recap par enregistrement, une cellule par plan dans
    % chaque colonne. Conserver toutes les autres colonnes et lignes.
    if istable(recap_all_animal)
        if ~ismember('recording_keep',recap_all_animal.Properties.VariableNames) || ...
                ~iscell(recap_all_animal.recording_keep)
            recap_all_animal.recording_keep = cell(height(recap_all_animal),1);
        end
        if ~ismember('comment_saved',recap_all_animal.Properties.VariableNames) || ...
                ~iscell(recap_all_animal.comment_saved)
            recap_all_animal.comment_saved = cell(height(recap_all_animal),1);
        end
    end

    % ==========================================================
    % Full inputs / full results policy
    %
    % All F and detection inputs are assumed complete. The tuner always
    % receives the entire recording. Newly saved results_*.mat contain the
    % complete temporal detection matrices, even if include_stims=false.
    % Only the data RETURNED to the caller is cropped after the tuner
    % finishes and AFTER the complete results have been saved.
    % This applies both to calcium outputs and to data.motion.
    % In Viewer, any cropped motion is restored from results_motion.mat
    % before peak_detection_tuner is called.
    % ==========================================================
    include_stims = false;

    % ==========================================================
    % Defaults
    % ==========================================================

    if nargin < 16 || ...
            isempty(include_electroporated)

        include_electroporated = ...
            '1';
    end

    if nargin < 17 || ...
            isempty(peak_detection_mode)

        peak_detection_mode = ...
            'global';
    end

    if nargin < 20 || ...
            isempty(clear_outputs_requested)

        clear_outputs_requested = ...
            false;
    end

    include_electroporated = ...
        char(string(include_electroporated));

    process_electroporated_combined = ...
        strcmp( ...
            include_electroporated, ...
            '1');

    % ==========================================================
    % Detection fields GCaMP
    % ==========================================================

    fields_detect_gcamp = { ...
        'F0_gcamp_by_plane', ...
        'noise_est_gcamp_by_plane', ...
        'DF_gcamp_by_plane', ...
        'DF_raw_gcamp_by_plane', ...
        'valid_gcamp_cells_by_plane', ...
        'Raster_gcamp_by_plane', ...
        'Acttmp2_gcamp_by_plane', ...
        'MAct_gcamp_by_plane', ...
        'thresholds_gcamp_by_plane', ...
        'opts_detection_gcamp_by_plane', ...
        'selection_summary_gcamp_by_plane', ...
        'recording_keep_gcamp_by_plane', ...
        'isort1_gcamp_by_plane', ...
        'isort2_gcamp_by_plane', ...
        'Sm_gcamp_by_plane' ...
    };

    % ==========================================================
    % Detection fields electroporated
    % ==========================================================

    fields_detect_electroporated = { ...
        'F0_electroporated_by_plane', ...
        'noise_est_electroporated_by_plane', ...
        'DF_electroporated_by_plane', ...
        'DF_raw_electroporated_by_plane', ...
        'valid_electroporated_cells_by_plane', ...
        'Raster_electroporated_by_plane', ...
        'Acttmp2_electroporated_by_plane', ...
        'MAct_electroporated_by_plane', ...
        'thresholds_electroporated_by_plane', ...
        'opts_detection_electroporated_by_plane', ...
        'selection_summary_electroporated_by_plane', ...
        'recording_keep_electroporated_by_plane', ...
        'isort1_electroporated_by_plane', ...
        'isort2_electroporated_by_plane', ...
        'Sm_electroporated_by_plane' ...
    };

    % ==========================================================
    % Detection fields combined
    % ==========================================================

    fields_detect_combined = { ...
        'F0_combined_by_plane', ...
        'noise_est_combined_by_plane', ...
        'DF_combined_by_plane', ...
        'DF_raw_combined_by_plane', ...
        'valid_combined_cells_by_plane', ...
        'Raster_combined_by_plane', ...
        'Acttmp2_combined_by_plane', ...
        'MAct_combined_by_plane', ...
        'thresholds_combined_by_plane', ...
        'opts_detection_combined_by_plane', ...
        'selection_summary_combined_by_plane', ...
        'recording_keep_combined_by_plane', ...
        'isort1_combined_by_plane', ...
        'isort2_combined_by_plane', ...
        'Sm_combined_by_plane' ...
    };


    % ==========================================================
    % Motion temporelle utilisee par le Viewer
    %
    % Seuls ces champs sont croppes dans data puis, si necessaire,
    % restaures depuis results_motion.mat avant l'ouverture du Viewer.
    %
    % bad_segs_group est l'unique segmentation des mauvaises frames.
    % ==========================================================

    viewer_motion_fields = { ...
        'deviation_group', ...
        'bad_segs_group', ...
        'motion_energy_group', ...
        'speed_active_group' ...
    };


    % ==========================================================
    % CLEAR EXISTING PEAK-DETECTION OUTPUTS
    % ==========================================================

    if clear_outputs_requested

        fprintf('\n');
        fprintf('============================================\n');
        fprintf('CLEARING EXISTING PEAK-DETECTION OUTPUTS\n');
        fprintf('Animal: %s\n', char(string(animal)));
        fprintf('============================================\n');

        if process_electroporated_combined

            branches_to_clear = { ...
                'gcamp', ...
                'electroporated', ...
                'combined'};

        else

            branches_to_clear = { ...
                'gcamp'};
        end

        clear_detection_outputs( ...
            gcamp_root_folders, ...
            branches_to_clear, ...
            fields_detect_gcamp, ...
            fields_detect_electroporated, ...
            fields_detect_combined);

        % ======================================================
        % Clear memory
        % ======================================================

        if isfield(data,'gcamp_plane')

            for f = 1:numel(fields_detect_gcamp)

                fn = ...
                    fields_detect_gcamp{f};

                if isfield(data.gcamp_plane,fn)

                    if startsWith(fn,'selection_summary_')
                        % Garder les decisions precedentes comme reference.
                        data.gcamp_plane.(fn) = ...
                            strip_selection_summary_temporal_fields( ...
                                data.gcamp_plane.(fn));
                    elseif ~startsWith(fn,'recording_keep_')
                        data.gcamp_plane.(fn) = ...
                            cell(numFolders,1);
                    end
                end
            end
        end

        if process_electroporated_combined && ...
                isfield(data,'electroporated_plane')

            for f = 1:numel(fields_detect_electroporated)

                fn = ...
                    fields_detect_electroporated{f};

                if isfield(data.electroporated_plane,fn)

                    if startsWith(fn,'selection_summary_')
                        data.electroporated_plane.(fn) = ...
                            strip_selection_summary_temporal_fields( ...
                                data.electroporated_plane.(fn));
                    elseif ~startsWith(fn,'recording_keep_')
                        data.electroporated_plane.(fn) = ...
                            cell(numFolders,1);
                    end
                end
            end
        end

        if process_electroporated_combined && ...
                isfield(data,'combined_plane')

            for f = 1:numel(fields_detect_combined)

                fn = ...
                    fields_detect_combined{f};

                if isfield(data.combined_plane,fn)

                    if startsWith(fn,'selection_summary_')
                        data.combined_plane.(fn) = ...
                            strip_selection_summary_temporal_fields( ...
                                data.combined_plane.(fn));
                    elseif ~startsWith(fn,'recording_keep_')
                        data.combined_plane.(fn) = ...
                            cell(numFolders,1);
                    end
                end
            end
        end

        fprintf( ...
            'Existing peak-detection outputs cleared.\n\n');
    end

    % ==========================================================
    % Initialize branches
    % ==========================================================

    data = ...
        init_detection_branch_if_needed( ...
            data, ...
            'gcamp_plane', ...
            numFolders, ...
            fields_detect_gcamp);

    if process_electroporated_combined

        data = ...
            init_detection_branch_if_needed( ...
                data, ...
                'electroporated_plane', ...
                numFolders, ...
                fields_detect_electroporated);

        data = ...
            init_detection_branch_if_needed( ...
                data, ...
                'combined_plane', ...
                numFolders, ...
                fields_detect_combined);
    end


    % Decision independante POUR CHAQUE PLAN, sans toucher a DF/isort.
    if ~isfield(data,'recording_keep_group') || ...
            ~iscell(data.recording_keep_group)
        data.recording_keep_group = cell(numFolders,1);
    elseif numel(data.recording_keep_group) < numFolders
        data.recording_keep_group{numFolders} = [];
    end

    % ==========================================================
    % Existing-detection mode
    % ==========================================================

    processing_mode = ...
        lower( ...
            strtrim( ...
                char(string(peak_detection_mode))));

    global_existing_detection_action = '';

    switch processing_mode

        case 'viewer'

            global_existing_detection_action = ...
                'viewer';

        case 'load_only'

            global_existing_detection_action = ...
                'load_only';

        otherwise

            processing_mode = ...
                'global';
    end

    % ==========================================================
    % Outputs flags
    % ==========================================================

    has_new_saved = ...
        logical(clear_outputs_requested);

    modified_planes = ...
        cell( ...
            numFolders, ...
            1);

    % ==========================================================
    % RECORDINGS
    % ==========================================================

    for m = 1:numFolders

        % ======================================================
        % VIEWER SCOPE : skip non-selected recordings
        % ======================================================

        if strcmp(processing_mode,'viewer') && ...
                ~viewer_recording_mask(m)

            modified_planes{m} = [];
            continue;
        end

        has_new_gcamp_group = false;
        has_new_electroporated_group = false;
        has_new_combined_group = false;
        % ======================================================
        % Recording information
        % ======================================================

        current_output_folder = '';

        if m <= numel(current_output_folders) && ...
                ~isempty(current_output_folders{m})

            current_output_folder = ...
                current_output_folders{m};
        end

        date_m = ...
            current_dates{m};

        age_m = ...
            current_ages{m};

        record_label_m = ...
            sprintf( ...
                '%s - %s', ...
                string(animal), ...
                string(date_m));

        sampling_rate_plane_m = ...
            sampling_rate_plane{m};

        sync_frames_m = ...
            synchronous_frames_group{m};

        metadata_m = ...
            get_metadata_for_record( ...
                metadata, ...
                m);

        gcamp_suite2p_folders_m = ...
            current_gcamp_suite2p_folders{m};

        % ======================================================
        % Camera folder
        % ======================================================

        current_camera_folder_m = '';

        if m <= numel(current_camera_folders) && ...
                ~isempty(current_camera_folders{m})

            current_camera_folder_m = ...
                current_camera_folders{m};
        end

        % ======================================================
        % Metadata
        % ======================================================

        if ~isfield(metadata_m,'gcamp_plane') || ...
                isempty(metadata_m.gcamp_plane)

            error( ...
                'GCaMP metadata missing for group %d.', ...
                m);
        end

        metadata_gcamp_m = ...
            metadata_m.gcamp_plane;

        if ~isfield(metadata_gcamp_m,'NumPlanes') || ...
                isempty(metadata_gcamp_m.NumPlanes)

            error( ...
                'GCaMP metadata missing NumPlanes for group %d.', ...
                m);
        end

        nPlanes = ...
            max( ...
                1, ...
                round( ...
                    double( ...
                        metadata_gcamp_m.NumPlanes)));

        % ======================================================
        % Global frame rate
        %
        % Référentiel utilisé par :
        %   camera
        %   motion
        %   stim
        % ======================================================

        sampling_rate_motion_m = ...
            sampling_rate_plane_m * ...
            nPlanes;

        % ======================================================
        % Modified planes
        % ======================================================

        if clear_outputs_requested

            modified_planes{m} = ...
                true( ...
                    1, ...
                    nPlanes);

        else

            modified_planes{m} = ...
                false( ...
                    1, ...
                    nPlanes);
        end

        % ======================================================
        % Initialize plane slots
        % ======================================================

        for f = 1:numel(fields_detect_gcamp)

            data = ...
                ensure_branch_plane_cell( ...
                    data, ...
                    'gcamp_plane', ...
                    fields_detect_gcamp{f}, ...
                    m, ...
                    nPlanes);
        end

        if process_electroporated_combined

            for f = 1:numel(fields_detect_electroporated)

                data = ...
                    ensure_branch_plane_cell( ...
                        data, ...
                        'electroporated_plane', ...
                        fields_detect_electroporated{f}, ...
                        m, ...
                        nPlanes);
            end

            for f = 1:numel(fields_detect_combined)

                data = ...
                    ensure_branch_plane_cell( ...
                        data, ...
                        'combined_plane', ...
                        fields_detect_combined{f}, ...
                        m, ...
                        nPlanes);
            end
        end

        % ======================================================
        % Mean images
        % ======================================================

        if m <= numel(meanImgs_gcamp) && ...
                ~isempty(meanImgs_gcamp{m})

            meanImgs_m = ...
                meanImgs_gcamp{m};

        else

            meanImgs_m = ...
                cell(nPlanes,1);
        end

        % ======================================================
        % TSeries
        % ======================================================

        if m <= numel(current_gcamp_TSeries_path) && ...
                ~isempty(current_gcamp_TSeries_path{m})

            TSeries_m = ...
                current_gcamp_TSeries_path{m};

        else

            TSeries_m = '';
        end

        % ======================================================
        % Commentaire du recording : correspondance DATE + TSeries GCaMP.
        % Le tableau a deja ete filtre sur Type/Line/Animal par l'appelant.
        % Un commentaire vide dans recap_all_animal est intentionnel.
        % ======================================================

        recap_comment_m = '';
        recap_row_m = [];

        % recap_all_animal est le 21e argument et fait partie de la
        % signature actuelle de la fonction. Ne pas utiliser de test nargin
        % ici : l'ancien `nargin >= 22` rendait ce bloc inatteignable.
        if istable(recap_all_animal) && ...
                all(ismember({'Date','TSeries'}, ...
                             recap_all_animal.Properties.VariableNames)) && ...
                ~isempty(TSeries_m)

            [recap_comment_m, recap_row_m] = ...
                get_recap_comment_for_record( ...
                    recap_all_animal, ...
                    date_m, ...
                    TSeries_m);

            if isempty(recap_row_m)
                fprintf( ...
                    ['%s : aucune ligne recap associee au TSeries ' ...
                     'courant (date=%s, TSeries=%s).\n'], ...
                    record_label_m, ...
                    char(string(date_m)), ...
                    get_tseries_basename(TSeries_m));

            elseif isempty(strtrim(recap_comment_m))
                fprintf( ...
                    ['%s : aucun commentaire recap associe au TSeries ' ...
                     'courant (date=%s, TSeries=%s).\n'], ...
                    record_label_m, ...
                    char(string(date_m)), ...
                    get_tseries_basename(TSeries_m));
            end
        end

        % ======================================================
        % STIM
        % ======================================================

        stim_frames_m = [];
        first_stim_frame_global = [];

        if isfield(data,'stim') && ...
                isfield(data.stim,'stim_protocol_group') && ...
                numel(data.stim.stim_protocol_group) >= m

            % --------------------------------------------------
            % Frame reference for stimulation events
            %
            % Priority:
            %   1) stim_frames_log_group{m}
            %   2) stim_times_group{m} when stim_frames_log_group
            %      is absent or empty.
            %
            % IMPORTANT: stim_times_group is intentionally treated
            % here as already expressed in FRAMES (no time->frame
            % conversion is applied).
            % --------------------------------------------------

            stim_frames_tmp = [];

            if isfield(data.stim,'stim_frames_log_group') && ...
                    numel(data.stim.stim_frames_log_group) >= m && ...
                    ~isempty(data.stim.stim_frames_log_group{m})

                stim_frames_tmp = ...
                    data.stim.stim_frames_log_group{m};

            elseif isfield(data.stim,'stim_times_group') && ...
                    numel(data.stim.stim_times_group) >= m && ...
                    ~isempty(data.stim.stim_times_group{m})

                stim_frames_tmp = ...
                    data.stim.stim_times_group{m};
            end

            stim_protocol_tmp = ...
                data.stim.stim_protocol_group{m};

            if ~isempty(stim_frames_tmp) && ...
                    ~isempty(stim_protocol_tmp)

                stim_frames_tmp = ...
                    stim_frames_tmp(:);

                stim_protocol_tmp = ...
                    stim_protocol_tmp(:);

                n = ...
                    min( ...
                        numel(stim_frames_tmp), ...
                        numel(stim_protocol_tmp));

                stim_frames_tmp = ...
                    stim_frames_tmp(1:n);

                stim_protocol_tmp = ...
                    stim_protocol_tmp(1:n);

                stim_frames_m = ...
                    stim_frames_tmp( ...
                        stim_protocol_tmp == 0);
            end
        end

        % ======================================================
        % First stimulation in GLOBAL frame reference
        % ======================================================

        if ~isempty(stim_frames_m)

            stim_tmp = ...
                double( ...
                    stim_frames_m(:));

            stim_tmp = ...
                stim_tmp( ...
                    isfinite(stim_tmp));

            if ~isempty(stim_tmp)

                first_stim_frame_global = ...
                    round( ...
                        min(stim_tmp));
            end
        end

        % ======================================================
        % Recording root
        % ======================================================

        outdir_m = '';

        if m <= numel(gcamp_root_folders) && ...
                ~isempty(gcamp_root_folders{m})

            outdir_m = ...
                gcamp_root_folders{m};
        end

        if isstring(outdir_m)

            outdir_m = ...
                char(outdir_m);
        end

        if isempty(outdir_m) || ...
                ~ischar(outdir_m)

            fprintf( ...
                '%s: dossier gcamp_root invalide.\n', ...
                record_label_m);

            % Retourner aussi les statuts deja presents en memoire si ce
            % recording ne peut pas etre traite faute de dossier.
            if ~isempty(recap_row_m)
                recap_all_animal = update_recap_detection_row( ...
                    recap_all_animal,recap_row_m,data,m,nPlanes, ...
                    process_electroporated_combined);
            end
            continue;
        end

        if exist(outdir_m,'dir') ~= 7

            mkdir(outdir_m);
        end

        % ======================================================
        % Result files
        % ======================================================

        filePath_gcamp = ...
            fullfile( ...
                outdir_m, ...
                'results_gcamp.mat');

        filePath_electroporated = ...
            fullfile( ...
                outdir_m, ...
                'results_electroporated.mat');

        filePath_combined = ...
            fullfile( ...
                outdir_m, ...
                'results_combined.mat');

        filePath_motion = ...
            fullfile( ...
                outdir_m, ...
                'results_motion.mat');


        % ======================================================
        % Load GCaMP detection fields selectively
        %
        % If the detection core is absent, all missing detection
        % variables are requested. Once the core is already present,
        % legitimately-empty optional outputs do not trigger reloads.
        % ======================================================

        fields_to_load_gcamp = ...
            get_branch_fields_to_load( ...
                data, ...
                'gcamp_plane', ...
                fields_detect_gcamp, ...
                m, ...
                nPlanes);

        if ~isempty(fields_to_load_gcamp)

            if exist(filePath_gcamp,'file') == 2

                fprintf( ...
                    ['%s : chargement sélectif de results_gcamp.mat ' ...
                     '(mémoire incomplète).\n'], ...
                    record_label_m);

                loaded_gcamp = ...
                    load_available_variables_peak_detection( ...
                        filePath_gcamp, ...
                        fields_to_load_gcamp);

                data = ...
                    merge_loaded_branch_into_data( ...
                        data, ...
                        'gcamp_plane', ...
                        loaded_gcamp, ...
                        fields_to_load_gcamp, ...
                        m, ...
                        nPlanes);

            else

                fprintf( ...
                    '%s : results_gcamp.mat absent.\n', ...
                    record_label_m);
            end

        else

            fprintf( ...
                ['%s : données GCaMP déjà complètes en mémoire, ' ...
                 'pas de reload.\n'], ...
                record_label_m);
        end

        % ======================================================
        % Load Electroporated / Combined selectively
        % ======================================================

        if process_electroporated_combined

            fields_to_load_electroporated = ...
                get_branch_fields_to_load( ...
                    data, ...
                    'electroporated_plane', ...
                    fields_detect_electroporated, ...
                    m, ...
                    nPlanes);

            if ~isempty(fields_to_load_electroporated) && ...
                    exist(filePath_electroporated,'file') == 2

                loaded_electroporated = ...
                    load_available_variables_peak_detection( ...
                        filePath_electroporated, ...
                        fields_to_load_electroporated);

                data = ...
                    merge_loaded_branch_into_data( ...
                        data, ...
                        'electroporated_plane', ...
                        loaded_electroporated, ...
                        fields_to_load_electroporated, ...
                        m, ...
                        nPlanes);
            end

            fields_to_load_combined = ...
                get_branch_fields_to_load( ...
                    data, ...
                    'combined_plane', ...
                    fields_detect_combined, ...
                    m, ...
                    nPlanes);

            if ~isempty(fields_to_load_combined) && ...
                    exist(filePath_combined,'file') == 2

                loaded_combined = ...
                    load_available_variables_peak_detection( ...
                        filePath_combined, ...
                        fields_to_load_combined);

                data = ...
                    merge_loaded_branch_into_data( ...
                        data, ...
                        'combined_plane', ...
                        loaded_combined, ...
                        fields_to_load_combined, ...
                        m, ...
                        nPlanes);
            end
        end

        % Nettoyer les summaries deja en memoire, meme lorsque le
        % chargement selectif ne relit aucun champ depuis le disque.
        % Conserver toutes les decisions pour la nouvelle detection.
        data = sanitize_record_selection_summaries( ...
            data,m,nPlanes,process_electroporated_combined);

        % ======================================================
        % Motion inputs
        %
        % Toute la motion est chargee / calculee en amont par
        % load_or_process_motion. Cette fonction ne lit aucun fichier
        % motion et ne recalcule aucun artefact.
        % ======================================================

        % Camera motion : une valeur par acquisition.
        speed_active_group = get_motion_group_or_empty( ...
            data,'speed_active_group',m);
        motion_energy_group = get_motion_group_or_empty( ...
            data,'motion_energy_group',m);

        % Les artefacts Suite2p sont, eux, recuperes plus bas plan par plan :
        %   data.motion.deviation_group{m}{p}
        %   data.motion.bad_segs_group{m}{p}

        % Le tuner travaille sur les valeurs motion deja preparees.
        behavior_frame_limit_m = [];

        % Restaurer les decisions plan par plan, egalement en load_only.
        % L'ancien format scalaire est migre en une seule fois, en
        % privilegiant les statuts deja enregistres pour chaque plan.
        data = ensure_recording_keep_planes(data,m,nPlanes);
        for pp = 1:nPlanes
            data.recording_keep_group{m}{pp} = ...
                get_recording_keep_for_plane(data,m,pp);
        end

        % ======================================================
        % PLANES
        % ======================================================

        for p = 1:nPlanes

            has_new_gcamp_plane = false;
            has_new_electroporated_plane = false;
            has_new_combined_plane = false;

            % ==================================================
            % Output folder
            % ==================================================

            gcamp_output_folder_p = '';

            if m <= numel(gcamp_output_folders)

                current_recording_outputs = ...
                    gcamp_output_folders{m};

                if ischar(current_recording_outputs) || ...
                        isstring(current_recording_outputs)

                    current_recording_outputs = ...
                        cellstr(current_recording_outputs);
                end

                if iscell(current_recording_outputs) && ...
                        p <= numel(current_recording_outputs) && ...
                        ~isempty(current_recording_outputs{p})

                    gcamp_output_folder_p = ...
                        current_recording_outputs{p};
                end
            end

            if isstring(gcamp_output_folder_p)

                gcamp_output_folder_p = ...
                    char(gcamp_output_folder_p);
            end

            if isempty(gcamp_output_folder_p) || ...
                    ~ischar(gcamp_output_folder_p)

                fprintf( ...
                    '%s - plane %d: output folder absent.\n', ...
                    record_label_m, ...
                    p);

                continue;
            end

            if exist(gcamp_output_folder_p,'dir') ~= 7

                mkdir(gcamp_output_folder_p);
            end

            % ==================================================
            % Suite2p folder
            % ==================================================

            gcamp_suite2p_folder = '';

            if iscell(gcamp_suite2p_folders_m) && ...
                    numel(gcamp_suite2p_folders_m) >= p && ...
                    ~isempty(gcamp_suite2p_folders_m{p})

                gcamp_suite2p_folder = ...
                    gcamp_suite2p_folders_m{p};
            end

            while iscell(gcamp_suite2p_folder)

                if isempty(gcamp_suite2p_folder)

                    gcamp_suite2p_folder = '';
                    break;
                end

                gcamp_suite2p_folder = ...
                    gcamp_suite2p_folder{1};
            end

            % ==================================================
            % Branch
            % ==================================================

            use_combined_this_plane = ...
                process_electroporated_combined;

            stat_in = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'stat_by_plane', ...
                    m, ...
                    p);

            iscell_idx = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'iscell_idx_gcamp_by_plane', ...
                    m, ...
                    p);

            ops_in = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    'gcamp_plane', ...
                    'ops_suite2p_by_plane', ...
                    m, ...
                    p);

            % ==================================================
            % Combined
            % ==================================================

            if use_combined_this_plane

                F_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'F_combined_by_plane', ...
                        m, ...
                        p);

                masks_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'mask_combined_by_plane', ...
                        m, ...
                        p);

                outlines_x_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'outlines_x_combined_by_plane', ...
                        m, ...
                        p);

                outlines_y_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'outlines_y_combined_by_plane', ...
                        m, ...
                        p);

                electroporated_indices_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'combined_plane', ...
                        'electroporated_indices_combined_by_plane', ...
                        m, ...
                        p);

                % ==================================================
                % Combined absent -> GCaMP
                %
                % IMPORTANT EN VIEWER :
                % F en memoire peut avoir ete filtre/croppe, voire etre
                % absent, alors que la detection Combined sauvegardee est
                % disponible. Ne jamais choisir la branche Viewer a partir
                % de F. Si un DF Combined existe, conserver Combined ; F
                % complet sera recharge depuis results_combined.mat avant
                % l'appel du tuner.
                % ==================================================

                combined_detection_available = ...
                    has_existing_detection_new( ...
                        data, ...
                        'combined_plane', ...
                        'DF_combined_by_plane', ...
                        m, ...
                        p);

                if isempty(F_in) && ...
                        ~combined_detection_available

                    use_combined_this_plane = ...
                        false;

                    F_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'F_gcamp_by_plane', ...
                            m, ...
                            p);

                    masks_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'gcamp_mask_by_plane', ...
                            m, ...
                            p);

                    outlines_x_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'outlines_gcampx_by_plane', ...
                            m, ...
                            p);

                    outlines_y_in = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            'gcamp_plane', ...
                            'outlines_gcampy_by_plane', ...
                            m, ...
                            p);

                    electroporated_indices_in = [];

                    fprintf( ...
                        ['%s - plane %d: combined absent -> ' ...
                         'utilisation de F_gcamp.\n'], ...
                        record_label_m, ...
                        p);
                end

            else

                F_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'F_gcamp_by_plane', ...
                        m, ...
                        p);

                masks_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'gcamp_mask_by_plane', ...
                        m, ...
                        p);

                outlines_x_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'outlines_gcampx_by_plane', ...
                        m, ...
                        p);

                outlines_y_in = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        'gcamp_plane', ...
                        'outlines_gcampy_by_plane', ...
                        m, ...
                        p);

                electroporated_indices_in = [];
            end

            % ==================================================
            % Detection branch
            % ==================================================

            if use_combined_this_plane

                cell_type = ...
                    'combined';

                detection_branch = ...
                    'combined_plane';

                valid_field = ...
                    'valid_combined_cells_by_plane';

                Acttmp2_field = ...
                    'Acttmp2_combined_by_plane';

                Raster_field = ...
                    'Raster_combined_by_plane';

                thresholds_field = ...
                    'thresholds_combined_by_plane';

                DF_field = ...
                    'DF_combined_by_plane';

                DF_raw_field = ...
                    'DF_raw_combined_by_plane';

                F0_field = ...
                    'F0_combined_by_plane';

                noise_field = ...
                    'noise_est_combined_by_plane';

                selection_summary_field = ...
                    'selection_summary_combined_by_plane';

            else

                cell_type = ...
                    'gcamp';

                detection_branch = ...
                    'gcamp_plane';

                valid_field = ...
                    'valid_gcamp_cells_by_plane';

                Acttmp2_field = ...
                    'Acttmp2_gcamp_by_plane';

                Raster_field = ...
                    'Raster_gcamp_by_plane';

                thresholds_field = ...
                    'thresholds_gcamp_by_plane';

                DF_field = ...
                    'DF_gcamp_by_plane';

                DF_raw_field = ...
                    'DF_raw_gcamp_by_plane';

                F0_field = ...
                    'F0_gcamp_by_plane';

                noise_field = ...
                    'noise_est_gcamp_by_plane';

                selection_summary_field = ...
                    'selection_summary_gcamp_by_plane';
            end

            % Tri sauvegarde du MEME referentiel que le DF charge.
            % Viewer : afficher l'ordre sauvegarde sans recalcul,
            % sauf si confirmation explicite (tri du DF final dans le tuner).
            isort1_saved = get_branch_plane_or_empty(data,detection_branch, ...
                ['isort1_' cell_type '_by_plane'],m,p);
            isort2_saved = get_branch_plane_or_empty(data,detection_branch, ...
                ['isort2_' cell_type '_by_plane'],m,p);
            Sm_saved = get_branch_plane_or_empty(data,detection_branch, ...
                ['Sm_' cell_type '_by_plane'],m,p);

            has_detection_plane = ...
                has_existing_detection_new( ...
                    data, ...
                    detection_branch, ...
                    DF_field, ...
                    m, ...
                    p);

            % ==================================================
            % Viewer / Load-only
            % ==================================================

            viewer_mode_requested_plane = ...
                false;

            load_only_plane = ...
                false;

            if has_detection_plane

                if isempty(global_existing_detection_action)

                    global_existing_detection_action = ...
                        ask_existing_detection_action_global( ...
                            record_label_m);
                end

                switch global_existing_detection_action

                    case 'viewer'

                        viewer_mode_requested_plane = ...
                            true;

                    case 'load_only'

                        load_only_plane = ...
                            true;
                end
            end

            % ==================================================
            % Mean image
            % ==================================================

            if numel(meanImgs_m) >= p

                meanImg = ...
                    meanImgs_m{p};

            else

                meanImg = [];
            end

            % ==================================================
            % Saved detection
            % ==================================================

            Acttmp2_saved = [];
            Raster_saved = [];
            thresholds_saved = [];
            valid_cells_saved = [];
            DF_sg_saved = [];
            DF_raw_saved = [];
            F0_saved = [];
            noise_est_saved = [];
            selection_summary_saved = [];

            viewer_mode = ...
                viewer_mode_requested_plane && ...
                has_existing_detection_new( ...
                    data, ...
                    detection_branch, ...
                    DF_field, ...
                    m, ...
                    p);

            % ==================================================
            % VIEWER : charger directement les resultats sauvegardes
            %
            % Le pipeline sauvegarde DF / DF_raw / F0 / Raster / Acttmp2
            % AVANT tout crop. Le Viewer les recharge donc directement
            % depuis results_*.mat, sans comparaison de taille avec F.
            % ==================================================

            if viewer_mode

                if use_combined_this_plane

                    viewer_filePath = ...
                        filePath_combined;

                    viewer_fields = ...
                        fields_detect_combined;

                else

                    viewer_filePath = ...
                        filePath_gcamp;

                    viewer_fields = ...
                        fields_detect_gcamp;
                end

                if exist(viewer_filePath,'file') == 2

                    loaded_viewer = ...
                        load_available_variables_peak_detection( ...
                            viewer_filePath, ...
                            viewer_fields);

                    data = ...
                        merge_loaded_branch_into_data( ...
                            data, ...
                            detection_branch, ...
                            loaded_viewer, ...
                            viewer_fields, ...
                            m, ...
                            nPlanes, ...
                            p);

                    isort1_saved = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            detection_branch, ...
                            ['isort1_' cell_type '_by_plane'], ...
                            m, ...
                            p);

                    isort2_saved = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            detection_branch, ...
                            ['isort2_' cell_type '_by_plane'], ...
                            m, ...
                            p);

                    Sm_saved = ...
                        get_branch_plane_or_empty( ...
                            data, ...
                            detection_branch, ...
                            ['Sm_' cell_type '_by_plane'], ...
                            m, ...
                            p);

                else

                    warning( ...
                        ['%s - plane %d: Viewer : fichier results absent : %s'], ...
                        record_label_m, ...
                        p, ...
                        viewer_filePath);
                end
            end

            % ==================================================
            % VIEWER : restaurer uniquement les donnees motion
            % effectivement utilisees par l'interface.
            %
            % data.motion est compare a la version COMPLETE contenue dans
            % results_motion.mat. Seuls les champs identifies comme
            % croppes sont remplaces AVANT l'entree dans le tuner.
            %
            % Champs concernes :
            %   - deviation_group
            %   - bad_segs_group
            %   - motion_energy_group
            %   - speed_active_group
            % ==================================================

            if viewer_mode

                [data, motion_reloaded_for_viewer] = ...
                    restore_viewer_motion_from_results( ...
                        data, ...
                        m, ...
                        p, ...
                        filePath_motion, ...
                        viewer_motion_fields);

                if motion_reloaded_for_viewer

                    speed_active_group = ...
                        get_motion_group_or_empty( ...
                            data, ...
                            'speed_active_group', ...
                            m);

                    motion_energy_group = ...
                        get_motion_group_or_empty( ...
                            data, ...
                            'motion_energy_group', ...
                            m);
                end
            end

            % ==================================================
            % Migration automatique du selection_summary
            % ==================================================
            % Capturer d'abord un éventuel recording_keep legacy : il sera
            % déplacé vers son champ dédié avant suppression de l'ancien
            % contenu du summary.
            recording_keep_saved = ...
                get_recording_keep_for_plane(data,m,p);

            selection_summary_raw = ...
                get_branch_plane_or_empty( ...
                    data, ...
                    detection_branch, ...
                    selection_summary_field, ...
                    m, ...
                    p);

            if viewer_mode

                % En Viewer, le referentiel cellulaire vient uniquement du
                % DF sauvegarde complet. F est charge comme reserve brute,
                % mais ne pilote jamais la taille de l'interface.
                DF_summary_reference = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        DF_field, ...
                        m, ...
                        p);

                if isempty(DF_summary_reference)

                    error( ...
                        'run_gcamp_peak_detection:MissingViewerDF', ...
                        ['%s - plane %d: DF sauvegarde absent en Viewer.'], ...
                        record_label_m, ...
                        p-1);
                end

                nCells_summary = ...
                    size(DF_summary_reference,1);

            else

                nCells_summary = ...
                    size(F_in,1);
            end

            [selection_summary_saved,summary_migrated] = ...
                normalize_selection_summary_run( ...
                    selection_summary_raw, ...
                    nCells_summary);

            data.(detection_branch).(selection_summary_field){m}{p} = ...
                selection_summary_saved;

            if use_combined_this_plane
                selection_summary_file = filePath_combined;
            else
                selection_summary_file = filePath_gcamp;
            end

            if summary_migrated
                save_selection_summary_plane( ...
                    selection_summary_file, ...
                    selection_summary_field, ...
                    selection_summary_saved, ...
                    p, ...
                    nPlanes);

                if ~isempty(recording_keep_saved)
                    data = save_recording_keep_for_plane( ...
                        data,m,p,nPlanes,recording_keep_saved, ...
                        filePath_gcamp,filePath_electroporated, ...
                        filePath_combined,process_electroporated_combined);
                end
            end

            if viewer_mode || ...
                    load_only_plane

                valid_cells_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        valid_field, ...
                        m, ...
                        p);

                Acttmp2_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        Acttmp2_field, ...
                        m, ...
                        p);

                Raster_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        Raster_field, ...
                        m, ...
                        p);

                thresholds_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        thresholds_field, ...
                        m, ...
                        p);

                DF_sg_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        DF_field, ...
                        m, ...
                        p);

                DF_raw_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        DF_raw_field, ...
                        m, ...
                        p);

                F0_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        F0_field, ...
                        m, ...
                        p);

                noise_est_saved = ...
                    get_branch_plane_or_empty( ...
                        data, ...
                        detection_branch, ...
                        noise_field, ...
                        m, ...
                        p);

                % ==================================================
                % VIEWER : CHARGER F COMPLET D'OFFICE
                %
                % F n'est PAS le referentiel du Viewer. Il est charge ici
                % uniquement comme source brute de reserve, afin d'etre
                % disponible si l'utilisateur modifie un parametre de
                % preprocessing (window_size / SavGol).
                %
                % La taille attendue est imposee par DF_sg_saved. Un F
                % croppe/filtre ne peut donc jamais etre accepte en silence.
                % ==================================================

                if viewer_mode

                    if use_combined_this_plane
                        viewer_F_field = ...
                            'F_combined_by_plane';
                    else
                        viewer_F_field = ...
                            'F_gcamp_by_plane';
                    end

                    F_in = ...
                        load_complete_viewer_fluorescence( ...
                            viewer_filePath, ...
                            viewer_F_field, ...
                            p, ...
                            nPlanes, ...
                            DF_sg_saved, ...
                            F_in, ...
                            record_label_m);
                end

                % Existing full-length peaks, sorting and traces were
                % already retrieved from data, or selectively loaded once
                % from results_*.mat at recording entry. Never recompute
                % them just because the Viewer opens.

                % ==================================================
                % Load only
                % ==================================================

                if load_only_plane

                    fprintf( ...
                        ['%s - plane %d: existing detection ' ...
                         'loaded only.\n'], ...
                        record_label_m, ...
                        p);

                    call_random_peak_preview( ...
                        valid_cells_saved, ...
                        DF_sg_saved, ...
                        Acttmp2_saved, ...
                        thresholds_saved, ...
                        electroporated_indices_in, ...
                        sampling_rate_plane_m, ...
                        use_combined_this_plane, ...
                        include_electroporated, ...
                        gcamp_output_folder_p, ...
                        current_automatic_selection, ...
                        current_output_folder, ...
                        current_line, ...
                        animal, ...
                        date_m, ...
                        age_m, ...
                        p, ...
                        record_label_m, ...
                        modified_planes{m}(p));

                    % results_*.mat reste complet ; data ne conserve que
                    % les cellules retenues.
                    data = filter_detection_data_to_valid_cells( ...
                        data,m,p,process_electroporated_combined);

                    if ~include_stims
                        data = crop_detection_data_for_plane( ...
                            data,m,p,nPlanes,first_stim_frame_global, ...
                            sync_frames_m,process_electroporated_combined);
                    end

                    continue;
                end
            end

            % ==================================================
            % COMPLETE temporal inputs for peak_detection_tuner.
            % No calcium, motion or bad-frame crop before the tuner.
            % ==================================================

            F_view = F_in;

            % Artefacts Suite2p du PLAN COURANT uniquement.
            % Aucun fallback vers les artefacts d'un autre plan.
            bad_segs = ...
                get_motion_plane_or_empty( ...
                    data,'bad_segs_group',m,p);

            deviation = ...
                get_motion_plane_or_empty( ...
                    data,'deviation_group',m,p);

            % Motion camera : commune a l'acquisition.
            motion_energy = ...
                motion_energy_group;

            if viewer_mode

                if isempty(DF_sg_saved)

                    error( ...
                        'run_gcamp_peak_detection:MissingViewerDF', ...
                        ['%s - plane %d: Viewer impossible, ' ...
                         'DF_sg sauvegarde est vide.'], ...
                        record_label_m, ...
                        p-1);
                end

            elseif isempty(F_view)

                continue;
            end

            % ==================================================
            % Behavior frame limit
            %
            % Toujours dans le référentiel GLOBAL.
            %
            % Si stim / motion ont fourni une limite, on l'utilise.
            %
            % Sinon, fallback exact à partir de la dernière frame
            % calcium du plan courant :
            %
            % global_frame =
            %     p + (j-1)*nPlanes
            % ==================================================

            behavior_frame_limit = ...
                behavior_frame_limit_m;

            if isempty(behavior_frame_limit)

                if viewer_mode

                    % Reference temporelle du Viewer : DF sauvegarde complet.
                    nPlaneFrames = ...
                        size(DF_sg_saved,2);

                else

                    nPlaneFrames = ...
                        size(F_view,2);
                end

                if nPlaneFrames > 0

                    behavior_frame_limit = ...
                        p + ...
                        (nPlaneFrames - 1) * ...
                        nPlanes;

                else

                    behavior_frame_limit = ...
                        0;
                end
            end

            % ==================================================
            % Comment
            % ==================================================

            % Commentaire de DETECTION (independant du recapitulatif).
            % Seul selection_summary.comment alimente le panneau editable
            % et est sauvegarde dans results_*.mat.
            comment_saved = '';

            if isstruct(selection_summary_saved) && ...
                    isfield(selection_summary_saved,'comment') && ...
                    ~isempty(selection_summary_saved.comment)

                comment_saved = selection_summary_saved.comment;
            end

            % Le voyant concerne exclusivement le plan courant.
            % Un statut d'un autre plan ne peut jamais servir de fallback.
            if isempty(recording_keep_saved)
                recording_keep_saved = get_recording_keep_for_plane( ...
                    data,m,p);
            end
            data.recording_keep_group{m}{p} = recording_keep_saved;

            % ==================================================
            % Peak tuner
            % ==================================================

            [ ...
                F0, ...
                noise_est, ...
                valid_cells, ...
                DF_sg, ...
                DF_raw, ...
                Raster, ...
                Acttmp2, ...
                MAct, ...
                thresholds, ...
                opts_det, ...
                has_new, ...
                selected_signal, ...
                selection_summary, ...
                comment_modified, ...
                recording_keep_out, ...
                recording_keep_modified, ...
                isort1_plane, ...
                isort2_plane, ...
                Sm_plane ...
            ] = ...
                peak_detection_tuner( ...
                    current_type, ...
                    current_line, ...
                    animal, ...
                    date_m, ...
                    age_m, ...
                    p, ...
                    F_view, ...
                    sampling_rate_plane_m, ...
                    sampling_rate_motion_m, ...
                    sync_frames_m, ...
                    viewer_mode, ...
                    DF_sg_saved, ...
                    DF_raw_saved, ...
                    F0_saved, ...
                    noise_est_saved, ...
                    Acttmp2_saved, ...
                    Raster_saved, ...
                    thresholds_saved, ...
                    valid_cells_saved, ...
                    cell_type, ...
                    ops_in, ...
                    gcamp_suite2p_folder, ...
                    iscell_idx, ...
                    stat_in, ...
                    masks_in, ...
                    outlines_x_in, ...
                    outlines_y_in, ...
                    electroporated_indices_in, ...
                    meanImg, ...
                    TSeries_m, ...
                    current_camera_folder_m, ...
                    behavior_frame_limit, ...
                    deviation, ...
                    bad_segs, ...
                    motion_energy, ...
                    speed_active_group, ...
                    metadata_gcamp_m, ...
                    gcamp_output_folder_p, ...
                    current_output_folder, ...
                    selection_summary_saved, ...
                    comment_saved, ...
                    isort1_saved, ...
                    isort2_saved, ...
                    Sm_saved, ...
                    recording_keep_saved, ...
                    first_stim_frame_global, ...
                    include_stims, ...
                    stim_frames_m, ...
                    recap_comment_m, ...
                    clear_outputs_requested);

            % ==================================================
            % selected_signal = display / viewer information only
            %
            % IMPORTANT:
            % When electroporated processing is active, the outputs
            % returned by the tuner remain in the COMBINED reference.
            % selected_signal must therefore NOT change the saved branch.
            % ==================================================

            if isempty(selected_signal)

                if use_combined_this_plane
                    selected_signal = 'combined';
                else
                    selected_signal = 'gcamp';
                end
            end

            selected_signal = ...
                lower( ...
                    strtrim( ...
                        char(string(selected_signal))));

            if isstruct(selection_summary)
                % Summary = état global de sélection uniquement.
                % selected_signal reste une sortie d'affichage du tuner
                % mais n'est jamais sauvegardé dans selection_summary.
                selection_summary = ...
                    strip_selection_summary_temporal_fields(selection_summary);
            end

            % ==================================================
            % Random peak preview
            %
            % Called in EVERY mode whenever a DF is available:
            %   - global / new detection
            %   - viewer, modified or not
            %   - load_only without an existing detection (the detection
            %     is calculated, then previewed here)
            %
            % load_only WITH an existing detection is handled earlier,
            % because peak_detection_tuner is not called in that case.
            % ==================================================

            % Preview the complete saved recording, including stimulations.
            call_random_peak_preview( ...
                valid_cells, ...
                DF_sg, ...
                Acttmp2, ...
                thresholds, ...
                electroporated_indices_in, ...
                sampling_rate_plane_m, ...
                use_combined_this_plane, ...
                include_electroporated, ...
                gcamp_output_folder_p, ...
                current_automatic_selection, ...
                current_output_folder, ...
                current_line, ...
                animal, ...
                date_m, ...
                age_m, ...
                p, ...
                record_label_m, ...
                logical(has_new) || modified_planes{m}(p));

            % ==================================================
            % Comment modified
            % ==================================================

            if comment_modified

                if use_combined_this_plane

                    data.combined_plane. ...
                        selection_summary_combined_by_plane{m}{p} = ...
                        selection_summary;

                    save_selection_summary_plane( ...
                        filePath_combined, ...
                        'selection_summary_combined_by_plane', ...
                        selection_summary, ...
                        p, ...
                        nPlanes);

                    comment_value = '';

                    if isfield( ...
                            selection_summary, ...
                            'comment')

                        comment_value = ...
                            selection_summary.comment;
                    end

                    data = ...
                        update_reconstructed_comment( ...
                            data, ...
                            m, ...
                            p, ...
                            comment_value, ...
                            filePath_gcamp, ...
                            filePath_electroporated, ...
                            nPlanes);

                else

                    data.gcamp_plane. ...
                        selection_summary_gcamp_by_plane{m}{p} = ...
                        selection_summary;

                    save_selection_summary_plane( ...
                        filePath_gcamp, ...
                        'selection_summary_gcamp_by_plane', ...
                        selection_summary, ...
                        p, ...
                        nPlanes);
                end

                fprintf( ...
                    '%s - plane %d: comment saved.\n', ...
                    record_label_m, ...
                    p-1);
            end

            % ==================================================
            % Statut du plan courant uniquement, sans recalcul DF/isort.
            % Partage uniquement entre les populations de CE plan.
            % ==================================================
            recording_keep_current = ...
                normalize_recording_keep_run(recording_keep_out);
            if isempty(recording_keep_current)
                recording_keep_current = recording_keep_saved;
            end

            if recording_keep_modified && ~isempty(recording_keep_current)
                data = save_recording_keep_for_plane( ...
                    data,m,p,nPlanes,recording_keep_current, ...
                    filePath_gcamp,filePath_electroporated, ...
                    filePath_combined,process_electroporated_combined);
                fprintf('%s - plane %d: recording_keep = %d saved (no DF recompute).\n', ...
                    record_label_m,p-1,recording_keep_current);
            end

            % ==================================================
            % No new detection
            % ==================================================

            if ~has_new
                % In Viewer, no confirmation means no results file is
                % rewritten. The returned data still obeys include_stims.
                if ~viewer_mode
                    fprintf('%s - plane %d: no new outputs.\n', ...
                        record_label_m,p);
                end
                % Le Viewer a pu recharger le MAT complet : remettre data
                % au format historique réduit aux valid_cells.
                data = filter_detection_data_to_valid_cells( ...
                    data,m,p,process_electroporated_combined);

                if ~include_stims
                    data = crop_detection_data_for_plane( ...
                        data,m,p,nPlanes,first_stim_frame_global, ...
                        sync_frames_m,process_electroporated_combined);
                end
                continue;
            end

            % Synchroniser le groupe de statuts MEME si seule la selection
            % des cellules a ete confirmee (eventuellement statut []).
            if ~isempty(recording_keep_current)
                data.recording_keep_group{m}{p} = recording_keep_current;
            end

            % ==================================================
            % Combined
            % ==================================================

            if use_combined_this_plane

                has_new_combined_group = ...
                    true;

                has_new_combined_plane = ...
                    true;

                % Tri du DF final recalcule dans le tuner a la confirmation.
                isort1_combined = isort1_plane;
                isort2_combined = isort2_plane;
                Sm_combined = Sm_plane;

                data.combined_plane. ...
                    F0_combined_by_plane{m}{p} = ...
                    F0;

                data.combined_plane. ...
                    noise_est_combined_by_plane{m}{p} = ...
                    noise_est;

                data.combined_plane. ...
                    valid_combined_cells_by_plane{m}{p} = ...
                    valid_cells;

                data.combined_plane. ...
                    DF_combined_by_plane{m}{p} = ...
                    DF_sg;

                data.combined_plane. ...
                    DF_raw_combined_by_plane{m}{p} = ...
                    DF_raw;

                data.combined_plane. ...
                    Raster_combined_by_plane{m}{p} = ...
                    Raster;

                data.combined_plane. ...
                    Acttmp2_combined_by_plane{m}{p} = ...
                    Acttmp2;

                data.combined_plane. ...
                    MAct_combined_by_plane{m}{p} = ...
                    MAct;

                data.combined_plane. ...
                    thresholds_combined_by_plane{m}{p} = ...
                    thresholds;

                data.combined_plane. ...
                    opts_detection_combined_by_plane{m}{p} = ...
                    opts_det;

                data.combined_plane. ...
                    selection_summary_combined_by_plane{m}{p} = ...
                    selection_summary;

                data.combined_plane. ...
                    recording_keep_combined_by_plane{m}{p} = ...
                    recording_keep_current;

                data.combined_plane. ...
                    isort1_combined_by_plane{m}{p} = ...
                    isort1_combined;

                data.combined_plane. ...
                    isort2_combined_by_plane{m}{p} = ...
                    isort2_combined;

                data.combined_plane. ...
                    Sm_combined_by_plane{m}{p} = ...
                    Sm_combined;

                [ ...
                    data, ...
                    has_new_gcamp_plane, ...
                    has_new_electroporated_plane ...
                ] = ...
                    reconstruct_gcamp_electroporated_from_combined( ...
                        data, ...
                        m, ...
                        p, ...
                        valid_cells, ...
                        F0, ...
                        noise_est, ...
                        DF_sg, ...
                        DF_raw, ...
                        Raster, ...
                        Acttmp2, ...
                        thresholds, ...
                        opts_det, ...
                        electroporated_indices_in, ...
                        sync_frames_m, ...
                        isort1_combined, ...
                        isort2_combined, ...
                        Sm_combined, ...
                        selection_summary, ...
                        recording_keep_current, ...
                        size(DF_sg,1));

                has_new_gcamp_group = ...
                    has_new_gcamp_group || ...
                    has_new_gcamp_plane;

                has_new_electroporated_group = ...
                    has_new_electroporated_group || ...
                    has_new_electroporated_plane;

            % ==================================================
            % GCaMP only
            % ==================================================

            else

                has_new_gcamp_group = ...
                    true;

                has_new_gcamp_plane = ...
                    true;

                % Utiliser les trois sorties de peak_detection_tuner.
                % Aucun nouveau raster_processing dans cette fonction.

                data.gcamp_plane. ...
                    F0_gcamp_by_plane{m}{p} = ...
                    F0;

                data.gcamp_plane. ...
                    noise_est_gcamp_by_plane{m}{p} = ...
                    noise_est;

                data.gcamp_plane. ...
                    valid_gcamp_cells_by_plane{m}{p} = ...
                    valid_cells;

                data.gcamp_plane. ...
                    DF_gcamp_by_plane{m}{p} = ...
                    DF_sg;

                data.gcamp_plane. ...
                    DF_raw_gcamp_by_plane{m}{p} = ...
                    DF_raw;

                data.gcamp_plane. ...
                    Raster_gcamp_by_plane{m}{p} = ...
                    Raster;

                data.gcamp_plane. ...
                    Acttmp2_gcamp_by_plane{m}{p} = ...
                    Acttmp2;

                data.gcamp_plane. ...
                    MAct_gcamp_by_plane{m}{p} = ...
                    MAct;

                data.gcamp_plane. ...
                    thresholds_gcamp_by_plane{m}{p} = ...
                    thresholds;

                data.gcamp_plane. ...
                    opts_detection_gcamp_by_plane{m}{p} = ...
                    opts_det;

                data.gcamp_plane. ...
                    selection_summary_gcamp_by_plane{m}{p} = ...
                    selection_summary;

                data.gcamp_plane. ...
                    recording_keep_gcamp_by_plane{m}{p} = ...
                    recording_keep_current;

                data.gcamp_plane. ...
                    isort1_gcamp_by_plane{m}{p} = ...
                    isort1_plane;

                data.gcamp_plane. ...
                    isort2_gcamp_by_plane{m}{p} = ...
                    isort2_plane;

                data.gcamp_plane. ...
                    Sm_gcamp_by_plane{m}{p} = ...
                    Sm_plane;
            end

            % ==================================================
            % Save the COMPLETE detection before cropping returned data.
            % A confirmed Viewer selection may update rows/peaks but never
            % changes the time span of the recorded matrices.
            if has_new_gcamp_plane

                save_branch_plane_fields( ...
                    filePath_gcamp, ...
                    data, ...
                    'gcamp_plane', ...
                    fields_detect_gcamp, ...
                    m, ...
                    p, ...
                    nPlanes);

                has_new_saved = ...
                    true;

                modified_planes{m}(p) = ...
                    true;
            end

            if process_electroporated_combined && ...
                    has_new_electroporated_plane

                save_branch_plane_fields( ...
                    filePath_electroporated, ...
                    data, ...
                    'electroporated_plane', ...
                    fields_detect_electroporated, ...
                    m, ...
                    p, ...
                    nPlanes);

                has_new_saved = ...
                    true;

                modified_planes{m}(p) = ...
                    true;
            end

            if process_electroporated_combined && ...
                    has_new_combined_plane

                save_branch_plane_fields( ...
                    filePath_combined, ...
                    data, ...
                    'combined_plane', ...
                    fields_detect_combined, ...
                    m, ...
                    p, ...
                    nPlanes);

                has_new_saved = ...
                    true;

                modified_planes{m}(p) = ...
                    true;
            end

            % ==================================================
            % DATA-ONLY cell filtering, strictly AFTER all results_*.mat saves.
            %
            % Les MAT conservent toutes les cellules. data retrouve ensuite
            % uniquement les lignes correspondant aux valid_cells propres
            % à chaque branche.
            % ==================================================
            data = filter_detection_data_to_valid_cells( ...
                data,m,p,process_electroporated_combined);

            % ==================================================
            % DATA-ONLY temporal crop, après le filtrage cellulaire.
            if ~include_stims
                data = crop_detection_data_for_plane( ...
                    data,m,p,nPlanes,first_stim_frame_global, ...
                    sync_frames_m,process_electroporated_combined);
            end

        end

        % Mettre a jour la ligne du recording APRES tous les plans :
        % couvre le Viewer sans confirmation, load_only, detection nouvelle,
        % modification du commentaire ou du statut sans recalcul.
        if ~isempty(recap_row_m)
            recap_all_animal = update_recap_detection_row( ...
                recap_all_animal,recap_row_m,data,m,nPlanes, ...
                process_electroporated_combined);
        end

        % ======================================================
        % MOTION IS NOT SAVED
        %
        % Motion values computed/loaded above remain available in data for
        % the current execution only. results_motion.mat is never created
        % or modified by run_gcamp_peak_detection.
        % ======================================================

        % ======================================================
        % DATA-ONLY MOTION CROP
        %
        % Comme pour les sorties calcium :
        %   - results_motion.mat reste complet et n'est jamais modifie ;
        %   - seuls deviation, bad_segs, motion_energy et speed_active
        %     sont croppes dans data ;
        %   - le Viewer restaure uniquement les champs croppes depuis
        %     results_motion.mat avant d'entrer dans le tuner.
        % ======================================================

        if ~include_stims

            data = ...
                crop_motion_data_only( ...
                    data, ...
                    m, ...
                    first_stim_frame_global, ...
                    nPlanes);
        end
    end
end
