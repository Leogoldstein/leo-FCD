function summary = ...
    create_reconstructed_selection_summary( ...
        summary_combined, ...
        population_indices_combined, ...
        valid_cells_local, ...
        population_name)

    % ==========================================================
    % Nouveau selection_summary dans le référentiel local.
    %
    % Source de vérité :
    %   valid_cells_local
    %
    % Décisions héritées du Combined :
    %   manual_status
    %   cutoff_status
    % ==========================================================

    population_indices_combined = ...
        round( ...
            double( ...
                population_indices_combined(:)));

    population_indices_combined = ...
        population_indices_combined( ...
            isfinite(population_indices_combined) & ...
            population_indices_combined >= 1);

    nLocal = ...
        numel( ...
            population_indices_combined);

    % ==========================================================
    % Cellules réellement retenues
    % ==========================================================

    valid_cells_local = ...
        round( ...
            double( ...
                valid_cells_local(:)));

    valid_cells_local = ...
        valid_cells_local( ...
            isfinite(valid_cells_local) & ...
            valid_cells_local >= 1 & ...
            valid_cells_local <= nLocal);

    valid_cells_local = ...
        unique( ...
            valid_cells_local, ...
            'stable');

    % ==========================================================
    % Statuts
    % ==========================================================

    manual_status = ...
        zeros( ...
            nLocal, ...
            1);

    cutoff_status = ...
        zeros( ...
            nLocal, ...
            1);

    if ~isempty(summary_combined) && ...
            isstruct(summary_combined)

        if isfield( ...
                summary_combined, ...
                'manual_status') && ...
                ~isempty(summary_combined.manual_status)

            tmp = ...
                summary_combined.manual_status(:);

            valid_source = ...
                population_indices_combined <= ...
                numel(tmp);

            local_idx = ...
                find(valid_source);

            manual_status(local_idx) = ...
                tmp( ...
                    population_indices_combined( ...
                        valid_source));
        end

        if isfield( ...
                summary_combined, ...
                'cutoff_status') && ...
                ~isempty(summary_combined.cutoff_status)

            tmp = ...
                summary_combined.cutoff_status(:);

            valid_source = ...
                population_indices_combined <= ...
                numel(tmp);

            local_idx = ...
                find(valid_source);

            cutoff_status(local_idx) = ...
                tmp( ...
                    population_indices_combined( ...
                        valid_source));
        end
    end

    % ==========================================================
    % Etat final réellement sauvegardé
    % ==========================================================

    effective_status = ...
        -ones( ...
            nLocal, ...
            1);

    effective_status(valid_cells_local) = ...
        +1;

    active_indices = ...
        (1:nLocal).';

    % ==========================================================
    % Construction du summary
    % ==========================================================

    summary = ...
        struct();

    summary.selected_signal = ...
        population_name;

    if isfield(summary_combined,'recording_keep')
        summary.recording_keep = summary_combined.recording_keep;
    else
        summary.recording_keep = [];
    end

    % Preserve temporal-storage metadata from the complete Combined result.
    temporal_meta = {'include_stims','results_include_stims','data_include_stims', ...
        'n_frames_full','n_frames_saved','n_frames_data'};
    for tm = 1:numel(temporal_meta)
        fn = temporal_meta{tm};
        if isfield(summary_combined,fn)
            summary.(fn) = summary_combined.(fn);
        end
    end

    summary.active_indices = ...
        active_indices;

    summary.valid_cells = ...
        valid_cells_local;

    summary.manual_status = ...
        manual_status;

    summary.cutoff_status = ...
        cutoff_status;

    summary.effective_status = ...
        effective_status;

    switch lower(population_name)

        case 'gcamp'

            summary.gcamp_indices = ...
                (1:nLocal).';

            summary.electroporated_indices = ...
                zeros(0,1);

        case 'electroporated'

            summary.gcamp_indices = ...
                zeros(0,1);

            summary.electroporated_indices = ...
                (1:nLocal).';

        otherwise

            summary.gcamp_indices = ...
                zeros(0,1);

            summary.electroporated_indices = ...
                zeros(0,1);
    end

    summary.n_total = ...
        nLocal;

    summary.n_kept_final = ...
        numel( ...
            valid_cells_local);

    summary.n_manual_keep = ...
        sum( ...
            manual_status == +1);

    summary.n_manual_excl = ...
        sum( ...
            manual_status == -1);

    summary.n_cutoff_keep = ...
        sum( ...
            cutoff_status == +1);

    summary.n_cutoff_excl = ...
        sum( ...
            cutoff_status == -1);
end

function MAct = recompute_mact_from_raster(Raster, synchronous_frames)
    if isempty(Raster)
        MAct = zeros(1,0);
        return;
    end

    Nz = size(Raster, 2);
    if Nz > synchronous_frames
        MAct = zeros(1, Nz - synchronous_frames);
        for i = 1:(Nz - synchronous_frames)
            MAct(i) = sum(max(Raster(:, i:i+synchronous_frames), [], 2));
        end
    else
        MAct = zeros(1,0);
    end
end

function [isort1,isort2,Sm] = subset_combined_sort( ...
        combined1,combined2,combinedSm,subset_rows,nCombinedKept)
    % Conserve l'ordre Combined sans relancer raster_processing.
    % subset_rows sont les indices des lignes Combined retenues pour une
    % population ; les permutations de sortie referencent ses lignes DF.
    subset_rows = subset_rows(:);
    n = numel(subset_rows);
    isort1 = []; isort2 = []; Sm = [];
    if n==0, return; end
    if ~isequal(sort(double(combined1(:))),(1:nCombinedKept)')
        combined1 = (1:nCombinedKept)';
    end
    [tf,isort1] = ismember(combined1(ismember(combined1,subset_rows)),subset_rows);
    if ~all(tf) || numel(isort1)~=n
        error('subset_combined_sort:InvalidIndex','Indices Combined incoherents.');
    end
    isort1 = isort1(:);
    if isequal(sort(double(combined2(:))),(1:nCombinedKept)')
        [tf,isort2] = ismember( ...
            combined2(ismember(combined2,subset_rows)),subset_rows);
        if ~all(tf) || numel(isort2)~=n
            isort2 = [];
        else
            isort2 = isort2(:);
        end
    end
    if ~isempty(combinedSm)
        positions = find(ismember(combined1,subset_rows));
        if size(combinedSm,1)==nCombinedKept
            Sm = combinedSm(positions,:,:);
        elseif size(combinedSm,2)==nCombinedKept
            Sm = combinedSm(:,positions,:);
        end
    end
end


