            end

            % ==================================================
            % Statut du plan courant uniquement, sans recalcul DF/isort.
            % Partage uniquement entre les populations de CE plan.
            % ==================================================
            if isstruct(selection_summary) && ...
                    isfield(selection_summary,'recording_keep_modified')
                selection_summary = rmfield(selection_summary, ...
                    'recording_keep_modified');
            end
            if isstruct(selection_summary) && ...
                    isfield(selection_summary,'comment_modified')
                selection_summary = rmfield(selection_summary,'comment_modified');
            end
            if recording_keep_modified && isstruct(selection_summary) && ...
                    isfield(selection_summary,'recording_keep')
                recording_keep = normalize_recording_keep_run( ...
                    selection_summary.recording_keep);
                if ~isempty(recording_keep)
                    data = save_recording_keep_for_plane( ...
                        data,m,p,nPlanes,recording_keep, ...
                        filePath_gcamp,filePath_electroporated, ...
                        filePath_combined,process_electroporated_combined);
                    fprintf('%s - plane %d: recording_keep = %d saved (no DF recompute).\n', ...
                        record_label_m,p-1,recording_keep);
                end
            end

            % ==================================================
            % No new detection
            % ==================================================

            if ~has_new
                % In Viewer, no confirmation means no results file is
                % rewritten. The returned data still obeys include_stims.
                if ~viewer_mode
                    fprintf('%s - plane %d: no new outputs.\n', ...
                        record_label_m,p);
                end
                if ~include_stims
                    data = crop_detection_data_for_plane( ...
                        data,m,p,nPlanes,first_stim_frame_global, ...
                        sync_frames_m,process_electroporated_combined);
                end
                continue;
            end

            % Synchroniser le groupe de statuts MEME si seule la selection
            % des cellules a ete confirmee (eventuellement statut []).
            if isstruct(selection_summary) && ...
                    isfield(selection_summary,'recording_keep')
                data.recording_keep_group{m}{p} = ...
                    normalize_recording_keep_run(selection_summary.recording_keep);
            end

            % ==================================================
            % Combined
            % ==================================================

            if use_combined_this_plane

                has_new_combined_group = ...
                    true;

                has_new_combined_plane = ...
                    true;

                % Tri du DF final recalcule dans le tuner a la confirmation.
                isort1_combined = isort1_plane;
                isort2_combined = isort2_plane;
                Sm_combined = Sm_plane;

                data.combined_plane. ...
                    F0_combined_by_plane{m}{p} = ...
                    F0;

                data.combined_plane. ...
                    noise_est_combined_by_plane{m}{p} = ...
                    noise_est;

                data.combined_plane. ...
                    valid_combined_cells_by_plane{m}{p} = ...
                    valid_cells;

                data.combined_plane. ...
                    DF_combined_by_plane{m}{p} = ...
                    DF_sg;

                data.combined_plane. ...
                    DF_raw_combined_by_plane{m}{p} = ...
                    DF_raw;

                data.combined_plane. ...
                    Raster_combined_by_plane{m}{p} = ...
                    Raster;

                data.combined_plane. ...
                    Acttmp2_combined_by_plane{m}{p} = ...
                    Acttmp2;

                data.combined_plane. ...
                    MAct_combined_by_plane{m}{p} = ...
                    MAct;

                data.combined_plane. ...
                    thresholds_combined_by_plane{m}{p} = ...
                    thresholds;

                data.combined_plane. ...
                    bad_segs_combined_plane{m}{p} = ...
                    bad_segs_det;

                data.combined_plane. ...
                    opts_detection_combined_by_plane{m}{p} = ...
                    opts_det;

                data.combined_plane. ...
                    selection_summary_combined_by_plane{m}{p} = ...
                    selection_summary;

                data.combined_plane. ...
                    recording_keep_combined_by_plane{m}{p} = ...
                    selection_summary.recording_keep;

                data.combined_plane. ...
                    isort1_combined_by_plane{m}{p} = ...
                    isort1_combined;

                data.combined_plane. ...
                    isort2_combined_by_plane{m}{p} = ...
                    isort2_combined;

                data.combined_plane. ...
                    Sm_combined_by_plane{m}{p} = ...
                    Sm_combined;

                [ ...
                    data, ...
                    has_new_gcamp_plane, ...
                    has_new_electroporated_plane ...
                ] = ...
                    reconstruct_gcamp_electroporated_from_combined( ...
                        data, ...
                        m, ...
                        p, ...
                        valid_cells, ...
                        F0, ...
                        noise_est, ...
                        DF_sg, ...
                        DF_raw, ...
                        Raster, ...
                        Acttmp2, ...
                        thresholds, ...
                        bad_segs_det, ...
                        opts_det, ...
                        electroporated_indices_in, ...
                        sync_frames_m, ...
                        isort1_combined, ...
                        isort2_combined, ...
                        Sm_combined, ...
                        selection_summary, ...
                        size(F_in,1));

                has_new_gcamp_group = ...
                    has_new_gcamp_group || ...
                    has_new_gcamp_plane;

                has_new_electroporated_group = ...
                    has_new_electroporated_group || ...
                    has_new_electroporated_plane;

            % ==================================================
            % GCaMP only
            % ==================================================

            else

                has_new_gcamp_group = ...
                    true;

                has_new_gcamp_plane = ...
                    true;

                % Utiliser les trois sorties de peak_detection_tuner.
                % Aucun nouveau raster_processing dans cette fonction.

                data.gcamp_plane. ...
