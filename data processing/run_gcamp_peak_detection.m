function segTable = sort_segments_by_deviation(bad_segs, deviation)

    if nargin < 2
        error('Usage: segTable = sort_segments_by_deviation(bad_segs, deviation)');
    end

    deviation = deviation(:).';
    T = numel(deviation);

    if isempty(bad_segs)
        segTable = table([], [], [], [], ...
            'VariableNames', {'StartFrame','EndFrame','FrameExtent','ValMaxDeviation'});
        disp(segTable);
        return;
    end

    if size(bad_segs,2) ~= 2
        error('bad_segs doit être une matrice Nx2 [start end].');
    end

    N = size(bad_segs,1);

    startF = nan(N,1);
    endF   = nan(N,1);
    extent = nan(N,1);
    valMax = nan(N,1);

    for k = 1:N
        a = round(bad_segs(k,1));
        b = round(bad_segs(k,2));

        if a > b
            tmp = a; a = b; b = tmp;
        end

        a = max(1, min(T, a));
        b = max(1, min(T, b));

        startF(k) = a;
        endF(k)   = b;
        extent(k) = b - a + 1;

        segVals = deviation(a:b);
        segVals = segVals(isfinite(segVals));

        if isempty(segVals)
            valMax(k) = NaN;
        else
            valMax(k) = min(segVals);
        end
    end

    segTable = table(startF, endF, extent, valMax, ...
        'VariableNames', {'StartFrame','EndFrame','FrameExtent','ValMaxDeviation'});

    segTable = sortrows(segTable, 'ValMaxDeviation', 'ascend');
end

function [ ...
        motion_energy, ...
        speed_active, ...
        was_cropped ...
    ] = crop_motion_before_first_stim( ...
        motion_energy, ...
        speed_active, ...
        first_stim_frame_global)

    was_cropped = false;

    % ==========================================================
    % No valid first stimulation
    % ==========================================================
    if isempty(first_stim_frame_global) || ...
            ~isfinite(first_stim_frame_global)

        return;
    end

    first_stim_frame_global = ...
        round(first_stim_frame_global);

    last_frame = ...
        first_stim_frame_global - 1;

    % ==========================================================
    % Motion energy
    % ==========================================================
    if ~isempty(motion_energy)

        original_length = ...
            numel(motion_energy);

        nKeep = ...
            min( ...
                last_frame, ...
                original_length);

        if nKeep >= 1

            motion_energy = ...
                motion_energy(1:nKeep);

        else

            motion_energy = ...
                [];
        end

        if numel(motion_energy) ~= ...
                original_length

            was_cropped = true;
        end
    end

    % ==========================================================
    % Speed active
    % ==========================================================
    if ~isempty(speed_active)

        original_length = ...
            numel(speed_active);

        nKeep = ...
            min( ...
                last_frame, ...
                original_length);

        if nKeep >= 1

            speed_active = ...
                speed_active(1:nKeep);

        else

            speed_active = ...
                [];
        end

        if numel(speed_active) ~= ...
                original_length

            was_cropped = true;
        end
    end
end


