% =========================================================

function save_branch_plane_fields( ...
        filePath, ...
        data, ...
        branchName, ...
        saveFields, ...
        m, ...
        p, ...
        nPlanes)

    % ==========================================================
    % Sauvegarde uniquement le plan p dans results_*.mat.
    %
    % Les autres plans présents dans chaque champ sont conservés.
    % ==========================================================

    if isempty(filePath)
        return;
    end

    outdir = ...
        fileparts(filePath);

    if exist(outdir, 'dir') ~= 7
        mkdir(outdir);
    end

    % ==========================================================
    % Charger le fichier existant pour préserver les autres plans
    % ==========================================================
    if exist(filePath, 'file') == 2

        S = ...
            load(filePath);

    else

        S = ...
            struct();
    end

    % ==========================================================
    % Modifier uniquement le plan p pour chaque champ
    % ==========================================================
    for k = 1:numel(saveFields)

        fieldName = ...
            saveFields{k};

        if ~isfield(data, branchName) || ...
                ~isfield(data.(branchName), fieldName) || ...
                numel(data.(branchName).(fieldName)) < m || ...
                isempty(data.(branchName).(fieldName){m}) || ...
                ~iscell(data.(branchName).(fieldName){m}) || ...
                numel(data.(branchName).(fieldName){m}) < p

            continue;
        end

        newValue = ...
            data.(branchName).(fieldName){m}{p};

        % ------------------------------------------------------
        % Ancienne valeur du champ dans le fichier
        % ------------------------------------------------------
        if isfield(S, fieldName)

            oldField = ...
                S.(fieldName);

            if iscell(oldField)

                planeValues = ...
                    oldField(:);

            elseif nPlanes == 1

                % Compatibilité avec un ancien fichier monoplan
                % non stocké dans une cell.
                planeValues = ...
                    {oldField};

            else

                planeValues = ...
                    cell(nPlanes,1);
            end

        else

            planeValues = ...
                cell(nPlanes,1);
        end

        % ------------------------------------------------------
        % Garantir exactement nPlanes emplacements
        % ------------------------------------------------------
        if numel(planeValues) < nPlanes

            oldValues = ...
                planeValues;

            planeValues = ...
                cell(nPlanes,1);

            planeValues(1:numel(oldValues)) = ...
                oldValues(:);

        elseif numel(planeValues) > nPlanes

            planeValues = ...
                planeValues(1:nPlanes);
        end

        % ------------------------------------------------------
        % Modifier uniquement le plan demandé
        % ------------------------------------------------------
        planeValues{p} = ...
            newValue;

        S.(fieldName) = ...
            planeValues;
    end

    % ==========================================================
    % Réécriture du fichier avec les autres champs/plans conservés
    % ==========================================================
    save( ...
        filePath, ...
        '-struct', ...
        'S');
end

function save_motion_group_fields(filePath_motion, data, fields_motion_group, m)

    saveStruct = struct();

    for f = 1:numel(fields_motion_group)
        fn = fields_motion_group{f};

        if isfield(data,'motion') && ...
           isfield(data.motion, fn) && ...
           numel(data.motion.(fn)) >= m

            saveStruct.(fn) = data.motion.(fn){m};
        end
    end

    outdir = fileparts(filePath_motion);
    if ~exist(outdir,'dir')
        mkdir(outdir);
    end

    if exist(filePath_motion,'file') == 2
        save(filePath_motion, '-struct', 'saveStruct', '-append');
    else
        save(filePath_motion, '-struct', 'saveStruct');
    end
end

% =========================================================
% RECONSTRUCTION COMBINED VERS GCAMP / ELECTROPORATED
% =========================================================

function [ ...
        data, ...
        has_new_gcamp_group, ...
        has_new_electroporated_group ...
    ] = ...
    reconstruct_gcamp_electroporated_from_combined( ...
        data, ...
        m, ...
        p, ...
        valid_combined, ...
        F0_combined, ...
        noise_est_combined, ...
        DF_sg_combined, ...
        DF_raw_combined, ...
        Raster_combined, ...
        Acttmp2_combined, ...
        thresholds_combined, ...
        bad_segs_combined, ...
        opts_det_combined, ...
        electroporated_indices_combined, ...
        synchronous_frames, ...
        ops_in, ...
        selection_summary_combined, ...
        nCombined)

    % ==========================================================
    % Référentiel Combined original
    %
    % Combined contient toutes les cellules avant sélection.
    %
    % valid_combined :
    % indices des cellules actuellement retenues dans ce
    % référentiel Combined original.
    %
    % Les matrices :
    %
    %   F0_combined
    %   DF_sg_combined
    %   Raster_combined
    %   ...
    %
    % sont déjà réduites et leurs lignes correspondent,
    % dans le même ordre, à valid_combined.
    %
    % nCombined est fourni directement par :
    %
    %   size(F_in,1)
    % ==========================================================

    has_new_gcamp_group = ...
        true;

    has_new_electroporated_group = ...
        true;

    % ==========================================================
    % Vérification nCombined
    % ==========================================================

    nCombined = ...
        round( ...
            double( ...
                nCombined));

    if ~isscalar(nCombined) || ...
            ~isfinite(nCombined) || ...
            nCombined < 0

        error( ...
            ['Invalid nCombined passed to ' ...
             'reconstruct_gcamp_electroporated_from_combined.']);
    end

    % ==========================================================
    % Nettoyage indices Electroporated
    % ==========================================================

    electroporated_indices_combined = ...
        round( ...
            double( ...
                electroporated_indices_combined(:)));

    electroporated_indices_combined = ...
        electroporated_indices_combined( ...
            isfinite(electroporated_indices_combined) & ...
            electroporated_indices_combined >= 1 & ...
            electroporated_indices_combined <= nCombined);

    electroporated_indices_combined = ...
        unique( ...
            electroporated_indices_combined, ...
            'stable');

    % ==========================================================
    % Nettoyage valid_combined
    % ==========================================================

    valid_combined = ...
        round( ...
            double( ...
                valid_combined(:)));

    valid_combined = ...
        valid_combined( ...
            isfinite(valid_combined) & ...
            valid_combined >= 1 & ...
            valid_combined <= nCombined);

    valid_combined = ...
        unique( ...
            valid_combined, ...
            'stable');

    % ==========================================================
    % Summary Combined
    % ==========================================================

    if isempty(selection_summary_combined) || ...
            ~isstruct(selection_summary_combined)

        selection_summary_combined = ...
            struct();
    end

    % ==========================================================
    % Populations originales dans le référentiel Combined
    % ==========================================================

    all_combined_indices = ...
        (1:nCombined).';

    gcamp_indices_combined = ...
        setdiff( ...
            all_combined_indices, ...
            electroporated_indices_combined, ...
            'stable');

    nGcampOriginal = ...
        numel( ...
            gcamp_indices_combined);

    nElectroporatedOriginal = ...
        numel( ...
            electroporated_indices_combined);

    % ==========================================================
    % Vérification cohérence lignes / valid_combined
    % ==========================================================

    nValid = ...
        numel( ...
            valid_combined);

    if ~isempty(DF_sg_combined) && ...
            size(DF_sg_combined,1) ~= nValid

        error( ...
