                    isort2_plane;

                data.gcamp_plane. ...
                    Sm_gcamp_by_plane{m}{p} = ...
                    Sm_plane;
            end
        end

        % ======================================================
        % SAVE RECORDING
        % ======================================================
        if has_new_gcamp_group

            save_branch_fields( ...
                filePath_gcamp, ...
                data, ...
                'gcamp_plane', ...
                fields_detect_gcamp, ...
                m);
        end

        if process_electroporated_combined && ...
                has_new_electroporated_group

            save_branch_fields( ...
                filePath_electroporated, ...
                data, ...
                'electroporated_plane', ...
                fields_detect_electroporated, ...
