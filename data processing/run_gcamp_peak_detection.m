            ~isfield(data.motion,fieldName) || ...
            ~iscell(data.motion.(fieldName)) || ...
            numel(data.motion.(fieldName)) < m

        return;
    end

    by_plane = ...
        data.motion.(fieldName){m};

    if ~iscell(by_plane) || ...
            numel(by_plane) < p

        return;
    end

    v = ...
        by_plane{p};
end


function fields_to_load = get_branch_fields_to_load( ...
        data, ...
        branchName, ...
        fieldsToCheck, ...
        m, ...
        nPlanes)

    fields_to_load = {};

    % ==========================================================
    % Detection core
    %
    % DF_*_by_plane (excluding DF_raw) is used as the main marker that
    % an existing detection is already present in memory.
    % ==========================================================

    core_complete = ...
        branch_detection_core_complete( ...
            data, ...
            branchName, ...
            fieldsToCheck, ...
            m, ...
            nPlanes);

    for f = 1:numel(fieldsToCheck)

        fieldName = ...
            fieldsToCheck{f};

        field_missing = ...
            false;

        for p = 1:nPlanes

            slot_exists = ...
                branch_plane_slot_exists( ...
                    data, ...
                    branchName, ...
                    fieldName, ...
                    m, ...
                    p);

            if ~slot_exists

                field_missing = ...
                    true;

                break;
            end

            current_value = ...
                data.(branchName).(fieldName){m}{p};

            if isempty(current_value)

                % --------------------------------------------------
                % Before the core detection has been recovered, load
                % every missing detection variable available on disk.
                % --------------------------------------------------
                if ~core_complete

                    field_missing = ...
                        true;

                    break;
                end

                % --------------------------------------------------
                % Once the core exists, these outputs are allowed to
                % be legitimately empty and must not trigger reloads.
                % --------------------------------------------------
                % Le DF peut deja etre en memoire alors que son tri n'a
                % pas ete charge. Chercher les trois sorties dans le MAT
                % avant d'ouvrir le Viewer, sans relancer le calcul.
                if startsWith(fieldName,'isort1_') || ...
                        startsWith(fieldName,'isort2_') || ...
                        startsWith(fieldName,'Sm_') || ...
                        ~detection_field_allows_empty(fieldName)

                    field_missing = ...
                        true;

                    break;
                end
            end
        end

        if field_missing

            fields_to_load{end + 1} = ...
                fieldName; %#ok<AGROW>
        end
    end
end


function tf = branch_detection_core_complete( ...
        data, ...
        branchName, ...
        fieldsToCheck, ...
        m, ...
        nPlanes)

    tf = ...
        false;

    df_field = ...
        '';

    for f = 1:numel(fieldsToCheck)

        fieldName = ...
            fieldsToCheck{f};

        if startsWith(fieldName, 'DF_') && ...
                ~startsWith(fieldName, 'DF_raw_')

            df_field = ...
                fieldName;

            break;
        end
    end

    if isempty(df_field)
        return;
    end

    tf = ...
        true;

    for p = 1:nPlanes

        if ~branch_plane_slot_exists( ...
                data, ...
                branchName, ...
                df_field, ...
                m, ...
                p) || ...
                isempty( ...
                    data.(branchName).(df_field){m}{p})

            tf = ...
                false;

            return;
        end
    end
end


function tf = branch_plane_slot_exists( ...
        data, ...
        branchName, ...
        fieldName, ...
        m, ...
        p)

    tf = ...
        isfield(data, branchName) && ...
        isstruct(data.(branchName)) && ...
        isfield(data.(branchName), fieldName) && ...
        iscell(data.(branchName).(fieldName)) && ...
        numel(data.(branchName).(fieldName)) >= m && ...
        iscell(data.(branchName).(fieldName){m}) && ...
        numel(data.(branchName).(fieldName){m}) >= p;
end


function tf = detection_field_allows_empty(fieldName)

    tf = ...
        startsWith(fieldName, 'isort1_') || ...
        startsWith(fieldName, 'isort2_') || ...
        startsWith(fieldName, 'Sm_') || ...
        startsWith(fieldName, 'Acttmp2_');
end


function F_full = load_complete_viewer_fluorescence( ...
        filePath, ...
        fieldName, ...
        p, ...
        nPlanes, ...
        DF_reference, ...
        F_fallback, ...
        record_label)

    % ==========================================================
    % Charger le F BRUT COMPLET pour le Viewer.
    %
    % Priorite au results_*.mat du recording courant.
    % Le DF sauvegarde complet fixe le referentiel attendu :
    %   [nCells x nFrames].
    %
    % F n'est pas utilise pour construire le Viewer. Il est seulement
    % conserve comme source brute pour un eventuel recalcul de
    % preprocessing dans peak_detection_tuner.
    % ==========================================================

    F_full = [];

    if nargin < 7 || isempty(record_label)
        record_label = 'record';
    end

    if isempty(DF_reference)

        error( ...
            'run_gcamp_peak_detection:MissingViewerDFReference', ...
            ['%s - plane %d: impossible de verifier F complet car ' ...
             'DF_reference est vide.'], ...
            record_label, ...
            p-1);
    end

    expected_rows = ...
        size(DF_reference,1);

    expected_frames = ...
        size(DF_reference,2);

    % ==========================================================
    % 1) results_*.mat = source privilegiee
    % ==========================================================

    if ~isempty(filePath) && ...
            exist(filePath,'file') == 2

        loaded_F = ...
            load_available_variables_peak_detection( ...
                filePath, ...
                {fieldName});

        if isfield(loaded_F,fieldName)

            F_by_plane = ...
                coerce_to_plane_cell( ...
                    loaded_F.(fieldName), ...
                    nPlanes);

            if p <= numel(F_by_plane)

                candidate = ...
                    F_by_plane{p};

                if is_complete_viewer_F( ...
                        candidate, ...
                        expected_rows, ...
                        expected_frames)

                    F_full = ...
                        candidate;

                    fprintf( ...
                        ['%s - plane %d: F complet charge depuis %s ' ...
                         '(%d cellules x %d frames).\n'], ...
                        record_label, ...
                        p-1, ...
                        filePath, ...
                        expected_rows, ...
                        expected_frames);

                    return;
                end
            end
        end
    end

    % ==========================================================
    % 2) F deja en memoire : seulement s'il est EXACTEMENT complet
    % ==========================================================

    if is_complete_viewer_F( ...
            F_fallback, ...
            expected_rows, ...
            expected_frames)

        F_full = ...
            F_fallback;

        warning( ...
            'run_gcamp_peak_detection:ViewerFLoadedFromMemory', ...
            ['%s - plane %d: %s absent/incompatible dans results. ' ...
             'Le F en memoire est utilise car sa taille correspond ' ...
             'exactement au DF sauvegarde complet (%d x %d).'], ...
            record_label, ...
            p-1, ...
            fieldName, ...
            expected_rows, ...
            expected_frames);

        return;
    end

    % ==========================================================
    % Aucun F complet disponible : ne jamais accepter un F croppe.
    % ==========================================================

    if isempty(F_fallback)

        fallback_size = ...
            'vide';

    else

        fallback_size = ...
            sprintf( ...
                '%d x %d', ...
                size(F_fallback,1), ...
                size(F_fallback,2));
    end

    error( ...
        'run_gcamp_peak_detection:IncompleteViewerF', ...
        ['%s - plane %d: aucun F complet compatible avec le DF ' ...
         'sauvegarde n''a ete trouve. Attendu %d x %d, F memoire = %s. ' ...
         'Le Viewer refuse un F croppe pour eviter un recalcul faux.'], ...
        record_label, ...
        p-1, ...
        expected_rows, ...
        expected_frames, ...
        fallback_size);
end


function tf = is_complete_viewer_F( ...
        F_candidate, ...
        expected_rows, ...
        expected_frames)

    tf = ...
        isnumeric(F_candidate) && ...
        ismatrix(F_candidate) && ...
        ~isempty(F_candidate) && ...
        size(F_candidate,1) == expected_rows && ...
        size(F_candidate,2) == expected_frames;
end


function loaded = load_available_variables_peak_detection( ...
        filePath, ...
        requested_fields)

    loaded = ...
        struct();

    if isempty(filePath) || ...
            exist(filePath, 'file') ~= 2 || ...
            isempty(requested_fields)

        return;
    end

    variables_in_file = ...
        whos( ...
            '-file', ...
            filePath);

    if isempty(variables_in_file)
        return;
    end

    variable_names = ...
        {variables_in_file.name};

    fields_available = ...
        requested_fields( ...
            ismember( ...
                requested_fields, ...
                variable_names));

    fields_available = ...
