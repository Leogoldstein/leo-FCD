function Y = subset_detection_rows(X,rows,nSourceRows)
    if isempty(X)
        Y = X;
        return;
    end

    rows = round(double(rows(:)));
    rows = rows(isfinite(rows) & rows>=1 & rows<=nSourceRows);

    if isvector(X) && numel(X)==nSourceRows && size(X,1)~=nSourceRows
        Y = X(rows);
        if iscolumn(X)
            Y = Y(:);
        end
        return;
    end

    if size(X,1) ~= nSourceRows
        error('subset_detection_rows:RowMismatch', ...
            'Champ de détection : %d lignes, attendu %d.', ...
            size(X,1),nSourceRows);
    end

    Y = X(rows,:);
end

function summary = ...
    create_reconstructed_selection_summary( ...
        summary_combined, ...
        population_indices_combined, ...
        valid_cells_local)

    % ==========================================================
    % Nouveau selection_summary dans le référentiel local.
    %
    % Source de vérité :
    %   valid_cells_local
    %
    % Décisions héritées du Combined :
    %   manual_status
    %   cutoff_status
    % ==========================================================

    population_indices_combined = ...
        round( ...
            double( ...
                population_indices_combined(:)));

    population_indices_combined = ...
        population_indices_combined( ...
            isfinite(population_indices_combined) & ...
            population_indices_combined >= 1);

    nLocal = ...
        numel( ...
            population_indices_combined);

    % ==========================================================
    % Cellules réellement retenues
    % ==========================================================

    valid_cells_local = ...
        round( ...
            double( ...
                valid_cells_local(:)));

    valid_cells_local = ...
        valid_cells_local( ...
            isfinite(valid_cells_local) & ...
            valid_cells_local >= 1 & ...
            valid_cells_local <= nLocal);

    valid_cells_local = ...
        unique( ...
            valid_cells_local, ...
            'stable');

    % ==========================================================
    % Statuts
    % ==========================================================

    manual_status = ...
        zeros( ...
            nLocal, ...
            1);

    cutoff_status = ...
        zeros( ...
            nLocal, ...
            1);

    if ~isempty(summary_combined) && ...
            isstruct(summary_combined)

        if isfield( ...
                summary_combined, ...
                'manual_status') && ...
                ~isempty(summary_combined.manual_status)

            tmp = ...
                summary_combined.manual_status(:);

            valid_source = ...
                population_indices_combined <= ...
                numel(tmp);

            local_idx = ...
                find(valid_source);

            manual_status(local_idx) = ...
                tmp( ...
                    population_indices_combined( ...
                        valid_source));
        end

        if isfield( ...
                summary_combined, ...
                'cutoff_status') && ...
                ~isempty(summary_combined.cutoff_status)

            tmp = ...
                summary_combined.cutoff_status(:);

            valid_source = ...
                population_indices_combined <= ...
                numel(tmp);

            local_idx = ...
                find(valid_source);

            cutoff_status(local_idx) = ...
                tmp( ...
                    population_indices_combined( ...
                        valid_source));
        end
    end

    % ==========================================================
    % Etat final réellement sauvegardé
    % ==========================================================

    effective_status = ...
        -ones( ...
            nLocal, ...
            1);

    effective_status(valid_cells_local) = ...
        +1;

    % ==========================================================
    % Construction du summary local minimal
    % ==========================================================

    summary = struct();
    summary.manual_status = manual_status;
    summary.cutoff_status = cutoff_status;
    summary.effective_status = effective_status;

    if isstruct(summary_combined) && isfield(summary_combined,'comment')
        summary.comment = summary_combined.comment;
    else
        summary.comment = '';
    end
end

function MAct = recompute_mact_from_raster(Raster, synchronous_frames)
    if isempty(Raster)
        MAct = zeros(1,0);
        return;
    end

    Nz = size(Raster, 2);
    if Nz > synchronous_frames
        MAct = zeros(1, Nz - synchronous_frames);
        for i = 1:(Nz - synchronous_frames)
            MAct(i) = sum(max(Raster(:, i:i+synchronous_frames), [], 2));
        end
    else
        MAct = zeros(1,0);
    end
end

function [isort1,isort2,Sm] = subset_combined_sort( ...
        combined1,combined2,combinedSm,subset_rows,nCombinedKept)
    % Conserve l'ordre Combined sans relancer raster_processing.
    % subset_rows sont les indices des lignes Combined retenues pour une
    % population ; les permutations de sortie referencent ses lignes DF.
    subset_rows = subset_rows(:);
    n = numel(subset_rows);
    isort1 = []; isort2 = []; Sm = [];
    if n==0, return; end
    if ~isequal(sort(double(combined1(:))),(1:nCombinedKept)')
        combined1 = (1:nCombinedKept)';
    end
    [tf,isort1] = ismember(combined1(ismember(combined1,subset_rows)),subset_rows);
    if ~all(tf) || numel(isort1)~=n
        error('subset_combined_sort:InvalidIndex','Indices Combined incoherents.');
    end
    isort1 = isort1(:);
    if isequal(sort(double(combined2(:))),(1:nCombinedKept)')
        [tf,isort2] = ismember( ...
            combined2(ismember(combined2,subset_rows)),subset_rows);
        if ~all(tf) || numel(isort2)~=n
            isort2 = [];
        else
            isort2 = isort2(:);
        end
    end
    if ~isempty(combinedSm)
        positions = find(ismember(combined1,subset_rows));
        if size(combinedSm,1)==nCombinedKept
            Sm = combinedSm(positions,:,:);
        elseif size(combinedSm,2)==nCombinedKept
            Sm = combinedSm(:,positions,:);
        end
    end
end


% =========================================================
% COMMENTAIRE RECAPITULATIF DU RECORDING
% =========================================================

function [comment_text, row_idx] = get_recap_comment_for_record( ...
        recap_all_animal, date_value, tseries_value)

    comment_text = '';
    row_idx = [];

    if ~istable(recap_all_animal) || isempty(recap_all_animal) || ...
            ~all(ismember({'Date','TSeries'}, ...
                          recap_all_animal.Properties.VariableNames))
        return;
    end

    current_tseries = string(get_tseries_basename(tseries_value));
    current_tseries = strtrim(current_tseries);

    if strlength(current_tseries) == 0
        return;
    end

    nRows = height(recap_all_animal);
    recap_tseries = strings(nRows,1);

    for rr = 1:nRows
        recap_tseries(rr) = string( ...
            get_tseries_basename(recap_all_animal.TSeries(rr)));
    end

    recap_tseries = strtrim(recap_tseries);
    tseries_matches = find(strcmpi(recap_tseries,current_tseries));

    if isempty(tseries_matches)
        return;
    end

    % Exiger Date ET TSeries : jamais attribuer les valeurs au mauvais
    % enregistrement en cas d'homonyme ou de date differente.
    current_date = normalize_recap_date(date_value);
    recap_dates = strings(numel(tseries_matches),1);

    for jj = 1:numel(tseries_matches)
        recap_dates(jj) = normalize_recap_date( ...
            recap_all_animal.Date(tseries_matches(jj)));
    end

    matches = tseries_matches(strcmpi(recap_dates,current_date));
    if numel(matches) ~= 1
        if numel(matches) > 1
            warning('run_gcamp_peak_detection:AmbiguousRecapRow', ...
                'Date + TSeries non uniques dans recap_all_animal. Ligne non modifiee.');
        end
        return;
    end
    row_idx = matches(1);

    % La colonne Comment du recap est facultative et reste independante
    % de comment_saved (commentaire de detection par plan).
    if ~ismember('Comment',recap_all_animal.Properties.VariableNames)
        return;
    end
    comment_value = recap_all_animal.Comment(row_idx);

    if iscell(comment_value)
        if isempty(comment_value)
            return;
        end
        comment_value = comment_value{1};
    end

    comment_value = string(comment_value);

    if ~isempty(comment_value) && ~ismissing(comment_value(1))
        comment_text = char(comment_value(1));
    end
end


% =========================================================
% RECAP : UNE LIGNE PAR RECORDING, UNE CELLULE PAR PLAN
% =========================================================
function recap_all_animal = update_recap_detection_row( ...
        recap_all_animal,row_idx,data,m,nPlanes,processCombined)

    keep_by_plane = cell(nPlanes,1);
    comment_by_plane = repmat({''},nPlanes,1);

    for pp = 1:nPlanes
        % Priorite aux decisions individuelles, sans recopier le statut
        % d'un autre plan ou convertir [] en 0.
        keep_by_plane{pp} = get_recording_keep_for_plane(data,m,pp);

        % Meme branche que celle selectionnee pour le signal du plan :
        % Combined s'il existe et est demande, sinon GCaMP.
        useCombined = processCombined && ~isempty( ...
            get_branch_plane_or_empty(data,'combined_plane', ...
                'F_combined_by_plane',m,pp));
        if useCombined
            branch_names = {'combined','gcamp'};
        else
            branch_names = {'gcamp','combined'};
        end

        for bb = 1:numel(branch_names)
            name = branch_names{bb};
            if strcmp(name,'combined') && ~processCombined
                continue;
            end
            summary = get_branch_plane_or_empty( ...
                data,[name '_plane'], ...
                ['selection_summary_' name '_by_plane'],m,pp);
            if ~isstruct(summary) || isempty(summary)
                continue;
            end
            % Un commentaire vide d'un summary valide est intentionnel :
            % ne pas restaurer un commentaire obsolete de l'autre branche.
            if isfield(summary,'comment') && ~isempty(summary.comment)
                comment_by_plane{pp} = summary.comment;
            end
            break;
        end
    end

    % Indexation par accolades : chaque ligne contient elle-meme un
    % cell(nPlanes,1), et non nPlanes lignes supplementaires dans la table.
    recap_all_animal.recording_keep{row_idx} = keep_by_plane;
    recap_all_animal.comment_saved{row_idx} = comment_by_plane;
end


function name = get_tseries_basename(value)

    name = '';

    while iscell(value)
        if isempty(value)
            return;
        end
        value = value{1};
    end

    if isempty(value)
        return;
    end

    value = char(string(value));
    value = strtrim(value);

    if isempty(value)
        return;
    end

    value = regexprep(value,'[\\/]+$','');
    [~,name] = fileparts(value);

    % Si la valeur fournie est deja seulement un nom de TSeries,
    % fileparts le restitue normalement. Ce fallback couvre les cas
    % pathologiques ou aucun basename n'est obtenu.
    if isempty(name)
        name = value;
    end
end


function date_text = normalize_recap_date(value)

    while iscell(value)
        if isempty(value)
            date_text = "";
            return;
        end
        value = value{1};
    end

    if isdatetime(value)
        try
            date_text = string(value,'dd-MM-yyyy');
        catch
            date_text = string(value);
        end
    else
        date_text = string(value);
    end

    if isempty(date_text) || ismissing(date_text(1))
        date_text = "";
        return;
    end

    date_text = strtrim(date_text(1));
end


% =========================================================
% VIEWER, CHOIX UTILISATEUR ET PREVIEW
% =========================================================

function [viewer_mode, skip_plane] = ask_viewer(has_detection, record_label, p, cell_type)

    viewer_mode = false;
    skip_plane  = false;

    if ~has_detection
        return;
    end

    if nargin < 2 || isempty(record_label)
        record_label = 'record';
    end

    if nargin < 3 || isempty(p)
        p = 0;
    end

    if nargin < 4 || isempty(cell_type)
        cell_type = 'plane';
    end

    plane_label = sprintf('plane %d', p);

    msg = sprintf(['%s - %s\n\n' ...
                   'Existing %s detection found.\n\n' ...
                   'What do you want to do?'], ...
                   record_label, plane_label, cell_type);

    answer = questdlg( ...
        msg, ...
        'Existing detection', ...
        'Viewer', ...
        'Load only', ...
        'Load only');

    switch answer
        case 'Viewer'
            viewer_mode = true;
            skip_plane  = false;

        otherwise
            viewer_mode = false;
            skip_plane  = true;
    end
end

