function indices = normalize_indices_local(indices)

    if isempty(indices)

        indices = ...
            zeros(0,1);

        return;
    end

    indices = ...
        round(double(indices(:)));

    indices = ...
        indices( ...
            isfinite(indices) & ...
            indices >= 1);

    indices = ...
        unique( ...
            indices, ...
            'stable');
end


function MAct = recompute_mact_from_raster(Raster, synchronous_frames)
    if isempty(Raster)
        MAct = zeros(1,0);
        return;
    end

    Nz = size(Raster, 2);
    if Nz > synchronous_frames
        MAct = zeros(1, Nz - synchronous_frames);
        for i = 1:(Nz - synchronous_frames)
            MAct(i) = sum(max(Raster(:, i:i+synchronous_frames), [], 2));
        end
    else
        MAct = zeros(1,0);
    end
end

