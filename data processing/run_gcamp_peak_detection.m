    end

    loaded = ...
        load( ...
            filePath, ...
            fields_available{:});
end


function metadata_m = get_metadata_for_record(metadata, idx)

    metadata_m = struct();

    if isempty(metadata) || ...
            ~isstruct(metadata)

        return;
    end

    fields = fieldnames(metadata);

    for f = 1:numel(fields)

        field = fields{f};
        value = metadata.(field);

        % ==========================================================
        % Sous-structure
        % Exemple :
        %   metadata.gcamp_plane
        %   metadata.electroporated_plane
        % ==========================================================

        if isstruct(value)

            metadata_m.(field) = ...
                get_metadata_for_record( ...
                    value, ...
                    idx);

        % ==========================================================
        % Champ indexé par recording
        % ==========================================================

        elseif iscell(value)

            if numel(value) >= idx

                metadata_m.(field) = ...
                    value{idx};

            else

                metadata_m.(field) = [];
            end

        % ==========================================================
        % Champ global
        % ==========================================================

        else

            metadata_m.(field) = ...
                value;
        end
    end
end



function segs = frames_to_segments(fr)
    if isempty(fr)
        segs = zeros(0,2);
        return;
    end
    d = diff(fr);
    cuts = [1 find(d>1)+1 numel(fr)+1];
    segs = zeros(numel(cuts)-1,2);
    for k = 1:numel(cuts)-1
        segs(k,:) = [fr(cuts(k)) fr(cuts(k+1)-1)];
    end
end

