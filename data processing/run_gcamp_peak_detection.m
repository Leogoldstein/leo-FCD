        isort2_gcamp;

    data.gcamp_plane. ...
        Sm_gcamp_by_plane{m}{p} = ...
        Sm_gcamp;

    % ==========================================================
    % ==========================================================
    % ELECTROPORATED
    % ==========================================================
    % ==========================================================

    % ----------------------------------------------------------
    % Quelles cellules valid_combined sont Electroporated ?
    % ----------------------------------------------------------

    is_electroporated_valid = ...
        ismember( ...
            valid_combined, ...
