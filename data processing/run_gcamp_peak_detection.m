function metadata_m = get_metadata_for_record(metadata, idx)

    metadata_m = struct();

    if isempty(metadata) || ...
            ~isstruct(metadata)

        return;
    end

    fields = fieldnames(metadata);

    for f = 1:numel(fields)

        field = fields{f};
        value = metadata.(field);

        % ==========================================================
        % Sous-structure
        % Exemple :
        %   metadata.gcamp_plane
        %   metadata.electroporated_plane
        % ==========================================================

        if isstruct(value)

            metadata_m.(field) = ...
                get_metadata_for_record( ...
                    value, ...
                    idx);

        % ==========================================================
        % Champ indexé par recording
        % ==========================================================

        elseif iscell(value)

            if numel(value) >= idx

                metadata_m.(field) = ...
                    value{idx};

            else

                metadata_m.(field) = [];
            end

        % ==========================================================
        % Champ global
        % ==========================================================

        else

            metadata_m.(field) = ...
                value;
        end
    end
end


