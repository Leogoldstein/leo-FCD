function fields_to_load = get_branch_fields_to_load( ...
        data, ...
        branchName, ...
        fieldsToCheck, ...
        m, ...
        nPlanes)

    fields_to_load = {};

    % ==========================================================
    % Detection core
    %
    % DF_*_by_plane (excluding DF_raw) is used as the main marker that
    % an existing detection is already present in memory.
    % ==========================================================

    core_complete = ...
        branch_detection_core_complete( ...
            data, ...
            branchName, ...
            fieldsToCheck, ...
            m, ...
            nPlanes);

    for f = 1:numel(fieldsToCheck)

        fieldName = ...
            fieldsToCheck{f};

        field_missing = ...
            false;

        for p = 1:nPlanes

            slot_exists = ...
                branch_plane_slot_exists( ...
                    data, ...
                    branchName, ...
                    fieldName, ...
                    m, ...
                    p);

            if ~slot_exists

                field_missing = ...
                    true;

                break;
            end

            current_value = ...
                data.(branchName).(fieldName){m}{p};

            if isempty(current_value)

                % --------------------------------------------------
                % Before the core detection has been recovered, load
                % every missing detection variable available on disk.
                % --------------------------------------------------
                if ~core_complete

                    field_missing = ...
                        true;

                    break;
                end

                % --------------------------------------------------
                % Once the core exists, these outputs are allowed to
                % be legitimately empty and must not trigger reloads.
                % --------------------------------------------------
                % Le DF peut deja etre en memoire alors que son tri n'a
                % pas ete charge. Chercher les trois sorties dans le MAT
                % avant d'ouvrir le Viewer, sans relancer le calcul.
                if startsWith(fieldName,'isort1_') || ...
                        startsWith(fieldName,'isort2_') || ...
                        startsWith(fieldName,'Sm_') || ...
                        ~detection_field_allows_empty(fieldName)

                    field_missing = ...
                        true;

                    break;
                end
            end
        end

        if field_missing

            fields_to_load{end + 1} = ...
                fieldName; %#ok<AGROW>
        end
    end
end


function tf = branch_detection_core_complete( ...
        data, ...
        branchName, ...
        fieldsToCheck, ...
        m, ...
        nPlanes)

    tf = ...
        false;

    df_field = ...
        '';

    for f = 1:numel(fieldsToCheck)

        fieldName = ...
            fieldsToCheck{f};

        if startsWith(fieldName, 'DF_') && ...
                ~startsWith(fieldName, 'DF_raw_')

            df_field = ...
                fieldName;

            break;
        end
    end

    if isempty(df_field)
        return;
    end

    tf = ...
        true;

    for p = 1:nPlanes

        if ~branch_plane_slot_exists( ...
                data, ...
                branchName, ...
                df_field, ...
                m, ...
                p) || ...
                isempty( ...
                    data.(branchName).(df_field){m}{p})

            tf = ...
                false;

            return;
        end
    end
end


function tf = branch_plane_slot_exists( ...
        data, ...
        branchName, ...
        fieldName, ...
        m, ...
        p)

    tf = ...
        isfield(data, branchName) && ...
        isstruct(data.(branchName)) && ...
        isfield(data.(branchName), fieldName) && ...
        iscell(data.(branchName).(fieldName)) && ...
        numel(data.(branchName).(fieldName)) >= m && ...
        iscell(data.(branchName).(fieldName){m}) && ...
        numel(data.(branchName).(fieldName){m}) >= p;
end


function tf = detection_field_allows_empty(fieldName)

    tf = ...
        startsWith(fieldName, 'bad_segs_') || ...
        startsWith(fieldName, 'isort1_') || ...
        startsWith(fieldName, 'isort2_') || ...
        startsWith(fieldName, 'Sm_') || ...
        startsWith(fieldName, 'Acttmp2_');
end


function fields_to_load = get_motion_fields_to_load( ...
        data, ...
        fields_motion_group, ...
        m)

    fields_to_load = {};

    deviation_available = ...
        isfield(data, 'motion') && ...
        isfield(data.motion, 'deviation_group') && ...
        iscell(data.motion.deviation_group) && ...
        numel(data.motion.deviation_group) >= m && ...
        ~isempty(data.motion.deviation_group{m});

    status_value = ...
        get_motion_group_or_empty( ...
            data, ...
            'motion_energy_status', ...
            m);

    status_allows_empty_movie = ...
        false;

    if ~isempty(status_value)

        status_text = ...
            lower( ...
                strtrim( ...
                    char(string(status_value))));

        status_allows_empty_movie = ...
            ismember( ...
                status_text, ...
                {'skipped', 'no_camera', 'no_motion'});
    end

    for f = 1:numel(fields_motion_group)

        fieldName = ...
            fields_motion_group{f};

        slot_exists = ...
            isfield(data, 'motion') && ...
            isfield(data.motion, fieldName) && ...
            iscell(data.motion.(fieldName)) && ...
            numel(data.motion.(fieldName)) >= m;

        if ~slot_exists

            fields_to_load{end + 1} = ...
                fieldName; %#ok<AGROW>

            continue;
        end

        current_value = ...
            data.motion.(fieldName){m};

        if ~isempty(current_value)
            continue;
        end

        % ------------------------------------------------------
        % Before deviation is recovered, load all missing motion
        % variables so a fresh data struct is completed in one pass.
        % ------------------------------------------------------
        if ~deviation_available

            fields_to_load{end + 1} = ...
                fieldName; %#ok<AGROW>

            continue;
        end

        % ------------------------------------------------------
        % Empty artifact lists are valid once deviation exists.
        % ------------------------------------------------------
        if ismember( ...
                fieldName, ...
                { ...
                    'bad_frames_group', ...
                    'bad_segs_group', ...
                    'focus_segs_group' ...
                })

            continue;
        end

        % ------------------------------------------------------
        % Empty camera-derived motion is valid for these statuses.
        % ------------------------------------------------------
        if status_allows_empty_movie && ...
                ismember( ...
                    fieldName, ...
                    { ...
                        'motion_energy_group', ...
                        'speed_active_group' ...
                    })

            continue;
        end

        fields_to_load{end + 1} = ...
            fieldName; %#ok<AGROW>
    end

    fields_to_load = ...
        unique( ...
            fields_to_load, ...
            'stable');
end


