function save_branch_plane_fields( ...
        filePath, ...
        data, ...
        branchName, ...
        saveFields, ...
        m, ...
        p, ...
        nPlanes)

    % ==========================================================
    % Save only detection variables, never load the entire results file.
    % Other variables in results_*.mat (raw fluorescence, masks, etc.)
    % remain untouched.
    % ==========================================================

    if isempty(filePath)
        return;
    end

    outdir = ...
        fileparts(filePath);

    if exist(outdir, 'dir') ~= 7
        mkdir(outdir);
    end

    existing = ...
        struct();

    if exist(filePath, 'file') == 2

        existing = ...
            load_available_variables_peak_detection( ...
                filePath, ...
                saveFields);
    end

    saveStruct = ...
        struct();

    for k = 1:numel(saveFields)

        fieldName = ...
            saveFields{k};

        if ~isfield(data, branchName) || ...
                ~isfield(data.(branchName), fieldName) || ...
                numel(data.(branchName).(fieldName)) < m || ...
                isempty(data.(branchName).(fieldName){m}) || ...
                ~iscell(data.(branchName).(fieldName){m}) || ...
                numel(data.(branchName).(fieldName){m}) < p

            continue;
        end

        newValue = ...
            data.(branchName).(fieldName){m}{p};

        if isfield(existing, fieldName)

            oldField = ...
                existing.(fieldName);

            if iscell(oldField)

                planeValues = ...
                    oldField(:);

            elseif nPlanes == 1

                planeValues = ...
                    {oldField};

            else

                planeValues = ...
                    cell(nPlanes,1);
            end

        else

            planeValues = ...
                cell(nPlanes,1);
        end

        if numel(planeValues) < nPlanes

            oldValues = ...
                planeValues;

            planeValues = ...
                cell(nPlanes,1);

            planeValues(1:numel(oldValues)) = ...
                oldValues(:);

        elseif numel(planeValues) > nPlanes

            planeValues = ...
                planeValues(1:nPlanes);
        end

        if startsWith(fieldName,'selection_summary_')
            % Nettoyer aussi les autres plans deja presents dans le MAT.
            planeValues = strip_selection_summary_temporal_fields(planeValues);
            newValue = strip_selection_summary_temporal_fields(newValue);
        end
        planeValues{p} = ...
            newValue;

        saveStruct.(fieldName) = ...
            planeValues;
    end

    if isempty(fieldnames(saveStruct))
        return;
    end

    if exist(filePath, 'file') == 2

        save( ...
            filePath, ...
            '-struct', ...
            'saveStruct', ...
            '-append');

    else

        save( ...
            filePath, ...
            '-struct', ...
            'saveStruct');
    end
end

% =========================================================
% RECONSTRUCTION COMBINED VERS GCAMP / ELECTROPORATED
% =========================================================

function [ ...
        data, ...
        has_new_gcamp_group, ...
        has_new_electroporated_group ...
    ] = ...
    reconstruct_gcamp_electroporated_from_combined( ...
        data, ...
        m, ...
        p, ...
        valid_combined, ...
        F0_combined, ...
        noise_est_combined, ...
        DF_sg_combined, ...
        DF_raw_combined, ...
        Raster_combined, ...
        Acttmp2_combined, ...
        thresholds_combined, ...
        opts_det_combined, ...
        electroporated_indices_combined, ...
        synchronous_frames, ...
        isort1_combined, ...
        isort2_combined, ...
        Sm_combined, ...
        selection_summary_combined, ...
        recording_keep_combined, ...
        nCombined)

    % Les matrices Combined peuvent être :
    %   - NOUVEAU FORMAT : toutes les cellules originales (nCombined lignes) ;
    %   - ancien format   : uniquement valid_combined.
    %
    % Le nouveau format est conservé intégralement dans results_gcamp.mat
    % et results_electroporated.mat. valid_*_cells_by_plane et le
    % selection_summary indiquent ensuite quelles cellules sont retenues.

    has_new_gcamp_group = true;
    has_new_electroporated_group = true;

    nCombined = round(double(nCombined));
    if ~isscalar(nCombined) || ~isfinite(nCombined) || nCombined < 0
        error('reconstruct_gcamp_electroporated_from_combined:InvalidNCombined', ...
            'nCombined invalide.');
    end

    electroporated_indices_combined = ...
        round(double(electroporated_indices_combined(:)));
    electroporated_indices_combined = ...
        electroporated_indices_combined( ...
            isfinite(electroporated_indices_combined) & ...
            electroporated_indices_combined >= 1 & ...
            electroporated_indices_combined <= nCombined);
    electroporated_indices_combined = ...
        unique(electroporated_indices_combined,'stable');

    valid_combined = round(double(valid_combined(:)));
    valid_combined = valid_combined( ...
        isfinite(valid_combined) & ...
        valid_combined >= 1 & ...
        valid_combined <= nCombined);
    valid_combined = unique(valid_combined,'stable');

    if isempty(selection_summary_combined) || ...
            ~isstruct(selection_summary_combined)
        selection_summary_combined = struct();
    end

    all_combined_indices = (1:nCombined).';
    gcamp_indices_combined = ...
        setdiff(all_combined_indices,electroporated_indices_combined,'stable');

    nGcampOriginal = numel(gcamp_indices_combined);
    nElectroporatedOriginal = numel(electroporated_indices_combined);
    nValid = numel(valid_combined);

    % Déterminer le référentiel des matrices renvoyées par le tuner.
    nDataRows = 0;
    candidates = {DF_sg_combined,DF_raw_combined,F0_combined,Raster_combined};
    for kk = 1:numel(candidates)
        X = candidates{kk};
        if ~isempty(X)
            nDataRows = size(X,1);
            break;
        end
    end
    if nDataRows == 0 && ~isempty(noise_est_combined)
        nDataRows = numel(noise_est_combined);
    end

    if nDataRows == nCombined
        data_are_full = true;
        nSourceRows = nCombined;
    elseif nDataRows == nValid
        % Compatibilité avec d'anciens résultats déjà réduits.
        data_are_full = false;
        nSourceRows = nValid;
    else
        error('reconstruct_gcamp_electroporated_from_combined:RowMismatch', ...
            ['Matrices Combined incohérentes : %d lignes, attendu %d ' ...
             '(complet) ou %d (valid_cells).'], ...
            nDataRows,nCombined,nValid);
    end

    % Positions des cellules retenues dans la matrice réduite valid_combined.
    row_gcamp_valid = find(ismember(valid_combined,gcamp_indices_combined));
    row_electroporated_valid = ...
        find(ismember(valid_combined,electroporated_indices_combined));

    valid_gcamp_combined = valid_combined(row_gcamp_valid);
    [tf_gcamp,valid_gcamp_local] = ...
        ismember(valid_gcamp_combined,gcamp_indices_combined);
