function clear_detection_outputs( ...
        gcamp_root_folders, ...
        branches_to_clear, ...
        fields_detect_gcamp, ...
        fields_detect_electroporated, ...
        fields_detect_combined)

    % ==========================================================
    % Defaults
    % ==========================================================

    if nargin < 2 || ...
            isempty(branches_to_clear)

        branches_to_clear = { ...
            'gcamp', ...
            'electroporated', ...
            'combined'};
    end


    if nargin < 3 || ...
            isempty(fields_detect_gcamp)

        fields_detect_gcamp = {};
    end


    if nargin < 4 || ...
            isempty(fields_detect_electroporated)

        fields_detect_electroporated = {};
    end


    if nargin < 5 || ...
            isempty(fields_detect_combined)

        fields_detect_combined = {};
    end


    % ==========================================================
    % RECORDINGS
    % ==========================================================

    for m = 1:numel(gcamp_root_folders)

        % ======================================================
        % Recording root folder
        % ======================================================

        if isempty(gcamp_root_folders{m})

            continue;
        end


        outdir_m = ...
            gcamp_root_folders{m};


        if isstring(outdir_m)

            outdir_m = ...
                char(outdir_m);
        end


        if isempty(outdir_m) || ...
                ~ischar(outdir_m)

            fprintf( ...
                'Recording %d: invalid gcamp root folder, skip.\n', ...
                m);

            continue;
        end


        if exist(outdir_m,'dir') ~= 7

            fprintf( ...
                'Recording %d: gcamp root folder absent, skip:\n%s\n', ...
                m, ...
                outdir_m);

            continue;
        end


        fprintf('\n');
        fprintf( ...
            'Clearing peak-detection outputs - recording %d\n', ...
            m);


        % ======================================================
        % GCaMP
        % ======================================================

        if ismember( ...
                'gcamp', ...
                branches_to_clear) && ...
                ~isempty(fields_detect_gcamp)

            filePath_gcamp = ...
                fullfile( ...
                    outdir_m, ...
                    'results_gcamp.mat');


            clear_vars_in_matfile( ...
                filePath_gcamp, ...
                fields_detect_gcamp);
        end


        % ======================================================
        % Electroporated
        % ======================================================

        if ismember( ...
                'electroporated', ...
                branches_to_clear) && ...
                ~isempty(fields_detect_electroporated)

            filePath_electroporated = ...
                fullfile( ...
                    outdir_m, ...
                    'results_electroporated.mat');


            clear_vars_in_matfile( ...
                filePath_electroporated, ...
                fields_detect_electroporated);
        end


        % ======================================================
        % Combined
        % ======================================================

        if ismember( ...
                'combined', ...
                branches_to_clear) && ...
                ~isempty(fields_detect_combined)

            filePath_combined = ...
                fullfile( ...
                    outdir_m, ...
                    'results_combined.mat');


            clear_vars_in_matfile( ...
                filePath_combined, ...
                fields_detect_combined);
        end
    end
end

function clear_vars_in_matfile( ...
        filePath, ...
        vars_to_remove)

    % ==========================================================
    % Logical clear without loading/re-writing the whole MAT file.
    %
    % Existing peak-detection variables are overwritten by [].
    % Other variables in results_*.mat are left untouched.
    % ==========================================================

    if exist(filePath,'file') ~= 2

        fprintf( ...
            'File absent, skip: %s\n', ...
            filePath);

        return;
    end

    variables_in_file = ...
        whos( ...
            '-file', ...
            filePath);

    variable_names = ...
        {variables_in_file.name};

    % Conserver les summaries comme reference pour la nouvelle detection.
    % Nettoyer au passage les six anciens champs temporels dans le MAT.
    summary_names = vars_to_remove( ...
        ismember(vars_to_remove,variable_names) & ...
        startsWith(vars_to_remove,'selection_summary_'));

    clearStruct = struct();
    for k = 1:numel(summary_names)
        fn = summary_names{k};
        stored = load(filePath,fn);
        cleaned = strip_selection_summary_temporal_fields(stored.(fn));
        if ~isequaln(stored.(fn),cleaned)
            clearStruct.(fn) = cleaned;
        end
    end

    vars_present = vars_to_remove( ...
        ismember(vars_to_remove,variable_names) & ...
        ~startsWith(vars_to_remove,'recording_keep_') & ...
        ~startsWith(vars_to_remove,'selection_summary_'));

    if isempty(vars_present) && isempty(fieldnames(clearStruct))
        fprintf('No peak-detection fields to clear in:\n%s\n',filePath);
        return;
    end

    for k = 1:numel(vars_present)

        clearStruct.(vars_present{k}) = ...
            [];
    end

    save( ...
        filePath, ...
        '-struct', ...
        'clearStruct', ...
        '-append');

    fprintf( ...
        'Peak-detection fields cleared in:\n%s\n', ...
        filePath);
end

