function data = merge_loaded_branch_into_data(data, branchName, loaded, fieldsToLoad, m, nPlanes, overwritePlane)
    % Le chargement selectif standard comble seulement les valeurs vides.
    % En Viewer, overwritePlane force le remplacement du PLAN courant
    % lorsque les matrices en memoire ont ete croppees. Les summaries et
    % decisions recording_keep restent toutefois preserves comme reference.
    if nargin < 7
        overwritePlane = [];
    end
    for k = 1:numel(fieldsToLoad)
        fn = fieldsToLoad{k};
        if ~isfield(loaded, fn)
            continue;
        end

        loadedField = coerce_to_plane_cell(loaded.(fn), nPlanes);
        data = ensure_branch_plane_cell(data, branchName, fn, m, nPlanes);

        for p = 1:nPlanes
            if numel(loadedField) >= p
                overwriteThisPlane = ~isempty(overwritePlane) && ...
                    p == overwritePlane && ...
                    ~startsWith(fn,'selection_summary_') && ...
                    ~startsWith(fn,'recording_keep_');
                if overwriteThisPlane || isempty(data.(branchName).(fn){m}{p})
                    data.(branchName).(fn){m}{p} = loadedField{p};
                end
                if startsWith(fn,'selection_summary_')
                    data.(branchName).(fn){m}{p} = ...
                        strip_selection_summary_temporal_fields( ...
                            data.(branchName).(fn){m}{p});
                end
            end
        end
    end
end

