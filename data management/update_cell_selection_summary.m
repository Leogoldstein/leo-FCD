%======================================================================
% HELPER : compter les bad frames
%======================================================================
function bad_frame_count = count_bad_frames( ...
        bad_frames, total_frame_count)

    bad_frame_count = 0;

    if isempty(bad_frames)
        return;
    end

    if iscell(bad_frames)

        try
            bad_frames = cell2mat(bad_frames);
        catch
            return;
        end
    end

    if islogical(bad_frames)

        bad_frame_count = nnz(bad_frames);
        return;
    end

    if ~isnumeric(bad_frames)
        return;
    end

    bad_frames = double(bad_frames(:));
    bad_frames = bad_frames(isfinite(bad_frames));

    if isempty(bad_frames)
        return;
    end

    if isfinite(total_frame_count) && ...
            numel(bad_frames) == total_frame_count && ...
            all(ismember(bad_frames, [0, 1]))

        bad_frame_count = nnz(bad_frames);
        return;
    end

    bad_frames = round(bad_frames);
    bad_frames = bad_frames(bad_frames >= 1);

    if isfinite(total_frame_count)
        bad_frames = bad_frames( ...
            bad_frames <= total_frame_count);
    end

    bad_frame_count = numel(unique(bad_frames));
end
