%======================================================================
% BAD SEGMENTS -> NOMBRE DE FRAMES
%======================================================================

function bad_frame_count = count_bad_frames_from_segments( ...
        bad_segs, total_frame_count)

    bad_frame_count = ...
        0;


    if isempty(bad_segs)
        return;
    end


    if ~isnumeric(bad_segs)
        return;
    end


    bad_segs = ...
        double(bad_segs);


    if isvector(bad_segs) && ...
            numel(bad_segs) == 2

        bad_segs = ...
            reshape( ...
                bad_segs, ...
                1, ...
                2);
    end


    if size(bad_segs,2) < 2
        return;
    end


    bad_segs = ...
        bad_segs(:,1:2);


    %==============================================================
    % NORMALISATION DES BORNES
    %==============================================================

    valid_rows = ...
        all( ...
            isfinite(bad_segs), ...
            2);

    bad_segs = ...
        bad_segs(valid_rows,:);


    if isempty(bad_segs)
        return;
    end


    bad_segs = ...
        round(bad_segs);


    swap_rows = ...
        bad_segs(:,1) > ...
        bad_segs(:,2);


    if any(swap_rows)

        tmp = ...
            bad_segs(swap_rows,1);

        bad_segs(swap_rows,1) = ...
            bad_segs(swap_rows,2);

        bad_segs(swap_rows,2) = ...
            tmp;
    end


    bad_segs(:,1) = ...
        max( ...
            1, ...
            bad_segs(:,1));


    if isfinite(total_frame_count) && ...
            total_frame_count > 0

        total_frame_count = ...
            round(total_frame_count);

        bad_segs(:,2) = ...
            min( ...
                total_frame_count, ...
                bad_segs(:,2));
    end


    bad_segs = ...
        bad_segs( ...
            bad_segs(:,1) <= bad_segs(:,2), ...
            :);


    if isempty(bad_segs)
        return;
    end


    %==============================================================
    % FUSION DES SEGMENTS
    %
    % Evite tout double comptage si deux segments se chevauchent ou sont
    % adjacents.
    %==============================================================

    bad_segs = ...
        sortrows( ...
            bad_segs, ...
            [1 2]);


    merged = ...
        bad_segs(1,:);


    for k = 2:size(bad_segs,1)

        if bad_segs(k,1) <= ...
                merged(end,2) + 1

            merged(end,2) = ...
                max( ...
                    merged(end,2), ...
                    bad_segs(k,2));

        else

            merged(end+1,:) = ...
                bad_segs(k,:); %#ok<AGROW>
        end
    end


    bad_frame_count = ...
        sum( ...
            merged(:,2) - ...
            merged(:,1) + ...
            1);
end
