function [selected_groups, metadata_table] = create_metadata(selected_groups)

    metadata_table = table();

    if nargin < 1 || isempty(selected_groups)
        return;
    end

    save_to_excel = true;
    force_rebuild_metadata = true;

    type_names = fieldnames(selected_groups);

    for t = 1:numel(type_names)

        current_type = type_names{t};

        for k = 1:numel(selected_groups.(current_type))

            fprintf('\n==============================\n');
            fprintf('Metadata extraction\n');
            fprintf('Type: %s\n', current_type);
            fprintf('Animal %d / %d: %s\n', ...
                k, ...
                numel(selected_groups.(current_type)), ...
                string(selected_groups.(current_type)(k).animal));
            fprintf('==============================\n');

            % ==========================================================
            % Structure metadata
            %
            % metadata.gcamp_plane
            % metadata.electroporated_plane
            % metadata.ZSeries
            % ==========================================================

            selected_groups.(current_type)(k).metadata = ...
                empty_metadata_container();

            if ~isfield(selected_groups.(current_type)(k), 'paths') || ...
                    ~isstruct(selected_groups.(current_type)(k).paths)

                fprintf('Aucun champ paths disponible -> skip animal.\n');
                continue;
            end

            current_paths = ...
                selected_groups.(current_type)(k).paths;

            % ==========================================================
            % Dossier animal
            % ==========================================================

            if isfield(current_paths, 'animal') && ...
                    ~isempty(current_paths.animal)

                current_ani_path_group = ...
                    current_paths.animal;

            else

                current_ani_path_group = '';
            end

            % ==========================================================
            % TSeries
            %
            % 1 = GCaMP
            % 2 = Red
            % 3 = Blue
            % 4 = Green
            % ==========================================================

            if isfield(current_paths, 'TSeries') && ...
                    ~isempty(current_paths.TSeries)

                current_TSeries_group = ...
                    force_4col( ...
                        current_paths.TSeries);

            else

                current_TSeries_group = ...
                    cell(0,4);
            end

            % ==========================================================
            % XML
            %
            % 1 = GCaMP
            % 2 = Red
            % 3 = Blue
            % 4 = Green
            % 5 = ZSeries
            % ==========================================================

            if isfield(current_paths, 'xml') && ...
                    ~isempty(current_paths.xml)

                current_xml_group = ...
                    force_5col( ...
                        current_paths.xml);

            else

                current_xml_group = ...
                    cell( ...
                        size(current_TSeries_group,1), ...
                        5);
            end

            % ==========================================================
            % Nombre de recordings
            % ==========================================================

            nRecordings = max([ ...
                size(current_TSeries_group,1), ...
                size(current_xml_group,1), ...
                numel_safe_field( ...
                    selected_groups.(current_type)(k), ...
                    'dates')]);

            if nRecordings == 0

                fprintf('Aucun recording disponible -> skip animal.\n');
                continue;
            end

            current_TSeries_group = ...
                resize_4col( ...
                    current_TSeries_group, ...
                    nRecordings);

            current_xml_group = ...
                resize_5col( ...
                    current_xml_group, ...
                    nRecordings);

            % ==========================================================
            % Canal électroporé
            % ==========================================================

            electroporated_column_by_group = ...
                find_electroporated_column_from_tseries( ...
                    current_TSeries_group, ...
                    nRecordings);

            % ==========================================================
            % GCaMP root
            % ==========================================================

            if isfield(current_paths, 'gcamp_root') && ...
                    ~isempty(current_paths.gcamp_root)

                this_group_folders = ...
                    current_paths.gcamp_root;

            else

                this_group_folders = ...
                    cell(nRecordings,1);
            end

            if isrow(this_group_folders)
                this_group_folders = this_group_folders(:);
            end

            if numel(this_group_folders) < nRecordings

                tmp = ...
                    cell(nRecordings,1);

                tmp(1:numel(this_group_folders)) = ...
                    this_group_folders(:);

                this_group_folders = ...
                    tmp;
            end

            % ==========================================================
            % Fichiers Excel groupés
            % ==========================================================

            group_output_path_gcamp = '';
            group_output_path_electroporated = '';

            if save_to_excel && ...
                    ~isempty(current_ani_path_group)

                group_output_path_gcamp = ...
                    fullfile( ...
                        current_ani_path_group, ...
                        'metadata_results_group_gcamp.xlsx');

                group_output_path_electroporated = ...
                    fullfile( ...
                        current_ani_path_group, ...
                        'metadata_results_group_electroporated.xlsx');
            end

            [ ...
                group_table_gcamp, ...
                group_file_existed_gcamp ...
            ] = ...
                load_existing_group_table( ...
                    group_output_path_gcamp, ...
                    save_to_excel);

            [ ...
                group_table_electroporated, ...
                group_file_existed_electroporated ...
            ] = ...
                load_existing_group_table( ...
                    group_output_path_electroporated, ...
                    save_to_excel);

            group_table_modified_gcamp = false;
            group_table_modified_electroporated = false;

            % ==========================================================
            % BOUCLE RECORDINGS
            % ==========================================================

            for idx = 1:nRecordings

                % ======================================================
                % Date
                % ======================================================

                date = '';

                if isfield( ...
                        selected_groups.(current_type)(k), ...
                        'dates') && ...
                        numel( ...
                            selected_groups.(current_type)(k).dates) >= idx && ...
                        ~isempty( ...
                            selected_groups.(current_type)(k).dates{idx})

                    date = ...
                        selected_groups.(current_type)(k).dates{idx};
                end

                % ======================================================
                % Dossier output GCaMP
                % ======================================================

                this_folder = '';

                if idx <= numel(this_group_folders) && ...
                        ~isempty(this_group_folders{idx})

                    this_folder = ...
                        this_group_folders{idx};
                end

                % ======================================================
                % XML GCaMP
                % ======================================================

                gcamp_xml_file = ...
                    current_xml_group{idx,1};

                % ======================================================
                % XML électroporé
                % ======================================================

                electroporated_xml_file = '';

                electroporated_column = ...
                    electroporated_column_by_group(idx);

                if isfinite(electroporated_column)

                    electroporated_xml_file = ...
                        current_xml_group{ ...
                            idx, ...
                            electroporated_column};
                end

                % ======================================================
                % XML ZSeries
                % ======================================================

                zseries_xml_file = ...
                    current_xml_group{idx,5};

                % ======================================================
                % Affichage
                % ======================================================

                fprintf( ...
                    '\nRecording %d/%d\n', ...
                    idx, ...
                    nRecordings);

                fprintf( ...
                    'GCaMP XML: %s\n', ...
                    display_path(gcamp_xml_file));

                if isfinite(electroporated_column)

                    fprintf( ...
                        'Electroporated channel: column %d\n', ...
                        electroporated_column);

                    fprintf( ...
                        'Electroporated XML: %s\n', ...
                        display_path( ...
                            electroporated_xml_file));

                else

                    fprintf( ...
                        'Electroporated channel: none\n');
                end

                fprintf( ...
                    'ZSeries XML: %s\n', ...
                    display_path( ...
                        zseries_xml_file));

                % ======================================================
                % GCaMP metadata
                % ======================================================

                [ ...
                    selected_groups.(current_type)(k). ...
                        metadata.gcamp_plane, ...
                    rowTable_gcamp ...
                ] = ...
                    process_one_metadata_branch( ...
                        selected_groups.(current_type)(k). ...
                            metadata.gcamp_plane, ...
                        gcamp_xml_file, ...
                        date, ...
                        this_folder, ...
                        idx, ...
                        'gcamp', ...
                        save_to_excel, ...
                        force_rebuild_metadata);

                % ======================================================
                % Electroporated metadata
                % ======================================================

                if ~isempty(electroporated_xml_file)

                    [ ...
                        selected_groups.(current_type)(k). ...
                            metadata.electroporated_plane, ...
                        rowTable_electroporated ...
                    ] = ...
                        process_one_metadata_branch( ...
                            selected_groups.(current_type)(k). ...
                                metadata.electroporated_plane, ...
                            electroporated_xml_file, ...
                            date, ...
                            this_folder, ...
                            idx, ...
                            'electroporated', ...
                            save_to_excel, ...
                            force_rebuild_metadata);

                else

                    rowTable_electroporated = ...
                        table();
                end

                % ======================================================
                % ZSeries metadata
                % ======================================================

                if ~isempty(zseries_xml_file) && ...
                        exist(zseries_xml_file, 'file') == 2

                    zmeta = ...
                        find_zseries_metadata( ...
                            zseries_xml_file);

                    zmeta.Date = ...
                        date;

                    z_fields = ...
                        fieldnames(zmeta);

                    for f = 1:numel(z_fields)

                        fn = ...
                            z_fields{f};

                        if ~isfield( ...
                                selected_groups.(current_type)(k). ...
                                    metadata.ZSeries, ...
                                fn)

                            selected_groups.(current_type)(k). ...
                                metadata.ZSeries.(fn) = {};
                        end

                        selected_groups.(current_type)(k). ...
                            metadata.ZSeries.(fn){idx,1} = ...
                                zmeta.(fn);
                    end

                else

                    fprintf( ...
                        'ZSeries metadata rec %d: XML unavailable.\n', ...
                        idx);
                end

                % ======================================================
                % Tableau global GCaMP
                % ======================================================

                if ~isempty(rowTable_gcamp) && ...
                        height(rowTable_gcamp) >= 1

                    metadata_table = ...
                        append_metadata_summary( ...
                            metadata_table, ...
                            rowTable_gcamp, ...
                            current_type, ...
                            selected_groups.(current_type)(k), ...
                            'gcamp_plane');
                end

                % ======================================================
                % Tableau global Electroporated
                % ======================================================

                if ~isempty(rowTable_electroporated) && ...
                        height(rowTable_electroporated) >= 1

                    metadata_table = ...
                        append_metadata_summary( ...
                            metadata_table, ...
                            rowTable_electroporated, ...
                            current_type, ...
                            selected_groups.(current_type)(k), ...
                            'electroporated_plane');
                end

                % ======================================================
                % Excel groupé GCaMP
                % ======================================================

                if ~isempty(rowTable_gcamp) && ...
                        height(rowTable_gcamp) >= 1

                    [ ...
                        group_table_gcamp, ...
                        modified ...
                    ] = ...
                        add_metadata_row_if_new_date( ...
                            group_table_gcamp, ...
                            rowTable_gcamp);

                    group_table_modified_gcamp = ...
                        group_table_modified_gcamp || ...
                        modified;
                end

                % ======================================================
                % Excel groupé électroporé
                % ======================================================

                if ~isempty(rowTable_electroporated) && ...
                        height(rowTable_electroporated) >= 1

                    [ ...
                        group_table_electroporated, ...
                        modified ...
                    ] = ...
                        add_metadata_row_if_new_date( ...
                            group_table_electroporated, ...
                            rowTable_electroporated);

                    group_table_modified_electroporated = ...
                        group_table_modified_electroporated || ...
                        modified;
                end
            end

            % ==========================================================
            % Sauvegarde Excel groupée
            % ==========================================================

            if save_to_excel

                save_group_metadata_table( ...
                    group_table_gcamp, ...
                    group_output_path_gcamp, ...
                    group_file_existed_gcamp, ...
                    group_table_modified_gcamp);

                selected_groups.(current_type)(k). ...
                    metadata.gcamp_plane.source_file = ...
                    group_output_path_gcamp;

                save_group_metadata_table( ...
                    group_table_electroporated, ...
                    group_output_path_electroporated, ...
                    group_file_existed_electroporated, ...
                    group_table_modified_electroporated);

                selected_groups.(current_type)(k). ...
                    metadata.electroporated_plane.source_file = ...
                    group_output_path_electroporated;
            end
        end
    end
end


%% ========================================================================
% TRAITEMENT D'UNE BRANCHE
% ========================================================================

function [metadata_branch, rowTable] = ...
        process_one_metadata_branch( ...
            metadata_branch, ...
            xml_file, ...
            date, ...
            this_folder, ...
            idx, ...
            branch_name, ...
            save_to_excel, ...
            force_rebuild_metadata)

    rowTable = table();

    if isempty(xml_file) || ...
            exist(xml_file, 'file') ~= 2

        fprintf( ...
            '%s metadata rec %d: XML unavailable.\n', ...
            branch_name, ...
            idx);

        return;
    end

    % ==============================================================
    % Fichier Excel individuel
    % ==============================================================

    output_path_single = '';

    if ~isempty(this_folder)

        if ~exist(this_folder, 'dir')
            mkdir(this_folder);
        end

        switch lower(branch_name)

            case 'gcamp'

                output_path_single = ...
                    fullfile( ...
                        this_folder, ...
                        'metadata_results_gcamp.xlsx');

            case 'electroporated'

                output_path_single = ...
                    fullfile( ...
                        this_folder, ...
                        'metadata_results_electroporated.xlsx');
        end
    end

    loaded_from_single_file = false;

    % ==============================================================
    % Reconstruction forcée
    % ==============================================================

    if force_rebuild_metadata && ...
            ~isempty(output_path_single) && ...
            exist(output_path_single, 'file') == 2

        fprintf( ...
            '%s metadata rec %d: deleting old Excel -> rebuild from XML\n', ...
            branch_name, ...
            idx);

        delete(output_path_single);
    end

    % ==============================================================
    % Lecture Excel
    % ==============================================================

    if save_to_excel && ...
            ~isempty(output_path_single) && ...
            exist(output_path_single, 'file') == 2

        try

            rowTable = ...
                readtable( ...
                    output_path_single, ...
                    'VariableNamingRule', ...
                    'preserve');

            rowTable = ...
                normalize_metadata_table( ...
                    rowTable);

            if height(rowTable) > 1
                rowTable = rowTable(1,:);
            end

            if ~isempty(rowTable) && ...
                    isempty_value(rowTable.Date{1}) && ...
                    ~isempty(date)

                rowTable.Date{1} = ...
                    date;
            end

            loaded_from_single_file = true;

            fprintf( ...
                '%s metadata rec %d loaded from Excel\n', ...
                branch_name, ...
                idx);

        catch ME

            warning( ...
                'Impossible de relire %s : %s', ...
                output_path_single, ...
                ME.message);

            try
                delete(output_path_single);
            catch
            end

            rowTable = table();
        end
    end

    % ==============================================================
    % Extraction XML
    % ==============================================================

    if ~loaded_from_single_file

        meta_xml = ...
            find_key_value( ...
                xml_file);

        meta_xml.Date = ...
            date;

        rowTable = ...
            struct2table( ...
                meta_xml, ...
                'AsArray', ...
                true);

        rowTable = ...
            normalize_metadata_table( ...
                rowTable);

        if save_to_excel && ...
                ~isempty(output_path_single)

            writetable( ...
                rowTable, ...
                output_path_single, ...
                'FileType', ...
                'spreadsheet');

            fprintf( ...
                '%s metadata rec %d saved -> %s\n', ...
                branch_name, ...
                idx, ...
                output_path_single);
        end
    end

    if isempty(rowTable) || ...
            height(rowTable) < 1

        return;
    end

    metadata_branch = ...
        add_row_to_metadata_struct( ...
            metadata_branch, ...
            rowTable, ...
            idx);
end


