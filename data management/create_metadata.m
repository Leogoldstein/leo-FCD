function tf = isempty_value(x)

    if isempty(x)

        tf = true;

    elseif isstring(x)

        tf = ...
            all(strlength(x) == 0);

    elseif ischar(x)

        tf = ...
            isempty(strtrim(x));

    elseif iscell(x)

        tf = ...
            isempty(x) || ...
            isempty_value(x{1});

    elseif ismissing(x)

        tf = true;

    else

        tf = false;
    end
end


function value = unwrap_metadata_value(value)

    while iscell(value)

        if isempty(value)

            value = [];
            return;
        end

        value = ...
            value{1};
    end
end


function value = get_metadata_value(T, field)

    value = [];

    if isempty(T) || ...
            height(T) < 1

        return;
    end

    if ~any(strcmp( ...
            T.Properties.VariableNames, ...
            field))

        return;
    end

    value = ...
        T.(field);

    if iscell(value)

        if isempty(value)
            return;
        end

        value = ...
            value{1};

        value = ...
            unwrap_metadata_value( ...
                value);

    else

        value = ...
            value(1);
    end
end


