function tf = isempty_value(x)

    if isempty(x)

        tf = true;

    elseif isstring(x)

        tf = ...
            all(strlength(x) == 0);

    elseif ischar(x)

        tf = ...
            isempty(strtrim(x));

    elseif iscell(x)

        tf = ...
            isempty(x) || ...
            isempty_value(x{1});

    elseif ismissing(x)

        tf = true;

    else

        tf = false;
    end
end


function path_char = force_char_path(path_in)

    path_char = ...
        path_in;

    if isempty(path_char)

        path_char = '';
        return;
    end

    if istable(path_char)
        path_char = path_char{1,1};
    end

    if iscell(path_char)

        if isempty(path_char)
            path_char = '';
            return;
        end

        path_char = path_char{1};
    end

    if isstring(path_char)
        path_char = char(path_char);
    end

    if iscategorical(path_char)
        path_char = char(path_char);
    end

    if ~ischar(path_char)

        error( ...
            'Chemin invalide : type %s', ...
            class(path_char));
    end
end


function value = get_metadata_value(T, field)

    value = [];

    if isempty(T) || ...
            height(T) < 1

        return;
    end

    if ~any(strcmp( ...
            T.Properties.VariableNames, ...
            field))

        return;
    end

    current_value = ...
        T.(field);

    if iscell(current_value)

        if ~isempty(current_value)

            value = ...
                current_value{1};
        end

    else

        value = ...
            current_value(1);
    end
end


function C4 = force_4col(C)

    if isempty(C)

        C4 = ...
            cell(0,4);

        return;
    end

    if ~iscell(C)

        if isstring(C)

            C = ...
                cellstr(C);

        elseif ischar(C)

            C = ...
                {C};

        else

            C = ...
                num2cell(C);
        end
    end

    nRows = ...
        size(C,1);

    nCols = ...
        size(C,2);

    C4 = ...
        cell(nRows,4);

    C4(:,1:min(4,nCols)) = ...
        C(:,1:min(4,nCols));
end


function C = resize_4col(C, nRows)

    C = ...
        force_4col(C);

    out = ...
        cell(nRows,4);

    nCopy = ...
        min( ...
            size(C,1), ...
            nRows);

    if nCopy > 0

        out(1:nCopy,:) = ...
            C(1:nCopy,:);
    end

    C = out;
end


function path = get_matrix_path(C, row, col)

    path = '';

    if isempty(C) || ...
            row > size(C,1) || ...
            col > size(C,2)

        return;
    end

    value = ...
        C{row,col};

    while iscell(value)

        if isempty(value)
            value = '';
            break;
        end

        value = value{1};
    end

    if isempty(value)
        return;
    end

    path = ...
        force_char_path( ...
            value);
end


function n = numel_safe_field(S, field)

    n = 0;

    if isfield(S, field) && ...
            ~isempty(S.(field))

        n = ...
            numel(S.(field));
    end
end


function txt = display_path(path)

    if isempty(path)

        txt = '<none>';

    else

        txt = path;
    end
end