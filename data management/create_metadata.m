%% ========================================================================
% NORMALISATION TABLE
% ========================================================================

function T = normalize_metadata_table(T)

    expected_fields = ...
        metadata_field_list();

    T = ...
        remove_unused_metadata_columns( ...
            T);

    if isempty(T)

        T = ...
            cell2table( ...
                cell( ...
                    0, ...
                    numel(expected_fields)), ...
                'VariableNames', ...
                expected_fields);

        return;
    end

    nRows = ...
        height(T);

    for i = 1:numel(expected_fields)

        field = ...
            expected_fields{i};

        if ~any(strcmp( ...
                T.Properties.VariableNames, ...
                field))

            T.(field) = ...
                cell(nRows,1);
        end
    end

    current_fields = ...
        T.Properties.VariableNames;

    for i = 1:numel(current_fields)

        field = ...
            current_fields{i};

        if ~any(strcmp( ...
                expected_fields, ...
                field))

            T(:,field) = [];
        end
    end

    T = ...
        T(:,expected_fields);

    for i = 1:numel(expected_fields)

        field = ...
            expected_fields{i};

        if ~iscell(T.(field))

            T.(field) = ...
                num2cell( ...
                    T.(field));
        end
    end
end


%% ========================================================================
% ADD ROW
% ========================================================================

function metadata = ...
        add_row_to_metadata_struct( ...
            metadata, ...
            T, ...
            idx)

    wanted_fields = ...
        metadata_field_list();

    T = ...
        normalize_metadata_table( ...
            T);

    for i = 1:numel(wanted_fields)

        field = ...
            wanted_fields{i};

        if ~isfield(metadata, field)
            metadata.(field) = {};
        end

        if isempty(T) || ...
                height(T) < 1

            metadata.(field){idx,1} = [];

        else

            metadata.(field){idx,1} = ...
                T.(field){1};
        end
    end
end


%% ========================================================================
% REMOVE UNUSED
% ========================================================================

function T = remove_unused_metadata_columns(T)

    remove_fields = { ...
        'RastersPerFrame', ...
        'LaserPower_1040', ...
        'LaserPowerByPlane_1040', ...
        'PMTGainByPlane_Red', ...
        'PMTGainByPlane_Green', ...
        'PMTGainByPlane_Blue'};

    for i = 1:numel(remove_fields)

        field = ...
            remove_fields{i};

        if any(strcmp( ...
                T.Properties.VariableNames, ...
                field))

            T(:,field) = [];
        end
    end
end


%% ========================================================================
% DÉTECTION CANAL ÉLECTROPORÉ SANS SUITE2P
% ========================================================================

function electroporated_column_by_group = ...
        find_electroporated_column_from_tseries( ...
            TSeries_group, ...
            nRecordings)

    electroporated_column_by_group = ...
        nan(nRecordings,1);

    TSeries_group = ...
        resize_4col( ...
            TSeries_group, ...
            nRecordings);

    for idx = 1:nRecordings

        % ======================================================
        % Colonne 2 prioritaire, puis colonne 3.
        %
        % Aucune vérification Suite2p ici :
        % create_metadata doit fonctionner avant Suite2p.
        % ======================================================

        for col = [2 3]

            current_path = ...
                get_matrix_path( ...
                    TSeries_group, ...
                    idx, ...
                    col);

            if isempty(current_path)
                continue;
            end

            electroporated_column_by_group(idx) = col;
            break;
        end
    end
end


