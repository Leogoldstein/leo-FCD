function metadata_table = ...
        append_metadata_summary( ...
            metadata_table, ...
            rowTable, ...
            current_type, ...
            current_group, ...
            branch_name)

    current_mtor = '';

    if isfield(current_group, 'line')

        current_mtor = ...
            char(string( ...
                current_group.line));
    end

    current_animal = '';

    if isfield(current_group, 'animal')

        current_animal = ...
            char(string( ...
                current_group.animal));
    end

    summary_row = ...
        table( ...
            string(current_type), ...
            string(current_mtor), ...
            string(current_animal), ...
            string(branch_name), ...
            string(get_metadata_value( ...
                rowTable, ...
                'DateName')), ...
            get_metadata_value( ...
                rowTable, ...
                'NumPlanes'), ...
            get_metadata_value( ...
                rowTable, ...
                'OpticalZoom'), ...
            get_metadata_value( ...
                rowTable, ...
                'SamplingRatePlane'), ...
            get_metadata_value( ...
                rowTable, ...
                'TimeMinutes'), ...
            'VariableNames', { ...
                'Type', ...
                'mTOR', ...
                'Animal', ...
                'Branch', ...
                'Date', ...
                'NumPlanes', ...
                'OpticalZoom', ...
                'SamplingRate_Hz', ...
                'RecordingDuration_min'});

    if isempty(metadata_table)

        metadata_table = ...
            summary_row;

    else

        metadata_table = ...
            [ ...
                metadata_table; ...
                summary_row ...
            ];
    end
end


%% ========================================================================
% FICHIER GROUPÉ
% ========================================================================

function [group_table, existed] = ...
        load_existing_group_table( ...
            group_output_path, ...
            save_to_excel)

    group_table = table();

    existed = ...
        save_to_excel && ...
        ~isempty(group_output_path) && ...
        exist(group_output_path, 'file') == 2;

    if ~existed
        return;
    end

    try

        group_table = ...
            readtable( ...
                group_output_path, ...
                'VariableNamingRule', ...
                'preserve');

        group_table = ...
            normalize_metadata_table( ...
                group_table);

    catch ME

        warning( ...
            'Impossible de relire %s : %s', ...
            group_output_path, ...
            ME.message);

        group_table = table();
        existed = false;
    end
end


function [group_table, modified] = ...
        add_metadata_row_if_new_date( ...
            group_table, ...
            rowTable)

    modified = false;

    rowTable = ...
        normalize_metadata_table( ...
            rowTable);

    if isempty(group_table)

        group_table = ...
            rowTable;

        modified = true;
        return;
    end

    group_table = ...
        normalize_metadata_table( ...
            group_table);

    current_date = ...
        get_metadata_value( ...
            rowTable, ...
            'DateName');

    if isempty_value(current_date)
        return;
    end

    date_col = ...
        group_table.DateName;

    if ~iscell(date_col)
        date_col = num2cell(date_col);
    end

    idx_same_date = ...
        strcmp( ...
            string(date_col), ...
            string(current_date));

    if any(idx_same_date)
        return;
    end

    group_table = ...
        [ ...
            group_table; ...
            rowTable ...
        ];

    modified = true;
end


function save_group_metadata_table( ...
        group_table, ...
        output_path, ...
        file_existed, ...
        modified)

    if isempty(output_path) || ...
            isempty(group_table)

        return;
    end

    output_folder = ...
        fileparts( ...
            output_path);

    if ~exist(output_folder, 'dir')
        mkdir(output_folder);
    end

    if ~file_existed || modified

        group_table = ...
            normalize_metadata_table( ...
                group_table);

        writetable( ...
            group_table, ...
            output_path, ...
            'FileType', ...
            'spreadsheet');

        fprintf( ...
            'Grouped metadata saved -> %s\n', ...
            output_path);
    end
end


