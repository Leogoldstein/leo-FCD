%% ========================================================================
% TABLE GLOBAL
% ========================================================================

function metadata_table = ...
        append_metadata_summary( ...
            metadata_table, ...
            rowTable, ...
            current_type, ...
            current_group, ...
            branch_name)

    current_mtor = '';

    if isfield(current_group, 'line')

        current_mtor = ...
            current_group.line;
    end

    current_animal = '';

    if isfield(current_group, 'animal')

        current_animal = ...
            current_group.animal;
    end

    summary_row = ...
        table( ...
            string(current_type), ...
            string(current_mtor), ...
            string(current_animal), ...
            string(branch_name), ...
            string(get_metadata_value( ...
                rowTable, ...
                'Date')), ...
            get_metadata_value( ...
                rowTable, ...
                'NumPlanes'), ...
            get_metadata_value( ...
                rowTable, ...
                'OpticalZoom'), ...
            get_metadata_value( ...
                rowTable, ...
                'SamplingRatePlane'), ...
            get_metadata_value( ...
                rowTable, ...
                'TimeMinutes'), ...
            'VariableNames', { ...
                'Type', ...
                'mTOR', ...
                'Animal', ...
                'Branch', ...
                'Date', ...
                'NumPlanes', ...
                'OpticalZoom', ...
                'SamplingRate_Hz', ...
                'RecordingDuration_min'});

    if isempty(metadata_table)

        metadata_table = ...
            summary_row;

    else

        metadata_table = ...
            [ ...
                metadata_table; ...
                summary_row ...
            ];
    end
end


%% ========================================================================
% FICHIER GROUPÉ
% ========================================================================

function [group_table, existed] = ...
        load_existing_group_table( ...
            group_output_path, ...
            save_to_excel)

    group_table = ...
        table();

    existed = ...
        save_to_excel && ...
        ~isempty(group_output_path) && ...
        exist(group_output_path, 'file') == 2;

    if ~existed
        return;
    end

    try

        group_table = ...
            readtable( ...
                group_output_path, ...
                'VariableNamingRule', ...
                'preserve');

        group_table = ...
            normalize_metadata_table( ...
                group_table);

    catch ME

        warning( ...
            'Impossible de relire %s : %s', ...
            group_output_path, ...
            ME.message);

        group_table = table();
        existed = false;
    end
end


function [group_table, modified] = ...
        add_metadata_row_if_new_date( ...
            group_table, ...
            rowTable)

    modified = false;

    rowTable = ...
        normalize_metadata_table( ...
            rowTable);

    if isempty(group_table)

        group_table = ...
            rowTable;

        modified = true;

        return;
    end

    group_table = ...
        normalize_metadata_table( ...
            group_table);

    % ==========================================================
    % Date du nouveau recording
    % ==========================================================

    current_date = ...
        get_metadata_value( ...
            rowTable, ...
            'Date');

    current_date = ...
        unwrap_metadata_value( ...
            current_date);

    if isempty_value(current_date)
        return;
    end

    % ==========================================================
    % Comparaison aux dates existantes
    % ==========================================================

    existing_dates = ...
        strings( ...
            height(group_table), ...
            1);

    for i = 1:height(group_table)

        value = ...
            group_table.Date{i};

        value = ...
            unwrap_metadata_value( ...
                value);

        if ~isempty_value(value)

            existing_dates(i) = ...
                string(value);
        end
    end

    if any( ...
            existing_dates == ...
            string(current_date))

        return;
    end

    % ==========================================================
    % Ajouter ligne
    % ==========================================================

    group_table = ...
        [ ...
            group_table; ...
            rowTable ...
        ];

    modified = true;
end


function save_group_metadata_table( ...
        group_table, ...
        output_path, ...
        file_existed, ...
        modified)

    if isempty(output_path) || ...
            isempty(group_table)

        return;
    end

    output_folder = ...
        fileparts( ...
            output_path);

    if ~exist(output_folder, 'dir')

        mkdir(output_folder);
    end

    if ~file_existed || ...
            modified

        group_table = ...
            normalize_metadata_table( ...
                group_table);

        writetable( ...
            group_table, ...
            output_path, ...
            'FileType', ...
            'spreadsheet');

        fprintf( ...
            'Grouped metadata saved -> %s\n', ...
            output_path);
    end
end


