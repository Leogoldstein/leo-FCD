%% ========================================================================
% NORMALISATION TABLE
% ========================================================================

function T = normalize_metadata_table(T)

    expected_fields = ...
        metadata_field_list();

    T = ...
        remove_unused_metadata_columns( ...
            T);

    if isempty(T)

        T = ...
            cell2table( ...
                cell( ...
                    0, ...
                    numel(expected_fields)), ...
                'VariableNames', ...
                expected_fields);

        return;
    end

    nRows = ...
        height(T);

    for i = 1:numel(expected_fields)

        field = ...
            expected_fields{i};

        if ~any(strcmp( ...
                T.Properties.VariableNames, ...
                field))

            T.(field) = ...
                cell(nRows,1);
        end
    end

    current_fields = ...
        T.Properties.VariableNames;

    for i = 1:numel(current_fields)

        field = ...
            current_fields{i};

        if ~any(strcmp( ...
                expected_fields, ...
                field))

            T(:,field) = [];
        end
    end

    T = ...
        T(:,expected_fields);

    for i = 1:numel(expected_fields)

        field = ...
            expected_fields{i};

        if ~iscell(T.(field))

            T.(field) = ...
                num2cell( ...
                    T.(field));
        end
    end
end


%% ========================================================================
% ADD ROW
% ========================================================================

function metadata = ...
        add_row_to_metadata_struct( ...
            metadata, ...
            T, ...
            idx)

    wanted_fields = ...
        metadata_field_list();

    T = ...
        normalize_metadata_table( ...
            T);

    for i = 1:numel(wanted_fields)

        field = ...
            wanted_fields{i};

        if ~isfield(metadata, field)

            metadata.(field) = {};
        end

