function C4 = force_4col(C)

    if isempty(C)

        C4 = ...
            cell(0,4);

        return;
    end

    nRows = ...
        size(C,1);

    nCols = ...
        size(C,2);

    C4 = ...
        cell(nRows,4);

    C4(:,1:min(4,nCols)) = ...
        C(:,1:min(4,nCols));
end


function C5 = force_5col(C)

    if isempty(C)

        C5 = ...
            cell(0,5);

        return;
    end

    nRows = ...
        size(C,1);

    nCols = ...
        size(C,2);

    C5 = ...
        cell(nRows,5);

    C5(:,1:min(5,nCols)) = ...
        C(:,1:min(5,nCols));
end


function C = resize_4col(C, nRows)

    C = ...
        force_4col(C);

    out = ...
        cell(nRows,4);

    nCopy = ...
        min( ...
            size(C,1), ...
            nRows);

    if nCopy > 0

        out(1:nCopy,:) = ...
            C(1:nCopy,:);
    end

    C = ...
        out;
end


function C = resize_5col(C, nRows)

    C = ...
        force_5col(C);

    out = ...
        cell(nRows,5);

    nCopy = ...
        min( ...
            size(C,1), ...
            nRows);

    if nCopy > 0

        out(1:nCopy,:) = ...
            C(1:nCopy,:);
    end

    C = ...
        out;
end


function n = numel_safe_field(S, field)

    n = 0;

    if isfield(S, field) && ...
            ~isempty(S.(field))

        n = ...
            numel(S.(field));
    end
end


