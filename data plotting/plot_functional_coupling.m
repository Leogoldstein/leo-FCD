%==================================================================%
% Age / date
%==================================================================%
function age_label = ...
    get_age_label( ...
        ages, ...
        m)

    if iscell(ages)

        age_value = ...
            ages{m};

    else

        age_value = ...
            ages(m);
    end


    if isnumeric(age_value) || ...
            islogical(age_value)

        age_label = ...
            sprintf( ...
                'P%d', ...
                round( ...
                    double(age_value)));

    else

        age_txt = ...
            age_value;


        token = ...
            regexp( ...
                age_txt, ...
                '\d+', ...
                'match', ...
                'once');


        if isempty(token)

            age_label = ...
                age_txt;

        else

            age_label = ...
                ['P' token];
        end
    end
end


function date_label = ...
    get_date_label( ...
        dates, ...
        m)

    if iscell(dates)

        date_value = ...
            dates{m};

    else

        date_value = ...
            dates(m);
    end


    if isdatetime(date_value)

        date_label = ...
            datestr( ...
                date_value, ...
                'yyyy-mm-dd');

    else

        date_label = ...
            date_value;
    end
end