%==================================================================%
% Figure individuelle
%==================================================================%
function create_single_coupling_figure( ...
        D, ...
        p, ...
        figure_title, ...
        filename_title, ...
        current_gcamp_output_folder, ...
        current_line, ...
        current_animal, ...
        current_date, ...
        current_age, ...
        plane_number)

    fig = [];


    if isempty(current_gcamp_output_folder) || ...
            exist(current_gcamp_output_folder, 'dir') ~= 7

        return;
    end


    %==============================================================%
    % Filename
    %==============================================================%
    if isempty(current_line)

        filename = ...
            sprintf( ...
                '%s_%s_%s_plane%d_%s.png', ...
                current_animal, ...
                current_date, ...
                current_age, ...
                plane_number, ...
                filename_title);

    else

        filename = ...
            sprintf( ...
                '%s_%s_%s_%s_plane%d_%s.png', ...
                current_line, ...
                current_animal, ...
                current_date, ...
                current_age, ...
                plane_number, ...
                filename_title);
    end


    save_path = ...
        fullfile( ...
            current_gcamp_output_folder, ...
            filename);


    if exist(save_path, 'file') == 2

        fprintf( ...
            'Figure already exists, skip: %s\n', ...
            save_path);

        return;
    end


    try

        fig = ...
            figure( ...
                'Color', 'w', ...
                'Units', 'normalized', ...
                'Position', [0.03 0.15 0.94 0.68], ...
                'Name', figure_title);


        tl = ...
            tiledlayout( ...
                fig, ...
                1, ...
                4, ...
                'TileSpacing', 'compact', ...
                'Padding', 'compact');


        title( ...
            tl, ...
            figure_title, ...
            'Interpreter', 'none', ...
            'FontWeight', 'bold', ...
            'FontSize', 18);


        %==========================================================%
        % Population correlation
        %==========================================================%
        ax1 = ...
            nexttile(tl);


        pop = ...
            get_clean_plane( ...
                D.population_corr, ...
                p);


        if isempty(pop)

            empty_coupling_axis( ...
                ax1, ...
                'Population correlation');

        else

            histogram( ...
                ax1, ...
                pop, ...
                choose_nbins(pop));


            xline(ax1, 0, '--k');

            xlim(ax1, [-1 1]);

            xlabel(ax1, 'Correlation');

            ylabel(ax1, 'Cells');

            title( ...
                ax1, ...
                'Population correlation');


            grid(ax1, 'on');

            box(ax1, 'off');
        end


        %==========================================================%
        % Observed vs shuffle
        %==========================================================%
        ax2 = ...
            nexttile(tl);


        obs = ...
            get_plane_raw( ...
                D.observed, ...
                p);


        shuf = ...
            get_plane_raw( ...
                D.shuffle, ...
                p);


        [obs, shuf] = ...
            pair_same_cells( ...
                obs, ...
                shuf);


        if isempty(obs)

            empty_coupling_axis( ...
                ax2, ...
                'Observed vs shuffle');

        else

            hold(ax2, 'on');


            for c = 1:numel(obs)

                plot( ...
                    ax2, ...
                    [1 2], ...
                    [obs(c) shuf(c)], ...
                    '-', ...
                    'Color', ...
                    [0.75 0.75 0.75]);
            end


            scatter( ...
                ax2, ...
                ones(size(obs)), ...
                obs, ...
                30, ...
                'filled');


            scatter( ...
                ax2, ...
                2 .* ones(size(shuf)), ...
                shuf, ...
                30, ...
                'filled');


            xticks(ax2, [1 2]);

            xticklabels( ...
                ax2, ...
                {'Observed', 'Shuffle'});


            xlim(ax2, [0.5 2.5]);

            ylabel( ...
                ax2, ...
                'Active GCaMP fraction');


            title( ...
                ax2, ...
                'Observed vs shuffle');


            grid(ax2, 'on');

            box(ax2, 'off');

            hold(ax2, 'off');
        end


        %==========================================================%
        % Excess coupling
        %==========================================================%
        ax3 = ...
            nexttile(tl);


        exc = ...
            get_clean_plane( ...
                D.excess, ...
                p);


        if isempty(exc)

            empty_coupling_axis( ...
                ax3, ...
                'Excess coupling');

        else

            histogram( ...
                ax3, ...
                exc, ...
                choose_nbins(exc));


            xline(ax3, 0, '--k');

            xlabel( ...
                ax3, ...
                'Observed - shuffle');


            ylabel(ax3, 'Cells');

            title( ...
                ax3, ...
                'Excess coupling');


            grid(ax3, 'on');

            box(ax3, 'off');
        end


        %==========================================================%
        % Lagged coupling
        %==========================================================%
        ax4 = ...
            nexttile(tl);


        lag = ...
            get_plane_raw( ...
                D.lag_ms, ...
                p);


        lagcorr = ...
            get_plane_raw( ...
                D.max_lagged_corr, ...
                p);


        [lag, lagcorr] = ...
            pair_same_cells( ...
                lag, ...
                lagcorr);


        if isempty(lag)

            empty_coupling_axis( ...
                ax4, ...
                'Lagged coupling');

        else

            scatter( ...
                ax4, ...
                lag, ...
                lagcorr, ...
                35, ...
                'filled', ...
                'MarkerFaceAlpha', ...
                0.65);


            xline(ax4, 0, '--k');

            yline(ax4, 0, '--k');

            xlabel(ax4, 'Lag (ms)');

            ylabel( ...
                ax4, ...
                'Maximum correlation');


            ylim(ax4, [-1 1]);

            title( ...
                ax4, ...
                'Lagged coupling');


            grid(ax4, 'on');

            box(ax4, 'off');
        end


        set( ...
            fig, ...
            'WindowState', ...
            'maximized');


        drawnow;


        exportgraphics( ...
            fig, ...
            save_path, ...
            'Resolution', ...
            300);


        fprintf( ...
            'Saved: %s\n', ...
            save_path);


        close(fig);


    catch ME

        fprintf( ...
            '%s | plane %d: %s\n', ...
            figure_title, ...
            plane_number, ...
            ME.message);


        if ~isempty(fig) && ...
                isgraphics(fig)

            close(fig);
        end
    end
end


%==================================================================%
% Figure comparative
%==================================================================%
function create_comparative_coupling_figure( ...
        G, ...
        M, ...
        p, ...
        current_output_folder, ...
        current_line, ...
        current_animal, ...
        current_date, ...
        current_age, ...
        plane_number)

    fig = [];


    if isempty(current_output_folder) || ...
            exist(current_output_folder, 'dir') ~= 7

        return;
    end


    figure_title = ...
        'GCaMP vs mTOR functional coupling';


    if isempty(current_line)

        filename = ...
            sprintf( ...
                ['%s_%s_%s_plane%d_' ...
                 'GCaMP_vs_mTOR_functional_coupling.png'], ...
                current_animal, ...
                current_date, ...
                current_age, ...
                plane_number);

    else

        filename = ...
            sprintf( ...
                ['%s_%s_%s_%s_plane%d_' ...
                 'GCaMP_vs_mTOR_functional_coupling.png'], ...
                current_line, ...
                current_animal, ...
                current_date, ...
                current_age, ...
                plane_number);
    end


    save_path = ...
        fullfile( ...
            current_output_folder, ...
            filename);


    if exist(save_path, 'file') == 2

        fprintf( ...
            'Comparative coupling figure already exists, skip: %s\n', ...
            save_path);

        return;
    end


    try

        fig = ...
            figure( ...
                'Color', 'w', ...
                'Units', 'normalized', ...
                'Position', [0.03 0.15 0.94 0.68], ...
                'Name', figure_title);


        tl = ...
            tiledlayout( ...
                fig, ...
                1, ...
                4, ...
                'TileSpacing', 'compact', ...
                'Padding', 'compact');


        title( ...
            tl, ...
            figure_title, ...
            'Interpreter', 'none', ...
            'FontWeight', 'bold', ...
            'FontSize', 18);


        ax1 = ...
            nexttile(tl);


        plot_two_group_distribution( ...
            ax1, ...
            get_clean_plane(G.population_corr, p), ...
            get_clean_plane(M.population_corr, p), ...
            'Population correlation', ...
            'Cell-population correlation');


        ax2 = ...
            nexttile(tl);


        plot_two_group_distribution( ...
            ax2, ...
            get_clean_plane(G.excess, p), ...
            get_clean_plane(M.excess, p), ...
            'Excess coupling', ...
            'Observed - shuffled coupling');


        ax3 = ...
            nexttile(tl);


        plot_two_group_distribution( ...
            ax3, ...
            get_clean_plane(G.max_lagged_corr, p), ...
            get_clean_plane(M.max_lagged_corr, p), ...
            'Maximum lagged correlation', ...
            'Maximum correlation');


        ylim(ax3, [-1 1]);


        ax4 = ...
            nexttile(tl);


        plot_two_group_distribution( ...
            ax4, ...
            get_clean_plane(G.lag_ms, p), ...
            get_clean_plane(M.lag_ms, p), ...
            'Lag', ...
            'Lag (ms)');


        yline( ...
            ax4, ...
            0, ...
            '--k');


        set( ...
            fig, ...
            'WindowState', ...
            'maximized');


        drawnow;


        exportgraphics( ...
            fig, ...
            save_path, ...
            'Resolution', ...
            300);


        fprintf( ...
            'Saved: %s\n', ...
            save_path);


        close(fig);


    catch ME

        fprintf( ...
            'Comparative coupling | plane %d: %s\n', ...
            plane_number, ...
            ME.message);


        if ~isempty(fig) && ...
                isgraphics(fig)

            close(fig);
        end
    end
end


%==================================================================%
% Comparaison de deux distributions
%==================================================================%
function plot_two_group_distribution( ...
        ax, ...
        gcamp_gcamp_values, ...
        gcamp_mtor_values, ...
        panel_title, ...
        ylabel_text)

    gcamp_gcamp_values = ...
        clean_numeric_local( ...
            gcamp_gcamp_values);


    gcamp_mtor_values = ...
        clean_numeric_local( ...
            gcamp_mtor_values);


    n_gcamp = ...
        numel(gcamp_gcamp_values);


    n_mtor = ...
        numel(gcamp_mtor_values);


    if n_gcamp == 0 && ...
            n_mtor == 0

        empty_coupling_axis( ...
            ax, ...
            panel_title);

        return;
    end


    hold(ax, 'on');


    data = [];
    group = [];


    if n_gcamp > 0

        data = ...
            [data; gcamp_gcamp_values(:)];


        group = ...
            [group; ones(n_gcamp,1)];
    end


    if n_mtor > 0

        data = ...
            [data; gcamp_mtor_values(:)];


        group = ...
            [group; 2 .* ones(n_mtor,1)];
    end


    boxplot( ...
        ax, ...
        data, ...
        group, ...
        'Symbol', '', ...
        'Colors', 'k');


    color_gcamp = ...
        [0.20 0.65 0.25];


    color_mtor = ...
        [0.10 0.35 0.90];


    if n_gcamp > 0

        scatter( ...
            ax, ...
            1 + 0.06 .* randn(size(gcamp_gcamp_values)), ...
            gcamp_gcamp_values, ...
            28, ...
            'filled', ...
            'MarkerFaceColor', ...
            color_gcamp, ...
            'MarkerEdgeColor', ...
            'none', ...
            'MarkerFaceAlpha', ...
            0.55);
    end


    if n_mtor > 0

        scatter( ...
            ax, ...
            2 + 0.06 .* randn(size(gcamp_mtor_values)), ...
            gcamp_mtor_values, ...
            28, ...
            'filled', ...
            'MarkerFaceColor', ...
            color_mtor, ...
            'MarkerEdgeColor', ...
            'none', ...
            'MarkerFaceAlpha', ...
            0.55);
    end


    xticks(ax, [1 2]);


    xticklabels( ...
        ax, ...
        { ...
            sprintf('GCaMP-GCaMP (n = %d)', n_gcamp), ...
            sprintf('GCaMP-mTOR (n = %d)', n_mtor) ...
        });


    xlim(ax, [0.5 2.5]);


    ylabel( ...
        ax, ...
        ylabel_text);


    title( ...
        ax, ...
        panel_title);


    grid(ax, 'on');

    box(ax, 'off');

    hold(ax, 'off');
end


%==================================================================%
% Helpers
%==================================================================%
function x = clean_numeric_local(x)

    if isempty(x) || ...
            ~(isnumeric(x) || islogical(x))

        x = [];
        return;
    end


    x = ...
        double(x(:));


    x = ...
        x(isfinite(x));
end


function D = ...
    empty_coupling_data()

    D = ...
        struct( ...
            'population_corr', {{}}, ...
            'observed', {{}}, ...
            'shuffle', {{}}, ...
            'excess', {{}}, ...
            'ratio', {{}}, ...
            'max_lagged_corr', {{}}, ...
            'lag_ms', {{}});
end


function D = ...
    normalize_coupling_planes(D)

    fields = ...
        fieldnames(D);


    for i = 1:numel(fields)

        D.(fields{i}) = ...
            normalize_planes_cell( ...
                D.(fields{i}));
    end
end


function nPlanes = ...
    get_nplanes_coupling(D)

    fields = ...
