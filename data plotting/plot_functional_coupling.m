function plot_functional_coupling( ...
        results_analysis, ...
        current_automatic_selection, ...
        current_output_folder, ...
        gcamp_output_folders, ...
        current_line, ...
        current_animal, ...
        current_dates, ...
        current_ages)

%PLOT_FUNCTIONAL_COUPLING
%
% Selon les données disponibles :
%
%   results_analysis.gcamp_plane.coupling
%       -> GCaMP-GCaMP functional coupling
%
%   results_analysis.electroporated_plane.coupling
%       -> GCaMP-mTOR functional coupling
%
%   les deux présents
%       -> GCaMP vs mTOR functional coupling
%
% Une figure par recording et par plan.
%
% Organisation des dossiers GCaMP :
%
%   gcamp_output_folders{m}{p}
%
% avec :
%   m = recording
%   p = plan
%
% Sauvegarde :
%
%   GCaMP-GCaMP
%       -> gcamp_output_folders{m}{p}
%
%   GCaMP-mTOR
%       -> gcamp_output_folders{m}{p}
%
%   GCaMP vs mTOR
%       -> current_output_folder
%
% IMPORTANT :
%   - aucun dossier n'est créé ici ;
%   - si un dossier GCaMP de plan est absent, les figures locales
%     de ce plan sont ignorées ;
%   - current_output_folder doit déjà exister.
%
% Nomenclature :
%
%   line_animal_date_age_planeN_nomFigure.png


    %==============================================================%
    % Vérifications
    %==============================================================%
    if isempty(results_analysis) || ...
            ~isstruct(results_analysis)

        return;
    end


    %==============================================================%
    % Sauvegarde comparative dans current_output_folder ?
    %==============================================================%
    save_in_current_output = ...
        current_automatic_selection ~= 0;
    
    
    %==============================================================%
    % Vérifier current_output_folder uniquement si utilisé
    %
    % current_output_folder contient déjà Adult ou Development.
    % L'arborescence line / animal / date est créée plus bas
    % recording par recording.
    %==============================================================%
    valid_global_output = ...
        false;
    
    
    if save_in_current_output
    
        valid_global_output = ...
            ~isempty(current_output_folder);
    
    
        if ~valid_global_output
    
            warning( ...
                ['Functional coupling: current_output_folder is empty. ' ...
                 'Comparative figures will be skipped.']);
        end
    end


    %==============================================================%
    % GCaMP-GCaMP coupling disponible ?
    %==============================================================%
    has_gcamp = ...
        isfield(results_analysis, 'gcamp_plane') && ...
        isstruct(results_analysis.gcamp_plane) && ...
        isfield(results_analysis.gcamp_plane, 'coupling') && ...
        isstruct(results_analysis.gcamp_plane.coupling) && ...
        ~isempty(fieldnames( ...
            results_analysis.gcamp_plane.coupling));


    %==============================================================%
    % GCaMP-mTOR coupling disponible ?
    %==============================================================%
    has_mtor = ...
        isfield(results_analysis, 'electroporated_plane') && ...
        isstruct(results_analysis.electroporated_plane) && ...
        isfield(results_analysis.electroporated_plane, 'coupling') && ...
        isstruct(results_analysis.electroporated_plane.coupling) && ...
        ~isempty(fieldnames( ...
            results_analysis.electroporated_plane.coupling));


    %==============================================================%
    % Rien à afficher
    %==============================================================%
    if ~has_gcamp && ...
            ~has_mtor

        fprintf( ...
            '%s: no functional coupling metrics available.\n', ...
            current_animal);

        return;
    end


    %==============================================================%
    % Nombre de recordings
    %==============================================================%
    nRec = ...
        max( ...
            [ ...
                numel(gcamp_output_folders), ...
                numel(current_dates), ...
                numel(current_ages) ...
            ]);


    %==============================================================%
    % Recordings
    %==============================================================%
    for m = 1:nRec

        %==========================================================%
        % Date / âge
        %==========================================================%
        if m <= numel(current_dates)

            current_date = ...
                get_date_label( ...
                    current_dates, ...
                    m);

        else

            current_date = ...
                '';
        end


        if m <= numel(current_ages)

            current_age = ...
                get_age_label( ...
                    current_ages, ...
                    m);

        else

            current_age = ...
                '';
        end

        %==========================================================%
        % Automatic-selection recording folder
        %
        % current_output_folder/
        %   line/
        %     animal/
        %       date/
        %==========================================================%
        automatic_recording_folder = '';
        
        
        if save_in_current_output && ...
                valid_global_output
        
            automatic_recording_folder = ...
                fullfile( ...
                    current_output_folder, ...
                    char(string(current_line)), ...
                    char(string(current_animal)), ...
                    char(string(current_date)));
        
        
            if exist(automatic_recording_folder, 'dir') ~= 7
        
                mkdir(automatic_recording_folder);
            end
        end

        %==========================================================%
        % GCaMP-GCaMP
        %==========================================================%
        gcamp = ...
            empty_coupling_data();


        if has_gcamp

            gcamp = ...
                get_gcamp_coupling_for_recording( ...
                    results_analysis. ...
                    gcamp_plane. ...
                    coupling, ...
                    m);
        end


        %==========================================================%
        % GCaMP-mTOR
        %==========================================================%
        mtor = ...
            empty_coupling_data();


        if has_mtor

            mtor = ...
                get_mtor_coupling_for_recording( ...
                    results_analysis. ...
                    electroporated_plane. ...
                    coupling, ...
                    m);
        end


        %==========================================================%
        % Nombre de plans
        %==========================================================%
        nPlanes = ...
            max( ...
                get_nplanes_coupling(gcamp), ...
                get_nplanes_coupling(mtor));


        if nPlanes == 0

            fprintf( ...
                'Rec %d: no functional coupling data, skip.\n', ...
                m);

            continue;
        end


        %==========================================================%
        % Plans
        %==========================================================%
        for p = 1:nPlanes

            plane_number = ...
                p - 1;


            %======================================================%
            % Dossier GCaMP DU PLAN
            %======================================================%
            current_gcamp_output_folder = '';


            if m <= numel(gcamp_output_folders) && ...
                    ~isempty(gcamp_output_folders{m}) && ...
                    iscell(gcamp_output_folders{m}) && ...
                    p <= numel(gcamp_output_folders{m}) && ...
                    ~isempty(gcamp_output_folders{m}{p})

                current_gcamp_output_folder = ...
                    gcamp_output_folders{m}{p};
            end


            valid_gcamp_output = ...
                ~isempty(current_gcamp_output_folder) && ...
                (ischar(current_gcamp_output_folder) || ...
                 isstring(current_gcamp_output_folder)) && ...
                isscalar(string(current_gcamp_output_folder)) && ...
                exist( ...
                    current_gcamp_output_folder, ...
                    'dir') == 7;


            %======================================================%
            % GCaMP-GCaMP
            %======================================================%
            has_gcamp_plane = ...
                coupling_plane_has_data( ...
                    gcamp, ...
                    p);


            if has_gcamp_plane

                if valid_gcamp_output

                    create_single_coupling_figure( ...
                        gcamp, ...
                        p, ...
                        'GCaMP-GCaMP functional coupling', ...
                        'GCaMP_GCaMP_functional_coupling', ...
                        current_gcamp_output_folder, ...
                        current_line, ...
                        current_animal, ...
                        current_date, ...
                        current_age, ...
                        plane_number);

                else

                    warning( ...
                        ['GCaMP-GCaMP rec %d plane %d: ' ...
                         'GCaMP output folder missing or invalid, ' ...
                         'figure skipped.'], ...
                        m, ...
                        plane_number);
                end
            end


            %======================================================%
            % GCaMP-mTOR
            %======================================================%
            has_mtor_plane = ...
                coupling_plane_has_data( ...
                    mtor, ...
                    p);


            if has_mtor_plane

                if valid_gcamp_output

                    create_single_coupling_figure( ...
                        mtor, ...
                        p, ...
                        'GCaMP-mTOR functional coupling', ...
                        'GCaMP_mTOR_functional_coupling', ...
                        current_gcamp_output_folder, ...
                        current_line, ...
                        current_animal, ...
                        current_date, ...
                        current_age, ...
                        plane_number);

                else

                    warning( ...
                        ['GCaMP-mTOR rec %d plane %d: ' ...
                         'GCaMP output folder missing or invalid, ' ...
                         'figure skipped.'], ...
                        m, ...
                        plane_number);
                end
            end


            %======================================================%
            % Comparaison GCaMP vs mTOR
            %
            % Sauvegardée uniquement si automatic selection ~= 0
            %======================================================%
            if save_in_current_output && ...
                    has_gcamp_plane && ...
                    has_mtor_plane
            
                if ~isempty(automatic_recording_folder)
            
                    create_comparative_coupling_figure( ...
                        gcamp, ...
                        mtor, ...
                        p, ...
                        automatic_recording_folder, ...
                        current_line, ...
                        current_animal, ...
                        current_date, ...
                        current_age, ...
                        plane_number);
            
                else
            
                    warning( ...
                        ['Comparative coupling rec %d plane %d: ' ...
                         'global output folder missing, figure skipped.'], ...
                        m, ...
                        plane_number);
                end
            end
        end
    end
end


%==================================================================%
% GCaMP coupling
%==================================================================%
function D = ...
    get_gcamp_coupling_for_recording( ...
        C, ...
        m)

    D = ...
        empty_coupling_data();


    D.population_corr = ...
        get_recording_field( ...
            C, ...
            'population_corr_gcamp_gcamp_by_plane', ...
            m);


    D.observed = ...
        get_recording_field( ...
            C, ...
            'peak_coupling_fraction_gcamp_gcamp_by_plane', ...
            m);


    D.shuffle = ...
        get_recording_field( ...
            C, ...
            'peak_coupling_shuffle_gcamp_gcamp_by_plane', ...
            m);


    D.excess = ...
        get_recording_field( ...
            C, ...
            'peak_coupling_excess_gcamp_gcamp_by_plane', ...
            m);


    D.ratio = ...
        get_recording_field( ...
            C, ...
            'peak_coupling_ratio_gcamp_gcamp_by_plane', ...
            m);


    D.max_lagged_corr = ...
        get_recording_field( ...
            C, ...
            'max_lagged_corr_gcamp_gcamp_population_by_plane', ...
            m);


    D.lag_ms = ...
        get_recording_field( ...
            C, ...
            'lag_to_gcamp_gcamp_population_ms_by_plane', ...
            m);


    D = ...
        normalize_coupling_planes(D);
end


