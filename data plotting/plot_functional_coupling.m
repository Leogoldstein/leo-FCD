%==================================================================%
% Extraction
%==================================================================%
function x = ...
    get_recording_field( ...
        S, ...
        field_name, ...
        m)

    x = [];


    if ~isstruct(S) || ...
            ~isfield(S, field_name)

        return;
    end


    all_values = ...
        S.(field_name);


    if isempty(all_values)
        return;
    end


    if iscell(all_values)

        if numel(all_values) >= m

            x = ...
                all_values{m};
        end


    elseif m == 1

        x = ...
            all_values;
    end
end


function planes = ...
    normalize_planes_cell(x)

    if isempty(x)

        planes = {};


    elseif iscell(x)

        planes = ...
            x(:).';


    else

        planes = ...
            {x};
    end
end


function tf = ...
    has_numeric_plane( ...
        planes, ...
        p)

    tf = ...
        false;


    if numel(planes) < p || ...
            isempty(planes{p})

        return;
    end


    x = ...
        planes{p};


    if isnumeric(x) || ...
            islogical(x)

        tf = ...
            any( ...
                isfinite( ...
                    double(x(:))));
    end
end


function x = ...
    get_plane_raw( ...
        planes, ...
        p)

    x = [];


    if numel(planes) < p
        return;
    end


    x = ...
        planes{p};


    if ~(isnumeric(x) || ...
            islogical(x))

        x = [];
        return;
    end


    x = ...
        double(x(:));
end


function x = ...
    get_clean_plane( ...
        planes, ...
        p)

    x = ...
        get_plane_raw( ...
            planes, ...
            p);


    if isempty(x)
        return;
    end


    x = ...
        x(isfinite(x));
end


function [x, y] = ...
    pair_same_cells( ...
        x, ...
        y)

    if isempty(x) || ...
            isempty(y)

        x = [];
        y = [];

        return;
    end


    x = ...
        double(x(:));


    y = ...
        double(y(:));


    n = ...
        min( ...
            numel(x), ...
            numel(y));


    x = ...
        x(1:n);


    y = ...
        y(1:n);


    valid = ...
        isfinite(x) & ...
        isfinite(y);


    x = ...
        x(valid);


    y = ...
        y(valid);
end


