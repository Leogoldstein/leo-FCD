            {x};
    end
end


function tf = ...
    has_numeric_plane( ...
        planes, ...
        p)

    tf = ...
        false;


    if numel(planes) < p || ...
            isempty(planes{p})

        return;
    end


    x = ...
        planes{p};


    if isnumeric(x) || ...
            islogical(x)

        tf = ...
            any( ...
                isfinite(double(x(:))));
    end
end


