function plot_functional_coupling( ...
        results_analysis, ...
        current_automatic_selection, ...
        current_output_folders, ...
        gcamp_output_folders, ...
        current_line, ...
        current_animal, ...
        current_dates, ...
        current_ages)

%PLOT_FUNCTIONAL_COUPLING
%
% Selon les données disponibles :
%
%   results_analysis.gcamp_plane.coupling
%       -> GCaMP-GCaMP functional coupling
%
%   results_analysis.electroporated_plane.coupling
%       -> GCaMP-mTOR functional coupling
%
%   les deux présents
%       -> GCaMP vs mTOR functional coupling
%
% Une figure par recording et par plan.
%
% Organisation des dossiers :
%
%   gcamp_output_folders{m}{p}
%
%       -> figures individuelles GCaMP-GCaMP / GCaMP-mTOR
%
%   current_output_folders{m}
%
%       -> figures comparatives GCaMP vs mTOR
%
% Structure attendue :
%
%   current_output_folders{m} =
%
%   ...\Summary plots\
%       <mode>\
%       Development|Adult\
%       line\
%       animal\
%       date
%
% Aucun sous-dossier line / animal / date n'est reconstruit ici.


    %==============================================================%
    % Vérifications
    %==============================================================%
    if isempty(results_analysis) || ...
            ~isstruct(results_analysis)

        return;
    end


    %==============================================================%
    % Sauvegarde comparative automatique ?
    %==============================================================%
    save_in_current_output = ...
        current_automatic_selection;


    if save_in_current_output && ...
            isempty(current_output_folders)

        warning( ...
            ['Functional coupling: current_output_folders is empty. ', ...
             'Comparative figures will be skipped.']);

        save_in_current_output = ...
            false;
    end


    %==============================================================%
    % GCaMP-GCaMP coupling disponible ?
    %==============================================================%
    has_gcamp = ...
        isfield(results_analysis, 'gcamp_plane') && ...
        isstruct(results_analysis.gcamp_plane) && ...
        isfield(results_analysis.gcamp_plane, 'coupling') && ...
        isstruct(results_analysis.gcamp_plane.coupling) && ...
        ~isempty(fieldnames( ...
            results_analysis.gcamp_plane.coupling));


    %==============================================================%
    % GCaMP-mTOR coupling disponible ?
    %==============================================================%
    has_mtor = ...
        isfield(results_analysis, 'electroporated_plane') && ...
        isstruct(results_analysis.electroporated_plane) && ...
        isfield(results_analysis.electroporated_plane, 'coupling') && ...
        isstruct(results_analysis.electroporated_plane.coupling) && ...
        ~isempty(fieldnames( ...
            results_analysis.electroporated_plane.coupling));


    %==============================================================%
    % Rien à afficher
    %==============================================================%
    if ~has_gcamp && ...
            ~has_mtor

        fprintf( ...
            '%s: no functional coupling metrics available.\n', ...
            current_animal);

        return;
    end


    %==============================================================%
    % Nombre de recordings
    %==============================================================%
    nRec = ...
        max( ...
            [ ...
                numel(gcamp_output_folders), ...
                numel(current_dates), ...
                numel(current_ages) ...
            ]);


    %==============================================================%
    % Recordings
    %==============================================================%
    for m = 1:nRec

        %==========================================================%
        % Date
        %==========================================================%
        if m <= numel(current_dates)

            current_date = ...
                char(string(current_dates{m}));

        else

            current_date = ...
                '';
        end


        %==========================================================%
        % Age
        %==========================================================%
        if m <= numel(current_ages)

            current_age = ...
                char(string(current_ages{m}));

        else

            current_age = ...
                '';
        end


        %==========================================================%
        % Output folder du recording
        %
        % Déjà complet :
        %
        % ...\Development|Adult\line\animal\date
        %==========================================================%
        current_output_folder = '';


        if save_in_current_output

            if m <= numel(current_output_folders) && ...
                    ~isempty(current_output_folders{m})

                current_output_folder = ...
                    current_output_folders{m};


                if exist(current_output_folder, 'dir') ~= 7

                    mkdir( ...
                        current_output_folder);
                end

            else

                warning( ...
                    'Functional coupling rec %d: output folder missing.', ...
                    m);
            end
        end


        %==========================================================%
        % GCaMP-GCaMP
        %==========================================================%
        gcamp = ...
            empty_coupling_data();


        if has_gcamp

            gcamp = ...
                get_gcamp_coupling_for_recording( ...
                    results_analysis. ...
                        gcamp_plane. ...
                        coupling, ...
                    m);
        end


        %==========================================================%
        % GCaMP-mTOR
        %==========================================================%
        mtor = ...
            empty_coupling_data();


        if has_mtor

            mtor = ...
                get_mtor_coupling_for_recording( ...
                    results_analysis. ...
                        electroporated_plane. ...
                        coupling, ...
                    m);
        end


        %==========================================================%
        % Nombre de plans
        %==========================================================%
        nPlanes = ...
            max( ...
                get_nplanes_coupling(gcamp), ...
                get_nplanes_coupling(mtor));


        if nPlanes == 0

            fprintf( ...
                'Rec %d: no functional coupling data, skip.\n', ...
                m);

            continue;
        end


        %==========================================================%
        % Plans
        %==========================================================%
        for p = 1:nPlanes

            plane_number = ...
                p - 1;


            %======================================================%
            % Dossier GCaMP du plan
            %======================================================%
            current_gcamp_output_folder = '';


            if m <= numel(gcamp_output_folders) && ...
                    ~isempty(gcamp_output_folders{m}) && ...
                    iscell(gcamp_output_folders{m}) && ...
                    p <= numel(gcamp_output_folders{m}) && ...
                    ~isempty(gcamp_output_folders{m}{p})

                current_gcamp_output_folder = ...
                    gcamp_output_folders{m}{p};
            end


            valid_gcamp_output = ...
                ~isempty(current_gcamp_output_folder) && ...
                exist( ...
                    current_gcamp_output_folder, ...
                    'dir') == 7;


            %======================================================%
            % GCaMP-GCaMP
            %======================================================%
            has_gcamp_plane = ...
                coupling_plane_has_data( ...
                    gcamp, ...
                    p);


            if has_gcamp_plane

                if valid_gcamp_output

                    create_single_coupling_figure( ...
                        gcamp, ...
                        p, ...
                        'GCaMP-GCaMP functional coupling', ...
                        'GCaMP_GCaMP_functional_coupling', ...
                        current_gcamp_output_folder, ...
                        current_line, ...
                        current_animal, ...
                        current_date, ...
                        current_age, ...
                        plane_number);

                else

                    warning( ...
                        ['GCaMP-GCaMP rec %d plane %d: ', ...
                         'GCaMP output folder missing, figure skipped.'], ...
                        m, ...
                        plane_number);
                end
            end


            %======================================================%
            % GCaMP-mTOR
            %======================================================%
            has_mtor_plane = ...
                coupling_plane_has_data( ...
                    mtor, ...
                    p);


            if has_mtor_plane

                if valid_gcamp_output

                    create_single_coupling_figure( ...
                        mtor, ...
                        p, ...
                        'GCaMP-mTOR functional coupling', ...
                        'GCaMP_mTOR_functional_coupling', ...
                        current_gcamp_output_folder, ...
                        current_line, ...
                        current_animal, ...
                        current_date, ...
                        current_age, ...
                        plane_number);

                else

                    warning( ...
                        ['GCaMP-mTOR rec %d plane %d: ', ...
                         'GCaMP output folder missing, figure skipped.'], ...
                        m, ...
                        plane_number);
                end
            end


            %======================================================%
            % Comparaison GCaMP vs mTOR
            %
            % Sauvegarde directement dans current_output_folders{m}
            %======================================================%
            if save_in_current_output && ...
                    has_gcamp_plane && ...
                    has_mtor_plane

                if ~isempty(current_output_folder)

                    create_comparative_coupling_figure( ...
                        gcamp, ...
                        mtor, ...
                        p, ...
                        current_output_folder, ...
                        current_line, ...
                        current_animal, ...
                        current_date, ...
                        current_age, ...
                        plane_number);

                else

                    warning( ...
                        ['Comparative coupling rec %d plane %d: ', ...
                         'output folder missing, figure skipped.'], ...
                        m, ...
                        plane_number);
                end
            end
        end
    end
end


%==================================================================%
% GCaMP coupling
%==================================================================%
function D = ...
    get_gcamp_coupling_for_recording( ...
        C, ...
        m)

    D = ...
        empty_coupling_data();


    D.population_corr = ...
        get_recording_field( ...
            C, ...
            'population_corr_gcamp_gcamp_by_plane', ...
            m);


    D.observed = ...
        get_recording_field( ...
            C, ...
            'peak_coupling_fraction_gcamp_gcamp_by_plane', ...
            m);


    D.shuffle = ...
        get_recording_field( ...
            C, ...
            'peak_coupling_shuffle_gcamp_gcamp_by_plane', ...
            m);


    D.excess = ...
        get_recording_field( ...
            C, ...
            'peak_coupling_excess_gcamp_gcamp_by_plane', ...
            m);


    D.ratio = ...
        get_recording_field( ...
            C, ...
            'peak_coupling_ratio_gcamp_gcamp_by_plane', ...
            m);


    D.max_lagged_corr = ...
        get_recording_field( ...
            C, ...
            'max_lagged_corr_gcamp_gcamp_population_by_plane', ...
            m);


    D.lag_ms = ...
        get_recording_field( ...
            C, ...
            'lag_to_gcamp_gcamp_population_ms_by_plane', ...
            m);


    D = ...
        normalize_coupling_planes(D);
end


