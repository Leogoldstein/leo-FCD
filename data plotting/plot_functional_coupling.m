function [x, y] = ...
    pair_same_cells( ...
        x, ...
        y)

    if isempty(x) || ...
            isempty(y)

        x = [];
        y = [];

        return;
    end


    x = ...
        double(x(:));


    y = ...
        double(y(:));


    n = ...
        min( ...
            numel(x), ...
            numel(y));


    x = ...
        x(1:n);


    y = ...
        y(1:n);


    valid = ...
        isfinite(x) & ...
        isfinite(y);


    x = ...
        x(valid);


    y = ...
        y(valid);
end


