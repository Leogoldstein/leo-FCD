%==================================================================
% CARTOUCHES GROUPES
%==================================================================
function draw_grouped_violin_annotations( ...
        ax, ...
        values_by_age, ...
        animals_by_age, ...
        ages, ...
        violin_color)

    nAges = ...
        numel(ages);


    if nAges == 0

        return;
    end


    %==============================================================%
    % Ages separes de <= 3 jours = meme groupe
    %==============================================================%
    close_age_threshold = ...
        3;


    %==============================================================%
    % Construire les groupes
    %==============================================================%
    groups = ...
        cell(0,1);


    group_counter = ...
        1;


    groups{group_counter} = ...
        1;


    for a = 2:nAges

        if ages(a) - ages(a - 1) <= close_age_threshold

            groups{group_counter}(end+1) = ...
                a;

        else

            group_counter = ...
                group_counter + 1;


            groups{group_counter} = ...
                a;
        end
    end


    %==============================================================%
    % Limites axe
    %==============================================================%
    current_ylim = ...
        ylim(ax);


    y_range = ...
        current_ylim(2) - ...
        current_ylim(1);


    if ~isfinite(y_range) || ...
            y_range <= 0

        y_range = ...
            1;
    end


    %==============================================================%
    % Position verticale des cartouches
    %==============================================================%
    label_y = ...
        current_ylim(2) - ...
        0.10 * y_range;


    %==============================================================%
    % Chaque groupe
    %==============================================================%
    for g = 1:numel(groups)

        current_indices = ...
            groups{g};


        %==========================================================%
        % Garder uniquement les ages avec donnees
        %==========================================================%
        valid_indices = ...
            [];


        for j = 1:numel(current_indices)

            a = ...
                current_indices(j);


            values = ...
                clean_numeric( ...
                    values_by_age{a});


            if ~isempty(values)

                valid_indices(end+1) = ...
                    a;
            end
        end


        if isempty(valid_indices)

            continue;
        end


        %==========================================================%
        % Centre X du groupe
        %==========================================================%
        current_ages = ...
            ages(valid_indices);


        label_x = ...
            mean(current_ages);


        %==========================================================%
        % Recuperer animal(s) de chaque age
        %==========================================================%
        animal_text_by_age = ...
            strings( ...
                numel(valid_indices), ...
                1);


        for j = 1:numel(valid_indices)

            a = ...
                valid_indices(j);


            animal_names = ...
                string( ...
                    animals_by_age{a});


            animal_names = ...
                animal_names( ...
                    strlength(animal_names) > 0);


            animal_names = ...
                unique( ...
                    animal_names, ...
                    'stable');


            if isempty(animal_names)

                animal_text_by_age(j) = ...
                    "";

            else

                animal_text_by_age(j) = ...
                    strjoin( ...
                        animal_names, ...
                        ', ');
            end
        end


        %==========================================================%
        % CAS 1 :
        % UN SEUL AGE
        %
        %   1992
        %   n = 205
        %
        % Aucun age affiche
        %==========================================================%
        if numel(valid_indices) == 1

            a = ...
                valid_indices(1);


            values = ...
                clean_numeric( ...
                    values_by_age{a});


            n_values = ...
                numel(values);


            animal_text = ...
                animal_text_by_age(1);


            if strlength(animal_text) > 0

                label_text = ...
                    sprintf( ...
                        '%s\nn = %d', ...
                        animal_text, ...
                        n_values);

            else

                label_text = ...
                    sprintf( ...
                        'n = %d', ...
                        n_values);
            end


        %==========================================================%
        % CAS 2 :
        % PLUSIEURS AGES PROCHES
        %==========================================================%
        else

            %======================================================%
            % Verifier si tous les ages ont le meme animal
            %======================================================%
            nonempty_animals = ...
                animal_text_by_age( ...
                    strlength(animal_text_by_age) > 0);


            unique_animals = ...
                unique( ...
                    nonempty_animals, ...
                    'stable');


            same_animal = ...
                numel(unique_animals) == 1;


            %======================================================%
            % Meme animal pour tous les ages
            %
            %   1992
            %   n = 2
            %   n = 4
            %   n = 22
            %
            % Pas de 1-, 2-, 3-
            %======================================================%
            if same_animal

                label_lines = ...
                    strings(0,1);


                label_lines(end+1,1) = ...
                    unique_animals(1);


                for j = 1:numel(valid_indices)

                    a = ...
                        valid_indices(j);


                    values = ...
                        clean_numeric( ...
                            values_by_age{a});


                    n_values = ...
                        numel(values);


                    label_lines(end+1,1) = ...
                        string( ...
                            sprintf( ...
                                'n = %d', ...
                                n_values));
                end


            %======================================================%
            % Plusieurs animaux
            %
            %   1- 1992   n = 2
            %   2-        n = 4
            %   3- 2470   n = 22
            %
            % Ne pas repeter le meme animal consecutivement
            %======================================================%
            else

                label_lines = ...
                    strings(0,1);


                previous_animal_text = ...
                    "";


                for j = 1:numel(valid_indices)

                    a = ...
                        valid_indices(j);


                    values = ...
                        clean_numeric( ...
                            values_by_age{a});


                    n_values = ...
                        numel(values);


                    current_animal_text = ...
                        animal_text_by_age(j);


                    %==================================================%
                    % Ne pas repeter animal si identique
                    %==================================================%
                    if current_animal_text == previous_animal_text && ...
                            strlength(current_animal_text) > 0

                        animal_display = ...
                            "";

                    else

                        animal_display = ...
                            current_animal_text;
                    end


                    %==================================================%
                    % Ligne
                    %==================================================%
                    if strlength(animal_display) > 0

                        current_text = ...
                            sprintf( ...
                                '%d- %s   n = %d', ...
                                j, ...
                                animal_display, ...
                                n_values);

                    else

                        current_text = ...
                            sprintf( ...
                                '%d-        n = %d', ...
                                j, ...
                                n_values);
                    end


                    label_lines(end+1,1) = ...
                        string( ...
                            current_text);


                    previous_animal_text = ...
                        current_animal_text;
                end
            end


            label_text = ...
                strjoin( ...
                    label_lines, ...
                    newline);
        end


        %==========================================================%
        % Cartouche
        %==========================================================%
        text( ...
            ax, ...
            label_x, ...
            label_y, ...
            label_text, ...
            'HorizontalAlignment', ...
            'center', ...
            'VerticalAlignment', ...
            'middle', ...
            'FontSize', ...
            7.5, ...
            'FontWeight', ...
            'bold', ...
            'Color', ...
            [0.10 0.10 0.10], ...
            'BackgroundColor', ...
            'w', ...
            'EdgeColor', ...
            violin_color, ...
            'LineWidth', ...
            0.8, ...
            'Margin', ...
            2, ...
            'Clipping', ...
            'on');
    end
end

