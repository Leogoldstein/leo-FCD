%==================================================================
% IQR LOCAL
%==================================================================
function q = ...
    local_iqr( ...
        x)

    x = ...
        clean_numeric( ...
            x);


    if isempty(x)

        q = ...
            NaN;

        return;
    end


    x = ...
        sort(x);


    q25 = ...
        local_percentile( ...
            x, ...
            25);


    q75 = ...
        local_percentile( ...
            x, ...
            75);


    q = ...
        q75 - q25;
end


%==================================================================
% PERCENTILE LOCAL
%==================================================================
function value = ...
    local_percentile( ...
        x, ...
        percentile)

    x = ...
        sort( ...
            x(:));


    n = ...
        numel(x);


    if n == 0

        value = ...
            NaN;

        return;
    end


    if n == 1

        value = ...
            x(1);

        return;
    end


    position = ...
        1 + ...
        (n - 1) * ...
        percentile / 100;


    lower_index = ...
        floor(position);


    upper_index = ...
        ceil(position);


    if lower_index == upper_index

        value = ...
            x(lower_index);

    else

        fraction = ...
            position - lower_index;


        value = ...
            x(lower_index) * ...
            (1 - fraction) + ...
            x(upper_index) * ...
            fraction;
    end
end


