                            get_concat_data(data, mm);

                        if ~isempty(DF_concat_mm)

                            valid_dates(end+1) = ...
                                mm; %#ok<AGROW>
                        end
                    end

                    if isempty(valid_dates)

                        fprintf( ...
                            ['Animal summary: aucun raster ' ...
                             'concaténé valide.\n']);

                    elseif numel(valid_dates) < 2

                        fprintf( ...
                            ['Animal summary: une seule date ' ...
                             'valide, figure non générée.\n']);

                    else

                        %------------------------------------------
                        % Trier les dates selon l'âge
                        %------------------------------------------
                        ages_valid = nan( ...
                            numel(valid_dates), ...
