function build_rasterplot_DF( ...
        data, ...
        gcamp_output_folders, ...
        gcamp_root_folders, ...
        animal_path, ...
        current_line, ...
        current_animal, ...
        current_dates, ...
        current_ages, ...
        sampling_rate, ...
        automatic_selection, ...
        output_folder)

    numFolders = numel(gcamp_output_folders);

    animal_file_name = strrep( ...
        char(string(current_animal)), ...
        ' ', ...
        '_');

    line_file_name = strrep( ...
        char(string(current_line)), ...
        ' ', ...
        '_');

    if isempty(strtrim(line_file_name))

        line_prefix = '';

    else

        line_prefix = ...
            [line_file_name '_'];
    end

    %==============================================================
    % Chemin de la figure globale de l'animal
    %==============================================================
    fig_save_animal = ...
        fullfile( ...
            animal_path, ...
            sprintf( ...
                '%s%s_all_dates_all_ages_concat_rasters.png', ...
                line_prefix, ...
                animal_file_name));


    %==============================================================
    % RECORDINGS
    %==============================================================
    for m = 1:numFolders

        %==========================================================
        % Vérifier le dossier GCaMP de la date
        %==========================================================
        if isempty(gcamp_output_folders{m}) || ...
                ~iscell(gcamp_output_folders{m}) || ...
                isempty(gcamp_output_folders{m}{1})

            fprintf( ...
                'Group %d: gcamp_output_folders vide, skip.\n', ...
                m);

            continue;
        end


        %==========================================================
        % Vérifier le sampling rate
        %==========================================================
        current_sampling_rate = ...
            double(sampling_rate{m}(1));

        if ~isfinite(current_sampling_rate) || ...
                current_sampling_rate <= 0

            fprintf( ...
                'Group %d: sampling rate invalide, skip.\n', ...
                m);

            continue;
        end


        nPlanes = ...
            numel(gcamp_output_folders{m});


        %==========================================================
        % Motion sampling rate
        %
        % motion_energy / speed_active sont en coordonnées
        % global-frame.
        %==========================================================
        fs_motion = ...
            current_sampling_rate * nPlanes;


        %==========================================================
        % Age
        %==========================================================
        if numel(current_ages) >= m && ...
                ~isempty(current_ages{m})

            current_age_text = ...
                char(string( ...
                    current_ages{m}));

        else

            current_age_text = ...
                sprintf( ...
                    'Age_%d', ...
                    m);
        end


        age_file_name = ...
            strrep( ...
                current_age_text, ...
                ' ', ...
                '_');


        %==========================================================
        % Date
        %==========================================================
        if numel(current_dates) >= m && ...
                ~isempty(current_dates{m})

            current_date_text = ...
                char(string( ...
                    current_dates{m}));

        else

            current_date_text = ...
                sprintf( ...
                    'Date_%d', ...
                    m);
        end


        date_file_name = ...
            strrep( ...
                current_date_text, ...
                ' ', ...
                '_');


        %==========================================================
        % Automatic-selection recording folder
        %
        % output_folder/
        %   Development|Adult/
        %     line/
        %       animal/
        %         date/
        %==========================================================
        automatic_recording_folder = '';

        if automatic_selection && ...
                ~isempty(output_folder)

            current_age_value = ...
                str2double( ...
                    regexprep( ...
                        char(string(current_age_text)), ...
                        '[^\d\.]', ...
                        ''));


            if isfinite(current_age_value) && ...
                    current_age_value <= 15

                age_output_folder = ...
                    fullfile( ...
                        output_folder, ...
                        'Development');

            else

                age_output_folder = ...
                    fullfile( ...
                        output_folder, ...
                        'Adult');
            end


            automatic_recording_folder = ...
                fullfile( ...
                    age_output_folder, ...
                    char(string(current_line)), ...
                    char(string(current_animal)), ...
                    char(string(current_date_text)));


            if exist(automatic_recording_folder, 'dir') ~= 7

                mkdir(automatic_recording_folder);
            end
        end


        %==========================================================
        % Motion branch
        %==========================================================

        %----------------------------------------------------------
        % Speed active
        %----------------------------------------------------------
        speed_active = [];

        if isfield(data, 'motion') && ...
                isstruct(data.motion) && ...
                isfield(data.motion, 'speed_active_group') && ...
                iscell(data.motion.speed_active_group) && ...
                numel(data.motion.speed_active_group) >= m && ...
                ~isempty(data.motion.speed_active_group{m})

            speed_active = ...
                data.motion.speed_active_group{m};
        end


        %----------------------------------------------------------
        % Motion energy
        %----------------------------------------------------------
        motion_energy = [];

        if isfield(data, 'motion') && ...
                isstruct(data.motion) && ...
                isfield(data.motion, 'motion_energy_group') && ...
                iscell(data.motion.motion_energy_group) && ...
                numel(data.motion.motion_energy_group) >= m && ...
                ~isempty(data.motion.motion_energy_group{m})

            motion_energy = ...
                data.motion.motion_energy_group{m};
        end


        has_motion_energy = ...
            ~isempty(motion_energy);

        line_width_trace = ...
            1.5;


        %==========================================================
        % 1) RASTERS PAR PLAN
        %
        % Sauvegarde :
        %
        % - toujours localement dans le dossier du plan
        %
        % - si nPlanes == 1 ET automatic_selection :
        %     copie également dans
        %
        %     output_folder/
        %       Development|Adult/
        %         line/
        %           animal/
        %             date/
        %
        % - si nPlanes > 1 :
        %     pas de copie automatique ici
        %     -> la summary date sera copiée plus bas
        %==========================================================
        for p = 1:nPlanes
        
            fig = [];
        
            try
        
                %--------------------------------------------------
                % Dossier du plan
                %--------------------------------------------------
                current_plane_folder = ...
                    gcamp_output_folders{m}{p};
        
        
                if isempty(current_plane_folder) || ...
                        exist(current_plane_folder, 'dir') ~= 7
        
                    fprintf( ...
                        ['Group %d plane %d: dossier de sortie ' ...
                         'invalide, skip.\n'], ...
                        m, ...
                        p-1);
        
                    continue;
                end
        
        
                %--------------------------------------------------
                % Chemin local
                %--------------------------------------------------
                raster_filename = ...
                    sprintf( ...
                        '%s%s_%s_%s_plane%d_rastermap.png', ...
                        line_prefix, ...
                        animal_file_name, ...
                        date_file_name, ...
                        age_file_name, ...
                        p-1);
        
        
                fig_save_path = ...
                    fullfile( ...
                        current_plane_folder, ...
                        raster_filename);
        
        
                %--------------------------------------------------
                % Chemin automatic_selection
                %
                % Seulement si un seul plan.
                %--------------------------------------------------
                fig_save_output_single_plane = '';
        
        
                if nPlanes == 1 && ...
                        automatic_selection && ...
                        ~isempty(automatic_recording_folder)
        
                    fig_save_output_single_plane = ...
                        fullfile( ...
                            automatic_recording_folder, ...
                            raster_filename);
                end
        
        
                %--------------------------------------------------
                % Vérifier indépendamment les destinations
                %--------------------------------------------------
                plane_raster_exists = ...
                    exist( ...
                        fig_save_path, ...
                        'file') == 2;
        
        
                output_single_plane_exists = ...
                    ~isempty(fig_save_output_single_plane) && ...
                    exist( ...
                        fig_save_output_single_plane, ...
                        'file') == 2;
        
        
                %--------------------------------------------------
                % Déterminer ce qui doit être créé
                %--------------------------------------------------
                need_local_raster = ...
                    ~plane_raster_exists;
        
        
                need_output_single_plane = ...
                    nPlanes == 1 && ...
                    automatic_selection && ...
                    ~isempty(fig_save_output_single_plane) && ...
                    ~output_single_plane_exists;
        
        
                %--------------------------------------------------
                % Ne rien recalculer seulement si toutes les
                % destinations nécessaires existent déjà
                %--------------------------------------------------
                if ~need_local_raster && ...
                        ~need_output_single_plane
        
                    fprintf( ...
                        ['Plane raster already exists in all required ' ...
                         'locations, processing skipped.\n']);
        
                    continue;
                end
        
        
                %--------------------------------------------------
                % Charger les données
                %--------------------------------------------------
                [DFp, isort_p, MAct_p] = ...
                    get_plane_data( ...
                        data, ...
                        m, ...
                        p);
        
        
                if isempty(DFp)
        
                    fprintf( ...
                        ['Group %d plane %d: DF vide, ' ...
                         'skip raster plan.\n'], ...
                        m, ...
                        p-1);
        
                    continue;
                end
        
        
                [NCell, Nz] = ...
                    size(DFp);
        
        
                if NCell == 0 || ...
                        Nz == 0
        
                    fprintf( ...
                        'Group %d plane %d: DF vide, skip.\n', ...
                        m, ...
                        p-1);
        
                    continue;
                end
        
        
                isort_p = ...
                    sanitize_isort( ...
                        isort_p, ...
                        NCell);
        
        
                MAct_p = ...
                    resize_MAct( ...
                        MAct_p, ...
                        Nz);
        
        
                prop_MAct_p = ...
                    MAct_p / ...
                    max(NCell, 1);
        
        
                total_time = ...
                    Nz / ...
                    current_sampling_rate;
        
        
                t_sec = ...
                    (0:Nz-1) / ...
                    current_sampling_rate;
        
        
                activity_segs_sec = ...
                    build_activity_segments( ...
                        speed_active, ...
                        fs_motion);
        
        
                %==================================================
                % Figure : raster + activité + motion
                %==================================================
                subplot_count = ...
                    3;
        
        
                fig = ...
                    figure( ...
                        'Color', ...
                        'w');
        
        
                set( ...
                    fig, ...
                    'Position', ...
                    get(0, 'ScreenSize'));
        
        
                %--------------------------------------------------
                % AXE 1 : Raster
                %--------------------------------------------------
                ax1 = ...
                    subplot( ...
                        subplot_count, ...
                        1, ...
                        1);
        
        
                A = ...
                    double( ...
                        DFp(isort_p, :));
        
        
                A_z = ...
                    robust_zscore_rows(A);
        
        
                imagesc( ...
                    ax1, ...
                    t_sec, ...
                    1:NCell, ...
                    A_z);
        
        
                axis( ...
                    ax1, ...
                    'tight');
        
        
                set( ...
                    ax1, ...
                    'TickLength', ...
                    [0 0], ...
                    'YDir', ...
                    'normal');
        
        
                ylabel( ...
                    ax1, ...
                    'Neurons', ...
                    'FontSize', ...
                    18);
        
        
                colormap( ...
                    ax1, ...
                    parula);
        
        
                clim( ...
                    ax1, ...
                    [0.1 2]);
        
        
                title( ...
                    ax1, ...
                    sprintf( ...
                        ['Sorted raster of GCaMP cells ' ...
                         'activity - Plane %d'], ...
                        p-1), ...
                    'FontSize', ...
                    20, ...
                    'FontWeight', ...
                    'bold');
        
        
                xlim( ...
                    ax1, ...
                    [0 total_time]);
        
        
                %--------------------------------------------------
                % AXE 2 : Proportion de cellules actives
                %--------------------------------------------------
                ax2 = ...
                    subplot( ...
                        subplot_count, ...
                        1, ...
                        2);
        
        
                plot( ...
                    ax2, ...
                    t_sec, ...
                    prop_MAct_p, ...
                    'LineWidth', ...
                    line_width_trace);
        
        
                ylabel( ...
                    ax2, ...
                    'Proportion (0-1)', ...
                    'FontSize', ...
                    18);
        
        
                title( ...
                    ax2, ...
                    sprintf( ...
                        ['Proportion of Active GCaMP Cells ' ...
                         '- Plane %d'], ...
                        p-1), ...
                    'FontSize', ...
                    20, ...
                    'FontWeight', ...
                    'bold');
        
        
                grid( ...
                    ax2, ...
                    'off');
        
        
                box( ...
                    ax2, ...
                    'off');
        
        
                xlim( ...
                    ax2, ...
                    [0 total_time]);
        
        
                plot_activity_bands( ...
                    ax2, ...
                    activity_segs_sec);
        
        
                %--------------------------------------------------
                % AXE 3 : Motion energy
                %--------------------------------------------------
                ax3 = ...
                    subplot( ...
                        subplot_count, ...
                        1, ...
                        3);
        
        
                if has_motion_energy
        
                    t_motion = ...
                        (0:numel(motion_energy)-1) / ...
                        fs_motion;
        
        
                    plot( ...
                        ax3, ...
                        t_motion, ...
                        motion_energy, ...
                        'LineWidth', ...
                        line_width_trace);
        
        
                    ylabel( ...
                        ax3, ...
                        'Motion energy', ...
                        'FontSize', ...
                        18);
        
        
                    title( ...
                        ax3, ...
                        'Motion Energy', ...
                        'FontSize', ...
                        20, ...
                        'FontWeight', ...
                        'bold');
        
        
                    plot_activity_bands( ...
                        ax3, ...
                        activity_segs_sec);
        
                else
        
                    text( ...
                        ax3, ...
                        0.5, ...
                        0.5, ...
                        'No motion energy available', ...
                        'Units', ...
                        'normalized', ...
                        'HorizontalAlignment', ...
                        'center', ...
                        'FontSize', ...
                        14);
        
        
                    ylabel( ...
                        ax3, ...
                        'Motion energy', ...
                        'FontSize', ...
                        18);
        
        
                    title( ...
                        ax3, ...
                        'Motion Energy', ...
                        'FontSize', ...
                        20, ...
                        'FontWeight', ...
                        'bold');
                end
        
        
                box( ...
                    ax3, ...
                    'off');
        
        
                grid( ...
                    ax3, ...
                    'off');
        
        
                xlabel( ...
                    ax3, ...
                    'Time (s)', ...
                    'FontSize', ...
                    18);
        
        
                xlim( ...
                    ax3, ...
                    [0 total_time]);
        
        
                %--------------------------------------------------
                % Synchroniser les axes temporels
                %--------------------------------------------------
                linkaxes( ...
                    [ax1 ax2 ax3], ...
                    'x');
        
        
                %--------------------------------------------------
                % Sauvegarde locale
                %--------------------------------------------------
                if need_local_raster
        
                    saveas( ...
                        fig, ...
                        fig_save_path);
        
        
                    fprintf( ...
                        'Raster plot saved locally:\n%s\n', ...
                        fig_save_path);
                end
        
        
                %--------------------------------------------------
                % Copie automatic_selection
                %
                % Seulement pour nPlanes == 1
                %--------------------------------------------------
                if need_output_single_plane
        
                    saveas( ...
                        fig, ...
                        fig_save_output_single_plane);
        
        
                    fprintf( ...
                        ['Automatic-selection single-plane raster ' ...
                         'saved in:\n%s\n'], ...
                        fig_save_output_single_plane);
                end
        
        
                close(fig);
        
                fig = [];
        
        
            catch ME
        
                fprintf( ...
                    '\nError for group %d plane %d: %s\n', ...
                    m, ...
                    p-1, ...
                    ME.message);
        
        
                if ~isempty(fig) && ...
                        ishghandle(fig)
        
                    close(fig);
                end
            end
        end


        %==========================================================
        % 2) RASTER CONCATÉNÉ
        %==========================================================
        if nPlanes > 1

            fig = [];

            try

                %--------------------------------------------------
                % Chemin local
                %--------------------------------------------------
                fig_save_path = ...
                    fullfile( ...
                        gcamp_root_folders{m}, ...
                        sprintf( ...
                            '%s%s_%s_%s_rastermap_concat.png', ...
                            line_prefix, ...
                            animal_file_name, ...
                            date_file_name, ...
                            age_file_name));


                if exist(fig_save_path, 'file') == 2

                    fprintf( ...
                        ['Concatenated raster already exists, ' ...
                         'all processing skipped:\n%s\n'], ...
                        fig_save_path);

                else

                    [ ...
                        DF_concat, ...
                        isort_concat, ...
                        MAct_concat ...
                    ] = ...
                        get_concat_data( ...
                            data, ...
                            m);


                    if isempty(DF_concat)

                        fprintf( ...
                            ['Group %d: DF concaténé vide, ' ...
                             'skip raster concat.\n'], ...
                            m);

                    else

                        [NCell, Nz] = ...
                            size(DF_concat);


                        if NCell == 0 || ...
                                Nz == 0

                            fprintf( ...
                                ['Group %d: DF concaténé vide, ' ...
                                 'skip raster concat.\n'], ...
                                m);

                        else

                            isort_concat = ...
                                sanitize_isort( ...
                                    isort_concat, ...
                                    NCell);


                            MAct_concat = ...
                                resize_MAct( ...
                                    MAct_concat, ...
                                    Nz);


                            prop_MAct = ...
                                MAct_concat / ...
                                max(NCell, 1);


                            total_time = ...
                                Nz / ...
                                current_sampling_rate;


                            t_sec = ...
                                (0:Nz-1) / ...
                                current_sampling_rate;


                            activity_segs_sec = ...
                                build_activity_segments( ...
                                    speed_active, ...
                                    fs_motion);


                            subplot_count = ...
                                2 + ...
                                has_motion_energy;


                            fig = ...
                                figure( ...
                                    'Color', ...
                                    'w');


                            set( ...
                                fig, ...
                                'Position', ...
                                get(0, 'ScreenSize'));


                            %--------------------------------------
                            % Raster concaténé
                            %--------------------------------------
                            ax1 = ...
                                subplot( ...
                                    subplot_count, ...
                                    1, ...
                                    1);


                            A = ...
                                double( ...
                                    DF_concat( ...
                                        isort_concat, ...
                                        :));


                            A_z = ...
                                robust_zscore_rows(A);


                            imagesc( ...
                                ax1, ...
                                t_sec, ...
                                1:NCell, ...
                                A_z);


                            axis( ...
                                ax1, ...
                                'tight');


                            set( ...
                                ax1, ...
                                'TickLength', ...
                                [0 0], ...
                                'YDir', ...
                                'normal');


                            xlabel( ...
                                ax1, ...
                                'Time (s)');


                            ylabel( ...
                                ax1, ...
                                'Neurons');


                            colormap( ...
                                ax1, ...
                                parula);


                            clim( ...
                                ax1, ...
                                [0.1 2]);


                            title( ...
                                ax1, ...
                                'Raster plot concaténé (z-score)');


                            xlim( ...
                                ax1, ...
                                [0 total_time]);


                            %--------------------------------------
                            % Activité concaténée
                            %--------------------------------------
                            ax2 = ...
                                subplot( ...
                                    subplot_count, ...
                                    1, ...
                                    2);


                            plot( ...
                                ax2, ...
                                t_sec, ...
                                prop_MAct, ...
                                'LineWidth', ...
                                line_width_trace);


                            ylabel( ...
                                ax2, ...
                                'Prop. Active Cells');


                            title( ...
                                ax2, ...
                                ['Proportion of Active Cells ' ...
                                 '- concaténé']);


                            grid( ...
                                ax2, ...
                                'off');


                            box( ...
                                ax2, ...
                                'off');


                            xlim( ...
                                ax2, ...
                                [0 total_time]);


                            plot_activity_bands( ...
                                ax2, ...
                                activity_segs_sec);


                            axes_list = ...
                                [ax1 ax2];


                            %--------------------------------------
                            % Motion energy
                            %--------------------------------------
                            if has_motion_energy

                                ax3 = ...
                                    subplot( ...
                                        subplot_count, ...
                                        1, ...
                                        3);


                                t_motion = ...
                                    (0:numel(motion_energy)-1) / ...
                                    fs_motion;


                                plot( ...
                                    ax3, ...
                                    t_motion, ...
                                    motion_energy, ...
                                    'LineWidth', ...
                                    line_width_trace);


                                xlabel( ...
                                    ax3, ...
                                    'Time (s)');


                                ylabel( ...
                                    ax3, ...
                                    'Motion energy');


                                title( ...
                                    ax3, ...
                                    'Motion Energy');


                                box( ...
                                    ax3, ...
                                    'off');


                                grid( ...
                                    ax3, ...
                                    'off');


                                xlim( ...
                                    ax3, ...
                                    [0 total_time]);


                                plot_activity_bands( ...
                                    ax3, ...
                                    activity_segs_sec);


                                axes_list = ...
                                    [axes_list ax3]; %#ok<AGROW>
                            end


                            linkaxes( ...
                                axes_list, ...
                                'x');


                            saveas( ...
                                fig, ...
                                fig_save_path);


                            fprintf( ...
                                ['Concatenated raster plot ' ...
                                 'saved in:\n%s\n'], ...
                                fig_save_path);


                            close(fig);

                            fig = [];
                        end
                    end
                end


            catch ME

                fprintf( ...
                    ['\nError for concatenated raster ' ...
                     'group %d: %s\n'], ...
                    m, ...
                    ME.message);


                if ~isempty(fig) && ...
                        ishghandle(fig)

                    close(fig);
                end
            end


            %======================================================
            % 3) SUMMARY DATE : PLANS + CONCATÉNÉ + MOTION
            %
            % Sauvegarde :
            %   - locale dans gcamp_root_folders{m}
            %   - copie automatic_selection dans :
            %
            % output_folder/
            %   Development|Adult/
            %     line/
            %       animal/
            %         date/
            %======================================================
            fig = [];

            try

                %--------------------------------------------------
                % Chemin local
                %--------------------------------------------------
                summary_filename = ...
                    sprintf( ...
                        '%s%s_%s_%s_rastermap_summary.png', ...
                        line_prefix, ...
                        animal_file_name, ...
                        date_file_name, ...
                        age_file_name);


                fig_save_summary = ...
                    fullfile( ...
                        gcamp_root_folders{m}, ...
                        summary_filename);


                %--------------------------------------------------
                % Chemin automatic_selection
                %--------------------------------------------------
                fig_save_summary_output = '';

                if automatic_selection && ...
                        ~isempty(automatic_recording_folder)

                    fig_save_summary_output = ...
                        fullfile( ...
                            automatic_recording_folder, ...
                            summary_filename);
                end


                %--------------------------------------------------
                % Vérifier indépendamment les deux destinations
                %--------------------------------------------------
                summary_local_exists = ...
                    exist( ...
                        fig_save_summary, ...
                        'file') == 2;


                summary_output_exists = ...
                    ~isempty(fig_save_summary_output) && ...
                    exist( ...
                        fig_save_summary_output, ...
                        'file') == 2;


                need_local_summary = ...
                    ~summary_local_exists;


                need_output_summary = ...
                    automatic_selection && ...
                    ~isempty(fig_save_summary_output) && ...
                    ~summary_output_exists;


                %--------------------------------------------------
                % Skip seulement si tout existe
                %--------------------------------------------------
                if ~need_local_summary && ...
                        ~need_output_summary

                    fprintf( ...
                        ['Summary raster already exists in all ' ...
                         'required locations, processing skipped.\n']);

                else

                    %--------------------------------------------------
                    % Plans valides
                    %--------------------------------------------------
                    valid_plane_idx = [];

                    for p = 1:nPlanes

                        [DFp, ~, ~] = ...
                            get_plane_data( ...
                                data, ...
                                m, ...
                                p);


                        if ~isempty(DFp)

                            valid_plane_idx(end+1) = ...
                                p; %#ok<AGROW>
                        end
                    end


                    %--------------------------------------------------
                    % Concaténé
                    %--------------------------------------------------
                    [ ...
                        DF_concat, ...
                        isort_concat, ...
                        MAct_concat ...
                    ] = ...
                        get_concat_data( ...
                            data, ...
                            m);


                    has_concat = ...
                        ~isempty(DF_concat);


                    %--------------------------------------------------
                    % Motion
                    %
                    % Exactement la même logique que pour les rasters
                    % individuels.
                    %--------------------------------------------------
                    has_summary_motion = ...
                        ~isempty(motion_energy);


                    if isempty(valid_plane_idx) && ...
                            ~has_concat

                        fprintf( ...
                            ['Group %d: no valid planes for ' ...
                             'summary figure.\n'], ...
                            m);

                    else

                        nValidPlanes = ...
                            numel(valid_plane_idx);


                        nRows_main = ...
                            nValidPlanes + ...
                            double(has_concat);


                        nRows = ...
                            nRows_main + ...
                            double(has_summary_motion);


                        nCols = ...
                            2;


                        fig = ...
                            figure( ...
                                'Color', ...
                                'w');


                        set( ...
                            fig, ...
                            'Position', ...
                            get(0, 'ScreenSize'));


                        row_counter = ...
                            0;


                        %------------------------------------------
                        % Plans individuels
                        %------------------------------------------
