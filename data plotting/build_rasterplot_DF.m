                                continue;
                            end

                            if numel(current_sampling_rate) < mm || ...
                                    isempty( ...
                                        current_sampling_rate{mm})

                                continue;
                            end

                            current_sampling_rate_mm = double( ...
                                current_sampling_rate{mm}(1));

                            if ~isfinite(current_sampling_rate_mm) || ...
                                    current_sampling_rate_mm <= 0

                                continue;
                            end

                            [NCell, Nz] = ...
                                size(DF_concat);

                            if NCell == 0 || Nz == 0
                                continue;
                            end

                            isort_concat = ...
                                sanitize_isort( ...
                                    isort_concat, ...
                                    NCell);

                            total_time = ...
                                Nz / current_sampling_rate_mm;

                            t_sec = ...
                                (0:Nz-1) / ...
                                current_sampling_rate_mm;

                            ax = subplot( ...
                                nRows, ...
                                1, ...
                                idx);

                            A = double( ...
                                DF_concat( ...
                                    isort_concat, :));

                            A_z = ...
                                robust_zscore_rows(A);

                            imagesc( ...
                                ax, ...
                                t_sec, ...
                                1:NCell, ...
                                A_z);

                            axis(ax, 'tight');

                            set( ...
                                ax, ...
                                'YDir', 'normal', ...
                                'TickLength', [0 0]);

                            colormap(ax, parula);
                            clim(ax, [0 2]);

                            xlim( ...
                                ax, ...
                                [0 total_time]);

                            ylabel( ...
                                ax, ...
                                sprintf( ...
                                    '%d neurons', ...
                                    NCell));

                            %--------------------------------------
                            % Date
                            %--------------------------------------
                            if numel(current_dates) >= mm && ...
                                    ~isempty(current_dates{mm})
                            
                                date_text = char(string( ...
                                    current_dates{mm}));
                            
                            else
                            
                                date_text = sprintf( ...
                                    'Date_%d', ...
                                    mm);
                            end

                            %--------------------------------------
                            % Âge
                            %--------------------------------------
                            age_text_mm = ...
                                sprintf('Age_%d', mm);

                            if numel(current_ages) >= mm && ...
                                    ~isempty( ...
                                        current_ages{mm})

                                age_text_mm = char(string( ...
                                    current_ages{mm}));
                            end

                            title( ...
                                ax, ...
                                sprintf( ...
                                    '%s - %s', ...
                                    date_text, ...
                                    age_text_mm), ...
                                'Interpreter', ...
                                'none');

                            if idx == nRows

                                xlabel( ...
                                    ax, ...
                                    'Time (s)');
                            end
                        end

                        sgtitle( ...
                            sprintf( ...
                                '%s - all dates concat rasters', ...
                                strrep( ...
                                    current_animal, ...
                                    '_', ...
                                    '\_')));

                        saveas( ...
                            fig, ...
                            fig_save_animal);

                        fprintf( ...
                            ['Animal concat raster summary ' ...
                             'saved in:\n%s\n'], ...
                            fig_save_animal);

                        close(fig);
                        fig = [];
                    end
                end

            catch ME

                fprintf( ...
                    ['\nError for animal concat raster ' ...
                     'summary: %s\n'], ...
                    ME.message);

                if ~isempty(fig) && ishghandle(fig)
                    close(fig);
                end
            end
        end
    end
end

