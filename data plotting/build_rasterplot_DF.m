function isort = ...
        sanitize_isort( ...
            isort, ...
            NCell)

    if isempty(isort)

        isort = ...
            (1:NCell)';

        return;
    end


    isort = ...
        isort(:);


    bad = ...
        isort < 1 | ...
        isort > NCell | ...
        isnan(isort);


    isort(bad) = [];


    if numel(isort) ~= NCell || ...
            numel(unique(isort)) ~= numel(isort)

        isort = ...
            (1:NCell)';
    end
end


function Z = ...
        robust_zscore_rows(A)

    Z = ...
        nan(size(A));


    for i = 1:size(A,1)

        x = ...
            A(i,:);


        mu = ...
            median( ...
                x, ...
                'omitnan');


        sig = ...
            1.4826 * ...
            mad( ...
                x, ...
                1);


        if isfinite(sig) && ...
                sig > eps

            Z(i,:) = ...
                (x - mu) / ...
                sig;

        else

            Z(i,:) = ...
                x - mu;
        end
    end
end


function apply_percentile_clim( ...
        ax, ...
        A)

    v = ...
        A(isfinite(A));


    if isempty(v)
        return;
    end


    lo = ...
        prctile( ...
            v, ...
            2);


    hi = ...
        prctile( ...
            v, ...
            98);


    if isfinite(lo) && ...
            isfinite(hi) && ...
            hi > lo

        clim( ...
            ax, ...
            [lo hi]);
    end
end


