function Xcat = ...
        concat_planes( ...
            branch, ...
            m, ...
            fieldName)

    Xcat = [];


    if ~isfield(branch, fieldName) || ...
            numel(branch.(fieldName)) < m || ...
            isempty(branch.(fieldName){m})

        return;
    end


    Xcell = ...
        branch.(fieldName){m};


    if isempty(Xcell)
        return;
    end


    valid = ...
        ~cellfun( ...
            @isempty, ...
            Xcell);


    Xcell = ...
        Xcell(valid);


    if isempty(Xcell)
        return;
    end


    nCols = ...
        cellfun( ...
            @(x) size(x, 2), ...
            Xcell);


    Nz = ...
        min(nCols);


    for k = 1:numel(Xcell)

        Xcell{k} = ...
            Xcell{k}(:,1:Nz);
    end


    Xcat = ...
        cat( ...
            1, ...
            Xcell{:});
end


function MAct_sum = ...
        merge_MAct_planes( ...
            branch, ...
            m, ...
            fieldName)

    MAct_sum = [];


    if ~isfield(branch, fieldName) || ...
            numel(branch.(fieldName)) < m || ...
            isempty(branch.(fieldName){m})

        return;
    end


    MAct_cell = ...
        branch.(fieldName){m};


    if isempty(MAct_cell)
        return;
    end


    valid = ...
        ~cellfun( ...
            @isempty, ...
            MAct_cell);


    MAct_cell = ...
        MAct_cell(valid);


    if isempty(MAct_cell)
        return;
    end


    lengths = ...
        cellfun( ...
            @numel, ...
            MAct_cell);


    Nz = ...
        min(lengths);


    MAct_sum = ...
        zeros( ...
            1, ...
            Nz);


    for p = 1:numel(MAct_cell)

        M_p = ...
            MAct_cell{p};


        M_p = ...
            resize_MAct( ...
                M_p, ...
                Nz);


        MAct_sum = ...
            MAct_sum + ...
            M_p;
    end
end


function [ ...
        isort1_out, ...
        isort2_out, ...
        Sm_out ...
    ] = ...
    compute_sort_outputs_from_df( ...
        DF_in, ...
        ops_in)

    isort1_out = [];
    isort2_out = [];
    Sm_out = [];


    if isempty(DF_in)
        return;
    end


    try

        [ ...
            isort1_out, ...
            isort2_out, ...
            Sm_out ...
        ] = ...
            raster_processing( ...
                double(DF_in), ...
                ops_in);


    catch ME

        warning( ...
            'compute_sort_outputs_from_df:raster_processing', ...
            'raster_processing failed (%s).', ...
