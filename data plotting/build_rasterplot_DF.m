function segs_sec = ...
        build_activity_segments( ...
            speed_active, ...
            fs_motion)

    segs_sec = [];


    if isempty(speed_active)
        return;
    end


    if isempty(fs_motion) || ...
            ~isfinite(fs_motion) || ...
            fs_motion <= 0

        return;
    end


    L = ...
        numel(speed_active);


    t_speed = ...
        (0:L-1) / ...
        fs_motion;


    segs_sec = ...
        mask_to_segments_time( ...
            t_speed, ...
            speed_active > 0);
end


function segs_sec = ...
        mask_to_segments_time( ...
            t, ...
            mask)

    mask = ...
        mask(:)';


    t = ...
        t(:)';


    if isempty(mask)

        segs_sec = [];

        return;
    end


    d = ...
        diff( ...
            [ ...
                false, ...
                mask, ...
                false ...
            ]);


    starts = ...
        find(d == 1);


    ends = ...
        find(d == -1) - 1;


    segs_sec = ...
        [ ...
            t(starts(:))', ...
            t(ends(:))' ...
        ];
end


