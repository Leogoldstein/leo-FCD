                                    current_age_text, ...
                                    '_', ...
                                    '\_')));

                        saveas( ...
                            fig, ...
                            fig_save_summary);

                        fprintf( ...
                            ['Summary raster plot ' ...
                             'saved in:\n%s\n'], ...
                            fig_save_summary);

                        close(fig);
                        fig = [];
                    end
                end

            catch ME

                fprintf( ...
                    ['\nError for summary raster ' ...
                     'group %d: %s\n'], ...
                    m, ME.message);

                if ~isempty(fig) && ishghandle(fig)
                    close(fig);
                end
            end

        else

            fprintf( ...
                ['Summary root folder skipped: ' ...
                 'nPlanes = %d <= 1.\n'], ...
                nPlanes);
        end

        %==========================================================
        % 4) SUMMARY ANIMAL : TOUS LES RASTERS CONCATÉNÉS
        %==========================================================
        if m == numFolders

            fig = [];

            try
                %--------------------------------------------------
                % Test avant tout appel à get_concat_data
                %--------------------------------------------------
                if exist(fig_save_animal, 'file') == 2

