                                        'Concat\nNeurons'));

                                title( ...
                                    ax_r, ...
                                    'Raster concaténé');

                                % Activité concaténée
                                ax_a = subplot( ...
                                    nRows, ...
                                    nCols, ...
                                    (row_counter-1)*nCols + 2);

                                plot( ...
                                    ax_a, ...
                                    t_sec_c, ...
                                    prop_MAct_c, ...
                                    'LineWidth', ...
                                    line_width_trace);

                                box(ax_a, 'off');
                                grid(ax_a, 'off');

                                xlim( ...
                                    ax_a, ...
                                    [0 total_time_c]);

                                ylabel( ...
                                    ax_a, ...
                                    'Prop. active');

                                title( ...
                                    ax_a, ...
                                    'Active cells concaténé');

                                plot_activity_bands( ...
                                    ax_a, ...
                                    activity_segs_sec_c);
                            end
                        end

                        %------------------------------------------
                        % Motion
                        %------------------------------------------
                        if has_summary_motion

                            row_counter = row_counter + 1;

                            if has_concat

                                total_time_motion = ...
                                    size(DF_concat, 2) / ...
                                    current_sampling_rate;

                            elseif ~isempty(valid_plane_idx)

                                p0 = valid_plane_idx(1);

                                [DF0, ~, ~] = ...
                                    get_plane_data( ...
                                        data, ...
                                        m, ...
                                        p0);

                                total_time_motion = ...
                                    size(DF0, 2) / ...
                                    current_sampling_rate;

                            else

                                total_time_motion = ...
                                    numel(motion_energy);
                            end

                            t_motion = linspace( ...
                                0, ...
                                total_time_motion, ...
                                numel(motion_energy));

                            activity_segs_sec_m = ...
                                build_activity_segments( ...
                                    speed_active, ...
                                    total_time_motion);

