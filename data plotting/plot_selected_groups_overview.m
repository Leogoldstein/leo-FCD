%% ========================================================================
% Position Z
% =========================================================================
function z = ...
    get_position_z_for_plane( ...
        metadata, ...
        branch_name, ...
        recording_index, ...
        plane_index)

    z = ...
        NaN;


    if ~isfield(metadata, branch_name)
        return;
    end


    branch = ...
        metadata.(branch_name);


    if ~isfield(branch, 'PositionZ') || ...
            isempty(branch.PositionZ)

        return;
    end


    if numel(branch.PositionZ) < recording_index
        return;
    end


    raw = ...
        branch.PositionZ{recording_index};


    z = ...
        extract_position_z_plane_local( ...
            raw, ...
            plane_index);
end


function z = ...
    extract_position_z_plane_local( ...
        raw, ...
        plane_index)

    z = ...
        NaN;


    if isempty(raw)
        return;
    end


    if iscell(raw)

        if numel(raw) >= plane_index

            raw = ...
                raw{plane_index};

        elseif isscalar(raw)

            raw = ...
                raw{1};

        else

            return;
        end
    end


    if isnumeric(raw) || ...
            islogical(raw)

        values = ...
            double(raw(:));


        values = ...
            values(isfinite(values));


        if numel(values) >= plane_index

            z = ...
                values(plane_index);

        elseif numel(values) == 1 && ...
                plane_index == 1

            z = ...
                values(1);
        end

        return;
    end


    tokens = ...
        regexp( ...
            char(string(raw)), ...
            '[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?', ...
            'match');


    values = ...
        str2double(tokens);


    values = ...
        values(isfinite(values));


    if numel(values) >= plane_index

        z = ...
            values(plane_index);
    end
end


