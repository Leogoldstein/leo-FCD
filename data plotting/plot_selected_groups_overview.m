        output_folder, ...
        filename, ...
        maximize_figure)

    if isempty(fig) || ...
            ~ishghandle(fig)

        return;
    end


    if exist(output_folder, 'dir') ~= 7

        mkdir( ...
            output_folder);
    end


    if maximize_figure

        set( ...
            fig, ...
            'Units', ...
            'normalized', ...
            'OuterPosition', ...
            [0 0 1 1]);
    end


    drawnow;


    output_path = ...
        fullfile( ...
            output_folder, ...
            filename);


    try

        exportgraphics( ...
            fig, ...
            output_path, ...
            'Resolution', ...
            300);

    catch ME

        warning( ...
            'exportgraphics failed (%s). saveas used instead.', ...
            ME.message);


        saveas( ...
            fig, ...
            output_path);
    end


    fprintf( ...
        'Figure saved/updated:\n%s\n', ...
        output_path);
end