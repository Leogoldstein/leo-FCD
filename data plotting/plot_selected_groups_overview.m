function [figs, day_table, animal_table, legend_table] = ...
    plot_selected_groups_overview( ...
        selected_groups, ...
        include_electroporated_cells, ...
        automatic_selection, ...
        output_folders_type)

% PLOT_SELECTED_GROUPS_OVERVIEW
%
% Crée et sauvegarde :
%
%   figs.overview : âges enregistrés et nombre moyen de cellules par animal
%   figs.layers   : profondeur des plans et couches corticales
%   figs.legend   : légende commune des couleurs attribuées aux animaux
%
% Structure attendue :
%
% selected_groups.(type)(k).line
% selected_groups.(type)(k).animal
% selected_groups.(type)(k).dates
% selected_groups.(type)(k).ages
% selected_groups.(type)(k).metadata
% selected_groups.(type)(k).data
%
% output_folders_type :
%
%   output_folders_type{t}
%
% avec une entrée par type dans le même ordre que :
%
%   type_names = fieldnames(selected_groups)
%
% Exemple :
%
%   D:\Imaging\FCD\Summary plots\Pre-selection electroporated cells\Adult
%
% Les figures et tables sont systématiquement recalculées et écrasées.


    %==============================================================%
    % Initialize outputs
    %==============================================================%
    figs = struct( ...
        'overview', struct(), ...
        'layers',   struct(), ...
        'legend',   []);

    day_table = ...
        initialize_day_table();

    animal_table = ...
        initialize_animal_table();

    legend_table = ...
        initialize_legend_table();


    %==============================================================%
    % Input checks
    %==============================================================%
    if nargin < 1 || isempty(selected_groups)

        error( ...
            'selected_groups is empty.');
    end


    if nargin < 2 || ...
            isempty(include_electroporated_cells)

        include_electroporated_cells = ...
            false;
    end


    if nargin < 3 || ...
            isempty(automatic_selection)

        automatic_selection = ...
            false;
    end


    type_names = ...
        fieldnames(selected_groups);


    if nargin < 4 || ...
            isempty(output_folders_type)

        error( ...
            'output_folders_type must be provided.');
    end


    if ~iscell(output_folders_type)

        output_folders_type = ...
            {output_folders_type};
    end


    if numel(output_folders_type) ~= ...
            numel(type_names)

        error( ...
            ['output_folders_type must contain ', ...
             'one output folder per type.']);
    end


    %==============================================================%
    % Vérifier qu'au moins un type est en sélection automatique
    %==============================================================%
    automatic_fields = ...
        fieldnames(automatic_selection);


    has_automatic_selection = ...
        false;


    for i = 1:numel(automatic_fields)

        if automatic_selection.(automatic_fields{i})

            has_automatic_selection = ...
                true;

            break;
        end
    end


    if ~has_automatic_selection

        fprintf( ...
            '[OVERVIEW] Manual selection: overview plots skipped.\n');

        return;
    end


    %==============================================================%
    % Extract data
    %==============================================================%
    for t = 1:numel(type_names)

        current_type = ...
            type_names{t};


        %==========================================================%
        % Seulement les types en sélection automatique
        %==========================================================%
        if ~isfield( ...
                automatic_selection, ...
                current_type)

            warning( ...
                'Missing automatic_selection for type %s.', ...
                current_type);

            continue;
        end


        current_automatic_selection = ...
            automatic_selection.(current_type);


        if ~current_automatic_selection

            fprintf( ...
                '[OVERVIEW] %s: manual selection, skipped.\n', ...
                current_type);

            continue;
        end


        current_groups = ...
            selected_groups.(current_type);


        if isempty(current_groups)

            continue;
        end


        for g = 1:numel(current_groups)

            current_group = ...
                current_groups(g);


            %======================================================%
            % Structure directe
            %======================================================%
            current_line = ...
                current_group.line;


            current_animal = ...
                current_group.animal;


            current_dates = ...
                current_group.dates;


            current_ages = ...
                current_group.ages;


            metadata = ...
                current_group.metadata;


            %======================================================%
            % Data
            %======================================================%
            if ~isfield(current_group, 'data') || ...
                    isempty(current_group.data) || ...
                    ~isstruct(current_group.data)

                fprintf( ...
                    '[OVERVIEW] No data for %s - %s\n', ...
                    current_type, ...
                    string(current_animal));

                continue;
            end


            data = ...
                current_group.data;


            %======================================================%
            % GCaMP
            %======================================================%
            day_table = ...
                extract_branch_counts( ...
                    day_table, ...
                    current_type, ...
                    current_line, ...
                    current_animal, ...
                    current_ages, ...
                    current_dates, ...
                    metadata, ...
                    data, ...
                    'gcamp_plane');


            %======================================================%
            % Electroporated
            %======================================================%
            if include_electroporated_cells

                day_table = ...
                    extract_branch_counts( ...
                        day_table, ...
                        current_type, ...
                        current_line, ...
                        current_animal, ...
                        current_ages, ...
                        current_dates, ...
                        metadata, ...
                        data, ...
                        'electroporated_plane');
            end
        end
    end


    %==============================================================%
    % Check extracted data
    %==============================================================%
    if isempty(day_table)

        warning( ...
            'No valid cell counts were found in selected_groups.');

        return;
    end


    %==============================================================%
    % Summaries and shared legend
    %==============================================================%
    animal_table = ...
        build_animal_summary( ...
            day_table);


    legend_table = ...
        build_animal_legend_table( ...
            day_table);


    %==============================================================%
    % Types réellement présents
    %==============================================================%
    plotted_types = ...
        unique( ...
            string(day_table.Type), ...
            'stable');


    plotted_types = ...
        plotted_types( ...
            strlength(plotted_types) > 0);


    if isempty(plotted_types)

        warning( ...
            'No valid experimental type was found in day_table.');

        return;
    end


    shared_prefix = ...
        char( ...
            strjoin( ...
                plotted_types, ...
                '_'));


    %==============================================================%
    % Overview + layers par type
    %==============================================================%
    for t = 1:numel(plotted_types)

        current_type = ...
            plotted_types(t);


        current_field = ...
            matlab.lang.makeValidName( ...
                char(current_type));


        %----------------------------------------------------------%
        % Retrouver l'index du type dans type_names
        %
        % Nécessaire car plotted_types peut être un sous-ensemble
        % de type_names.
        %----------------------------------------------------------%
        type_index = ...
            find( ...
                strcmpi( ...
                    string(type_names), ...
                    current_type), ...
                1, ...
                'first');


        if isempty(type_index)

            warning( ...
                'No type index found for %s.', ...
                char(current_type));

            continue;
        end


        %----------------------------------------------------------%
        % Output folder du type courant
        %----------------------------------------------------------%
        output_folder = ...
            output_folders_type{type_index};


        if isempty(output_folder)

            warning( ...
                'Empty output folder for type %s.', ...
                char(current_type));

            continue;
        end


        if exist(output_folder, 'dir') ~= 7

            mkdir( ...
                output_folder);
        end


        %----------------------------------------------------------%
        % Tables du type courant
        %----------------------------------------------------------%
        current_day_table = ...
            day_table( ...
                strcmpi( ...
                    string(day_table.Type), ...
                    current_type), ...
                :);


        current_animal_table = ...
            animal_table( ...
                strcmpi( ...
                    string(animal_table.Type), ...
                    current_type), ...
                :);


        %----------------------------------------------------------%
        % File names
        %----------------------------------------------------------%
        overview_filename = ...
            sprintf( ...
                '%s_overview.png', ...
                char(current_type));


        layers_filename = ...
            sprintf( ...
                '%s_layers.png', ...
                char(current_type));


        %==========================================================%
        % Overview
        %==========================================================%
        figs.overview.(current_field) = ...
            plot_combined_overview( ...
                current_day_table, ...
                current_animal_table, ...
                legend_table, ...
                include_electroporated_cells, ...
                current_type);


        save_overview_figure( ...
            figs.overview.(current_field), ...
            output_folder, ...
            overview_filename, ...
            true);


        %==========================================================%
        % Layers
        %==========================================================%
        figs.layers.(current_field) = ...
            plot_selected_groups_layers( ...
                current_day_table, ...
                legend_table, ...
                current_type);


        save_overview_figure( ...
            figs.layers.(current_field), ...
            output_folder, ...
            layers_filename, ...
            true);
    end


    %==============================================================%
    % Shared legend
    %==============================================================%
    legend_filename = ...
        sprintf( ...
            '%s_legend.png', ...
            shared_prefix);


    legend_table_filename = ...
        sprintf( ...
            '%s_legend_table.csv', ...
            shared_prefix);


    %==============================================================%
    % Utiliser le premier output folder valide
    %==============================================================%
    shared_output_folder = ...
        '';


    for t = 1:numel(output_folders_type)

        if ~isempty(output_folders_type{t})

            shared_output_folder = ...
                output_folders_type{t};

            break;
        end
    end


    if isempty(shared_output_folder)

        warning( ...
            'No valid output folder found for shared legend.');

        return;
    end


    if exist(shared_output_folder, 'dir') ~= 7

        mkdir( ...
            shared_output_folder);
    end


    %==============================================================%
    % Shared legend figure
    %==============================================================%
    figs.legend = ...
        plot_selected_groups_legend( ...
            legend_table);


    save_overview_figure( ...
        figs.legend, ...
        shared_output_folder, ...
        legend_filename, ...
        false);


    %==============================================================%
    % Shared legend table
    %==============================================================%
    legend_table_path = ...
        fullfile( ...
            shared_output_folder, ...
            legend_table_filename);


    writetable( ...
        legend_table, ...
        legend_table_path);


    fprintf( ...
        'Legend table saved/updated:\n%s\n', ...
        legend_table_path);


    close all
end


%% ========================================================================
% Extract cell counts for one branch
% =========================================================================
function day_table = ...
    extract_branch_counts( ...
        day_table, ...
        current_type, ...
        current_line, ...
        current_animal, ...
        current_ages, ...
        current_dates, ...
        metadata, ...
        data, ...
        branch_name)

    [planes_by_recording, source_field] = ...
        get_branch_planes( ...
            data, ...
            branch_name);


    if isempty(planes_by_recording)

        fprintf( ...
            '[OVERVIEW] No %s data for %s - %s\n', ...
            branch_name, ...
            current_type, ...
            string(current_animal));

        return;
    end


    n_recordings = ...
        numel(planes_by_recording);


    for m = 1:n_recordings

        current_planes = ...
            planes_by_recording{m};


        if isempty(current_planes)
            continue;
        end


        if ~iscell(current_planes)

            current_planes = ...
                {current_planes};
        end


        %==========================================================%
        % Age et date directement indexés par recording
        %==========================================================%
        if m > numel(current_ages) || ...
                m > numel(current_dates)

            warning( ...
                ['Missing age/date for %s - %s - ', ...
                 'recording %d. Skipping.'], ...
                current_type, ...
                string(current_animal), ...
                m);

            continue;
        end


        age_label = ...
            string( ...
                current_ages{m});


        age_number = ...
            extract_age_number_local( ...
                age_label);


        date_name = ...
            string( ...
                current_dates{m});


        %==========================================================%
        % Plans
        %==========================================================%
        n_planes = ...
            numel(current_planes);


        cells_by_plane = ...
            nan(1, n_planes);


        position_z_by_plane = ...
            nan(1, n_planes);


        for p = 1:n_planes

            current_data = ...
                current_planes{p};


            n_cells = ...
                count_cells_in_plane( ...
                    current_data);


            if isfinite(n_cells)

                cells_by_plane(p) = ...
                    n_cells;
            end


            position_z_by_plane(p) = ...
                get_position_z_for_plane( ...
                    metadata, ...
                    branch_name, ...
                    m, ...
                    p);
        end


        valid_planes = ...
            isfinite(cells_by_plane);


        if ~any(valid_planes)
            continue;
        end


        total_cells_day = ...
            sum( ...
                cells_by_plane(valid_planes), ...
                'omitnan');


        %==========================================================%
        % Une ligne par plan
        %==========================================================%
        for p = 1:n_planes

            if ~isfinite(cells_by_plane(p))
                continue;
            end


            new_row = ...
                table( ...
                    string(current_type), ...
                    string(current_line), ...
                    string(current_animal), ...
                    string(age_label), ...
                    double(age_number), ...
                    string(date_name), ...
                    double(m), ...
                    string(branch_name), ...
                    string(source_field), ...
                    double(p), ...
                    double(position_z_by_plane(p)), ...
                    double(cells_by_plane(p)), ...
                    double(total_cells_day), ...
                    'VariableNames', { ...
                        'Type', ...
                        'Line', ...
                        'Animal', ...
                        'Age', ...
                        'AgeNumber', ...
                        'Date', ...
                        'RecordingIndex', ...
                        'Branch', ...
                        'SourceField', ...
                        'Plane', ...
                        'PositionZ_um', ...
                        'CellsInPlane', ...
                        'TotalCellsDay'});


            day_table = ...
                [ ...
                    day_table; ...
                    new_row ...
                ]; %#ok<AGROW>
        end
    end
end


%% ========================================================================
% Find cellular field for branch
% =========================================================================
function [planes_by_recording, source_field] = ...
    get_branch_planes( ...
        data, ...
        branch_name)

    planes_by_recording = ...
        {};


    source_field = ...
        "";


    if ~isfield(data, branch_name) || ...
            ~isstruct(data.(branch_name))

        return;
    end


    branch = ...
        data.(branch_name);


    switch branch_name

        case 'gcamp_plane'

            candidate_fields = { ...
                'Raster_gcamp_by_plane', ...
                'DF_gcamp_by_plane', ...
                'F_gcamp_by_plane', ...
                'DFF0_gcamp_by_plane'};


        case 'electroporated_plane'

            candidate_fields = { ...
                'Raster_electroporated_by_plane', ...
                'DF_electroporated_by_plane', ...
                'F_electroporated_by_plane', ...
                'DFF0_electroporated_by_plane'};


        otherwise

            candidate_fields = {};
    end


    for f = 1:numel(candidate_fields)

        current_field = ...
            candidate_fields{f};


        if ~isfield(branch, current_field)
            continue;
        end


        current_value = ...
            branch.(current_field);


        if isempty(current_value)
            continue;
        end


        if ~iscell(current_value)

            current_value = ...
                {current_value};
        end


        if contains_nonempty_recording(current_value)

            planes_by_recording = ...
                current_value;


            source_field = ...
                string(current_field);

            return;
        end
    end
end


function tf = ...
    contains_nonempty_recording(values)

    tf = ...
        false;


    for m = 1:numel(values)

        current_value = ...
            values{m};


        if isempty(current_value)
            continue;
        end


        if iscell(current_value)

            for p = 1:numel(current_value)

                if ~isempty(current_value{p})

                    tf = ...
                        true;

                    return;
                end
            end

        else

            tf = ...
                true;

            return;
        end
    end
end


%% ========================================================================
% Count cells
% =========================================================================
function n_cells = ...
    count_cells_in_plane(current_data)

    n_cells = ...
        NaN;


    if isempty(current_data)
        return;
    end


    if istable(current_data)

        n_cells = ...
            height(current_data);

        return;
    end


    if isnumeric(current_data) || ...
            islogical(current_data)

        if ismatrix(current_data)

            n_cells = ...
                size(current_data, 1);
        end

        return;
    end


    if iscell(current_data)

        n_cells = ...
            numel(current_data);
    end
end


%% ========================================================================
% Build animal summary
% =========================================================================
function animal_table = ...
    build_animal_summary(day_table)

    animal_table = ...
        initialize_animal_table();


    if isempty(day_table)
        return;
    end


    session_table = ...
        unique( ...
            day_table(:, { ...
                'Type', ...
                'Line', ...
                'Animal', ...
                'Age', ...
                'AgeNumber', ...
                'Date', ...
                'RecordingIndex', ...
                'Branch', ...
                'TotalCellsDay'}), ...
            'rows', ...
            'stable');


    group_keys = ...
        unique( ...
            session_table(:, { ...
                'Type', ...
                'Line', ...
                'Animal', ...
                'Branch'}), ...
            'rows', ...
            'stable');


    for i = 1:height(group_keys)

        current_type = ...
            group_keys.Type(i);


        current_line = ...
            group_keys.Line(i);


        current_animal = ...
            group_keys.Animal(i);


        current_branch = ...
            group_keys.Branch(i);


        rows = ...
            session_table.Type == current_type & ...
            session_table.Line == current_line & ...
            session_table.Animal == current_animal & ...
            session_table.Branch == current_branch;


        current_sessions = ...
            session_table(rows, :);


        total_cells = ...
            double( ...
                current_sessions.TotalCellsDay);


        total_cells = ...
            total_cells( ...
                isfinite(total_cells));


        if isempty(total_cells)

            mean_cells = NaN;
            median_cells = NaN;
            min_cells = NaN;
            max_cells = NaN;

        else

            mean_cells = ...
                mean( ...
                    total_cells, ...
                    'omitnan');


            median_cells = ...
                median( ...
                    total_cells, ...
                    'omitnan');


            min_cells = ...
                min(total_cells);


            max_cells = ...
                max(total_cells);
        end


        age_numbers = ...
            double( ...
                current_sessions.AgeNumber);


        age_numbers = ...
            age_numbers( ...
                isfinite(age_numbers));


        if isempty(age_numbers)

            min_age = NaN;
            max_age = NaN;
            unique_ages = "";

        else

            min_age = ...
                min(age_numbers);


            max_age = ...
                max(age_numbers);


            unique_age_values = ...
                unique( ...
                    age_numbers, ...
                    'sorted');


            unique_ages = ...
                strjoin( ...
                    "P" + string(unique_age_values), ...
                    ", ");
        end


        n_recordings = ...
            height(current_sessions);


        valid_dates = ...
            current_sessions.Date;


        valid_dates = ...
            valid_dates( ...
                strlength(valid_dates) > 0);


        if isempty(valid_dates)

            n_days = ...
                n_recordings;

        else

            n_days = ...
                numel( ...
                    unique(valid_dates));
        end


        new_row = ...
            table( ...
                current_type, ...
                current_line, ...
                current_animal, ...
                current_branch, ...
                double(n_recordings), ...
                double(n_days), ...
                double(mean_cells), ...
                double(median_cells), ...
                double(min_cells), ...
                double(max_cells), ...
                double(min_age), ...
                double(max_age), ...
                string(unique_ages), ...
                'VariableNames', { ...
                    'Type', ...
                    'Line', ...
                    'Animal', ...
                    'Branch', ...
                    'NRecordings', ...
                    'NDays', ...
                    'MeanCellsPerDay', ...
                    'MedianCellsPerDay', ...
                    'MinCellsPerDay', ...
                    'MaxCellsPerDay', ...
                    'MinAge', ...
                    'MaxAge', ...
                    'Ages'});


        animal_table = ...
            [ ...
                animal_table; ...
                new_row ...
            ]; %#ok<AGROW>
    end


    animal_table = ...
        sortrows( ...
            animal_table, ...
            { ...
                'Type', ...
                'Line', ...
                'Animal', ...
                'Branch' ...
            });
end


%% ========================================================================
% Plot overview
% =========================================================================
function fig = ...
    plot_combined_overview( ...
        day_table, ...
        animal_table, ...
        legend_table, ...
        include_electroporated_cells, ...
        current_type)

    if isempty(day_table)

        fig = [];
        return;
    end


    session_table = ...
        unique( ...
            day_table(:, { ...
                'Type', ...
                'Line', ...
                'Animal', ...
                'Age', ...
                'AgeNumber', ...
                'Date', ...
                'RecordingIndex', ...
                'Branch', ...
                'TotalCellsDay'}), ...
            'rows', ...
            'stable');


    session_table.DisplayAnimal = ...
        create_animal_labels( ...
            session_table.Type, ...
            session_table.Line, ...
            session_table.Animal);


    animal_table.DisplayAnimal = ...
        create_animal_labels( ...
            animal_table.Type, ...
            animal_table.Line, ...
            animal_table.Animal);


    animal_labels = ...
        unique( ...
            session_table.DisplayAnimal, ...
            'stable');


    n_animals = ...
        numel(animal_labels);


    if n_animals == 0

        fig = [];
        return;
    end


    %==============================================================%
    % Ages
    %==============================================================%
    finite_ages = ...
        session_table.AgeNumber( ...
            isfinite( ...
                session_table.AgeNumber));


    if isempty(finite_ages)

        age_ticks = ...
            1;


        age_tick_labels = ...
            "";

    else

        min_age = ...
            floor( ...
                min(finite_ages));


        max_age = ...
            ceil( ...
                max(finite_ages));


        age_ticks = ...
            min_age:max_age;


        age_tick_labels = ...
            "P" + string(age_ticks);
    end


    y_positions = ...
        1:n_animals;


    %==============================================================%
    % Cell means
    %==============================================================%
    mean_gcamp = ...
        nan(n_animals, 1);


    mean_mtor = ...
        nan(n_animals, 1);


    for a = 1:n_animals

        current_animal = ...
            animal_labels(a);


        gcamp_rows = ...
            animal_table.DisplayAnimal == current_animal & ...
            animal_table.Branch == "gcamp_plane";


        if any(gcamp_rows)

            values = ...
                animal_table.MeanCellsPerDay(gcamp_rows);


            values = ...
                values( ...
                    isfinite(values));


            if ~isempty(values)

                mean_gcamp(a) = ...
                    values(1);
            end
        end


        electroporated_rows = ...
            animal_table.DisplayAnimal == current_animal & ...
            animal_table.Branch == "electroporated_plane";


        if any(electroporated_rows)

            values = ...
                animal_table.MeanCellsPerDay(electroporated_rows);


            values = ...
                values( ...
                    isfinite(values));


            if ~isempty(values)

                mean_mtor(a) = ...
                    values(1);
            end
        end
    end


    has_mtor_data = ...
        include_electroporated_cells && ...
        any( ...
            isfinite(mean_mtor));


    %==============================================================%
    % Figure
    %==============================================================%
    fig = ...
        figure( ...
            'Color', ...
            'w', ...
            'Name', ...
            'Selected groups overview', ...
            'NumberTitle', ...
            'off', ...
            'Units', ...
            'normalized', ...
            'OuterPosition', ...
            [0 0 1 1]);


    main_ax = ...
        axes( ...
            fig, ...
            'Position', ...
            [0.10 0.17 0.56 0.70]);


    bar_ax = ...
        axes( ...
            fig, ...
            'Position', ...
            [0.72 0.17 0.23 0.70]);


    hold(main_ax, 'on');
    hold(bar_ax, 'on');


    x_limits = ...
        [ ...
            age_ticks(1) - 0.5, ...
            age_ticks(end) + 0.5 ...
        ];


    %==============================================================%
    % Grid
    %==============================================================%
    for y = 0.5:1:(n_animals + 0.5)

        plot( ...
            main_ax, ...
            x_limits, ...
            [y y], ...
            'Color', ...
            [0.82 0.82 0.82], ...
            'LineWidth', ...
            0.8);
    end


