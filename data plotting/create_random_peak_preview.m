        fig_handle, ...
        file_path)

    try

        exportgraphics( ...
            fig_handle, ...
            file_path, ...
            'Resolution', 300);

    catch ME_export

        try

            saveas( ...
                fig_handle, ...
                file_path);

        catch ME_saveas

            warning( ...
                ['Unable to save figure:\n%s\n' ...
                 'exportgraphics: %s\n' ...
                 'saveas: %s'], ...
                file_path, ...
                ME_export.message, ...
                ME_saveas.message);
        end
    end
end


% ========================================================================
function value = normalize_peak_figure_text(value)

    if isempty(value)

        value = '';

        return;
    end


    if isstring(value)

        value = ...
            char(value(1));

    elseif iscell(value)

        value = ...
            value{1};


        if isstring(value)

            value = ...
                char(value);
        end
    end


    if isnumeric(value)

        value = ...
            num2str(value);
    end


    if ~ischar(value)

        value = ...
            char(string(value));
    end


    value = ...
        strtrim(value);
end


% ========================================================================
function value = sanitize_peak_figure_filename(value)

    value = ...
        normalize_peak_figure_text( ...
            value);


    if isempty(value)
        return;
    end


    value = ...
        regexprep( ...
            value, ...
            '[<>:"/\\|?*]', ...
            '-');


    value = ...
        regexprep( ...
            value, ...
            '\s+', ...
            '_');


    value = ...
        regexprep( ...
            value, ...
            '_+', ...
            '_');


    value = ...
        regexprep( ...
            value, ...
            '^[_\-.]+|[_\-.]+$', ...
            '');
end